using System;
using System.Collections.Generic;
using System.Reflection;
using UnityEngine;

    // 数据服务：加载 Resources/Data/*.json 并缓存为字典；启动全量跨引用校验。
    // 任何缺失/断裂引用都会写入 校验错误，由装配层阻止进入游戏（不静默崩溃）。
    public sealed class DataService
    {
        private readonly EventBus 事件;

        // 各数据表（可读写，供校验/测试注入）
        public Dictionary<string, 剧情节点> 剧情 { get; private set; } = new Dictionary<string, 剧情节点>();
        public Dictionary<string, 敌人数据> 敌人 { get; private set; } = new Dictionary<string, 敌人数据>();
        public Dictionary<string, 物品数据> 物品 { get; private set; } = new Dictionary<string, 物品数据>();
        public Dictionary<string, 技能数据> 技能 { get; private set; } = new Dictionary<string, 技能数据>();
        public Dictionary<string, 任务数据> 任务 { get; private set; } = new Dictionary<string, 任务数据>();
        // 注：原有 `设施`（设施定义）与 `训练项目` 两个字典 —— v51 刀7e 随 **设施子系统整体退役** 一起删：
        // 设施（交易站/诊所/家/训练场）的入口三层全断（设施工厂.创建 0 调用 / 打开功能面板事件 从未发布 /
        // 设施功能面板基类 0 子类），用户拍板"不接"；训练项目 的唯一消费者是设施里的 训练逻辑，跟着一起走。
        public Dictionary<string, Buff定义> Buffs { get; private set; } = new Dictionary<string, Buff定义>();
        public Dictionary<string, 敌人组数据> 敌人组 { get; private set; } = new Dictionary<string, 敌人组数据>();
        public Dictionary<string, 助战组数据> 助战组 { get; private set; } = new Dictionary<string, 助战组数据>();
        public Dictionary<string, 配方数据> 配方 { get; private set; } = new Dictionary<string, 配方数据>();
        public Dictionary<string, 职业数据> 职业 { get; private set; } = new Dictionary<string, 职业数据>();
        public Dictionary<string, 天赋数据> 天赋 { get; private set; } = new Dictionary<string, 天赋数据>();
        // 注：原有 `Dictionary<string, 天气数据> 天气` + `加载("天气", …)` —— v51 刀7c 删：
        // 天气.json 不存在，且 数据.天气 全仓库无人读（天气是 世界时间管理器 按枚举随机取的）。
        public Dictionary<string, 家具数据> 家具 { get; private set; } = new Dictionary<string, 家具数据>();
        public 视野数据 视野 { get; private set; } = new 视野数据();   // 视野规则（角色 + 时段）
        public List<情报条目> 情报 { get; private set; } = new List<情报条目>();   // 收音机 情报池（无标识，列表承载）
        public Dictionary<string, 搜索地图类型> 搜索地图类型 { get; private set; } = new Dictionary<string, 搜索地图类型>();
        public Dictionary<string, 战斗棋盘数据> 战斗棋盘 { get; private set; } = new Dictionary<string, 战斗棋盘数据>();
        public Dictionary<string, 房间模板> 房间模板 { get; private set; } = new Dictionary<string, 房间模板>();
        public Dictionary<string, 区域模板> 区域模板 { get; private set; } = new Dictionary<string, 区域模板>();
        public Dictionary<string, 建筑模板> 建筑模板 { get; private set; } = new Dictionary<string, 建筑模板>();
        public Dictionary<string, 世界模板> 世界 { get; private set; } = new Dictionary<string, 世界模板>();

        public List<string> 校验错误 { get; } = new List<string>();
        // 校验警告：不致命（游戏照进），但多半是数据写歪了——例如"门通向那间房，可那边没门通回来"
        public List<string> 校验警告 { get; } = new List<string>();
        // 加载期的异常（"某项没有 标识 被丢掉"）：在 加载全部() 阶段记下，由 重新校验() 汇总报出
        // （加载发生在 重新校验 之前，直接写 校验警告 会被 Clear 掉）
        private readonly List<string> 加载异常 = new List<string>();

        // 物品「类型」的合法取值（v51 刀15 起由 重新校验() 强制白名单）。
        // 依据：`Assets/Resources/Data/物品/**` 里实际出现的取值（269 件）。
        // ⚠ 新增物品类型时**必须同时加到这里**，否则装配期会报"类型非法"（这是故意的：宁可报错也别静默）。
        // ⚠ 注意「技能书 / 配方书 / 蓝图」是 `书籍种类` 的取值，**不是** `类型` —— 类型只有"书籍"。
        private static readonly HashSet<string> 合法物品类型 = new HashSet<string>
        {
            "武器", "防具", "饮食", "医疗", "材料", "弹药", "任务品", "容器", "书籍",
        };

        public DataService(EventBus 事件)
        {
            this.事件 = 事件;
            加载全部();
            重新校验();
        }

        // 统一加载入口：文件名 -> 目标字典 -> 根对象中提取数组
        private void 加载全部()
        {
            加载("story", 剧情, (剧情根 根) => 根.节点);
            加载("enemies", 敌人, (敌人根 根) => 根.敌人);
            加载物品();   // items.json 已按类型拆分多文件（便于查看修改），全部合并进 物品 字典
            加载("skills", 技能, (技能根 根) => 根.技能);
            加载("quests", 任务, (任务根 根) => 根.任务);
            加载("buffs", Buffs, (Buff根 根) => 根.Buffs);
            加载("encounters", 敌人组, (敌人组根 根) => 根.敌人组);
            // 配方 按 制作 家具 一 家具 一 文件（recipes_<家具>.json——工作台/灶台/医疗站）
            加载("recipes_工作台", 配方, (配方根 根) => 根.配方);
            加载("recipes_灶台", 配方, (配方根 根) => 根.配方);
            加载("recipes_医疗站", 配方, (配方根 根) => 根.配方);
            加载("职业", 职业, (职业根 根) => 根.职业);       // 允许缺失（职业系统）
            加载("天赋", 天赋, (天赋根 根) => 根.天赋);       // 允许缺失（天赋系统）
            加载("家具", 家具, (家具根 根) => 根.家具);       // 允许缺失（安全屋系统）
            加载("搜索_地图类型", 搜索地图类型, (搜索地图类型根 根) => 根.地图类型);   // 允许缺失（搜索容器系统）
            加载("战斗棋盘", 战斗棋盘, (战斗棋盘根 根) => 根.棋盘);   // 允许缺失（战斗沙盒）
            加载("房间模板", 房间模板, (房间模板根 根) => 根.房间);   // 允许缺失（房间层 · 单房间模板）
            加载("区域模板", 区域模板, (区域模板根 根) => 根.区域);   // 允许缺失（区域层 · 区域网格）
            加载("建筑模板", 建筑模板, (建筑模板根 根) => 根.建筑);   // 允许缺失（建筑层 · 楼层 + 楼梯）
            加载("世界", 世界, (世界根 根) => 根.世界);               // 允许缺失（大世界 · 100×100 格子网格）
            加载视野();
            加载情报();
            加载助战组();
        }

        // 物品数据按类型拆分（Data/物品/items_*.json）一 类型 一 文件，逐文件加载合并；同名标识后加载覆盖。
        // 材料 再 按 种类 一 类 一 文件（物品/材料/items_材料_<种类>.json）；防具 再 按 部位 一 部位 一 文件（物品/items_防具_<槽位>.json）
        private void 加载物品()
        {
            加载("物品/items_武器", 物品, (物品根 根) => 根.物品);
            string[] 防具文件 =
            {
                "物品/防具/items_防具_头部", "物品/防具/items_防具_胸部", "物品/防具/items_防具_腿部", "物品/防具/items_防具_脚部",
                "物品/防具/items_防具_手部", "物品/防具/items_防具_弹挂", "物品/防具/items_防具_腰封", "物品/防具/items_防具_背包",
            };
            foreach (var 文件 in 防具文件) 加载(文件, 物品, (物品根 根) => 根.物品);
            加载("物品/items_饮食", 物品, (物品根 根) => 根.物品);
            加载("物品/items_医疗", 物品, (物品根 根) => 根.物品);
            string[] 材料文件 =
            {
                "物品/材料/items_材料_医疗用品", "物品/材料/items_材料_建筑材料", "物品/材料/items_材料_日常用品", "物品/材料/items_材料_工具",
                "物品/材料/items_材料_燃料物品", "物品/材料/items_材料_能源产品", "物品/材料/items_材料_电子产品", "物品/材料/items_材料_贵重物品",
                "物品/材料/items_材料_情报物品", "物品/材料/items_材料_食物原料", "物品/材料/items_材料_图纸", "物品/材料/items_材料_其他",
            };
            foreach (var 文件 in 材料文件) 加载(文件, 物品, (物品根 根) => 根.物品);
            加载("物品/items_弹药", 物品, (物品根 根) => 根.物品);
            加载("物品/items_任务品", 物品, (物品根 根) => 根.物品);
            加载("物品/items_容器", 物品, (物品根 根) => 根.物品);
            加载("物品/items_书籍", 物品, (物品根 根) => 根.物品);   // 书籍：技能书/配方书/蓝图（允许缺失——书籍系统）
        }

        // 视野规则（单条配置；允许缺失 → 用默认值兜底）
        private void 加载视野()
        {
            var 资产 = Resources.Load<TextAsset>("Data/视野");
            if (资产 == null) { Debug.LogWarning("[数据] 缺失 Data/视野.json —— 视野规则用默认值"); return; }
            var 根 = JsonUtility.FromJson<视野数据根>(资产.text);
            if (根?.视野 != null && 根.视野.Length > 0) 视野 = 根.视野[0];
        }

        // 情报池（收音机 收听 播报内容；无标识，列表承载）
        private void 加载情报()
        {
            var 资产 = Resources.Load<TextAsset>("Data/情报");
            if (资产 == null) { Debug.LogWarning($"[数据] 缺失 Data/情报.json——请检查 Resources/Data 下文件与文件名"); return; }
            var 根 = JsonUtility.FromJson<情报根>(资产.text);
            if (根?.情报 != null) 情报.AddRange(根.情报);
        }

        // 附加表：encounters 里的 助战组（同一文件内的第二数组）
        // 注：原来这里还顺带从 story 里读 `区域剧情`，v51 刀7b 随 区域剧情路由 一起删了
        //     （它的唯一消费者 地图服务 在刀3 就退役，且它挂在已删的 主线阶段 上；story.json 本来也不存在）。
        private void 加载助战组()
        {
            var 敌人组资产 = Resources.Load<TextAsset>("Data/encounters");
            if (敌人组资产 == null) return;
            var 根 = JsonUtility.FromJson<敌人组根>(敌人组资产.text);
            if (根?.助战组 == null) return;
            foreach (var 项 in 根.助战组)
                if (!string.IsNullOrEmpty(项.标识)) 助战组[项.标识] = 项;
        }

        private void 加载<T, TRoot>(string 文件, Dictionary<string, T> 目标, Func<TRoot, T[]> 提取) where T : class
        {
            var 资产 = Resources.Load<TextAsset>($"Data/{文件}");
            if (资产 == null) { Debug.LogWarning($"[数据] 缺失 Data/{文件}.json——请检查 Resources/Data 下文件与文件名"); return; }
            var 根 = JsonUtility.FromJson<TRoot>(资产.text);
            if (根 == null) return;
            int 丢掉 = 0;
            foreach (var 项 in 提取(根))
            {
                var 标识 = 获取标识(项);
                if (string.IsNullOrEmpty(标识)) { 丢掉++; continue; }
                目标[标识] = 项;
            }
            // ★ 静默失败防线（v51 刀15）：`获取标识` 取不到就**整项丢掉**，而这里原来一声不响 ——
            //   24 个 `*根` DTO 全依赖"恰好有一个叫 标识 的 string 字段"这个约定，
            //   任何一个 DTO 漏写/改名，那张表就会**静默缺条目**（甚至整表空），而 校验错误 依旧是空的。
            //   记到 加载异常，由 重新校验() 统一报出来（见那里的注释：为什么先报警告而不是错误）。
            if (丢掉 > 0)
                加载异常.Add($"{文件}：{丢掉} 项没有可用的 标识 字段被丢掉（DTO 类型 {typeof(T).Name}）——"
                          + "这些条目在游戏里等于不存在。请检查该 DTO 是否漏写或改名了 标识");
        }

        // 反射取各模型的「标识」字段。
        // v51 刀15：加 FieldInfo 缓存 —— 原来每个条目都 `typeof(T).GetField("标识")` 反射一次
        //   （24 张表 × 条目数，装配期白花；物品一类就有 269 条）。null 也缓存，同一类型只反射一次。
        private static readonly Dictionary<Type, FieldInfo> 标识字段缓存 = new Dictionary<Type, FieldInfo>();
        private static string 获取标识<T>(T 项)
        {
            var 类型 = typeof(T);
            if (!标识字段缓存.TryGetValue(类型, out var 字段))
            {
                字段 = 类型.GetField("标识");
                标识字段缓存[类型] = 字段;
            }
            return 字段?.GetValue(项) as string;
        }

        // 全量跨引用校验：清空后重查，错误写入 校验错误（警告写入 校验警告，不拦进游戏）
        public void 重新校验()
        {
            校验错误.Clear();
            校验警告.Clear();
            // 加载期发现的"整项被丢掉"（见 加载<T,TRoot> 里的注释）—— 这里统一报出来。
            // ⚠ 先报**警告**而不是错误：它若判成错误，`GameBootstrap` 会中止装配 → 整个游戏进不去。
            //   现在能确认"所有当前被加载的 DTO 都有 标识"（装配日志里 敌人 9 / 物品 269 / 技能 21 都非空
            //   就是证据），但这个守卫是给**将来新增 DTO** 用的 —— 那时它会响亮，而不是静默缺条目。
            //   等哪天真在 Unity 里验过一遍"没有任何 加载异常"，再考虑升级成 校验错误。
            if (加载异常.Count > 0) 校验警告.AddRange(加载异常);

            // —— 剧情：选项目标 / 强制战斗敌人 / 下一节点 ——
            foreach (var (标识, 节点) in 剧情)
            {
                if (节点.选项 != null)
                    foreach (var 选项 in 节点.选项)
                    {
                        if (string.IsNullOrEmpty(选项.目标)) continue;
                        // 特殊目标跳过：**只列 DialogueService.处理选项 真正认的那几个前缀**（战斗: / 地图: / __）。
                        // v51 刀7e 收紧了这份名单：原来还含 设施: / 探索: / 区域: / 任务: / 购买: / 学习: ——
                        // 那些系统的服务/指令**都已经删了**，现在还写它们只会落到 进入节点() 然后报"节点不存在"。
                        // 与其静默跳过（让作者以为它有用），不如让校验把它报成"目标不存在"。
                        else if (!选项.目标.StartsWith("战斗:") && !选项.目标.StartsWith("地图:") &&
                                 !选项.目标.StartsWith("__") &&
                                 !剧情.ContainsKey(选项.目标))
                        {
                            校验错误.Add($"剧情[{标识}] → 节点[{选项.目标}] 不存在");
                        }
                        // 战斗:敌人组:胜利节点[:助战组] —— 敌人组/助战组 存在性
                        if (选项.目标.StartsWith("战斗:"))
                        {
                            var 部分 = 选项.目标.Split(':');
                            if (部分.Length >= 2 && !敌人组.ContainsKey(部分[1]))
                                校验错误.Add($"剧情[{标识}] → 战斗敌人组[{部分[1]}] 不存在");
                            if (部分.Length >= 4 && !string.IsNullOrEmpty(部分[3]) && !助战组.ContainsKey(部分[3]))
                                校验错误.Add($"剧情[{标识}] → 助战组[{部分[3]}] 不存在");
                        }
                    }
                // 强制战斗
                if (!string.IsNullOrEmpty(节点.战斗))
                {
                    var 部分 = 节点.战斗.Split(':');
                    if (部分.Length >= 2 && !敌人.ContainsKey(部分[1]))
                        校验错误.Add($"剧情[{标识}] 战斗敌人[{部分[1]}] 不存在");
                }
                // 下一节点（剧情链自动播放）
                if (!string.IsNullOrEmpty(节点.下一节点) && !剧情.ContainsKey(节点.下一节点))
                    校验错误.Add($"剧情[{标识}] → 下一节点[{节点.下一节点}] 不存在");
            }

            // —— 注：原有一段「区域剧情路由」校验（区域模板/节点/需要物品/需要任务 是否存在）——
            //    v51 刀7b 随 区域剧情路由 一起删（它挂在已删的 主线阶段 上，消费者 地图服务 也早已退役）。

            // —— 助战组：引用的伙伴单位存在 ——
            foreach (var (标识, 组) in 助战组)
            {
                if (组.成员 == null) continue;
                foreach (var 项 in 组.成员)
                    if (!敌人.ContainsKey(项.标识))
                        校验错误.Add($"助战组[{标识}] → 伙伴[{项.标识}] 不存在");
            }

            // —— 地图：v51 起**节点网图整体退役**（大世界改成 100×100 格子网格，见 Data/世界.json）——
            //   原来那段「地点.连接 邻接表校验」随 地图地点/map.json/地图服务 一起删掉了。
            //   大世界的数据级校验在下面「大世界（世界.json）」那一段；"摆出来连不连通"由 Tools/大世界验证 离线断言。

            // —— 物品：装备类必须有 槽位 ——
            foreach (var (标识, 物品) in 物品)
            {
                // ★ v51 刀15：`类型` 白名单（原来只查"武器/防具 要有槽位"，**完全没有白名单**）——
                //   于是"类型"写错一个词（历史上真发生过：代码里判过 `类型 == "技能书"`，
                //   而全 JSON 的类型取值里根本没有"技能书"，它其实是 `书籍种类`）永远不会被报出来，
                //   只会表现成"某个功能莫名其妙不生效"。这里把合法取值**显式列出来**，
                //   以后新增物品类型必须同时改这里（改一处报一处，而不是静默）。
                if (!合法物品类型.Contains(物品.类型 ?? ""))
                    校验错误.Add($"物品[{标识}] → 类型[{物品.类型}] 非法（只能是 {string.Join("/", 合法物品类型)}）");
                if ((物品.类型 == "武器" || 物品.类型 == "防具") && string.IsNullOrEmpty(物品.槽位))
                    校验错误.Add($"物品[{标识}] 装备类缺少 槽位（主手/副手/头部/胸部/腿部/脚部/手部/弹挂/腰封/背包）");
            }

            // —— 书籍：配方书 配方池 引用 + 技能书 技能 引用 ——
            foreach (var (标识, 物品) in 物品)
            {
                if (物品.类型 != "书籍") continue;
                if (物品.书籍种类 == "配方书" && 物品.配方池 != null)
                    foreach (var 配方标识 in 物品.配方池)
                        if (!string.IsNullOrEmpty(配方标识) && !配方.ContainsKey(配方标识))
                            校验错误.Add($"书籍[{标识}] → 配方池[{配方标识}] 不存在");
                if (物品.书籍种类 == "技能书" && !string.IsNullOrEmpty(物品.技能) && !技能.ContainsKey(物品.技能))
                    校验错误.Add($"书籍[{标识}] → 技能[{物品.技能}] 不存在");
            }

            // —— 区域（旧"深度分层闯关"的事件表校验已随 探索服务/探索面板 一起删除）——
            // 区域网格的校验（建筑模板 / 街道敌人组）等 区域生成器 落地后再加在这里。

            // —— 配方：产物/材料/图纸 物品存在 + 类型/等级 合法 ——
            foreach (var (标识, 配方) in 配方)
            {
                if (!物品.ContainsKey(配方.产物))
                    校验错误.Add($"配方[{标识}] → 产物[{配方.产物}] 不存在");
                if (配方.材料 != null)
                    foreach (var 材 in 配方.材料)
                        if (!物品.ContainsKey(材.物品))
                            校验错误.Add($"配方[{标识}] → 材料[{材.物品}] 不存在");
                if (!string.IsNullOrEmpty(配方.解锁图纸) && !物品.ContainsKey(配方.解锁图纸))
                    校验错误.Add($"配方[{标识}] → 图纸[{配方.解锁图纸}] 不存在");
                if (配方.类型 != "工作台" && 配方.类型 != "灶台" && 配方.类型 != "医疗站")
                    校验错误.Add($"配方[{标识}] → 类型[{配方.类型}] 非法（工作台/灶台/医疗站）");
                if (配方.需要等级 < 1 || 配方.需要等级 > 3)
                    校验错误.Add($"配方[{标识}] → 需要等级[{配方.需要等级}] 非法（1~3）");
            }

            // —— 搜索容器：地图类型 → 房间 → 容器（尺寸合法 + 搜索表物品存在 + 形状块合法）——
            foreach (var (类型标识, 地图类型) in 搜索地图类型)
            {
                if (地图类型.房间 == null) { 校验错误.Add($"搜索容器[{类型标识}] 缺少 房间 定义"); continue; }
                foreach (var 房间 in 地图类型.房间)
                {
                    string 房名 = $"搜索容器[{类型标识}]·房间[{房间.标识}]";
                    if (房间.容器 == null || 房间.容器.Length == 0)
                    { 校验错误.Add($"{房名} 缺少 容器 定义"); continue; }
                    foreach (var 容器 in 房间.容器)
                    {
                        string 容名 = $"{房名}·容器[{容器.标识}]";
                        if (容器.容器列 <= 0 || 容器.容器行 <= 0)
                        { 校验错误.Add($"{容名} 尺寸非法（列×行）"); continue; }
                        if (容器.容器形状 != null && 容器.容器形状.Length > 0)
                            foreach (var 块 in 容器.容器形状)
                                if (块 == null || 块.宽 <= 0 || 块.高 <= 0 || 块.列 < 0 || 块.行 < 0
                                    || 块.列 + 块.宽 > 容器.容器列 || 块.行 + 块.高 > 容器.容器行)
                                { 校验错误.Add($"{容名} 形状块越界/非法"); break; }
                        if (容器.搜索表 != null)
                            foreach (var 条目 in 容器.搜索表)
                            {
                                if (条目 == null || string.IsNullOrEmpty(条目.物品标识)) continue;
                                if (!物品.ContainsKey(条目.物品标识))
                                    校验错误.Add($"{容名} → 物品[{条目.物品标识}] 不存在");
                                else if (!string.IsNullOrEmpty(容器.容器允许类型))
                                {
                                    var 模板 = 物品[条目.物品标识];
                                    if (模板.类型 != 容器.容器允许类型)
                                        校验错误.Add($"{容名} → 物品[{条目.物品标识}] 类型[{模板.类型}] 与 允许类型[{容器.容器允许类型}] 不符");
                                }
                            }
                    }
                }
            }

            // —— 安全屋家具：材料/升级材料 物品存在 + 形状/效果 合法 ——
            foreach (var (标识, 家具) in 家具)
            {
                if (家具.最大等级 <= 0) 校验错误.Add($"家具[{标识}] 最大等级 非法");
                if (家具.形状宽 <= 0 || 家具.形状高 <= 0) 校验错误.Add($"家具[{标识}] 形状 非法（宽×高）");
                if (家具.效果 == null || 家具.效果.Length < 家具.最大等级)
                    校验错误.Add($"家具[{标识}] 效果 长度不足（需 {家具.最大等级} 级，当前 {(家具.效果?.Length ?? 0)}）");
                if (家具.材料 != null)
                    foreach (var 材 in 家具.材料)
                        if (!物品.ContainsKey(材.物品)) 校验错误.Add($"家具[{标识}] → 材料[{材.物品}] 不存在");
                if (家具.升级 != null)
                    for (int i = 0; i < 家具.升级.Length; i++)
                    {
                        var 需 = 家具.升级[i];
                        if (需 == null) continue;
                        if (需.材料 != null)
                            foreach (var 材 in 需.材料)
                                if (!物品.ContainsKey(材.物品)) 校验错误.Add($"家具[{标识}] 升{i + 2}级 → 材料[{材.物品}] 不存在");
                    }
            }
            // ================= 房间层（房间模板） =================
            // —— 房间模板：尺寸 / 入口边 / 容器池（地图类型+房间 必须存在）/ 敌人组 / 棋盘 ——
            foreach (var (标识, 房) in 房间模板)
            {
                string 名 = $"房间模板[{标识}]";
                if (房.列 < 8 || 房.行 < 6) 校验错误.Add($"{名} 房间尺寸过小（至少 8×6）");
                if (房.列 > 26 || 房.行 > 18) 校验错误.Add($"{名} 房间尺寸过大（至多 26×18）");
                if (房.容器池 == null || 房.容器池.Length == 0) 校验错误.Add($"{名} 没有 容器池（房间里会空无一物）");
                else
                    foreach (var 池 in 房.容器池)
                    {
                        if (池 == null) continue;
                        if (池.数量最大 < 池.数量最小) 校验错误.Add($"{名} → 容器池[{池.地图类型}/{池.房间}] 数量区间非法");
                        if (!搜索地图类型.TryGetValue(池.地图类型, out var 类型))
                        {
                            校验错误.Add($"{名} → 地图类型[{池.地图类型}] 不存在（容器来源）");
                            continue;
                        }
                        if (string.IsNullOrEmpty(池.房间)) continue;
                        bool 命中 = false;
                        if (类型.房间 != null)
                            foreach (var 房项 in 类型.房间)
                                if (房项 != null && 房项.标识 == 池.房间) { 命中 = true; break; }
                        if (!命中) 校验错误.Add($"{名} → 地图类型[{池.地图类型}] 里没有房间[{池.房间}]");
                    }
                if (房.敌人数量最大 > 0)
                {
                    if (string.IsNullOrEmpty(房.敌人组)) 校验错误.Add($"{名} 有敌人数量但没有 敌人组");
                    else if (!敌人组.ContainsKey(房.敌人组)) 校验错误.Add($"{名} → 敌人组[{房.敌人组}] 不存在");
                }
                if (!string.IsNullOrEmpty(房.战斗棋盘) && !战斗棋盘.ContainsKey(房.战斗棋盘))
                    校验错误.Add($"{名} → 战斗棋盘[{房.战斗棋盘}] 不存在");

                // —— 门：边合法 / 通向存在 / 建议互开（开不出的门 = 走不过去的路） ——
                if (房.门 == null) continue;
                foreach (var 门 in 房.门)
                {
                    if (门 == null) continue;
                    if (门.边 != "上" && 门.边 != "下" && 门.边 != "左" && 门.边 != "右")
                        校验错误.Add($"{名} → 门 的边[{门.边}] 非法（只能 上/下/左/右）");
                    if (string.IsNullOrEmpty(门.通向))
                    {
                        校验错误.Add($"{名} → 门 没有写 通向（通向外面的大门由 入口边 推出来，不用写）");
                        continue;
                    }
                    if (门.通向 == 标识) 校验错误.Add($"{名} → 门 通向自己");
                    if (!房间模板.ContainsKey(门.通向))
                    {
                        校验错误.Add($"{名} → 门 通向的房间模板[{门.通向}] 不存在");
                        continue;
                    }
                    // 门锁：钥匙物品必须存在（钥匙会随机塞进这间房的某个容器里，所以这间房也得有容器可放）
                    if (!string.IsNullOrEmpty(门.锁))
                    {
                        if (!物品.ContainsKey(门.锁)) 校验错误.Add($"{名} → 门 的锁 需要物品[{门.锁}]，但 items 里没有这件东西");
                        else if (物品[门.锁].类型 != "任务品") 校验警告.Add($"{名} → 门 的锁 用了[{门.锁}]（类型 {物品[门.锁].类型}）——钥匙一般是 任务品");
                        // 钥匙得有地方放：本房要能有"可搜索容器"（柜子 / 或打赢后的战利品尸体）
                        bool 有柜子 = 房.容器池 != null && 房.容器池.Length > 0;
                        bool 有敌人 = 房.敌人数量最大 > 0 && !string.IsNullOrEmpty(房.敌人组);
                        if (!有柜子 && !有敌人)
                            校验警告.Add($"{名} → 门 有锁，但这间房既没有容器池也没有敌人：钥匙会无处可放，运行时那扇门会自动取消锁");
                    }
                    // 互开检查：目标房应当也有一扇门通回来（否则进去只能靠按 Esc / 走不到别的门）
                    var 回房 = 房间模板[门.通向];
                    bool 有回路 = false;
                    if (回房.门 != null)
                        foreach (var 回门 in 回房.门)
                            if (回门 != null && 回门.通向 == 标识) { 有回路 = true; break; }
                    if (!有回路) 校验警告.Add($"{名} → 门 通向[{门.通向}]，但那边没有门通回来（建议补一扇，否则回不去）");
                }
            }

            // ================= 区域层（区域模板） =================
            // —— 区域模板：尺寸 / 建筑（房间模板必须存在）/ 地块够不够 / 棋盘 ——
            // 注：这里只做**数据级**校验；"摆出来连不连通"由 Tools/区域验证 离线跑种子断言。
            foreach (var (标识, 区) in 区域模板)
            {
                string 名 = $"区域模板[{标识}]";
                if (区.列 < 12 || 区.行 < 8 || 区.列 > 40 || 区.行 > 28)
                    校验警告.Add($"{名} 区域尺寸 {区.列}×{区.行} 超出推荐范围（12×8 ~ 40×28；相机窗口一屏约看 26×15 格）");
                if (区.建筑 == null || 区.建筑.Length == 0) 校验错误.Add($"{名} 没有 建筑（区域里会空无一物）");
                else
                {
                    int 展开 = 0;
                    foreach (var 项 in 区.建筑)
                    {
                        if (项 == null) continue;
                        展开 += Math.Max(1, 项.数量);
                        string 定 = string.IsNullOrEmpty(项.建筑模板) ? 项.房间模板 : 项.建筑模板;
                        if (string.IsNullOrEmpty(定)) { 校验错误.Add($"{名} → 建筑项 既没写 建筑模板 也没写 房间模板"); continue; }
                        // 建筑模板 优先（一栋多层的楼）；没写就退化成"一个房间模板当一栋小房子"
                        if (!string.IsNullOrEmpty(项.建筑模板) && !建筑模板.ContainsKey(项.建筑模板))
                            校验错误.Add($"{名} → 建筑模板[{项.建筑模板}] 不存在");
                        if (!string.IsNullOrEmpty(项.房间模板) && !房间模板.ContainsKey(项.房间模板))
                            校验错误.Add($"{名} → 房间模板[{项.房间模板}] 不存在（建筑里叫不出房间）");
                        if (项.宽 < 2 || 项.高 < 2) 校验错误.Add($"{名} → 建筑[{定}] 占地 {项.宽}×{项.高} 太小（至少 2×2）");
                    }
                    // 地块数 = 区域生成器.地块列数 × 地块行数（2×2 = 4）；多写的建筑不会摆出来
                    if (展开 > 4) 校验警告.Add($"{名}：写了 {展开} 栋建筑，但一屏只有 4 个地块（2×2）—— 多出来的不会摆");
                }
                // 街上敌人（v51 刀12）：定义标识必须在 enemies.json 里，数量必须为正
                // 注：这边只查"名字对不对"；"撒不撒得下、会不会堵死路"由 Tools/区域验证 逐种子断言
                if (区.敌人 != null)
                    foreach (var 项 in 区.敌人)
                    {
                        if (项 == null) continue;
                        if (string.IsNullOrEmpty(项.定义标识)) { 校验错误.Add($"{名} → 敌人项 没写 定义标识"); continue; }
                        if (!敌人.ContainsKey(项.定义标识)) 校验错误.Add($"{名} → 敌人[{项.定义标识}] 不存在（enemies.json 里没有）");
                        if (项.数量 <= 0) 校验错误.Add($"{名} → 敌人[{项.定义标识}] 数量 {项.数量} 不是正数");
                    }
                if (!string.IsNullOrEmpty(区.战斗棋盘) && !战斗棋盘.ContainsKey(区.战斗棋盘))
                    校验错误.Add($"{名} → 战斗棋盘[{区.战斗棋盘}] 不存在");
            }

            // ================= 建筑层（建筑模板） =================
            // —— 楼层表：房间模板存在 / 楼梯间尺寸与建筑一致（楼梯才对得齐）/ 门只在本层内 / 楼梯与大门别挤同一面墙 ——
            foreach (var (标识, 建) in 建筑模板)
            {
                string 名 = $"建筑模板[{标识}]";
                if (建.楼层 == null || 建.楼层.Length == 0) { 校验错误.Add($"{名} 没有 楼层（一栋楼至少一层）"); continue; }
                if (建.楼梯边 != "上" && 建.楼梯边 != "下" && 建.楼梯边 != "左" && 建.楼梯边 != "右")
                    校验错误.Add($"{名} → 楼梯边[{建.楼梯边}] 非法（只能 上/下/左/右）");
                int 大门层数 = 0;
                for (int 层 = 0; 层 < 建.楼层.Length; 层++)
                {
                    var 楼层 = 建.楼层[层];
                    string 层名 = $"{名}·{层 + 1}F";
                    if (楼层?.房间 == null || 楼层.房间.Length == 0) { 校验错误.Add($"{层名} 没有 房间（每层至少一间）"); continue; }
                    if (楼层.大门) 大门层数++;
                    for (int i = 0; i < 楼层.房间.Length; i++)
                    {
                        string 房标 = 楼层.房间[i];
                        if (string.IsNullOrEmpty(房标) || !房间模板.TryGetValue(房标, out var 房))
                        { 校验错误.Add($"{层名} → 房间模板[{房标}] 不存在"); continue; }
                        // 楼梯间（每层 房间[0]）的尺寸 = 全楼统一尺寸：否则楼上楼下的楼梯格对不齐
                        if (i == 0 && (房.列 != 建.列 || 房.行 != 建.行))
                            校验错误.Add($"{层名} → 首间房[{房标}] 尺寸 {房.列}×{房.行} ≠ 建筑 {建.列}×{建.行}（楼梯会上下错位）");
                        // 大门和楼梯抢同一面墙时：建墙() 会把楼梯那面墙内缩 1 格，而 开门() 按整边摆大门，
                        // 结果正门正好落在楼梯间的延伸格里，楼梯间也就围不起来（见 建筑验证 报的"邻居不是墙"）。
                        // 这是**排不出来**的硬冲突，不是风格建议，所以报错不报警告。
                        if (i == 0 && 楼层.大门 && 房.入口边 == 建.楼梯边)
                            校验错误.Add($"{层名} → 大门（入口边 {房.入口边}）和楼梯开在同一面墙：排不出来，必须把 楼梯边 挪到别的边");
                        // ★ v51 刀15：**内门同理**（原来只查了大门 → 漏掉了"门开在楼梯那一列"这个真 bug）。
                        //   楼梯那一侧的外线整个属于楼梯间（楼梯格 + 两侧墙 + 其余界外），门开在那儿三种结局都是坏的：
                        //   压在楼梯格上（带锁就上不了楼）/ 顶掉楼梯间侧墙（围不住）/ 掉进界外（走不到）。
                        //   见 房间生成器.开门 方法头 ★。
                        if (i == 0 && 房.门 != null)
                            foreach (var 内门 in 房.门)
                                if (内门 != null && !string.IsNullOrEmpty(内门.通向) && 内门.边 == 建.楼梯边)
                                    校验错误.Add($"{层名} → 房间[{房标}] 的内门开在 [{内门.边}]，而那正是 楼梯边："
                                              + "楼梯那一列只属于楼梯间（楼梯格+两侧墙+界外），门会压在楼梯格上或掉进界外 → 交互不了。"
                                              + "把 门.边 换一条边，或把 建筑模板.楼梯边 挪到别的边");
                        // 门只在**本层内**串联（跨层一律走楼梯）
                        if (房.门 != null)
                            foreach (var 门 in 房.门)
                            {
                                if (门 == null || string.IsNullOrEmpty(门.通向)) continue;
                                bool 在本层 = false;
                                foreach (var 同层 in 楼层.房间) if (同层 == 门.通向) { 在本层 = true; break; }
                                if (!在本层) 校验错误.Add($"{层名} → 房间[{房标}] 的门通向[{门.通向}]，但它不在本层的 房间 列表里（跨层只能走楼梯）");
                            }
                    }
                }
                if (大门层数 == 0) 校验警告.Add($"{名} 没有任何一层写了 大门 = true（进了楼就出不去了）");
                if (大门层数 > 1) 校验警告.Add($"{名} 有 {大门层数} 层写了 大门 = true（一栋楼只该有一扇正门）");
            }

            // ================= 大世界（世界.json） =================
            // —— 尺寸 / 营地界内 / 区域占地（形状认得出 + 区域模板存在 + 界内）/ 解锁条件 / 棋盘 / 搜索参数 ——
            // 注：这里只做**数据级**校验；"区域占地不重叠 / 摆出来连不连通 / 障碍撒完成立"由 Tools/大世界验证 离线跑种子断言
            //     （与 区域层/建筑层 同一条规矩，见 工作移交报告 开发注意事项 #22）。
            foreach (var (标识, 世) in 世界)
            {
                string 名 = $"世界[{标识}]";
                if (世.列 < 世界规格.最小列 || 世.行 < 世界规格.最小行 ||
                    世.列 > 世界规格.最大列 || 世.行 > 世界规格.最大行)
                    校验错误.Add($"{名} 尺寸 {世.列}×{世.行} 超出范围"
                              + $"（{世界规格.最小列}×{世界规格.最小行} ~ {世界规格.最大列}×{世界规格.最大行}）");

                if (世.营地 == null) 校验错误.Add($"{名} 没写 营地（玩家没有落点）");
                else if (世.营地.列 < 世界规格.边距 || 世.营地.行 < 世界规格.边距 ||
                         世.营地.列 + 世界规格.营地宽 > 世.列 - 世界规格.边距 ||
                         世.营地.行 + 世界规格.营地高 > 世.行 - 世界规格.边距)
                    校验错误.Add($"{名} → 营地({世.营地.列},{世.营地.行}) 放不下"
                              + $"（{世界规格.营地宽}×{世界规格.营地高}，且要离世界边界至少 {世界规格.边距} 格）");

                if (世.区域 == null || 世.区域.Length == 0)
                    校验警告.Add($"{名} 一片区域都没有（大世界上没地方可去）");
                else
                    for (int i = 0; i < 世.区域.Length; i++)
                    {
                        var 项 = 世.区域[i];
                        if (项 == null) continue;
                        string 子 = $"{名}·区域[{i}]";
                        if (string.IsNullOrEmpty(项.区域模板)) { 校验错误.Add($"{子} 没写 区域模板"); continue; }
                        子 = $"{名}·区域[{项.区域模板}]";
                        if (!区域模板.ContainsKey(项.区域模板))
                        { 校验错误.Add($"{子} → 区域模板[{项.区域模板}] 不存在"); continue; }

                        // 占地形状：认得出才生成掩码（形状名写错要报出来，别静默当矩形）
                        var 形 = 项.占地 ?? new 建筑外形数据 { 形状 = 建筑外形.矩形, 宽 = 6, 高 = 5 };
                        if (!建筑外形.认得出(形.形状))
                            校验错误.Add($"{子} → 占地形状[{形.形状}] 认不出（只能是 {建筑外形.形状清单()}）");
                        else
                        {
                            建筑外形.生成(形, out int 宽, out int 高);
                            if (项.列 < 世界规格.边距 || 项.行 < 世界规格.边距 ||
                                项.列 + 宽 > 世.列 - 世界规格.边距 || 项.行 + 高 > 世.行 - 世界规格.边距)
                                校验错误.Add($"{子} → 占地 {宽}×{高} @({项.列},{项.行}) 越界"
                                          + $"（要离世界边界至少 {世界规格.边距} 格）");
                        }

                        if (项.解锁 == null) continue;
                        foreach (var 条 in 项.解锁)
                        {
                            if (条 == null) continue;
                            if (条.条件 != "情报" && 条.条件 != "物品" && 条.条件 != "天数")
                            { 校验错误.Add($"{子} → 解锁条件[{条.条件}] 非法（只能是 情报/物品/天数）"); continue; }
                            // ★ 不许出现"永远打不开的门"（v49 钥匙投放那条纪律的延伸）：
                            //   「情报」目前**根本没有实现** —— 情报系统只到"收音机播报池"为止，
                            //   全仓库没有任何"已获得某条情报"的记录。写了它就是一道打不开的门 → 直接判错误。
                            //   （曾经还有「前置区域」，靠"标记区域已通关"；本作不要"通关"这个概念，已整个收掉。）
                            if (条.条件 == "情报")
                                校验错误.Add($"{子} → 解锁条件「情报」暂不可用：情报系统还没有\"已获得\"的记录，"
                                          + "写了会变成一道永远打不开的门。请先用 物品 / 天数。");
                            if (条.条件 == "天数" && 条.数值 <= 0)
                                校验错误.Add($"{子} → 解锁条件 天数 没写正的 数值");
                            if (条.条件 == "物品" && !物品.ContainsKey(条.标识))
                                校验错误.Add($"{子} → 解锁条件 物品[{条.标识}] 不存在");
                        }
                    }

                if (!string.IsNullOrEmpty(世.战斗棋盘) && !战斗棋盘.ContainsKey(世.战斗棋盘))
                    校验错误.Add($"{名} → 战斗棋盘[{世.战斗棋盘}] 不存在");

                if (世.搜索 != null)
                {
                    if (世.搜索.行动点 < 0 || 世.搜索.游戏分钟 < 0)
                        校验错误.Add($"{名} → 搜索 行动点/游戏分钟 不能是负数");
                    if (世.搜索.出现概率 < 0 || 世.搜索.出现概率 > 100)
                        校验错误.Add($"{名} → 搜索出现概率 {世.搜索.出现概率} 不在 0~100");
                    if (世.搜索.半径 < 1 || 世.搜索.半径 > 12)
                        校验警告.Add($"{名} → 搜索半径 {世.搜索.半径} 不在 1~12（太大会一次搜出一堆临时建筑）");

                    // —— v52：防"站在安全屋门口刷"的三条约束（设计见 docs/大世界搜索约束设计.md）——
                    // ① 局部枯竭
                    if (世.搜索.枯竭半径 < 0 || 世.搜索.枯竭半径 > 30)
                        校验错误.Add($"{名} → 搜索枯竭半径 {世.搜索.枯竭半径} 不在 0~30（0 = 关掉这条约束）");
                    if (世.搜索.枯竭概率 < 0 || 世.搜索.枯竭概率 > 100)
                        校验错误.Add($"{名} → 搜索枯竭概率 {世.搜索.枯竭概率} 不在 0~100");
                    if (世.搜索.枯竭半径 > 0 && 世.搜索.枯竭概率 >= 世.搜索.出现概率)
                        校验错误.Add($"{名} → 搜索枯竭概率 {世.搜索.枯竭概率} ≥ 出现概率 {世.搜索.出现概率}："
                                  + "局部枯竭就失效了（站在翻过的地方不该更容易出新东西）");
                    // ② 越翻越累
                    if (世.搜索.每多一次多花行动点 < 0)
                        校验错误.Add($"{名} → 搜索 每多一次多花行动点 不能是负数");
                    if (世.搜索.枯竭半径 <= 0 && 世.搜索.每多一次多花行动点 <= 0)
                        校验警告.Add($"{名} → 搜索的两条防刷约束**都关着**（枯竭半径 = 0 且 每多一次多花行动点 = 0）"
                                  + "：玩家可以站在安全屋门口一直搜，把探索区域整个跳过");
                    // ③ 楼型白名单 + 禁区清单 + 允许地图类型
                    var 禁 = new HashSet<string>();
                    if (世.搜索.禁区楼型 != null)
                        foreach (var s in 世.搜索.禁区楼型)
                        {
                            if (string.IsNullOrEmpty(s)) continue;
                            禁.Add(s);
                            if (!建筑模板.ContainsKey(s)) 校验错误.Add($"{名} → 搜索禁区楼型[{s}] 不存在（建筑模板里没有）");
                        }
                    if (世.搜索.临时建筑 != null && 世.搜索.临时建筑.Length > 0)
                    {
                        int 总权 = 0;
                        foreach (var 项 in 世.搜索.临时建筑)
                        {
                            if (项 == null || string.IsNullOrEmpty(项.建筑模板)) { 校验错误.Add($"{名} → 搜索白名单有项没写 建筑模板"); continue; }
                            if (!建筑模板.ContainsKey(项.建筑模板))
                                校验错误.Add($"{名} → 搜索白名单楼型[{项.建筑模板}] 不存在（建筑模板里没有）");
                            // ★ 这一条是白名单存在的**全部理由**：区专属楼型一旦进了池子，
                            //   玩家第 1 天就能在安全屋门口刷出手枪弹/血清/军刀图纸，把 天数≥3/6/10 的门架空
                            if (禁.Contains(项.建筑模板))
                                校验错误.Add($"{名} → 搜索白名单楼型[{项.建筑模板}] 在**禁区清单**里："
                                          + "临时建筑不许出区专属楼型（会把区域的解锁门架空）");
                            if (项.权重 <= 0) 校验错误.Add($"{名} → 搜索白名单楼型[{项.建筑模板}] 权重 {项.权重} 不是正数");
                            总权 += Math.Max(1, 项.权重);
                        }
                        if (总权 <= 0) 校验错误.Add($"{名} → 搜索白名单 总权重为 0");
                    }
                    else
                        校验警告.Add($"{名} → 搜索没写 临时建筑 白名单：会走兜底（全部楼型里滤掉禁区楼型）");

                    // 允许地图类型：白名单楼型的房间容器池**只许**引用它们。
                    // 为什么查这条：白名单只保证"楼型不是区专属的"，防不住"有人把医院房间塞进便利店"——
                    //   那样临时建筑照样能拉出抗生素/血浆。这条把"奖励越级"从数据层面彻底焊死。
                    if (世.搜索.临时建筑 != null && 世.搜索.临时建筑.Length > 0)
                    {
                        var 允许 = new HashSet<string>();
                        if (世.搜索.允许地图类型 == null || 世.搜索.允许地图类型.Length == 0)
                            校验错误.Add($"{名} → 搜索写了白名单却没写 允许地图类型（没法核对容器池）");
                        else
                            foreach (var t in 世.搜索.允许地图类型)
                            {
                                if (string.IsNullOrEmpty(t)) continue;
                                允许.Add(t);
                                if (!搜索地图类型.ContainsKey(t)) 校验错误.Add($"{名} → 搜索允许地图类型[{t}] 不存在（搜索_地图类型.json 里没有）");
                            }
                        foreach (var 项 in 世.搜索.临时建筑)
                        {
                            if (项 == null || string.IsNullOrEmpty(项.建筑模板)) continue;
                            if (!建筑模板.TryGetValue(项.建筑模板, out var 建) || 建.楼层 == null) continue;
                            foreach (var 层 in 建.楼层)
                            {
                                if (层?.房间 == null) continue;
                                foreach (var 房标 in 层.房间)
                                {
                                    if (string.IsNullOrEmpty(房标) || !房间模板.TryGetValue(房标, out var 房)) continue;
                                    if (房.容器池 == null) continue;
                                    foreach (var 池 in 房.容器池)
                                    {
                                        if (池 == null || string.IsNullOrEmpty(池.地图类型)) continue;
                                        if (允许.Contains(池.地图类型)) continue;
                                        校验错误.Add($"{名} → 搜索白名单楼型[{项.建筑模板}] 的房间[{房标}] "
                                                  + $"容器池引用了 地图类型[{池.地图类型}]，但它不在 允许地图类型 里"
                                                  + "（临时建筑不许拉区专属战利品）");
                                    }
                                }
                            }
                        }
                    }
                }
            }

            // ================= 职业 / 天赋（保留但暂时不补内容） =================
            // ⚠ 这一块**故意只报 校验警告、不报 校验错误**：用户拍板「职业/天赋暂时不补充，但保留」
            //   （见 docs/大世界网格与副本设计.md §6.3 与 §16.1）。所以**不能**把它们判成错误挡进游戏。
            //   但**不能不报** —— 这几条在运行时全是**静默失效**，不报就等于让人以为它们生效了：
            //     · 职业.初始技能 → PlayerService:109 `TryGetValue` 不中 → 静默 continue，这个职业开局没技能
            //     · 职业.天赋     → PlayerService:123 **不查表**，直接塞进 档案.天赋 → 一条永远不生效的天赋
            //     · 职业.初始装备 → 档案.添加物品 也不查表 → 一件 items 里没有的东西进了背包
            //   照项目纪律「别静默」把每一条都报出来，等要补内容时照着这份清单补。
            //   （离线那一半在 Tools/数据引用核对.ps1 —— 不打开 Unity 也能看到同一批问题。）
            foreach (var (标识, 职) in 职业)
            {
                string 名 = $"职业[{标识}]";
                if (!string.IsNullOrEmpty(职.初始技能) && !技能.ContainsKey(职.初始技能))
                    校验警告.Add($"{名} → 初始技能[{职.初始技能}] 不在 skills.json：这个职业开局学不到它");
                if (!string.IsNullOrEmpty(职.天赋) && !天赋.ContainsKey(职.天赋))
                    校验警告.Add($"{名} → 天赋[{职.天赋}] 不在 天赋.json：会被塞进 档案.天赋 但永远不生效");
                if (职.初始装备 == null) continue;
                foreach (var 项 in 职.初始装备)
                    if (项 != null && !string.IsNullOrEmpty(项.标识) && !物品.ContainsKey(项.标识))
                        校验警告.Add($"{名} → 初始装备[{项.标识}] 不在 items：会进背包，但是件没有定义的东西");
            }
        }
    }

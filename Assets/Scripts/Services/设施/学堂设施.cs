// 诊所设施（原学堂）：教学（医疗/急救技能）+ 买卖（医疗品/技能书）+ 训练
// 技能学习交给 技能服务（属性前提统一判定），买卖/训练委托共用助手，设施只做"教什么/卖什么"筛选。
public sealed class 学堂设施 : 设施逻辑, 教学功能, 买卖功能, 训练功能
{
    private 买卖逻辑 买卖助手;
    private 训练逻辑 训练助手;
    private 买卖逻辑 买卖 => 买卖助手 ??= new 买卖逻辑(玩家, 数据, 事件);
    private 训练逻辑 训练 => 训练助手 ??= new 训练逻辑(玩家, 数据, 事件);

    // 教学：诊所教 急救/医疗类 技能（智慧派系）
    public 技能数据[] 可学技能() => ServiceRegistry.Get<技能服务>().技能列表(技能 => 技能.类别枚举 == 技能类别.治疗 || 技能.标识.Contains("急救") || 技能.标识.Contains("医疗"));
    public bool 尝试学习(string 技能标识) => ServiceRegistry.Get<技能服务>().尝试学习(技能标识);

    // 买卖：医疗/技能书
    public 物品数据[] 可购商品() => 买卖.可购商品(物品 => 物品.类型 == "医疗" || 物品.类型 == "技能书");
    public bool 尝试购买(string 物品标识) => 买卖.尝试购买(物品标识);
    // 卖出：只收医疗/技能书/材料
    public 物品堆叠[] 可卖物品() => 买卖.可卖物品(物品 => 物品.类型 == "医疗" || 物品.类型 == "技能书" || 物品.类型 == "材料");
    public bool 尝试卖出(string 物品标识) => 买卖.尝试卖出(物品标识);

    // 训练
    public 训练项目[] 可训项目() => 训练.可训项目();
    public bool 尝试训练(string 项目标识) => 训练.尝试训练(项目标识);
    public 技能数据[] 可练熟练技能() => 训练.可练熟练技能();
    public int 熟练训练花费(string 技能标识) => 训练.熟练训练花费(技能标识);
    public int 每级熟练度(技能数据 技能) => 训练.每级熟练度(技能);
    public bool 尝试熟练训练(string 技能标识) => 训练.尝试熟练训练(技能标识);
}

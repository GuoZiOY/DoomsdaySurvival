// 交易站设施（原商店）：买卖功能（委托 买卖逻辑；交易站收售通用物资）
public sealed class 商店设施 : 设施逻辑, 买卖功能
{
    private 买卖逻辑 助手;
    private 买卖逻辑 买卖 => 助手 ??= new 买卖逻辑(玩家, 数据, 事件);

    // 通用商品：价值>0 且非任务品（图纸 可买）
    public 物品数据[] 可购商品() => 买卖.可购商品(物品 => 物品.价值 > 0 && 物品.类型 != "任务品");
    public bool 尝试购买(string 物品标识) => 买卖.尝试购买(物品标识);
    // 交易站什么都收（价值>0 内滤；任务品/技能书 不可卖——卖了就没用了）
    public 物品堆叠[] 可卖物品() => 买卖.可卖物品(物品 => 物品.类型 != "任务品" && 物品.类型 != "技能书");
    public bool 尝试卖出(string 物品标识) => 买卖.尝试卖出(物品标识);
}

// 家设施：睡觉功能（恢复生命/行动点/疲劳，推进时间到次日 6:00——末日营地睡觉）
public sealed class 家设施 : 设施逻辑, 睡觉功能
{
    public string 睡觉描述() => "躺到床上，睡到天亮。";

    public bool 尝试睡觉()
    {
        玩家.睡觉();
        事件.发布(new 生命变化事件(玩家.生命, 玩家.最大生命, 玩家.生命));
        事件.发布(new 精力变化事件(玩家.行动点, 玩家.最大行动点, 玩家.行动点));
        事件.发布(new 伤病变化事件(伤病类型.疲劳, 玩家.疲劳, 0));
        // 感冒/流血/发烧/中毒 也在 睡觉() 中缓慢恢复
        foreach (伤病类型 类型 in System.Enum.GetValues(typeof(伤病类型)))
            if (类型 != 伤病类型.疲劳)
                事件.发布(new 伤病变化事件(类型, 玩家.伤病值(类型), 0));
        事件.发布(new 日志事件(日志类型.生存, "你睡了一觉。天亮了，新的一天。"));
        return true;
    }
}

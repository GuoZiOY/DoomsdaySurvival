// 家设施：睡觉功能（恢复满状态：生命/魔力/精力；时间推进后续接 游戏时钟）
public sealed class 家设施 : 设施逻辑, 睡觉功能
{
    public string 睡觉描述() => "躺到床上，睡到天亮。";

    public bool 尝试睡觉()
    {
        玩家.生命 = 玩家.最大生命;
        玩家.魔力 = 玩家.最大魔力;
        玩家.精力 = 玩家.最大精力;
        事件.发布(new 生命变化事件(玩家.生命, 玩家.最大生命, 玩家.生命));
        事件.发布(new 魔力变化事件(玩家.魔力, 玩家.最大魔力, 玩家.魔力));
        事件.发布(new 精力变化事件(玩家.精力, 玩家.最大精力, 玩家.精力));
        事件.发布(new 日志事件(日志类型.反馈, "你睡了一觉，恢复了全部状态。"));
        return true;
    }
}

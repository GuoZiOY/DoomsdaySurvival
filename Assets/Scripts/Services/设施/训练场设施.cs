// 训练场设施：训练功能（属性训练 + 熟练训练，委托 训练逻辑）
public sealed class 训练场设施 : 设施逻辑, 训练功能
{
    private 训练逻辑 助手;
    private 训练逻辑 训练 => 助手 ??= new 训练逻辑(玩家, 数据, 事件);

    public 训练项目[] 可训项目() => 训练.可训项目();
    public bool 尝试训练(string 项目标识) => 训练.尝试训练(项目标识);
    public 技能数据[] 可练熟练技能() => 训练.可练熟练技能();
    public int 熟练训练花费(string 技能标识) => 训练.熟练训练花费(技能标识);
    public bool 尝试熟练训练(string 技能标识) => 训练.尝试熟练训练(技能标识);
    public int 每级熟练度(技能数据 技能) => 训练.每级熟练度(技能);
}

using UnityEngine;

// 世界时间管理器：统一管理 游戏内时间 的 推进/结算/跳时——挂机、制作、睡觉 等 一切 时间 变化 都 收敛 到这里。
// 职责：
//   ① 推进（挂机 驱动 每帧）：现实 秒 → 游戏 分钟；跨天 → 随机 天气；满 1 游戏时 → 统一 结算。
//   ② 结算时间段(分钟, 含饱食水分)：饱食/水分 基础 2/2 + 伤病 持续 + 疲劳 恢复 + 寒潮 感冒（余数 按 比例）。
//   ③ 跳时（制作 动画 / 未来 其他 一次性 推进）：只 推 时间 + 跨天 天气；副作用 由 调用方 按 需 结算。
//   ④ 同步整点基准：外部 跳时 后 调用，防 挂机 整点 重复 结算。
//   ⑤ 状态 修改 统一 出口：进食/饮水/调整伤病（float 精确 0.1）。
// 事件 发布：整点 结算 / 跳时 后 发布 时间变化 + 生存状态变化 + 伤病变化（HUD 等 订阅 刷新）。
// 驱动：内嵌 MonoBehaviour（世界时间管理器.驱动），GameBootstrap 装配时 自动 挂 场景 常驻 物体（替代 旧 游戏时钟）。
public sealed class 世界时间管理器
{
    private readonly EventBus 事件;
    private 玩家档案 玩家 => ServiceRegistry.Get<PlayerService>().档案;

    // 时间 速率：1 现实 分钟 = 30 游戏 分钟（一天 1440 游戏 分钟 = 48 现实 分钟）；每 现实 秒 = 0.5 游戏 分钟
    public const float 每现实分钟游戏分钟 = 30f;

    // 挂机 整点 结算 基准（上次 已 结算 的 游戏 分钟；外部 跳时 后 同步，防 重复 结算）
    private float 上次结算分钟;
    private int 上次天 = -1;

    // ★ 刀64：整点结算基准是**存档载荷的一部分**（见 存档模型.存档数据.整点基准）。
    // 为什么必须进档：推进() 的 while 拿它当"已经结算到哪"的比较对象，而它原本是纯运行期字段、初值 **0**。
    // 读一张第 5 天的档：基准 0 而 游戏分钟数 ≈ 7200 → 同一帧里补算 120 次 结算时间段(60,true)
    // → 饱食/水分归零 → 按 3 点/小时扣满血 → 腐坏结算把仓库清空 = **读档即死**。
    public float 整点基准 => 上次结算分钟;

    // 当前是第几天（跨天判定 与 读档对齐 共用一份算法，别写两遍）
    private static int 当前天(玩家档案 玩家) => (int)(玩家.游戏分钟数 / 1440f);

    // ★ 刀64：**新游戏 / 读档 之后必须调一次** —— 把两个运行期基准对到（存档里的）游戏时间上。
    //   · 基准 = 存档里记的那一个（保住"不足 1 整点的那一截"，否则读档白送/白扣最多 1 小时消耗）；
    //     存档缺这个字段（v4 旧档）或值越界 → 退化为当前分钟（安全等价选择）。
    //   · 天   = **当前天**（不是存档里的天）：这样 检查跨天() 不会在读档首帧触发，
    //     存档里的 天气 / 预知天气 才不会"读档即被重掷"（旧行为：读档当天天气必被 Random 换掉，并吃掉收音机的预知）。
    public void 读档后对齐(float 存档基准分钟)
    {
        var 玩家 = ServiceRegistry.Get<PlayerService>()?.档案;
        if (玩家 == null) return;
        上次结算分钟 = (存档基准分钟 > 0f && 存档基准分钟 <= 玩家.游戏分钟数)
            ? 存档基准分钟 : 玩家.游戏分钟数;
        上次天 = 当前天(玩家);
    }

    // 距 上次 整点 结算 已 流逝 的 游戏 分钟（0~60；面板 平滑 显示 进度 用：净化 等 整点 粒度 结算 的 中间 值）
    public float 距上次结算游戏分钟 => 玩家 != null ? Mathf.Max(0f, 玩家.游戏分钟数 - 上次结算分钟) : 0f;

    public 世界时间管理器(EventBus 事件)
    {
        this.事件 = 事件;
    }

    // ===== ① 推进（挂机 驱动 每帧 调用） =====

    // 现实 秒 → 游戏 时间 推进；跨天 随机 天气；满 整点（上次 结算 起 ≥ 60 游戏 分钟）→ 统一 结算（含 饱食/水分）
    public void 推进(float 现实秒)
    {
        var 玩家 = ServiceRegistry.Get<PlayerService>()?.档案;
        if (玩家 == null) return;
        float 游戏分钟 = 现实秒 / 60f * 每现实分钟游戏分钟;
        玩家.游戏分钟数 += 游戏分钟;
        检查跨天(玩家);
        // 净化 逐帧 推进（净水器 等：平滑 进度条；数量 少 成本 低；挂机 时间 走 → 净化 走）
        净化推进(游戏分钟);
        // 生长 逐帧 推进（种植箱：平滑 倒计时；挂机 时间 走 → 生长 走，与 净化 同 模式）
        生长推进(游戏分钟);
        // 阅读 逐帧 推进（书籍 读满 → 结算 习得/失败；挂机 时间 走 → 阅读 走，与 生长/净化 同 模式）
        ServiceRegistry.Get<书籍服务>()?.阅读推进(游戏分钟);
        // ★ 刀61：敌人的行动走**游戏时间**，而且**三层都要喂**（大世界 / 区域 / 房间）。
        //   本作是**即时制**（不是回合制）—— "站着不动敌人就冻结"是 bug，不是取舍。
        //   与 净化/生长/阅读 同一个模式；走路时 推进一步→推进时钟 也会走到这里
        //   （玩家每格消耗本层的 移动游戏分钟 5 / 1 / 1 → "走 N 格它走 1 格"的平衡三层都成立）。
        //   三份都调：只有"当前所在的那一层"当前世界非空，其余两层会自己早退。
        ServiceRegistry.Get<大世界探索服务>()?.时间推进(游戏分钟);
        ServiceRegistry.Get<区域探索服务>()?.时间推进(游戏分钟);
        ServiceRegistry.Get<房间探索服务>()?.时间推进(游戏分钟);
        // 整点 结算：从 上次 结算 点 起 每 满 60 游戏 分钟 结算 一次
        // ★ 刀64：循环与"是否需要自愈重对齐"的计算搬到了 `整点结算`（纯 C#，Domain/时间）——
        //   这样离线验证器（Tools/存档验证）跑的是**游戏同一份代码**，而不是照抄一遍的副本。
        //   这个 bug 的表现是"读档即死"，静默自愈等于把它藏起来 —— 所以要出声。
        if (整点结算.需要重对齐(玩家.游戏分钟数, 上次结算分钟, out float 基准差))
        {
            Debug.LogWarning($"[世界时间] 整点基准与游戏时间相差 {(int)基准差} 游戏分钟（新游戏/读档没对齐？）—— 已重新对齐。");
            上次结算分钟 = 玩家.游戏分钟数;
            上次天 = 当前天(玩家);
        }
        bool 结算了 = false;
        int 结算次数 = 整点结算.应结算次数(玩家.游戏分钟数, 上次结算分钟, out float 新基准);
        if (结算次数 > 0)
        {
            上次结算分钟 = 新基准;
            for (int i = 0; i < 结算次数; i++) 结算时间段(60, true);
            结算了 = true;
        }
        if (结算了) 发布状态事件(玩家);
    }

    // ===== ② 统一 结算 =====

    // 任意 推进 的 游戏 分钟 都 走 这里：饱食/水分 基础 消耗（每 游戏 时 各 2）+ 伤病 持续 + 疲劳 恢复 + 寒潮 感冒。
    // 含饱食水分：true = 挂机（按 基础 速率 扣 饱食/水分）；false = 制作/跳时（饱食/水分 已 按 配方 另 扣，只 补 副作用）。
    // 余数 按 比例：不足 1 游戏 时 的 分钟 按 比例 折算（疲劳/伤病/寒潮 判定 次数 = 向上 取整）。
    public void 结算时间段(int 分钟, bool 含饱食水分)
    {
        if (分钟 <= 0) return;
        float 时数 = 分钟 / 60f;
        var 天气 = (天气类型)玩家.天气;
        // 饱食/水分 基础 下降（体质/天赋 修正；雨天 补水 / 酷暑 耗水）——float 精确 0.1
        if (含饱食水分)
        {
            float 扣饱 = 2 * 饱食下降修正 * 时数;
            float 扣水 = 2 * 水分下降修正 * 时数;
            if (天气 == 天气类型.雨 || 天气 == 天气类型.雷雨) 扣水 -= 1f * 时数;
            if (天气 == 天气类型.酷暑) 扣水 += 2f * 时数;
            玩家.饱食度 = 夹(玩家.饱食度 - 扣饱, 0, 100);
            玩家.水分度 = 夹(玩家.水分度 - 扣水, 0, 100);
        }
        // 寒潮：无 火炉/厚衣 可能 感冒（每小时 判定 一次，次数 向上 取整；灶台 保暖 豁免）
        if (天气 == 天气类型.寒潮 && 玩家.感冒 == 0)
        {
            int 灶台豁免 = 玩家.家具效果("灶台");   // 灶台 家具：1=概率减半 / 2+=完全豁免（等级效果）
            if (灶台豁免 < 2)
            {
                int 判定次数 = Mathf.CeilToInt(时数);
                for (int i = 0; i < 判定次数 && 玩家.感冒 == 0; i++)
                {
                    int 感冒阈值 = 玩家.意志 * 3;
                    if (玩家.天赋.Contains("慢性病")) 感冒阈值 /= 2;
                    if (灶台豁免 >= 1) 感冒阈值 *= 2;   // 灶台 1 级：有火，感冒概率减半
                    if (随机(100) > 感冒阈值) 玩家.感冒 = 5;
                }
            }
        }
        // 疲劳 缓慢 恢复（行动时 累积，这里 基础 恢复；按 时数 比例）
        玩家.疲劳 = (int)夹(玩家.疲劳 - 1 * 时数, 0, 100);
        // 伤病 持续 掉血（按 时数 比例，至少 1）
        if (玩家.流血 > 0) 玩家.生命 = Mathf.Max(0, 玩家.生命 - Mathf.Max(1, Mathf.RoundToInt((玩家.流血 / 20f + 1) * 时数)));
        if (玩家.中毒 > 0) 玩家.生命 = Mathf.Max(0, 玩家.生命 - Mathf.Max(1, Mathf.RoundToInt((玩家.中毒 / 25f + 1) * 时数)));
        if (玩家.发烧 > 0) 玩家.生命 = Mathf.Max(0, 玩家.生命 - Mathf.Max(1, Mathf.RoundToInt((玩家.发烧 / 30f + 1) * 时数)));
        // 饱食/水分 归零：不致死，只 削弱（持续 少量 掉血 警示）
        if (玩家.饱食度 <= 0) 玩家.生命 = Mathf.Max(0, 玩家.生命 - Mathf.Max(1, Mathf.RoundToInt(1 * 时数)));
        if (玩家.水分度 <= 0) 玩家.生命 = Mathf.Max(0, 玩家.生命 - Mathf.Max(1, Mathf.RoundToInt(2 * 时数)));
        // 腐坏 结算：易腐 物品 随 时间 变质（常温 扣减；冰箱 内 按 倍率 减速）
        腐坏结算(分钟);
        // 生长 不 在 整点 结算（生长推进 已 在 推进()/跳时() 逐帧 走，与 净化 同 模式——避免 双 扣）
        // 净化 不 在 整点 结算（净化推进 已 在 推进() 逐帧 走，避免 双 扣）
    }

    // ===== 腐坏 结算（易腐 物品 随 时间 变质） =====

    // 遍历 所有 持有 物品（穿戴容器+仓库+嵌套）+ 家具 容器 物品（冰箱 内）：
    //   惰性 初始化：新鲜分钟<=0 且 物品 有 保质期 → 补 保质期×60（兼容 旧档/漏 初始化）
    //   扣减：常温 -分钟；冰箱 内 -分钟 ÷ 倍率
    //   变质：新鲜分钟 <=0 且 已 初始化 → 替换 为 "腐坏食物"（数量 不变）
    private void 腐坏结算(int 分钟)
    {
        if (分钟 <= 0) return;
        var 数据 = ServiceRegistry.Get<DataService>();
        if (数据 == null) return;
        bool 有变化 = false;
        foreach (var 堆叠 in 玩家.所有持有物品())
            if (堆叠 != null) 有变化 |= 腐坏单个(堆叠, 分钟, 1, 数据);
        // 家具 容器（冰箱 等 在 安全屋）：内部 物品 按 家具 保鲜 倍率 减速；
        // 就地转化 家具（种植箱/晾晒架）例外——内 物品 不 腐坏（种子/作物 与 正在晾的肉/皮）
        foreach (var 家具 in 玩家.家具)
        {
            if (家具?.容器物品 == null) continue;
            var (家具定义标识, _) = 家具工具.解码(家具.标识);
            if (数据.家具.TryGetValue(家具定义标识, out var 家具定义) && 家具工具.是就地转化家具(家具定义)) continue;
            float 倍率 = 家具保鲜倍率(家具);
            foreach (var 堆叠 in 家具.容器物品)
                if (堆叠 != null) 有变化 |= 腐坏单个(堆叠, 分钟, 倍率, 数据);
        }
        if (有变化)
            事件?.发布(new 背包变化事件("", 0, 变化原因.获得));   // 触发 网格/容器 面板 刷新（变质 替换）
    }

    // 单个 物品 腐坏 处理：返回 是否 状态 变化（初始化/变质）
    private bool 腐坏单个(物品堆叠 堆叠, int 分钟, float 倍率, DataService 数据)
    {
        if (堆叠 == null || string.IsNullOrEmpty(堆叠.标识) || 堆叠.标识 == "腐坏食物") return false;
        if (!数据.物品.TryGetValue(堆叠.标识, out var 模板) || 模板.保质期 <= 0) return false;   // 无 保质期 = 永久
        // 惰性 初始化（新鲜分钟 0 = 未 初始化/旧档）：补 保质期×60
        if (堆叠.新鲜分钟 <= 0)
        {
            堆叠.新鲜分钟 = 模板.保质期 * 60f;
            return true;
        }
        堆叠.新鲜分钟 -= 分钟 / Mathf.Max(1f, 倍率);
        if (堆叠.新鲜分钟 > 0) return false;
        // 变质：替换 为 腐坏食物（保持 数量/位置；清 新鲜分钟 = 0 表示 已 变质 不再 扣）
        堆叠.标识 = "腐坏食物";
        堆叠.新鲜分钟 = 0;
        return true;
    }

    // 家具 保鲜 倍率：冰箱 等 容器 家具（家具数据.保质期倍率[等级-1]；非 容器/无 配置 = 1 常温）
    private float 家具保鲜倍率(物品堆叠 家具)
    {
        var 数据 = ServiceRegistry.Get<DataService>();
        if (数据 == null) return 1f;
        var (定义标识, 等级) = 家具工具.解码(家具.标识);
        if (!数据.家具.TryGetValue(定义标识, out var 定义) || 定义.保质期倍率 == null || 定义.保质期倍率.Length == 0) return 1f;
        int 索引 = Mathf.Clamp(等级 - 1, 0, 定义.保质期倍率.Length - 1);
        return 定义.保质期倍率[索引] > 0 ? 定义.保质期倍率[索引] : 1f;
    }

    // ===== 就地转化 推进（种植箱 内 种子 → 成熟 / 晾晒架 上 生肉·兽皮 → 肉干·皮革）=====
    // 两件家具**共用同一套字段与同一个推进器**（物品数据.转化用途 / 生长时间 / 成熟产物；堆叠.生长分钟）：
    //   种植箱 = 种子发芽（土豆种子 24 游戏时 → 土豆）
    //   晾晒架 = 风干与硝制（生肉 12 游戏时 → 肉干 / 兽皮 24 游戏时 → 皮革）
    // 归属 判定：物品.转化用途 必须 等于 家具.功能类型（家具工具.可就地转化）——
    //   所以 种子 扔 在 晾晒架 上 只 会 干等着（不 转化），生肉 扔 在 种植箱 里 同理。
    // 生长分钟 记 在该 堆叠 上（距 转化 剩余 游戏 分钟；随档）：
    //   惰性 初始化：<=0 且 可转化（生长时间>0 且 有 成熟产物）→ 补 生长时间×60（满 起点；兼容 旧档）
    //   扣减：-**加速后的游戏分钟**；到点（<=0）→ 就地替换 为 成熟产物（数量不变；清 生长分钟 防 重 替换）
    //   加速 = 家具效果（种植箱/晾晒架 的 效果[等级-1]，0/25/50 = +0%/+25%/+50%）—— 让升级真的有收益
    private void 生长推进(float 游戏分钟)
    {
        if (游戏分钟 <= 0) return;
        var 数据 = ServiceRegistry.Get<DataService>();
        if (数据 == null) return;
        bool 有变化 = false;
        foreach (var 家具堆叠 in 玩家.家具)
        {
            if (家具堆叠?.容器物品 == null) continue;
            var (定义标识, _) = 家具工具.解码(家具堆叠.标识);
            if (!数据.家具.TryGetValue(定义标识, out var 家具定义)) continue;
            if (!家具工具.是就地转化家具(家具定义)) continue;   // 只有 种植箱/晾晒架 这两类 会 就地转化
            float 加速 = 1f + 玩家.家具效果(定义标识) / 100f;             // 0 级 破损 = 效果 减半（家具效果 已处理）
            foreach (var 堆叠 in 家具堆叠.容器物品)
                if (堆叠 != null) 有变化 |= 生长推进单个(堆叠, 游戏分钟 * 加速, 数据, 家具定义);
        }
        if (有变化)
            事件?.发布(new 背包变化事件("", 0, 变化原因.获得));   // 触发 网格/容器 面板 刷新（成熟 替换）
    }

    // 单个 可转化物 推进：返回 是否 状态 变化（初始化/转化 替换）
    private bool 生长推进单个(物品堆叠 堆叠, float 游戏分钟, DataService 数据, 家具数据 家具定义)
    {
        if (堆叠 == null || string.IsNullOrEmpty(堆叠.标识)) return false;
        if (!数据.物品.TryGetValue(堆叠.标识, out var 模板)) return false;
        if (!家具工具.可就地转化(模板, 家具定义)) return false;   // 不 是 这件 家具 管 的（用途 不符）= 不 转化、也 不 初始化
        // 惰性 初始化（生长分钟 0 = 未 初始化/旧档）：补 生长时间×60
        if (堆叠.生长分钟 <= 0)
        {
            堆叠.生长分钟 = 模板.生长时间 * 60f;
            return true;
        }
        堆叠.生长分钟 -= 游戏分钟;
        if (堆叠.生长分钟 > 0) return false;
        // 成熟：替换 为 成熟产物（保持 数量/位置；清 生长分钟 = 0 表示 已 成熟 不再 长）
        堆叠.标识 = 模板.成熟产物;
        堆叠.生长分钟 = 0;
        return true;
    }

    // ===== 净化 推进（净水器 等 自动 净化 家具：逐帧 平滑——挂机 时间 走 净水器 走） =====

    // 净水器 = 分区容器 家具 + 净化配置（家具数据.净化间隔分>0；材料A/B 分区 0/1，产物 分区 2）。
    // 净化分钟 记 净水器 实例 堆叠 上（本批 距 完成 剩余 游戏 分钟；随档，平滑 递减）：
    //   惰性 初始化：<=0 且 有 净化 配置 → 补 间隔分（满 批 起点；兼容 旧档/漏 初始化）
    //   扣减：材料 齐 + 净水 区 可放 → -游戏分钟；缺 材料/产物 区 满 → 冻结（进度 保留，条件 恢复 继续）
    //   完成（<=0）：扣 材料A/B 各 1 → 产物 区 放 1 → 本批 结束 + 间隔分（下 批 满 起点）
    private void 净化推进(float 游戏分钟)
    {
        if (游戏分钟 <= 0) return;
        var 数据 = ServiceRegistry.Get<DataService>();
        if (数据 == null) return;
        bool 有变化 = false;
        foreach (var 净水器 in 玩家.家具)
        {
            if (净水器?.容器物品 == null) continue;
            var (定义标识, _) = 家具工具.解码(净水器.标识);
            if (!数据.家具.TryGetValue(定义标识, out var 定义)) continue;
            if (定义.净化间隔分 <= 0 || string.IsNullOrEmpty(定义.净化材料A)
                || string.IsNullOrEmpty(定义.净化材料B) || string.IsNullOrEmpty(定义.净化产物)) continue;   // 非 净化 家具
            var 容器服务 = ServiceRegistry.Get<容器服务>();
            if (容器服务 == null) continue;
            // 分区 未 初始化（从未 打开 过 面板）→ 先 初始化（幂等：已 建 子容器 则 直接 返回）
            if (净水器.容器物品 == null || 净水器.容器物品.Count == 0)
                容器服务.初始化容器(净水器);
            var 材料A区 = 容器服务.分区子容器(净水器, 0);
            var 材料B区 = 容器服务.分区子容器(净水器, 1);
            var 产物区 = 容器服务.分区子容器(净水器, 2);
            if (材料A区 == null || 材料B区 == null || 产物区 == null) continue;
            // 惰性 初始化（净化分钟 <=0 = 未 初始化/旧档）：补 间隔分（满 批 起点）
            if (净水器.净化分钟 <= 0) 净水器.净化分钟 = 定义.净化间隔分;
            // 缺 材料 或 产物 区 满 → 冻结（进度 保留 在 当前 剩余，条件 恢复 继续）
            if (!区内有(材料A区, 定义.净化材料A) || !区内有(材料B区, 定义.净化材料B)
                || !区内可放(容器服务, 产物区, 定义.净化产物))
                continue;
            净水器.净化分钟 -= 游戏分钟;
            while (净水器.净化分钟 <= 0)
            {
                // 完成 一批：扣 材料 → 产 物（产物 区 满 兜底：不 扣 料，进度 卡 0.5 等 空间）
                区扣(材料A区, 定义.净化材料A, 1);
                区扣(材料B区, 定义.净化材料B, 1);
                var 产物视图 = 容器服务.打开(产物区);
                int 放入 = 产物视图.放入网格(定义.净化产物, 定义.净化产物数量);
                if (放入 <= 0)
                {
                    材料A区.容器物品 ??= new System.Collections.Generic.List<物品堆叠>();
                    材料B区.容器物品 ??= new System.Collections.Generic.List<物品堆叠>();
                    var 视图A = 容器服务.打开(材料A区);
                    var 视图B = 容器服务.打开(材料B区);
                    视图A.放入网格(定义.净化材料A, 1);
                    视图B.放入网格(定义.净化材料B, 1);
                    净水器.净化分钟 = 0.5f;
                    break;
                }
                净水器.净化分钟 += 定义.净化间隔分;   // 本批 完成 → 下 批 满 起点（材料 足 则 连续 产）
                有变化 = true;
            }
        }
        if (有变化)
            事件?.发布(new 背包变化事件("", 0, 变化原因.获得));   // 触发 净水器 面板 刷新（出 水）
    }

    // 分区 内 是否 有 该 标识（净化 材料 检查）
    private static bool 区内有(物品堆叠 子容器, string 标识)
    {
        if (子容器?.容器物品 == null) return false;
        foreach (var 堆叠 in 子容器.容器物品)
            if (堆叠 != null && 堆叠.标识 == 标识 && 堆叠.数量 > 0) return true;
        return false;
    }

    // 净化 区 是否 可 放入（产物 区 满 判定：同类 未满 堆叠 可 叠 或 网格 有 空位）
    private bool 区内可放(容器服务 容器服务, 物品堆叠 子容器, string 标识)
    {
        if (子容器?.容器物品 == null) return false;
        // 已有 同类 且 未 满 堆叠 上限 → 可 叠
        foreach (var 堆叠 in 子容器.容器物品)
            if (堆叠 != null && 堆叠.标识 == 标识 && 堆叠.数量 > 0)
                return true;
        // 无 同类：网格 找 空位（可 开 新 堆叠）
        var 视图 = 容器服务.打开(子容器);
        return 视图.寻找可放置格(new 物品堆叠(标识, 1)) != null;
    }

    // 从 分区 扣 指定 标识 数量（耗尽 移除）
    private static void 区扣(物品堆叠 子容器, string 标识, int 数量)
    {
        if (子容器?.容器物品 == null) return;
        for (int i = 子容器.容器物品.Count - 1; i >= 0; i--)
        {
            var 堆叠 = 子容器.容器物品[i];
            if (堆叠 == null || 堆叠.标识 != 标识) continue;
            堆叠.数量 -= 数量;
            if (堆叠.数量 <= 0) 子容器.容器物品.RemoveAt(i);
            return;
        }
    }

    // ===== ③ 跳时（制作 动画 / 一次性 推进：只 推 时间 + 跨天；副作用 由 调用方 结算） =====

    // 制作 动画 期间 推进：游戏 时间 随 进度 走，不 触发 整点 结算（制作 结束 统一 结算）——
    // 同时 同步 整点 基准（防 挂机 驱动 把 制作 推进 的 时间 再 结算 一遍）
    public void 跳时(float 游戏分钟)
    {
        var 玩家 = ServiceRegistry.Get<PlayerService>()?.档案;
        if (玩家 == null) return;
        玩家.游戏分钟数 += 游戏分钟;
        检查跨天(玩家);
        上次结算分钟 = 玩家.游戏分钟数;   // 同步 基准：这段 时间 的 副作用 由 制作 结算 负责
        // 净化 推进：制作 时间 流逝 → 净水器 同步 走（挂机 在 推进()，制作 在 跳时()——两 时间 流 都 覆盖）
        净化推进(游戏分钟);
        // 生长 推进：制作 时间 流逝 → 种植箱 同步 走（两 时间 流 都 覆盖，与 净化 同）
        生长推进(游戏分钟);
        // 阅读 推进：制作 时间 流逝 → 书籍 同步 读（两 时间 流 都 覆盖，与 生长/净化 同）
        ServiceRegistry.Get<书籍服务>()?.阅读推进(游戏分钟);
        // ★ 刀61：三层敌人 同理 —— 两条时间流（挂机 / 跳时）都要覆盖，否则"制作期间世界冻结"
        ServiceRegistry.Get<大世界探索服务>()?.时间推进(游戏分钟);
        ServiceRegistry.Get<区域探索服务>()?.时间推进(游戏分钟);
        ServiceRegistry.Get<房间探索服务>()?.时间推进(游戏分钟);
        事件?.发布(new 时间变化事件(玩家.游戏分钟数));
    }

    // 外部 跳时 后 同步 整点 基准（制作 取消 回滚 时间 后 也 调用，防 基准 漂移）
    public void 同步整点基准()
    {
        var 玩家 = ServiceRegistry.Get<PlayerService>()?.档案;
        if (玩家 == null) return;
        上次结算分钟 = 玩家.游戏分钟数;
    }

    // ===== ⑤ 状态 修改（统一 出口；float 精确 0.1） =====

    public void 进食(float 数值) => 玩家.饱食度 = 夹(玩家.饱食度 + 数值, 0, 100);
    public void 饮水(float 数值) => 玩家.水分度 = 夹(玩家.水分度 + 数值, 0, 100);

    // ===== 事件 发布（整点 结算 / 跳时 后：HUD 等 订阅 刷新） =====

    public void 发布状态事件(玩家档案 玩家)
    {
        事件?.发布(new 时间变化事件(玩家.游戏分钟数));
        事件?.发布(new 生存状态变化事件(生存状态类型.饱食度, 玩家.饱食度, 0));
        事件?.发布(new 生存状态变化事件(生存状态类型.水分度, 玩家.水分度, 0));
        foreach (伤病类型 类型 in System.Enum.GetValues(typeof(伤病类型)))
            事件?.发布(new 伤病变化事件(类型, 玩家.伤病值(类型), 0));
        if (玩家.生命 <= 0)
            事件?.发布(new 日志事件(日志类型.警告, "你倒下了……世界在你眼前暗去。"));
    }

    // ===== 跨天：随机 新 天气（收音机 预知 优先——预知 只 保 一天，用 后 清零） =====

    private void 检查跨天(玩家档案 玩家)
    {
        int 当天 = 当前天(玩家);
        if (当天 == 上次天) return;
        上次天 = 当天;
        var 天气 = 玩家.预知天气 >= 0 ? (天气类型)玩家.预知天气
            : (天气类型)Random.Range(0, System.Enum.GetValues(typeof(天气类型)).Length);
        玩家.天气 = (int)天气;
        玩家.预知天气 = -1;
        事件?.发布(new 天气变化事件(天气));
    }

    // ===== 工具 =====

    private static float 夹(float 值, float 最小, float 最大) => 值 < 最小 ? 最小 : (值 > 最大 ? 最大 : 值);
    private static int 随机(int 上限) => 上限 <= 0 ? 0 : Random.Range(0, 上限);

    // 饱食/水分 下降 速度 修正（体质 减缓；天赋"铁胃"减缓、"胃口大"加速）——与 生存管理器 同 规则
    public float 饱食下降修正
    {
        get
        {
            float 修正 = 1f - (玩家.体质 - 5) * 0.04f;
            if (玩家.天赋.Contains("铁胃")) 修正 -= 0.15f;
            if (玩家.天赋.Contains("胃口大")) 修正 += 0.6f;
            return Mathf.Max(0.2f, 修正);
        }
    }

    public float 水分下降修正
    {
        get
        {
            float 修正 = 1f - (玩家.体质 - 5) * 0.04f;
            if (玩家.天赋.Contains("口渴快")) 修正 += 0.6f;
            return Mathf.Max(0.2f, 修正);
        }
    }

    // ===== 驱动（内嵌 MonoBehaviour：挂 场景 常驻 物体，每帧 推进；替代 旧 游戏时钟） =====

    public sealed class 驱动 : MonoBehaviour
    {
        private void Update()
        {
            // ★ v51 刀17：**战斗时钟从 UI 面板搬到这里**（原来在 `战斗沙盒面板.Update`）。
            //   面板是可切换面板，隐藏 = SetActive(false) → Update 停 → 战斗内双方读条/冷却/眩晕全部冻结
            //   （玩家能无限"看牌"、从容挑道具）。刀15 只堵住"战斗中按 F1"那一条路，
            //   "引擎正确性挂在 UI 激活态上"的根还在。驱动是场景常驻物体，永远在跑 —— 面板只订阅渲染。
            var 战斗 = ServiceRegistry.Get<BattleService>();
            if (战斗 != null)
            {
                // 战斗中：时间由 BattleService.推进战斗 统一推进（行动条 + 战斗内时间流逝，不结算生存），
                // 挂机驱动暂停，防双时钟。
                if (战斗.战斗中) { 战斗.推进战斗(Time.deltaTime); return; }
                // 战斗刚结束：把上一帧登记的"自动回派"落地（结算与切层拆开，见 BattleService.结束战斗）
                战斗.处理自动回派();
            }
            var 管理器 = ServiceRegistry.Get<世界时间管理器>();
            if (管理器 == null) return;
            // ★ 刀64 / 步2：**未开局（主菜单 / 角色创建）时世界时间与敌人 AI 都不该走**。
            //   原来这里每帧无条件 推进() —— 在标题界面干坐 10 现实分钟 = 世上过去 300 游戏分钟，
            //   而 检查跨天() 还会在玩家还没进游戏时就把天气掷掉（并吃掉上一档的 预知天气）。
            //   ★ 步2 起改读 **游戏会话阶段**（原来读的是 `档案.当前节点` 是不是空 —— 那是"有没有存档价值"
            //     的判据，而"游戏有没有在跑"是另一件事；会话状态才是后者的唯一答案）。
            玩家档案 档 = ServiceRegistry.Get<PlayerService>()?.档案;
            if (档 == null || !游戏会话.是游戏里) return;
            管理器.推进(Time.deltaTime);
        }
    }

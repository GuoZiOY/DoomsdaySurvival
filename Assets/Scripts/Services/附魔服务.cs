using UnityEngine;

// 附魔服务：消耗 1 份「材料」物品，为单件装备附加随机词条（按装备品质取池）。
// 成功(70%) → 追加/升级一条随机词缀；失败(30%) → 装备本体损毁消散。
// 目标装备需为背包中「单件」堆叠（数量为 1 或已携带词缀的独立实例）。
public sealed class 附魔服务
{
    private readonly DataService 数据;
    private readonly PlayerService 玩家服务;
    private readonly EventBus 事件;
    private readonly 词缀服务 词缀;

    // 附魔失败 → 装备损坏概率
    public const float 损坏概率 = 0.30f;

    public 附魔服务(DataService 数据, PlayerService 玩家服务, EventBus 事件, 词缀服务 词缀)
    {
        this.数据 = 数据;
        this.玩家服务 = 玩家服务;
        this.事件 = 事件;
        this.词缀 = 词缀;
    }

    // 尝试附魔：消耗 1 份材料（类型="材料"），为 装备标识 的单件装备附加随机词条
    public bool 尝试附魔(string 装备标识, string 材料标识)
    {
        var 玩家 = 玩家服务.档案;

        // —— 验证 ——
        if (!数据.物品.TryGetValue(装备标识, out var 模板) || !是装备(模板))
        {
            事件.发布(new 日志事件(日志类型.反馈坏, "唯有武器、防具、饰品方可接受附魔。"));
            return false;
        }
        if (!数据.物品.TryGetValue(材料标识, out var 材料) || 材料.类型 != "材料")
        {
            事件.发布(new 日志事件(日志类型.反馈坏, "附魔需消耗一份「材料」。"));
            return false;
        }
        if (玩家.物品数量(材料标识) < 1)
        {
            事件.发布(new 日志事件(日志类型.反馈坏, $"缺少附魔材料：{材料.名称}。"));
            return false;
        }

        // 定位单件目标装备（数量为 1 或已携带词缀的堆叠，视为那件具体装备）
        var 目标 = 找单件(玩家, 装备标识);
        if (目标 == null)
        {
            事件.发布(new 日志事件(日志类型.反馈坏, $"请先将 {模板.名称} 单独持有一件（拆分出来），方可附魔。"));
            return false;
        }

        // —— 扣材料 ——
        玩家.移除物品(材料标识, 1);
        事件.发布(new 背包变化事件(材料标识, -1, 变化原因.消耗));

        // —— 掷骰 ——
        bool 损坏 = Random.value < 损坏概率;

        if (损坏)
        {
            // 失败：装备本体损毁消散
            玩家.背包.Remove(目标);
            事件.发布(new 背包变化事件(装备标识, -1, 变化原因.消耗));
            事件.发布(new 日志事件(日志类型.反馈坏,
                $"附魔的灵光本欲凝入 {模板.名称}，却骤然爆裂。" +
                $"灼热的禁忌之力反噬而下，{模板.名称} 寸寸碎裂，化作一地飞灰与碎屑，消散于风中。"));
            return false;
        }

        // —— 成功：附加/淬炼词条 ——
        品质 档 = 有效品质(目标, 模板);
        var 已有 = 目标.词缀 ?? new System.Collections.Generic.List<词缀条>();
        int 最大 = 词缀服务.最大条数(档);

        if (已有.Count >= 最大)
        {
            // 灵纹已满 → 随机升级一条（原位替换，不占新槽）
            if (已有.Count > 0)
            {
                int 序 = Random.Range(0, 已有.Count);
                var 升 = 词缀.升级一条(模板, 已有[序], 档);
                if (升 != null)
                {
                    已有[序] = 升;
                    目标.词缀 = 已有;
                    事件.发布(new 日志事件(日志类型.反馈,
                        $"附魔的暖光缓缓没入 {模板.名称}，原有的一道灵纹被冲灌得愈发明亮。" +
                        $"（灵纹淬炼为「{词缀名(升)}」。）"));
                    return true;
                }
            }
            事件.发布(new 日志事件(日志类型.反馈坏, $"附魔之力徘徊一圈，却寻不到可淬炼之处，此次附魔无果而返。"));
            return true;
        }

        // 未满 → 新增随机词条
        var 新条 = 词缀.追加一条(模板, 档, 已有);
        if (新条 == null)
        {
            事件.发布(new 日志事件(日志类型.反馈坏, $"附魔之力徘徊一圈，却寻不到落点，此次附魔无果而返。"));
            return true;
        }
        已有.Add(新条);
        目标.词缀 = 已有;

        事件.发布(new 日志事件(日志类型.反馈,
            $"附魔的暖光缓缓没入 {模板.名称}，一道崭新的灵纹在其表面浮现。" +
            $"（新增「{词缀名(新条)}」，{模板.名称} 愈发锋锐灵动。）"));

        return true;
    }

    // 找该标识可操作的单件装备堆叠：优先携带词缀者，否则任一数量为 1 的堆叠
    private static 物品堆叠 找单件(玩家档案 玩家, string 装备标识)
    {
        物品堆叠 数量一 = null;
        foreach (var 堆叠 in 玩家.背包)
            if (堆叠.标识 == 装备标识 && 堆叠.数量 > 0)
            {
                if (堆叠.词缀 != null && 堆叠.词缀.Count > 0 && 堆叠.数量 == 1) return 堆叠;
                if (堆叠.数量 == 1 && 数量一 == null) 数量一 = 堆叠;   // 优先词缀，其次任意单件
            }
        return 数量一;
    }

    private static bool 是装备(物品数据 物品)
        => 物品.类型 == "武器" || 物品.类型 == "防具" || 物品.类型 == "饰品";

    // 获取堆叠有效品质（覆盖优先，否则取模板品质）
    private static 品质 有效品质(物品堆叠 堆叠, 物品数据 模板)
        => string.IsNullOrEmpty(堆叠.品质) ? 模板.品质档 : 数据解析.枚举<品质>(堆叠.品质);

    private string 词缀名(词缀条 条)
        => 数据.词缀.TryGetValue(条.标识, out var 定) ? $"{定.名称} +{条.数值}" : 条.标识;
}
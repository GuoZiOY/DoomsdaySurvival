using UnityEngine;

// 镶缀服务：消耗 1 颗「宝石」，为单件装备赋予该宝石指定属性的词缀（如 红宝石→攻击）。
// 成功(75%) → 追加/升级一条指定属性词缀；失败(25%) → 宝石碎裂损毁，装备无恙。
// 目标装备需为背包中「单件」堆叠；宝石通过其「指定词缀属性」决定要赋予的词条类型。
public sealed class 镶缀服务
{
    private readonly DataService 数据;
    private readonly PlayerService 玩家服务;
    private readonly EventBus 事件;
    private readonly 词缀服务 词缀;

    // 镶缀失败 → 宝石损坏概率
    public const float 损坏概率 = 0.25f;

    public 镶缀服务(DataService 数据, PlayerService 玩家服务, EventBus 事件, 词缀服务 词缀)
    {
        this.数据 = 数据;
        this.玩家服务 = 玩家服务;
        this.事件 = 事件;
        this.词缀 = 词缀;
    }

    // 尝试镶缀：消耗 1 颗宝石，为 装备标识 的单件装备赋予宝石指定的属性词缀
    public bool 尝试镶缀(string 装备标识, string 宝石标识)
    {
        var 玩家 = 玩家服务.档案;

        // —— 验证 ——
        if (!数据.物品.TryGetValue(装备标识, out var 模板) || !是装备(模板))
        {
            事件.发布(new 日志事件(日志类型.反馈坏, "唯有武器、防具、饰品方可承受镶缀。"));
            return false;
        }
        if (!数据.物品.TryGetValue(宝石标识, out var 宝石) || 宝石.类型 != "宝石")
        {
            事件.发布(new 日志事件(日志类型.反馈坏, "镶缀需消耗一颗「宝石」。"));
            return false;
        }
        if (玩家.物品数量(宝石标识) < 1)
        {
            事件.发布(new 日志事件(日志类型.反馈坏, $"缺少宝石：{宝石.名称}。"));
            return false;
        }
        if (string.IsNullOrEmpty(宝石.指定词缀属性))
        {
            事件.发布(new 日志事件(日志类型.反馈坏, $"宝石 {宝石.名称} 未能明示其灵性所向，镶缀无从施展。"));
            return false;
        }
        词缀属性 指定 = 宝石.指定词缀属性枚举;

        var 目标 = 找单件(玩家, 装备标识);
        if (目标 == null)
        {
            事件.发布(new 日志事件(日志类型.反馈坏, $"请先将 {模板.名称} 单独持有一件（拆分出来），方可镶缀。"));
            return false;
        }

        // —— 扣宝石 ——
        玩家.移除物品(宝石标识, 1);
        事件.发布(new 背包变化事件(宝石标识, -1, 变化原因.消耗));

        // —— 掷骰 ——
        bool 碎裂 = Random.value < 损坏概率;

        if (碎裂)
        {
            // 失败：宝石碎裂损毁，装备完好
            事件.发布(new 日志事件(日志类型.反馈坏,
                $"镶缀的灵光在那瞬间剧烈摇曳，{宝石.名称} 承受不住，喀喇一声迸裂为漫天尘粉。" +
                $"好在 {模板.名称} 安然无恙，只是空空留下一个未竟的孔窍。"));
            return false;
        }

        // —— 成功：赋予指定属性词缀 ——
        品质 档 = 有效品质(目标, 模板);
        var 已有 = 目标.词缀 ?? new System.Collections.Generic.List<词缀条>();
        int 最大 = 词缀服务.最大条数(档);
        // 已有同属性词缀 → 可原位升级（不占新槽），不受条数上限约束
        bool 已有同属性 = false;
        foreach (var 条 in 已有)
            if (数据.词缀.TryGetValue(条.标识, out var 定) && 定.属性枚举 == 指定) { 已有同属性 = true; break; }
        if (!已有同属性 && 已有.Count >= 最大)
        {
            事件.发布(new 日志事件(日志类型.反馈坏, $"灵纹已满，{模板.名称} 再无处容纳新气韵，此次镶缀无果而返。"));
            return true;
        }
        var 结果 = 词缀.追加指定属性(模板, 档, 指定, 已有);   // 同属性升级 or 新增强化
        if (结果 == null)
        {
            事件.发布(new 日志事件(日志类型.反馈坏, $"宝石的灵性与 {模板.名称} 相通却无从驻留，此次镶缀无果而返。"));
            return true;
        }
        if (!已有.Contains(结果)) 已有.Add(结果);   // 升级时服务已替换进列表，仅新增才 Add
        目标.词缀 = 已有;

        事件.发布(new 日志事件(日志类型.反馈,
            $"{宝石.名称} 悄然没入 {模板.名称}，一道「{指定.ToString()}」的气韵随之凝成灵纹。" +
            $"（{模板.名称} 得到「{词缀名(结果)}」的滋养，愈发非凡。）"));

        return true;
    }

    // 找该标识可操作的单件装备堆叠（同附魔）
    private static 物品堆叠 找单件(玩家档案 玩家, string 装备标识)
    {
        物品堆叠 数量一 = null;
        foreach (var 堆叠 in 玩家.所有持有物品())
            if (堆叠.标识 == 装备标识 && 堆叠.数量 > 0)
            {
                if (堆叠.词缀 != null && 堆叠.词缀.Count > 0 && 堆叠.数量 == 1) return 堆叠;
                if (堆叠.数量 == 1 && 数量一 == null) 数量一 = 堆叠;
            }
        return 数量一;
    }

    private static bool 是装备(物品数据 物品)
        => 物品.类型 == "武器" || 物品.类型 == "防具" || 物品.类型 == "饰品";

    private static 品质 有效品质(物品堆叠 堆叠, 物品数据 模板)
        => string.IsNullOrEmpty(堆叠.品质) ? 模板.品质档 : 数据解析.枚举<品质>(堆叠.品质);

    private string 词缀名(词缀条 条)
        => 数据.词缀.TryGetValue(条.标识, out var 定) ? $"{定.名称} +{条.数值}" : 条.标识;
}
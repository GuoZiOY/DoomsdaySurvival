// 安全屋管理器：安全屋家具 的 建造/升级 与 房间网格（塔科夫藏身处式家具经营）。
// 家具 = 物品堆叠 承载（玩家档案.家具：标识 含 等级后缀"储物箱_2"、数量恒 1、列/行/旋转 = 房间网格位置）。
// 房间网格 = 网格服务（10×7，复用 占格/移动/换位/旋转 网格算法；形状解析 = 家具形状[按等级]；家具 不 堆叠）。
// 家具效果 查询 走 玩家档案.家具效果（床恢复系数 / 储物箱仓库行加成 / 灶台寒潮豁免 / 收音机电池次数 / 工作台词缀概率）。
// 建造/升级 扣 玩家持有材料（跨 穿戴容器/仓库）；事件 发布 背包变化 + 日志。
public sealed class 安全屋管理器
{
    private readonly EventBus 事件;
    private readonly DataService 数据;
    private 玩家档案 玩家 => ServiceRegistry.Get<PlayerService>().档案;

    public 安全屋管理器(EventBus 事件, DataService 数据)
    {
        this.事件 = 事件;
        this.数据 = 数据;
    }

    // —— 家具网格（懒建；每次取用 重绑 玩家.家具 与 形状解析——读档后列表已恢复） ——
    private 网格服务 网格缓存;
    public 网格服务 网格()
    {
        if (网格缓存 == null)
        {
            网格缓存 = new 网格服务 { 网格列 = 10, 网格行 = 7 };   // 房间 10×7 = 70 格
            网格缓存.堆叠上限解析 = _ => 0;   // 家具 不 堆叠（同标识 不合并）
        }
        网格缓存.网格物品 = 玩家.家具;
        网格缓存.形状解析 = 家具形状;
        return 网格缓存;
    }

    // 家具形状（按 等级 后缀 解码；储物箱 升级 占格 变大）
    private 物品形状 家具形状(string 实例标识)
    {
        var (定义标识, 等级) = 家具工具.解码(实例标识);
        if (!数据.家具.TryGetValue(定义标识, out var 定义)) return new 物品形状(1, 1);
        int 宽 = 定义.形状宽, 高 = 定义.形状高;
        if (定义.升级 != null)
            for (int i = 0; i < 等级 - 1 && i < 定义.升级.Length; i++)
            {
                var 需 = 定义.升级[i];
                if (需 == null) continue;
                if (需.形状宽 > 0) 宽 = 需.形状宽;
                if (需.形状高 > 0) 高 = 需.形状高;
            }
        return new 物品形状(宽, 高);
    }

    // 家具 当前占格（按 旋转）：旋转 则 宽高互换
    private (int 宽, int 高) 家具占格(string 实例标识, bool 旋转)
    {
        var 形状 = 家具形状(实例标识);
        return 旋转 ? (形状.高, 形状.宽) : (形状.宽, 形状.高);
    }

    // 家具 当前占格（按 旋转）：旋转 则 宽高互换（面板 摆放预览 用）
    public (int 宽, int 高) 占格(string 实例标识, bool 旋转) => 家具占格(实例标识, 旋转);

    // ===== 建造 =====

    public bool 建造(string 定义标识, int 列, int 行, bool 旋转)
    {
        if (!数据.家具.TryGetValue(定义标识, out var 定义)) { UnityEngine.Debug.Log($"[安全屋] 建造失败：未知家具 {定义标识}"); 提示("未知家具：" + 定义标识); return false; }
        if (玩家.家具实例(定义标识) != null) { UnityEngine.Debug.Log($"[安全屋] 建造失败：已建 {定义.名称}"); 提示($"已经有一张 {定义.名称} 了。"); return false; }
        if (!材料足够(定义.材料)) { UnityEngine.Debug.Log($"[安全屋] 建造失败：材料不足 {定义.名称}"); 提示($"材料不足，无法建造 {定义.名称}。"); return false; }
        string 实例标识 = 家具工具.编码(定义标识, 1);
        if (!网格().可放置(实例标识, 列, 行, 旋转)) { UnityEngine.Debug.Log($"[安全屋] 建造失败：放不下 {定义.名称} @{列},{行}"); 提示("这里放不下，换个位置。"); return false; }
        扣材料(定义.材料);
        网格().网格物品.Add(new 物品堆叠(实例标识, 1) { 列 = 列, 行 = 行, 旋转 = 旋转 });
        事件.发布(new 背包变化事件("", 0, 变化原因.获得));   // 触发持有面板刷新（材料已扣）
        事件.发布(new 日志事件(日志类型.反馈, $"建好了 {定义.名称}。"));
        return true;
    }

    // ===== 升级 =====

    public bool 升级(物品堆叠 家具)
    {
        var (定义标识, 当前等级) = 家具工具.解码(家具.标识);
        if (!数据.家具.TryGetValue(定义标识, out var 定义)) return false;
        if (当前等级 >= 定义.最大等级) { 提示($"{定义.名称} 已经满级了。"); return false; }
        var 需求 = 定义.升级 != null && 当前等级 - 1 < 定义.升级.Length ? 定义.升级[当前等级 - 1] : null;
        if (需求 == null || !材料足够(需求.材料)) { 提示($"材料不足，无法升级 {定义.名称}。"); return false; }
        // 升级后占格（储物箱 变大）：原位放不下 → 智能找空位（找不到 = 空间不足，阻止升级）
        string 新标识 = 家具工具.编码(定义标识, 当前等级 + 1);
        var (新宽, 新高) = 家具占格(新标识, 家具.旋转);
        var 网格视图 = 网格();
        if (网格视图.可放置(新标识, 家具.列, 家具.行, 家具.旋转, 家具) == false)
        {
            var 空位 = 找空位(新标识, 家具.旋转, 家具);
            if (空位 == null) { 提示("房间空间不足，升级后放不下。"); return false; }
            家具.列 = 空位.Value.列;
            家具.行 = 空位.Value.行;
        }
        扣材料(需求.材料);
        家具.标识 = 新标识;
        事件.发布(new 背包变化事件("", 0, 变化原因.获得));
        事件.发布(new 日志事件(日志类型.反馈, $"{定义.名称} 升到了 {当前等级 + 1} 级。"));
        return true;
    }

    // 找空位（忽略 指定 家具；供 升级 后占格变大 重摆）
    private (int 列, int 行)? 找空位(string 实例标识, bool 旋转, 物品堆叠 排除)
    {
        var (宽, 高) = 家具占格(实例标识, 旋转);
        var 网格视图 = 网格();
        for (int 行 = 0; 行 <= 网格视图.网格行 - 高; 行++)
            for (int 列 = 0; 列 <= 网格视图.网格列 - 宽; 列++)
                if (网格视图.可放置(实例标识, 列, 行, 旋转, 排除)) return (列, 行);
        return null;
    }

    // ===== 收音机（电池 机制 暂 移除——做 收音机 功能 时 再 设计；现在 收听 免费） =====

    // 收听一次：需 收音机 家具（不 耗 电）；收听 时 预知 明日天气
    public bool 尝试收听()
    {
        if (玩家.家具实例("收音机") == null) return false;
        玩家.预知天气 = UnityEngine.Random.Range(0, System.Enum.GetValues(typeof(天气类型)).Length);   // 预知 明日天气（跨天 优先用）
        return true;
    }

    // ===== 材料（跨 穿戴容器/仓库 统一扣） =====

    private bool 材料足够(配方材料[] 材料)
    {
        if (材料 == null) return true;
        foreach (var 材 in 材料)
            if (玩家.持有管理.物品数量(材.物品) < 材.数量) return false;
        return true;
    }

    private void 扣材料(配方材料[] 材料)
    {
        if (材料 == null) return;
        foreach (var 材 in 材料)
        {
            玩家.持有管理.移除物品(材.物品, 材.数量);
            事件.发布(new 背包变化事件(材.物品, -材.数量, 变化原因.消耗));
        }
    }

    private void 提示(string 文本) => 事件.发布(new 日志事件(日志类型.反馈坏, 文本));
}

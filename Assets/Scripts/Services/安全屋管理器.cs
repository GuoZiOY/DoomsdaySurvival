// 安全屋管理器：安全屋家具 的 建造/升级 与 房间网格（塔科夫藏身处式家具经营）。
// 家具 = 物品堆叠 承载（玩家档案.家具：标识 含 等级后缀"储物箱_2"、数量恒 1、列/行/旋转 = 房间网格位置）。
// 房间网格 = 网格服务（10×7，复用 占格/移动/换位/旋转 网格算法；形状解析 = 家具形状[按等级]；家具 不 堆叠）。
// 家具效果 查询 走 玩家档案.家具效果（床恢复系数 / 储物箱仓库行加成 / 灶台寒潮豁免 / 收音机电池次数 / 工作台词缀概率）。
// 建造/升级 扣 玩家持有材料（跨 穿戴容器/仓库）；事件 发布 背包变化 + 日志。
public sealed class 安全屋管理器
{
    private readonly EventBus 事件;
    private readonly DataService 数据;
    private 玩家档案 玩家 => ServiceRegistry.Get<PlayerService>().档案;

    public 安全屋管理器(EventBus 事件, DataService 数据)
    {
        this.事件 = 事件;
        this.数据 = 数据;
    }

    // —— 家具网格（懒建；每次取用 重绑 玩家.家具 与 形状解析——读档后列表已恢复） ——
    private 网格服务 网格缓存;
    private 安全屋户型 户型;   // 程序化 随机 户型（懒 生成；种子 = 玩家档案.户型种子——读档 同 种子 恢复）
    public 网格服务 网格()
    {
        if (网格缓存 == null)
        {
            网格缓存 = new 网格服务 { 网格列 = 10, 网格行 = 7 };   // 默认（户型 生成 后 更新 动态 尺寸）
            网格缓存.堆叠上限解析 = _ => 0;   // 家具 不 堆叠（同标识 不合并）
        }
        网格缓存.网格物品 = 玩家.家具;
        网格缓存.形状解析 = 家具形状;
        // 户型（房间 + 缝）：注入 形状——家具 跨 墙 自动 禁止、墙 视觉 自动 渲染（容器 同款 机制）
        if (户型 == null)
        {
            户型 = 安全屋户型.生成(玩家.户型种子);
            确保基础家具();   // 新 户型：自动 摆 0 级 破损 基础 家具（床/门/厕所/灶台/储物箱）
        }
        网格缓存.网格列 = 户型.房间列数;   // 动态 尺寸（面积 90~110，宽 高 随 户型）
        网格缓存.网格行 = 户型.房间行数;
        网格缓存.格可用 = (列, 行) => 户型.格可用[列, 行];
        网格缓存.格所属块 = (列, 行) => 户型.格所属块[列, 行];
        网格缓存.形状块 = 户型.形状块;
        return 网格缓存;
    }

    // 家具形状（按 等级 后缀 解码；储物箱 升级 占格 变大）
    private 物品形状 家具形状(string 实例标识)
    {
        var (定义标识, 等级) = 家具工具.解码(实例标识);
        if (!数据.家具.TryGetValue(定义标识, out var 定义)) return new 物品形状(1, 1);
        int 宽 = 定义.形状宽, 高 = 定义.形状高;
        if (定义.升级 != null)
            for (int i = 0; i < 等级 - 1 && i < 定义.升级.Length; i++)
            {
                var 需 = 定义.升级[i];
                if (需 == null) continue;
                if (需.形状宽 > 0) 宽 = 需.形状宽;
                if (需.形状高 > 0) 高 = 需.形状高;
            }
        return new 物品形状(宽, 高);
    }

    // 家具 当前占格（按 旋转）：旋转 则 宽高互换
    private (int 宽, int 高) 家具占格(string 实例标识, bool 旋转)
    {
        var 形状 = 家具形状(实例标识);
        return 旋转 ? (形状.高, 形状.宽) : (形状.宽, 形状.高);
    }

    // 家具 当前占格（按 旋转）：旋转 则 宽高互换（面板 摆放预览 用）
    public (int 宽, int 高) 占格(string 实例标识, bool 旋转) => 家具占格(实例标识, 旋转);

    // ===== 建造 =====

    public bool 建造(string 定义标识, int 列, int 行, bool 旋转)
    {
        if (!数据.家具.TryGetValue(定义标识, out var 定义)) { UnityEngine.Debug.Log($"[安全屋] 建造失败：未知家具 {定义标识}"); 提示("未知家具：" + 定义标识); return false; }
        if (玩家.家具实例(定义标识) != null) { UnityEngine.Debug.Log($"[安全屋] 建造失败：已建 {定义.名称}"); 提示($"已经有一张 {定义.名称} 了。"); return false; }
        if (!材料足够(定义.材料)) { UnityEngine.Debug.Log($"[安全屋] 建造失败：材料不足 {定义.名称}"); 提示($"材料不足，无法建造 {定义.名称}。"); return false; }
        string 实例标识 = 家具工具.编码(定义标识, 1);
        if (!网格().可放置(实例标识, 列, 行, 旋转)) { UnityEngine.Debug.Log($"[安全屋] 建造失败：放不下 {定义.名称} @{列},{行}"); 提示("这里放不下，换个位置。"); return false; }
        扣材料(定义.材料);
        var 家具实例 = new 物品堆叠(实例标识, 1) { 列 = 列, 行 = 行, 旋转 = 旋转 };
        初始化家具容器(家具实例);   // 容器型 家具（冰箱 等）：建造 即 初始化 内部 网格
        网格().网格物品.Add(家具实例);
        事件.发布(new 背包变化事件("", 0, 变化原因.获得));   // 触发持有面板刷新（材料已扣）
        事件.发布(new 日志事件(日志类型.反馈, $"建好了 {定义.名称}。"));
        return true;
    }

    // 容器型 家具 初始化 内部 容器（冰箱 等：打开 时 才 建 列表 会 晚 一步——建造/放置 时 即 初始化）
    private void 初始化家具容器(物品堆叠 家具实例)
    {
        var (定义标识, _) = 家具工具.解码(家具实例.标识);
        if (!数据.家具.TryGetValue(定义标识, out var 定义) || !定义.是容器) return;
        ServiceRegistry.Get<容器服务>()?.初始化容器(家具实例);
    }

    // ===== 升级 =====

    public bool 升级(物品堆叠 家具)
    {
        var (定义标识, 当前等级) = 家具工具.解码(家具.标识);
        if (!数据.家具.TryGetValue(定义标识, out var 定义)) return false;
        if (当前等级 >= 定义.最大等级) { 提示($"{定义.名称} 已经满级了。"); return false; }
        var 需求 = 定义.升级 != null && 当前等级 - 1 < 定义.升级.Length ? 定义.升级[当前等级 - 1] : null;
        if (需求 == null || !材料足够(需求.材料)) { 提示($"材料不足，无法升级 {定义.名称}。"); return false; }
        // 升级后占格（储物箱 变大）：原位放不下 → 智能找空位（找不到 = 空间不足，阻止升级）
        string 新标识 = 家具工具.编码(定义标识, 当前等级 + 1);
        var 落点 = 升级后落点(家具, 新标识, 家具.旋转);
        if (落点 == null) { 提示("房间空间不足，升级后放不下。"); return false; }
        if (落点.Value.列 != 家具.列 || 落点.Value.行 != 家具.行)
        {
            家具.列 = 落点.Value.列;
            家具.行 = 落点.Value.行;
        }
        扣材料(需求.材料);
        家具.标识 = 新标识;
        事件.发布(new 背包变化事件("", 0, 变化原因.获得));
        事件.发布(new 日志事件(日志类型.反馈, $"{定义.名称} 升到了 {当前等级 + 1} 级。"));
        return true;
    }

    // 升级后 落点：原位 放得下 → 原位；否则 全房间 找空位（null = 空间 不足——升级 后 放不下）
    private (int 列, int 行)? 升级后落点(物品堆叠 家具, string 新标识, bool 旋转)
    {
        var 网格视图 = 网格();
        if (网格视图.可放置(新标识, 家具.列, 家具.行, 旋转, 家具)) return (家具.列, 家具.行);
        return 找空位(新标识, 旋转, 家具);
    }

    // 升级 空间 是否 足够（占格 变大 后 原位 或 全房间 有空位；供 建造面板 占格 变红 警示；满级/无升级 = true）
    public bool 升级空间足够(物品堆叠 家具)
    {
        if (家具 == null) return true;
        var (定义标识, 当前等级) = 家具工具.解码(家具.标识);
        if (!数据.家具.TryGetValue(定义标识, out var 定义)) return true;
        if (当前等级 >= 定义.最大等级) return true;
        return 升级后落点(家具, 家具工具.编码(定义标识, 当前等级 + 1), 家具.旋转) != null;
    }

    // 重新 生成 随机 户型（快速 测试 面板 用）：新 随机 种子 + 立即 生成（数据源 缓存 的 lambda 捕获 字段 户型——
    // 必须 立即 非 null，不能 等 网格() 懒 生成）+ 同步 缓存 尺寸（数据源 引用 缓存——强制重建 用 缓存.网格列/行，
    // 不 同步 则 新 户型 比 旧 小 时 数组 越界）+ 家具 清空 后 重新 摆 基础 家具
    public void 重新生成户型()
    {
        玩家.户型种子 = UnityEngine.Random.Range(1, int.MaxValue);
        户型 = 安全屋户型.生成(玩家.户型种子);
        if (网格缓存 != null)
        {
            网格缓存.网格列 = 户型.房间列数;   // 同步 缓存 尺寸（新 户型 可能 更 大/更 小）
            网格缓存.网格行 = 户型.房间行数;
        }
        玩家.家具.Clear();
        确保基础家具();   // 新 户型：重新 摆 0 级 破损 基础 家具
        事件.发布(new 背包变化事件("", 0, 变化原因.获得));   // 触发 网格 刷新
    }

    // ===== 基础 家具（0 级 破损：安全屋 破损 状态——自动 摆 到 对应 房间，修复 后 变 1 级） =====

    // 户型 生成 后 自动 摆 放：床→主屋、灶台→厨房、厕所→洗浴间、门→门房、储物箱→大厅（0 级；已 有 则 跳过——幂等）
    private void 确保基础家具()
    {
        if (户型 == null) return;
        var 网格视图 = 网格();
        foreach (var (定义标识, 房间类型, _, _) in 安全屋户型.基础家具表)
        {
            if (玩家.家具实例(定义标识) != null) continue;   // 已 有（玩家 建/修复 过）
            int 块 = 户型.房间块号(房间类型);
            if (块 < 0 || 块 >= 户型.形状块.Count) continue;
            var 房间 = 户型.形状块[块];
            string 实例标识 = 家具工具.编码(定义标识, 0);   // 0 级（破损）
            var 空位 = 房间空位(网格视图, 房间, 实例标识);
            if (空位 == null) continue;
            网格视图.网格物品.Add(new 物品堆叠(实例标识, 1) { 列 = 空位.Value.列, 行 = 空位.Value.行, 旋转 = 空位.Value.旋转 });
        }
    }

    // 房间 矩形 内 找 家具 空位（可 旋转；可放置 自动 校验 同 块/不 重叠）
    private (int 列, int 行, bool 旋转)? 房间空位(网格服务 网格视图, 容器形状块 房间, string 实例标识)
    {
        var 形状 = 网格视图.形状解析?.Invoke(实例标识) ?? new 物品形状(1, 1);
        for (int 旋转 = 0; 旋转 <= 1; 旋转++)
        {
            int w = 旋转 == 1 ? 形状.高 : 形状.宽;
            int h = 旋转 == 1 ? 形状.宽 : 形状.高;
            for (int 行 = 房间.行; 行 + h <= 房间.行 + 房间.高; 行++)
                for (int 列 = 房间.列; 列 + w <= 房间.列 + 房间.宽; 列++)
                    if (网格视图.可放置(实例标识, 列, 行, 旋转 == 1)) return (列, 行, 旋转 == 1);
        }
        return null;
    }

    // 修复（0 级 → 1 级）：扣 建造 材料 一半；恢复 功能
    public bool 修复(物品堆叠 家具)
    {
        if (家具 == null) return false;
        var (定义标识, 等级) = 家具工具.解码(家具.标识);
        if (等级 != 0) return false;
        if (!数据.家具.TryGetValue(定义标识, out var 定义)) return false;
        var 修复材料 = 材料减半(定义.材料);
        if (!材料足够(修复材料)) { 提示($"材料不足，无法修复 {定义.名称}。"); return false; }
        扣材料(修复材料);
        家具.标识 = 定义标识;   // 0 级 → 1 级（"床_0" → "床"）
        事件.发布(new 背包变化事件("", 0, 变化原因.获得));
        事件.发布(new 日志事件(日志类型.反馈, $"修复了 {定义.名称}。"));
        return true;
    }

    private 配方材料[] 材料减半(配方材料[] 材料)
    {
        if (材料 == null) return null;
        var 结果 = new 配方材料[材料.Length];
        for (int i = 0; i < 材料.Length; i++)
            if (材料[i] != null)
                结果[i] = new 配方材料 { 物品 = 材料[i].物品, 数量 = System.Math.Max(1, 材料[i].数量 / 2) };
        return 结果;
    }

    // 修复 需求 材料（0 级 家具 = 建造 材料 一半；非 0 级 = null）——建造面板 显示/判断 用
    public 配方材料[] 修复需求(物品堆叠 家具)
    {
        if (家具 == null) return null;
        var (定义标识, 等级) = 家具工具.解码(家具.标识);
        if (等级 != 0 || !数据.家具.TryGetValue(定义标识, out var 定义)) return null;
        return 材料减半(定义.材料);
    }

    // ===== 拆墙（隔离 格 -2 = 房间 间 缝）：拆除 并 入 相邻 房间 → 扩大 可用 范围 =====

    public bool 拆除墙(int 列, int 行)
    {
        if (户型 == null) return false;
        if (列 < 0 || 行 < 0 || 列 >= 户型.房间列数 || 行 >= 户型.房间行数) return false;
        if (户型.格所属块[列, 行] != -2) return false;   // 只 拆 墙（未 覆盖 格）
        var (块A, 块B) = 相邻房间块对(列, 行);
        if (块A < 0) return false;
        户型.格所属块[列, 行] = 块A;   // 墙 格 变 可用（并 入 主 块）
        户型.格可用[列, 行] = true;
        // 打通：墙 两 侧 房间 合并 成 一个 大 房间（家具 可 跨 原 边界）
        if (块B >= 0)
            for (int c = 0; c < 户型.房间列数; c++)
                for (int r = 0; r < 户型.房间行数; r++)
                    if (户型.格所属块[c, r] == 块B) 户型.格所属块[c, r] = 块A;
        事件.发布(new 背包变化事件("", 0, 变化原因.获得));   // 触发 网格 刷新（底格 重画）
        事件.发布(new 日志事件(日志类型.反馈, 块B >= 0 ? "拆除了墙体，房间打通。" : "拆除了墙体，房间扩大。"));
        return true;
    }

    // 墙 格 相邻 的 房间 块（去 重；最多 2 个——墙 两侧；无 相邻 块 = (-1, -1)）
    private (int A, int B) 相邻房间块对(int 列, int 行)
    {
        int A = -1, B = -1;
        foreach (var (dx, dy) in 安全屋户型.四方向)
        {
            int c = 列 + dx, r = 行 + dy;
            if (c < 0 || r < 0 || c >= 户型.房间列数 || r >= 户型.房间行数) continue;
            int 块 = 户型.格所属块[c, r];
            if (块 < 0) continue;
            if (A == -1) A = 块;
            else if (块 != A && B == -1) B = 块;
        }
        return (A, B);
    }

    // 找空位（忽略 指定 家具；供 升级 后占格变大 重摆）
    private (int 列, int 行)? 找空位(string 实例标识, bool 旋转, 物品堆叠 排除)
    {
        var (宽, 高) = 家具占格(实例标识, 旋转);
        var 网格视图 = 网格();
        for (int 行 = 0; 行 <= 网格视图.网格行 - 高; 行++)
            for (int 列 = 0; 列 <= 网格视图.网格列 - 宽; 列++)
                if (网格视图.可放置(实例标识, 列, 行, 旋转, 排除)) return (列, 行);
        return null;
    }

    // ===== 收音机（电池 机制 暂 移除——做 收音机 功能 时 再 设计；现在 收听 免费） =====

    // 收听一次：需 收音机 家具（不 耗 电）；收听 时 预知 明日天气
    public bool 尝试收听()
    {
        if (玩家.家具实例("收音机") == null) return false;
        玩家.预知天气 = UnityEngine.Random.Range(0, System.Enum.GetValues(typeof(天气类型)).Length);   // 预知 明日天气（跨天 优先用）
        return true;
    }

    // ===== 材料（跨 穿戴容器/仓库 统一扣） =====

    private bool 材料足够(配方材料[] 材料)
    {
        if (材料 == null) return true;
        foreach (var 材 in 材料)
            if (玩家.持有管理.物品数量(材.物品) < 材.数量) return false;
        return true;
    }

    private void 扣材料(配方材料[] 材料)
    {
        if (材料 == null) return;
        foreach (var 材 in 材料)
        {
            玩家.持有管理.移除物品(材.物品, 材.数量);
            事件.发布(new 背包变化事件(材.物品, -材.数量, 变化原因.消耗));
        }
    }

    private void 提示(string 文本) => 事件.发布(new 日志事件(日志类型.反馈坏, 文本));
}

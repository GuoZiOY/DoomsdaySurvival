using System;
using System.Collections.Generic;
using UnityEngine;

// ============================================================
// 大世界探索服务：**大世界层**（100×100 格子网格）的状态机（纯逻辑，零 MonoBehaviour）。
// 基类 = 格子探索服务（格子世界运行器）→ 令牌 / A* / 逐格推进 / 三态迷雾 / 视野记忆 / 相机数据 /
// 回安全屋清战局 全部白送，这里只写"大世界语义"。
//
// 与另外两层的分工：
//   大世界（本类）→ 区域副本（区域探索服务）→ 建筑/房间（房间探索服务）
//   走到**区域门口格** = 进副本；走到**营地门口格** = 回安全屋（这一趟出行结束）。
//
// 时间：**5 游戏分钟/格**（赶路有代价，配合"87 天"倒计时形成取舍）；楼里/区域里仍是 1 分钟/格。
//
// 种子（**一把钥匙就够**，见 docs/大世界网格与副本设计.md §3.1 的设计纠正）：
//   大世界布局 = 大世界生成器.生成(世界种子, 模板)              → 同一存档永远同一座废城
//   区域布局   = 派生(世界种子, "区域:" + 区域标识)              → 同一存档内永远同一套楼
//   内容"可重复刷"不靠第二把钥匙，靠**回安全屋重置**（v48/v49 定版，见 房间探索服务.清战局）。
//
// 迷雾 / 视野：**不覆写** —— 直接用基类那套（读 视野.json：白天 7 / 夜晚 3 + 夜晚弱视野圈）。
//   记忆键 = 种子#世界标识：出城再回来，走过的街还认得（回安全屋才清，与另外两层同一时机）。
// ============================================================
public sealed class 大世界探索服务 : 格子探索服务
{
    public 网格数据 当前大世界 => 当前世界;
    public string 当前世界标识 { get; private set; } = "";
    public 世界模板 当前模板 { get; private set; }

    public 大世界探索服务(EventBus 事件, DataService 数据, PlayerService 玩家服务)
        : base(事件, 数据, 玩家服务) { }

    // ================= 基类钩子（大世界语义） =================

    // 走一格 5 游戏分钟（楼里/区域里是基类默认的 1）：赶路是**有代价**的
    public override int 移动游戏分钟 => 5;

    // ★ 大世界的迷雾**随档永久保留**（v52）：布局种子固定 → 重看信息量为零；
    //   而且它是"一张 100×100 的城市地图"，重新摸一遍纯粹是从 87 天里扣时间。
    //   （内容仍在重置：街上敌人、临时建筑、区域里的柜子照旧每趟都是新的。）
    protected override bool 迷雾随档保存 => true;
    protected override string 层标签 => "大世界";

    // 记忆键 = 种子#世界标识（与 区域层 的 "种子#区域"、房间层的 "种子#模板" 同一套约定）
    protected override string 记忆键(string 标识, int 种子) => $"{种子}#{标识}";

    protected override void 发布显示事件(string 信息条, int 列, int 行)
        => 事件?.发布(new 大世界显示事件(信息条, 列, 行));

    // ================= 遭遇（街上撞上敌人；流程都在 格子探索服务） =================

    // 走完一步先看有没有撞上街上的敌人 —— 与房间层共用基类那一套
    // （一场遭遇 = 一个敌人、打赢必留可搜尸体、尸体留在他倒下的那一格由玩家走过去搜）
    protected override bool 抵达后检查() => 检查遭遇();

    protected override string 遭遇胜利节点 => "__大世界胜利";
    protected override string 遭遇返回节点 => "__大世界返回";
    protected override string 遭遇日志前缀 => "大世界";
    // 结算完把面板切回大世界（否则战斗面板会留在最上面，回不到街上）
    protected override void 战斗收尾之后() => 事件?.发布(new 回到大世界事件());

    // 踩到这一格上有什么：营地门口 → 回安全屋；区域门口 → 进副本（返回 true = 停下，不再沿路径走）
    protected override bool 抵达格()
    {
        if (当前世界 == null) return false;

        // —— 营地门口那一格：回安全屋 ——
        var 营门 = 大世界生成器.营地门口格(当前世界);
        if (营门.列 == 玩家列 && 营门.行 == 玩家行)
        {
            事件?.发布(new 日志事件(日志类型.系统, "你回到了安全屋。"));
            事件?.发布(new 打开营地事件());   // 面板管理器 → 安全屋面板；各格子层据此清"这一趟"的临时数据
            return true;
        }

        // —— 区域门口那一格：进副本（解锁条件不满足就只提示，人停在门口）——
        foreach (var 区 in 大世界生成器.区域列表(当前世界))
        {
            var 门 = 大世界生成器.区域门口格(区);
            if (门.列 != 玩家列 || 门.行 != 玩家行) continue;
            return 进区域(区);
        }

        // —— 临时建筑的门口那一格：进去看看（一次性，出来就拆）——
        foreach (var 物 in 大世界生成器.临时建筑列表(当前世界))
        {
            var 门 = 大世界生成器.临时建筑门口格(物);
            if (门.列 != 玩家列 || 门.行 != 玩家行) continue;
            return 进临时建筑(物);
        }
        return false;
    }
    // ================= 敌人 AI（刀61）—— 本层只填"差异" =================
    // **AI 机制本身已经下沉到 格子探索服务**（三层共用：大世界 / 区域 / 房间 的敌人都一样会巡街、听声、追人）。
    // 本层只需要回答两个"大世界才有"的问题：

    // ① 声音在旷野里传得最远（基类默认就是 1.0，这里写出来是为了对齐"三层各自的系数"这件事）
    protected override float 噪音层系数 => 1f;

    // ② 撤退点 = **营地门口格**：会动的敌人是"活的墙"，
    //    所以每次移动之后必须校验"玩家还走不走得回安全屋"，破了就把这一步整体撤销（基类里做）。
    //    为什么大世界要单独给：楼里/区域里的"出口"是另一套（区域 = 街口，房间 = 门/楼梯），
    //    基类不知道哪一格算出口 —— 所以撤退点由各层自己给。
    protected override void 收撤退点(List<(int 列, int 行)> 收)
    {
        if (当前世界 == null) return;
        var 门 = 大世界生成器.营地门口格(当前世界);
        收.Add(门);
    }

    // 进出大世界 / 回安全屋时，敌人 AI 的运行期态由基类统一清（清空世界态 / 回安全屋清战局 里调的 清敌人AI态）。

    // ================= 搜索（以角色为半径翻出一间一次性临时建筑） =================

    private readonly HashSet<string> 已进过的临时建筑 = new HashSet<string>();
    private int 搜索次数;
    // 本趟**翻出来过**的临时建筑落点（占地的左上角）—— 局部枯竭就靠它：
    //   · 只活**一趟**（回安全屋 清战局 时清掉）：与项目"回安全屋是唯一重置时机"那条口径一致；
    //   · ⚠ 必须和实体分开记：临时建筑**进去一趟就塌了**（清掉用过的临时建筑），
    //     但"这一带翻过了"得留着 —— 挂在实体上会随着坍塌一起忘掉。
    private readonly List<(int 列, int 行)> 本趟翻出的 = new List<(int 列, int 行)>();

    // 「搜索」：有代价（行动点 + 游戏分钟）→ 按概率在**角色半径内**翻出一间临时建筑。
    // 失败也给反馈（"翻了一圈，什么也没有"）—— 不做"点了没反应"。
    //
    // 三条防"站在安全屋门口刷"的约束（v52，设计见 docs/大世界搜索约束设计.md）：
    //   ① 局部枯竭  站在"已翻过"里 → 成功率掉到 枯竭概率；且枯竭格不给放（搜索落点 里跳过）
    //   ② 越翻越累  第 N 次搜索的行动点 = 行动点 + (N-1)×每多一次多花行动点
    //   ③ 楼型白名单 永久排除区专属楼型（市立医院/城西分局/纺织厂）
    // 算式全部走 搜索规则（Domain 纯函数）—— 只有"掷"留在这里，这样曲线能离线验。
    public bool 搜索()
    {
        if (当前世界 == null) { 播报("这里没什么可搜的。"); return false; }
        var 档 = 档案;
        if (档 == null) return false;
        var 参 = 当前模板?.搜索 ?? new 世界搜索参数();

        // ② 越翻越累：这一次是第几次尝试（**不管上一次成没成功** —— 失败不涨价等于没约束）
        int 第几次 = 搜索次数 + 1;
        int 价 = 搜索规则.搜索行动点(参, 第几次);
        if (行动点不足(档, 价, 第几次)) return false;

        档.消耗行动点(价);
        推进游戏分钟(参.游戏分钟);
        事件?.发布(new 精力变化事件(档.行动点, 档.最大行动点, 档.行动点));   // HUD 顶栏「精力」位
        // ★ 刀61：**翻箱倒柜是这一层里最响的一件事**（45，介于"翻柜子 25"与"枪声 90"之间）。
        //   位置在玩家脚下；成败都响（动作已经做了，声音不取决于你有没有翻出东西）。
        //   这是"搜索"这个动作的**真实代价**：它不是免费的 —— 你在街上闹出动静，附近的东西会过来。
        播噪音(噪音强度.大世界搜索);
        搜索次数 = 第几次;   // 尝试计数：成功失败都算（下一条的种子也靠它，保证每次都不同）

        // ① 局部枯竭：站在"已翻过"里 → 成功率掉到 枯竭概率
        bool 在枯竭区 = 搜索规则.在枯竭区(玩家列, 玩家行, 本趟翻出的, 参.枯竭半径);
        int 成功率 = 搜索规则.搜索成功率(参, 在枯竭区);

        // 掷"这一次翻不翻得出来"
        if (UnityEngine.Random.Range(0, 100) >= 成功率)
        {
            播报(在枯竭区
                ? $"这一带你翻过了 —— 得往别处走走。（-{价} 精力 · {参.游戏分钟} 分钟）"
                : $"你在附近翻了一圈，什么也没有。（-{价} 精力 · {参.游戏分钟} 分钟）");
            发布显示();
            return false;
        }

        var 落 = 大世界生成器.搜索落点(当前世界, 玩家列, 玩家行, 参.半径,
                                     确定性随机.派生(出行种子, $"搜索{搜索次数}"),
                                     本趟翻出的, 参.枯竭半径);
        if (!落.找到)
        {
            音效管理器.实例?.播放失败();
            播报(在枯竭区
                ? $"这一带能翻的都翻过了。（-{价} 精力 · {参.游戏分钟} 分钟）"
                : $"附近太挤，找不到能落脚的地方。（-{价} 精力 · {参.游戏分钟} 分钟）");
            发布显示();
            return false;
        }

        string 定义 = 挑临时建筑定义(out string 名);
        if (string.IsNullOrEmpty(定义))
        {
            // ★ v51 刀15：这两条失败路径原来**已经扣了行动点与时间，却零反馈零音效**
            //   （`挑临时建筑定义` 返回空 / `放临时建筑` 返回 null）—— 玩家只觉得"资源少了"。
            音效管理器.实例?.播放失败();
            播报($"没翻出什么像样的地方（楼型数据缺失）。（-{价} 精力 · {参.游戏分钟} 分钟）");
            发布显示();
            return false;
        }
        var 物 = 大世界生成器.放临时建筑(当前世界, 落.列, 落.行, 搜索次数.ToString(), 名, 定义);
        if (物 == null)
        {
            音效管理器.实例?.播放失败();
            播报($"那地方塌了半边，什么也没留下。（-{价} 精力 · {参.游戏分钟} 分钟）");
            发布显示();
            return false;
        }
        本趟翻出的.Add((落.列, 落.行));   // ① 记下来：这一带翻过了（连同它周围 枯竭半径 格）
        清流场缓存();   // ★ 刀61：地上多了一间 2×2 的占格物 → 所有追踪场作废（方向可能已经指向它的墙里）

        同步网格();
        音效管理器.实例?.播放成功();
        播报($"你翻出一间{名}（{落.列},{落.行}）——门开着，走上去就能进去看看。");
        发布显示();
        return true;
    }

    private bool 行动点不足(玩家档案 档, int 需要, int 第几次)
    {
        if (档.行动点 >= 需要) return false;
        音效管理器.实例?.播放失败();
        // 越翻越累要说清楚"为什么这次更贵"，不然玩家只看到数字变大（不静默）
        播报(第几次 > 1
            ? $"精力不够——这趟翻到第 {第几次} 次，一次要 {需要} 点，你只剩 {档.行动点}。（回安全屋睡一觉能恢复）"
            : $"精力不够——搜索要 {需要} 点，你只剩 {档.行动点}。（回安全屋睡一觉能恢复）");
        return true;
    }

    // 临时建筑用哪个楼型：按 世界搜索参数 的**白名单 + 权重**抽（Domain 纯函数，只有掷点在这儿）。
    // 白名单为空 → 兜底：全部建筑模板里**滤掉禁区楼型**（不会退化回"能在门口刷出市立医院"）。
    // 一个建筑模板都没有 → 退化成一个房间模板（老行为，便于只填了房间模板的档继续能玩）。
    private string 挑临时建筑定义(out string 显示名)
    {
        显示名 = "";
        if (数据 == null) return "";
        var 全部楼型 = new List<string>();
        foreach (var kv in 数据.建筑模板) 全部楼型.Add(kv.Key);
        var 参 = 当前模板?.搜索 ?? new 世界搜索参数();

        if (全部楼型.Count > 0)
        {
            int 总 = 搜索规则.总权重(参, 全部楼型);
            if (总 > 0)
            {
                string 定 = 搜索规则.挑临时建筑(参, 全部楼型, UnityEngine.Random.Range(0, 总));
                if (!string.IsNullOrEmpty(定)) { 显示名 = 取名(定); return 定; }
            }
        }
        // 兜底：没有可用的建筑模板 → 从房间模板里随便挑一间当"小房子"
        var 房间候选 = new List<string>();
        foreach (var kv in 数据.房间模板) 房间候选.Add(kv.Key);
        if (房间候选.Count == 0) return "";
        string 房 = 房间候选[UnityEngine.Random.Range(0, 房间候选.Count)];
        显示名 = 取名(房);
        return 房;
    }

    private bool 进临时建筑(网格实体 物)
    {
        if (物 == null) return false;
        var 房服 = ServiceRegistry.Get<房间探索服务>();
        if (房服 == null) { Debug.LogError("[大世界] 房间探索服务未装配，进不了临时建筑"); return true; }
        已进过的临时建筑.Add(物.标识);   // 记下来：回到大世界时把它拆掉（一次性）
        int 种子 = UnityEngine.Random.Range(1, int.MaxValue);   // 一次性 → 不必固定
        播报($"你推开了{物.名称}的门。");
        bool 成 = false;
        if (数据 != null && 数据.建筑模板.ContainsKey(物.定义标识)) 成 = 房服.进入建筑(物.定义标识, 种子);
        else if (数据 != null && 数据.房间模板.ContainsKey(物.定义标识)) 成 = 房服.进入房间(物.定义标识, 种子, "");
        if (!成) 播报($"{物.名称}的门后堵死了。");
        return true;   // 消费这次抵达
    }

    // 回到大世界时扫一遍：**进过的临时建筑立刻拆掉**（一次性）。
    // 由 房间探索服务.离开() 在"回到外面那一层"时调用（那条路会顺带重发显示）。
    public void 清掉用过的临时建筑()
    {
        if (当前世界 == null || 已进过的临时建筑.Count == 0) return;
        var 待删 = new List<网格实体>();
        foreach (var 物 in 大世界生成器.临时建筑列表(当前世界))
            if (物 != null && 已进过的临时建筑.Contains(物.标识)) 待删.Add(物);
        if (待删.Count == 0) { 已进过的临时建筑.Clear(); return; }
        foreach (var 物 in 待删)
        {
            当前世界.移除实体(物);
            已进过的临时建筑.Remove(物.标识);
        }
        清流场缓存();   // ★ 刀61：拆了一间房子 → 地形变了，追踪场作废
        同步网格();
        播报("那间屋子塌了半边，没什么可再翻的了。");
        发布显示();
    }

    // 回安全屋：大世界这一趟的临时态（进过的临时建筑 / 搜索计数 / **已翻过的那几块**）一并作废。
    // 世界本身下次用 打开默认世界 重新生成（临时建筑自然也就没了）。
    // 「已翻过」跟着清 → 同一片街区下一趟又能翻（与"内容可重复刷靠回安全屋重置"是同一口径：
    //   局部枯竭不是产量阀门，是"别站桩"的阀门；产量上限由 越翻越累 卡）。
    protected override void 清战局()
    {
        已进过的临时建筑.Clear();
        本趟翻出的.Clear();
        搜索次数 = 0;
        // 注：敌人 AI 的运行期态由基类统一清（回安全屋清战局 → 清敌人AI态），这里不再各清一份。
    }

    // ================= 进出 =================

    // 进入大世界：主菜单「新游戏/继续」、角色创建、剧情「地图:」 都走这里。
    // 种子 = 玩家档案.世界种子 → 同一存档每次进来都是同一座废城（布局固定）。
    public bool 进入大世界(string 世界标识, int 种子)    {
        if (数据 == null || !数据.世界.TryGetValue(世界标识, out var 模板))
        {
            Debug.LogError($"[大世界] 世界模板不存在: {世界标识}（看 Data/世界.json）");
            return false;
        }
        出行种子 = 种子;
        出行起点标识 = 世界标识;

        存视野记忆();          // 上一张图看过的格存回记忆表（换图前必须存）
        当前世界 = 大世界生成器.生成(种子, 模板, 取名);
        if (当前世界 == null) return false;
        当前种子 = 种子;
        当前世界标识 = 世界标识;
        当前模板 = 模板;

        已探索.Clear();
        装回迷雾记忆();   // 会话缓存 ∪ 存档里的永久记忆（大世界是永久层）
        当前可见.Clear();
        当前路径.Clear();
        遭遇中 = false;
        遭遇目标 = null;
        最近尸体容器 = "";
        // 世界是**重新生成**的 → 上一张图上的"本趟临时态"全部失效（它们记的是旧图上的坐标/标识）：
        //   · 已翻过的那几块：坐标已经没有意义
        //   · 进过的临时建筑：标识也随新图重建
        //   · 搜索次数：重置让"越翻越累"从第 1 次重新起算
        // （正常路径上 进入大世界 前面一定有一次 回安全屋 → 清战局 已经清过；这里是**快速测试面板
        //   直接重进**那条路的兜底，不清就会出现"新图第 1 次搜索却按第 7 次收费"这种鬼现象。）
        本趟翻出的.Clear();
        已进过的临时建筑.Clear();
        搜索次数 = 0;
        // ★ 刀61：新图 = 新实体 → 敌人 AI 态（键是旧实体）必须整批丢掉（基类的 清敌人AI态）

        刷新视野();
        同步网格();
        补敌人显示名();
        事件?.发布(new 打开大地图事件(世界标识, 种子));   // 面板管理器 → 大世界面板
        播报($"你站在{当前世界.名称}的街口。{危险度文本(当前世界.危险度)}");
        发布显示();
        return true;
    }

    // 打开默认世界：**主菜单「新游戏/继续」/ 角色创建 / 剧情「地图:」 全走这一个入口**。
    // 世界标识留空（或写了不存在的）= 取 Data/世界.json 里的第一个世界。
    // 种子取自 玩家档案.世界种子 → 同一存档每次进来都是同一座废城。
    public bool 打开默认世界(string 世界标识 = "")
    {
        if (数据 == null || 数据.世界.Count == 0)
        {
            Debug.LogError("[大世界] Data/世界.json 没加载到任何世界 —— 大世界进不去");
            return false;
        }
        string 标识 = 世界标识;
        if (string.IsNullOrEmpty(标识) || !数据.世界.ContainsKey(标识))
        {
            标识 = null;
            foreach (var kv in 数据.世界) { 标识 = kv.Key; break; }
        }
        int 种子 = 档案?.世界种子 ?? 0;
        if (种子 <= 0) 种子 = 1;   // 旧档没写世界种子时兜底（PlayerService 清理非法值 里也会补随机）
        return 进入大世界(标识, 种子);
    }

    // 离开大世界（回安全屋）：清这一层的临时态
    public void 离开()
    {
        if (当前世界 == null) return;
        离开世界();
        当前世界标识 = "";
        当前模板 = null;
    }

    // ================= 「出门」 =================
    // 安全屋 → 废城。**安全屋那一侧只有这一个出口**，两个入口都汇到这里：
    //   · 安全屋面板的「出门」按钮（Esc / 取消文本也是"出门"）；
    //   · 安全屋网格里**门**的右键菜单（门只有一个选项就是「出去」）。
    // 统一放在这里的原因：失败提示只有一份（"Data/世界.json 没读到？"），
    //   免得两处各写一遍、以后改一处忘另一处（两处都在 UI 层，谁也管不着谁）。
    public bool 出门()
    {
        if (打开默认世界()) return true;
        音效管理器.实例?.播放失败();
        事件?.发布(new 日志事件(日志类型.警告, "现在还出不去（Data/世界.json 没读到？）。"));
        return false;
    }

    // ================= 进副本 =================

    private bool 进区域(网格实体 区)
    {
        if (区 == null) return false;
        string 缘由 = 未解锁缘由(区);
        if (!string.IsNullOrEmpty(缘由))
        {
            音效管理器.实例?.播放失败();
            播报(缘由);
            return true;   // 消费这次抵达：停在门口，不继续沿路径走
        }
        var 区服 = ServiceRegistry.Get<区域探索服务>();
        if (区服 == null) { Debug.LogError("[大世界] 区域探索服务未装配，进不了副本"); return true; }
        // 区域布局种子 = 派生(世界种子, "区域:" + 区域标识) → 同一存档里那片区域**永远同一套楼**
        int 区种子 = 确定性随机.派生(出行种子, "区域:" + 区.定义标识);
        播报($"你从{区.名称}的街口拐了进去。");
        区服.进入区域(区.定义标识, 区种子);   // 服务内部会发 打开区域事件 → 面板管理器切到区域面板
        return true;
    }

    // ================= 解锁条件 =================

    // 未解锁缘由（"" = 放行）。条件类型见 数据模型.解锁条件项：
    //   天数 / 物品 —— 这两条都挂在**现有的**玩家档案状态上。
    //   注：「情报」暂不可用（情报系统只到"收音机播报池"为止，全仓库没有任何"已获得"的记录
    //       → 写了就是一道**永远打不开的门**）。DataService 会把「情报」直接判成校验错误。
    public string 未解锁缘由(网格实体 区)
    {
        if (区?.解锁 == null || 区.解锁.Length == 0) return "";
        var 档 = 档案;
        if (档 == null) return "";
        foreach (var 条 in 区.解锁)
        {
            if (条 == null) continue;
            bool 满足;
            switch (条.条件)
            {
                case "天数": 满足 = 档.游戏天数 + 1 >= 条.数值; break;   // 游戏天数 从 0 起（第 1 天 = 0）
                case "物品": 满足 = 档.持有物品(条.标识); break;
                default:     满足 = false; break;                       // 未知条件当作未满足（不静默放行）
            }
            if (!满足) return 默认提示(条, 区);
        }
        return "";
    }

    public bool 已解锁(网格实体 区) => string.IsNullOrEmpty(未解锁缘由(区));

    private static string 默认提示(解锁条件项 条, 网格实体 区)
    {
        if (!string.IsNullOrEmpty(条.提示)) return 条.提示;
        string 名 = 区?.名称 ?? "那片地方";
        switch (条.条件)
        {
            case "天数": return $"你还不敢往{名}那边去——再撑几天，摸清这一带的规律。";
            case "物品": return string.IsNullOrEmpty(条.标识) ? $"进{名}得先有点准备，你手上没有。" : $"进{名}得先有{条.标识}，你手上没有。";
            default:     return $"{名}现在还进不去。";
        }
    }

    // ================= 数据取用 =================

    // 区域标识 → 显示名（区域模板名；没有就退回标识）
    private string 取名(string 标识)
    {
        if (string.IsNullOrEmpty(标识)) return "";
        if (数据 != null && 数据.区域模板.TryGetValue(标识, out var 区) && !string.IsNullOrEmpty(区.名称)) return 区.名称;
        return 标识;
    }

using System;
using System.Collections.Generic;
using UnityEngine;

// ============================================================
// 区域探索服务：**区域层**的状态机（纯逻辑，零 MonoBehaviour）。基类 = 格子探索服务（格子世界运行器）。
// 循环：进入区域（按种子生成一张区域网格：地块制摆若干建筑）→ 点地面走位（走 1 格 = 1 游戏分钟）
//       → 走到某栋楼的**入口格**上 → 进楼（第 1 刀：直接进那栋楼对应的房间；建筑层接管后改成进它的 1F）。
//
// 迷雾 / 视野：**和房间层同一套**（基类那套，这里一行都不用重写）——
//   以令牌为中心的正方形视野（白天 7 / 夜晚 3，读 视野.json）+ 三态（亮 / 白天记忆 / 全黑）
//   + 夜晚弱视野圈（只看得见楼影）+ 记忆按「种子#区域」存（走回头路 / 出了再进来还认得，回安全屋才清）。
//   → 街上"哪栋楼没去过"一眼就能看出来：没去过的地方是黑的，去过但此刻看不见的是压暗的记忆。
//
// 第 1 刀不做（记在这，别以为漏了）：
//   · 视线遮挡（楼挡住楼后面）：**方形视野不做遮挡**（与房间层一致，见 网格视野 文件头）。
//     楼体是 挡视线 的，真开遮挡后楼的正脸看得见、楼后的格子看不见 —— 但同时楼**占地中间那几格**
//     也永远不可见，压在那些格上的楼名会跟着被黑雾埋掉。要开的话得连"楼名画在雾之上"一起做。
//
// v51 刀12 补上的两件（原来挂在"第 2 刀"）：
//   · **街上遭遇**：遭遇与战斗那一整块已经从 房间探索服务 上移到 格子探索服务（刀8），
//     这边只填三件语义 —— 抵达后检查 → 检查遭遇()、胜负节点 __区域胜利/__区域返回、战斗收尾之后 → 回区域面板。
//     敌人由 区域生成器.撒敌人 按 区域模板.敌人 摆在街上（占格 = true，走到相邻格就开打）。
//   · **街口（区域出口格）**：区域生成器 在边界墙上正对入口那一格打通、放一扇不占格的门；
//     走上去 = 离开这一片，回大世界（见 抵达格()）。
// ============================================================
public sealed class 区域探索服务 : 格子探索服务
{
    // 当前这一片区域（UI 用这个名字；实体就是基类的 当前世界）
    public 网格数据 当前区域 => 当前世界;
    public string 当前区域标识 { get; private set; } = "";

    public 区域探索服务(EventBus 事件, DataService 数据, PlayerService 玩家服务)
        : base(事件, 数据, 玩家服务) { }

    // ================= 基类钩子（区域语义） =================

    // 迷雾 / 视野：**不覆写** —— 直接用基类那套（有迷雾 = true、视野边长 = 角色+时段 的方形视野）。
    // 街上和楼里"看得见多少"用同一个 视野.json，改一处两处都变。

    // 遭遇：走完一步先看有没有撞上街上敌人（与房间层/大世界层同一个实现，基类里那套）
    protected override bool 抵达后检查() => 检查遭遇();

    // ================= 敌人 AI（刀61）—— 本层只填"差异" =================
    // 机制全在 格子探索服务（三层共用：区域街上的敌人也会巡街、听声、追人）。

    // ① 街区里声音传得比旷野近（有楼挡着）：0.65
    public override float 噪音层系数 => 0.65f;

    // ② 撤退点 = **街口（出口格）**：会动的敌人是"活的墙"，
    //    移动之后必须校验"玩家还走不走得出这片区域"，破了就整体撤销那一步。
    protected override void 收撤退点(List<(int 列, int 行)> 收)
    {
        if (当前世界 == null) return;
        var 口 = 区域生成器.出口格(当前世界);
        收.Add(口);
    }

    protected override string 遭遇胜利节点 => "__区域胜利";    protected override string 遭遇返回节点 => "__区域返回";
    protected override string 遭遇日志前缀 => "区域";
    // ★ 区域的迷雾**随档永久保留**（v52）：区域布局种子 = 派生(世界种子, 区域标识) 固定 → 重看信息量为零。
    //   内容照旧每趟重置（柜子/门锁/街上敌人），所以"路我认得、东西得重新翻"。
    protected override bool 迷雾随档保存 => true;
    protected override string 层标签 => "区域";
    // 结算完把面板切回区域层（否则战斗面板会留在最上面，回不到街上）
    protected override void 战斗收尾之后() => 事件?.发布(new 回到区域事件());

    // 走到某一格上：① 街口 = 出门（回大世界）② 某栋楼的入口格 = 进楼
    // 顺序要紧：街口先判 —— 它是"离开这一层"，优先级高于任何建筑。
    protected override bool 抵达格()
    {
        if (当前世界 == null) return false;
        var 口 = 区域生成器.出口格(当前世界);
        if (口.列 == 玩家列 && 口.行 == 玩家行)
        {
            播报($"你走出了{当前世界.名称}的街口。");
            // 与房间层"走大门出楼"同一条路（房间探索服务.推门出去 → 离开房间事件）：
            // **服务只发意图，UI 那侧负责清态 + 回上一个面板**（区域面板 订阅 → 回退 → 服务.离开() + 返回上一面板()）。
            // 这样"从大世界进来的"回大世界面板、"快速测试面板直接进来的"回测试面板，两边都对。
            事件?.发布(new 离开区域事件());
            return true;
        }
        foreach (var 楼 in 当前世界.取类型(网格实体类型.建筑))
        {
            var 门 = 区域生成器.建筑入口格(楼);
            if (门.列 != 玩家列 || 门.行 != 玩家行) continue;
            return 进楼(楼);
        }
        return false;
    }

    protected override void 发布显示事件(string 信息条, int 列, int 行)
        => 事件?.发布(new 区域显示事件(信息条, 列, 行));

    // ================= 进出 =================

    // 进入区域：大地图/荒野节点进来时调用。同一种子 = 同一片区域（楼的位置、种类都一样）。
    public bool 进入区域(string 区域标识, int 种子)
    {
        if (数据 == null || !数据.区域模板.TryGetValue(区域标识, out var 模板))
        {
            Debug.LogError($"[区域] 区域模板不存在: {区域标识}");
            return false;
        }
        出行种子 = 种子;
        出行起点标识 = 区域标识;
        存视野记忆();          // 上一片区域看过的格存回记忆表（换地图前必须存，下一行接不上就白走了）
        当前世界 = 区域生成器.生成(种子, 模板, 取名, 取建筑模板);
        if (当前世界 == null) return false;
        当前种子 = 种子;
        当前区域标识 = 区域标识;
        已探索.Clear();
        // 装回这一片区域的迷雾记忆：**同一片区域**出楼再进来 / 出区域再回来 / 关游戏再读档，
        // 看过的街不会又变回全黑（区域是**永久层**，记忆进档；见 格子探索服务.装回迷雾记忆）
        装回迷雾记忆();
        当前可见.Clear();
        当前路径.Clear();
        遭遇中 = false;
        遭遇目标 = null;
        最近尸体容器 = "";
        刷新视野();
        同步网格();
        补敌人显示名();   // 生成器只塞了 定义标识，这里从 enemies.json 换成真名（遭遇播报要用）
        事件?.发布(new 打开区域事件(区域标识, 种子));
        播报($"你走进了{当前世界.名称}。{危险度文本(当前世界.危险度)}");
        发布显示();
        return true;
    }

    // 离开区域：清这一片的临时态（楼里的进度由 房间探索服务 / 搜索服务 管）
    public void 离开()
    {
        if (当前世界 == null) return;
        离开世界();
        当前区域标识 = "";
        // 回大世界：HUD 地点位与面板内容都交给 大世界探索服务 重发一次 —— 它才是"当前那一层"的持有者。
        // （原来是把 档案.当前大节点 这个字符串刷回 HUD；节点网图退役后没有这个字段了。）
        var 大世界 = ServiceRegistry.Get<大世界探索服务>();
        if (大世界 != null && 大世界.探索中) 大世界.发布显示();
        else 事件?.发布(new 地图位置事件(地图模式.大地图, "安全屋"));
    }

    // ================= 进楼 =================

    // 第 1 刀：一栋楼 = 一个房间模板（先直接进那间房）。
    // 建筑层（第 3 层）接管后：定义标识 换成 建筑模板 → 这里改成"进它的 1F"，房间由建筑层再往下发。
    private bool 进楼(网格实体 楼)
    {
        if (楼 == null) return false;
        string 定 = 楼.定义标识;
        var 房服 = ServiceRegistry.Get<房间探索服务>();
        if (房服 == null) { Debug.LogError("[区域] 房间探索服务未装配，进不了楼"); return false; }
        // 楼种子 = 派生(区域出行种子, 楼标识)：**同一栋楼**永远是同一套内容（柜子进度也留得住），
        // 同一片区域里两栋同类型的楼也不会共用同一份内容。
        int 楼种子 = 确定性随机.派生(出行种子, 楼.标识);
        播报($"你推开了{楼.名称}的门。");
        // ① 建筑模板（多层楼）优先；② 没有就退化成"一个房间模板当一栋小房子"
        if (数据 != null && 数据.建筑模板.ContainsKey(定)) return 房服.进入建筑(定, 楼种子);
        if (数据 != null && 数据.房间模板.ContainsKey(定)) return 房服.进入房间(定, 楼种子, "");
        播报($"{楼.名称}的门锁着，里面一片黑。");   // 数据没对上：给一句反馈，不要静默
        Debug.LogWarning($"[区域] 建筑[{楼.标识}] 指向的 [{定}] 既不是建筑模板也不是房间模板");
        return false;
    }

    // ================= 数据取用 =================

    // 标识 → 显示名（建筑模板优先，其次房间模板）
    private string 取名(string 标识)
    {
        if (string.IsNullOrEmpty(标识)) return "";
        if (数据 != null && 数据.建筑模板.TryGetValue(标识, out var 建) && !string.IsNullOrEmpty(建.名称)) return 建.名称;
        if (数据 != null && 数据.房间模板.TryGetValue(标识, out var 房) && !string.IsNullOrEmpty(房.名称)) return 房.名称;
        return 标识;
    }

    // 建筑标识 → 建筑模板（拿它的**外形**：L 型等非矩形占地）
    private 建筑模板 取建筑模板(string 标识)
    {
        if (数据 == null || string.IsNullOrEmpty(标识)) return null;
        return 数据.建筑模板.TryGetValue(标识, out var 建) ? 建 : null;
    }
}

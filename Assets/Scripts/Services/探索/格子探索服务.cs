    // ================= 噪音 + 敌人 AI（刀61，三层共用） =================
    // 玩家做什么事都会发出大大小小的声音（强度表在 数据模型.噪音强度）。噪音有两个作用：
    //   · 听得见但 < 敌人.噪音阈值 → **吸引靠近**（只改巡逻方向："过去看看"，不是锁定你）
    //   · 听得见且 ≥ 阈值      → **直接进入追踪**（目标格 = 噪音格）
    // ★ **第三层修正：下沉到基类**。原来只接在大世界层 → 用户在**建筑里**看敌人"根本没动过"
    //   （那是我的范围限定，不是 bug，但结论很清楚：玩家期望的是"到哪儿敌人都是活的"）。
    //   AI 的规则全在 Domain（与"格子上是什么"无关），所以三层共用一份实现；
    //   各层的差异只有两个，由派生覆写：`噪音层系数`（声音传多远）与 `收撤退点`（不许把玩家围死）。
    // 传播范围仍是**同层**（房间里开枪吵不到街上）；跨层要"楼层 → 建筑入口格"的映射，另做。

    // 声音在**这一层**传得多远：大世界 1.0（旷野）/ 区域 0.65（街区，楼挡着）/ 房间 0.35（室内）。
    // 乘在**半径**上，不乘在强度上 —— 否则"房子小"会让室内开枪不算巨响（两件事被混成一件）。
    public virtual float 噪音层系数 => 1f;   // public：探索图层的流场调试叠层（F2）要在面板上显示它

    // 敌人移动之后"玩家还走得出去吗"要校验的落点（派生给；默认不校验）。
    protected virtual void 收撤退点(List<(int 列, int 行)> 收) { }

    // 在玩家此刻的位置上发出一声噪音（绝大多数噪音都是"我在哪儿弄出的声音"）
    protected void 播噪音(int 强度) => 播噪音(玩家列, 玩家行, 强度);

    protected void 播噪音(int 列, int 行, int 强度)
    {
        if (当前世界 == null || 强度 <= 0) return;
        噪音结算(new 噪音事件(列, 行, 强度));
    }

    // 玩家这一下攻击有多响（按**当前持用的武器种类**）：枪械 90 / 弓弩 25 / 近战 15。
    // 取武器的口径与 战斗单位 造玩家单位时**完全一致**（主手优先、主手空则副手）——
    // 两处若不一致，会出现"面板上写你拿着枪、噪音却按近战算"这种查不出来的偏差。
    protected int 战斗噪音强度()
    {
        var 档 = 档案;
        if (档 == null) return 噪音强度.近战;
        string 武 = 档.装备管理?.装备标识("主手") ?? "";
        if (string.IsNullOrEmpty(武)) 武 = 档.装备管理?.装备标识("副手") ?? "";
        var 类 = 档.武器种类解析?.Invoke(武) ?? 武器种类.无;
        if (武器种类判定.是枪械(类)) return 噪音强度.开枪;
        if (武器种类判定.是弓弩(类)) return 噪音强度.弓弩;
        return 噪音强度.近战;
    }

    // 噪音结算：让本层的敌人听见（三层共用同一份实现）
    protected void 噪音结算(噪音事件 噪)
    {
        if (当前世界 == null) return;
        int 潜行值 = 档案?.潜行值 ?? 0;
        int 被惊动 = 0;
        foreach (var 敌 in 当前世界.取类型(网格实体类型.敌人))
        {
            var 数据 = 取敌数据(敌);
            if (数据 == null) continue;
            var 态 = 取态(敌);
            // 返回值 = 发生了"过阈 → 直接进追踪"那次迁移（小噪音的"吸引靠近"不算，它只改巡逻方向）
            if (大世界敌人AI.结算噪音(态, 数据, 敌.列, 敌.行, 噪, 潜行值, 噪音层系数)) 被惊动++;
        }
        if (被惊动 > 0) 播报($"那一下动静传出去很远——{被惊动} 个东西朝这边来了。");
    }

    // ================= 敌人 AI 的时间驱动（即时制·三层共用） =================
    // 由 世界时间管理器.推进() / 跳时() 每帧调用 —— 与 净化 / 生长 / 阅读 同一个模式。
    // 按**游戏分钟**而不是按"玩家走一步"：本作是即时制，站着不动世界冻结是 bug。
    // 间隔 = 移动步频 × **本层**每格游戏分钟（大世界 5 / 楼里 1）
    //   → "玩家走 N 格它走 1 格"这条平衡在**三层都成立**。
    // 整数分钟累加 → 与帧率无关（同样的总分钟数 = 同样的步序），可离线复现、可断言。
    public void 时间推进(float 游戏分钟)
    {
        if (当前世界 == null || 游戏分钟 <= 0f) return;
        分钟累计 += 游戏分钟;
        int 整数分 = (int)分钟累计;   // 攒够整分钟才算 —— 否则敌人会随帧率"一小步一小步地挪"
        if (整数分 <= 0) return;
        分钟累计 -= 整数分;
        驱动敌人(整数分);
    }

    private void 驱动敌人(int 整数分)
    {
        if (当前世界 == null) return;
        var 敌人们 = 当前世界.取类型(网格实体类型.敌人);
        剪掉失联的敌人态(敌人们);
        if (敌人们.Count == 0) return;

        int 潜行值 = 档案?.潜行值 ?? 0;
        var 本步移动 = new List<(网格实体 敌, int 原列, int 原行)>();

        foreach (var 敌 in 敌人们)
        {
            var 数据 = 取敌数据(敌);
            if (数据 == null) continue;
            var 态 = 取态(敌);
            态.分钟计 += 整数分;
            int 间隔 = 大世界敌人AI.间隔分钟(数据, 移动游戏分钟);
            // 一次推进可能跨过好几个节拍（`跳时` 制作 100 分钟就是这样）→ while 不是 if
            while (态.分钟计 >= 间隔)
            {
                态.分钟计 -= 间隔;
                态.步数++;
                int 掷 = 大世界敌人AI.掷点(出行种子, 敌.标识, 态.步数);
                if (大世界敌人AI.感知与迁移(态, 数据, 敌.列, 敌.行, 玩家列, 玩家行, 当前时段, 潜行值, 掷))
                {
                    // 只报"它盯上了你"，而且**只在你看得见它的时候报** —— 视野外的状态变化不该剧透
                    if (态.状态 == 敌人状态.追踪 && 态.目标是不是玩家 && 可见(敌.列, 敌.行))
                        播报($"{敌.名称}盯上了你。");
                }
                流场 场 = null;
                if (态.状态 == 敌人状态.追踪 && 态.目标列 >= 0) 场 = 取追踪场(态.目标列, 态.目标行);
                if (!大世界敌人AI.想走的格(当前世界, 态, 数据, 敌.列, 敌.行, 场, 掷,
                                            out int 目标列, out int 目标行)) continue;
                落子(敌, 态, 目标列, 目标行, 本步移动);
            }
        }

        if (本步移动.Count == 0) return;

        // ★ 不破连通（**硬保证**）：会动的占格敌人是"活的墙"。
        //   生成期那条"占格物彼此切比雪夫≥2 → 凑不出 8 连通屏障"的数学论证（大世界生成器 L311）**前提是它们从不移动**。
        //   这里用一次早退 BFS 换硬保证：破了就把这一步**整体撤销**。
        if (!连通还成立())
        {
            foreach (var (敌, 原列, 原行) in 本步移动) { 敌.列 = 原列; 敌.行 = 原行; }
            本步移动.Clear();
            Debug.Log($"[{遭遇日志前缀}] 敌人这一步会把玩家围死 —— 已整体撤销（连通硬保证）");
            return;
        }
        // 一趟里**第一次**有敌人挪窝时打一行 —— "敌人 AI 到底跑没跑"的直接证据（一趟只有一行）
        if (!敌人AI已启动)
        {
            敌人AI已启动 = true;
            var s = 本步移动[0];
            Debug.Log($"[{遭遇日志前缀}] 敌人 AI 已启动：本次 {本步移动.Count} 只移动（样例 {s.敌.名称} ({s.原列},{s.原行})→({s.敌.列},{s.敌.行})）");
        }
        同步网格();   // 敌人在 网格数据 里换了格 → 渲染框架那份要跟上
        发布显示();
    }

    // 落子：判据与落子都在 Domain（服务层与 `Tools/大世界敌人验证` 跑同一份）
    private bool 落子(网格实体 敌, 大世界敌人AI.敌人AI态 态, int 目标列, int 目标行,
                     List<(网格实体 敌, int 原列, int 原行)> 本步移动)
    {
        if (!大世界敌人AI.落子(当前世界, 敌, 态, 目标列, 目标行)) return false;
        本步移动.Add((敌, 态.上次列, 态.上次行));   // 落子已把"原格"写进 态.上次列/行
        return true;
    }

    // 连通硬保证：敌人移动之后玩家必须还走得到**任一**撤退点（**敌人挡路 = true**：这里是"活墙"校验）。
    private bool 连通还成立()
    {
        if (当前世界 == null) return true;
        var 点 = new List<(int 列, int 行)>();
        收撤退点(点);
        if (点.Count == 0) return true;   // 这一层没给撤退点 → 不校验（基类不知道哪一格是出口）
        foreach (var p in 点)
            if (流场.可达(当前世界, p.列, p.行, 玩家列, 玩家行, true)) return true;
        return false;
    }

    // 追踪场：按 **(世界, 目标格)** 缓存 —— **必须带世界**：房间层换层之后 (列,行) 会撞车。
    private 流场 取追踪场(int 目标列, int 目标行)
    {
        var 键 = (当前世界, 目标列, 目标行);
        if (追踪场表.TryGetValue(键, out var 场) && 场 != null) return 场;
        if (追踪场表.Count >= 追踪场上限) 追踪场表.Clear();   // 上限：重建很便宜（BFS 亚毫秒级）
        场 = 流场.建场(当前世界, 目标列, 目标行);
        追踪场表[键] = 场;
        return 场;
    }

    // 障碍（临时建筑）变了 → 所有流场作废。**敌人死了不作废**：追踪场里敌人是透明的。
    protected void 清流场缓存() => 追踪场表.Clear();

    // 敌人 AI 的运行期态活"一趟"：回安全屋 / 换世界时整体作废
    protected void 清敌人AI态()
    {
        敌人态.Clear();
        追踪场表.Clear();
        已报过的敌人.Clear();
        分钟累计 = 0f;
        敌人AI已启动 = false;
    }

    private readonly Dictionary<网格实体, 大世界敌人AI.敌人AI态> 敌人态
        = new Dictionary<网格实体, 大世界敌人AI.敌人AI态>();
    private readonly Dictionary<(网格数据 世界, int 列, int 行), 流场> 追踪场表
        = new Dictionary<(网格数据, int, int), 流场>();
    private const int 追踪场上限 = 8;
    private readonly HashSet<网格实体> 已报过的敌人 = new HashSet<网格实体>();
    private float 分钟累计;
    private bool 敌人AI已启动;

    private 敌人数据 取敌数据(网格实体 敌)
        => 数据 != null && 敌 != null && 数据.敌人.TryGetValue(敌.定义标识 ?? "", out var d) ? d : null;

    private 大世界敌人AI.敌人AI态 取态(网格实体 敌)
    {
        if (敌人态.TryGetValue(敌, out var 态) && 态 != null) return 态;
        态 = new 大世界敌人AI.敌人AI态();
        大世界敌人AI.记账出生点(态, 敌.列, 敌.行);   // 出生点 = 生成时撒的位置
        敌人态[敌] = 态;
        return 态;
    }

    // 敌人被打死 / 被连通校验撤掉之后，它的态要跟着走（否则字典一直攥着旧实体 → 泄漏 + 误命中）
    private void 剪掉失联的敌人态(List<网格实体> 敌人们)
    {
        if (敌人态.Count == 敌人们.Count) return;   // 数量一致就一定没有失联项
        var 集合 = new HashSet<网格实体>(敌人们);
        var 待删 = new List<网格实体>();
        foreach (var kv in 敌人态) if (!集合.Contains(kv.Key)) 待删.Add(kv.Key);
        foreach (var k in 待删) 敌人态.Remove(k);
    }

    // ================= 遭遇 / 战斗（三层共用） =================
    // 原在 房间探索服务 里；v51 刀8 上移到基类 —— 让**区域层（街上）**与**大世界层（废城街道）**也能撞上敌人。
    // 派生只填"这一层的语义"（下面这些虚属性/钩子），流程一行不用重写。
    // 铁律（沿用 v49 定版）：**一场遭遇 = 一个敌人**（一个标识 = 一只），解决掉它再碰到下一只才是另一场。

    public const int 先手撞上 = 1;   // 相邻撞上：敌人先手
    public const int 先手看清 = 2;   // 视野内 ≥3 格先看见：玩家先手

    // 本次战斗是不是由**本层**发起的（战斗结束事件回来时用来过滤掉别人的战斗）
    public bool 本次战斗来自本层 { get; protected set; }

    protected virtual string 遭遇胜利节点 => "__房间胜利";
    protected virtual string 遭遇返回节点 => "__房间返回";
    protected virtual string 遭遇棋盘 => 当前世界?.战斗棋盘 ?? "";
    protected virtual string 遭遇日志前缀 => "格子";
    // 先手判定：**在 ≥3 格看清过这一只 → 玩家先手**（三层同一口径）。
    // `已察觉` 由 刷新视野之后 维护（基类，见上面）。
    // 注：房间层原来自己覆写过这一条，刀61 上移到基类后它不再需要覆写 —— 行为完全一致。
    protected virtual int 遭遇先手(网格实体 敌)
        => 敌 != null && 已察觉.Contains(敌) ? 先手看清 : 先手撞上;
    // 胜利之后（尸体已经登记好）：房间层用它把"挂在敌人身上的钥匙"塞进尸体
    protected virtual void 胜利之后(网格实体 尸位) { }
    // 结算完把面板切回来：各层发自己的"回到X事件"（房间 → 回到房间事件 / 大世界 → 回到大世界事件）
    protected virtual void 战斗收尾之后() { }

    // 玩家是否与敌人正交相邻 → 触发遭遇（派生在 抵达后检查() 里调它）
    protected virtual bool 检查遭遇()
    {
        if (当前世界 == null || 遭遇中) return false;
        foreach (var 敌 in 当前世界.取类型(网格实体类型.敌人))
        {
            if (Math.Abs(敌.列 - 玩家列) + Math.Abs(敌.行 - 玩家行) != 1) continue;
            开始遭遇(敌);
            return true;
        }
        return false;
    }

    protected virtual void 开始遭遇(网格实体 敌)
    {
        遭遇中 = true;
        遭遇目标 = 敌;
        本次战斗来自本层 = true;
        当前路径.Clear();
        int 先手 = 遭遇先手(敌);
        播报(先手 == 先手看清 ? $"你早就看见它了——先动手。（{敌.名称}）" : $"{敌.名称}扑了上来！");
        // ★ 刀61：**战斗本身也是一次噪音**（枪声 90 / 弓弩 30 / 近战 25）。
        //   位置取敌人那一格：战斗棋盘上没有大世界的坐标，而遭遇就发生在它旁边。
        //   玩家看到效果的时刻是"战斗结束回到本层"——"你打完一只，抬头发现两只堵在路口"。
        播噪音(敌.列, 敌.行, 战斗噪音强度());
        var 战斗 = ServiceRegistry.Get<BattleService>();
        if (战斗 == null) { Debug.LogError($"[{遭遇日志前缀}] 战斗服务未装配，遭遇无法开始"); return; }
        // **只把这一个标识**交给战斗：既不按 敌人组 展开（那是"一个标识变多只"的旧 bug），也不把周围一起拉进来打
        var 参战 = new List<(string 定义标识, string 实例标识)> { (敌.定义标识, 敌.标识) };
        Debug.Log($"[{遭遇日志前缀}] {当前世界.名称} 遭遇 {敌.名称}[{敌.标识}]：参战 1 只（一个标识 = 一个敌人）");
        战斗.开始战斗(当前世界.敌人组, 遭遇胜利节点, 遭遇返回节点, 先手, "", 遭遇棋盘, 参战);
    }

    // 战斗结束（BattleService 发布）：先记住本次的战利品尸体容器
    protected virtual void 战斗结束响应(战斗结束事件 e)
    {
        if (!本次战斗来自本层) return;
        if (!e.胜利) return;
        if (!string.IsNullOrEmpty(e.尸体容器)) 最近尸体容器 = e.尸体容器;
    }

    // 胜利：**只解决掉遭遇的那一只**，在它的位置留一具可搜尸体。
    // 尸体是硬保证：战斗没产出战利品（很多敌人补给值 <4 → 面包/水 都是 0、又没有掉落）时，
    // 这里自己登记一具**空尸体** —— 打死谁都得留下一具能翻的（钥匙挂在它身上时也才有地方掉）。
    // 返回"本层是否真的收尾了"：false = 没切回本层（调用方必须留着结果节点，别当成功）。
    // ★ v51 刀17：这两个方法原来**静默 return**（当前世界 == null 时直接走人）——
    //   调用方（BattleService.回派）以为层已收尾就清掉结果节点，于是战斗面板留在最上层、
    //   [继续] 点了没反应，玩家只能取消/回主菜单。现在返回 false + 大声报，回派方保留节点可重试。
    public virtual bool 战斗胜利()
    {
        if (当前世界 == null)
        {
            Debug.LogError($"[{遭遇日志前缀}] 战斗胜利时当前世界为空（层已提前退出？）—— 战斗无法收尾");
            return false;
        }
        遭遇中 = false;
        本次战斗来自本层 = false;
        var 尸位 = 遭遇目标;
        if (尸位 != null) 当前世界.移除实体(尸位);   // 只移除被解决的那一只（不是"敌人全灭"）
        bool 还有敌人 = 当前世界.敌人总数() > 0;
        var 搜索 = ServiceRegistry.Get<搜索服务>();
        if (尸位 != null && string.IsNullOrEmpty(最近尸体容器) && 搜索 != null)
            最近尸体容器 = 搜索.注册尸体容器("敌人的尸体", 8, 5, null, 0.5f);   // 空尸体（搜一下就知道啥也没有，不拖时间）
        胜利之后(尸位);   // 派生：房间层在这里把"挂在这一只身上的钥匙"塞进尸体
        if (尸位 != null && !string.IsNullOrEmpty(最近尸体容器))
        {
            当前世界.实体.Add(new 网格实体
            {
                标识 = 最近尸体容器,       // 直接用搜索服务登记的战利品容器 id：点击即搜那一份战利品
                类型 = 网格实体类型.尸体,
                阵营 = 网格阵营.中立,
                定义标识 = "尸体",
                名称 = "尸体",
                列 = 尸位.列,
                行 = 尸位.行,
                占格 = false,               // 尸体可以踩过去
                挡视线 = false,
                容器定义 = 搜索?.查找容器(最近尸体容器)
            });
        }
        遭遇目标 = null;
        最近尸体容器 = "";
        刷新视野();
        同步网格();
        播报(还有敌人 ? "它倒下了。地上留着具尸体——周围还有别的东西在动。"
                      : "周围安静下来了。地上留着具尸体——能翻出点东西。");
        发布显示();
        战斗收尾之后();   // 派生：把面板切回本层（否则战斗面板会留在最上面）
        return true;
    }

    // 逃跑：敌人留在原地，玩家退回遭遇前那一格
    public virtual bool 战斗逃跑()
    {
        if (当前世界 == null)
        {
            Debug.LogError($"[{遭遇日志前缀}] 战斗逃跑时当前世界为空（层已提前退出？）—— 战斗无法收尾");
            return false;
        }
        遭遇中 = false;
        本次战斗来自本层 = false;
        遭遇目标 = null;
        最近尸体容器 = "";
        当前路径.Clear();
        if (当前世界.可通行(遭遇前格.列, 遭遇前格.行))
            当前世界.移动玩家(遭遇前格.列, 遭遇前格.行);
        刷新视野();
        同步网格();
        播报("你退了出来，那东西还在那边。");
        发布显示();
        战斗收尾之后();
        return true;
    }

    // ================= 离开 =================

    // 派生类离开时调：存记忆 → 清世界态 → 自己那几样
    protected void 离开世界()
    {
        if (当前世界 == null) return;
        存视野记忆();
        离开前();
        清空世界态();
    }

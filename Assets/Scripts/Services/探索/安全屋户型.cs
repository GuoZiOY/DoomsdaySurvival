using System.Collections.Generic;

// 安全屋户型：程序化 随机 生成 房间 布局——固定 7 房间（门/大厅/主屋/厨房/洗浴间/阳台/二间，
// 二间 三选一：客卧/杂物间/书房）。
// 生成 = 切块引导贪心（BSP 简化精神）：把 网格 递归 二分 成 7 块（块间 留 1 格 墙 = 可拆），
// 每 块 放 一个 房间——房间 均匀 铺满 网格（无 内部 空洞、利用 率 高），门/阳台 分 到 贴 网格 边 的 块。
// 面积 90~110（宽 高 组合 随机，可 横 可 竖）。确定性：同一 种子 同一 户型（读档 恢复）。
public sealed class 安全屋户型
{
    // 房间 类型（固定 7；二间 = 客卧/杂物间/书房 三选一）
    public enum 房间类型 { 门, 大厅, 主屋, 厨房, 洗浴间, 阳台, 二间 }

    public int 房间列数, 房间行数;   // 本 户型 网格 尺寸（面积 90~110）
    public bool[,] 格可用;           // [列,行]
    public int[,] 格所属块;          // >=0 = 块（房间）；-1 = 院子/空地（不可 放）；-2 = 墙（可 拆）
    public List<容器形状块> 形状块;  // 每 块 一个 矩形（索引 = 块号）
    public List<房间类型> 房间类型表;   // 块号 → 类型
    public string 二间名称;          // 客卧/杂物间/书房（随机）

    // 类型 名称（房间 标签 显示 用）
    public static string 类型名称(房间类型 类型) => 类型 switch
    {
        房间类型.门 => "门",
        房间类型.大厅 => "大厅",
        房间类型.主屋 => "主屋",
        房间类型.厨房 => "厨房",
        房间类型.洗浴间 => "洗浴间",
        房间类型.阳台 => "阳台",
        _ => "二间",
    };

    // 基础 家具（0 级 破损 自动 摆放）：床→主屋、灶台→厨房、厕所→洗浴间、门→门房、储物箱→大厅
    public static readonly (string 定义标识, 房间类型 房间, int 宽, int 高)[] 基础家具表 =
    {
        ("床", 房间类型.主屋, 2, 3),
        ("灶台", 房间类型.厨房, 2, 2),
        ("厕所", 房间类型.洗浴间, 2, 1),
        ("门", 房间类型.门, 2, 1),
        ("储物箱", 房间类型.大厅, 2, 3),
    };

    // 网格 面积 组合（90~110；2K 屏 允许 宽、不 允许 过 长——高度 上限 10，宽度 可达 15）
    private static readonly (int 宽, int 高)[] 网格组合 =
    {
        (15, 7), (14, 7), (13, 7), (12, 8), (13, 8),
        (11, 9), (12, 9), (10, 10), (11, 10), (9, 10), (10, 9),
    };

    // 房间 最小 尺寸（切块 时 每 块 至少 装 得 下；可 旋转；阳台 取 1×3 档）
    private static (int 宽, int 高) 最小尺寸(房间类型 类型) => 类型 switch
    {
        房间类型.大厅 => (4, 4),
        房间类型.主屋 => (3, 3),
        房间类型.二间 => (3, 3),
        房间类型.厨房 => (2, 2),
        房间类型.洗浴间 => (2, 2),
        房间类型.门 => (2, 1),
        _ => (3, 1),
    };

    private static string 随机选(System.Random 随机, params string[] 项) => 项[随机.Next(项.Length)];

    // 生成：种子 → 户型（尝试 40 次；全 失败 → 固定 布局 兜底）
    public static 安全屋户型 生成(int 种子)
    {
        var 随机 = new System.Random(种子);
        安全屋户型 最好 = null;
        int 最好利用 = -1;
        for (int 尝试 = 0; 尝试 < 40; 尝试++)
        {
            try
            {
                var 户型 = 尝试生成(随机);
                if (户型 == null) continue;
                int 利用 = 户型.面积利用率();
                if (利用 > 最好利用) { 最好利用 = 利用; 最好 = 户型; }
                if (户型.家具都放得下()) return 户型;
            }
            catch (System.Exception) { }
        }
        return 最好 ?? 固定布局(随机);
    }

    // ===== BSP 切块：递归 二分 网格 → 7 块，块 = 房间（块 尺寸 = 房间 尺寸） =====

    private static 安全屋户型 尝试生成(System.Random 随机)
    {
        var (宽数, 高数) = 网格组合[随机.Next(网格组合.Length)];
        // 房间 顺序 洗牌（布局 多样）；目标 面积 = 各 类型 合理 面积（决定 切块 比例）
        var 全部 = new[] { 房间类型.大厅, 房间类型.主屋, 房间类型.二间, 房间类型.厨房, 房间类型.洗浴间, 房间类型.门, 房间类型.阳台 };
        for (int i = 全部.Length - 1; i > 0; i--)
        {
            int j = 随机.Next(i + 1);
            (全部[i], 全部[j]) = (全部[j], 全部[i]);
        }
        var 房间 = new List<(房间类型 类型, int 目标宽, int 目标高)>();
        foreach (var 类型 in 全部)
        {
            var (宽, 高) = 目标面积尺寸(类型, 随机);
            房间.Add((类型, 宽, 高));
        }
        // 切块（整 网格，四 边 均 贴 网格 边界）——块 = 房间 矩形，直接 登记
        var 块列表 = 切块(随机, 0, 0, 宽数, 高数, 房间, true, true, true, true);
        if (块列表 == null) return null;
        var 户型 = new 安全屋户型 { 房间列数 = 宽数, 房间行数 = 高数 };
        户型.格可用 = new bool[宽数, 高数];
        户型.格所属块 = new int[宽数, 高数];
        户型.形状块 = new List<容器形状块>();
        户型.房间类型表 = new List<房间类型>();
        户型.二间名称 = 随机选(随机, "客卧", "杂物间", "书房");
        for (int 列 = 0; 列 < 宽数; 列++)
            for (int 行 = 0; 行 < 高数; 行++)
                户型.格所属块[列, 行] = -1;   // 院子/空地
        int 块号 = 0;
        foreach (var (列, 行, 宽, 高, 类型) in 块列表)
        {
            块号++;
            for (int c = 列; c < 列 + 宽; c++)
                for (int r = 行; r < 行 + 高; r++)
                    户型.格所属块[c, r] = 块号;
            户型.形状块.Add(new 容器形状块 { 列 = 列, 行 = 行, 宽 = 宽, 高 = 高 });
            户型.房间类型表.Add(类型);
        }
        if (块号 == 0) return null;
        // 未 覆盖 格 全部 = 墙（-2，可 拆）——切块 缝 + 边缘 空隙；暂无 院子 概念
        for (int 列 = 0; 列 < 宽数; 列++)
            for (int 行 = 0; 行 < 高数; 行++)
                if (户型.格所属块[列, 行] == -1) 户型.格所属块[列, 行] = -2;
        for (int 列 = 0; 列 < 宽数; 列++)
            for (int 行 = 0; 行 < 高数; 行++)
                户型.格可用[列, 行] = 户型.格所属块[列, 行] >= 0;
        return 户型;
    }

    // 目标 面积 尺寸：各 类型 的 期望 尺寸（随机 微调 避免 千篇一律；门 恒 2×1/1×2）
    private static (int 宽, int 高) 目标面积尺寸(房间类型 类型, System.Random 随机) => 类型 switch
    {
        房间类型.大厅 => 随机.Next(2) == 0 ? (6, 4) : (4, 6),
        房间类型.主屋 => 随机.Next(2) == 0 ? (4, 5) : (5, 4),
        房间类型.二间 => 随机.Next(2) == 0 ? (4, 4) : (4, 3),
        房间类型.厨房 => 随机.Next(2) == 0 ? (3, 3) : (2, 4),
        房间类型.洗浴间 => 随机.Next(2) == 0 ? (2, 3) : (3, 2),
        房间类型.门 => 随机.Next(2) == 0 ? (2, 1) : (1, 2),
        _ => 随机.Next(2) == 0 ? (1, 4) : (4, 1),   // 阳台 长条
    };

    // 递归 切块：把 矩形 (列,行,宽,高) 切 成 房间.Count 块，块 间 留 1 格 墙（缝）。
    // 块 = 房间（叶子 块 尺寸 即 房间 尺寸）；贴上/贴下/贴左/贴右 = 本 矩形 的 哪些 边 是 网格 外边界。
    // 门/阳台：块 必须 长边 贴 网格 外边界（门 恒 2×1/1×2；阳台 长条）。
    // 返回 (列,行,宽,高,类型) 列表；失败 返回 null。
    private static List<(int 列, int 行, int 宽, int 高, 房间类型 类型)> 切块(
        System.Random 随机, int 列, int 行, int 宽, int 高,
        List<(房间类型 类型, int 目标宽, int 目标高)> 房间,
        bool 贴上, bool 贴下, bool 贴左, bool 贴右)
    {
        if (房间.Count == 1)
        {
            var (类型, _, _) = 房间[0];
            var (最小宽, 最小高) = 最小尺寸(类型);
            // 尺寸 校验：块 能 装 下 最小 尺寸（可 旋转）
            bool 尺寸可 = (宽 >= 最小宽 && 高 >= 最小高) || (宽 >= 最小高 && 高 >= 最小宽);
            if (!尺寸可) return null;
            // 门：块 必须 是 2×1 或 1×2，且 长边（2 格）贴 网格 外边界
            if (类型 == 房间类型.门)
            {
                if (宽 == 2 && 高 == 1) { if (!(贴上 || 贴下)) return null; }
                else if (宽 == 1 && 高 == 2) { if (!(贴左 || 贴右)) return null; }
                else return null;
            }
            // 阳台：块 必须 是 长条（宽=1 或 高=1），长边 贴 网格 外边界
            if (类型 == 房间类型.阳台)
            {
                if (宽 == 1 && 高 > 1) { if (!(贴左 || 贴右)) return null; }   // 竖条 长边 贴 左/右
                else if (高 == 1 && 宽 > 1) { if (!(贴上 || 贴下)) return null; }   // 横条 长边 贴 上/下
                else return null;   // 非 长条（方形 或 宽高 都 >1）不 允许
            }
            return new List<(int, int, int, int, 房间类型)> { (列, 行, 宽, 高, 类型) };
        }
        // 分组：按 目标 面积 均衡（贪心——每次 给 当前 和 小 的 组）
        var 组A = new List<(房间类型, int, int)>();
        var 组B = new List<(房间类型, int, int)>();
        long 和A = 0, 和B = 0;
        foreach (var r in 房间)
        {
            long 面积 = (long)r.目标宽 * r.目标高;
            if (和A <= 和B) { 组A.Add(r); 和A += 面积; }
            else { 组B.Add(r); 和B += 面积; }
        }
        // 两种 归属（A 上/左，B 下/右；或 交换）——门/阳台 所在 组 尽量 分 到 贴 所需 边 的 块
        var 变体 = new[] { (组A, 组B), (组B, 组A) };
        foreach (var (组上, 组下) in 变体)
        {
            for (int 尝试 = 0; 尝试 < 16; 尝试++)
            {
                // 强制 先 切 长 边（宽 > 高×2 只 竖切；高 > 宽×2 只 横切）——块 不 细 长，利用 率 高
                bool 横切;
                if (宽 > 高 * 2) 横切 = false;
                else if (高 > 宽 * 2) 横切 = true;
                else 横切 = 随机.Next(2) == 0;
                if (横切)
                {
                    // 需求：两 组 在 宽 列 内 至少 需 多 高（可 旋转；放 不 下 = 无限）
                    int 需A = 需求高(组上, 宽), 需B = 需求高(组下, 宽);
                    int 可用 = 高 - 1;   // 减 1 格 墙（块 间 缝）
                    if (需A != int.MaxValue && 需B != int.MaxValue && 需A + 需B <= 可用)
                    {
                        // 按 面积 比例 + 随机：上 块 高 ∈ [需A, 可用 - 需B]
                        long 总 = 和A + 和B;
                        int 比例高 = (int)(可用 * (组上 == 变体[0].Item1 ? 和A : 和B) / 总);
                        比例高 = System.Math.Clamp(比例高, 需A, 可用 - 需B);
                        int 抖动 = 随机.Next(3) - 1;
                        int 上高 = System.Math.Clamp(比例高 + 抖动, 需A, 可用 - 需B);
                        var 子上 = 切块(随机, 列, 行, 宽, 上高, 组上, 贴上, false, 贴左, 贴右);
                        if (子上 != null)
                        {
                            var 子下 = 切块(随机, 列, 行 + 上高 + 1, 宽, 高 - 上高 - 1, 组下, false, 贴下, 贴左, 贴右);
                            if (子下 != null) { 子上.AddRange(子下); return 子上; }
                        }
                    }
                }
                else
                {
                    int 需A = 需求宽(组上, 高), 需B = 需求宽(组下, 高);
                    int 可用 = 宽 - 1;
                    if (需A != int.MaxValue && 需B != int.MaxValue && 需A + 需B <= 可用)
                    {
                        long 总 = 和A + 和B;
                        int 比例宽 = (int)(可用 * (组上 == 变体[0].Item1 ? 和A : 和B) / 总);
                        比例宽 = System.Math.Clamp(比例宽, 需A, 可用 - 需B);
                        int 抖动 = 随机.Next(3) - 1;
                        int 左宽 = System.Math.Clamp(比例宽 + 抖动, 需A, 可用 - 需B);
                        var 子左 = 切块(随机, 列, 行, 左宽, 高, 组上, 贴上, 贴下, 贴左, false);
                        if (子左 != null)
                        {
                            var 子右 = 切块(随机, 列 + 左宽 + 1, 行, 宽 - 左宽 - 1, 高, 组下, 贴上, 贴下, false, 贴右);
                            if (子右 != null) { 子左.AddRange(子右); return 子左; }
                        }
                    }
                }
            }
        }
        return null;
    }

    // 组 在 固定 宽 内 至少 需 多 高（每 房间 用 最小 尺寸、可 旋转；任意 房间 放 不 下 = int.MaxValue）
    private static int 需求高(List<(房间类型, int, int)> 组, int 可用宽)
    {
        int 高 = 1;
        foreach (var (类型, _, _) in 组)
        {
            var (最小宽, 最小高) = 最小尺寸(类型);
            if (可用宽 >= 最小宽) 高 = System.Math.Max(高, 最小高);
            else if (可用宽 >= 最小高) 高 = System.Math.Max(高, 最小宽);
            else return int.MaxValue;
        }
        return 高;
    }

    // 组 在 固定 高 内 至少 需 多 宽
    private static int 需求宽(List<(房间类型, int, int)> 组, int 可用高)
    {
        int 宽 = 1;
        foreach (var (类型, _, _) in 组)
        {
            var (最小宽, 最小高) = 最小尺寸(类型);
            if (可用高 >= 最小高) 宽 = System.Math.Max(宽, 最小宽);
            else if (可用高 >= 最小宽) 宽 = System.Math.Max(宽, 最小高);
            else return int.MaxValue;
        }
        return 宽;
    }

    // 四方向（上下 左右）——拆墙 找 相邻 房间 用
    public static readonly (int, int)[] 四方向 = { (0, 1), (0, -1), (1, 0), (-1, 0) };

    // 类型 对应 房间 块号（-1 = 无）
    public int 房间块号(房间类型 类型)
    {
        for (int i = 0; i < 房间类型表.Count; i++)
            if (房间类型表[i] == 类型) return i;
        return -1;
    }

    // ===== 家具 适配 校验 =====

    // 通用 5 件（全 网格 找 空位）+ 基础 5 件（对应 房间 找 空位）——均 可 旋转；
    // 另 校验 面积 利用率（≥60%）与 无 内部 空洞（空白 不 被 房间 围 死）
    private bool 家具都放得下()
    {
        if (!面积利用率够()) return false;
        if (!无内部空洞()) return false;
        var 通用 = new (string, int, int)[]
        {
            ("床", 2, 3), ("工作台", 3, 2), ("储物箱", 2, 3), ("收音机", 1, 1), ("灶台", 2, 2),
            ("晾晒架", 3, 1),   // 刀54：晾晒架（细长，摆在哪儿都放得下——阳台最合适）
        };
        foreach (var (_, 宽, 高) in 通用)
        {
            bool 有 = false;
            for (int 旋转 = 0; 旋转 <= 1 && !有; 旋转++)
            {
                int w = 旋转 == 1 ? 高 : 宽, h = 旋转 == 1 ? 宽 : 高;
                for (int 行 = 0; 行 <= 房间行数 - h && !有; 行++)
                    for (int 列 = 0; 列 <= 房间列数 - w && !有; 列++)
                        if (可放置(列, 行, w, h)) 有 = true;
            }
            if (!有) return false;
        }
        // 基础 4 件：对应 房间 内 找
        foreach (var (_, 类型, 宽, 高) in 基础家具表)
        {
            int 块 = 房间块号(类型);
            if (块 < 0 || 块 >= 形状块.Count) return false;
            var 房间 = 形状块[块];
            bool 有 = false;
            for (int 旋转 = 0; 旋转 <= 1 && !有; 旋转++)
            {
                int w = 旋转 == 1 ? 高 : 宽, h = 旋转 == 1 ? 宽 : 高;
                for (int 行 = 房间.行; 行 + h <= 房间.行 + 房间.高 && !有; 行++)
                    for (int 列 = 房间.列; 列 + w <= 房间.列 + 房间.宽 && !有; 列++)
                        if (可放置(列, 行, w, h)) 有 = true;
            }
            if (!有) return false;
        }
        return true;
    }

    // 形状 校验：覆盖 格 全 可用 且 同 一 块（不 跨 房间/墙）
    private bool 可放置(int 列, int 行, int 宽, int 高)
    {
        int 块 = -2;
        for (int r = 行; r < 行 + 高; r++)
            for (int c = 列; c < 列 + 宽; c++)
            {
                int 此块 = 格所属块[c, r];
                if (此块 < 0) return false;
                if (块 == -2) 块 = 此块;
                else if (块 != 此块) return false;
            }
        return true;
    }

    // 面积 利用率（百分数）：房间 面积 / 网格 面积
    public int 面积利用率()
    {
        int 房间面积 = 0;
        for (int 列 = 0; 列 < 房间列数; 列++)
            for (int 行 = 0; 行 < 房间行数; 行++)
                if (格所属块[列, 行] >= 0) 房间面积++;
        return 房间面积 * 100 / (房间列数 * 房间行数);
    }

    private bool 面积利用率够() => 面积利用率() >= 60;

    // 内部 空洞：空白 格 被 房间 完全 包围（4 邻 全 房间 且 不 贴 网格 边界）→ 不 符合 直觉 → 重试
    private bool 无内部空洞()
    {
        for (int 列 = 0; 列 < 房间列数; 列++)
            for (int 行 = 0; 行 < 房间行数; 行++)
            {
                if (格所属块[列, 行] >= 0) continue;
                if (列 == 0 || 行 == 0 || 列 == 房间列数 - 1 || 行 == 房间行数 - 1) continue;
                bool 全房间 = true;
                foreach (var (dx, dy) in 四方向)
                {
                    int c = 列 + dx, r = 行 + dy;
                    if (c < 0 || r < 0 || c >= 房间列数 || r >= 房间行数 || 格所属块[c, r] < 0) { 全房间 = false; break; }
                }
                if (全房间) return false;
            }
        return true;
    }

    // ===== 兜底：固定 布局（7 房 10×10；门/阳台 贴边；随机 镜像） =====

    private static 安全屋户型 固定布局(System.Random 随机)
    {
        var 户型 = new 安全屋户型 { 房间列数 = 10, 房间行数 = 10 };
        户型.格可用 = new bool[10, 10];
        户型.格所属块 = new int[10, 10];
        户型.形状块 = new List<容器形状块>();
        户型.房间类型表 = new List<房间类型>();
        户型.二间名称 = 随机选(随机, "客卧", "杂物间", "书房");
        for (int 列 = 0; 列 < 10; 列++)
            for (int 行 = 0; 行 < 10; 行++)
                户型.格所属块[列, 行] = -2;
        int 块号 = 0;
        登记固定房间(户型, 0, 0, 4, 5, 房间类型.大厅, ref 块号);     // 大厅（行0-4 列0-3）
        登记固定房间(户型, 5, 0, 3, 4, 房间类型.主屋, ref 块号);       // 主屋（列5-7 行0-3；床 2×3）
        登记固定房间(户型, 8, 0, 2, 1, 房间类型.门, ref 块号);         // 门（2×1；长边 贴 上 边界）
        登记固定房间(户型, 6, 9, 4, 1, 房间类型.阳台, ref 块号);       // 阳台（横条 4×1；长边 贴 下 边界）
        登记固定房间(户型, 8, 4, 2, 2, 房间类型.洗浴间, ref 块号);     // 洗浴间（列8-9 行4-5；厕所 2×1）——不 与 任何 房 重叠
        登记固定房间(户型, 5, 4, 2, 3, 房间类型.厨房, ref 块号);       // 厨房（列5-6 行4-6；灶台 2×2）
        登记固定房间(户型, 0, 6, 4, 4, 房间类型.二间, ref 块号);       // 二间（列0-3 行6-9）
        for (int 列 = 0; 列 < 10; 列++)
            for (int 行 = 0; 行 < 10; 行++)
                户型.格可用[列, 行] = 户型.格所属块[列, 行] >= 0;
        if (随机.Next(2) == 0) 水平镜像(户型);
        if (随机.Next(2) == 0) 垂直镜像(户型);
        return 户型;
    }

    // 水平 镜像（列 翻转）：格所属块/格可用 与 形状块 同步 翻转
    private static void 水平镜像(安全屋户型 户型)
    {
        int 宽 = 户型.房间列数;
        var 新块 = new int[宽, 户型.房间行数];
        var 新可用 = new bool[宽, 户型.房间行数];
        for (int 列 = 0; 列 < 宽; 列++)
            for (int 行 = 0; 行 < 户型.房间行数; 行++)
            {
                新块[列, 行] = 户型.格所属块[宽 - 1 - 列, 行];
                新可用[列, 行] = 户型.格可用[宽 - 1 - 列, 行];
            }
        户型.格所属块 = 新块;
        户型.格可用 = 新可用;
        foreach (var 块 in 户型.形状块) 块.列 = 宽 - 1 - (块.列 + 块.宽 - 1);
    }

    // 垂直 镜像（行 翻转）
    private static void 垂直镜像(安全屋户型 户型)
    {
        int 高 = 户型.房间行数;
        var 新块 = new int[户型.房间列数, 高];
        var 新可用 = new bool[户型.房间列数, 高];
        for (int 列 = 0; 列 < 户型.房间列数; 列++)
            for (int 行 = 0; 行 < 高; 行++)
            {
                新块[列, 行] = 户型.格所属块[列, 高 - 1 - 行];
                新可用[列, 行] = 户型.格可用[列, 高 - 1 - 行];
            }
        户型.格所属块 = 新块;
        户型.格可用 = 新可用;
        foreach (var 块 in 户型.形状块) 块.行 = 高 - 1 - (块.行 + 块.高 - 1);
    }

    private static void 登记固定房间(安全屋户型 户型, int 列, int 行, int 宽, int 高, 房间类型 类型, ref int 块号)
    {
        块号++;
        for (int c = 列; c < 列 + 宽; c++)
            for (int r = 行; r < 行 + 高; r++)
                户型.格所属块[c, r] = 块号;
        户型.形状块.Add(new 容器形状块 { 列 = 列, 行 = 行, 宽 = 宽, 高 = 高 });
        户型.房间类型表.Add(类型);
    }

using System.Collections.Generic;
using UnityEngine;

// 书籍服务：书籍 阅读 系统 统一入口（技能书/配方书/知识/蓝图）。
// 阅读 = 耗时（世界时间管理器 逐帧 推进 堆叠.阅读分钟）→ 读满 → 扣耐久（无论成败）→ 成功率判定 → 习得/失败。
// 数值：书籍级别（低/中/高/顶）→ 成功率 + 每次耐久 消耗（档位表：低 8 / 中 10 / 高 20 / 顶 40；
//       单本书 用 `物品数据.每次耐久消耗` 覆盖它，知识书 正是靠这个字段 做到"一本读一次"）。
//       失败 叠加（每次 +12%）；智慧 每点 +1%；天赋「学霸」抽奖书 有 概率 不扣耐久、知识书 经验 ×1.15。
// 习得：配方书 → 权重池 抽 1 个（已习得 降权 ×0.2）；
//       技能书/指南 → 技能池 抽 1 个（已学会 降权 ×0.2 → 未学会优先；未学会 授技能 / 已学会 提熟练度）；
//       知识书（精通/制作）→ **必成**（不掷成功率）：首次读满 解锁该知识，之后 加经验、满「该书 知识门槛」升级
//                            → 按 (旧, 新] 发该级奖励（解锁配方/技能 + 属性加成）。
// 蓝图：被动持有即解锁（不 参与 阅读；制作 服务 判 持有 解锁图纸）。
public sealed class 书籍服务
{
    private readonly EventBus 事件;
    private readonly DataService 数据;
    private 玩家档案 玩家 => ServiceRegistry.Get<PlayerService>().档案;

    // 失败 叠加：每次 失败 +12% 成功率（成功/习得 全部掌握 时 清零）
    private const float 失败叠加系数 = 0.12f;
    // 已习得 配方 权 重 衰减（软防重复——仍可 重复 抽到，但 概率 大跌）
    private const float 已习得权重衰减 = 0.2f;

    // 书籍级别 →（成功率, 每次耐久消耗）——低/中/高/顶（传奇 = 蓝图，被动 不 阅读）
    private static readonly Dictionary<string, (float 成功率, int 每次消耗)> 级别数值 = new Dictionary<string, (float, int)>
    {
        ["低"] = (0.44f, 8),
        ["中"] = (0.33f, 10),
        ["高"] = (0.22f, 20),
        ["顶"] = (0.11f, 40),
    };

    // 抽奖书（手册 / 指南）里「学霸」不消耗耐久的概率 —— 书越难抽到，白读的机会越小
    private static readonly Dictionary<string, float> 学霸免耗概率 = new Dictionary<string, float>
    {
        ["低"] = 0.26f,
        ["中"] = 0.20f,
        ["高"] = 0.13f,
        ["顶"] = 0.07f,
    };

    // 知识书 没配 `知识门槛` 时的兜底曲线（就是那份"前松后紧"的标准表：100/200/…/1600/2000）
    private static readonly int[] 默认知识门槛 = { 100, 200, 300, 400, 500, 700, 900, 1200, 1600, 2000 };

    public 书籍服务(EventBus 事件, DataService 数据)
    {
        this.事件 = 事件;
        this.数据 = 数据;
    }

    // 是否 可读 书籍（类型=书籍 且 种类=技能书/配方书/知识；蓝图 被动 不 阅读）
    public bool 是可读书籍(物品数据 物品)
        => 物品 != null && 物品.类型 == "书籍"
           && (物品.书籍种类 == "技能书" || 物品.书籍种类 == "配方书" || 物品.书籍种类 == "知识");

    // 级别 → 成功率
    public float 成功率(物品数据 物品)
        => 级别数值.TryGetValue(物品?.书籍级别 ?? "", out var 值) ? 值.成功率 : 0.44f;

    // 每次 耐久 消耗：单本书 配了 `每次耐久消耗` 就听它的（知识书 = 40 → 读一次 耗光 自身耐久 → 崩解）；
    // 没配 才 回落到 级别 档位表 —— 老书 靠这条 走原来那套
    public int 每次耐久消耗(物品数据 物品)
        => 物品 != null && 物品.每次耐久消耗 > 0
            ? 物品.每次耐久消耗
            : (级别数值.TryGetValue(物品?.书籍级别 ?? "", out var 值) ? 值.每次消耗 : 8);

    // 开始 阅读：设 堆叠.阅读分钟 = 阅读时间分（世界时间管理器 逐帧 扣减 到 0 → 结算）
    public void 开始阅读(物品堆叠 堆叠, 物品数据 物品)
    {
        if (堆叠 == null || 物品 == null || 物品.阅读时间分 <= 0 || 堆叠.阅读分钟 > 0) return;
        // 知识书 已 满级：不 再 开读（读了 只 会 把 书 读散，什么都拿不到）；手册/指南/技能书 不 受这条管
        int 上限 = 物品.知识等级?.Length ?? 0;
        if (物品.书籍种类 == "知识" && 上限 > 0 && 玩家.知识等级(物品.标识) >= 上限)
        {
            事件.发布(new 日志事件(日志类型.系统, "这门知识你已经全部掌握了"));
            return;
        }
        堆叠.阅读分钟 = 物品.阅读时间分;
        事件.发布(new 日志事件(日志类型.角色, $"你翻开《{物品.标识}》，开始研读。"));
    }

    // 阅读 推进（世界时间管理器 推进/跳时 调用）：遍历 持有 书籍，阅读分钟 递减；到 0 → 结算
    public void 阅读推进(float 游戏分钟)
    {
        if (游戏分钟 <= 0 || 玩家 == null) return;
        foreach (var 堆叠 in 玩家.所有持有物品())
        {
            if (堆叠 == null || 堆叠.阅读分钟 <= 0) continue;
            if (!数据.物品.TryGetValue(堆叠.标识, out var 物品) || !是可读书籍(物品)) { 堆叠.阅读分钟 = 0; continue; }
            堆叠.阅读分钟 -= 游戏分钟;
            if (堆叠.阅读分钟 <= 0) 结算阅读(堆叠, 物品);
        }
    }

    // ===== 结算 阅读（读满：扣耐久 + 判定） =====

    private void 结算阅读(物品堆叠 堆叠, 物品数据 物品)
    {
        堆叠.阅读分钟 = 0;
        // 知识书 必成：读的是"手艺"不是"运气"（读满 就 一定 有 收获），走 成功结算，连 判定 都 不掷
        if (物品.书籍种类 == "知识") 成功结算(堆叠, 物品);
        else if (判定成功(物品, 堆叠)) 成功结算(堆叠, 物品);
        else 失败结算(堆叠, 物品);

        // 扣 耐久（无论 成败——每 读满 一次 消耗）；耐久 ≤0 → 崩解
        // 天赋「学霸」（大学生）：抽奖书 有 概率 这一遍 白读（不扣耐久）——知识书 不 吃这条（它 已经 必成 + 一次 一本）
        bool 白读 = 物品.书籍种类 != "知识" && 学霸免耗(物品);
        if (!白读) 堆叠.当前耐久 -= 每次耐久消耗(物品);
        if (堆叠.当前耐久 <= 0) 崩解(堆叠, 物品);
    }

    // 「学霸」这一遍是否 白读（不 消耗 耐久）：没有该天赋 或 抽不到 → false
    private bool 学霸免耗(物品数据 物品)
        => 玩家.天赋.Contains("学霸")
           && 学霸免耗概率.TryGetValue(物品.书籍级别 ?? "", out var 概率)
           && Random.value < 概率;

    // 成功率 = 基础率 + 智慧×1% + 失败叠加（原来是"智力"—— 那是奇幻 RPG 的别名，v51 已删）
    private bool 判定成功(物品数据 物品, 物品堆叠 堆叠)
    {
        float 基础 = 成功率(物品);
        float 智慧修正 = 玩家.智慧 * 0.01f;
        float 叠加 = 堆叠.失败叠加 * 失败叠加系数;
        float 率 = Mathf.Clamp01(基础 + 智慧修正 + 叠加);
        return Random.value < 率;
    }

    private void 成功结算(物品堆叠 堆叠, 物品数据 物品)
    {
        if (物品.书籍种类 == "配方书") 配方书成功(堆叠, 物品);
        else if (物品.书籍种类 == "技能书") 技能书成功(堆叠, 物品);
        else if (物品.书籍种类 == "知识") 知识书成功(堆叠, 物品);
        堆叠.失败叠加 = 0;   // 成功 → 清 叠加
    }

    private void 失败结算(物品堆叠 堆叠, 物品数据 物品)
    {
        堆叠.失败叠加++;
        // 软收益（温故知新）：技能书/指南 → 已学会的随机一条给半量熟练度
        // （知识书 不到这儿：它 走"必成"，压根 没有 失败结算）
        if (物品.书籍种类 == "技能书")
        {
            string 标识 = 随机一条已学会(物品);
            if (!string.IsNullOrEmpty(标识) && 数据.技能.TryGetValue(标识, out var 技能))
                玩家.记录熟练度(标识, Mathf.Max(1, 每次熟练度点(物品, 技能) / 2), Mathf.Max(1, 技能.熟练度每级));
        }
        事件.发布(new 日志事件(日志类型.警告, $"你反复研读《{物品.标识}》，却仍是似懂非懂……（下次成功率提升）"));
    }

    // 池 / 单条 里「已学会」的随机一条（失败·温故知新 用）；无 → 空
    private string 随机一条已学会(物品数据 物品)
    {
        var 候选 = new List<string>();
        if (物品.技能池 != null && 物品.技能池.Length > 0)
        {
            foreach (var 标识 in 物品.技能池)
                if (!string.IsNullOrEmpty(标识) && 玩家.掌握技能(标识)) 候选.Add(标识);
        }
        else if (!string.IsNullOrEmpty(物品.技能) && 玩家.掌握技能(物品.技能)) 候选.Add(物品.技能);
        return 候选.Count == 0 ? null : 候选[Random.Range(0, 候选.Count)];
    }

    // 配方书成功：权重池 抽 1 个 配方（已习得 降权）
    private void 配方书成功(物品堆叠 堆叠, 物品数据 物品)
    {
        string 配方标识 = 权重抽取(物品.配方池);
        if (string.IsNullOrEmpty(配方标识))
        {
            事件.发布(new 日志事件(日志类型.系统, $"这本书里的配方，你都已经掌握了。"));
            return;
        }
        if (!玩家.记录习得配方(配方标识)) return;
        var 名称 = 数据.配方.TryGetValue(配方标识, out var 配方) ? 配方.名称 : 配方标识;
        事件.发布(new 日志事件(日志类型.获得, $"你从《{物品.标识}》中学会了【{名称}】的做法！"));
    }

    // 技能书/指南成功：技能池 抽 1 条（已学会降权 → 未学会优先）→ 未学会 授技能 / 已学会 提熟练度
    private void 技能书成功(物品堆叠 堆叠, 物品数据 物品)
    {
        string 技能标识 = 技能池抽取(物品);
        if (string.IsNullOrEmpty(技能标识) || !数据.技能.TryGetValue(技能标识, out var 技能)) return;
        if (玩家.掌握技能(技能标识))
        {
            玩家.记录熟练度(技能标识, 每次熟练度点(物品, 技能), Mathf.Max(1, 技能.熟练度每级));
            事件.发布(new 日志事件(日志类型.角色, $"温故知新，你的《{技能.名称}》熟练度提升了。"));
        }
        else if (ServiceRegistry.Get<技能服务>()?.尝试学习(技能标识) == true)
        {
            事件.发布(new 日志事件(日志类型.角色, $"你读懂了《{物品.标识}》，学会了技能《{技能.名称}》！"));
        }
    }

    // 技能书 每次 熟练度 点数（书 配置 覆盖，缺省 = 每级阈值 一半）
    private int 每次熟练度点(物品数据 物品, 技能数据 技能)
        => 物品.熟练度点 > 0 ? 物品.熟练度点 : Mathf.Max(1, 技能.熟练度每级 / 2);

    // 权重池 抽取：基础权重 按 配方品质（普通5/优秀4/稀有3/史诗2/英雄1），已习得 ×0.2
    private string 权重抽取(string[] 池)
    {
        if (池 == null || 池.Length == 0) return null;
        var 候选 = new List<(string 标识, float 权重)>();
        float 总 = 0f;
        foreach (var 标识 in 池)
        {
            if (!数据.配方.TryGetValue(标识, out var 配方)) continue;
            float 基础 = 配方基础权重(配方);
            float 有效 = 玩家.配方已习得(标识) ? 基础 * 已习得权重衰减 : 基础;
            候选.Add((标识, 有效));
            总 += 有效;
        }
        if (候选.Count == 0) return null;
        float 掷 = Random.value * 总;
        foreach (var (标识, 权重) in 候选)
        {
            if (掷 < 权重) return 标识;
            掷 -= 权重;
        }
        return 候选[候选.Count - 1].标识;
    }

    private static float 配方基础权重(配方数据 配方)
    {
        switch (配方.品质)
        {
            case "优秀": return 4f;
            case "稀有": return 3f;
            case "史诗": return 2f;
            case "英雄": return 1f;
            default: return 5f;   // 普通/空
        }
    }

    // ===== 技能池（技能书 / 指南） =====

    // 技能书/指南 取一条技能：`技能池` 非空 → 按技能品质权重抽 1（已学会 ×0.2，软防重复）；否则回退单条 `技能`
    private string 技能池抽取(物品数据 物品)
    {
        if (物品.技能池 == null || 物品.技能池.Length == 0) return 物品.技能;
        var 候选 = new List<(string 标识, float 权重)>();
        float 总 = 0f;
        foreach (var 标识 in 物品.技能池)
        {
            if (string.IsNullOrEmpty(标识) || !数据.技能.TryGetValue(标识, out var 技能)) continue;
            float 基础 = 技能基础权重(技能);
            float 有效 = 玩家.掌握技能(标识) ? 基础 * 已习得权重衰减 : 基础;
            候选.Add((标识, 有效));
            总 += 有效;
        }
        if (候选.Count == 0) return null;
        float 掷 = Random.value * 总;
        foreach (var (标识, 权重) in 候选)
        {
            if (掷 < 权重) return 标识;
            掷 -= 权重;
        }
        return 候选[候选.Count - 1].标识;
    }

    private static float 技能基础权重(技能数据 技能)
    {
        switch (技能.品质)
        {
            case "优秀": return 4f;
            case "稀有": return 3f;
            case "史诗": return 2f;
            case "英雄": return 1f;
            default: return 5f;   // 普通/空
        }
    }

    // ===== 知识书（精通 / 制作：经验升级式） =====

    // 知识书 每次读满 给的经验（书 配置 覆盖；缺省 100）。「学霸」的 ×1.15 在 成长管理器 里 统一算（那是 天赋 该待的地方）
    private static int 每次知识经验(物品数据 物品) => 物品.知识经验 > 0 ? 物品.知识经验 : 100;

    // 知识书成功：首次读满 → 解锁（1 级）；之后加经验、升级 → 按 (旧, 新] 发该级奖励
    private void 知识书成功(物品堆叠 堆叠, 物品数据 物品)
    {
        int 上限 = 物品.知识等级?.Length ?? 0;
        if (上限 <= 0) return;
        int 旧 = 玩家.知识等级(物品.标识);
        if (旧 >= 上限)
        {
            事件.发布(new 日志事件(日志类型.系统, $"《{物品.标识}》的内容你已经全部掌握了。"));
            return;
        }
        知识进阶(物品, 每次知识经验(物品));
        int 新 = 玩家.知识等级(物品.标识);
        if (新 > 旧)
            事件.发布(new 日志事件(日志类型.角色, 旧 == 0
                ? $"你读懂了《{物品.标识}》，掌握了这门手艺。"
                : $"研读《{物品.标识}》，你的造诣提升到 {新} 级。"));
    }

    // 知识进阶：加经验 → 升级 → 按 (旧, 新] 发该级奖励。
    // 门槛表由这里从书的数据里取出、传进 Domain —— 玩家档案 / 成长管理器 不 认识 DataService，
    // 想按"每本书自己的曲线"升级，就只能由调用方把表递过去。
    private void 知识进阶(物品数据 物品, int 经验)
    {
        var 表 = 物品.知识等级;
        if (表 == null || 表.Length == 0) return;
        var 门槛 = 物品.知识门槛 != null && 物品.知识门槛.Length > 0 ? 物品.知识门槛 : 默认知识门槛;
        var (旧, 新) = 玩家.加知识经验(物品.标识, 经验, 门槛, 表.Length);
        for (int 级 = 旧 + 1; 级 <= 新; 级++) 发知识奖励(物品, 级);
    }

    // 发一级奖励：解锁配方（记录习得——与配方书同一方法，零新机制）
    //              + 解锁技能（走 技能服务.尝试学习，属性前提不满足会记日志跳过，不阻断升级）
    //              + 属性加成（数值本身由 装备管理器.知识加成 读 玩家.已掌握知识 聚合，这里只播报）
    private void 发知识奖励(物品数据 物品, int 级)
    {
        var 行 = 找等级行(物品.知识等级, 级);
        if (行 == null) return;
        if (行.解锁配方 != null)
            foreach (var 配方标识 in 行.解锁配方)
            {
                if (string.IsNullOrEmpty(配方标识) || !玩家.记录习得配方(配方标识)) continue;
                string 名 = 数据.配方.TryGetValue(配方标识, out var 配方) ? 配方.名称 : 配方标识;
                事件.发布(new 日志事件(日志类型.获得, $"《{物品.标识}》{级} 级：你学会了【{名}】。"));
            }
        if (行.解锁技能 != null)
            foreach (var 技能标识 in 行.解锁技能)
            {
                if (string.IsNullOrEmpty(技能标识)) continue;
                if (ServiceRegistry.Get<技能服务>()?.尝试学习(技能标识) == true)
                    事件.发布(new 日志事件(日志类型.获得, $"《{物品.标识}》{级} 级：你领悟了【{技能标识}】。"));
            }
        if (!string.IsNullOrEmpty(行.加成属性) && 行.加成值 != 0f)
            事件.发布(new 日志事件(日志类型.获得, $"《{物品.标识}》{级} 级：{行.加成属性} +{行.加成值:0.#}。"));
    }

    private static 知识等级数据 找等级行(知识等级数据[] 表, int 级)
    {
        if (表 == null) return null;
        foreach (var 行 in 表) if (行 != null && 行.级 == 级) return 行;
        return null;
    }

    // 崩解：耐久 耗尽 → 移除 书籍 + 「读透」被动 + 日志
    private void 崩解(物品堆叠 堆叠, 物品数据 物品)
    {
        if (!玩家.移除物品(堆叠.标识, 1)) return;
        事件.发布(new 背包变化事件(堆叠.标识, -1, 变化原因.消耗));
        事件.发布(new 日志事件(日志类型.系统, $"《{物品.标识}》被你翻散架了，只剩一捧纸屑。"));
        // 「读透」被动（`物品数据.读透被动`）：放在**崩解这一刻**，而不是抽奖池里。
        // 为什么：指南本身是抽奖产物，被动再进 `技能池` 就是拿随机性罚第二次（读烂三本也可能摸不到）。
        //   挂在这里 = 这本书彻底读完（耐久见底）就必定到手，与"读透"这件事的语义也对得上。
        // 为什么先自己播报、再调 尝试学习：尝试学习 失败时会走"无法学习 …（你已经掌握这个技能了）"那条**警告**，
        //   可在这里"已经会了"根本不是玩家做错了什么，平淡带过即可；成功那条才值得说清 被动 是哪来的。
        if (物品.读透被动 == null || 物品.读透被动.Length == 0) return;
        var 技能服务 = ServiceRegistry.Get<技能服务>();
        if (技能服务 == null) return;
        foreach (var 被动标识 in 物品.读透被动)
        {
            if (string.IsNullOrEmpty(被动标识)) continue;
            if (玩家.掌握技能(被动标识))
            {
                事件.发布(new 日志事件(日志类型.系统, $"《{物品.标识}》里那点东西，你早就吃透了。"));
                continue;
            }
            if (技能服务.尝试学习(被动标识) != true) continue;
            string 名 = 数据.技能.TryGetValue(被动标识, out var 被动) ? 被动.名称 : 被动标识;
            事件.发布(new 日志事件(日志类型.角色, $"你把《{物品.标识}》读透了，领悟了【{名}】。"));
        }
    }

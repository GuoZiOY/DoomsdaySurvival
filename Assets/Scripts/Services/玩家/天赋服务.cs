using UnityEngine;

// 天赋服务（机制型天赋核心）：订阅 致命伤害/制作完成 等事件，检查玩家天赋并执行机制。
// 纯数值类天赋（骆驼/渴死鬼/经验倍率/医疗加成/夜晚修正 等）由 玩家档案 派生属性读取（数据表）。
// 机制类天赋（钢铁意志/医者仁心/美食家 等）在此订阅事件响应——方法返回 void（EventBus 只支持 Action<T>），
// 效果直接改 玩家档案/战斗单位 状态，系统通过检查状态感知结果。
// 触发记录（冷却）存 玩家档案.天赋冷却，随档保存。
public sealed class 天赋服务
{
    private readonly EventBus 事件;
    private readonly PlayerService 玩家服务;
    private 玩家档案 档案 => 玩家服务.档案;

    public 天赋服务(EventBus 事件, PlayerService 玩家服务)
    {
        this.事件 = 事件;
        this.玩家服务 = 玩家服务;
        订阅事件();
    }

    private void 订阅事件()
    {
        事件.订阅<致命伤害事件>(处理致命伤害);
        事件.订阅<制作完成事件>(处理制作完成);
    }

    // 是否有某天赋（含职业天赋）
    public bool 有天赋(string 标识)
    {
        if (档案 == null || 档案.天赋 == null) return false;
        return 档案.天赋.Contains(标识);
    }

    // 记录天赋冷却（存 天赋冷却：标识 → 游戏分钟）。★ 刀64：载体从 Dictionary 换成 List<天赋冷却条>
    // —— 原 Dictionary 被 JsonUtility 静默丢弃，冷却根本没随过档，见 玩家档案.天赋冷却 的注释。
    public void 记录冷却(string 标识) => 档案?.记天赋冷却(标识);

    // 冷却是否就绪（默认无冷却）
    public bool 冷却就绪(string 标识, float 冷却分钟)
        => 档案 == null || 档案.天赋冷却就绪(标识, 冷却分钟);

    // ===== 致命伤害响应（钢铁意志 / 医者仁心） =====
    // public：战斗系统在 玩家倒下 时主动调用（发事件 + 检查存活）；EventBus 订阅也走此方法。
    // 效果直接改 战斗单位.生命（保底 1 = 免疫死亡），战斗系统检查 单位.存活 感知结果。

    public void 处理致命伤害(致命伤害事件 e)
    {
        if (档案 == null || e.玩家 == null) return;

        // 退役军人·钢铁意志：免疫致命伤 + 1回合无敌 + 重伤buff；冷却 10 游戏天
        if (有天赋("钢铁意志") && 冷却就绪("钢铁意志", 10 * 1440f))
        {
            记录冷却("钢铁意志");
            e.玩家.生命 = Mathf.Max(1, e.玩家.生命);   // 保底 1（不死亡）
            e.玩家.无敌回合 = 1;
            e.玩家.添加Buff(重伤Buff());
            事件.发布(new 日志事件(日志类型.获得, "钢铁意志！你绝不会倒在这里！"));
            return;
        }

        // 医生·医者仁心：50% 概率自动用绷带自救（恢复 30%）
        if (有天赋("医者仁心") && 冷却就绪("医者仁心", 5 * 1440f))
        {
            if (Random.value < 0.5f && 档案.物品数量("家用绷带") > 0)
            {
                记录冷却("医者仁心");
                档案.移除物品("家用绷带", 1);
                事件.发布(new 背包变化事件("家用绷带", -1, 变化原因.消耗));
                e.玩家.生命 = Mathf.Max(1, e.玩家.最大生命 * 3 / 10);
                事件.发布(new 日志事件(日志类型.获得, "多年的职业本能让你在倒下前为自己做了急救！"));
            }
        }
    }

    // ===== 制作完成响应（美食家：双倍产出） =====

    private void 处理制作完成(制作完成事件 e)
    {
        if (档案 == null) return;
        // 厨师·美食家：灶台（饮食）制作 30% 双倍
        if (有天赋("美食家") && e.类型 == "灶台" && Random.value < 0.3f)
        {
            档案.添加物品(e.产物, e.数量);
            事件.发布(new 背包变化事件(e.产物, e.数量, 变化原因.获得));
            事件.发布(new 日志事件(日志类型.获得, "美食家的手艺——同样的材料，做出了双份！"));
        }
    }

    // 重伤 buff 定义（钢铁意志触发后）
    private static Buff定义 重伤Buff()
    {
        return new Buff定义
        {
            标识 = "重伤",
            名称 = "重伤",
            类型 = "减益",
            属性 = "攻击",
            数值 = -30,       // 攻击 -30%
            持续回合 = 5
        };
    }
}

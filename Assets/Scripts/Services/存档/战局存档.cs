// 战局存档：**把"你现在在哪、周围什么样子"抓成一份快照**（刀65 取的一半；装回是 战局恢复.cs）。
//
// 为什么单独一个类：这件事要同时问三层的服务（大世界/区域/房间）+ 全局的搜索服务，
// 放进任何一层的服务里都会变成"某一层懂另外两层的事"。这里是服务层内部的搬运工，不持状态。
public static class 战局存档
{
    // 抓当前战局。**任何时刻都能调用**（战斗中除外 —— 上层 存档门禁 已经把战斗中拦掉了）。
    // 玩家在安全屋（三层都没有活着的世界）时返回 层 = 安全屋 的战局 → 读档走"从安全屋出发"的老路。
    public static 存档战局 取()
    {
        var 局 = new 存档战局
        {
            层 = 存档战局.层安全屋,
            玩家列 = -1,
            玩家行 = -1,
        };

        // 由外向内：三层**可能同时活着**（世界时间管理器 每帧喂三层，而进楼/进区域时上层并不清空）
        // → 活着的每一层都要抓，否则读档后外层敌人的位置会"凭空前进"。
        var 世 = 服务<大世界探索服务>();
        if (世 != null && 世.探索中)
        {
            局.大世界标识 = 世.当前世界标识;
            局.大世界种子 = 世.当前种子;
            局.活层.Add(世.取快照(层快照.类大世界));
        }

        var 区 = 服务<区域探索服务>();
        if (区 != null && 区.探索中)
        {
            局.区域标识 = 区.当前区域标识;
            局.区域种子 = 区.当前种子;
            局.活层.Add(区.取快照(层快照.类区域));
        }

        var 房 = 服务<房间探索服务>();
        if (房 != null && 房.探索中)
        {
            var 快 = 房.取快照(层快照.类房间);
            局.活层.Add(快);
            局.单间种子 = 快.种子;
            局.玩家列 = 房.玩家列;
            局.玩家行 = 房.玩家行;
            if (房.当前建筑 != null && 房.当前层 >= 0)
            {
                // 楼里：记"哪栋楼 + 什么种子 + 第几层"，读档时按这条链重建再覆盖快照
                局.层 = 存档战局.层建筑;
                局.建筑标识 = 房.当前建筑.标识;
                局.建筑种子 = 房.当前建筑种子;
                局.建筑层 = 房.当前层;
            }
            else
            {
                局.层 = 存档战局.层单间;
                局.房间模板 = 快.标识;
            }
        }
        else if (区 != null && 区.探索中)
        {
            局.层 = 存档战局.层区域;
            局.玩家列 = 区.玩家列;
            局.玩家行 = 区.玩家行;
        }
        else if (世 != null && 世.探索中)
        {
            局.层 = 存档战局.层大世界;
            局.玩家列 = 世.玩家列;
            局.玩家行 = 世.玩家行;
        }

        // 容器战局：全局一份（`搜索服务` 的键里带种子，不同层不会撞名）
        var 搜 = 服务<搜索服务>();
        if (搜 != null) 局.容器们 = 搜.取战局();

        return 局;
    }

    private static T 服务<T>() where T : class
        => ServiceRegistry.已注册<T>() ? ServiceRegistry.Get<T>() : null;
}

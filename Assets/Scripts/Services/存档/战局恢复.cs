// 战局恢复：**按存档把"你离开时的那个局面"重建出来**（刀65 装回的一半；取的一半在 战局存档.cs）。
//
// 重建分三步，顺序不能换：
//   ① **由外向内把层造出来** —— 只为了拿到"活着的层"这几个对象（结构由种子决定，是确定性的）。
//   ② **每层用快照整体覆盖** —— 位置/已搜/门锁/敌人位置/迷雾 这些重建不出来，只能覆盖。
//   ③ **容器战局** —— 先按静态模板重抄实例副本，再装内容（快照不存副本，躲搜索表被复制进存档）。
// 最后把玩家放到存档那一格。
//
// 返回 false = "这份存档不该走重建"（老档没有战局快照 / 存档时人在安全屋）→ 调用方走 `打开默认世界()`。
public static class 战局恢复
{
    public static bool 装回(存档战局 局)
    {
        if (局 == null || 局.层 == 存档战局.层安全屋) return false;

        var 世 = 服务<大世界探索服务>();
        var 区 = 服务<区域探索服务>();
        var 房 = 服务<房间探索服务>();
        if (世 == null || 区 == null || 房 == null) return false;

        // ① 由外向内重建（`进入大世界/进入区域/进入建筑/进入房间` 各自会发对应的"打开面板"事件）
        if (!世.进入大世界(局.大世界标识, 局.大世界种子)) return false;
        if (局.层 >= 存档战局.层区域 && !区.进入区域(局.区域标识, 局.区域种子)) return false;
        if (局.层 == 存档战局.层建筑 && !房.进入建筑(局.建筑标识, 局.建筑种子)) return false;
        if (局.层 == 存档战局.层单间)
        {
            // 单间的种子**必须**用存档里那个：一次性临时建筑是 `UnityEngine.Random` 播的种，推不出来
            int 种子 = 局.单间种子 > 0 ? 局.单间种子 : 确定性随机.派生(局.大世界种子, 局.房间模板);
            if (!房.进入房间(局.房间模板, 种子)) return false;
        }

        // ② 每层装回快照（整体覆盖重建结果）
        if (局.活层 != null)
            foreach (var 快 in 局.活层)
            {
                if (快 == null) continue;
                var 服 = 按层类(快.层类, 世, 区, 房);
                if (服 != null) 服.装回快照(快);
            }

        // ③ 容器战局：顺序要紧 —— 先登记实例副本（`查找容器` 靠它拿形状），再装内容
        var 搜 = 服务<搜索服务>();
        if (搜 != null)
        {
            房.重新登记实例();
            搜.装回战局(局.容器们);
        }

        // ④ 玩家落到存档那一格。放在最后：② 里的 装回快照 会刷新视野，
        //    那时玩家还在"重建出来的入口格"，得挪到存档格之后再刷一次。
        var 最内 = 最内层(局.层, 世, 区, 房);
        if (最内?.当前世界 != null && 局.玩家列 >= 0 && 局.玩家行 >= 0)
        {
            最内.当前世界.移动玩家(局.玩家列, 局.玩家行);
            最内.刷新视野();
            最内.发布显示();
        }
        return true;
    }

    // 层类（快照自己标的）→ 服务
    private static 格子探索服务 按层类(int 层类, 大世界探索服务 世, 区域探索服务 区, 房间探索服务 房)
    {
        switch (层类)
        {
            case 层快照.类大世界: return 世;
            case 层快照.类区域: return 区;
            case 层快照.类房间: return 房;
            default: return null;
        }
    }

    // 玩家所在那一层的服务（存档战局.层 → 服务）
    private static 格子探索服务 最内层(int 层, 大世界探索服务 世, 区域探索服务 区, 房间探索服务 房)
    {
        switch (层)
        {
            case 存档战局.层建筑:
            case 存档战局.层单间: return 房;
            case 存档战局.层区域: return 区;
            case 存档战局.层大世界: return 世;
            default: return null;
        }
    }

    private static T 服务<T>() where T : class
        => ServiceRegistry.已注册<T>() ? ServiceRegistry.Get<T>() : null;
}

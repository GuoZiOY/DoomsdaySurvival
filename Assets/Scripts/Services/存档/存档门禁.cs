// 存档门禁：**"什么时候不许存 / 不许读"的唯一真相**。
//
// 为什么要有这个类，而不是各调用点各写一遍 if（v52 刀64 新增）：
//   ① 两条路各有多个入口 —— 存：侧边栏「存档」· 存档面板 · 自动存档器；
//      读：存档面板「读取」。散着写必然漂移，而**事实上原来就漂了**：
//      **存**有守卫（还只在 UI 层），**读**一个都没有。
//   ② 更关键：正确性必须在**代码层**，不能只靠"按钮被隐藏了"。
//      UI 隐藏是体验，代码守卫才是正确性 —— 评估 §二 B4 点过这条（"守卫不够"）。
//      而且"按钮隐藏"挡不住这一条真实路径：**存档面板是运行期全屏叠层，它开着的时候
//      世界时间照走、敌人照走，遭遇会在面板背后打起来** → 玩家能在一个已经进入战斗的局面里点「读取」。
//   ③ 用户口径（2026-09-13）：**「战斗时不需要存档读档」**。理由也都成立：
//      · 档案里不含战斗状态（双方血量/读条/冷却/行动条全在 BattleService 里）；
//      · 战斗期 `BattleService.推进战斗` 已经把 `游戏分钟数` 推过一段（`BattleService.推进.cs:35`）；
//      · 于是"战斗存档 → 读档"= **必败战免费逃跑**，而且读回来的时间与状态对不上。
//      推论：战斗态**不进存档** —— 与此配套，**刀65 的战局快照也不需要处理战斗**
//      （它只要覆盖"探索中"的层，战斗永远发生在"存不了档"的窗口里）。
//
// 与 `Tools/存档接线核对.ps1` 段[9] 配套：那条门禁断言"存与读都走这里 + 读档不再有'失败就开新游戏'的兜底"。
public static class 存档门禁
{
    // 保存前检查。返回 "" = 允许；否则是**给玩家看的原因**（调用方直接播报/显示，不必自己拼文案）。
    public static string 存前检查()
    {
        string 基础 = 已开局检查();
        if (基础 != "") return 基础;
        return 战斗中检查();
    }

    // 读取前检查。★ 与 存前检查 **故意不同**：读档**允许在未开局时进行** ——
    //   主菜单「继续」正是在"还没开局"的状态下读档的（启动时装配出来的那份档案是空的、`当前节点` 为空）。
    //   所以读这条路只拦"战斗中"，不拦"未开局"。
    public static string 读前检查() => 战斗中检查();

    public static bool 可存 => 存前检查() == "";
    public static bool 可读 => 读前检查() == "";

    // 战斗中：既不存也不读 —— 同一个原因，所以只有一份文案（两个入口说法一致，玩家不会以为规则不同）
    public static string 战斗中检查()
        => 正在战斗
            ? "战斗中不能存档或读档：档案里不含战斗状态，战斗期间时间也已经被推进过，存下去或读回来都会得到一个时间与状态对不上的局面。"
            : "";

    // 战斗中？（`BattleService` 可能因数据校验失败而没被装配 → 先问 已注册，别让 Get 抛）
    public static bool 正在战斗
        => ServiceRegistry.已注册<BattleService>() && ServiceRegistry.Get<BattleService>()?.战斗中 == true;

    private static string 已开局检查()
    {
        // ★ 步2：改读**会话阶段**（"游戏有没有在跑"的唯一答案）。
        //   原来读 `档案.当前节点` 是不是空 —— 那是"这段进度值不值得存"的判据，被借来当"开局没有"用。
        //   两者今天结论一致，但语义不同：`当前节点` 是剧情进度，会话阶段才是"现在在哪一屏"。
        if (游戏会话.是未开局) return "尚未开始冒险，无可保存的进度。";
        var 玩家 = 档案();
        if (玩家 == null) return "还没开始冒险，无可保存的进度。";
        return "";
    }

    private static 玩家档案 档案()
        => ServiceRegistry.已注册<PlayerService>() ? ServiceRegistry.Get<PlayerService>()?.档案 : null;
}

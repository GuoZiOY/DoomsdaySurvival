using System.Collections.Generic;
using UnityEngine;

// 合成服务：消耗多件同标识装备，概率提升品质 + 获得/提升词缀，失败返还基础件。
// 成功率 = 40% + (材料数-1)×10%，上限 80%；最少 2 件，最多 5 件。
// 成功 → 品质+1 档（传奇封顶）+ 词缀追加/升级；失败 → 燃料损毁，基础件原样退回。
public sealed class 合成服务
{
    private readonly DataService 数据;
    private readonly PlayerService 玩家服务;
    private readonly EventBus 事件;
    private readonly 词缀服务 词缀;

    public const int 最少材料 = 2;
    public const int 最多材料 = 5;

    public 合成服务(DataService 数据, PlayerService 玩家服务, EventBus 事件, 词缀服务 词缀)
    {
        this.数据 = 数据;
        this.玩家服务 = 玩家服务;
        this.事件 = 事件;
        this.词缀 = 词缀;
    }

    // 成功率：40% + 每多1件 +10%，上限 80%
    public float 成功率(int 材料数) => Mathf.Min(0.8f, 0.4f + (材料数 - 1) * 0.1f);

    // 尝试合成：消耗 材料数 件同标识装备，概率提升品质+词缀
    public bool 尝试合成(string 装备标识, int 材料数)
    {
        var 玩家 = 玩家服务.档案;

        // —— 验证 ——
        if (材料数 < 最少材料 || 材料数 > 最多材料)
        {
            事件.发布(new 日志事件(日志类型.反馈坏, $"合成需投入 {最少材料}～{最多材料} 件同种装备。"));
            return false;
        }
        if (!数据.物品.TryGetValue(装备标识, out var 模板))
        {
            事件.发布(new 日志事件(日志类型.反馈坏, "未找到该装备。"));
            return false;
        }
        bool 装备 = 模板.类型 == "武器" || 模板.类型 == "防具" || 模板.类型 == "饰品";
        if (!装备)
        {
            事件.发布(new 日志事件(日志类型.反馈坏, "唯有武器、防具、饰品方可入炉合成。"));
            return false;
        }

        // 统计总数 + 选最佳基础（词缀最多者优先，同为无词缀取先出现的）
        int 总数 = 0;
        物品堆叠 基础 = null;
        int 最佳词缀数 = -1;
        foreach (var 堆叠 in 玩家.背包)
        {
            if (堆叠.标识 != 装备标识 || 堆叠.数量 <= 0) continue;
            总数 += 堆叠.数量;
            int 词缀数 = 堆叠.词缀 != null ? 堆叠.词缀.Count : 0;
            if (词缀数 > 最佳词缀数) { 最佳词缀数 = 词缀数; 基础 = 堆叠; }
        }
        if (总数 < 材料数)
        {
            事件.发布(new 日志事件(日志类型.反馈坏,
                $"材料不足：合成 {模板.名称} 需 {材料数} 件，当前仅有 {总数} 件。"));
            return false;
        }

        // 备份基础词缀与品质（成功时继承到新产物）
        var 继承词缀 = new List<词缀条>();
        if (基础.词缀 != null) foreach (var a in 基础.词缀) 继承词缀.Add(new 词缀条(a.标识, a.数值));
        品质 基础品质 = 有效品质(基础, 模板);

        // —— 消耗燃料（材料数-1 件）：先扣非基础堆叠，不够再从基础扣到剩 1 ——
        int 待扣 = 材料数 - 1;
        for (int i = 玩家.背包.Count - 1; i >= 0 && 待扣 > 0; i--)
        {
            var 堆叠 = 玩家.背包[i];
            if (堆叠.标识 != 装备标识 || 堆叠 == 基础) continue;
            int 扣 = Mathf.Min(堆叠.数量, 待扣);
            堆叠.数量 -= 扣;
            待扣 -= 扣;
            if (堆叠.数量 <= 0) 玩家.背包.RemoveAt(i);
        }
        if (待扣 > 0)
        {
            int 可扣 = Mathf.Max(0, 基础.数量 - 1);
            int 扣 = Mathf.Min(可扣, 待扣);
            基础.数量 -= 扣;
            待扣 -= 扣;
        }

        // —— 掷骰 ——
        bool 成功 = Random.value < 成功率(材料数);

        if (!成功)
        {
            // 失败：燃料已毁，基础件原样退回背包（品质/词缀不变）
            事件.发布(new 背包变化事件(装备标识, 1 - 材料数, 变化原因.消耗));
            事件.发布(new 日志事件(日志类型.反馈坏,
                $"炉火骤灭，铁液四溅。投入的 {材料数 - 1} 件 {模板.名称} 化为飞灰，" +
                "唯余一柄残品跌落砧台，灵纹尽散，黯然归入背包。"));
            return false;
        }

        // —— 成功：升级品质 + 改善词缀 ——
        bool 品质跃升 = 基础品质 < 品质.传奇;
        品质 新品质 = 品质跃升 ? (品质)((int)基础品质 + 1) : 基础品质;
        string 品质覆盖 = 新品质 != 模板.品质档 ? 品质工具.品质名(新品质) : null;

        // 词缀改善：未满则追加，已满则随机升级一条
        int 最大 = 词缀服务.最大条数(新品质);
        if (继承词缀.Count < 最大)
        {
            var 新条 = 词缀.追加一条(模板, 新品质, 继承词缀);
            if (新条 != null) 继承词缀.Add(新条);
        }
        else if (继承词缀.Count > 0)
        {
            int 序 = Random.Range(0, 继承词缀.Count);
            var 升级 = 词缀.升级一条(模板, 继承词缀[序], 新品质);
            if (升级 != null) 继承词缀[序] = 升级;
        }

        // 从基础堆叠取 1 件作为合成基体（数量>1 则扣 1，=1 则移除），添加合成产物
        基础.数量 -= 1;
        if (基础.数量 <= 0) 玩家.背包.Remove(基础);
        var 产物 = new 物品堆叠(装备标识, 1)
        {
            词缀 = 继承词缀.Count > 0 ? 继承词缀 : null,
            品质 = 品质覆盖,
            当前耐久 = 玩家.有效最大耐久(装备标识)
        };
        玩家.放入网格堆叠(产物);

        // 事件 + 日志
        事件.发布(new 背包变化事件(装备标识, 1 - 材料数, 变化原因.消耗));
        string 品质文 = 品质跃升
            ? $"品质跃升至【{品质工具.品质名(新品质)}】，"
            : "品质已达传奇之巅，";
        事件.发布(new 日志事件(日志类型.反馈,
            $"炉火轰鸣，{材料数} 件 {模板.名称} 在烈焰中融为一体。" +
            $"{品质文}新生之物表面泛起" + 色名(新品质) + "微光，灵纹流转，隐现异力。"));

        return true;
    }

    // 获取堆叠有效品质（覆盖优先，否则取模板品质）
    private static 品质 有效品质(物品堆叠 堆叠, 物品数据 模板)
        => string.IsNullOrEmpty(堆叠.品质) ? 模板.品质档 : 数据解析.枚举<品质>(堆叠.品质);

    // 品质 → 颜色描述（日志文采用）
    private static string 色名(品质 档)
    {
        switch (档)
        {
            case 品质.普通: return "灰白";
            case 品质.优秀: return "翠绿";
            case 品质.稀有: return "湛蓝";
            case 品质.史诗: return "深紫";
            case 品质.英雄: return "赤金";
            case 品质.传奇: return "血红";
            default: return "微弱";
        }
    }
}

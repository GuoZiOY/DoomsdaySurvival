using System.Collections.Generic;
using UnityEngine;

// BattleService · 回派 分部 —— 战斗结束与回派（结束战斗/自动回派/失败惩罚/回写/返回/分派结果节点）
// （v51 刀25 纯组织性拆分：**零逻辑改动**，只是把一个 1486 行的文件按原有分节切开。
//    「哪些该真的拆成类」的判据见 docs/优化实施进度.md §一之十一：先拆文件，再沉纯逻辑。）
public sealed partial class BattleService
{
    // ===== 战斗结束 + 离场回写 =====
    private void 结束战斗(bool 胜利, string 文本, string 进入节点, bool 惩罚 = true)
    {
        战斗中 = false;
        结果节点 = 进入节点;
        // ★ v51 刀17：格子层战斗（结果节点 = `__` 前缀）**不需要玩家点 [继续]**，登记"自动回派"，
        //   由驱动方下一帧落地（见本函数末尾）。这里就定下来，是为了让下面的 `战斗结束事件`
        //   订阅者（战斗面板.显示结算）能在同一帧就读到"这一场会自动回去"。
        自动回派待办 = !string.IsNullOrEmpty(结果节点) && 结果节点.StartsWith("__");
        if (胜利) { }
        else if (惩罚 && 结果节点 == 返回节点) 结算失败惩罚();
        结算回写();
        // ★ v51 刀15：**显式清战斗临时状态**。
        //   原来这里什么都没清，而"战斗单位每场重建"（`开始战斗` 里 `战斗单位.从玩家投影`）恰好让
        //   Buff/冷却/眩晕/无敌 都不会跨场残留 —— 也就是说**正确性是侥幸来的，没有一行代码表达这个意图**。
        //   将来一旦有人改成"复用战斗单位"（性能优化时很可能这么干），这里就会静默漏清。
        //   写成承诺（代价 4 行），并注掉上面那条依赖：
        玩家?.Buffs.Clear();
        玩家?.技能冷却.Clear();
        if (玩家 != null) { 玩家.眩晕剩余秒 = 0f; 玩家.无敌回合 = 0; 玩家.防御姿态 = false; }
        // 胜利 战利品 → 尸体 搜索 容器（世界 沙盒 前：战后 自动 进入 搜索；之后 由 世界 在 原地 生成 尸体）
        string 尸体容器 = "";
        if (胜利 && 尸体战利品.Count > 0)
        {
            尸体容器 = ServiceRegistry.Get<搜索服务>()?.注册尸体容器("敌人的尸体", 8, 5, 尸体战利品) ?? "";
            尸体战利品.Clear();
        }
        事件.发布(new 战斗结束事件(胜利, 文本, 尸体容器));
        // 战斗结果摘要沉淀入日志（非过程消息；战斗过程逐条已标记 过程=true 不入历史）
        if (!string.IsNullOrEmpty(文本))
            事件.发布(new 日志事件(日志类型.战斗, 文本));
        // ★ v51 刀17：**结算与回派拆开**（原来这里直接内联 `返回()`）。
        //   原来一个函数压着两个事务边界：① `返回()` 会一路调进 `格子探索服务.战斗胜利()` ——
        //   改网格实体、登记尸体容器、`面板管理器.显示` 切面板；它一旦抛异常，异常会**穿过结束战斗
        //   回到 `推进战斗`**，推进战斗 后面的行就在"层已切一半"的状态下继续跑；
        //   ② `战斗结束事件` 的订阅者（战斗面板/侧边栏/HUD/格子探索服务）刷新发生在**层已切换之后**，
        //   顺序由订阅顺序决定，不可控。
        //   现在这里只登记待办（上面已设 `自动回派待办`），回派由 驱动 在下一帧调用 `处理自动回派()`。
        //   剧情战斗（结果节点 = 剧情节点）不走这条：那边要把控制权交给对话流程，仍由面板 [继续] 触发。
    }

    // 驱动方（世界时间管理器.驱动）在**战斗已结束**后每帧调用：把上一帧登记的自动回派落地。
    // 为什么"下一帧"而不是 结束战斗 里直接切层：本帧所有 战斗结束事件 订阅者要先把结算表现跑完。
    public void 处理自动回派()
    {
        if (!自动回派待办) return;
        自动回派待办 = false;   // **只自动试一次**：失败就交给面板 [继续] 手动重试，避免每帧刷错误日志
        if (string.IsNullOrEmpty(结果节点)) return;
        回派(结果节点);
    }

    // 失败惩罚：末日版——掉 10% 价值物资 + 回营地半状态（不再满血复活）
    private void 结算失败惩罚()
    {
        // 以物易物经济：损失 10% 持有物资（穿戴容器 + 仓库 + 嵌套容器，按价值最贵的优先——统一持有入口）
        var 持有 = 档案.所有持有物品();
        int 损失件数 = 持有.Count > 0 ? Mathf.Max(1, 持有.Count / 10) : 0;
        for (int i = 0; i < 损失件数 && 持有.Count > 0; i++)
        {
            var 堆叠 = 持有[持有.Count - 1];
            if (档案.移除物品(堆叠.标识, 1))
                事件.发布(new 背包变化事件(堆叠.标识, -1, 变化原因.失去));
        }
        档案.生命 = Mathf.Max(1, 档案.最大生命 / 2);
        档案.行动点 = Mathf.Max(1, 档案.最大行动点 / 2);
        // ★ v51 刀17：**半状态必须同时写进战斗单位**。
        //   离场回写（结算回写）是 `档案.生命 = 玩家.生命` —— 只改档案的话，紧接着那一行
        //   就会用"倒下时的 0 血"把这份恢复覆盖成 0：玩家顶着 0 血回到探索层，
        //   这条"回营地半状态"的失败惩罚等于形同虚设（而且日志照样说"挣扎着逃回安全处"）。
        if (玩家 != null)
        {
            玩家.生命 = Mathf.Min(玩家.最大生命, 档案.生命);
            玩家.精力 = Mathf.Min(玩家.最大精力, 档案.行动点);
        }
        事件.发布(new 生命变化事件(档案.生命, 档案.最大生命, 档案.生命));
        事件.发布(new 精力变化事件(档案.行动点, 档案.最大行动点, 档案.行动点));
        发消息($"你被击倒了，丢了随身的一些东西，挣扎着逃回安全处。");
    }

    // 离场回写：生命/行动点 + 道具消耗统一扣；Buff/临时状态丢弃（战斗外无临时buff）
    // ⚠ v51 刀17：这里的口径是"**生命/行动点以战斗单位为准**"。所以任何**在战斗中直接改 档案.生命/行动点**
    //    的地方，都必须把同一份恢复同步进战斗单位（升级半状态、失败惩罚半状态都已照做），
    //    否则会被这两行反向覆盖 —— 静默、无报错、日志照旧。这条不变量写在这里，改战斗流程前先读它。
    // 注：v51 刀15 删掉了 `消耗道具` 死字段（声明 + 这里的两行）—— 全仓库没有任何一行往它里面加东西
    //     （真正的消耗走 `扣战斗容器` 直接改容器），留着会让读者以为"战斗消耗品有统一登记口"，
    //     若有人照着旧写法去"登记消耗"还会造成双重扣减。
    private void 结算回写()
    {
        档案.生命 = 玩家.生命;
        档案.行动点 = 玩家.精力;   // 战斗消耗的行动点（战斗单位精力=行动点）随战斗保留
    }

    // 战斗结束后面板 [继续]：进入结果节点
    // 房间/区域/大世界 的战斗现在**由驱动方自动回派**（不用点继续，见 处理自动回派）；剧情战斗仍由 [继续] 按钮触发。
    // 幂等：靠 `回派中` 重入锁 + "分派成功才清结果节点"（见 回派），不再是"先把节点清掉"。
    public void 返回()
    {
        if (string.IsNullOrEmpty(结果节点)) return;
        回派(结果节点);
    }

    // 回派：把结果节点交给对应探索层 / 剧情。
    // ★ v51 刀17 两处修正（原实现：第一件事就是 `结果节点 = ""`，然后才 if/else 分派）：
    //   ① **幂等锁挪到分派之后**。分派目标有 early return（`格子探索服务.战斗胜利/战斗逃跑` 在
    //      `当前世界 == null` 时直接走人；`DialogueService.进入节点` 在节点不存在时 LogError + return），
    //      原写法下节点已经丢了 → 战斗面板留在最上层、[继续] 点了没反应（1293 判空 return），
    //      玩家只能靠取消/回主菜单脱身，且这一场的尸体永不落地。
    //      现在：节点**分派成功才清**（失败保留 → [继续] 可重试 → 日志里明确报为什么没落地）。
    //   ② 分派包 try/catch：目标层抛异常时拦在这里（大声报 + 保留节点），不再穿回 推进战斗 的中途。
    //   重入锁（回派中）代替"先清"来防重复：自动回派与 [继续] 按钮可能同帧都触发。
    private void 回派(string 节点)
    {
        if (回派中) return;
        回派中 = true;
        bool 已落地 = false;
        try { 已落地 = 分派结果节点(节点); }
        catch (System.Exception 异常)
        {
            Debug.LogError($"[战斗] 回派 {节点} 抛异常（已拦下，未继续传播；[继续] 可重试）：{异常}");
        }
        finally
        {
            回派中 = false;
            if (已落地) 结果节点 = "";
            else Debug.LogError($"[战斗] 结果节点 {节点} 没有落地（层未切回）：战斗面板会留在原地，[继续] 可重试。");
        }
    }

    // 结果节点 → 归属层 / 剧情；返回"是否真的处理了"（false = 没落地，调用方必须保留节点）
    private bool 分派结果节点(string 节点)
    {
        switch (节点)
        {
            case "__房间胜利": return 回格子层(ServiceRegistry.Get<房间探索服务>(), true, 节点);
            case "__房间返回": return 回格子层(ServiceRegistry.Get<房间探索服务>(), false, 节点);
            case "__大世界胜利": return 回格子层(ServiceRegistry.Get<大世界探索服务>(), true, 节点);
            case "__大世界返回": return 回格子层(ServiceRegistry.Get<大世界探索服务>(), false, 节点);
            case "__区域胜利": return 回格子层(ServiceRegistry.Get<区域探索服务>(), true, 节点);
            case "__区域返回": return 回格子层(ServiceRegistry.Get<区域探索服务>(), false, 节点);
        }
        var 对话 = ServiceRegistry.Get<DialogueService>();
        if (对话 == null)
        {
            Debug.LogError($"[战斗] 结果节点 {节点} 需要 DialogueService，但它未装配");
            return false;
        }
        return 对话.进入节点(节点);
    }

    private static bool 回格子层(格子探索服务 层, bool 胜利, string 节点)
    {
        if (层 == null)
        {
            Debug.LogError($"[战斗] 结果节点 {节点} 对应的探索服务未装配（层无法恢复）");
            return false;
        }
        return 胜利 ? 层.战斗胜利() : 层.战斗逃跑();
    }

    public List<战斗单位> 全部单位()
    {
        var 列表 = new List<战斗单位>();
        列表.AddRange(我方); 列表.AddRange(敌方);
        return 列表;
    }

    private void 发消息(string 文本)
    {
        当前消息 = 文本;
        事件.发布(new 日志事件(日志类型.战斗, 文本, true));   // 战斗过程 = 过程消息（短暂展示，不沉淀历史）
    }

    // 单位名预处理：我方=正常色、敌方=血红；名称左右各留一个空格分隔
    private static string 名(战斗单位 单位)
    {
        if (单位 == null) return " ？？？ ";
        if (单位.是否我方) return $" {单位.名称} ";
        return $" <color={游戏主题.危险色值}>{单位.名称}</color> ";
    }
}

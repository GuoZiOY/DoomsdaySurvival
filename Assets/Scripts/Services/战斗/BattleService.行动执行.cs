using System.Collections.Generic;
using UnityEngine;

// BattleService · 行动执行 分部 —— 统一行动执行（弹药与消耗物/攻击/技能/位移/推挤/中断读条/眩晕/Buff）
// （v51 刀25 纯组织性拆分：**零逻辑改动**，只是把一个 1486 行的文件按原有分节切开。
//    「哪些该真的拆成类」的判据见 docs/优化实施进度.md §一之十一：先拆文件，再沉纯逻辑。）
public sealed partial class BattleService
{
    // ===== 统一行动执行 =====

    // 自动普攻：近战（攻击距离 1）→ 物理伤害；远程（攻击距离 >1）→ 远程伤害
    // ===== 弹药 / 技能 消耗物（玩家：弹挂/腰封 供；敌人 天然 无限，不 参与） =====

    private string 武器弹药标识(武器种类 种类) => 种类 switch
    {
        武器种类.手枪 => "手枪弹",
        武器种类.步枪 => "步枪弹",
        武器种类.霰弹枪 => "霰弹",
        武器种类.弩 => "弩箭",
        武器种类.弓 => "箭矢",
        _ => "",
    };

    private bool 是弹药类(string 标识) => !string.IsNullOrEmpty(标识) && 数据.物品.TryGetValue(标识, out var 模板) && 模板.类型 == "弹药";

    // 弹挂/腰封 中 找 首个 满足 条件 的 堆叠
    private 物品堆叠 找战斗容器堆叠(System.Func<物品堆叠, bool> 匹配)
    {
        if (档案 == null || 匹配 == null) return null;
        foreach (var 槽位 in new[] { "弹挂", "腰封" })
        {
            var 记录 = 档案.装备.Find(e => e.槽位 == 槽位);
            if (记录?.容器物品 == null) continue;
            foreach (var 堆叠 in 记录.容器物品)
                if (堆叠 != null && 堆叠.数量 > 0 && 匹配(堆叠)) return 堆叠;
        }
        return null;
    }

    private void 扣战斗容器(物品堆叠 堆叠, int 数量)
    {
        if (堆叠 == null || 数量 <= 0) return;
        堆叠.数量 -= 数量;
        if (堆叠.数量 <= 0) 移除容器堆叠(堆叠);
        ServiceRegistry.Get<EventBus>()?.发布(new 背包变化事件(堆叠.标识, -数量, 变化原因.消耗));
    }

    // ===== 弹匣 / 换弹（v51 刀46；用户拍板"只自动换弹"）=====
    // 规则（写在明处）：
    //   · 只有**枪械**（手枪/步枪/霰弹枪，数据里配了 弹匣容量）走弹匣；弓弩/近战/没配容量的武器
    //     → 容量 0 → 直接沿用旧行为（每发从 弹挂/腰封 扣），一行老逻辑都不用改
    //   · 出战 / 换武器 → **自动装满**（从 弹挂/腰封 抽；没弹药就空着）
    //   · 射击 → 扣 1 发；**打空立刻自动换弹**（1.5 秒，玩家行动条冻结，眩晕打断）
    //   · 换弹期间再按技能：因为没子弹会再触发"开始换弹"（幂等，不会叠加）
    private 装备记录 当前武器记录()
    {
        if (档案 == null || 玩家 == null) return null;
        return 档案.装备.Find(e => e != null && e.标识 == 玩家.当前武器标识);
    }

    // 有效容量（本体 + 该武器装上的弹匣配件）；0 = 无弹匣概念
    private int 当前弹匣容量() => 档案?.装备管理.有效弹匣容量(当前武器记录()) ?? 0;

    // 从 弹挂/腰封 抽弹药（按武器种类匹配）填进弹匣，直到满或抽不到
    private int 装填满(战斗单位 单位)
    {
        if (单位 != 玩家) return 0;
        var 记录 = 当前武器记录();
        if (记录 == null) return 0;
        int 容量 = 档案.装备管理.有效弹匣容量(记录);
        if (容量 <= 0) return 0;                        // 无弹匣武器：不参与
        int 要装 = 容量 - 记录.已装填;
        if (要装 <= 0) return 0;
        int 装了 = 0;
        while (装了 < 要装)
        {
            var 堆叠 = 找弹药堆叠();
            if (堆叠 == null) break;
            扣战斗容器(堆叠, 1);
            装了++;
        }
        if (装了 > 0) 档案.装备管理.设已装填(记录.槽位, 记录.已装填 + 装了);
        return 装了;
    }

    // 开始换弹（幂等：已经在换就别重开）
    private void 开始换弹(装备记录 记录)
    {
        if (记录 == null || 换弹剩余秒 > 0f) return;
        if (找弹药堆叠() == null) return;               // 没弹药：不空放（由调用方给"没弹药了"提示）
        换弹剩余秒 = 换弹秒;
        换弹槽位 = 记录.槽位;
        发消息($"换弹中…（{换弹秒:0.#} 秒）");
    }

    // 换弹完成：把弹匣补满（能抽多少抽多少）
    private void 完成换弹()
    {
        var 记录 = 档案?.装备.Find(e => e != null && e.槽位 == 换弹槽位);
        换弹剩余秒 = 0f; 换弹槽位 = null;
        if (记录 == null) return;
        int 装了 = 装填满(玩家);
        int 容量 = 档案.装备管理.有效弹匣容量(记录);
        if (装了 > 0) 发消息($"装填完毕 {记录.已装填}/{容量}");
        else 发消息("没有弹药了！往弹挂/腰封里备些弹药吧。");
    }

    // 换弹被打断（眩晕等）：进度清零，**弹匣里已装的子弹保留**（下次换弹接着补）
    private void 打断换弹(战斗单位 单位)
    {
        if (单位 != 玩家 || 换弹剩余秒 <= 0f) return;
        换弹剩余秒 = 0f; 换弹槽位 = null;
        发消息("换弹被打断！");
    }

    // 换弹倒计时（由 推进一步 每步调用）
    private void 推进换弹(float 现实秒)
    {
        if (换弹剩余秒 <= 0f) return;
        if (玩家 == null || !玩家.存活) { 换弹剩余秒 = 0f; 换弹槽位 = null; return; }
        // 眩晕/定身 → 断（重新装）
        if (玩家.无法行动) { 打断换弹(玩家); return; }
        换弹剩余秒 -= 现实秒;
        if (换弹剩余秒 <= 0f) 完成换弹();
    }

    // 调试面板入口（刀46）：装满 / 打空当前武器弹匣（不碰战斗流程，只改弹匣状态）
    public void 调试装满弹匣()
    {
        int 装 = 装填满(玩家);
        发消息($"（调试）装填 {装} 发 —— {弹匣文本()}");
    }

    public void 调试打空弹匣()
    {
        var 记录 = 当前武器记录();
        if (记录 == null || 档案 == null) return;
        档案.装备管理.设已装填(记录.槽位, 0);
        换弹剩余秒 = 0f; 换弹槽位 = null;
        发消息("（调试）弹匣已清空");
    }

    // UI 用：主手弹匣文本（"12/30" / "换弹中…" / "" = 无弹匣）
    public string 弹匣文本()
    {
        var 记录 = 当前武器记录();
        if (记录 == null) return "";
        int 容量 = 档案?.装备管理.有效弹匣容量(记录) ?? 0;
        if (容量 <= 0) return "";
        if (换弹剩余秒 > 0f) return $"换弹中…（{换弹剩余秒:0.#}）";
        return $"{记录.已装填}/{容量}";
    }

    // 有可用弹药吗（弹匣里有 或 弹挂/腰封 里有）：技能可用性判定要用**同一个**口径，
    //   否则会出现"弹匣里明明有子弹，技能却是灰的"（旧判定只看背包）
    private bool 有可用弹药()
    {
        if (当前弹匣容量() > 0 && (当前武器记录()?.已装填 ?? 0) > 0) return true;
        return 找弹药堆叠() != null;
    }
    // 远程 攻击/技能 扣 弹药：**有弹匣的枪械先吃弹匣**（打空→自动换弹），其余沿用旧逻辑
    private bool 尝试扣弹药(战斗单位 单位)
    {
        if (单位 != 玩家) return true;   // 敌人：无需 装填（刀46 也不给敌人做弹匣）
        var 记录 = 当前武器记录();
        int 容量 = 记录 != null ? (档案?.装备管理.有效弹匣容量(记录) ?? 0) : 0;
        if (容量 > 0)
        {
            if (记录.已装填 > 0)
            {
                档案.装备管理.设已装填(记录.槽位, 记录.已装填 - 1);
                if (记录.已装填 <= 0) 开始换弹(记录);   // 打空 → **立刻自动换弹**（用户拍板：只自动换弹）
                return true;
            }
            // 弹匣空：有备弹就先开始换弹（这一击打不出），没备弹就落到下面"没弹药了"
            if (找弹药堆叠() != null) { 开始换弹(记录); 发消息("弹匣空了，正在换弹…"); return false; }
        }
        var 堆叠 = 找弹药堆叠();
        if (堆叠 == null)
        {
            音效管理器.实例?.播放失败();
            发消息("没有弹药了！往弹挂/腰封里备些弹药吧。");
            return false;
        }
        扣战斗容器(堆叠, 1);
        return true;
    }

    // 主弹药 优先，其次 任意 弹药 类 兜底（"有没有弹药"与"扣哪一堆"必须是同一个判据 ——
    // 抽成一个查询，别的判定（如 可释放技能）才能与真的扣减保持一致）
    private 物品堆叠 找弹药堆叠()
    {
        string 主 = 武器弹药标识(玩家.当前武器);
        return 找战斗容器堆叠(s => s.标识 == 主) ?? 找战斗容器堆叠(s => 是弹药类(s.标识));
    }

    // 技能 指定 消耗物品（从 弹挂/腰封 扣 指定 数量）
    private bool 尝试扣消耗物(战斗单位 单位, string 标识, int 数量)
    {
        if (单位 != 玩家) return true;
        var 堆叠 = 找战斗容器堆叠(s => s.标识 == 标识 && s.数量 >= Mathf.Max(1, 数量));
        if (堆叠 == null)
        {
            音效管理器.实例?.播放失败();
            发消息($"需要「{标识}」×{数量}（放 弹挂/腰封 里）。");
            return false;
        }
        扣战斗容器(堆叠, 数量);
        return true;
    }

    // **纯查询**：这个技能"现在按下去能不能放"（给 UI 技能槽说真话用；无任何副作用 ——
    // 不扣精力、不扣弹药、不发消息、不播音效）。原因短文本直接给 UI 显示（如"精力不足"）。
    // ★ v51 刀17（档1 #9）：原来这三类失败（精力/弹药/消耗物/武器不对）**只在按下去那一刻**才判定，
    //   失败的唯一反馈是左下角 6 秒就消失的日志 —— 玩家看到的是"点了没反应"。
    //   判据与 `执行技能` **逐条对齐**（同一份规则只能有一处，否则界面说能按、按下去却失败）。
    public bool 可释放技能(string 技能标识, out string 原因)
    {
        原因 = "";
        var 玩家单位 = 玩家;
        if (玩家单位 == null) { 原因 = "未就绪"; return false; }
        if (string.IsNullOrEmpty(技能标识) || !数据.技能.TryGetValue(技能标识, out var 技能)) { 原因 = "无技能"; return false; }
        if (玩家单位.冷却剩余(技能标识) > 0f) { 原因 = "冷却中"; return false; }
        // 武器规则（与 执行技能 同）：仅物理攻击技能 受 专向 限制
        if (技能.类别枚举 == 技能类别.攻击 && 技能.伤害类型枚举 == 伤害类型.物理
            && 技能.武器规则枚举 == 武器规则.专向
            && (玩家单位.当前武器 == 武器种类.无 || 玩家单位.当前武器 != 技能.武器种类枚举))
        { 原因 = $"需{技能.武器种类}"; return false; }
        if (玩家单位.精力 < 技能.消耗精力) { 原因 = "精力不足"; return false; }
        if (技能.伤害类型枚举 == 伤害类型.远程 && !有可用弹药()) { 原因 = "无弹药"; return false; }
        if (!string.IsNullOrEmpty(技能.消耗物品)
            && 找战斗容器堆叠(s => s.标识 == 技能.消耗物品 && s.数量 >= Mathf.Max(1, 技能.消耗数量)) == null)
        { 原因 = $"缺{技能.消耗物品}"; return false; }
        return true;
    }

    // 执行攻击：自动 普攻（远程 武器 需 弹药，无 弹药 = 空枪 不出 伤）
    //   刀55：物理/远程 **按 `攻击者.近战攻击` 判**（不再看 `攻击距离 > 1`）——
    //   长柄近战射程 2，隔一格打出去仍然是物理伤害、仍然吃力量加成。
    private void 执行攻击(战斗单位 攻击者, 战斗单位 目标)
    {
        if (目标 == null || !目标.存活) return;
        var 类型 = 攻击者.近战攻击 ? 伤害类型.物理 : 伤害类型.远程;
        if (类型 == 伤害类型.远程 && !尝试扣弹药(攻击者)) return;   // 缺 弹药：这一 击 打 不 出（条 已 耗）
        造成伤害(攻击者, 目标, 类型, 100, 0);
    }

    // 执行技能：返回是否成功释放（资源不足/冷却中/专向不匹配 = false，调用方据此决定是否消耗行动）
    private bool 执行技能(战斗单位 施法者, string 技能标识, 战斗单位 目标)
    {
        if (!数据.技能.TryGetValue(技能标识, out var 技能)) return false;
        if (施法者.冷却剩余(技能标识) > 0)
        {
            if (施法者 == 玩家) 发消息($"《{技能.名称}》 还在冷却中！");
            return false;
        }
        // 武器规则（仅物理攻击技能）：专向=仅指定武器可用（不匹配则不消耗行动）；弱向=指定武器伤害↑、其余↓
        float 技能武器修正 = 1f;
        if (技能.类别枚举 == 技能类别.攻击 && 技能.伤害类型枚举 == 伤害类型.物理)
        {
            bool 匹配 = 施法者.当前武器 != 武器种类.无 && 施法者.当前武器 == 技能.武器种类枚举;
            if (技能.武器规则枚举 == 武器规则.专向 && !匹配)
            {
                if (施法者 == 玩家) 发消息($"《{技能.名称}》需要装备「{技能.武器种类}」才能使用！");
                return false;
            }
            if (技能.武器规则枚举 == 武器规则.弱向) 技能武器修正 = 匹配 ? 1.25f : 0.75f;
        }
        // 资源规则：技能统一消耗精力（行动点）
        if (!施法者.消耗精力(技能.消耗精力))
        {
            if (施法者.是否我方) { 音效管理器.实例?.播放失败(); 发消息("精力不足！"); }
            return false;
        }
        // 消耗 型（玩家）：远程 伤害 技能 → 弹药；技能 指定 消耗物品 → 弹挂/腰封 扣（缺 → 释放 失败）
        if (施法者 == 玩家)
        {
            if (技能.伤害类型枚举 == 伤害类型.远程 && !尝试扣弹药(施法者)) return false;
            if (!string.IsNullOrEmpty(技能.消耗物品) && !尝试扣消耗物(施法者, 技能.消耗物品, Mathf.Max(1, 技能.消耗数量))) return false;
        }
        // 位移技（推进/后撤/冲撞）：瞬发 改变 站位——无 目标/伤害/熟练；消耗精力后 结算 并 进入冷却
        if (!string.IsNullOrEmpty(技能.位移))
        {
            执行位移(施法者, 技能);
            施法者.开始冷却(技能标识, 技能.冷却);
            return true;
        }
        int 熟练 = 施法者.熟练等级(技能标识);
        float 品质倍 = 品质工具.倍率(技能.品质档);
        switch (技能.类别枚举)
        {
            case 技能类别.攻击:
                {
                    var 目标列表 = 技能目标列表(技能, 目标);   // 单体=1 / 敌方两名=2 / 全体=全部存活
                    switch (技能.伤害方式枚举)
                    {
                        case 技能伤害方式.固定:
                            // 固定伤害：无视角色的属性与装备，只打技能的固定数值
                            {
                                int 固定值 = Mathf.Max(1, Mathf.RoundToInt(技能.数值));
                                foreach (var 敌 in 目标列表) 造成固定伤害(施法者, 敌, 固定值);
                                break;
                            }
                        case 技能伤害方式.附加:
                            // 附加伤害：在角色的伤害值上 + 数值
                            {
                                int 附加 = Mathf.Max(1, Mathf.RoundToInt(技能.数值 * 技能武器修正));
                                foreach (var 敌 in 目标列表) 造成伤害(施法者, 敌, 技能.伤害类型枚举, 100, 附加);
                                break;
                            }
                        default:
                            // 倍率伤害：角色伤害值 × 数值（受品质/熟练/防御/暴击/抗性影响）
                            {
                                int 倍率 = Mathf.RoundToInt(技能.数值 * 品质倍 * (1f + 熟练 * 技能.熟练伤害加成 / 100f) * 技能武器修正 * 100f);
                                foreach (var 敌 in 目标列表) 造成伤害(施法者, 敌, 技能.伤害类型枚举, 倍率, 0);
                                break;
                            }
                    }
                    附加Buff(施法者, 目标, 技能);   // 攻击技能可同时挂载减益（如 撕咬→中毒）
                    break;
                }
            case 技能类别.净化:
                // 净化：取消目标（友方）的随机一个减益
                // 掷点由**服务层**掷（域层不掷随机，刀33）；只有真有减益时才掷 —— 保持"掷点次数"与原来一致
                {
                    var 净化目标 = 目标;
                    int 减益数 = 净化目标 != null ? 净化目标.减益数量() : 0;
                    if (净化目标 != null && 减益数 > 0 && 净化目标.移除随机减益(随机.范围(0, 减益数)))
                    {
                        事件.发布(new 状态变化事件(净化目标, "", 0, 0, true));
                        发消息($"{名(施法者)} 施展《{技能.名称}》，清除了{名(净化目标)}身上的一个减益！");
                    }
                    else 发消息($"{名(施法者)} 施展《{技能.名称}》，{名(净化目标)}身上没有可清除的减益。");
                    break;
                }
            case 技能类别.治疗:
                {
                    int 恢复 = Mathf.Max(1, Mathf.RoundToInt(技能.数值 * 品质倍 * (1f + 熟练 * 技能.熟练伤害加成 / 100f)));
                    var 治疗目标 = 技能.目标枚举 == 目标类型.自己 ? 施法者 : 目标;
                    治疗目标.恢复生命(恢复);
                    事件.发布(new 治疗事件(治疗目标, 恢复));
                    发消息($"{名(施法者)} 施展《{技能.名称}》，{名(治疗目标)}恢复 {恢复} 点生命。");
                    break;
                }
            default:   // 增益 / 减益 / 控制：挂载 buff（目标=自己 时作用于施法者）
                附加Buff(施法者, 技能.目标枚举 == 目标类型.自己 ? 施法者 : 目标, 技能);
                break;
        }
        // 眩晕 效果（秒制；攻击 类 = 打到的 每个 目标；其余 = 命中 目标/自己）
        if (技能.眩晕秒 > 0f)
        {
            var 眩晕目标 = 技能.类别枚举 == 技能类别.攻击
                ? 技能目标列表(技能, 目标)
                : new List<战斗单位> { 技能.目标枚举 == 目标类型.自己 ? 施法者 : 目标 };
            foreach (var 眩晕者 in 眩晕目标)
                if (眩晕者 != null && 眩晕者.存活) 施加眩晕(眩晕者, 技能.眩晕秒, $"《{技能.名称}》");
        }
        施法者.开始冷却(技能标识, 技能.冷却);
        // 仅玩家本人使用技能累积熟练度（助战单位不记）
        if (施法者 == 玩家 && 熟练 < 玩家档案.熟练等级上限)
            ServiceRegistry.Get<技能服务>().记录熟练度(技能标识, 1);
        return true;
    }

    // 位移技 结算（推进/后撤/冲撞）：逐格 冲刺；敌方 挡路 → 贴脸 停；冲撞 = 把 挡路 敌人 顶退
    private void 执行位移(战斗单位 施法者, 技能数据 技能)
    {
        int 前进 = 施法者.是否我方 ? 1 : -1;       // 朝 敌方 一侧 为 前进
        string 类型 = 技能.位移;
        int 方向 = 类型 == "后撤" ? -前进 : 前进;   // 推进/冲撞 = 前进；后撤 = 反向
        int 距离 = Mathf.Max(1, 技能.位移距离);
        bool 推撞 = 类型 == "冲撞";
        for (int 步 = 0; 步 < 距离; 步++)
        {
            int 下一列 = 施法者.列 + 方向;
            if (下一列 < 0 || 下一列 >= 棋盘宽) break;   // 出界 → 停
            if (对方占用(施法者, 下一列))
            {
                if (!推撞) break;                        // 普通冲刺：被 敌 挡 → 贴脸 停
                if (!推挤级联(施法者, 下一列, 方向)) break;   // 冲撞：顶退 挡路 敌；顶 不动 → 停
            }
            施法者.列 = 下一列;
        }
        发消息($"{名(施法者)} {位移动作名(类型)}！(节点 {施法者.列})");
    }

    // 指定 列 是否有 存活 敌方 单位
    private bool 对方占用(战斗单位 施法者, int 列)
    {
        foreach (var 敌 in 施法者.是否我方 ? 敌方 : 我方)
            if (敌.存活 && 敌.列 == 列) return true;
        return false;
    }

    // 冲撞 顶退：把 起点 起 沿 方向 的 敌方 链 各 顶退 1 格（同节点 多个 一起 顶）；链尾 是 边界/无空位 → false
    private bool 推挤级联(战斗单位 施法者, int 起点列, int 方向)
    {
        var 对方 = 施法者.是否我方 ? 敌方 : 我方;
        int 尾 = 起点列;
        while (尾 + 方向 >= 0 && 尾 + 方向 < 棋盘宽 && 对方占用(施法者, 尾 + 方向)) 尾 += 方向;
        if (尾 + 方向 < 0 || 尾 + 方向 >= 棋盘宽) return false;   // 顶 到 边界
        for (int c = 尾; ; c -= 方向)
        {
            foreach (var 敌 in 对方)
                if (敌.存活 && 敌.列 == c)
                {
                    敌.列 = c + 方向;
                    // 冲撞 命中：读条 大招（技能 意图）被 撞 断
                    if (敌.意图已选 && 敌.当前意图 == 战斗单位.意图类型.技能 && 敌.行动条 > 0.01f)
                    {
                        string 招名 = string.IsNullOrEmpty(敌.意图技能) ? "读条大招" : 敌.意图技能;
                        中断读条(敌, $"的「{招名}」读条被撞断");
                    }
                }
            if (c == 起点列) break;
        }
        return true;
    }

    // 中断读条（被打断）：行动条清零 + 意图 作废 + 玩家 蓄力 预约 一并 取消（不 扣 物品/资源）
    // 玩家/敌人 双向 通用：受控（无法行动）断 一切 读条；位移/控制 命中 读条 大招 同样 触发
    private void 中断读条(战斗单位 单位, string 描述)
    {
        if (单位 == null || !单位.存活) return;
        bool 在读条 = 单位.行动条 > 0.01f || (单位 == 玩家 && 待动类型 != 待动类别.无);
        if (!在读条) return;
        单位.行动条 = 0f;
        单位.意图已选 = false;
        单位.意图技能 = null;
        if (单位 == 玩家 && 待动类型 != 待动类别.无) 取消待行动作();
        if (!string.IsNullOrEmpty(描述)) 发消息($"{名(单位)} {描述}！");
    }

    // 施加 眩晕（秒制）：先 断 其 读条（清零 重来），再 冻结 一段时间（期间 不 推 读条）；到时 自动 恢复 重锁 意图
    public void 施加眩晕(战斗单位 单位, float 秒, string 来源 = null)
    {
        if (单位 == null || !单位.存活 || 秒 <= 0f) return;
        中断读条(单位, null);
        单位.施加眩晕(秒);
        if (!string.IsNullOrEmpty(来源)) 发消息($"{名(单位)} 被{来源}眩晕 {Mathf.CeilToInt(秒)} 秒！");
    }

    private static string 位移动作名(string 类型) => 类型 switch
    {
        "推进" => "向前冲刺",
        "后撤" => "向后退撤",
        _ => "向前冲撞",
    };

    // 技能攻击目标列表：单体=选中；敌方两名=选中 + 另一个存活敌人；全体=全部存活敌人
    private List<战斗单位> 技能目标列表(技能数据 技能, 战斗单位 选中)
    {
        var 列表 = new List<战斗单位>();
        if (选中 != null && 选中.存活) 列表.Add(选中);
        if (技能.目标枚举 == 目标类型.敌方全体)
        {
            foreach (var 敌 in 敌方)
                if (敌.存活 && !列表.Contains(敌)) 列表.Add(敌);
        }
        else if (技能.目标枚举 == 目标类型.敌方两名)
        {
            foreach (var 敌 in 敌方)
                if (敌.存活 && !列表.Contains(敌)) { 列表.Add(敌); break; }   // 补第二个目标
        }
        return 列表;
    }

    // 技能挂载 Buff（攻击技能也可携带减益，如 撕咬→中毒 / 骨刺→防御削弱）
    private void 附加Buff(战斗单位 施法者, 战斗单位 目标, 技能数据 技能)
    {
        if (string.IsNullOrEmpty(技能.挂载Buff) || !数据.Buffs.TryGetValue(技能.挂载Buff, out var buff)) return;
        目标.添加Buff(buff);
        var 实例 = 目标.Buffs.Find(b => b.定义.标识 == buff.标识);
        事件.发布(new 状态变化事件(目标, buff.标识, 实例?.层数 ?? 1, buff.持续回合, false));
        发消息($"{名(目标)} 获得「{buff.名称}」！");
    }


using UnityEngine;

// BattleService · 伤害与结算 分部 —— 伤害管线（**唯一伤害公式权威**，数值已抽到 Domain/战斗/伤害计算.cs）
//   + 单位死亡 / 胜利结算（单个敌人·战利品入尸）/ 检查战斗结束
// （v51 刀25 拆分时这里原是 伤害.cs 与 结算.cs 两个文件；刀27 合并 —— 它们本来就是一件事：
// 「打完一下之后怎么算账」。）
public sealed partial class BattleService
{
    // ===== 统一伤害管线（全项目唯一伤害公式权威 —— **数值部分已抽到 Domain/战斗/伤害计算.cs**） =====
    // 这里只剩"取快照 → 掷点 → 调纯函数 → 应用结果 → 发事件/文案/死亡"。
    // 抽出去的是**公式**（命中/暴击/减伤链/下限），它现在能离线断言（见 Tools/战斗验证）。
    // ⚠ 掷点（Random.value）留在本层，且**每条路径的掷点次数与拆分前逐一致**：
    //   无敌 0 次 / 闪避 1 次 / 真实伤害 1 次 / 普通 2 次 —— 次数一变，全局随机序列就变。
    private void 造成伤害(战斗单位 攻击者, 战斗单位 目标, 伤害类型 类型, int 倍率100, int 附加 = 0)
    {
        if (目标 == null || !目标.存活) return;
        // 无敌判定（天赋触发后：免疫伤害 1 轮）
        if (目标.无敌)
        {
            事件.发布(new 伤害事件(目标, 0, 类型, false, false));
            发消息($"{名(目标)} 处于无敌状态，攻击被弹开！");
            return;
        }
        // 命中判定：基础命中率 vs 目标当前闪避（敏捷 buff 生效）
        if (!伤害计算.是否命中(随机.值(), 攻击者.命中率, 目标.当前闪避率))
        {
            事件.发布(new 伤害事件(目标, 0, 类型, false, true));
            发消息($"{名(目标)} 闪避了{名(攻击者)}的攻击！");
            return;
        }
        // 掷点：**真实伤害不掷暴击点**（原来那条分支在掷点之前就 return 了，这里要一样）
        var 果 = 伤害计算.计算(new 伤害输入
        {
            类型 = 类型,
            攻击者近战 = 攻击者.当前近战,
            攻击者远程 = 攻击者.当前远程,
            倍率100 = 倍率100,
            附加 = 附加,
            攻击者暴击率 = 攻击者.当前暴击率,
            目标防御减伤 = 目标.防御减伤,
            目标抗性百分比 = 目标.抗性百分比,
            目标防御姿态 = 目标.防御姿态,
            掷暴击 = 类型 == 伤害类型.真实 ? 0f : 随机.值(),
        });
        // 耐久消耗：玩家命中 → 主武器武器耐久 -1；玩家被击中 → 胸部防具耐久 -1
        //   （真实伤害/固定伤害不走这条 —— 与拆分前一致：耐久在原实现里位于真伤分支之后）
        if (!果.是真实伤害)
        {
            if (攻击者.是否我方 && !string.IsNullOrEmpty(攻击者.当前武器标识)) 档案.扣装备标识耐久(攻击者.当前武器标识, 1);
            if (目标.是否我方) 档案.扣装备耐久("胸部", 1);
        }
        目标.受到伤害(果.数值);
        事件.发布(new 伤害事件(目标, 果.数值, 类型, 果.暴击, false));
        if (果.是真实伤害)
            发消息($"{名(攻击者)}对{名(目标)}造成 {果.数值} 点伤害。");
        else
            发消息($"{(果.暴击 ? "<color=#e0b84a>暴击！</color>" : "")}{名(攻击者)}对{名(目标)}造成 {果.数值} 点伤害。");
        检查单位死亡(目标);
    }

    // 固定伤害：不受任何因素影响（无视命中/攻防/暴击/抗性），只打出固定数值
    private void 造成固定伤害(战斗单位 攻击者, 战斗单位 目标, int 数值)
    {
        if (目标 == null || !目标.存活) return;
        // 与拆分前的 `Mathf.Max(1, 数值)` 同口径（走纯函数，免得 1 这个下限散在第二处）
        int 伤害 = 伤害计算.计算(new 伤害输入 { 类型 = 伤害类型.真实, 倍率100 = 数值 }).数值;
        目标.受到伤害(伤害);
        事件.发布(new 伤害事件(目标, 伤害, 伤害类型.真实, false, false));
        发消息($"{名(攻击者)}对{名(目标)}造成 {伤害} 点固定伤害。");
        检查单位死亡(目标);
    }

    private void 检查单位死亡(战斗单位 单位)
    {
        if (单位.存活) return;
        // 玩家倒下：先发 致命伤害事件（天赋服务 检查 钢铁意志/医者仁心——免疫则保命继续）
        if (单位 == 玩家 && ServiceRegistry.已注册<天赋服务>())
        {
            ServiceRegistry.Get<天赋服务>().处理致命伤害(new 致命伤害事件(单位));
            if (单位.存活)   // 天赋免疫成功（生命已保底）
            {
                事件.发布(new 目标变化事件(单位));
                事件.发布(new 战斗消息事件("你挺过了致命一击！"));
                return;
            }
        }
        if (单位.是否我方) 我方.Remove(单位);
        else { 敌方.Remove(单位); 结算单个敌人(单位); }
        事件.发布(new 目标变化事件(单位));
        发消息($"{名(单位)} 倒下了！");
    }

    // ===== 胜利结算（每死一个敌人即时结算；末日以物易物：掉落补给而非金币） =====
    private void 结算单个敌人(战斗单位 敌人)
    {
        var 敌 = 敌人.源数据;
        if (敌 == null) return;
        // 战利品（补给 + 掉落）→ 进 尸体：战后 搜刮（不 直接 入包；尸体 由 结束战斗 生成 搜索 容器）
        int 补给值 = Mathf.Max(0, 敌.货币奖励);
        int 面包数 = 补给值 / 4, 水数 = 补给值 / 8;
        if (面包数 > 0) 战利品入尸("面包", 面包数);
        if (水数 > 0) 战利品入尸("水", 水数);
        // ★ v51 刀17：**升级恢复必须同步进战斗单位**。
        //   `档案.获得经验` 升级时会把 档案.生命/行动点 抬到"半状态"（成长管理器.获得经验），
        //   但战斗单位（面板上那条血、面板上那个精力）不会跟着变；而离场时 `结算回写` 是
        //   **拿战斗单位覆盖档案** → 这次恢复会被静默抹掉：玩家看到"升级/+3 属性点"的日志，
        //   血量和行动点却一动不动（无法从日志察觉的结算错）。
        //   做法：记下档案侧被外部改动的**差值**，补到战斗单位上（快照差值法）。
        int 升级前生命 = 档案.生命, 升级前精力 = 档案.行动点;
        bool 升级 = 档案.获得经验(敌.经验奖励); 累计经验 += 敌.经验奖励;
        事件.发布(new 经验变化事件(档案.等级, 档案.经验, 档案.升级所需经验, 升级));
        if (升级)
        {
            if (玩家 != null)
            {
                玩家.生命 = Mathf.Min(玩家.最大生命, 玩家.生命 + Mathf.Max(0, 档案.生命 - 升级前生命));
                玩家.精力 = Mathf.Min(玩家.最大精力, 玩家.精力 + Mathf.Max(0, 档案.行动点 - 升级前精力));
            }
            事件.发布(new 属性变化事件(档案.体质, 档案.力量, 档案.智慧, 档案.敏捷, 档案.意志, 档案.自由属性点));
        }
        if (!string.IsNullOrEmpty(敌.掉落物品) && 随机.值() < 敌.掉落概率)
        {
            // 掉落就是**物品本体**（v51 刀35）：装备不再生成随机词缀/配件 ——
            // 配件是独立物品（占背包、有重量），掉落与拾取都走普通物品那条路。
            // 这里保留"耐久初始化"：装备类掉落物要带一个有效最大耐久，否则捡起来就是坏的。
            if (数据.物品.TryGetValue(敌.掉落物品, out _))
                战利品入尸(new 物品堆叠(敌.掉落物品, 1) { 当前耐久 = 档案.有效最大耐久(敌.掉落物品) });
            else 战利品入尸(敌.掉落物品, 1);
        }
        ServiceRegistry.Get<QuestService>().记录击败(敌.标识);
        string 补给文本 = 面包数 > 0 || 水数 > 0 ? $"、面包×{面包数}、水×{水数}" : "";
        发消息($"击败 <color={游戏主题.危险色值}>{敌.名称}</color> ！获得{补给文本}{敌.经验奖励} 经验。");
    }

    // 战利品 收集：同名（无 配件）合并 数量；配件 实例 独立 一件
    private void 战利品入尸(string 标识, int 数量)
    {
        var 已有 = 尸体战利品.Find(s => s != null && s.标识 == 标识 && s.配件 == null);
        if (已有 != null) { 已有.数量 += 数量; return; }
        尸体战利品.Add(new 物品堆叠(标识, 数量));
    }

    private void 战利品入尸(物品堆叠 堆叠) { if (堆叠 != null) 尸体战利品.Add(堆叠); }

    private bool 检查战斗结束()
    {
        if (!战斗中) return true;
        // ⚠ 顺序要紧（v51 刀15 修正）：**失败判定必须先于胜利判定**。
        //   原来先判"敌方清空"→ 同一次结算里玩家与最后一只敌人同时倒下会判**胜利**，
        //   然后 `结算回写` 把 档案.生命 = 玩家.生命（0）→ 玩家以 **0 血**回到探索层继续走
        //   （生存系统的"倒下"只在整点结算里提示），是明确的边界结算错。
        //   现在玩家倒下优先 = 失败。
        if (玩家 == null || !玩家.存活) { 结束战斗(false, "你被击败了……", 返回节点); return true; }
        if (敌方.Count == 0) { 结束战斗(true, $"战斗胜利！共获得 {累计经验} 经验，搜刮战利品吧。", 胜利节点); return true; }
        return false;
    }

}

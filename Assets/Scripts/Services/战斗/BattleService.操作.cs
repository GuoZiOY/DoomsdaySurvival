{
    // ===== 玩家主动操作（即时制：随时可点，释放即重置行动条） =====

    // 主动技能：瞬发 = 点击 立即 出手（重置行动条）；蓄力（默认）= 预约 下一次 满条 行动位
    public bool 玩家主动技能(string 技能标识, 战斗单位 目标)
    {
        if (!战斗中 || 玩家 == null || !玩家.存活) return false;
        if (!数据.技能.TryGetValue(技能标识, out var 技能)) return false;
        if (玩家.冷却剩余(技能标识) > 0) { 发消息($"《{技能.名称}》 还在冷却中！"); return false; }
        if (目标 == null || !目标.存活) return false;
        if (!技能目标合法(技能, 玩家, 目标)) { 发消息($"《{技能.名称}》的目标不在射程内。"); return false; }
        if (技能.出手时机枚举 == 技能时机.瞬发)   // 瞬发（应急）：立即 出手
        {
            取消待行动作();
            if (!执行技能(玩家, 技能标识, 目标)) return false;   // 资源不足/武器不匹配 = 不消耗
            发消息($"你使用了技能《{技能.名称}》！");
            重置行动条(玩家);
            return true;
        }
        预约待行动作(待动类别.技能, 技能标识, 目标, $"你开始蓄力《{技能.名称}》……蓄力完成后生效。");
        return true;
    }

    // 主动道具（蓄力制）：点击 使用 + 选目标 → 打断 当前 行动 并 重置 行动条；
    // 待 行动条 再次 蓄满（满条 自动 行动）才 真正 从 弹挂/腰封 扣除 并 生效——道具 = 一次 完整 行动
    public bool 玩家主动道具(string 物品标识, 战斗单位 目标)
    {
        if (!战斗中 || 玩家 == null || !玩家.存活) return false;
        if (!数据.物品.TryGetValue(物品标识, out var 物品) || !物品.战斗内使用) return false;
        if (战斗道具堆叠(物品标识) == null) { 发消息("弹挂/腰封里没有这个物品。"); return false; }
        if (目标 == null || !目标.存活) return false;
        if (!道具目标合法(物品, 目标)) { 发消息("这个物品的目标不在射程内。"); return false; }
        预约待行动作(待动类别.道具, 物品标识, 目标, $"你开始使用「{物品.标识}」……蓄力完成后生效。");
        return true;
    }

    // 弹挂/腰封 中查找战斗道具堆叠
    private 物品堆叠 战斗道具堆叠(string 标识)
    {
        foreach (var 槽 in new[] { "弹挂", "腰封" })
        {
            var 记录 = 档案.装备.Find(e => e.槽位 == 槽);
            if (记录?.容器物品 == null) continue;
            var 堆叠 = 记录.容器物品.Find(s => s != null && s.标识 == 标识 && s.数量 > 0);
            if (堆叠 != null) return 堆叠;
        }
        return null;
    }

    private void 移除容器堆叠(物品堆叠 堆叠)
    {
        foreach (var 槽 in new[] { "弹挂", "腰封" })
        {
            var 记录 = 档案.装备.Find(e => e.槽位 == 槽);
            if (记录?.容器物品 == null) continue;
            记录.容器物品.Remove(堆叠);
        }
    }

    // 技能目标合法性：阵营匹配 + 攻击距离（>1 需直线视线；自己/距离0 恒合法）
    private bool 技能目标合法(技能数据 技能, 战斗单位 施法者, 战斗单位 目标)
    {
        var 期望 = 技能.目标枚举;
        if (期望 == 目标类型.自己) return 目标 == 施法者;
        bool 敌方类 = 期望 == 目标类型.敌方单体 || 期望 == 目标类型.敌方全体 || 期望 == 目标类型.敌方两名;
        if (敌方类 && 目标.是否我方) return false;
        if (!敌方类 && !目标.是否我方) return false;
        int 距 = Mathf.Abs(施法者.列 - 目标.列);
        if (距 == 0) return true;   // 自己恒可（治疗自己等）
        int 距离 = 技能.攻击距离 > 0 ? 技能.攻击距离 : 1;
        return 距 <= 距离;   // 轨道：节点差 ≤ 攻击距离 即可（无障碍，无需视线）
    }

    // 道具目标合法性：按 使用效果 判定阵营（恢复/增益 = 我方，缺省=恢复；减益 = 敌方）+ 距离（节点差 ≤ 1 贴脸可用）
    private bool 道具目标合法(物品数据 物品, 战斗单位 目标)
    {
        bool 攻击类 = 物品.使用效果枚举 == 效果类型.减益;
        if (攻击类 && 目标.是否我方) return false;
        if (!攻击类 && !目标.是否我方) return false;
        int 距 = Mathf.Abs(玩家.列 - 目标.列);
        return 距 <= 1;   // 投掷类后续按 攻击距离 扩展
    }

    // 执行道具（即时制：不从战斗单位消耗清单扣——已从弹挂/腰封容器扣）
    private void 执行道具即时(战斗单位 使用者, string 物品标识, 战斗单位 目标)
    {
        if (!数据.物品.TryGetValue(物品标识, out var 物品) || !物品.战斗内使用) return;
        switch (物品.使用效果枚举)
        {
            case 效果类型.恢复:
                {
                    int 恢复 = Mathf.Max(1, Mathf.RoundToInt(物品.恢复量 * 品质工具.倍率(物品.品质档)));
                    目标.恢复生命(恢复);
                    事件.发布(new 治疗事件(目标, 恢复));
                    发消息($"{名(使用者)} 使用{物品.标识}，恢复 {恢复} 点生命。");
                    break;
                }
            default:
                if (!string.IsNullOrEmpty(物品.挂载Buff) && 数据.Buffs.TryGetValue(物品.挂载Buff, out var buff))
                {
                    目标.添加Buff(buff);
                    事件.发布(new 状态变化事件(目标, buff.标识, 1, buff.持续回合, false));
                    发消息($"{名(目标)} 获得「{buff.名称}」！");
                }
                break;
        }
    }

    // 预约 待行动作（技能/道具 统一入口）：覆盖 旧 预约 → 提示 → 重置行动条（打断 当前 蓄力）
    private void 预约待行动作(待动类别 类别, string 标识, 战斗单位 目标, string 提示)
    {
        取消待行动作();
        待动类型 = 类别;
        待动标识 = 标识;
        待动目标 = 目标;
        发消息(提示);
        重置行动条(玩家);
    }

    // 待行动作 完成（满条 自动行动 时）：按 类别 真正 执行；目标/资源 失效 → 取消 并 落回 自动 行动
    private bool 完成待行动作()
    {
        if (待动类型 == 待动类别.道具) return 完成待用道具(待动标识, 待动目标);
        if (待动类型 == 待动类别.技能)
        {
            string 标识 = 待动标识;
            var 目标 = 待动目标;
            if (string.IsNullOrEmpty(标识) || 目标 == null || !目标.存活
                || !数据.技能.TryGetValue(标识, out var 技能) || !技能目标合法(技能, 玩家, 目标)
                || 玩家.冷却剩余(标识) > 0)
            {
                取消待行动作(标识 == null ? null : "蓄力中的技能落空了——目标已不可用。");
                return false;
            }
            取消待行动作();                 // 先 清，防 执行 过程 内 再 触发
            if (!执行技能(玩家, 标识, 目标)) return false;   // 资源不足/武器不匹配 = 不消耗，落回 自动
            发消息($"你使用了技能《{技能.名称}》！");
            return true;
        }
        return false;
    }

    // 待行动作（道具）完成：扣除 容器 物品 → 生效；目标/物品 失效 → 取消 并 落回 自动 行动
    private bool 完成待用道具(string 标识, 战斗单位 目标)
    {
        if (string.IsNullOrEmpty(标识) || 目标 == null || !目标.存活 || !数据.物品.TryGetValue(标识, out var 物品)
            || !道具目标合法(物品, 目标))
        {
            取消待行动作(标识 == null ? null : "蓄力中的道具落空了——目标已不可用。");
            return false;
        }
        var 堆叠 = 战斗道具堆叠(标识);
        if (堆叠 == null) { 取消待行动作("蓄力中的道具不见了——弹挂/腰封里已没有它。"); return false; }
        取消待行动作();                 // 先 清 状态，防 执行 过程 内 再 触发
        堆叠.数量--;
        if (堆叠.数量 <= 0) 移除容器堆叠(堆叠);
        ServiceRegistry.Get<EventBus>()?.发布(new 背包变化事件(标识, -1, 变化原因.消耗));
        执行道具即时(玩家, 标识, 目标);
        return true;
    }

    // 取消 待行动作（覆盖 / 目标失效 / 新 主动操作 / 新 战斗 等）
    private void 取消待行动作(string 提示 = null)
    {
        if (待动类型 == 待动类别.无) return;
        if (!string.IsNullOrEmpty(提示)) 发消息(提示);
        待动类型 = 待动类别.无;
        待动标识 = null;
        待动目标 = null;
    }

    // ===== 模式切换（重置行动条） =====

    // 切换运动模式：0 自动前进 → 1 原地等待 → 2 自动后退 → 0
    public void 切换运动模式()
    {
        if (!战斗中 || 玩家 == null) return;
        玩家.运动模式 = (玩家.运动模式 + 1) % 3;
        重置行动条(玩家);
        发消息(运动模式名(玩家.运动模式));
    }

    // 切换行动模式：0 自动攻击 → 1 自动防御 → 0
    public void 切换行动模式()
    {
        if (!战斗中 || 玩家 == null) return;
        玩家.行动模式 = 玩家.行动模式 == 0 ? 1 : 0;
        重置行动条(玩家);
        发消息(玩家.行动模式 == 0 ? "切回自动攻击。" : "转为自动防御。");
    }

    private static string 运动模式名(int 模式) => 模式 switch
    {
        0 => "自动前进。",
        1 => "原地等待。",
        _ => "自动后退。",
    };

    // 玩家主动技能/道具 的可选目标集合（面板高亮用）
    public List<战斗单位> 技能可选目标(string 技能标识)
    {
        var 列表 = new List<战斗单位>();
        if (!战斗中 || 玩家 == null) return 列表;
        if (!数据.技能.TryGetValue(技能标识, out var 技能)) return 列表;
        foreach (var 单位 in 全部单位())
            if (单位.存活 && 技能目标合法(技能, 玩家, 单位)) 列表.Add(单位);
        return 列表;
    }

    public List<战斗单位> 道具可选目标(string 物品标识)
    {
        var 列表 = new List<战斗单位>();
        if (!战斗中 || 玩家 == null) return 列表;
        if (!数据.物品.TryGetValue(物品标识, out var 物品)) return 列表;
        foreach (var 单位 in 全部单位())
            if (单位.存活 && 道具目标合法(物品, 单位)) 列表.Add(单位);
        return 列表;
    }

    // 弹挂/腰封 内可战斗使用的道具清单（面板渲染用）：返回 (堆叠, 物品数据)
    public List<(物品堆叠 堆叠, 物品数据 物品)> 战斗道具清单()
    {
        var 列表 = new List<(物品堆叠 堆叠, 物品数据 物品)>();
        foreach (var 槽 in new[] { "弹挂", "腰封" })
        {
            var 记录 = 档案.装备.Find(e => e.槽位 == 槽);
            if (记录?.容器物品 == null) continue;
            foreach (var 堆叠 in 记录.容器物品)
            {
                if (堆叠 == null || string.IsNullOrEmpty(堆叠.标识)) continue;
                if (!数据.物品.TryGetValue(堆叠.标识, out var 物品) || !物品.战斗内使用) continue;
                if (!列表.Exists(x => x.堆叠.标识 == 堆叠.标识)) 列表.Add((堆叠, 物品));
            }
        }
        return 列表;
    }

    public void 逃跑()
    {
        if (!战斗中 || 玩家 == null || !玩家.存活) return;
        int 敌速 = 0;
        foreach (var e in 敌方) if (e.存活 && e.基础速度 > 敌速) 敌速 = e.基础速度;
        float 概率 = Mathf.Clamp(0.5f + (玩家.基础速度 - 敌速) * 0.02f, 0.2f, 0.95f);
        if (随机.值() < 概率) { 结束战斗(false, "你成功逃离了战斗。", 返回节点, false); return; }
        音效管理器.实例?.播放失败();
        发消息("逃跑失败！");
        重置行动条(玩家);   // 逃跑 = 主动操作：重置行动条
        // 失败惩罚：所有存活敌人立即行动一次
        foreach (var 敌 in new List<战斗单位>(敌方)) if (敌.存活) 单位自动行动(敌);
    }

    // 切武器（即时制）：主手↔副手 切换当前持用武器，改变 近/远程伤害类型 与 攻击射程；重置行动条
    public void 切换武器()
    {
        if (!战斗中 || 玩家 == null || !玩家.存活) return;
        var 主手种 = 玩家.主手武器 != null ? (档案.武器种类解析?.Invoke(玩家.主手武器) ?? 武器种类.无) : 武器种类.无;
        var 副手种 = 玩家.副手武器 != null ? (档案.武器种类解析?.Invoke(玩家.副手武器) ?? 武器种类.无) : 武器种类.无;
        if (副手种 == 武器种类.无)
        {
            发消息("你没有可切换的第二把武器。");
            return;   // 无第二把武器（副手为盾/空）：不重置行动条
        }
        bool 切到副手 = 玩家.当前武器标识 == 玩家.主手武器;
        玩家.当前武器标识 = 切到副手 ? 玩家.副手武器 : 玩家.主手武器;
        玩家.当前武器 = 切到副手 ? 副手种 : 主手种;
        玩家.攻击距离 = 武器攻击距离(玩家.当前武器标识);   // 射程随武器变化
        刷新玩家速率();   // 攻速倍率 随 当前 武器 变化（切 重武器 → 攻 变 慢）
        string 武器名 = 数据.物品.TryGetValue(玩家.当前武器标识, out var 物品) ? 物品.标识 : 玩家.当前武器标识;
        发消息($"你换持了「{武器名}」。（{玩家.当前武器}）");
        装填满(玩家);   // 刀46：换武器后自动装满新枪的弹匣（老枪的弹匣状态留在它的装备记录上，换回来还在）
        重置行动条(玩家);   // 切换消耗蓄力
    }

}

using System.Collections.Generic;
using UnityEngine;

// BattleService · 推进 分部 —— 时钟与轮次（推进战斗/轮次结算/满条行动/意图间隔/意图选定）
// （v51 刀25 纯组织性拆分：**零逻辑改动**，只是把一个 1486 行的文件按原有分节切开。
//    「哪些该真的拆成类」的判据见 docs/优化实施进度.md §一之十一：先拆文件，再沉纯逻辑。）
public sealed partial class BattleService
{
    // ===== 即时制核心：时间推进 → 行动条 → 轮次结算 → 满条自动行动 =====

    // 战斗推进（**驱动方每帧调用**：世界时间管理器.驱动 —— 不再是战斗面板的 Update）：推进世界时间 + 行动条累积 + 轮次结算 + 满条行动。
    // 战斗中挂机驱动暂停（世界时间管理器.驱动 检查 战斗中），时间只在此推进，避免双时钟。
    // 战斗中不结算生存（饱食/水分/伤病 暂停——战斗冲突中不吃不喝也不扣），仅推进时间并同步整点基准（防挂机恢复时补结算战斗期间）。
    // ★ v51 刀17：驱动从 `战斗沙盒面板.Update` 搬到 `世界时间管理器.驱动.Update`。
    //   面板是 `可切换面板`，隐藏 = SetActive(false) = Update 停 → 战斗里双方读条/冷却/眩晕**全部冻结**
    //   （可无限"看牌"、从容挑道具）。刀15 只是堵住了"战斗中按 F1"这一条路，
    //   而"引擎的正确性挂在 UI 激活态上"这个根还在：将来任何新增的、能在战斗中显示的面板都会再踩一次。
    // ★ v51 刀27：**固定步长**（审计 D8）。原来这里直接吃 `Time.deltaTime`，
    //   而"读条临界点被撞断 / 眩晕到期 / 冷却过零"都精确依赖"这一帧多少秒" →
    //   60fps 与 30fps 打出来结果不同、也无法离线复现。
    //   现在：驱动每帧把现实秒喂进来 → 折成整数个 1/30 秒的逻辑步 → 逐步推进（余量跨帧累积，卡帧有上限保护）。
    //   ⚠ 这是一处**行为改动**（判定粒度从"每帧"变成"1/30 秒"）：战斗结果在数学上更干净了，
    //     但同一场战斗的细节会与旧版不同，需要实机试玩确认手感（见 docs 的 P 清单）。
    public void 推进战斗(float 现实秒)
    {
        if (!战斗中 || 现实秒 <= 0f) return;
        int 步数 = 固定步长.取步数(ref 待推进秒, 现实秒);
        for (int i = 0; i < 步数 && 战斗中; i++) 推进一步(固定步长.步长);
    }

    // 一个逻辑步（固定 1/30 秒）：推进世界时间 + 行动条累积 + 轮次结算 + 满条行动
    private void 推进一步(float 现实秒)
    {
        float 游戏分钟 = 现实秒 * 每现实秒游戏分钟;
        // 世界时间：推进档案分钟（不结算生存）+ 同步整点基准 + 时间事件
        var 档案实例 = 档案;
        if (档案实例 != null)
        {
            档案实例.游戏分钟数 += 游戏分钟;
            ServiceRegistry.Get<世界时间管理器>()?.同步整点基准();
            // ★ v51 刀15：时间事件**按游戏分钟粒度发**，不再每帧发。
            //   原来 60fps 下一场 60 秒战斗要发 3600 次，而订阅者干的是重活
            //   （格子探索服务.时间变化响应 里无条件 刷新视野() → 每帧 new 一个可见集 HashSet；
            //     HUD 每帧格式化时间串 + TMP 富文本重赋值；自动存档器 每帧判跨天）。
            //   跨天 / 白天夜晚切换 都只需要分钟粒度，所以这里按 (int)游戏分钟数 去重。
            int 整分 = (int)档案实例.游戏分钟数;
            if (整分 != 上次发事件的分)
            {
                上次发事件的分 = 整分;
                事件.发布(new 时间变化事件(档案实例.游戏分钟数));
            }
        }
        推进换弹(现实秒);   // 刀46：换弹倒计时（1.5 秒；眩晕 → 打断换弹）
        // 行动条累积：每轮 先 锁 意图（读条 = 意图，颜色 由 意图 决定），按 意图 间隔（现实 秒）匀速 推进——满 100 = 一次 行动
        foreach (var 单位 in 全部单位())
        {
            if (!单位.存活) continue;
            // 受控（眩晕/定身 类 Buff 或 眩晕秒）：读条 冻结 + 意图 作废 + 玩家 蓄力 预约 一并 取消（被控 = 断 一切 读条）
            if (单位.无法行动)
            {
                if (单位.眩晕剩余秒 > 0f) 单位.眩晕剩余秒 = Mathf.Max(0f, 单位.眩晕剩余秒 - 现实秒);   // 眩晕 秒制 倒计时
                if (单位.行动条 > 0.01f) 中断读条(单位, null);
                else if (单位 == 玩家 && 待动类型 != 待动类别.无) 取消待行动作();
                continue;
            }
            if (!单位.意图已选) { 选定下一意图(单位); 单位.意图已选 = true; }
            // 刀46：换弹期间**玩家行动条冻结**（= 换弹占用一次行动）——不然会出现"读条和换弹同时在涨"的怪状态
            if (单位 == 玩家 && 换弹剩余秒 > 0f) continue;
            float 每秒填充 = 100f / 意图间隔秒(单位);
            单位.行动条 = Mathf.Min(200f, 单位.行动条 + 每秒填充 * 现实秒);
        }
        // 技能冷却：现实秒 逐帧 推进（真实时间 等待，不受 游戏时间 倍率 影响）
        foreach (var 单位 in 全部单位())
            if (单位.存活) 单位.推进冷却(现实秒);
        // 轮次结算：每 5 游戏分钟 = 5 现实秒 一轮（每现实秒游戏分钟 = 1）——buff 时长（持续秒）与
        //   持续伤害（结算时机 开始/结束）都按这个节拍走。（旧口径是 60 游戏分钟一轮，见 一轮分钟）
        战斗分钟 += 游戏分钟;
        while (战斗分钟 >= 一轮分钟)
        {
            战斗分钟 -= 一轮分钟;
            轮次结算();
            if (!战斗中) return;
        }
        处理满条行动();
    }

    // 轮次结算（每 5 现实秒 一轮）：持续伤害「结束」→「开始」→ 持续恢复（再生）→ buff 时长递减 / 无敌递减。
    //   ★ 顺序要紧：**先结算、后递减**。持续秒 15 的流血要正好跳 3 次（t=5/10/15），
    //     先递减的话最后一跳会被"归零即移除"吞掉 → 只剩 2 次（设计是 3 次共 6 点）。
    private void 轮次结算()
    {
        回合数++;
        // 持续伤害「结束」时机
        foreach (var 单位 in 全部单位())
        {
            int 毒伤 = 单位.持续伤害量("结束");
            if (毒伤 <= 0) continue;
            单位.受到伤害(毒伤);
            事件.发布(new 伤害事件(单位, 毒伤, 伤害类型.真实, false, false));
            发消息($"{名(单位)} 受到 {毒伤} 点毒噬伤害。");
            检查单位死亡(单位);
        }
        if (检查战斗结束()) return;
        // 持续伤害「开始」时机
        foreach (var 单位 in 全部单位())
        {
            int 毒伤 = 单位.持续伤害量("开始");
            if (毒伤 <= 0) continue;
            单位.受到伤害(毒伤);
            事件.发布(new 伤害事件(单位, 毒伤, 伤害类型.真实, false, false));
            发消息($"{名(单位)} 受到 {毒伤} 点持续伤害。");
            检查单位死亡(单位);
        }
        if (检查战斗结束()) return;
        // 持续恢复（增益「再生」）：与异常跳伤同一节拍，逐 5 秒回一次
        foreach (var 单位 in 全部单位()) 再生回复(单位);
        // buff 时长递减（现实秒）+ 无敌（1 轮 = 5 秒）
        foreach (var 单位 in 全部单位())
        {
            单位.推进Buff(一轮分钟);
            if (单位.无敌回合 > 0) 单位.无敌回合--;
        }
    }

    // 增益「再生」的逐 5 秒回血：数值 = 每次回复量（buffs.json 再生.数值），层数可叠。
    //   满血时不回也不播报 —— 否则日志会说"恢复 6 点生命"而血条一动不动（这种日志是骗人的）。
    private void 再生回复(战斗单位 单位)
    {
        if (!单位.存活 || 单位.生命 >= 单位.最大生命) return;
        var 再生 = 单位.Buffs.Find(b => b.定义.标识 == "再生");
        if (再生 == null) return;
        int 回复 = Mathf.Max(1, 再生.定义.数值 * 再生.层数);
        单位.恢复生命(回复);
        事件.发布(new 治疗事件(单位, 回复));
        发消息($"{名(单位)} 的「再生」生效，恢复 {回复} 点生命。");
    }

    // 满条行动：按行动条值降序（溢出多=等待久）逐个执行自动行动
    private void 处理满条行动()
    {
        while (战斗中)
        {
            战斗单位 待动 = null;
            foreach (var 单位 in 全部单位())
                if (单位.存活 && 单位.行动条 >= 100f && (待动 == null || 单位.行动条 > 待动.行动条)) 待动 = 单位;
            if (待动 == null) break;
            单位自动行动(待动);
        }
    }

    // —— 行动 间隔（现实 秒 = 一次 行动 用时）——
    // 玩家：移动/技能/攻击 一律 5 秒（无 加成 基准）；装备 移速 / 武器 攻速 倍率 = 预留 钩子
    // 敌人：无 装备，天然 按 敌人数据 设定 的 移动/攻击/技能 间隔（三类 各自 不同）
    private float 意图间隔秒(战斗单位 单位)
    {
        float 间隔 = 单位.当前意图 switch
        {
            战斗单位.意图类型.攻击 => 单位.攻击间隔秒,
            战斗单位.意图类型.技能 => 单位.技能间隔秒,
            _ => 单位.移动间隔秒,   // 移动 / 戒备
        };
        float 倍率 = 单位 == 玩家
            ? (单位.当前意图 == 战斗单位.意图类型.攻击 ? 单位.攻速倍率
                : 单位.当前意图 == 战斗单位.意图类型.移动 ? 单位.移速倍率 : 1f)
            : 1f;
        if (单位 == 玩家)
        {
            // 速度 buff（专注）：**只加快行动条填充** —— 不碰暴击/闪避（那两条只吃敏捷，见 战斗单位.当前暴击率/闪避率）
            倍率 *= 1f + 单位.属性修正("速度") / 100f;
            // 被动「松弦」（弓弩精通 6 级）：**蓄力类技能**的读条时长 −30%
            //   蓄力技的"读条"就是这条意图间隔（满条才出手），所以减在这里；
            //   意图技能在整条读条期间是锁定的（承诺制），间隔不会中途变。
            if (单位.当前意图 == 战斗单位.意图类型.技能 && !string.IsNullOrEmpty(单位.意图技能)
                && 单位.被动技能.Contains("松弦")
                && 数据.技能.TryGetValue(单位.意图技能, out var 读条技能)
                && 读条技能.出手时机枚举 == 技能时机.蓄力)
                间隔 *= 0.7f;
        }
        return Mathf.Max(0.5f, 间隔 / Mathf.Max(0.1f, 倍率));
    }

    // 意图 选定（读条 开始 时；满条 前 不变；受控 不 换）
    private void 选定下一意图(战斗单位 单位)
    {
        if (单位.无法行动) return;
        if (单位 == 玩家) { 选定玩家意图(单位); return; }
        选定敌人意图(单位);
    }

    private void 选定玩家意图(战斗单位 玩)
    {
        if (待动类型 != 待动类别.无) { 玩.当前意图 = 战斗单位.意图类型.技能; 玩.意图技能 = 待动标识; return; }   // 蓄力 技能/道具
        玩.意图技能 = null;
        玩.当前意图 = 可攻击目标(玩) != null ? 战斗单位.意图类型.攻击 : 战斗单位.意图类型.移动;
    }

    private void 选定敌人意图(战斗单位 敌)
    {
        var 源 = 敌.源数据;
        // 技能：行动表 有 技能 且 就绪 → 技能 意图（读条 大招；执行 时 再 校验）
        if (源?.行动表 != null && 源.行动表.Length > 0)
        {
            // ★ 刀28：抽招决策唯一入口（纯函数 + 掷点由这里给）。抽到的招**锁进 意图技能**，
            //   满条执行时不再抽第二次（原来 自动攻击 会再抽一次 → 权重被采样两次、且"读条显示攻击却甩技能"）。
            string 动作 = 敌人AI.抽行动(源, 随机.范围(0, 敌人AI.权重总和(源)));
            if (!string.IsNullOrEmpty(动作) && 动作 != "普攻" && 数据.技能.TryGetValue(动作, out _) && 敌.冷却剩余(动作) <= 0f)
            {
                敌.当前意图 = 战斗单位.意图类型.技能; 敌.意图技能 = 动作; return;
            }
        }
        敌.意图技能 = null;
        if (敌.移动AI == "驻守") { 敌.当前意图 = 战斗单位.意图类型.戒备; return; }
        敌.当前意图 = 可攻击目标(敌) != null ? 战斗单位.意图类型.攻击 : 战斗单位.意图类型.移动;
    }

    // 自动行动：满条触发——按 读条 期 锁定 的 意图 执行（不再 临场 改招）
}

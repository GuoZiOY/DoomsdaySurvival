using System.Collections.Generic;
using UnityEngine;

// BattleService · AI 分部 —— 敌人 AI 的**服务侧胶水**：查存活列表、掷点、执行招式。
// 决策本身（抽哪一招 / 打谁 / 治谁）已抽到 `Domain/战斗/敌人AI.cs`（纯函数，掷点由这里给）。
public sealed partial class BattleService
{
    // ===== 敌人AI（P6） =====
    // ⚠ 这是**第三条入口**（只有"逃跑失败惩罚"在调）。它仍走意图机 → 见 docs 的 D15 余项：
    //   ① 会顺手把敌人的行动条清零（对玩家有利的隐藏副作用）；② 意图是"移动"时惩罚近乎为零。
    //   两个候选改法（显式普攻 / 只推进行动条 +30）在文档里等你选，这里先不动。
    private void 敌人行动(战斗单位 敌人)
    {
        var 敌数据 = 敌人.源数据;
        string 行动 = 敌数据?.行动表 != null && 敌数据.行动表.Length > 0
            ? 敌人AI.抽行动(敌数据, Random.Range(0, 敌人AI.权重总和(敌数据)))
            : 敌人AI.普攻;
        // 治疗/增益类技能（我方单体/我方全体/自己 目标）：选友方（同伴）目标，否则会误治疗玩家
        战斗单位 目标;
        if (行动 != 敌人AI.普攻 && 数据.技能.TryGetValue(行动, out var 技能) && 技能.目标枚举 != 目标类型.敌方单体 && 技能.目标枚举 != 目标类型.敌方全体)
            目标 = AI选友方(敌人, 技能);
        else 目标 = AI选目标(敌人, 敌数据);
        if (行动 == 敌人AI.普攻) 执行攻击(敌人, 目标);
        else 执行技能(敌人, 行动, 目标);
    }

    // 治疗/增益选友方目标：同伴 = 与施法者同阵营；治疗选最残血，其余选第一个（决策在 Domain）
    private 战斗单位 AI选友方(战斗单位 施法者, 技能数据 技能)
    {
        var 同伴 = 施法者.是否我方 ? 我方 : 敌方;
        var 存活 = 同伴.FindAll(u => u.存活);
        战斗单位 兜底 = 施法者.是否我方 ? 玩家 : (敌方.Count > 0 ? 敌方[0] : 施法者);
        return 敌人AI.选友方(施法者, 技能, 存活, 兜底);
    }

    private 战斗单位 AI选目标(战斗单位 敌人, 敌人数据 敌数据)
    {
        var 存活 = 我方.FindAll(u => u.存活);
        return 敌人AI.选目标(敌数据, 存活, Random.Range(0, 存活.Count <= 0 ? 1 : 存活.Count));
    }
}

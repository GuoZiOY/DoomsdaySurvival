using System.Collections.Generic;
using UnityEngine;

// BattleService · 行动 分部 —— 行动与移动（自动行动/技能意图/目标/自动移动/防御/行动条重置/速率）
// （v51 刀25 纯组织性拆分：**零逻辑改动**，只是把一个 1486 行的文件按原有分节切开。
//    「哪些该真的拆成类」的判据见 docs/优化实施进度.md §一之十一：先拆文件，再沉纯逻辑。）
public sealed partial class BattleService
{
    private void 单位自动行动(战斗单位 单位)
    {
        if (!战斗中) return;
        单位.行动条 = 0f;
        if (!单位.存活) return;
        if (单位.无法行动) { 发消息($"{名(单位)} 被控制，无法行动！"); return; }
        单位.防御姿态 = false;   // 清上一轮防御（防御持续到下次行动）
        // 待行动作：玩家 蓄力 满条 → 完成（技能/道具）；失败 落 回 自动
        if (单位 == 玩家 && 待动类型 != 待动类别.无 && 完成待行动作()) { 单位.意图已选 = false; 检查战斗结束(); return; }
        if (单位 == 玩家 && 待动类型 == 待动类别.无 && 单位.当前意图 == 战斗单位.意图类型.技能)
        {
            // 蓄力 已 被 取消/落空：本 次 按 常规 出手（不再 按 技能 意图）
            单位.意图技能 = null;
            单位.当前意图 = 可攻击目标(单位) != null ? 战斗单位.意图类型.攻击 : 战斗单位.意图类型.移动;
        }
        switch (单位.当前意图)
        {
            case 战斗单位.意图类型.技能:
                执行技能意图(单位);
                break;
            case 战斗单位.意图类型.移动:
                自动移动(单位);
                break;
            case 战斗单位.意图类型.戒备:
                {
                    var 目标 = 可攻击目标(单位);
                    if (目标 != null) 自动攻击(单位, 目标);   // 驻守：来犯 才 出手
                    break;
                }
            default:   // 攻击：射程 内 出手；目标 脱身 → 趁机 逼近
                {
                    var 目标 = 可攻击目标(单位);
                    if (目标 != null)
                    {
                        if (单位.行动模式 == 1) 触发防御(单位);
                        else 自动攻击(单位, 目标);
                    }
                    else 自动移动(单位);
                    break;
                }
        }
        单位.意图已选 = false;   // 满条 已 执行 → 下轮 重锁
        检查战斗结束();
    }

    // 技能 意图 执行：锁 的 技能 就绪 且 目标 合法 → 释放；否则 落 回 移动（逼近/走位）
    private void 执行技能意图(战斗单位 施法者)
    {
        string 标识 = 施法者.意图技能;
        施法者.意图技能 = null;
        var 目标 = 可攻击目标(施法者);
        if (string.IsNullOrEmpty(标识) || !数据.技能.TryGetValue(标识, out var 技能数据) || 施法者.冷却剩余(标识) > 0f)
        { 自动移动(施法者); return; }
        if (目标 != null && 技能目标合法(技能数据, 施法者, 目标) && 执行技能(施法者, 标识, 目标)) return;
        自动移动(施法者);
    }

    // 射程内有目标（距离 = 节点差 ≤ 攻击距离；轨道无障碍，无需视线）
    private 战斗单位 可攻击目标(战斗单位 单位)
    {
        战斗单位 最近 = null; int 最近距 = int.MaxValue;
        foreach (var 敌 in 对方阵营(单位))
        {
            if (!敌.存活) continue;
            int 距 = Mathf.Abs(单位.列 - 敌.列);
            if (距 > 单位.攻击距离) continue;
            if (距 < 最近距) { 最近 = 敌; 最近距 = 距; }
        }
        return 最近;
    }

    private List<战斗单位> 对方阵营(战斗单位 单位) => 单位.是否我方 ? 敌方 : 我方;

    // 自动攻击：**执行读条期锁定的意图**（不再现场抽行动）
    // ★ 刀28（审计 D15-a）：原来这里又抽了一次 `AI抽行动` → JSON 权重被采样两次：
    //   实际技能率与配置不符（偏高），而且"读条显示攻击、满条却甩技能"，破坏了承诺制。
    //   现在技能只可能来自 意图技能（选定敌人意图 时锁定），这条路上它就是空 → 出普攻。
    //   ⚠ 行为/平衡改动：敌人放技能的频率会**低于**旧版（旧版等于抽两次），需要试玩调权重（见 docs P7）。
    private void 自动攻击(战斗单位 攻击者, 战斗单位 目标)
    {
        string 行动 = 攻击者.意图技能;
        if (!string.IsNullOrEmpty(行动) && 数据.技能.TryGetValue(行动, out var 技能))
        {
            if (技能目标合法(技能, 攻击者, 目标)) { 执行技能(攻击者, 行动, 目标); return; }
        }
        执行攻击(攻击者, 目标);
    }

    // 自动移动（节点式轨道）：玩家按 运动模式（前进/等待/后退）；敌人按 移动AI（冲锋/风筝/驻守）。
    // 停止规则：无论敌我，前方节点被敌方单位占据 → 停在相邻节点（不越过、不重叠——贴脸对峙）
    private void 自动移动(战斗单位 单位)
    {
        int 方向 = 0;   // +1 前进（节点+1）/ -1 后退（节点-1）/ 0 不动
        if (单位.是否我方)
        {
            if (单位.运动模式 == 1) return;   // 原地等待
            var 敌 = 最近敌人(单位);
            if (敌 == null) return;
            方向 = 单位.运动模式 == 0 ? (敌.列 > 单位.列 ? 1 : -1) : (敌.列 < 单位.列 ? 1 : -1);
        }
        else
        {
            var 玩 = 玩家;
            if (玩 == null || !玩.存活) return;
            switch (单位.移动AI)
            {
                case "驻守": return;
                case "风筝":
                    {
                        int 距 = Mathf.Abs(单位.列 - 玩.列);
                        if (距 > 单位.攻击距离) 方向 = 玩.列 > 单位.列 ? 1 : -1;   // 逼近到射程边缘
                        else if (距 <= 1) 方向 = 玩.列 < 单位.列 ? 1 : -1;         // 被贴脸 → 拉远
                        else return;   // 射程内站桩输出
                        break;
                    }
                default: 方向 = 玩.列 > 单位.列 ? 1 : -1; break;   // 冲锋
            }
        }
        if (方向 == 0) return;
        int 目标列 = 单位.列 + 方向;
        if (目标列 < 0 || 目标列 >= 棋盘宽) return;
        foreach (var 敌 in 对方阵营(单位))
            if (敌.存活 && 敌.列 == 目标列) return;   // 前方节点被敌方占据 → 停（贴脸）
        单位.列 = 目标列;
    }

    private 战斗单位 最近敌人(战斗单位 单位)
    {
        战斗单位 最近 = null; int 最近距 = int.MaxValue;
        foreach (var 敌 in 对方阵营(单位))
        {
            if (!敌.存活) continue;
            int 距 = Mathf.Abs(单位.列 - 敌.列);
            if (距 < 最近距) { 最近 = 敌; 最近距 = 距; }
        }
        return 最近;
    }

    // 防御姿态：持续到下次行动；期间受击减半
    private void 触发防御(战斗单位 单位)
    {
        单位.防御姿态 = true;
        发消息($"{名(单位)} 摆出防御姿态！");
    }

    // 主动操作统一出口：重置行动条（打断当前蓄力）+ 下轮 重锁 意图
    private void 重置行动条(战斗单位 单位)
    {
        单位.行动条 = 0f;
        单位.意图已选 = false;
    }

    // —— 待行动作（点击 技能/道具 → 打断并重置行动条 → 行动条 再次 蓄满 才 真正 生效；蓄力制，与普攻共用行动位）——
    private enum 待动类别 { 无, 道具, 技能 }
    private 待动类别 待动类型 = 待动类别.无;   // 蓄力 中 的 动作 类别
    private string 待动标识;                   // 蓄力 中 的 技能/道具 标识
    private 战斗单位 待动目标;                 // 该 动作 的 目标

    // UI 查询：当前 蓄力中 的 技能（无 = null）／是否 蓄力中
    public string 蓄力中技能 => 待动类型 == 待动类别.技能 ? 待动标识 : null;
    public bool 蓄力中 => 待动类型 != 待动类别.无;

    // 武器攻击距离解析（战斗沙盒自动攻击范围）：1=近战、>1=远程
    private int 武器攻击距离(string 武器标识)
    {
        if (数据.物品.TryGetValue(武器标识, out var 物品) && 物品.攻击距离 > 0) return 物品.攻击距离;
        return 1;
    }

    // 玩家 攻速/移速 倍率（行动 间隔 除数：>1 更快 / <1 更慢，下限 0.4）
    // = 1 + 敏捷 贡献（敏捷 总成 移速&攻速）+ 当前 武器 攻速加成% + 全身 防具 移速加成% 之和（重型 可为 负）
    private void 刷新玩家速率()
    {
        if (玩家 == null || 档案 == null) return;
        int 敏 = 档案.敏捷;
        float 攻 = 1f + (敏 - 5) * 0.01f;   // 敏捷 → 攻速：每点 +1%（基准 5 点 = 0）
        float 移 = 1f + (敏 - 5) * 0.015f;  // 敏捷 → 移速：每点 +1.5%
        string 武 = 玩家.当前武器标识;
        if (!string.IsNullOrEmpty(武) && 数据.物品.TryGetValue(武, out var 武器) && 武器.攻速加成 != 0f)
            攻 += 武器.攻速加成 / 100f;   // 轻 武器 快 / 重 武器 慢（负面）
        foreach (var 记录 in 档案.装备)
        {
            if (记录 == null || string.IsNullOrEmpty(记录.标识)) continue;
            if (记录.槽位 == "主手" || 记录.槽位 == "副手") continue;   // 攻速 只 按 当前 武器
            if (数据.物品.TryGetValue(记录.标识, out var 装) && 装.移速加成 != 0f)
                移 += 装.移速加成 / 100f;   // 重型 甲 负 值 → 拖慢
        }
        玩家.攻速倍率 = Mathf.Max(0.4f, 攻);
        玩家.移速倍率 = Mathf.Max(0.4f, 移);
    }

}

//   BattleService.操作.cs        玩家主动操作：主动技能与道具/预约与取消/模式切换/逃跑/切武器
//   BattleService.AI.cs          敌人 AI 的服务侧胶水（查存活/掷点/执行）；决策在 Domain/战斗/敌人AI.cs
//   BattleService.行动执行.cs    统一行动执行：弹药与消耗物/攻击/技能/位移/推挤/中断读条/眩晕/Buff/可释放技能

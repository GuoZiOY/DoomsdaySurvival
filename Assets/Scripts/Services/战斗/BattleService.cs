// ===== 分部索引（v51 刀25 拆、刀27 合并与补索引）=====
// 同一个类按职责拆成 8 个文件；**字段全在本文件**，找方法照下表（别的分部不重复定义任何字段）：
//   BattleService.推进.cs        时钟与轮次：推进战斗/轮次结算/满条行动/意图间隔/意图选定

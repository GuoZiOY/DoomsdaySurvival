    private float 换弹剩余秒;
    private string 换弹槽位;               // 正在换弹的武器槽（主手/副手）
    private const float 换弹秒 = 1.5f;     // 无加成 基准（被动「疾风装填」走 换弹用时() 缩短）

    // —— 战斗状态 ——
    public bool 战斗中 { get; private set; }

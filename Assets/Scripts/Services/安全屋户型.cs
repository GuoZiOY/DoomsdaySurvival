using System.Collections.Generic;

// 安全屋户型：程序化 随机 生成 房间 布局（容器 口袋 式 隔离——房间 之间 留 1 格 缝 = 墙 空隙）。
// 房间 类型：大厅/卧室/洗浴间/厨房/阳台/客卧/杂物间（数量 3~7 随机：必含 大厅+卧室+洗浴间，其余 随机 补足）。
// 面积：网格 尺寸 随 房间 数 递增——最少 3 房 = 10×7，最多 7 房 = 12×9（玩家 档案 存 种子，读档 恢复）。
// 生成：① 随机 房间 数 N + 类型 组合 → ② 网格 尺寸（N → 表）→ ③ BSP 迭代 切 成 N 矩形（缝 1 格，凸凹 自然）→
//       ④ 矩形 面积 降序 ↔ 类型 面积 需求 降序 一一 对应（大厅 配 大 矩形）→ ⑤ 家具 适配 校验（5 件 必 有 空位，
//       可 旋转）→ 无效 重试（30 次）→ 兜底 固定 布局。
public sealed class 安全屋户型
{
    // 房间 类型（7 种；面积 需求 排序 用 类型面积()）
    public enum 房间类型 { 大厅, 卧室, 洗浴间, 厨房, 阳台, 客卧, 杂物间 }

    public int 房间列数, 房间行数;   // 本 户型 网格 尺寸（随 房间 数 变）
    public bool[,] 格可用;           // [列,行]
    public int[,] 格所属块;          // >=0 = 块（房间）；-1 = 缝/院子（不可 放）
    public List<容器形状块> 形状块;  // 每 块 一个 矩形（索引 = 块号）
    public List<房间类型> 房间类型表;   // 块号 → 类型（索引 = 块号）

    // 类型 名称（房间 标签 显示 用）
    public static string 类型名称(房间类型 类型) => 类型 switch
    {
        房间类型.大厅 => "大厅",
        房间类型.卧室 => "卧室",
        房间类型.洗浴间 => "洗浴间",
        房间类型.厨房 => "厨房",
        房间类型.阳台 => "阳台",
        房间类型.客卧 => "客卧",
        _ => "杂物间",
    };

    // 家具 清单（适配 校验 用）：标识 + 未旋转 宽高（与 安全屋管理器.家具形状 一致）
    private static readonly (string 标识, int 宽, int 高)[] 家具清单 =
    {
        ("床", 2, 3), ("工作台", 3, 2), ("储物箱", 2, 3), ("收音机", 1, 1), ("灶台", 2, 2),
    };

    // 房间 尺寸 上限：不 过 长/过 宽/过 大（最大 = 大厅；比例 多 为 2:3 / 3:4 / 5:6 或 正方形；洗浴间 最小 2×2）
    private const int 最大宽 = 6, 最大高 = 5;

    // 生成：种子 → 户型（先 定死 房间 数——大 户型 有 完整 30 次 尝试 机会，不 被 小 户型 抢 先；
    // 单次 异常 跳过 重试；全 失败 → 最后 尝试 户型 兜底，再 无 → 3 房 固定 布局）
    public static 安全屋户型 生成(int 种子)
    {
        var 随机 = new System.Random(种子);
        int 房间数 = 随机.Next(3, 8);   // 本 户型 固定 房间 数（3~7）
        安全屋户型 最后尝试 = null;
        for (int 尝试 = 0; 尝试 < 30; 尝试++)
        {
            try
            {
                var 户型 = 尝试生成(随机, 房间数);
                if (户型 == null) continue;
                最后尝试 = 户型;
                if (户型.家具都放得下()) return 户型;
            }
            catch (System.Exception) { }
        }
        return 最后尝试 ?? 固定布局();
    }

    // ===== 随机 生成 一次（固定 房间 数） =====

    private static 安全屋户型 尝试生成(System.Random 随机, int 房间数)
    {
        var (列数, 行数) = 网格尺寸(房间数);
        var 类型组合 = 随机类型组合(随机, 房间数);
        类型组合.Sort((a, b) => 类型面积(b).CompareTo(类型面积(a)));   // 面积 需求 降序（大厅 大）

        // —— BSP 迭代 切 分：全 网格 矩形 反复 切（缝 1 格）到 目标 房间 数；
        //    房间 尺寸 受 上限（最大宽/高）+ 比例（1:2~2:1）约束——不 过 长/过 宽/过 大 ——
        var 矩形 = new List<(int 列, int 行, int 宽, int 高)> { (0, 0, 列数, 行数) };
        while (矩形.Count < 房间数)
        {
            // 需 切：超 上限 或 比例 失衡（宽 > 2 高 或 高 > 2 宽）
            var 需切 = 矩形.FindAll(r => r.宽 > 最大宽 || r.高 > 最大高 || r.宽 > r.高 * 2 || r.高 > r.宽 * 2);
            // 可 切（物理 + 缝）：宽 ≥5 或 高 ≥5（切 后 两 边 ≥2 + 缝 1）
            var 可切 = 矩形.FindAll(r => r.宽 >= 5 || r.高 >= 5);
            if (需切.Count == 0 && (可切.Count == 0 || 矩形.Count >= 房间数)) break;
            var 候选 = 需切.Count > 0 ? 需切 : 可切;
            if (候选.Count == 0) break;
            var r = 候选[随机.Next(候选.Count)];
            矩形.Remove(r);
            // 切 方向：高 过 长 → 水平（减 高）；宽 过 长 → 垂直（减 宽）；均衡 → 随机
            bool 水平;
            if (r.高 > r.宽 * 2) 水平 = true;
            else if (r.宽 > r.高 * 2) 水平 = false;
            else if (r.高 >= 5 && (r.宽 < 5 || 随机.Next(2) == 0)) 水平 = true;
            else 水平 = false;
            if (水平)
            {
                // 上 高 在 [高/3, 2高/3]（夹 [2, 高-3]）——子 矩形 比例 不 失衡（2:1 内）
                int 最小上 = System.Math.Max(2, r.高 / 3);
                int 最大上 = System.Math.Min(r.高 - 3, r.高 * 2 / 3);
                if (最小上 > 最大上) 最小上 = 最大上;
                int 上高 = 随机.Next(最小上, 最大上 + 1);
                int 切行 = r.行 + 上高;   // 缝 = 切行（空 1 行）
                矩形.Add((r.列, r.行, r.宽, 上高));
                矩形.Add((r.列, 切行 + 1, r.宽, r.行 + r.高 - 切行 - 1));
            }
            else
            {
                int 最小左 = System.Math.Max(2, r.宽 / 3);
                int 最大左 = System.Math.Min(r.宽 - 3, r.宽 * 2 / 3);
                if (最小左 > 最大左) 最小左 = 最大左;
                int 左宽 = 随机.Next(最小左, 最大左 + 1);
                int 切列 = r.列 + 左宽;   // 缝 = 切列（空 1 列）
                矩形.Add((r.列, r.行, 左宽, r.高));
                矩形.Add((切列 + 1, r.行, r.列 + r.宽 - 切列 - 1, r.高));
            }
        }
        if (矩形.Count < 3) return null;

        // —— 登记 房间 + 类型 分配（矩形 面积 降序 ↔ 类型 面积 需求 降序） ——
        矩形.Sort((a, b) => (b.宽 * b.高).CompareTo(a.宽 * a.高));
        var 户型 = new 安全屋户型 { 房间列数 = 列数, 房间行数 = 行数 };
        户型.格可用 = new bool[列数, 行数];
        户型.格所属块 = new int[列数, 行数];
        户型.形状块 = new List<容器形状块>();
        户型.房间类型表 = new List<房间类型>();
        for (int 列 = 0; 列 < 列数; 列++)
            for (int 行 = 0; 行 < 行数; 行++)
                户型.格所属块[列, 行] = -1;   // 缝/院子
        int 块号 = 0;
        for (int i = 0; i < 矩形.Count; i++)
        {
            var (列, 行, 宽, 高) = 矩形[i];
            if (宽 < 2 || 高 < 2) continue;
            块号++;
            for (int c = 列; c < 列 + 宽; c++)
                for (int r = 行; r < 行 + 高; r++)
                    户型.格所属块[c, r] = 块号;
            户型.形状块.Add(new 容器形状块 { 列 = 列, 行 = 行, 宽 = 宽, 高 = 高 });
            户型.房间类型表.Add(类型组合[System.Math.Min(i, 类型组合.Count - 1)]);
        }
        if (块号 == 0) return null;
        for (int 列 = 0; 列 < 列数; 列++)
            for (int 行 = 0; 行 < 行数; 行++)
                户型.格可用[列, 行] = 户型.格所属块[列, 行] >= 0;
        return 户型;
    }

    // 房间 数 → 网格 尺寸（最少 3 房 10×7；每 多 房 面积 递增，7 房 12×9）
    private static (int 列, int 行) 网格尺寸(int 房间数) => 房间数 switch
    {
        3 => (10, 7),
        4 => (10, 8),
        5 => (11, 8),
        6 => (12, 8),
        _ => (12, 9),
    };

    // 随机 类型 组合：必含 大厅+卧室+洗浴间；厨房/阳台/客卧/杂物间 随机 补足 至 N
    private static List<房间类型> 随机类型组合(System.Random 随机, int N)
    {
        var 组合 = new List<房间类型> { 房间类型.大厅, 房间类型.卧室, 房间类型.洗浴间 };
        var 可选 = new List<房间类型> { 房间类型.厨房, 房间类型.阳台, 房间类型.客卧, 房间类型.杂物间 };
        while (组合.Count < N && 可选.Count > 0)
        {
            int i = 随机.Next(可选.Count);
            组合.Add(可选[i]);
            可选.RemoveAt(i);
        }
        return 组合;
    }

    // 类型 面积 需求（排序：大厅 最大，洗浴 最小）
    private static int 类型面积(房间类型 类型) => 类型 switch
    {
        房间类型.大厅 => 12,
        房间类型.卧室 => 8,
        房间类型.客卧 => 8,
        房间类型.杂物间 => 8,
        房间类型.厨房 => 6,
        房间类型.阳台 => 6,
        _ => 4,   // 洗浴间
    };

    // ===== 家具 适配 校验（5 件 全 户型 找 空位，可 旋转） =====

    private bool 家具都放得下()
    {
        foreach (var (_, 宽, 高) in 家具清单)
        {
            bool 有 = false;
            for (int 旋转 = 0; 旋转 <= 1 && !有; 旋转++)
            {
                int w = 旋转 == 1 ? 高 : 宽, h = 旋转 == 1 ? 宽 : 高;
                for (int 行 = 0; 行 <= 房间行数 - h && !有; 行++)
                    for (int 列 = 0; 列 <= 房间列数 - w && !有; 列++)
                        if (可放置(列, 行, w, h)) 有 = true;
            }
            if (!有) return false;
        }
        return true;
    }

    // 形状 校验：覆盖 格 全 可用 且 同 一 块（不 跨 房间/缝/院子）
    private bool 可放置(int 列, int 行, int 宽, int 高)
    {
        int 块 = -2;
        for (int r = 行; r < 行 + 高; r++)
            for (int c = 列; c < 列 + 宽; c++)
            {
                int 此块 = 格所属块[c, r];
                if (此块 < 0) return false;
                if (块 == -2) 块 = 此块;
                else if (块 != 此块) return false;
            }
        return true;
    }

    // ===== 兜底：固定 布局（3 房：大厅+卧室+洗浴间，10×7，缝 隔离；保证 可玩） =====

    private static 安全屋户型 固定布局()
    {
        var 户型 = new 安全屋户型 { 房间列数 = 10, 房间行数 = 7 };
        户型.格可用 = new bool[10, 7];
        户型.格所属块 = new int[10, 7];
        户型.形状块 = new List<容器形状块>();
        户型.房间类型表 = new List<房间类型>();
        for (int 列 = 0; 列 < 10; 列++)
            for (int 行 = 0; 行 < 7; 行++)
                户型.格所属块[列, 行] = -1;
        int 块号 = 0;
        登记固定房间(户型, 0, 0, 6, 4, 房间类型.大厅, ref 块号);     // 大厅（6×4 最大；行0-3）
        登记固定房间(户型, 7, 0, 3, 4, 房间类型.卧室, ref 块号);       // 卧室（3×4；列6 缝；床 2×3）
        登记固定房间(户型, 0, 5, 4, 2, 房间类型.洗浴间, ref 块号);     // 洗浴间（4×2；行4 缝；列4-9 行5-6 院子）
        for (int 列 = 0; 列 < 10; 列++)
            for (int 行 = 0; 行 < 7; 行++)
                户型.格可用[列, 行] = 户型.格所属块[列, 行] >= 0;
        return 户型;
    }

    private static void 登记固定房间(安全屋户型 户型, int 列, int 行, int 宽, int 高, 房间类型 类型, ref int 块号)
    {
        块号++;
        for (int c = 列; c < 列 + 宽; c++)
            for (int r = 行; r < 行 + 高; r++)
                户型.格所属块[c, r] = 块号;
        户型.形状块.Add(new 容器形状块 { 列 = 列, 行 = 行, 宽 = 宽, 高 = 高 });
        户型.房间类型表.Add(类型);
    }
}

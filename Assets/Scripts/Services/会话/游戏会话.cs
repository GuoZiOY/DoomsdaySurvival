// 游戏会话状态：**"现在玩家处于哪个阶段"的唯一答案**（v52 · UI管理器 步2）。
//
// 为什么必须有这个显式的东西：
//   在这之前，"常驻 HUD 该不该显示""世界时间该不该走""能不能存档"这三件**互不相干**的事，
//   各自去**推断**当前状态 —— `世界时间管理器` 用"`玩家档案.当前节点` 是不是空"、
//   `面板管理器` 用"当前显示面板是不是主菜单"、`侧边栏` 又自己判一遍。
//   推断散在三处就会各自漂移：这一轮已经修过它的**两个症状**
//   （未开局时世界时间在走 · 战斗中禁存读只在 UI 层）。项目评估把它点名为"D 组非法中间态"的根因。
//
// ★ 单一写入方（这是关键）：**只有 `面板管理器.显示()` 写它** —— 只有它知道"现在显示的是哪个面板"。
//   `BattleService.战斗中` 仍然管"战斗进行中"（那是战斗内部的真相），**不**写会话状态；
//   战斗面板显示/隐藏时，面板管理器 自然会把阶段切进/切出「战斗」。
//   于是"谁能写"只有一处，不存在两个写入方打架 —— 这一点比状态本身更重要。
//
// 为什么四个值而不是更多：**只留有消费者的**。
//   （"结算中"这种听起来合理但今天没有任何一处会读它的状态，先不加 —— 加了就是没人读的状态。）
//
// 注：`会话阶段` 这个枚举放在 **Domain/会话/会话阶段.cs**（按项目约定"共用枚举归最底层"）——
//   放这里会让 `Events → Services` 成为层次违规（分层核对 当场报过）。本文件只有行为。

public sealed class 游戏会话
{
    private readonly EventBus 事件;

    public 会话阶段 阶段 { get; private set; } = 会话阶段.主菜单;

    public 游戏会话(EventBus 事件) { this.事件 = 事件; }

    // 在游戏里（探索 或 战斗）—— 常驻 HUD / 侧边栏 / 世界时间 都读这个
    public bool 在游戏里 => 阶段 == 会话阶段.探索 || 阶段 == 会话阶段.战斗;

    // 还没开局（标题界面 / 建角色）—— 存档门禁 读这个
    public bool 未开局 => 阶段 == 会话阶段.主菜单 || 阶段 == 会话阶段.角色创建;

    // 只有 `面板管理器.显示()` 调它（见文件头"单一写入方"）
    public void 置(会话阶段 新阶段)
    {
        if (新阶段 == 阶段) return;
        阶段 = 新阶段;
        事件?.发布(new 会话变化事件(新阶段));
    }

    // 便捷读法：拿不到服务时当作"还在主菜单"（= 什么都不放行），宁可保守
    public static 游戏会话 当前
        => ServiceRegistry.已注册<游戏会话>() ? ServiceRegistry.Get<游戏会话>() : null;

    public static bool 是游戏里 => 当前?.在游戏里 ?? false;
    public static bool 是未开局 => 当前?.未开局 ?? true;
}

    // 待行动作 完成（满条 自动行动 时）：按 类别 真正 执行；目标/资源 失效 → 取消 并 落回 自动 行动
    private bool 完成待行动作()
    {
        if (待动类型 == 待动类别.道具) return 完成待用道具(待动标识, 待动目标);
        if (待动类型 == 待动类别.技能)
        {
            string 标识 = 待动标识;
            var 目标 = 待动目标;
            if (string.IsNullOrEmpty(标识) || 目标 == null || !目标.存活
                || !数据.技能.TryGetValue(标识, out var 技能) || !技能目标合法(技能, 玩家, 目标)
                || 玩家.冷却剩余(标识) > 0)
            {
                取消待行动作(标识 == null ? null : "蓄力中的技能落空了——目标已不可用。");
                return false;
            }
            取消待行动作();                 // 先 清，防 执行 过程 内 再 触发
            if (!执行技能(玩家, 标识, 目标)) return false;   // 资源不足/武器不匹配 = 不消耗，落回 自动
            发消息($"你使用了技能《{技能.名称}》！");
            return true;
        }
        return false;
    }

    // 待行动作（道具）完成：扣除 容器 物品 → 生效；目标/物品 失效 → 取消 并 落回 自动 行动
    private bool 完成待用道具(string 标识, 战斗单位 目标)
    {
        if (string.IsNullOrEmpty(标识) || 目标 == null || !目标.存活 || !数据.物品.TryGetValue(标识, out var 物品)
            || !道具目标合法(物品, 目标))
        {
            取消待行动作(标识 == null ? null : "蓄力中的道具落空了——目标已不可用。");
            return false;
        }
        var 堆叠 = 战斗道具堆叠(标识);
        if (堆叠 == null) { 取消待行动作("蓄力中的道具不见了——弹挂/腰封里已没有它。"); return false; }
        取消待行动作();                 // 先 清 状态，防 执行 过程 内 再 触发
        堆叠.数量--;
        if (堆叠.数量 <= 0) 移除容器堆叠(堆叠);
        ServiceRegistry.Get<EventBus>()?.发布(new 背包变化事件(标识, -1, 变化原因.消耗));
        执行道具即时(玩家, 标识, 目标);
        return true;
    }

    // 取消 待行动作（覆盖 / 目标失效 / 新 主动操作 / 新 战斗 等）

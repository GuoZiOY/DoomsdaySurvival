    // 弹挂/腰封 中查找战斗道具堆叠
    private 物品堆叠 战斗道具堆叠(string 标识)
    {
        foreach (var 槽 in new[] { "弹挂", "腰封" })
        {
            var 记录 = 档案.装备.Find(e => e.槽位 == 槽);
            if (记录?.容器物品 == null) continue;
            var 堆叠 = 记录.容器物品.Find(s => s != null && s.标识 == 标识 && s.数量 > 0);
            if (堆叠 != null) return 堆叠;
        }
        return null;
    }

    private void 移除容器堆叠(物品堆叠 堆叠)
    {
        foreach (var 槽 in new[] { "弹挂", "腰封" })
        {
            var 记录 = 档案.装备.Find(e => e.槽位 == 槽);
            if (记录?.容器物品 == null) continue;
            记录.容器物品.Remove(堆叠);
        }
    }

    // 技能目标合法性：阵营匹配 + 攻击距离（>1 需直线视线；自己/距离0 恒合法）
    private bool 技能目标合法(技能数据 技能, 战斗单位 施法者, 战斗单位 目标)
    {
        var 期望 = 技能.目标枚举;
        if (期望 == 目标类型.自己) return 目标 == 施法者;
        bool 敌方类 = 期望 == 目标类型.敌方单体 || 期望 == 目标类型.敌方全体 || 期望 == 目标类型.敌方两名;
        if (敌方类 && 目标.是否我方) return false;
        if (!敌方类 && !目标.是否我方) return false;
        int 距 = Mathf.Abs(施法者.列 - 目标.列);
        if (距 == 0) return true;   // 自己恒可（治疗自己等）
        int 距离 = 技能.攻击距离 > 0 ? 技能.攻击距离 : 1;
        return 距 <= 距离;   // 轨道：节点差 ≤ 攻击距离 即可（无障碍，无需视线）
    }

    // 道具目标合法性：按 使用效果 判定阵营（恢复/增益 = 我方，缺省=恢复；减益 = 敌方）+ 距离（节点差 ≤ 1 贴脸可用）
    private bool 道具目标合法(物品数据 物品, 战斗单位 目标)
    {
        bool 攻击类 = 物品.使用效果枚举 == 效果类型.减益;
        if (攻击类 && 目标.是否我方) return false;
        if (!攻击类 && !目标.是否我方) return false;
        int 距 = Mathf.Abs(玩家.列 - 目标.列);
        return 距 <= 1;   // 投掷类后续按 攻击距离 扩展
    }

    // 执行道具（即时制：不从战斗单位消耗清单扣——已从弹挂/腰封容器扣）
    private void 执行道具即时(战斗单位 使用者, string 物品标识, 战斗单位 目标)
    {
        if (!数据.物品.TryGetValue(物品标识, out var 物品) || !物品.战斗内使用) return;
        switch (物品.使用效果枚举)
        {
            case 效果类型.恢复:
                {
                    int 恢复 = Mathf.Max(1, Mathf.RoundToInt(物品.恢复量 * 品质工具.倍率(物品.品质档)));
                    目标.恢复生命(恢复);
                    事件.发布(new 治疗事件(目标, 恢复));
                    发消息($"{名(使用者)} 使用{物品.标识}，恢复 {恢复} 点生命。");
                    break;
                }
            default:
                if (!string.IsNullOrEmpty(物品.挂载Buff) && 数据.Buffs.TryGetValue(物品.挂载Buff, out var buff))
                {
                    目标.添加Buff(buff);
                    事件.发布(new 状态变化事件(目标, buff.标识, 1, buff.持续回合, false));
                    发消息($"{名(目标)} 获得「{buff.名称}」！");
                }
                break;
        }
    }

    // 预约 待行动作（技能/道具 统一入口）：覆盖 旧 预约 → 提示 → 重置行动条（打断 当前 蓄力）
    private void 预约待行动作(待动类别 类别, string 标识, 战斗单位 目标, string 提示)
    {
        取消待行动作();
        待动类型 = 类别;

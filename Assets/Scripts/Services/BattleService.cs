using System.Collections.Generic;
using UnityEngine;

// 战斗服务：回合制战斗状态机。战斗单位统一抽象（玩家/敌人都是它），速度队列行动序，
// 伤害管线/状态(buff)/多敌人/敌人AI/结算回写 全在此驱动。UI 只订阅事件 + 调用行动入口，不直接改战斗数据。
// 进场投影(从玩家档案/敌人数据生成战斗单位) → 战斗 → 离场回写(生命/魔力/道具消耗/奖励)。
public sealed class BattleService
{
    private readonly EventBus 事件;
    private readonly DataService 数据;
    private readonly PlayerService 玩家服务;
    private 玩家档案 档案 => 玩家服务.档案;   // 动态取当前档案（新游戏/读档会替换实例，不能缓存旧引用）

    // —— 战斗状态 ——
    public bool 战斗中 { get; private set; }
    public int 回合数 { get; private set; }
    public 战斗单位 玩家 { get; private set; }
    public readonly List<战斗单位> 我方 = new List<战斗单位>();
    public readonly List<战斗单位> 敌方 = new List<战斗单位>();

    private readonly Queue<战斗单位> 行动队列 = new Queue<战斗单位>();
    private readonly List<战斗单位> 本回合行动列表 = new List<战斗单位>();   // 本回合完整速度序（信息条显示全轮）
    public 战斗单位 当前行动单位 { get; private set; }
    public int 当前行动索引 { get; private set; } = -1;
    // 玩家回合 = 轮到玩家本人（助战单位回合不算玩家回合，自动走 AI 推进）
    public bool 玩家回合 => 战斗中 && 当前行动单位 != null && 当前行动单位 == 玩家;

    // 本回合完整行动序（存活，速度序）：已行动在前、当前行动、后续排队 全显示
    public List<战斗单位> 本回合行动显示()
    {
        var 列表 = new List<战斗单位>();
        foreach (var u in 本回合行动列表) if (u.存活) 列表.Add(u);
        return 列表;
    }

    // 战斗结束衔接
    private string 胜利节点;
    private string 返回节点;
    private string 结果节点;
    private int 先手模式;   // 0=速度序 1=敌方先手 2=我方先手
    private readonly List<string> 消耗道具 = new List<string>();
    private int 累计金币, 累计经验;

    public string 当前消息 { get; private set; }

    // 增幅选择：玩家回合内当前蓄力的增幅级（0~3，影响下一次普攻/攻击技能倍率）
    public int 当前增幅 { get; private set; }

    private const string 危险色 = "#c7473d";

    public BattleService(EventBus 事件, DataService 数据, PlayerService 玩家服务)
    { this.事件 = 事件; this.数据 = 数据; this.玩家服务 = 玩家服务; }

    // ===== 开始战斗 =====
    // 先手：0=速度序（遇见） 1=敌方绝对先手（被偷袭） 2=我方绝对先手（偷袭）
    // 助战组：encounters 助战组标识（可选）；助战单位以 是否我方=true 加入我方，自动 AI 行动（轻量助战）
    public void 开始战斗(string 敌人组标识, string 胜利后节点, string 返回节点, int 先手 = 0, string 助战组标识 = "")
    {
        if (!数据.敌人组.TryGetValue(敌人组标识, out var 组))
        {
            Debug.LogError($"[战斗] 敌人组不存在: {敌人组标识}");
            return;
        }
        // 先激活战斗面板再开始布置/推进（面板需处于激活态才能渲染布阵、启动敌方停顿协程）；
        // 统一在此发布，剧情/探索/通路战斗 所有入口都能正确切入战斗面板。
        事件.发布(new 打开战斗事件(返回节点));
        this.胜利节点 = 胜利后节点; this.返回节点 = 返回节点;
        this.先手模式 = 先手;
        战斗中 = true; 回合数 = 0;
        我方.Clear(); 敌方.Clear(); 消耗道具.Clear(); 行动队列.Clear();
        累计金币 = 0; 累计经验 = 0; 当前行动单位 = null;
        var 玩家单位 = 战斗单位.从玩家投影(档案);
        玩家 = 玩家单位; 我方.Add(玩家单位);
        // 轻量助战：加入我方，AI 行动表自动出手（玩家不可手动操控；倒下无碍，玩家倒下=败）
        if (!string.IsNullOrEmpty(助战组标识) && 数据.助战组.TryGetValue(助战组标识, out var 助战组) && 助战组.成员 != null)
            foreach (var 项 in 助战组.成员)
            {
                if (!数据.敌人.TryGetValue(项.标识, out var 助)) continue;
                for (int i = 0; i < Mathf.Max(1, 项.数量); i++) 我方.Add(战斗单位.从助战生成(助));
            }
        if (组.敌人 != null)
            foreach (var 项 in 组.敌人)
            {
                if (!数据.敌人.TryGetValue(项.敌人, out var 敌)) continue;
                for (int i = 0; i < Mathf.Max(1, 项.数量); i++) 敌方.Add(战斗单位.从敌人生成(敌));
            }
        事件.发布(new 战斗开始事件(我方.ToArray(), 敌方.ToArray()));
        回合开始();
    }

    // ===== 回合循环 =====
    private void 回合开始()
    {
        回合数++;
        // 增幅点 BP：不随时间白送，改为事件驱动——命中弱点 / 造成破防 时由 奖励增幅点() 发放（见 造成伤害）
        // 回合开始：结算「开始」时机的持续伤害（中毒/灼烧）
        foreach (var 单位 in 全部单位())
        {
            int 毒伤 = 单位.持续伤害量("开始");
            if (毒伤 <= 0) continue;
            单位.受到伤害(毒伤);
            事件.发布(new 伤害事件(单位, 毒伤, 伤害类型.真实, false, false));
            发消息($"{名(单位)} 受到 <color={危险色}>{毒伤}</color> 点持续伤害。");
            检查单位死亡(单位);
        }
        if (检查战斗结束()) return;
        // 按速度降序生成本回合完整行动序（队列执行 + 信息条显示全轮）；先手方同速优先（偷袭/被偷袭）
        行动队列.Clear();
        本回合行动列表.Clear();
        本回合行动列表.AddRange(全部单位());
        本回合行动列表.Sort((a, b) =>
        {
            int 先 = 先手优先级(a).CompareTo(先手优先级(b));
            if (先 != 0) return 先;
            return b.当前速度.CompareTo(a.当前速度);
        });
        当前行动索引 = -1;
        foreach (var u in 本回合行动列表) 行动队列.Enqueue(u);
        事件.发布(new 回合开始事件(回合数));
        推进();
    }

    // 先手优先级：1=敌方绝对先手 / 2=我方绝对先手 / 0=纯速度序（同速比速度）
    private int 先手优先级(战斗单位 单位)
    {
        if (先手模式 == 1) return 单位.是否我方 ? 1 : 0;
        if (先手模式 == 2) return 单位.是否我方 ? 0 : 1;
        return 0;
    }

    // 弹出下一个可行动单位；玩家回合停下等操作，敌人回合跑AI
    private void 推进()
    {
        while (行动队列.Count > 0)
        {
            当前行动单位 = 行动队列.Dequeue();
            当前行动索引 = 本回合行动列表.IndexOf(当前行动单位);
            if (!当前行动单位.存活) continue;
            if (当前行动单位.无法行动)
            {
                发消息($"{名(当前行动单位)} 被眩晕，无法行动！");
                continue;
            }
            if (当前行动单位.破防)
            {
                // 破防晕眩：跳过本回合行动，随后恢复并重整护盾（破防结束）
                当前行动单位.破防 = false;
                if (当前行动单位.有护盾)
                {
                    当前行动单位.护盾 = 当前行动单位.护盾上限;
                    发消息($"{名(当前行动单位)} 从破防中恢复，护盾重整！");
                }
                continue;
            }
            事件.发布(new 行动轮换事件(当前行动单位, 当前行动单位.是否我方));
            return;   // 玩家回合等玩家输入；敌方回合等面板停顿后调用 继续()
        }
        回合结束();
    }

    // 面板在敌方/助战回合停顿后调用：执行当前单位行动（敌方=AI，助战=AI 自动），再推进
    public void 继续()
    {
        if (!战斗中 || 当前行动单位 == null) return;
        if (当前行动单位 == 玩家) return;
        if (!当前行动单位.存活) { 行动完成(); return; }
        敌人行动(当前行动单位);
        行动完成();
    }

    private void 回合结束()
    {
        // 回合结束：结算「结束」时机的持续伤害（蛇咬之刺等）
        foreach (var 单位 in 全部单位())
        {
            int 毒伤 = 单位.持续伤害量("结束");
            if (毒伤 <= 0) continue;
            单位.受到伤害(毒伤);
            事件.发布(new 伤害事件(单位, 毒伤, 伤害类型.真实, false, false));
            发消息($"{名(单位)} 受到 <color={危险色}>{毒伤}</color> 点毒噬伤害。");
            检查单位死亡(单位);
        }
        if (检查战斗结束()) return;
        foreach (var u in 全部单位()) u.回合结束();
        回合开始();
    }

    // ===== 玩家行动（面板调用入口） =====
    public void 玩家普攻(战斗单位 目标)
    {
        if (!玩家回合 || 目标 == null || !目标.存活) return;
        int 增幅 = 当前增幅;
        执行攻击(玩家, 目标, 增幅);
        结算增幅(增幅);
        行动完成();
    }

    public void 玩家技能(string 技能标识, 战斗单位 目标)
    {
        if (!玩家回合 || 目标 == null || !目标.存活) return;
        // 释放日志（无论成败都记录，便于定位技能链路；敌人/助战不刷屏）
        if (数据.技能.TryGetValue(技能标识, out var 技能))
           发消息($"你使用了技能《{技能.名称}》！");
        else
        {
            Debug.LogError($"[战斗] 玩家技能不存在: {技能标识}");
            return;
        }
        // 增幅倍率传入执行；成功释放（消耗回合）才扣 BP/归零，失败保留选择
        int 增幅 = 当前增幅;
        if (执行技能(玩家, 技能标识, 目标, 增幅)) { 结算增幅(增幅); 行动完成(); }
    }

    // 结算增幅：本次行动已消耗（普攻/成功技能），归零选择并扣 BP
    private void 结算增幅(int 增幅)
    {
        当前增幅 = 0;
        if (增幅 > 0) 玩家.BP = Mathf.Max(0, 玩家.BP - 增幅);
    }

    // 发放增幅点：命中弱点 / 造成破防 时奖励 +1（上限 3）；满格则静默
    private void 奖励增幅点(string 原因)
    {
        if (玩家 == null || 玩家.BP >= 战斗单位.BP上限) return;
        玩家.BP++;
        发消息($"增幅点 +1（{原因}，当前 {玩家.BP}/{战斗单位.BP上限}）。");
    }

    public void 玩家道具(string 物品标识, 战斗单位 目标)
    {
        if (!玩家回合 || 目标 == null) return;
        执行道具(玩家, 物品标识, 目标);
        行动完成();
    }

    public void 逃跑()
    {
        if (!玩家回合) return;
        int 敌速 = 0;
        foreach (var e in 敌方) if (e.存活 && e.基础速度 > 敌速) 敌速 = e.基础速度;
        float 概率 = Mathf.Clamp(0.5f + (玩家.基础速度 - 敌速) * 0.02f, 0.2f, 0.95f);
        if (Random.value < 概率) { 结束战斗(false, "你成功逃离了战斗。", 返回节点, false); return; }
        音效管理器.实例?.播放失败();
        发消息("逃跑失败！");
        行动完成();
    }

    // 切武器：消耗当前回合（与防御同级）。在主手↔副手武器之间切换当前持用武器，
    // 改变物理弱点判定用的武器种类（战斗内临时，不写回档案装备）。
    public void 切换武器()
    {
        if (!玩家回合) return;
        var 主手种 = 玩家.主手武器 != null ? (档案.武器种类解析?.Invoke(玩家.主手武器) ?? 武器种类.无) : 武器种类.无;
        var 副手种 = 玩家.副手武器 != null ? (档案.武器种类解析?.Invoke(玩家.副手武器) ?? 武器种类.无) : 武器种类.无;
        if (副手种 == 武器种类.无)
        {
            发消息("你没有可切换的第二把武器。");
            return;   // 无第二把武器（副手为盾/空）：不消耗回合
        }
        bool 切到副手 = 玩家.当前武器标识 == 玩家.主手武器;
        玩家.当前武器标识 = 切到副手 ? 玩家.副手武器 : 玩家.主手武器;
        玩家.当前武器 = 切到副手 ? 副手种 : 主手种;
        string 武器名 = 数据.物品.TryGetValue(玩家.当前武器标识, out var 物品) ? 物品.名称 : 玩家.当前武器标识;
        发消息($"你换持了「{武器名}」。（{玩家.当前武器}）");
        行动完成();   // 切换消耗当前回合
    }

    // 切换增幅等级：玩家回合内点击 0→1→2→3→0（消耗 BP 提升下一次普攻/攻击技能伤害）
    public void 切换增幅()
    {
        if (!玩家回合) return;
        当前增幅 = Mathf.Min(当前增幅 + 1, 战斗单位.BP上限);
        if (当前增幅 > 玩家.BP) 当前增幅 = 0;   // 攒到超过当前 BP → 归零重来
        发消息(当前增幅 > 0 ? $"增幅 ×{当前增幅}（消耗 {当前增幅} 增幅点，对下一次普攻/攻击技能生效）" : "增幅已取消。");
    }

    // ===== 敌人AI（P6） =====
    private void 敌人行动(战斗单位 敌人)
    {
        var 敌数据 = 敌人.源数据;
        string 行动 = 敌数据?.行动表 != null && 敌数据.行动表.Length > 0 ? AI抽行动(敌数据) : "普攻";
        // 治疗/增益类技能（我方单体/我方全体/自己 目标）：选友方（同伴）目标，否则会误治疗玩家
        战斗单位 目标;
        if (行动 != "普攻" && 数据.技能.TryGetValue(行动, out var 技能) && 技能.目标枚举 != 目标类型.敌方单体 && 技能.目标枚举 != 目标类型.敌方全体)
            目标 = AI选友方(敌人, 技能);
        else 目标 = AI选目标(敌人, 敌数据);
        if (行动 == "普攻") 执行攻击(敌人, 目标);
        else 执行技能(敌人, 行动, 目标);
    }

    // 治疗/增益选友方目标：同伴 = 与施法者同阵营；治疗选最残血，其余选第一个
    private 战斗单位 AI选友方(战斗单位 施法者, 技能数据 技能)
    {
        var 同伴 = 施法者.是否我方 ? 我方 : 敌方;
        var 存活 = 同伴.FindAll(u => u.存活);
        if (存活.Count == 0) return 施法者.是否我方 ? 玩家 : 敌方[0];
        if (技能.目标枚举 == 目标类型.自己) return 施法者;
        if (技能.目标枚举 == 目标类型.我方单体)
        {
            存活.Sort((a, b) => a.生命.CompareTo(b.生命));
            return 存活[0];
        }
        return 存活[0];
    }

    private string AI抽行动(敌人数据 敌数据)
    {
        int 总 = 0; foreach (var a in 敌数据.行动表) 总 += Mathf.Max(1, a.权重);
        int 掷 = Random.Range(0, 总);
        foreach (var a in 敌数据.行动表)
        {
            掷 -= Mathf.Max(1, a.权重);
            if (掷 < 0) return a.行动;
        }
        return "普攻";
    }

    private 战斗单位 AI选目标(战斗单位 敌人, 敌人数据 敌数据)
    {
        var 存活 = 我方.FindAll(u => u.存活);
        if (存活.Count == 0) return null;
        if (敌数据?.目标策略 == "残血")
        {
            存活.Sort((a, b) => a.生命.CompareTo(b.生命));
            return 存活[0];
        }
        return 存活[Random.Range(0, 存活.Count)];
    }

    // ===== 统一行动执行 =====
    // 增幅：消耗 1~3 BP 提升本次攻击倍率 ×(1+0.5×增幅)（敌人/助战增幅=0）
    private void 执行攻击(战斗单位 攻击者, 战斗单位 目标, int 增幅 = 0)
    {
        if (目标 == null || !目标.存活) return;
        int 倍率 = Mathf.RoundToInt(100f * (1f + 0.5f * 增幅));
        造成伤害(攻击者, 目标, 伤害类型.物理, 倍率, 0, 攻击者.当前武器);
    }

    // 执行技能：返回是否成功释放（资源不足/冷却中/专向不匹配 = false，调用方据此决定是否消耗回合）
    private bool 执行技能(战斗单位 施法者, string 技能标识, 战斗单位 目标, int 增幅 = 0)
    {
        if (!数据.技能.TryGetValue(技能标识, out var 技能)) return false;
        if (施法者.冷却剩余(技能标识) > 0)
        {
            if (施法者 == 玩家) 发消息($"《{技能.名称}》 还在冷却中！");
            return false;
        }
        // 武器规则（仅物理攻击技能）：专向=仅指定武器可用（不匹配则不消耗回合）；弱向=指定武器伤害↑、其余↓
        float 技能武器修正 = 1f;
        if (技能.类别枚举 == 技能类别.攻击 && 技能.伤害类型枚举 == 伤害类型.物理)
        {
            bool 匹配 = 施法者.当前武器 != 武器种类.无 && 施法者.当前武器 == 技能.武器种类枚举;
            if (技能.武器规则枚举 == 武器规则.专向 && !匹配)
            {
                if (施法者 == 玩家) 发消息($"《{技能.名称}》需要装备「{技能.武器种类}」才能使用！");
                return false;
            }
            if (技能.武器规则枚举 == 武器规则.弱向) 技能武器修正 = 匹配 ? 1.25f : 0.75f;
        }
        // 资源规则：物理派系技能耗精力，魔法派系技能耗魔力（格挡/猎人直觉 等增益类也按派系）
        bool 物理技能 = 技能.物理派系;
        bool 够资源 = 物理技能 ? 施法者.消耗精力(技能.消耗魔力) : 施法者.消耗魔力(技能.消耗魔力);
        if (!够资源)
        {
            if (施法者.是否我方) { 音效管理器.实例?.播放失败(); 发消息(物理技能 ? "精力不足！" : "魔力不足！"); }
            return false;
        }
        int 熟练 = 施法者.熟练等级(技能标识);
        float 品质倍 = 品质工具.倍率(技能.品质档);
        // 弱点判定参数：物理=施法者当前武器种类，魔法=技能五行
        武器种类 判断武器 = 技能.伤害类型枚举 == 伤害类型.物理 ? 施法者.当前武器 : 武器种类.无;
        五行 判断五行 = 技能.伤害类型枚举 == 伤害类型.魔法 ? 技能.五行枚举 : 五行.无;
        switch (技能.类别枚举)
        {
            case 技能类别.攻击:
                {
                    var 目标列表 = 技能目标列表(技能, 目标);   // 单体=1 / 敌方两名=2 / 全体=全部存活
                    switch (技能.伤害方式枚举)
                    {
                        case 技能伤害方式.固定:
                            // 固定伤害：无视角色的属性（力量/智力/装备加成），只打技能的固定数值；物理/魔法技能皆如此
                            {
                                int 固定值 = Mathf.Max(1, Mathf.RoundToInt(技能.数值));
                                foreach (var 敌 in 目标列表) 造成固定伤害(施法者, 敌, 固定值);
                                break;
                            }
                        case 技能伤害方式.附加:
                            // 附加伤害：在角色的伤害值上 + 数值（物理技能=物理伤害值，魔法技能=魔法伤害值）
                            {
                                int 附加 = Mathf.Max(1, Mathf.RoundToInt(技能.数值 * 技能武器修正 * (1f + 0.5f * 增幅)));
                                foreach (var 敌 in 目标列表) 造成伤害(施法者, 敌, 技能.伤害类型枚举, 100, 附加, 判断武器, 判断五行);
                                break;
                            }
                        default:
                            // 倍率伤害：角色伤害值 × 数值（物理技能=物攻，魔法技能=魔攻；受品质/熟练/防御/暴击/抗性影响）
                            {
                                int 倍率 = Mathf.RoundToInt(技能.数值 * 品质倍 * (1f + 熟练 * 技能.熟练伤害加成 / 100f) * 技能武器修正 * (1f + 0.5f * 增幅) * 100f);
                                foreach (var 敌 in 目标列表) 造成伤害(施法者, 敌, 技能.伤害类型枚举, 倍率, 0, 判断武器, 判断五行);
                                break;
                            }
                    }
                    附加Buff(施法者, 目标, 技能);   // 攻击技能可同时挂载减益（如 撕咬→中毒）
                    break;
                }
            case 技能类别.净化:
                // 净化：取消目标（友方）的随机一个减益
                {
                    var 净化目标 = 目标;
                    if (净化目标 != null && 净化目标.移除随机减益())
                    {
                        事件.发布(new 状态变化事件(净化目标, "", 0, 0, true));
                        发消息($"{名(施法者)} 施展《{技能.名称}》，清除了{名(净化目标)}身上的一个减益！");
                    }
                    else 发消息($"{名(施法者)} 施展《{技能.名称}》，{名(净化目标)}身上没有可清除的减益。");
                    break;
                }
            case 技能类别.治疗:
                {
                    int 恢复 = Mathf.Max(1, Mathf.RoundToInt(技能.数值 * 品质倍 * (1f + 熟练 * 技能.熟练伤害加成 / 100f)));
                    var 治疗目标 = 技能.目标枚举 == 目标类型.自己 ? 施法者 : 目标;
                    治疗目标.恢复生命(恢复);
                    事件.发布(new 治疗事件(治疗目标, 恢复));
                    发消息($"{名(施法者)} 施展《{技能.名称}》，{名(治疗目标)}恢复 {恢复} 点生命。");
                    break;
                }
            default:   // 增益 / 减益 / 控制：挂载 buff（目标=自己 时作用于施法者）
                附加Buff(施法者, 技能.目标枚举 == 目标类型.自己 ? 施法者 : 目标, 技能);
                break;
        }
        施法者.开始冷却(技能标识, 技能.冷却);
        // 仅玩家本人使用技能累积熟练度（助战单位不记）
        if (施法者 == 玩家 && 熟练 < 玩家档案.熟练等级上限)
            ServiceRegistry.Get<技能服务>().记录熟练度(技能标识, 1);
        return true;
    }

    // 技能攻击目标列表：单体=选中；敌方两名=选中 + 另一个存活敌人；全体=全部存活敌人
    private List<战斗单位> 技能目标列表(技能数据 技能, 战斗单位 选中)
    {
        var 列表 = new List<战斗单位>();
        if (选中 != null && 选中.存活) 列表.Add(选中);
        if (技能.目标枚举 == 目标类型.敌方全体)
        {
            foreach (var 敌 in 敌方)
                if (敌.存活 && !列表.Contains(敌)) 列表.Add(敌);
        }
        else if (技能.目标枚举 == 目标类型.敌方两名)
        {
            foreach (var 敌 in 敌方)
                if (敌.存活 && !列表.Contains(敌)) { 列表.Add(敌); break; }   // 补第二个目标
        }
        return 列表;
    }

    // 技能挂载 Buff（攻击技能也可携带减益，如 撕咬→中毒 / 骨刺→防御削弱）
    private void 附加Buff(战斗单位 施法者, 战斗单位 目标, 技能数据 技能)
    {
        if (string.IsNullOrEmpty(技能.挂载Buff) || !数据.Buffs.TryGetValue(技能.挂载Buff, out var buff)) return;
        目标.添加Buff(buff);
        var 实例 = 目标.Buffs.Find(b => b.定义.标识 == buff.标识);
        事件.发布(new 状态变化事件(目标, buff.标识, 实例?.层数 ?? 1, buff.持续回合, false));
        发消息($"{名(目标)} 获得「{buff.名称}」！");
    }

    private void 执行道具(战斗单位 使用者, string 物品标识, 战斗单位 目标)
    {
        if (!数据.物品.TryGetValue(物品标识, out var 物品) || !物品.战斗内使用) return;
        消耗道具.Add(物品标识);   // 记入消耗清单，结束统一扣档案（D14-B）
        switch (物品.使用效果枚举)
        {
            case 效果类型.恢复:
                {
                    int 恢复 = Mathf.Max(1, Mathf.RoundToInt(物品.恢复量 * 品质工具.倍率(物品.品质档)));
                    目标.恢复生命(恢复);
                    事件.发布(new 治疗事件(目标, 恢复));
                    发消息($"{名(使用者)} 使用{物品.名称}，恢复 {恢复} 点生命。");
                    break;
                }
            default:   // 增益 / 减益
                if (!string.IsNullOrEmpty(物品.挂载Buff) && 数据.Buffs.TryGetValue(物品.挂载Buff, out var buff))
                {
                    目标.添加Buff(buff);
                    事件.发布(new 状态变化事件(目标, buff.标识, 1, buff.持续回合, false));
                    发消息($"{名(目标)} 获得「{buff.名称}」！");
                }
                break;
        }
    }

    // ===== 统一伤害管线（全项目唯一伤害公式权威）=====
    // 普攻/技能伤害公式：物/魔 = 基础攻 × 倍率100/100 + 附加（下限 1）
    // 判定顺序：命中（攻方命中率 vs 目标闪避）→ 暴击（×1.5）→ 目标分支 → 下限 1
    // 敌方：防御→护盾量；弱点系数（弱1.0/非0.5）同时决定扣盾与血量有效输出；抗性仅在血量上再衰减；护盾归零→破防晕眩
    //   有效 = 基础×弱系数；扣盾=有效；血量=有效×抗性×(破防?1.5:1)
    // 我方/无盾目标：传统 基础×抗性 − 防御 减免
    private void 造成伤害(战斗单位 攻击者, 战斗单位 目标, 伤害类型 类型, int 倍率100, int 附加 = 0, 武器种类 攻方武器 = 武器种类.无, 五行 攻方五行 = 五行.无)
    {
        if (目标 == null || !目标.存活) return;
        // 命中判定：基础命中率 vs 目标当前闪避（敏捷 buff 生效）
        if (Random.value >= 攻击者.命中率 - 目标.当前闪避率)
        {
            事件.发布(new 伤害事件(目标, 0, 类型, false, true));
            发消息($"{名(目标)} 闪避了{名(攻击者)}的攻击！");
            return;
        }
        // 真实伤害：无视命中/攻防/暴击/抗性/护盾（毒/固定伤 走此路，直接结算）
        if (类型 == 伤害类型.真实)
        {
            int 真伤 = Mathf.Max(1, 倍率100 + 附加);
            目标.受到伤害(真伤);
            事件.发布(new 伤害事件(目标, 真伤, 类型, false, false));
            发消息($"{名(攻击者)}对{名(目标)}造成 {真伤} 点伤害。");
            检查单位死亡(目标);
            return;
        }
        bool 暴击 = Random.value < 攻击者.当前暴击率;
        bool 弱点 = 判弱点(攻击者, 目标, 类型, 攻方武器, 攻方五行);
        int 基础攻 = 类型 == 伤害类型.物理 ? 攻击者.当前物攻 : 攻击者.当前魔攻;
        int 基础伤害 = Mathf.Max(1, Mathf.RoundToInt(基础攻 * 倍率100 / 100f) + 附加);
        if (暴击) 基础伤害 = Mathf.RoundToInt(基础伤害 * 1.5f);

        int 伤害;
        bool 本次破防 = false;
        if (目标.有护盾)   // 敌方：防御→护盾量；弱点同时决定扣盾与生命的有效输出倍率
        {
            // 有效输出 = 基础 ×（命中弱点 1.0 / 未命中 0.5），血盾共用；抗性仅在血量上再衰减
            int 有效 = Mathf.Max(1, Mathf.RoundToInt(基础伤害 * 弱点系数(弱点)));
            if (目标.破防) 伤害 = Mathf.Max(1, Mathf.RoundToInt(有效 * 目标.抗性倍率(类型) * 1.5f));   // 破防易伤窗口
            else
            {
                伤害 = Mathf.Max(1, Mathf.RoundToInt(有效 * 目标.抗性倍率(类型)));   // 血量被抗性衰减
                目标.护盾 = Mathf.Max(0, 目标.护盾 - 有效);   // 扣盾仅按弱点系数，抗性不参与
                if (目标.护盾 <= 0)
                {
                    目标.破防 = true; 本次破防 = true;
                    发消息($"{名(目标)} 护盾破碎，陷入<color={危险色}>破防</color>晕眩！");
                }
            }
        }
        else   // 我方（玩家/助战）或无护盾敌人：传统固定防御减免（抗性作受伤害百分比衰减）
        {
            int 基础防 = 类型 == 伤害类型.物理 ? 目标.当前物防 : 目标.当前魔防;
            int 抗伤 = Mathf.Max(1, Mathf.RoundToInt(基础伤害 * 目标.抗性倍率(类型)));
            if (目标.抗性百分比 > 0)   // 玩家装备抗性：血量额外百分比衰减（非线性封顶 50%）
                抗伤 = Mathf.Max(1, Mathf.RoundToInt(抗伤 * (1f - 目标.抗性百分比 / 100f)));
            伤害 = Mathf.Max(1, 抗伤 - 基础防);
        }
        伤害 = Mathf.Max(1, 伤害);
        目标.受到伤害(伤害);
        事件.发布(new 伤害事件(目标, 伤害, 类型, 暴击, false));
        string 弱点标 = 弱点 ? "<color=#e0b84a>弱点！</color>" : "";
        发消息($"{弱点标}{(暴击 ? "<color=#e0b84a>暴击！</color>" : "")}{名(攻击者)}对{名(目标)}造成 {伤害} 点伤害。");
        // 增幅点奖励（仅玩家本人）：命中弱点 +1；本击造成破防 +1（与弱点可叠加，但同一击只各加一次）
        if (攻击者 == 玩家)
        {
            if (弱点) 奖励增幅点("命中弱点");
            if (本次破防) 奖励增幅点("造成破防");
        }
        检查单位死亡(目标);
    }

    // 弱点系数：命中弱点=满效（×1.0），未命中=减半（×0.5），同时作用于扣盾与血量；抗性只额外衰减血量
    private float 弱点系数(bool 弱点)
    {
        return 弱点 ? 1.0f : 0.5f;
    }

    // 弱点判定：仅我方命中敌方有效（敌人打玩家/助战无弱点）。
    // 物理弱点 = 命中武器种类 ∈ 目标物理弱点；魔法弱点 = 技能五行克制目标五行。
    private bool 判弱点(战斗单位 攻击者, 战斗单位 目标, 伤害类型 类型, 武器种类 攻方武器, 五行 攻方五行)
    {
        if (!攻击者.是否我方 || 目标.是否我方 || !目标.有护盾) return false;
        if (类型 == 伤害类型.物理) return 攻方武器 != 武器种类.无 && 目标.物理弱点.Contains(攻方武器);
        if (类型 == 伤害类型.魔法) return 五行工具.克制(攻方五行, 目标.五行属性);
        return false;
    }

    // 固定伤害：不受任何因素影响（无视命中/攻防/暴击/抗性），只打出固定数值
    private void 造成固定伤害(战斗单位 攻击者, 战斗单位 目标, int 数值)
    {
        if (目标 == null || !目标.存活) return;
        int 伤害 = Mathf.Max(1, 数值);
        目标.受到伤害(伤害);
        事件.发布(new 伤害事件(目标, 伤害, 伤害类型.真实, false, false));
        发消息($"{名(攻击者)}对{名(目标)}造成 {伤害} 点固定伤害。");
        检查单位死亡(目标);
    }

    private void 检查单位死亡(战斗单位 单位)
    {
        if (单位.存活) return;
        if (单位.是否我方) 我方.Remove(单位);
        else { 敌方.Remove(单位); 结算单个敌人(单位); }
        事件.发布(new 目标变化事件(单位));
        发消息($"{名(单位)} 倒下了！");
    }

    // ===== 胜利结算（每死一个敌人即时结算；末日以物易物：掉落补给而非金币） =====
    private void 结算单个敌人(战斗单位 敌人)
    {
        var 敌 = 敌人.源数据;
        if (敌 == null) return;
        // 货币奖励 → 掉落补给（面包/水，按价值折算）
        int 补给值 = 敌.货币奖励 > 0 ? 敌.货币奖励 : 0;
        int 面包数 = 0, 水数 = 0;
        if (补给值 > 0)
        {
            面包数 = 补给值 / 4;
            水数 = 补给值 / 8;
            if (面包数 > 0) { 档案.添加物品("面包", 面包数); 事件.发布(new 背包变化事件("面包", 面包数, 变化原因.获得)); }
            if (水数 > 0) { 档案.添加物品("水", 水数); 事件.发布(new 背包变化事件("水", 水数, 变化原因.获得)); }
        }
        bool 升级 = 档案.获得经验(敌.经验奖励); 累计经验 += 敌.经验奖励;
        事件.发布(new 经验变化事件(档案.等级, 档案.经验, 档案.升级所需经验, 升级));
        if (升级) 事件.发布(new 属性变化事件(档案.体质, 档案.力量, 档案.智慧, 档案.敏捷, 档案.意志, 档案.自由属性点));
        if (!string.IsNullOrEmpty(敌.掉落物品) && Random.value < 敌.掉落概率)
        {
            // 掉落装备 → 随机词缀实例；非装备 → 普通堆叠
            if (数据.物品.TryGetValue(敌.掉落物品, out var 掉物))
            {
                var 词缀 = ServiceRegistry.Get<词缀服务>()?.生成(掉物);
                if (词缀 != null) 档案.添加堆叠(new 物品堆叠(敌.掉落物品, 1) { 词缀 = 词缀 });
                else 档案.添加物品(敌.掉落物品, 1);
            }
            else 档案.添加物品(敌.掉落物品, 1);
            事件.发布(new 背包变化事件(敌.掉落物品, 1, 变化原因.获得));
        }
        ServiceRegistry.Get<QuestService>().记录击败(敌.标识);
        string 补给文本 = 面包数 > 0 || 水数 > 0 ? $"、面包×{面包数}、水×{水数}" : "";
        发消息($"击败 <color={游戏主题.危险色值}>{敌.名称}</color> ！获得{补给文本}{敌.经验奖励} 经验。");
    }

    // ===== 行动完成 → 推进/结束 =====
    private void 行动完成()
    {
        if (检查战斗结束()) return;
        推进();
    }

    private bool 检查战斗结束()
    {
        if (!战斗中) return true;
        if (敌方.Count == 0) { 结束战斗(true, $"战斗胜利！共获得 {累计经验} 经验与补给。", 胜利节点); return true; }
        // 玩家本人倒下=失败（助战单位倒下无碍，仍继续战斗）
        if (玩家 == null || !玩家.存活) { 结束战斗(false, "你被击败了……", 返回节点); return true; }
        return false;
    }

    // ===== 战斗结束 + 离场回写 =====
    private void 结束战斗(bool 胜利, string 文本, string 进入节点, bool 惩罚 = true)
    {
        战斗中 = false;
        结果节点 = 进入节点;
        if (胜利) { }
        else if (惩罚 && 结果节点 == 返回节点) 结算失败惩罚();
        结算回写();
        事件.发布(new 战斗结束事件(胜利, 文本));
    }

    // 失败惩罚：末日版——掉 10% 价值物资 + 回营地半状态（不再满血复活）
    private void 结算失败惩罚()
    {
        // 以物易物经济：损失 10% 背包物资（按价值最贵的优先）
        int 损失件数 = 档案.背包.Count > 0 ? Mathf.Max(1, 档案.背包.Count / 10) : 0;
        for (int i = 0; i < 损失件数 && 档案.背包.Count > 0; i++)
        {
            var 堆叠 = 档案.背包[档案.背包.Count - 1];
            档案.移除物品(堆叠.标识, 1);
            事件.发布(new 背包变化事件(堆叠.标识, -1, 变化原因.失去));
        }
        档案.生命 = Mathf.Max(1, 档案.最大生命 / 2);
        档案.行动点 = Mathf.Max(1, 档案.最大行动点 / 2);
        事件.发布(new 生命变化事件(档案.生命, 档案.最大生命, 档案.生命));
        事件.发布(new 精力变化事件(档案.行动点, 档案.最大行动点, 档案.行动点));
        发消息($"你被击倒了，丢了随身的一些东西，挣扎着逃回安全处。");
    }

    // 离场回写：生命/行动点 + 道具消耗统一扣；Buff/临时状态丢弃（战斗外无临时buff）
    private void 结算回写()
    {
        档案.生命 = 玩家.生命;
        档案.行动点 = 玩家.行动点;   // 战斗消耗的行动点随战斗保留（探索血线张力）
        foreach (var 标识 in 消耗道具) 档案.移除物品(标识);
        消耗道具.Clear();
    }

    // 战斗结束后面板 [继续]：进入结果节点
    public void 返回()
    {
        if (结果节点 == "__探索胜利") { ServiceRegistry.Get<探索服务>().战斗胜利(); return; }
        if (结果节点 == "__探索返回") { ServiceRegistry.Get<探索服务>().战斗逃跑(); return; }
        if (!string.IsNullOrEmpty(结果节点)) ServiceRegistry.Get<DialogueService>().进入节点(结果节点);
    }

    private List<战斗单位> 全部单位()
    {
        var 列表 = new List<战斗单位>();
        列表.AddRange(我方); 列表.AddRange(敌方);
        return 列表;
    }

    private void 发消息(string 文本)
    {
        当前消息 = 文本;
        事件.发布(new 日志事件(日志类型.战斗, 文本));
    }

    // 单位名预处理：我方=正常色、敌方=血红；名称左右各留一个空格分隔
    private static string 名(战斗单位 单位)
    {
        if (单位 == null) return " ？？？ ";
        if (单位.是否我方) return $" {单位.名称} ";
        return $" <color={游戏主题.危险色值}>{单位.名称}</color> ";
    }

using System.Collections.Generic;
using UnityEngine;

// 战斗服务：回合制战斗状态机。战斗单位统一抽象（玩家/敌人都是它），速度队列行动序，
// 伤害管线/状态(buff)/多敌人/敌人AI/结算回写 全在此驱动。UI 只订阅事件 + 调用行动入口，不直接改战斗数据。
// 进场投影(从玩家档案/敌人数据生成战斗单位) → 战斗 → 离场回写(生命/魔力/道具消耗/奖励)。
public sealed class BattleService
{
    private readonly EventBus 事件;
    private readonly DataService 数据;
    private readonly PlayerService 玩家服务;
    private 玩家档案 档案 => 玩家服务.档案;   // 动态取当前档案（新游戏/读档会替换实例，不能缓存旧引用）

    // —— 战斗状态 ——
    public bool 战斗中 { get; private set; }
    public int 回合数 { get; private set; }
    public 战斗单位 玩家 { get; private set; }
    public readonly List<战斗单位> 我方 = new List<战斗单位>();
    public readonly List<战斗单位> 敌方 = new List<战斗单位>();

    // —— 战斗沙盒（即时制 + 节点式轨道） ——
    public int 棋盘宽 { get; private set; } = 12;   // 轨道节点数（横向战线：0 ~ 棋盘宽-1）；节点间前后移动，无行维度
    public float 战斗分钟 { get; private set; }   // 本回合已累计分钟（满 60 结算一轮）
    public const float 每现实秒游戏分钟 = 1f;      // 战斗时间流速：1 现实秒 = 1 游戏分钟（2 倍正常流速，可调）

    // 战斗结束衔接
    private string 胜利节点;
    private string 返回节点;
    private string 结果节点;
    private int 先手模式;   // 0=速度序 1=敌方先手 2=我方先手
    private readonly List<string> 消耗道具 = new List<string>();
    private int 累计金币, 累计经验;
    private readonly List<物品堆叠> 尸体战利品 = new List<物品堆叠>();   // 胜利 战利品（进 尸体 供 搜索，不 直接 入包）

    public string 当前消息 { get; private set; }

    private const string 危险色 = "#c7473d";

    public BattleService(EventBus 事件, DataService 数据, PlayerService 玩家服务)
    { this.事件 = 事件; this.数据 = 数据; this.玩家服务 = 玩家服务; }

    // ===== 开始战斗（即时制：棋盘 + 行动条） =====
    // 先手：0=速度序（遇见） 1=敌方绝对先手（被偷袭） 2=我方绝对先手（偷袭）
    // 助战组：encounters 助战组标识（可选）；助战单位以 是否我方=true 加入我方，自动 AI 行动（轻量助战）
    public void 开始战斗(string 敌人组标识, string 胜利后节点, string 返回节点, int 先手 = 0, string 助战组标识 = "")
    {
        if (!数据.敌人组.TryGetValue(敌人组标识, out var 组))
        {
            Debug.LogError($"[战斗] 敌人组不存在: {敌人组标识}");
            return;
        }
        // 先激活战斗面板再开始布置（面板需处于激活态才能渲染布阵）；剧情/探索 所有入口统一切入。
        事件.发布(new 打开战斗事件(返回节点));
        this.胜利节点 = 胜利后节点; this.返回节点 = 返回节点;
        this.先手模式 = 先手;
        战斗中 = true; 回合数 = 1; 战斗分钟 = 0f;
        我方.Clear(); 敌方.Clear(); 消耗道具.Clear();
        累计金币 = 0; 累计经验 = 0;
        尸体战利品.Clear();
        取消待行动作();   // 新 战斗 清 残留 蓄力
        var 玩家单位 = 战斗单位.从玩家投影(档案);
        玩家 = 玩家单位; 我方.Add(玩家单位);
        // 轻量助战：加入我方，AI 行动表自动出手（玩家不可手动操控；倒下无碍，玩家倒下=败）
        if (!string.IsNullOrEmpty(助战组标识) && 数据.助战组.TryGetValue(助战组标识, out var 助战组) && 助战组.成员 != null)
            foreach (var 项 in 助战组.成员)
            {
                if (!数据.敌人.TryGetValue(项.标识, out var 助)) continue;
                for (int i = 0; i < Mathf.Max(1, 项.数量); i++) 我方.Add(战斗单位.从助战生成(助));
            }
        if (组.敌人 != null)
            foreach (var 项 in 组.敌人)
            {
                if (!数据.敌人.TryGetValue(项.敌人, out var 敌)) continue;
                for (int i = 0; i < Mathf.Max(1, 项.数量); i++) 敌方.Add(战斗单位.从敌人生成(敌));
            }
        // 玩家攻击距离按当前武器射程；棋盘与落位先于 战斗开始事件（面板订阅事件布阵时数据已就绪）
        玩家.攻击距离 = 武器攻击距离(玩家.当前武器标识);
        刷新玩家速率();   // 敏捷 + 武器攻速/装备移速（含 重型 负面）→ 攻速/移速倍率
        初始化棋盘();
        落位单位(先手);
        事件.发布(new 战斗开始事件(我方.ToArray(), 敌方.ToArray()));
    }

    // 轨道生成：节点数 = 战斗棋盘.宽（默认 12）；无行维度、无障碍物——单位沿节点前后移动
    private void 初始化棋盘()
    {
        if (数据.战斗棋盘.TryGetValue("街头", out var 默认)) 棋盘宽 = Mathf.Max(4, 默认.宽);
    }

    // 落位：我方节点 0，敌方节点 棋盘宽-1（同节点多单位重叠，视觉错位由轨道面板处理）
    private void 落位单位(int 先手)
    {
        int 我方列 = 0, 敌方列 = 棋盘宽 - 1;
        if (数据.战斗棋盘.TryGetValue("街头", out var 棋盘)) 敌方列 = Mathf.Max(我方列 + 1, 棋盘.宽 - 1);
        if (先手 == 1)   // 被偷袭：敌方先手（行动条领先）
        {
            foreach (var 敌 in 敌方) 敌.行动条 = 60f;
            foreach (var 我 in 我方) 我.行动条 = 0f;
        }
        else if (先手 == 2)  // 偷袭：我方先手
        {
            foreach (var 敌 in 敌方) 敌.行动条 = 0f;
            foreach (var 我 in 我方) 我.行动条 = 60f;
        }
        落位一侧(我方, 我方列);
        落位一侧(敌方, 敌方列);
    }

    private void 落位一侧(List<战斗单位> 单位组, int 列)
    {
        foreach (var 单位 in 单位组) 单位.列 = 列;   // 同节点重叠（视觉错位 面板 处理）
    }

    // ===== 即时制核心：时间推进 → 行动条 → 轮次结算 → 满条自动行动 =====

    // 战斗推进（面板每帧调用）：推进世界时间 + 行动条累积 + 轮次结算 + 满条行动。
    // 战斗中挂机驱动暂停（世界时间管理器.驱动 检查 战斗中），时间只在此推进，避免双时钟。
    // 战斗中不结算生存（饱食/水分/伤病 暂停——战斗冲突中不吃不喝也不扣），仅推进时间并同步整点基准（防挂机恢复时补结算战斗期间）。
    public void 推进战斗(float 现实秒)
    {
        if (!战斗中 || 现实秒 <= 0f) return;
        float 游戏分钟 = 现实秒 * 每现实秒游戏分钟;
        // 世界时间：推进档案分钟（不结算生存）+ 同步整点基准 + 时间事件
        var 档案实例 = 档案;
        if (档案实例 != null)
        {
            档案实例.游戏分钟数 += 游戏分钟;
            ServiceRegistry.Get<世界时间管理器>()?.同步整点基准();
            事件.发布(new 时间变化事件(档案实例.游戏分钟数));
        }
        // 行动条累积：每轮 先 锁 意图（读条 = 意图，颜色 由 意图 决定），按 意图 间隔（现实 秒）匀速 推进——满 100 = 一次 行动
        foreach (var 单位 in 全部单位())
        {
            if (!单位.存活) continue;
            // 受控（眩晕/定身 类 Buff 或 眩晕秒）：读条 冻结 + 意图 作废 + 玩家 蓄力 预约 一并 取消（被控 = 断 一切 读条）
            if (单位.无法行动)
            {
                if (单位.眩晕剩余秒 > 0f) 单位.眩晕剩余秒 = Mathf.Max(0f, 单位.眩晕剩余秒 - 现实秒);   // 眩晕 秒制 倒计时
                if (单位.行动条 > 0.01f) 中断读条(单位, null);
                else if (单位 == 玩家 && 待动类型 != 待动类别.无) 取消待行动作();
                continue;
            }
            if (!单位.意图已选) { 选定下一意图(单位); 单位.意图已选 = true; }
            float 每秒填充 = 100f / 意图间隔秒(单位);
            单位.行动条 = Mathf.Min(200f, 单位.行动条 + 每秒填充 * 现实秒);
        }
        // 技能冷却：现实秒 逐帧 推进（真实时间 等待，不受 游戏时间 倍率 影响）
        foreach (var 单位 in 全部单位())
            if (单位.存活) 单位.推进冷却(现实秒);
        // 轮次结算：每满 60 分钟 一轮（buff/持续伤害 计时）
        战斗分钟 += 游戏分钟;
        while (战斗分钟 >= 60f)
        {
            战斗分钟 -= 60f;
            轮次结算();
            if (!战斗中) return;
        }
        处理满条行动();
    }

    // 轮次结算：等价旧"回合结束 + 回合开始"的副作用（持续伤害/buff/冷却/无敌），不操作行动队列
    private void 轮次结算()
    {
        回合数++;
        // 持续伤害「结束」时机
        foreach (var 单位 in 全部单位())
        {
            int 毒伤 = 单位.持续伤害量("结束");
            if (毒伤 <= 0) continue;
            单位.受到伤害(毒伤);
            事件.发布(new 伤害事件(单位, 毒伤, 伤害类型.真实, false, false));
            发消息($"{名(单位)} 受到 {毒伤} 点毒噬伤害。");
            检查单位死亡(单位);
        }
        if (检查战斗结束()) return;
        // buff/冷却/无敌 计时递减
        foreach (var 单位 in 全部单位()) 单位.回合结束();
        // 持续伤害「开始」时机
        foreach (var 单位 in 全部单位())
        {
            int 毒伤 = 单位.持续伤害量("开始");
            if (毒伤 <= 0) continue;
            单位.受到伤害(毒伤);
            事件.发布(new 伤害事件(单位, 毒伤, 伤害类型.真实, false, false));
            发消息($"{名(单位)} 受到 {毒伤} 点持续伤害。");
            检查单位死亡(单位);
        }
        if (检查战斗结束()) return;
    }

    // 满条行动：按行动条值降序（溢出多=等待久）逐个执行自动行动
    private void 处理满条行动()
    {
        while (战斗中)
        {
            战斗单位 待动 = null;
            foreach (var 单位 in 全部单位())
                if (单位.存活 && 单位.行动条 >= 100f && (待动 == null || 单位.行动条 > 待动.行动条)) 待动 = 单位;
            if (待动 == null) break;
            单位自动行动(待动);
        }
    }

    // —— 行动 间隔（现实 秒 = 一次 行动 用时）——
    // 玩家：移动/技能/攻击 一律 5 秒（无 加成 基准）；装备 移速 / 武器 攻速 倍率 = 预留 钩子
    // 敌人：无 装备，天然 按 敌人数据 设定 的 移动/攻击/技能 间隔（三类 各自 不同）
    private float 意图间隔秒(战斗单位 单位)
    {
        float 间隔 = 单位.当前意图 switch
        {
            战斗单位.意图类型.攻击 => 单位.攻击间隔秒,
            战斗单位.意图类型.技能 => 单位.技能间隔秒,
            _ => 单位.移动间隔秒,   // 移动 / 戒备
        };
        float 倍率 = 单位 == 玩家
            ? (单位.当前意图 == 战斗单位.意图类型.攻击 ? 单位.攻速倍率
                : 单位.当前意图 == 战斗单位.意图类型.移动 ? 单位.移速倍率 : 1f)
            : 1f;
        return Mathf.Max(0.5f, 间隔 / Mathf.Max(0.1f, 倍率));
    }

    // 意图 选定（读条 开始 时；满条 前 不变；受控 不 换）
    private void 选定下一意图(战斗单位 单位)
    {
        if (单位.无法行动) return;
        if (单位 == 玩家) { 选定玩家意图(单位); return; }
        选定敌人意图(单位);
    }

    private void 选定玩家意图(战斗单位 玩)
    {
        if (待动类型 != 待动类别.无) { 玩.当前意图 = 战斗单位.意图类型.技能; 玩.意图技能 = 待动标识; return; }   // 蓄力 技能/道具
        玩.意图技能 = null;
        玩.当前意图 = 可攻击目标(玩) != null ? 战斗单位.意图类型.攻击 : 战斗单位.意图类型.移动;
    }

    private void 选定敌人意图(战斗单位 敌)
    {
        var 源 = 敌.源数据;
        // 技能：行动表 有 技能 且 就绪 → 技能 意图（读条 大招；执行 时 再 校验）
        if (源?.行动表 != null && 源.行动表.Length > 0)
        {
            string 动作 = AI抽行动(源);
            if (!string.IsNullOrEmpty(动作) && 动作 != "普攻" && 数据.技能.TryGetValue(动作, out _) && 敌.冷却剩余(动作) <= 0f)
            {
                敌.当前意图 = 战斗单位.意图类型.技能; 敌.意图技能 = 动作; return;
            }
        }
        敌.意图技能 = null;
        if (敌.移动AI == "驻守") { 敌.当前意图 = 战斗单位.意图类型.戒备; return; }
        敌.当前意图 = 可攻击目标(敌) != null ? 战斗单位.意图类型.攻击 : 战斗单位.意图类型.移动;
    }

    // 自动行动：满条触发——按 读条 期 锁定 的 意图 执行（不再 临场 改招）
    private void 单位自动行动(战斗单位 单位)
    {
        if (!战斗中) return;
        单位.行动条 = 0f;
        if (!单位.存活) return;
        if (单位.无法行动) { 发消息($"{名(单位)} 被控制，无法行动！"); return; }
        单位.防御姿态 = false;   // 清上一轮防御（防御持续到下次行动）
        // 待行动作：玩家 蓄力 满条 → 完成（技能/道具）；失败 落 回 自动
        if (单位 == 玩家 && 待动类型 != 待动类别.无 && 完成待行动作()) { 单位.意图已选 = false; 检查战斗结束(); return; }
        if (单位 == 玩家 && 待动类型 == 待动类别.无 && 单位.当前意图 == 战斗单位.意图类型.技能)
        {
            // 蓄力 已 被 取消/落空：本 次 按 常规 出手（不再 按 技能 意图）
            单位.意图技能 = null;
            单位.当前意图 = 可攻击目标(单位) != null ? 战斗单位.意图类型.攻击 : 战斗单位.意图类型.移动;
        }
        switch (单位.当前意图)
        {
            case 战斗单位.意图类型.技能:
                执行技能意图(单位);
                break;
            case 战斗单位.意图类型.移动:
                自动移动(单位);
                break;
            case 战斗单位.意图类型.戒备:
                {
                    var 目标 = 可攻击目标(单位);
                    if (目标 != null) 自动攻击(单位, 目标);   // 驻守：来犯 才 出手
                    break;
                }
            default:   // 攻击：射程 内 出手；目标 脱身 → 趁机 逼近
                {
                    var 目标 = 可攻击目标(单位);
                    if (目标 != null)
                    {
                        if (单位.行动模式 == 1) 触发防御(单位);
                        else 自动攻击(单位, 目标);
                    }
                    else 自动移动(单位);
                    break;
                }
        }
        单位.意图已选 = false;   // 满条 已 执行 → 下轮 重锁
        检查战斗结束();
    }

    // 技能 意图 执行：锁 的 技能 就绪 且 目标 合法 → 释放；否则 落 回 移动（逼近/走位）
    private void 执行技能意图(战斗单位 施法者)
    {
        string 标识 = 施法者.意图技能;
        施法者.意图技能 = null;
        var 目标 = 可攻击目标(施法者);
        if (string.IsNullOrEmpty(标识) || !数据.技能.TryGetValue(标识, out var 技能数据) || 施法者.冷却剩余(标识) > 0f)
        { 自动移动(施法者); return; }
        if (目标 != null && 技能目标合法(技能数据, 施法者, 目标) && 执行技能(施法者, 标识, 目标)) return;
        自动移动(施法者);
    }

    // 射程内有目标（距离 = 节点差 ≤ 攻击距离；轨道无障碍，无需视线）
    private 战斗单位 可攻击目标(战斗单位 单位)
    {
        战斗单位 最近 = null; int 最近距 = int.MaxValue;
        foreach (var 敌 in 对方阵营(单位))
        {
            if (!敌.存活) continue;
            int 距 = Mathf.Abs(单位.列 - 敌.列);
            if (距 > 单位.攻击距离) continue;
            if (距 < 最近距) { 最近 = 敌; 最近距 = 距; }
        }
        return 最近;
    }

    private List<战斗单位> 对方阵营(战斗单位 单位) => 单位.是否我方 ? 敌方 : 我方;

    // 自动攻击：按行动表抽行动（敌人可用技能；玩家无行动表=普攻）；技能超出射程则退回普攻
    private void 自动攻击(战斗单位 攻击者, 战斗单位 目标)
    {
        string 行动 = 攻击者.源数据?.行动表 != null && 攻击者.源数据.行动表.Length > 0 ? AI抽行动(攻击者.源数据) : "普攻";
        if (行动 != "普攻" && 数据.技能.TryGetValue(行动, out var 技能))
        {
            if (技能目标合法(技能, 攻击者, 目标)) { 执行技能(攻击者, 行动, 目标); return; }
        }
        执行攻击(攻击者, 目标);
    }

    // 自动移动（节点式轨道）：玩家按 运动模式（前进/等待/后退）；敌人按 移动AI（冲锋/风筝/驻守）。
    // 停止规则：无论敌我，前方节点被敌方单位占据 → 停在相邻节点（不越过、不重叠——贴脸对峙）
    private void 自动移动(战斗单位 单位)
    {
        int 方向 = 0;   // +1 前进（节点+1）/ -1 后退（节点-1）/ 0 不动
        if (单位.是否我方)
        {
            if (单位.运动模式 == 1) return;   // 原地等待
            var 敌 = 最近敌人(单位);
            if (敌 == null) return;
            方向 = 单位.运动模式 == 0 ? (敌.列 > 单位.列 ? 1 : -1) : (敌.列 < 单位.列 ? 1 : -1);
        }
        else
        {
            var 玩 = 玩家;
            if (玩 == null || !玩.存活) return;
            switch (单位.移动AI)
            {
                case "驻守": return;
                case "风筝":
                    {
                        int 距 = Mathf.Abs(单位.列 - 玩.列);
                        if (距 > 单位.攻击距离) 方向 = 玩.列 > 单位.列 ? 1 : -1;   // 逼近到射程边缘
                        else if (距 <= 1) 方向 = 玩.列 < 单位.列 ? 1 : -1;         // 被贴脸 → 拉远
                        else return;   // 射程内站桩输出
                        break;
                    }
                default: 方向 = 玩.列 > 单位.列 ? 1 : -1; break;   // 冲锋
            }
        }
        if (方向 == 0) return;
        int 目标列 = 单位.列 + 方向;
        if (目标列 < 0 || 目标列 >= 棋盘宽) return;
        foreach (var 敌 in 对方阵营(单位))
            if (敌.存活 && 敌.列 == 目标列) return;   // 前方节点被敌方占据 → 停（贴脸）
        单位.列 = 目标列;
    }

    private 战斗单位 最近敌人(战斗单位 单位)
    {
        战斗单位 最近 = null; int 最近距 = int.MaxValue;
        foreach (var 敌 in 对方阵营(单位))
        {
            if (!敌.存活) continue;
            int 距 = Mathf.Abs(单位.列 - 敌.列);
            if (距 < 最近距) { 最近 = 敌; 最近距 = 距; }
        }
        return 最近;
    }


        if (目标 == null || !目标.存活) return false;
        if (!道具目标合法(物品, 目标)) { 发消息("这个物品的目标不在射程内。"); return false; }
        预约待行动作(待动类别.道具, 物品标识, 目标, $"你开始使用「{物品.标识}」……蓄力完成后生效。");
        return true;

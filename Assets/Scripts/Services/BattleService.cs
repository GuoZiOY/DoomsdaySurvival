    public void 逃跑()
    {
        if (!战斗中 || 玩家 == null || !玩家.存活) return;
        int 敌速 = 0;
        foreach (var e in 敌方) if (e.存活 && e.基础速度 > 敌速) 敌速 = e.基础速度;
        float 概率 = Mathf.Clamp(0.5f + (玩家.基础速度 - 敌速) * 0.02f, 0.2f, 0.95f);
        if (Random.value < 概率) { 结束战斗(false, "你成功逃离了战斗。", 返回节点, false); return; }
        音效管理器.实例?.播放失败();
        发消息("逃跑失败！");
        重置行动条(玩家);   // 逃跑 = 主动操作：重置行动条
        // 失败惩罚：所有存活敌人立即行动一次
        foreach (var 敌 in new List<战斗单位>(敌方)) if (敌.存活) 单位自动行动(敌);
    }

    // 切武器（即时制）：主手↔副手 切换当前持用武器，改变 近/远程伤害类型 与 攻击射程；重置行动条
    public void 切换武器()
    {
        if (!战斗中 || 玩家 == null || !玩家.存活) return;
        var 主手种 = 玩家.主手武器 != null ? (档案.武器种类解析?.Invoke(玩家.主手武器) ?? 武器种类.无) : 武器种类.无;
        var 副手种 = 玩家.副手武器 != null ? (档案.武器种类解析?.Invoke(玩家.副手武器) ?? 武器种类.无) : 武器种类.无;
        if (副手种 == 武器种类.无)
        {
            发消息("你没有可切换的第二把武器。");
            return;   // 无第二把武器（副手为盾/空）：不重置行动条
        }
        bool 切到副手 = 玩家.当前武器标识 == 玩家.主手武器;
        玩家.当前武器标识 = 切到副手 ? 玩家.副手武器 : 玩家.主手武器;
        玩家.当前武器 = 切到副手 ? 副手种 : 主手种;
        玩家.攻击距离 = 武器攻击距离(玩家.当前武器标识);   // 射程随武器变化
        刷新玩家速率();   // 攻速倍率 随 当前 武器 变化（切 重武器 → 攻 变 慢）
        string 武器名 = 数据.物品.TryGetValue(玩家.当前武器标识, out var 物品) ? 物品.标识 : 玩家.当前武器标识;
        发消息($"你换持了「{武器名}」。（{玩家.当前武器}）");
        重置行动条(玩家);   // 切换消耗蓄力
    }

    // ===== 敌人AI（P6） =====
    private void 敌人行动(战斗单位 敌人)
    {
        var 敌数据 = 敌人.源数据;
        string 行动 = 敌数据?.行动表 != null && 敌数据.行动表.Length > 0 ? AI抽行动(敌数据) : "普攻";
        // 治疗/增益类技能（我方单体/我方全体/自己 目标）：选友方（同伴）目标，否则会误治疗玩家
        战斗单位 目标;
        if (行动 != "普攻" && 数据.技能.TryGetValue(行动, out var 技能) && 技能.目标枚举 != 目标类型.敌方单体 && 技能.目标枚举 != 目标类型.敌方全体)
            目标 = AI选友方(敌人, 技能);
        else 目标 = AI选目标(敌人, 敌数据);
        if (行动 == "普攻") 执行攻击(敌人, 目标);
        else 执行技能(敌人, 行动, 目标);
    }

    // 治疗/增益选友方目标：同伴 = 与施法者同阵营；治疗选最残血，其余选第一个
    private 战斗单位 AI选友方(战斗单位 施法者, 技能数据 技能)
    {
        var 同伴 = 施法者.是否我方 ? 我方 : 敌方;
        var 存活 = 同伴.FindAll(u => u.存活);
        if (存活.Count == 0) return 施法者.是否我方 ? 玩家 : 敌方[0];
        if (技能.目标枚举 == 目标类型.自己) return 施法者;
        if (技能.目标枚举 == 目标类型.我方单体)
        {
            存活.Sort((a, b) => a.生命.CompareTo(b.生命));
            return 存活[0];
        }
        return 存活[0];
    }

    private string AI抽行动(敌人数据 敌数据)
    {
        int 总 = 0; foreach (var a in 敌数据.行动表) 总 += Mathf.Max(1, a.权重);
        int 掷 = Random.Range(0, 总);
        foreach (var a in 敌数据.行动表)
        {
            掷 -= Mathf.Max(1, a.权重);
            if (掷 < 0) return a.行动;
        }
        return "普攻";
    }

    private 战斗单位 AI选目标(战斗单位 敌人, 敌人数据 敌数据)
    {
        var 存活 = 我方.FindAll(u => u.存活);
        if (存活.Count == 0) return null;
        if (敌数据?.目标策略 == "残血")
        {
            存活.Sort((a, b) => a.生命.CompareTo(b.生命));
            return 存活[0];
        }
        return 存活[Random.Range(0, 存活.Count)];
    }


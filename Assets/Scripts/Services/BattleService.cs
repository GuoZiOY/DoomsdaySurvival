    // 自动普攻：近战（攻击距离 1）→ 物理伤害；远程（攻击距离 >1）→ 远程伤害
    // ===== 弹药 / 技能 消耗物（玩家：弹挂/腰封 供；敌人 天然 无限，不 参与） =====

    private string 武器弹药标识(武器种类 种类) => 种类 switch
    {
        武器种类.手枪 => "手枪弹",
        武器种类.步枪 => "步枪弹",
        武器种类.霰弹枪 => "霰弹",
        武器种类.弩 => "弩箭",
        武器种类.弓 => "箭矢",
        _ => "",
    };

    private bool 是弹药类(string 标识) => !string.IsNullOrEmpty(标识) && 数据.物品.TryGetValue(标识, out var 模板) && 模板.类型 == "弹药";

    // 弹挂/腰封 中 找 首个 满足 条件 的 堆叠
    private 物品堆叠 找战斗容器堆叠(System.Func<物品堆叠, bool> 匹配)
    {
        if (档案 == null || 匹配 == null) return null;
        foreach (var 槽位 in new[] { "弹挂", "腰封" })
        {
            var 记录 = 档案.装备.Find(e => e.槽位 == 槽位);
            if (记录?.容器物品 == null) continue;
            foreach (var 堆叠 in 记录.容器物品)
                if (堆叠 != null && 堆叠.数量 > 0 && 匹配(堆叠)) return 堆叠;
        }
        return null;
    }

    private void 扣战斗容器(物品堆叠 堆叠, int 数量)
    {
        if (堆叠 == null || 数量 <= 0) return;
        堆叠.数量 -= 数量;
        if (堆叠.数量 <= 0) 移除容器堆叠(堆叠);
        ServiceRegistry.Get<EventBus>()?.发布(new 背包变化事件(堆叠.标识, -数量, 变化原因.消耗));
    }

    // 远程 攻击/技能 扣 弹药：主弹药 优先，其次 任意 弹药 类 兜底
    private bool 尝试扣弹药(战斗单位 单位)
    {
        if (单位 != 玩家) return true;   // 敌人：无需 装填
        string 主 = 武器弹药标识(单位.当前武器);
        var 堆叠 = 找战斗容器堆叠(s => s.标识 == 主) ?? 找战斗容器堆叠(s => 是弹药类(s.标识));
        if (堆叠 == null)
        {
            音效管理器.实例?.播放失败();
            发消息("没有弹药了！往弹挂/腰封里备些弹药吧。");
            return false;
        }
        扣战斗容器(堆叠, 1);
        return true;
    }

    // 技能 指定 消耗物品（从 弹挂/腰封 扣 指定 数量）
    private bool 尝试扣消耗物(战斗单位 单位, string 标识, int 数量)
    {
        if (单位 != 玩家) return true;
        var 堆叠 = 找战斗容器堆叠(s => s.标识 == 标识 && s.数量 >= Mathf.Max(1, 数量));
        if (堆叠 == null)
        {
            音效管理器.实例?.播放失败();
            发消息($"需要「{标识}」×{数量}（放 弹挂/腰封 里）。");
            return false;
        }
        扣战斗容器(堆叠, 数量);
        return true;
    }

    // 执行攻击：自动 普攻（远程 武器 需 弹药，无 弹药 = 空枪 不出 伤）
    private void 执行攻击(战斗单位 攻击者, 战斗单位 目标)
    {
        if (目标 == null || !目标.存活) return;
        var 类型 = 攻击者.攻击距离 > 1 ? 伤害类型.远程 : 伤害类型.物理;
        if (类型 == 伤害类型.远程 && !尝试扣弹药(攻击者)) return;   // 缺 弹药：这一 击 打 不 出（条 已 耗）
        造成伤害(攻击者, 目标, 类型, 100, 0);
    }

    // 执行技能：返回是否成功释放（资源不足/冷却中/专向不匹配 = false，调用方据此决定是否消耗行动）
    private bool 执行技能(战斗单位 施法者, string 技能标识, 战斗单位 目标)
    {
        if (!数据.技能.TryGetValue(技能标识, out var 技能)) return false;
        if (施法者.冷却剩余(技能标识) > 0)
        {
            if (施法者 == 玩家) 发消息($"《{技能.名称}》 还在冷却中！");
            return false;
        }
        // 武器规则（仅物理攻击技能）：专向=仅指定武器可用（不匹配则不消耗行动）；弱向=指定武器伤害↑、其余↓
        float 技能武器修正 = 1f;
        if (技能.类别枚举 == 技能类别.攻击 && 技能.伤害类型枚举 == 伤害类型.物理)
        {
            bool 匹配 = 施法者.当前武器 != 武器种类.无 && 施法者.当前武器 == 技能.武器种类枚举;
            if (技能.武器规则枚举 == 武器规则.专向 && !匹配)
            {
                if (施法者 == 玩家) 发消息($"《{技能.名称}》需要装备「{技能.武器种类}」才能使用！");
                return false;
            }
            if (技能.武器规则枚举 == 武器规则.弱向) 技能武器修正 = 匹配 ? 1.25f : 0.75f;
        }
        // 资源规则：技能统一消耗精力（行动点）
        if (!施法者.消耗精力(技能.消耗精力))
        {
            if (施法者.是否我方) { 音效管理器.实例?.播放失败(); 发消息("精力不足！"); }
            return false;
        }
        // 消耗 型（玩家）：远程 伤害 技能 → 弹药；技能 指定 消耗物品 → 弹挂/腰封 扣（缺 → 释放 失败）
        if (施法者 == 玩家)
        {
            if (技能.伤害类型枚举 == 伤害类型.远程 && !尝试扣弹药(施法者)) return false;
            if (!string.IsNullOrEmpty(技能.消耗物品) && !尝试扣消耗物(施法者, 技能.消耗物品, Mathf.Max(1, 技能.消耗数量))) return false;
        }
        // 位移技（推进/后撤/冲撞）：瞬发 改变 站位——无 目标/伤害/熟练；消耗精力后 结算 并 进入冷却
        if (!string.IsNullOrEmpty(技能.位移))
        {
            执行位移(施法者, 技能);
            施法者.开始冷却(技能标识, 技能.冷却);
            return true;
        }
        int 熟练 = 施法者.熟练等级(技能标识);
        float 品质倍 = 品质工具.倍率(技能.品质档);
        switch (技能.类别枚举)
        {
            case 技能类别.攻击:
                {
                    var 目标列表 = 技能目标列表(技能, 目标);   // 单体=1 / 敌方两名=2 / 全体=全部存活
                    switch (技能.伤害方式枚举)
                    {
                        case 技能伤害方式.固定:
                            // 固定伤害：无视角色的属性与装备，只打技能的固定数值
                            {
                                int 固定值 = Mathf.Max(1, Mathf.RoundToInt(技能.数值));
                                foreach (var 敌 in 目标列表) 造成固定伤害(施法者, 敌, 固定值);
                                break;
                            }
                        case 技能伤害方式.附加:
                            // 附加伤害：在角色的伤害值上 + 数值
                            {
                                int 附加 = Mathf.Max(1, Mathf.RoundToInt(技能.数值 * 技能武器修正));
                                foreach (var 敌 in 目标列表) 造成伤害(施法者, 敌, 技能.伤害类型枚举, 100, 附加);
                                break;
                            }
                        default:
                            // 倍率伤害：角色伤害值 × 数值（受品质/熟练/防御/暴击/抗性影响）
                            {
                                int 倍率 = Mathf.RoundToInt(技能.数值 * 品质倍 * (1f + 熟练 * 技能.熟练伤害加成 / 100f) * 技能武器修正 * 100f);
                                foreach (var 敌 in 目标列表) 造成伤害(施法者, 敌, 技能.伤害类型枚举, 倍率, 0);
                                break;
                            }
                    }
                    附加Buff(施法者, 目标, 技能);   // 攻击技能可同时挂载减益（如 撕咬→中毒）
                    break;
                }
            case 技能类别.净化:
                // 净化：取消目标（友方）的随机一个减益
                {
                    var 净化目标 = 目标;
                    if (净化目标 != null && 净化目标.移除随机减益())
                    {
                        事件.发布(new 状态变化事件(净化目标, "", 0, 0, true));
                        发消息($"{名(施法者)} 施展《{技能.名称}》，清除了{名(净化目标)}身上的一个减益！");
                    }
                    else 发消息($"{名(施法者)} 施展《{技能.名称}》，{名(净化目标)}身上没有可清除的减益。");
                    break;
                }
            case 技能类别.治疗:
                {
                    int 恢复 = Mathf.Max(1, Mathf.RoundToInt(技能.数值 * 品质倍 * (1f + 熟练 * 技能.熟练伤害加成 / 100f)));
                    var 治疗目标 = 技能.目标枚举 == 目标类型.自己 ? 施法者 : 目标;
                    治疗目标.恢复生命(恢复);
                    事件.发布(new 治疗事件(治疗目标, 恢复));
                    发消息($"{名(施法者)} 施展《{技能.名称}》，{名(治疗目标)}恢复 {恢复} 点生命。");
                    break;
                }
            default:   // 增益 / 减益 / 控制：挂载 buff（目标=自己 时作用于施法者）
                附加Buff(施法者, 技能.目标枚举 == 目标类型.自己 ? 施法者 : 目标, 技能);
                break;
        }
        // 眩晕 效果（秒制；攻击 类 = 打到的 每个 目标；其余 = 命中 目标/自己）
        if (技能.眩晕秒 > 0f)
        {
            var 眩晕目标 = 技能.类别枚举 == 技能类别.攻击
                ? 技能目标列表(技能, 目标)
                : new List<战斗单位> { 技能.目标枚举 == 目标类型.自己 ? 施法者 : 目标 };
            foreach (var 眩晕者 in 眩晕目标)
                if (眩晕者 != null && 眩晕者.存活) 施加眩晕(眩晕者, 技能.眩晕秒, $"《{技能.名称}》");
        }
        施法者.开始冷却(技能标识, 技能.冷却);
        // 仅玩家本人使用技能累积熟练度（助战单位不记）
        if (施法者 == 玩家 && 熟练 < 玩家档案.熟练等级上限)
            ServiceRegistry.Get<技能服务>().记录熟练度(技能标识, 1);
        return true;
    }

    // 位移技 结算（推进/后撤/冲撞）：逐格 冲刺；敌方 挡路 → 贴脸 停；冲撞 = 把 挡路 敌人 顶退
    private void 执行位移(战斗单位 施法者, 技能数据 技能)
    {
        int 前进 = 施法者.是否我方 ? 1 : -1;       // 朝 敌方 一侧 为 前进
        string 类型 = 技能.位移;
        int 方向 = 类型 == "后撤" ? -前进 : 前进;   // 推进/冲撞 = 前进；后撤 = 反向
        int 距离 = Mathf.Max(1, 技能.位移距离);
        bool 推撞 = 类型 == "冲撞";
        for (int 步 = 0; 步 < 距离; 步++)
        {
            int 下一列 = 施法者.列 + 方向;
            if (下一列 < 0 || 下一列 >= 棋盘宽) break;   // 出界 → 停
            if (对方占用(施法者, 下一列))
            {
                if (!推撞) break;                        // 普通冲刺：被 敌 挡 → 贴脸 停
                if (!推挤级联(施法者, 下一列, 方向)) break;   // 冲撞：顶退 挡路 敌；顶 不动 → 停
            }
            施法者.列 = 下一列;
        }
        发消息($"{名(施法者)} {位移动作名(类型)}！(节点 {施法者.列})");
    }

    // 指定 列 是否有 存活 敌方 单位
    private bool 对方占用(战斗单位 施法者, int 列)
    {
        foreach (var 敌 in 施法者.是否我方 ? 敌方 : 我方)
            if (敌.存活 && 敌.列 == 列) return true;
        return false;
    }

    // 冲撞 顶退：把 起点 起 沿 方向 的 敌方 链 各 顶退 1 格（同节点 多个 一起 顶）；链尾 是 边界/无空位 → false
    private bool 推挤级联(战斗单位 施法者, int 起点列, int 方向)
    {
        var 对方 = 施法者.是否我方 ? 敌方 : 我方;
        int 尾 = 起点列;
        while (尾 + 方向 >= 0 && 尾 + 方向 < 棋盘宽 && 对方占用(施法者, 尾 + 方向)) 尾 += 方向;
        if (尾 + 方向 < 0 || 尾 + 方向 >= 棋盘宽) return false;   // 顶 到 边界
        for (int c = 尾; ; c -= 方向)
        {
            foreach (var 敌 in 对方)
                if (敌.存活 && 敌.列 == c)
                {
                    敌.列 = c + 方向;
                    // 冲撞 命中：读条 大招（技能 意图）被 撞 断
                    if (敌.意图已选 && 敌.当前意图 == 战斗单位.意图类型.技能 && 敌.行动条 > 0.01f)
                    {
                        string 招名 = string.IsNullOrEmpty(敌.意图技能) ? "读条大招" : 敌.意图技能;
                        中断读条(敌, $"的「{招名}」读条被撞断");
                    }
                }
            if (c == 起点列) break;
        }
        return true;
    }

    // 中断读条（被打断）：行动条清零 + 意图 作废 + 玩家 蓄力 预约 一并 取消（不 扣 物品/资源）
    // 玩家/敌人 双向 通用：受控（无法行动）断 一切 读条；位移/控制 命中 读条 大招 同样 触发
    private void 中断读条(战斗单位 单位, string 描述)
    {
        if (单位 == null || !单位.存活) return;
        bool 在读条 = 单位.行动条 > 0.01f || (单位 == 玩家 && 待动类型 != 待动类别.无);
        if (!在读条) return;
        单位.行动条 = 0f;
        单位.意图已选 = false;
        单位.意图技能 = null;
        if (单位 == 玩家 && 待动类型 != 待动类别.无) 取消待行动作();
        if (!string.IsNullOrEmpty(描述)) 发消息($"{名(单位)} {描述}！");
    }

    // 施加 眩晕（秒制）：先 断 其 读条（清零 重来），再 冻结 一段时间（期间 不 推 读条）；到时 自动 恢复 重锁 意图
    public void 施加眩晕(战斗单位 单位, float 秒, string 来源 = null)
    {
        if (单位 == null || !单位.存活 || 秒 <= 0f) return;
        中断读条(单位, null);
        单位.施加眩晕(秒);
        if (!string.IsNullOrEmpty(来源)) 发消息($"{名(单位)} 被{来源}眩晕 {Mathf.CeilToInt(秒)} 秒！");
    }

    private static string 位移动作名(string 类型) => 类型 switch
    {
        "推进" => "向前冲刺",
        "后撤" => "向后退撤",
        _ => "向前冲撞",
    };

    // 技能攻击目标列表：单体=选中；敌方两名=选中 + 另一个存活敌人；全体=全部存活敌人
    private List<战斗单位> 技能目标列表(技能数据 技能, 战斗单位 选中)
    {
        var 列表 = new List<战斗单位>();
        if (选中 != null && 选中.存活) 列表.Add(选中);
        if (技能.目标枚举 == 目标类型.敌方全体)
        {
            foreach (var 敌 in 敌方)
                if (敌.存活 && !列表.Contains(敌)) 列表.Add(敌);
        }
        else if (技能.目标枚举 == 目标类型.敌方两名)
        {
            foreach (var 敌 in 敌方)
                if (敌.存活 && !列表.Contains(敌)) { 列表.Add(敌); break; }   // 补第二个目标
        }
        return 列表;
    }

    // 技能挂载 Buff（攻击技能也可携带减益，如 撕咬→中毒 / 骨刺→防御削弱）
    private void 附加Buff(战斗单位 施法者, 战斗单位 目标, 技能数据 技能)
    {
        if (string.IsNullOrEmpty(技能.挂载Buff) || !数据.Buffs.TryGetValue(技能.挂载Buff, out var buff)) return;
        目标.添加Buff(buff);
        var 实例 = 目标.Buffs.Find(b => b.定义.标识 == buff.标识);
        事件.发布(new 状态变化事件(目标, buff.标识, 实例?.层数 ?? 1, buff.持续回合, false));
        发消息($"{名(目标)} 获得「{buff.名称}」！");
    }

    // ===== 统一伤害管线（全项目唯一伤害公式权威） =====
    // 普攻/技能伤害公式：近战=基础近战（力量+装备）/ 远程=基础远程（武器+词缀）× 倍率/100 + 附加（下限 1）
    // 判定顺序：命中（攻方命中率 vs 目标闪避）→ 暴击（×1.5）→ 减伤（目标防御% → 抗性% → 防御姿态减半）→ 下限 1
    // 防御减伤：物防 1 点 = 1%（封顶 50%）；抗性 = 装备第二层减伤（封顶 50%）；防御姿态 = 再减半
    private void 造成伤害(战斗单位 攻击者, 战斗单位 目标, 伤害类型 类型, int 倍率100, int 附加 = 0)
    {
        if (目标 == null || !目标.存活) return;
        // 无敌判定（天赋触发后：免疫伤害 1 轮）
        if (目标.无敌)
        {
            事件.发布(new 伤害事件(目标, 0, 类型, false, false));
            发消息($"{名(目标)} 处于无敌状态，攻击被弹开！");
            return;
        }
        // 命中判定：基础命中率 vs 目标当前闪避（敏捷 buff 生效）
        if (Random.value >= 攻击者.命中率 - 目标.当前闪避率)
        {
            事件.发布(new 伤害事件(目标, 0, 类型, false, true));
            发消息($"{名(目标)} 闪避了{名(攻击者)}的攻击！");
            return;
        }
        // 真实伤害：无视命中/攻防/暴击/抗性（毒/固定伤 走此路，直接结算）
        if (类型 == 伤害类型.真实)
        {
            int 真伤 = Mathf.Max(1, 倍率100 + 附加);
            目标.受到伤害(真伤);
            事件.发布(new 伤害事件(目标, 真伤, 类型, false, false));
            发消息($"{名(攻击者)}对{名(目标)}造成 {真伤} 点伤害。");
            检查单位死亡(目标);
            return;
        }
        // 耐久消耗：玩家命中 → 主武器武器耐久 -1；玩家被击中 → 胸部防具耐久 -1
        if (攻击者.是否我方 && !string.IsNullOrEmpty(攻击者.当前武器标识)) 档案.扣装备标识耐久(攻击者.当前武器标识, 1);
        if (目标.是否我方) 档案.扣装备耐久("胸部", 1);
        bool 暴击 = Random.value < 攻击者.当前暴击率;
        int 基础攻 = 类型 == 伤害类型.远程 ? 攻击者.当前远程 : 攻击者.当前近战;
        int 基础伤害 = Mathf.Max(1, Mathf.RoundToInt(基础攻 * 倍率100 / 100f) + 附加);
        if (暴击) 基础伤害 = Mathf.RoundToInt(基础伤害 * 1.5f);
        // 减伤链路：防御% → 抗性%（装备第二层）→ 防御姿态减半
        int 伤害 = Mathf.Max(1, Mathf.RoundToInt(基础伤害 * (1f - 目标.防御减伤)));
        if (目标.抗性百分比 > 0)
            伤害 = Mathf.Max(1, Mathf.RoundToInt(伤害 * (1f - 目标.抗性百分比 / 100f)));
        if (目标.防御姿态) 伤害 = Mathf.Max(1, Mathf.RoundToInt(伤害 * 0.5f));
        目标.受到伤害(伤害);
        事件.发布(new 伤害事件(目标, 伤害, 类型, 暴击, false));
        发消息($"{(暴击 ? "<color=#e0b84a>暴击！</color>" : "")}{名(攻击者)}对{名(目标)}造成 {伤害} 点伤害。");
        检查单位死亡(目标);
    }

    // 固定伤害：不受任何因素影响（无视命中/攻防/暴击/抗性），只打出固定数值
    private void 造成固定伤害(战斗单位 攻击者, 战斗单位 目标, int 数值)
    {
        if (目标 == null || !目标.存活) return;
        int 伤害 = Mathf.Max(1, 数值);
        目标.受到伤害(伤害);
        事件.发布(new 伤害事件(目标, 伤害, 伤害类型.真实, false, false));
        发消息($"{名(攻击者)}对{名(目标)}造成 {伤害} 点固定伤害。");
        检查单位死亡(目标);
    }

    private void 检查单位死亡(战斗单位 单位)
    {
        if (单位.存活) return;
        // 玩家倒下：先发 致命伤害事件（天赋服务 检查 钢铁意志/医者仁心——免疫则保命继续）
        if (单位 == 玩家 && ServiceRegistry.已注册<天赋服务>())
        {
            ServiceRegistry.Get<天赋服务>().处理致命伤害(new 致命伤害事件(单位));
            if (单位.存活)   // 天赋免疫成功（生命已保底）
            {
                事件.发布(new 目标变化事件(单位));
                事件.发布(new 战斗消息事件("你挺过了致命一击！"));
                return;
            }
        }
        if (单位.是否我方) 我方.Remove(单位);
        else { 敌方.Remove(单位); 结算单个敌人(单位); }
        事件.发布(new 目标变化事件(单位));
        发消息($"{名(单位)} 倒下了！");
    }

    // ===== 胜利结算（每死一个敌人即时结算；末日以物易物：掉落补给而非金币） =====
    private void 结算单个敌人(战斗单位 敌人)
    {
        var 敌 = 敌人.源数据;
        if (敌 == null) return;
        // 战利品（补给 + 掉落）→ 进 尸体：战后 搜刮（不 直接 入包；尸体 由 结束战斗 生成 搜索 容器）
        int 补给值 = Mathf.Max(0, 敌.货币奖励);
        int 面包数 = 补给值 / 4, 水数 = 补给值 / 8;
        if (面包数 > 0) 战利品入尸("面包", 面包数);
        if (水数 > 0) 战利品入尸("水", 水数);
        bool 升级 = 档案.获得经验(敌.经验奖励); 累计经验 += 敌.经验奖励;
        事件.发布(new 经验变化事件(档案.等级, 档案.经验, 档案.升级所需经验, 升级));
        if (升级) 事件.发布(new 属性变化事件(档案.体质, 档案.力量, 档案.智慧, 档案.敏捷, 档案.意志, 档案.自由属性点));
        if (!string.IsNullOrEmpty(敌.掉落物品) && Random.value < 敌.掉落概率)
        {
            // 掉落装备 → 词缀 实例；非装备 → 普通 堆叠（均 进 尸体）
            if (数据.物品.TryGetValue(敌.掉落物品, out var 掉物))
            {
                var 词缀 = ServiceRegistry.Get<词缀服务>()?.生成(掉物);
                if (词缀 != null) 战利品入尸(new 物品堆叠(敌.掉落物品, 1) { 词缀 = 词缀, 当前耐久 = 档案.有效最大耐久(敌.掉落物品) });
                else 战利品入尸(敌.掉落物品, 1);
            }
            else 战利品入尸(敌.掉落物品, 1);
        }
        ServiceRegistry.Get<QuestService>().记录击败(敌.标识);
        string 补给文本 = 面包数 > 0 || 水数 > 0 ? $"、面包×{面包数}、水×{水数}" : "";
        发消息($"击败 <color={游戏主题.危险色值}>{敌.名称}</color> ！获得{补给文本}{敌.经验奖励} 经验。");
    }

    // 战利品 收集：同名（无 词缀）合并 数量；词缀 实例 独立 一件
    private void 战利品入尸(string 标识, int 数量)
    {
        var 已有 = 尸体战利品.Find(s => s != null && s.标识 == 标识 && s.词缀 == null);
        if (已有 != null) { 已有.数量 += 数量; return; }
        尸体战利品.Add(new 物品堆叠(标识, 数量));
    }

    private void 战利品入尸(物品堆叠 堆叠) { if (堆叠 != null) 尸体战利品.Add(堆叠); }

    private bool 检查战斗结束()
    {
        if (!战斗中) return true;
        if (敌方.Count == 0) { 结束战斗(true, $"战斗胜利！共获得 {累计经验} 经验，搜刮战利品吧。", 胜利节点); return true; }
        // 玩家本人倒下=失败（助战单位倒下无碍，仍继续战斗）
        if (玩家 == null || !玩家.存活) { 结束战斗(false, "你被击败了……", 返回节点); return true; }
        return false;
    }

    // ===== 战斗结束 + 离场回写 =====
    private void 结束战斗(bool 胜利, string 文本, string 进入节点, bool 惩罚 = true)
    {
        战斗中 = false;
        结果节点 = 进入节点;
        if (胜利) { }
        else if (惩罚 && 结果节点 == 返回节点) 结算失败惩罚();
        结算回写();
        // 胜利 战利品 → 尸体 搜索 容器（世界 沙盒 前：战后 自动 进入 搜索；之后 由 世界 在 原地 生成 尸体）
        string 尸体容器 = "";
        if (胜利 && 尸体战利品.Count > 0)
        {
            尸体容器 = ServiceRegistry.Get<搜索服务>()?.注册尸体容器("敌人的尸体", 8, 5, 尸体战利品) ?? "";
            尸体战利品.Clear();
        }
        事件.发布(new 战斗结束事件(胜利, 文本, 尸体容器));
        // 战斗结果摘要沉淀入日志（非过程消息；战斗过程逐条已标记 过程=true 不入历史）
        if (!string.IsNullOrEmpty(文本))
            事件.发布(new 日志事件(日志类型.战斗, 文本));
    }

    // 失败惩罚：末日版——掉 10% 价值物资 + 回营地半状态（不再满血复活）
    private void 结算失败惩罚()
    {
        // 以物易物经济：损失 10% 持有物资（穿戴容器 + 仓库 + 嵌套容器，按价值最贵的优先——统一持有入口）
        var 持有 = 档案.所有持有物品();
        int 损失件数 = 持有.Count > 0 ? Mathf.Max(1, 持有.Count / 10) : 0;
        for (int i = 0; i < 损失件数 && 持有.Count > 0; i++)
        {
            var 堆叠 = 持有[持有.Count - 1];
            if (档案.移除物品(堆叠.标识, 1))
                事件.发布(new 背包变化事件(堆叠.标识, -1, 变化原因.失去));
        }
        档案.生命 = Mathf.Max(1, 档案.最大生命 / 2);
        档案.行动点 = Mathf.Max(1, 档案.最大行动点 / 2);
        事件.发布(new 生命变化事件(档案.生命, 档案.最大生命, 档案.生命));
        事件.发布(new 精力变化事件(档案.行动点, 档案.最大行动点, 档案.行动点));
        发消息($"你被击倒了，丢了随身的一些东西，挣扎着逃回安全处。");
    }

    // 离场回写：生命/行动点 + 道具消耗统一扣；Buff/临时状态丢弃（战斗外无临时buff）
    private void 结算回写()
    {
        档案.生命 = 玩家.生命;
        档案.行动点 = 玩家.精力;   // 战斗消耗的行动点（战斗单位精力=行动点）随战斗保留
        foreach (var 标识 in 消耗道具) 档案.移除物品(标识);
        消耗道具.Clear();
    }

    // 战斗结束后面板 [继续]：进入结果节点
    public void 返回()
    {
        if (结果节点 == "__探索胜利") { ServiceRegistry.Get<探索服务>().战斗胜利(); return; }
        if (结果节点 == "__探索返回") { ServiceRegistry.Get<探索服务>().战斗逃跑(); return; }
        if (!string.IsNullOrEmpty(结果节点)) ServiceRegistry.Get<DialogueService>().进入节点(结果节点);
    }

    public List<战斗单位> 全部单位()
    {
        var 列表 = new List<战斗单位>();
        列表.AddRange(我方); 列表.AddRange(敌方);
        return 列表;
    }

    private void 发消息(string 文本)
    {
        当前消息 = 文本;
        事件.发布(new 日志事件(日志类型.战斗, 文本, true));   // 战斗过程 = 过程消息（短暂展示，不沉淀历史）
    }

    // 单位名预处理：我方=正常色、敌方=血红；名称左右各留一个空格分隔
    private static string 名(战斗单位 单位)
    {
        if (单位 == null) return " ？？？ ";
        if (单位.是否我方) return $" {单位.名称} ";
        return $" <color={游戏主题.危险色值}>{单位.名称}</color> ";
    }

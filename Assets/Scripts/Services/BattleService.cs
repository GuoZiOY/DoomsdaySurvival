    // 玩家 攻速/移速 倍率（行动 间隔 除数：>1 更快 / <1 更慢，下限 0.4）
    // = 1 + 敏捷 贡献（敏捷 总成 移速&攻速）+ 当前 武器 攻速加成% + 全身 防具 移速加成% 之和（重型 可为 负）
    private void 刷新玩家速率()
    {
        if (玩家 == null || 档案 == null) return;
        int 敏 = 档案.敏捷;
        float 攻 = 1f + (敏 - 5) * 0.02f;   // 敏捷 → 攻速：每点 +2%（基准 5 点 = 0）
        float 移 = 1f + (敏 - 5) * 0.03f;   // 敏捷 → 移速：每点 +3%
        string 武 = 玩家.当前武器标识;
        if (!string.IsNullOrEmpty(武) && 数据.物品.TryGetValue(武, out var 武器) && 武器.攻速加成 != 0f)
            攻 += 武器.攻速加成 / 100f;   // 轻 武器 快 / 重 武器 慢（负面）
        foreach (var 记录 in 档案.装备)
        {
            if (记录 == null || string.IsNullOrEmpty(记录.标识)) continue;
            if (记录.槽位 == "主手" || 记录.槽位 == "副手") continue;   // 攻速 只 按 当前 武器
            if (数据.物品.TryGetValue(记录.标识, out var 装) && 装.移速加成 != 0f)
                移 += 装.移速加成 / 100f;   // 重型 甲 负 值 → 拖慢
        }
        玩家.攻速倍率 = Mathf.Max(0.4f, 攻);
        玩家.移速倍率 = Mathf.Max(0.4f, 移);
    }


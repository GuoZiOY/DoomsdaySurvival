using System;
using System.Collections.Generic;
using UnityEngine;

// ============================================================
// 房间探索服务：房间层状态机（纯逻辑，零 MonoBehaviour）。
// 循环：进入房间（按种子生成）→ 点格寻路（走 1 格 = 1 游戏分钟）→ 右键容器搜索（扣 10 行动点）
//       → 看见/撞上敌人则遭遇（切战斗沙盒）→ 打完留下可搜尸体 → 离开。
// 与渲染的分工：本服务持有 房间数据（唯一真相：占位/可通行/视线），并同步出一个 网格服务
//               注入 房间网格面板（基类网格框架吃这个）；面板只负责画，不自己算规则。
// 迷雾：三态（未探索/已探索/可见），记忆在 已探索 集合里（本局有效，离开即弃）。
// ============================================================
public sealed class 房间探索服务
{
    // —— 规则常量（第 1 刀定版）——
    public const int 移动游戏分钟 = 1;      // 走一格推进的游戏分钟（不耗行动点：行动点留给搜索）
    public const int 搜索行动点 = 10;       // 搜一处扣的行动点（与 探索服务 一致）
    public const int 搜索游戏分钟 = 5;      // 搜一处推进的游戏分钟

    // —— 移动节奏（表现层用；游戏时间仍是 1 分钟/格，变的只是"你看它走"的现实秒数）——
    public const float 每格现实秒 = 0.30f;   // 走一格花的现实秒（放慢后：走路有分量，不再是瞬移）

    // 与 BattleService.开始战斗 的 先手 参数同语义：0=速度序 1=敌方绝对先手（被偷袭）2=我方绝对先手（偷袭）
    public const int 先手撞上 = 1;          // 相邻撞上：敌人先手
    public const int 先手看清 = 2;          // 视野内 ≥3 格先看见：玩家先手

    private readonly EventBus 事件;
    private readonly DataService 数据;
    private readonly PlayerService 玩家服务;
    private readonly BattleService 战斗;
    private readonly 搜索服务 搜索;

    private readonly Dictionary<房间实体, 物品堆叠> 框映射 = new Dictionary<房间实体, 物品堆叠>();
    private readonly Dictionary<string, (int 宽, int 高)> 形状表 = new Dictionary<string, (int, int)>();
    private readonly HashSet<房间实体> 已察觉 = new HashSet<房间实体>();   // 曾在 ≥3 格距离被看见的敌人（遭遇时给我方先手）

    private readonly 视野规则 规则;                       // 角色 + 时段 → 视野边长 / 有没有记忆（数据：视野.json）
    public 时段 当前时段 { get; private set; } = 时段.白天;
    public bool 有记忆 => 规则.有记忆(当前时段);            // 白天才有记忆（淡阴影），夜晚全黑
    public float 阴影压暗 => 规则.阴影压暗;   // 阴影区（白天记忆 / 夜晚弱视野）压暗程度

    public 房间数据 当前房间 { get; private set; }
    public 网格服务 网格 { get; private set; }
    public int 房间种子 { get; private set; }
    public string 提示 { get; private set; } = "";
    public List<(int 列, int 行)> 当前路径 { get; private set; } = new List<(int 列, int 行)>();
    // 注：**不再有"待走目标"缓冲**。走到一半点别处 = 当场换路径：视觉令牌是"从它此刻所在的位置
    //     走向下一步的格子"（房间图层.推进移动），换路径只会让它当场拐弯，不会把插值进度套到新方向
    //     上（那才是瞬移的老 bug），所以不需要等这一格走完。

    private readonly HashSet<int> 已探索 = new HashSet<int>();     // 迷雾记忆：进过视野的格
    private HashSet<int> 当前可见 = new HashSet<int>();
    private (int 列, int 行) 遭遇前格;
    private 房间实体 遭遇目标;
    private string 最近尸体容器 = "";
    private string 上次地点 = "";   // HUD 地点位去重（内容变了才发事件）

    public bool 探索中 => 当前房间 != null;
    public bool 遭遇中 { get; private set; }
    public bool 本次战斗来自房间 { get; private set; }
    public int 玩家列 => 当前房间?.玩家列() ?? 0;
    public int 玩家行 => 当前房间?.玩家行() ?? 0;

    private 玩家档案 档案 => 玩家服务?.档案;

    public 房间探索服务(EventBus 事件, DataService 数据, PlayerService 玩家服务, BattleService 战斗, 搜索服务 搜索)
    {
        this.事件 = 事件;
        this.数据 = 数据;
        this.玩家服务 = 玩家服务;
        this.战斗 = 战斗;
        this.搜索 = 搜索;
        规则 = 视野规则.从数据(数据?.视野);   // 视野：角色 + 时段（数据：Data/视野.json）
        if (事件 != null)
        {
            事件.订阅<战斗结束事件>(战斗结束响应);
            事件.订阅<时间变化事件>(时间变化响应);   // 站着不动跨过 6:00 / 18:00 也要立刻切换视野与记忆
            事件.订阅<打开营地事件>(_ => 回安全屋清战局());   // 回到安全屋 = 这一趟结束（战局临时数据作废的**唯一**时机）
        }
    }

    // 回安全屋：房间容器的战局临时数据（已生成内容 / 已翻标记 / 尸体容器）整体作废——下一趟出去是全新的一批物资。
    // **进房间 / 离开房间都不清**：一趟里搜到的进度要留到回安全屋为止（容器也不再是一次性的）。
    private void 回安全屋清战局() => 搜索?.清空战局();

    // ================= 进出 =================

    // 进入房间：按模板 + 种子生成（同模板同种子 = 同布局），建网格、揭初始视野、打开面板
    public bool 进入房间(string 模板标识, int 种子)
    {
        if (数据 == null || !数据.房间模板.TryGetValue(模板标识, out var 模板))
        {
            Debug.LogError($"[房间] 模板不存在: {模板标识}");
            return false;
        }
        当前房间 = 房间生成器.生成(种子, 模板, 取容器表, 取敌人组);
        if (当前房间 == null) return false;
        房间种子 = 种子;
        已探索.Clear();
        当前可见.Clear();
        已察觉.Clear();
        当前路径.Clear();
        遭遇中 = false;
        本次战斗来自房间 = false;
        遭遇目标 = null;
        最近尸体容器 = "";
        刷新视野();   // 容器战局数据**不在这里清**（见 回安全屋清战局）：这间房上次翻过的柜子，这次还是那副样子
        同步网格();
        事件?.发布(new 打开房间事件(模板标识, 种子));
        播报($"你推开了{当前房间.名称}的门。{危险度文本(当前房间.危险度)}");
        发布显示();
        return true;
    }

    // 离开房间：清空本局的**房间态**（房间结构本来就不存档，随用随生成）；
    // 容器的战局临时数据不在这次清（一路搜到的进度留到回安全屋为止，见 回安全屋清战局）
    public void 离开()
    {
        if (当前房间 == null) return;
        当前房间 = null;
        网格 = null;
        框映射.Clear();
        形状表.Clear();
        已探索.Clear();
        当前可见.Clear();
        已察觉.Clear();
        当前路径.Clear();
        遭遇中 = false;
        本次战斗来自房间 = false;
        遭遇目标 = null;
        上次地点 = "";
        string 回 = 档案?.当前大节点;
        事件?.发布(new 地图位置事件(地图模式.大地图, string.IsNullOrEmpty(回) ? "营地" : 回, ""));   // HUD 地点位还给"当前大节点"
    }

    // ================= 迷雾 / 视野 =================

    // 重算当前视野，并把可见格记入"已探索"记忆；顺带记录"看清了的敌人"（≥3 格 → 先手优势）
    public void 刷新视野()
    {
        if (当前房间 == null) return;
        // 边长与"有没有记忆"由角色与时段决定（白天 9 / 夜晚 3 之类，永远是单数）
        当前时段 = 规则.判时段(档案?.游戏分钟数 ?? 480f);
        当前房间.视野边长 = 规则.核心边长(当前时段);
        当前可见 = 房间视野.可见集(当前房间, 玩家列, 玩家行, 当前房间.视野边长);
        foreach (int 码 in 当前可见)
            已探索.Add(码);
        var 敌人们 = 当前房间.取类型(房间实体类型.敌人);
        foreach (var 敌 in 敌人们)
        {
            if (!当前可见.Contains(房间数据.编码(敌.列, 敌.行))) continue;
            int 距 = Math.Abs(敌.列 - 玩家列) + Math.Abs(敌.行 - 玩家行);
            if (距 >= 3) 已察觉.Add(敌);
        }
    }

    // 三态：0 未探索 / 1 已探索（此刻不可见） / 2 可见
    public byte 迷雾态(int 列, int 行)
    {
        int 码 = 房间数据.编码(列, 行);
        if (当前可见.Contains(码)) return 房间视野.可见;
        if (已探索.Contains(码)) return 房间视野.已探索;
        return 房间视野.未探索;
    }

    public bool 可见(int 列, int 行) => 当前可见.Contains(房间数据.编码(列, 行));
    public bool 已探索过(int 列, int 行) => 已探索.Contains(房间数据.编码(列, 行));

    // 每格的显示档（房间网格面板 与 房间图层 都照它画）：
    //   亮       = 核心方形内（含敌人）
    //   暗记忆   = 白天：已探索（墙/容器/尸体 可辨，敌人不画）
    //   暗中轮廓 = 夜晚：弱视野圈（只看得见建筑/墙）
    //   全黑     = 什么都不画
    public 视野档 档(int 列, int 行)
    {
        if (当前房间 == null) return 视野档.全黑;
        if (当前可见.Contains(房间数据.编码(列, 行))) return 视野档.亮;
        if (当前时段 == 时段.夜晚)
            return 规则.在弱视野圈(列, 行, 玩家列, 玩家行, 当前房间.视野边长 / 2) ? 视野档.暗中轮廓 : 视野档.全黑;
        return 已探索过(列, 行) ? 视野档.暗记忆 : 视野档.全黑;
    }


    // ================= 寻路 / 移动 =================

    // 算路径：容器/敌人 → 走到其相邻格；空格 → 直接走；未探索格 → 走到已知区域边缘；不可达 → null
    public List<(int 列, int 行)> 算路径(int 列, int 行)
    {
        if (当前房间 == null) return null;
        var 起 = (列: 玩家列, 行: 玩家行);
        if (列 == 起.列 && 行 == 起.行) return new List<(int 列, int 行)> { 起 };

        var 目标实体 = 当前房间.占位(列, 行);
        if (目标实体 != null)
            return 房间寻路.寻路到相邻(当前房间, 起, 目标实体);

        // 迷雾只影响"看不看得见"，不影响"走不走得过去"：空格一律按 A* 走（墙/容器自然挡路 → 返回 null 并提示）
        return 房间寻路.寻路(当前房间, 起, (列, 行));
    }

    // 点格：算路径 → **当场换路径**（面板立刻改画、令牌立刻拐弯）→ 图层沿路径逐格推进
    public bool 点格(int 列, int 行)
    {
        if (当前房间 == null || 遭遇中) return false;
        var 路 = 算路径(列, 行);
        if (路 == null || 路.Count == 0)
        {
            播报("那边过不去。");
            return false;
        }
        // 点自己脚下这格：站着 = 原地（单点路径，面板只高亮这一格）
        // 正在走 = **不打断**：路径照旧走完剩下的（半路把路径缩成单点会掐断脚下这半步，令牌得往回跳）
        if (列 == 玩家列 && 行 == 玩家行)
        {
            if (当前路径.Count > 1) return true;
            当前路径 = 路;
            发布显示();
            return true;
        }
        // 新路径一律从"当前逻辑格"起算；走到一半又点别处就当场换（视觉连续性由 房间图层 保证，见字段注释）
        当前路径 = 路;
        发布显示();
        return true;
    }

    // 方向键：走一格（相邻可站格）；正在走时同样当场改向
    public bool 方向移动(int 偏列, int 偏行)
    {
        if (当前房间 == null || 遭遇中) return false;
        int 列 = 玩家列 + 偏列, 行 = 玩家行 + 偏行;
        if (!当前房间.可通行(列, 行)) { 播报("那边过不去。"); return false; }
        当前路径 = new List<(int 列, int 行)> { (玩家列, 玩家行), (列, 行) };
        发布显示();
        return true;
    }

    // 沿路径走一步：推进游戏时间 → 刷新视野 → 检查遭遇；返回 true = 还有下一步
    // 由 房间图层 在"令牌真的踩到下一格"的那一刻调用（逻辑格与视觉到位同一时刻换，不会打架）
    public bool 推进一步()
    {
        if (当前房间 == null || 当前路径.Count <= 1)
        {
            当前路径.Clear();
            return false;
        }
        遭遇前格 = (玩家列, 玩家行);
        当前路径.RemoveAt(0);
        var 步 = 当前路径[0];
        当前房间.移动玩家(步.列, 步.行);
        推进游戏分钟(移动游戏分钟);
        刷新视野();
        发布显示();
        if (检查遭遇()) return false;   // 遭遇了：停在这里
        if (当前路径.Count <= 1)
        {
            当前路径.Clear();
            发布显示();
            return false;
        }
        return true;
    }

    // ================= 遭遇 / 战斗 =================

    // 玩家是否与敌人相邻 → 触发遭遇（敌人先手；若先前在 ≥3 格看清过该敌人 → 玩家先手）
    private bool 检查遭遇()
    {
        if (当前房间 == null || 遭遇中) return false;
        foreach (var 敌 in 当前房间.取类型(房间实体类型.敌人))
        {
            if (Math.Abs(敌.列 - 玩家列) + Math.Abs(敌.行 - 玩家行) != 1) continue;
            开始遭遇(敌);
            return true;
        }
        return false;
    }

    private void 开始遭遇(房间实体 敌)
    {
        遭遇中 = true;
        遭遇目标 = 敌;
        本次战斗来自房间 = true;
        当前路径.Clear();
        int 先手 = 已察觉.Contains(敌) ? 先手看清 : 先手撞上;
        播报(先手 == 先手看清 ? $"你早就看见它了——先动手。（{敌.名称}）" : $"{敌.名称}扑了上来！");
        if (战斗 == null)
        {
            Debug.LogError("[房间] 战斗服务未装配，遭遇无法开始");
            return;
        }
        战斗.开始战斗(当前房间.敌人组, "__房间胜利", "__房间返回", 先手, "", 当前房间.战斗棋盘);
    }

    // 时间变化（跨过 6:00 / 18:00）：视野边长与"记忆"立刻切换，不用等玩家走一步
    private void 时间变化响应(时间变化事件 e)
    {
        if (当前房间 == null) return;
        时段 之前 = 当前时段;
        刷新视野();
        if (之前 != 当前时段)
        {
            播报(当前时段 == 时段.白天 ? "天亮了。" : "天黑了——看不见的地方就是真的看不见。");
            发布显示();
        }
    }

    // 战斗结束（BattleService 发布）：记住本次的战利品尸体容器，供胜利后落到网格上
    private void 战斗结束响应(战斗结束事件 e)
    {
        if (!本次战斗来自房间) return;
        if (e.胜利 && !string.IsNullOrEmpty(e.尸体容器)) 最近尸体容器 = e.尸体容器;
    }

    // 胜利：敌人全灭；在遭遇位置留一具可搜尸体（内容 = 战斗产出的战利品容器）
    public void 战斗胜利()
    {
        if (当前房间 == null) return;
        遭遇中 = false;
        本次战斗来自房间 = false;
        var 敌人们 = 当前房间.取类型(房间实体类型.敌人);
        var 尸位 = 遭遇目标;
        foreach (var 敌 in 敌人们)
            当前房间.移除实体(敌);
        if (尸位 != null && !string.IsNullOrEmpty(最近尸体容器))
        {
            当前房间.实体.Add(new 房间实体
            {
                标识 = 最近尸体容器,       // 直接用搜索服务登记的战利品容器 id：点击即搜那一份战利品
                类型 = 房间实体类型.尸体,
                阵营 = 房间阵营.中立,
                定义标识 = "尸体",
                名称 = "尸体",
                列 = 尸位.列,
                行 = 尸位.行,
                占格 = false,               // 尸体可以踩过去
                挡视线 = false,
                容器定义 = 搜索?.查找容器(最近尸体容器)
            });
        }
        遭遇目标 = null;
        最近尸体容器 = "";
        刷新视野();
        同步网格();
        播报("周围安静下来了。地上留着具尸体——能翻出点东西。");
        发布显示();
    }

    // 逃跑：敌人留在原地，玩家退回遭遇前那一格
    public void 战斗逃跑()
    {
        if (当前房间 == null) return;
        遭遇中 = false;
        本次战斗来自房间 = false;
        遭遇目标 = null;
        最近尸体容器 = "";
        当前路径.Clear();
        if (当前房间.可通行(遭遇前格.列, 遭遇前格.行))
            当前房间.移动玩家(遭遇前格.列, 遭遇前格.行);
        刷新视野();
        同步网格();
        播报("你退了出来，那东西还在里面。");
        发布显示();
    }

    // ================= 搜索 =================

    // 够得着：玩家是否**正交相邻**于该实体占的任意一格（搜索/查看 的前置条件——隔着屋子不能操作）
    public bool 够得着(房间实体 实体)
    {
        if (当前房间 == null || 实体 == null) return false;
        for (int r = 实体.行; r < 实体.行 + 实体.高; r++)
            for (int c = 实体.列; c < 实体.列 + 实体.宽; c++)
                if (Math.Abs(c - 玩家列) + Math.Abs(r - 玩家行) == 1) return true;
        return false;
    }

    // 右键容器/尸体 → 搜索：**必须先走到旁边**（相邻）→ 首次 扣行动点 + 推时间 → 登记实例定义 → 打开现有搜索面板
    // 容器**不是一次性的**：翻过一次还能再打开（右键给「接着翻」），里头的进度原样留着（翻出来的不会再盖黑块，
    // 没翻的接着翻，拿走的不会回来）。所以 10 行动点 + 5 分钟**只在第一次打开时**扣，再打开只是接着看。
    public bool 搜索容器(房间实体 实体)
    {
        if (当前房间 == null || 实体 == null) return false;
        if (实体.类型 != 房间实体类型.容器 && 实体.类型 != 房间实体类型.尸体) return false;
        if (!够得着(实体)) { 播报("太远了——先走到旁边才能翻。"); return false; }
        bool 首次 = !已翻过(实体);
        if (首次 && (档案 == null || !档案.消耗行动点(搜索行动点)))
        {
            播报("你太累了，翻不动了。");
            音效管理器.实例?.播放失败();
            return false;
        }
        if (首次)
        {
            事件?.发布(new 精力变化事件(档案.行动点, 档案.最大行动点, -搜索行动点));
            推进游戏分钟(搜索游戏分钟);
            实体.已搜 = true;   // 本趟点过（表现位；能不能再翻由 搜索服务 的战局进度说了算，不看这个）
        }
        登记实例(实体);
        音效管理器.实例?.播放成功();
        搜索面板.打开搜索(实例标识(实体));
        播报(首次 ? $"你拉开了{实体.名称}。" : $"你又回到{实体.名称}前，接着翻。");
        发布显示();
        return true;
    }

    // 战局实例 id：容器 → 「房间种子#实体标识」（同一模板换个种子进去就是**另一批实物**，
    // 绝不能共用同一份已生成内容）；尸体 → 用战利品容器自己的 id（战斗系统已按 尸体_N 登记过）。
    public string 实例标识(房间实体 实体)
    {
        if (实体 == null) return "";
        if (实体.类型 == 房间实体类型.尸体) return 实体.标识;
        return $"{房间种子}#{实体.标识}";
    }

    // 这一处翻过没有（问 搜索服务 的战局进度；跨"再进这间房"保持，回安全屋才清）
    public bool 已翻过(房间实体 实体)
    {
        if (实体 == null || 搜索 == null) return false;
        if (实体.类型 != 房间实体类型.容器 && 实体.类型 != 房间实体类型.尸体) return false;
        return 搜索.已打开(实例标识(实体));
    }

    // 容器实例：拿实例 id 登记一份定义副本——同一间房两个"货架"必须各有一份内容
    private void 登记实例(房间实体 实体)
    {
        if (搜索 == null || 实体 == null) return;
        string 实例 = 实例标识(实体);
        if (搜索.已注册实例(实例)) return;
        var 源 = 实体.容器定义;
        if (源 == null) return;
        搜索.注册实例容器(new 搜索容器
        {
            标识 = 实例,
            名称 = 源.名称,
            描述 = 源.描述,
            容器列 = 源.容器列,
            容器行 = 源.容器行,
            容器形状 = 源.容器形状,
            容器允许类型 = 源.容器允许类型,
            搜索时间 = 源.搜索时间,
            搜索表 = 源.搜索表
        });
    }

    // ================= 网格同步（渲染用） =================

    // 把 房间数据 同步成一个 网格服务：墙/容器/尸体/敌人/玩家 全部当"物品堆叠"承载（基类网格框架吃这个）
    private void 同步网格()
    {
        if (当前房间 == null) return;
        if (网格 == null)
        {
            网格 = new 网格服务();
            网格.形状解析 = 标识 => 形状表.TryGetValue(标识, out var 形) ? new 物品形状(形.宽, 形.高) : new 物品形状(1, 1);
        }
        网格.网格列 = 当前房间.列;
        网格.网格行 = 当前房间.行;

        var 新列表 = new List<物品堆叠>();
        var 存活 = new HashSet<房间实体>();
        foreach (var e in 当前房间.实体)
        {
            if (e == null) continue;
            存活.Add(e);
            形状表[e.标识] = (e.宽, e.高);
            if (!框映射.TryGetValue(e, out var 堆叠))
            {
                堆叠 = new 物品堆叠(e.标识, 1);
                框映射[e] = 堆叠;
            }
            堆叠.列 = e.列;
            堆叠.行 = e.行;
            新列表.Add(堆叠);
        }
        // 清理已消失实体的映射（敌人被打死等）
        var 待删 = new List<房间实体>();
        foreach (var kv in 框映射)
            if (!存活.Contains(kv.Key)) 待删.Add(kv.Key);
        foreach (var e in 待删)
        {
            框映射.Remove(e);
            if (网格 != null) 网格.网格物品.RemoveAll(堆叠 => 堆叠 != null && 堆叠.标识 == e.标识);
        }
        网格.网格物品 = 新列表;
    }

    // 只更新玩家令牌位置（走一格的最省刷新路径：基类增量刷新只挪这一个框）
    private void 同步玩家格()
    {
        if (当前房间 == null || 网格 == null) return;
        var 玩家 = 当前房间.玩家();
        if (玩家 == null) return;
        if (!框映射.TryGetValue(玩家, out var 堆叠)) { 同步网格(); return; }
        堆叠.列 = 玩家.列;
        堆叠.行 = 玩家.行;
    }

    // ================= 信息 / 发布 =================

    public string 信息条()
    {
        if (当前房间 == null) return "";
        int 已搜 = 当前房间.已搜数(), 总 = 当前房间.容器总数();
        return $"{当前房间.名称} · {危险度文本(当前房间.危险度)}    " +
               $"行动 {档案?.行动点 ?? 0}/{档案?.最大行动点 ?? 0}    {时间文本()}    " +
               $"已搜 {已搜}/{总}    敌 {当前房间.敌人总数()}";
    }

    public static string 危险度文本(int 危险度)
    {
        string 点 = new string('●', Mathf.Clamp(危险度, 1, 5)) + new string('○', Mathf.Max(0, 5 - 危险度));
        return $"危险 {点}";
    }

    private string 时间文本()
    {
        if (档案 == null) return "";
        int 总分钟 = (int)档案.游戏分钟数;
        int 天 = 总分钟 / 1440 + 1;
        int 时 = 总分钟 % 1440 / 60;
        int 分 = 总分钟 % 60;
        return $"第{天}天 {时:00}:{分:00}";
    }

    // 播报：房间里的提示一律走日志（探索类）——房间面板不再有提示行
    private void 播报(string 文本)
    {
        提示 = 文本;
        事件?.发布(new 日志事件(日志类型.探索, 文本));
    }

    public void 发布显示()
    {
        同步玩家格();
        同步HUD地点();
        事件?.发布(new 房间显示事件(信息条(), 玩家列, 玩家行));
    }

    // HUD 的「地点」位显示房间状态（内容变了才发，避免每走一步都刷 HUD）
    private void 同步HUD地点()
    {
        string 文本 = 地点文本();
        if (文本 == 上次地点) return;
        上次地点 = 文本;
        事件?.发布(new 地图位置事件(地图模式.大地图, 文本, ""));
    }

    // HUD「地点」位：**只显示当前地点名**（如"便利店门厅"）——危险度/进度不进 HUD：
    // 危险度在进门那一条日志里说（见 进入房间），已搜/敌 数则不上 UI（迷雾本来就不该让你预先知道屋里有几只）。
    public string 地点文本() => 当前房间?.名称 ?? "";

    // 推进游戏时间：走世界时间管理器（统一时钟，禁自己加时间）
    private void 推进游戏分钟(int 分钟)
    {
        var 时钟 = ServiceRegistry.Get<世界时间管理器>();
        if (时钟 == null) return;
        时钟.推进(分钟 * 60f / 世界时间管理器.每现实分钟游戏分钟);
    }

    // ================= 数据取用（生成器回调） =================

    // 容器表：(地图类型, 房间) → 该房间的容器定义列表（房间 空 = 该地图类型全部房间）
    private List<搜索容器> 取容器表(string 地图类型, string 房间标识)
    {
        var 结果 = new List<搜索容器>();
        if (数据 == null || string.IsNullOrEmpty(地图类型)) return 结果;
        if (!数据.搜索地图类型.TryGetValue(地图类型, out var 类型) || 类型.房间 == null) return 结果;
        foreach (var 房 in 类型.房间)
        {
            if (房?.容器 == null) continue;
            if (!string.IsNullOrEmpty(房间标识) && 房.标识 != 房间标识) continue;
            foreach (var 容器 in 房.容器)
                if (容器 != null) 结果.Add(容器);
        }
        return 结果;
    }

    // 敌人组：敌人组标识 → 展开成"一只一项"的敌人定义标识列表
    private List<string> 取敌人组(string 敌人组标识)
    {
        var 结果 = new List<string>();
        if (数据 == null || string.IsNullOrEmpty(敌人组标识)) return 结果;
        if (!数据.敌人组.TryGetValue(敌人组标识, out var 组) || 组.敌人 == null) return 结果;
        foreach (var 项 in 组.敌人)
            for (int i = 0; i < Mathf.Max(1, 项.数量); i++)
                结果.Add(项.敌人);
        return 结果;
    }

using System;
using System.Collections.Generic;
using UnityEngine;

// ============================================================
// 房间探索服务：**房间层**的状态机（纯逻辑，零 MonoBehaviour）。基类 = 格子探索服务（格子世界运行器）。
// 循环：进入房间（按种子生成）→ 点格寻路（走 1 格 = 1 游戏分钟）→ 右键容器搜索（扣 10 行动点）
//       → 看见/撞上敌人则遭遇（切战斗沙盒）→ 打完留下可搜尸体 → 离开。
// 本文件只管"房间语义"：门与锁（钥匙 / 撬锁）、钥匙投放、搜索容器、遭遇与战斗收尾、HUD 信息条。
// 通用的一半（令牌 / 路径 / 视野 / 迷雾 / 网格同步 / 事件发布 / 回安全屋清战局）全在基类里。
// ============================================================
public sealed class 房间探索服务 : 格子探索服务
{
    // —— 规则常量（第 1 刀定版）——
    public const int 搜索行动点 = 10;       // 搜一处扣的行动点（与 探索服务 一致）
    public const int 搜索游戏分钟 = 5;      // 搜一处推进的游戏分钟

    // 与 BattleService.开始战斗 的 先手 参数同语义：0=速度序 1=敌方绝对先手（被偷袭）2=我方绝对先手（偷袭）
    public const int 先手撞上 = 1;          // 相邻撞上：敌人先手
    public const int 先手看清 = 2;          // 视野内 ≥3 格先看见：玩家先手

    // 开锁路径（三条；砸锁**本刀留空**：枚举留着、菜单不出、调用返回 false，等以后做"巨响惊动敌人"再接）
    public enum 开锁方式 { 钥匙, 撬锁, 砸锁 }

    // 门锁数值（都在这里，调平衡只改这几行）
    public const int 钥匙开锁游戏分钟 = 1;    // 用钥匙：最快，不耗行动点
    public const int 撬锁游戏分钟 = 3;        // 撬锁：失败也照样花掉
    public const int 撬锁行动点 = 5;
    public const int 撬锁耐久损耗 = 1;        // 失败扣工具耐久（工具有耐久上限才扣；钳子这类"用不坏"的不扣）
    public const int 撬锁基础成功率 = 55;     // %：55 + 敏捷×3 + 智慧×2，夹到 [5, 95]
    public const string 撬锁用途 = "撬锁";    // 物品数据.用途 标记（撬棍 / 螺丝刀 / 钳子）

    private readonly BattleService 战斗;
    private readonly 搜索服务 搜索;

    private readonly HashSet<网格实体> 已察觉 = new HashSet<网格实体>();   // 曾在 ≥3 格距离被看见的敌人（遭遇时给我方先手）

    // 本趟已解锁的门（键 = 实例标识）：与容器战局数据 / 视野记忆同一生命期 —— **回安全屋才清**，
    // 所以走回头路不会再锁上（房间每次重进都会重新生成，锁态要在这里记住）
    private readonly HashSet<string> 已解锁门 = new HashSet<string>();

    // 钥匙挂在敌人身上时：**指定是哪一只**（门实体标识 → (钥匙物品, 敌人实体标识)）。
    // 一场遭遇只打一个敌人，所以必须说清"钥匙在哪一只身上"：杀了它才掉，杀别的没有。
    private readonly Dictionary<string, (string 钥匙, string 敌人标识)> 敌人身上的钥匙 = new Dictionary<string, (string, string)>();

    // 当前这间房（UI 一直用这个名字；实体就是基类的 当前世界）
    public 网格数据 当前房间 => 当前世界;
    public bool 本次战斗来自房间 { get; private set; }

    // ================= 建筑层（第 3 层）：一栋楼 = 楼层 + 楼梯 =================
    // 在建筑里时：当前房间 = 当前层的那间房；上楼/下楼 = 换层（楼层缓存保证"杀过的敌人不会复活"）
    public 建筑模板 当前建筑 { get; private set; }
    public int 当前层 { get; private set; } = -1;
    public bool 在建筑里 => 当前建筑 != null && 当前层 >= 0;
    private int 建筑种子;
    // 楼层缓存：键 = "层#序号"。**同一趟出行里**回楼上楼下看到的是同一批柜子/尸体/敌人（回安全屋或出楼才清）
    private readonly Dictionary<string, 网格数据> 楼层缓存 = new Dictionary<string, 网格数据>();

    public 房间探索服务(EventBus 事件, DataService 数据, PlayerService 玩家服务, BattleService 战斗, 搜索服务 搜索)
        : base(事件, 数据, 玩家服务)
    {
        this.战斗 = 战斗;
        this.搜索 = 搜索;
        if (事件 != null) 事件.订阅<战斗结束事件>(战斗结束响应);
    }

    // ================= 基类钩子（房间语义） =================

    // 回安全屋：容器的战局临时数据（已生成内容 / 已翻标记 / 尸体容器）整体作废——下一趟出去是全新的一批物资。
    // 迷雾记忆（视野记忆）在同一时机清（基类做），门锁在这里清：下一趟出去，柜子是新的一批、门也重新锁。
    protected override void 清战局()
    {
        搜索?.清空战局();
        已解锁门.Clear();
        楼层缓存.Clear();   // 楼也一起"重新生成"：下一趟进来是全新的一栋（柜子/尸体/敌人都复位）
    }

    // 视野刷新之后：记"在 ≥3 格看清过的敌人"（遭遇时给玩家先手）
    protected override void 刷新视野之后()
    {
        var 敌人们 = 当前世界.取类型(网格实体类型.敌人);
        foreach (var 敌 in 敌人们)
        {
            if (!当前可见.Contains(网格数据.编码(敌.列, 敌.行))) continue;
            int 距 = Math.Abs(敌.列 - 玩家列) + Math.Abs(敌.行 - 玩家行);
            if (距 >= 3) 已察觉.Add(敌);
        }
    }

    // 走完一步：先看遭遇，再看脚下是不是"能过的门"（顺序与原实现一致）
    protected override bool 抵达后检查() => 检查遭遇();
    protected override bool 抵达格() => 踩到能过的门();

    // 房间层的"显示"事件（面板/图层订阅）
    protected override void 发布显示事件(string 信息条, int 列, int 行)
        => 事件?.发布(new 房间显示事件(信息条, 列, 行));

    // 离开前：清房间自己的临时表
    protected override void 离开前()
    {
        敌人身上的钥匙.Clear();
        已察觉.Clear();
        本次战斗来自房间 = false;
    }

    // ================= 进出 =================

    // 进入房间：按模板 + 种子生成（同模板同种子 = 同布局），建网格、揭初始视野、打开面板
    // 来路 = 上一间房的模板标识（穿过门进来时给；空 = 从外面进来 → 这一间就是本趟出行的起点，外墙上有大门）
    public bool 进入房间(string 模板标识, int 种子, string 来路 = "")
    {
        if (数据 == null || !数据.房间模板.TryGetValue(模板标识, out var 模板))
        {
            Debug.LogError($"[房间] 模板不存在: {模板标识}");
            return false;
        }
        当前建筑 = null;    // 单间模式：不是在一栋楼里（楼里进出房间走 进入建筑 / 切到房间）
        当前层 = -1;
        楼层缓存.Clear();
        bool 从外面进 = string.IsNullOrEmpty(来路);
        if (从外面进)
        {
            出行种子 = 种子;          // 本趟出行的基准种子：门后每一间房的种子都由它派生
            出行起点标识 = 模板标识;   // 起点房（外墙上有大门的那一间）
        }
        // 同一趟出行里，每间房的种子 = 派生(出行种子, 模板标识) → 走回头路看到的还是同一间房（柜子状态也才留得住）
        int 实种子 = 确定性随机.派生(出行种子, 模板标识);
        存视野记忆();   // 先把**上一间房**看过的格存回记忆表（换房前必须存，后面会清空 已探索）
        当前世界 = 房间生成器.生成(实种子, 模板, 取容器表, 取敌人组, 含大门: 模板标识 == 出行起点标识);
        if (当前世界 == null) return false;
        当前种子 = 实种子;
        // 落点：从门进来 → 站在"通回来那扇门"的内侧（不是门格本身，否则会被立刻弹回去）；从外面进 → 入口格
        (int 列, int 行)? 落点 = null;
        if (!从外面进)
        {
            var 回门 = 当前世界.找门通向(来路);
            if (回门 != null) 落点 = 当前世界.门内侧格(回门);
        }
        装好房间(当前世界, 落点);
        播报(从外面进 ? $"你推开了{当前世界.名称}的门。{危险度文本(当前世界.危险度)}"
                        : $"你推门进了{当前世界.名称}。{危险度文本(当前世界.危险度)}");
        发布显示();
        return true;
    }

    // 把一间（新生成 / 缓存里的）房"装好"：落点 / 门锁写回 / 放钥匙 / 迷雾记忆 / 刷新视野 / 同步网格 / 发事件。
    // **不清容器战局数据**（见 清战局）：这间房上次翻过的柜子，这次还是那副样子。
    private void 装好房间(网格数据 房, (int 列, int 行)? 落点)
    {
        if (房 == null) return;
        if (落点 != null && 房.可通行(落点.Value.列, 落点.Value.行)) 房.移动玩家(落点.Value.列, 落点.Value.行);
        // 门锁：本趟已解锁的门**重进也要是开着的**（房间可能刚重新生成，锁态在这里写回）
        var 门列表 = 房.门列表();
        for (int i = 0; i < 门列表.Count; i++)
        {
            var 门 = 门列表[i];
            if (string.IsNullOrEmpty(门.锁钥匙)) continue;
            if (!已解锁门.Contains(实例标识(门))) continue;
            门.已解锁 = true;
            门.占格 = false;
            门.挡视线 = false;
        }
        放钥匙();   // 还锁着的门：钥匙随机塞进本房某个容器（第一次生成那个柜子的内容时塞进去）
        已探索.Clear();
        // 这间房以前看过的地方：把记忆装回来（走门回来 / 出楼再进来，迷雾不该整间又变黑）
        if (视野记忆.TryGetValue(记忆键(房.模板标识, 当前种子), out var 旧记忆) && 旧记忆 != null) 已探索.UnionWith(旧记忆);
        当前可见.Clear();
        已察觉.Clear();
        当前路径.Clear();
        遭遇中 = false;
        本次战斗来自房间 = false;
        遭遇目标 = null;
        最近尸体容器 = "";
        刷新视野();
        同步网格();
        事件?.发布(new 打开房间事件(房.模板标识, 当前种子));
    }

    // ================= 建筑层：进楼 / 上下楼 =================

    // 进楼（从区域或外面进来）：落在"有大门那一层"的首间房（= 楼梯间）
    public bool 进入建筑(string 建筑标识, int 种子)
    {
        if (数据 == null || !数据.建筑模板.TryGetValue(建筑标识, out var 模板))
        {
            Debug.LogError($"[建筑] 建筑模板不存在: {建筑标识}");
            return false;
        }
        建筑种子 = 种子;
        出行种子 = 种子;          // 这一趟（这一栋）的基准种子：各层房间的种子由它派生
        出行起点标识 = 建筑标识;
        当前建筑 = 模板;
        当前层 = -1;
        楼层缓存.Clear();
        int 层 = 建筑生成器.入口层(模板);
        if (!切到房间(层, 0, 从外面进: true))
        {
            当前建筑 = null;
            return false;
        }
        播报($"你走进了{模板.名称}（{建筑生成器.楼层名(模板, 层)}）。{危险度文本(模板.危险度)}");
        发布显示();
        return true;
    }

    // 上楼 / 下楼：得站到楼梯格上（或正交相邻）——楼梯是外墙上那一格"凸"
    public bool 上楼() => 换层(1);
    public bool 下楼() => 换层(-1);

    public bool 够得着楼梯(网格实体 梯)
    {
        if (当前世界 == null || 梯 == null || 梯.类型 != 网格实体类型.楼梯) return false;
        return Math.Abs(梯.列 - 玩家列) + Math.Abs(梯.行 - 玩家行) <= 1;
    }

    private bool 换层(int 方向)
    {
        if (!在建筑里 || 遭遇中) return false;
        int 目标 = 当前层 + 方向;
        if (目标 < 0 || 目标 >= 建筑生成器.楼层数(当前建筑))
        {
            播报(方向 > 0 ? "上面没有了。" : "下面没有了。");
            音效管理器.实例?.播放失败();
            return false;
        }
        var 梯 = 当前世界.楼梯列表().Find(够得着楼梯);
        if (梯 == null)
        {
            播报("先走到楼梯口。");
            音效管理器.实例?.播放失败();
            return false;
        }
        // 目标层的楼梯和这层**同坐标、同朝向**（硬规则：全楼同尺寸 + 楼梯位全楼共用）→ 内侧格也相同
        var 内侧 = 当前世界.门内侧格(梯);
        if (!切到房间(目标, 0, 从外面进: false, 落点: 内侧))
        {
            播报("楼梯那边过不去。");
            音效管理器.实例?.播放失败();
            return false;
        }
        string 名 = 建筑生成器.楼层名(当前建筑, 目标);
        播报(方向 > 0 ? $"你上了{名}。" : $"你下了{名}。");
        发布显示();
        return true;
    }

    // 换到某一层的某一间房（**缓存优先**：回楼上楼下看到的是同一批柜子/尸体/敌人）
    private bool 切到房间(int 层, int 序号, bool 从外面进, string 来路 = "", (int 列, int 行)? 落点 = null)
    {
        if (当前建筑?.楼层 == null || 层 < 0 || 层 >= 当前建筑.楼层.Length) return false;
        var 楼层项 = 当前建筑.楼层[层];
        if (楼层项?.房间 == null || 序号 < 0 || 序号 >= 楼层项.房间.Length) return false;
        存视野记忆();   // 先把**上一间房**看过的格存回记忆表（换房前必须存，后面会清空 已探索）
        string 键 = $"{层}#{序号}";
        if (!楼层缓存.TryGetValue(键, out var 房))
        {
            string 模板标识 = 楼层项.房间[序号];
            if (数据 == null || !数据.房间模板.TryGetValue(模板标识, out var 模板)) return false;
            bool 首间 = 序号 == 0;
            var 位 = 建筑生成器.楼梯位(建筑种子, 当前建筑);
            房 = 房间生成器.生成(建筑生成器.房间种子(建筑种子, 层, 序号), 模板, 取容器表, 取敌人组,
                              含大门: 首间 && 楼层项.大门, 楼梯: 首间 ? 位 : ((int, int)?)null);
            if (房 == null) return false;
            楼层缓存[键] = 房;
        }
        当前世界 = 房;
        当前层 = 层;
        当前种子 = 建筑生成器.房间种子(建筑种子, 层, 序号);
        if (落点 == null && !从外面进 && !string.IsNullOrEmpty(来路))
        {
            var 回门 = 房.找门通向(来路);
            if (回门 != null) 落点 = 房.门内侧格(回门);
        }
        装好房间(房, 落点);
        return true;
    }

    // 离开房间：清空本局的**房间态**（房间结构本来就不存档，随用随生成）；
    // 容器的战局临时数据不在这次清（一路搜到的进度留到回安全屋为止，见 清战局）
    public void 离开()
    {
        if (当前世界 == null) return;
        离开世界();   // 存视野记忆 → 离开前()（清钥匙表 / 已察觉 / 战斗标记）→ 清空世界态
        当前建筑 = null;
        当前层 = -1;
        楼层缓存.Clear();   // 楼的结构不存档：下一次进这栋楼是新的一批（柜子进度由 搜索服务 管到回安全屋）
        // HUD 地点位还给"外面那一层"：谁在跑就给谁（区域副本 → 区域；直接从大世界进楼 → 大世界）。
        // 原来是把 档案.当前大节点 这个字符串刷回去；节点网图退役后没有这个字段了。
        var 区服 = ServiceRegistry.Get<区域探索服务>();
        if (区服 != null && 区服.探索中) { 区服.发布显示(); return; }
        var 世服 = ServiceRegistry.Get<大世界探索服务>();
        if (世服 != null && 世服.探索中) { 世服.发布显示(); return; }
        事件?.发布(new 地图位置事件(地图模式.大地图, "安全屋"));
    }

    // ================= 门 =================

    public bool 锁着(网格实体 门) => 门 != null && 门.锁着;

    // 够得着门：站在门格上，或与门格正交相邻（跟"够得着容器"同一套手感：门口那一步之内）
    public bool 够得着门(网格实体 门)
    {
        if (当前世界 == null || 门 == null || 门.类型 != 网格实体类型.门) return false;
        return Math.Abs(门.列 - 玩家列) + Math.Abs(门.行 - 玩家行) <= 1;
    }

    // 开锁：走到门前（锁着站不上去，A* 只会把你送到门前那一格）→ 右键选一条路
    public bool 开锁(网格实体 门, 开锁方式 方式)
    {
        if (当前世界 == null || 门 == null || 门.类型 != 网格实体类型.门 || 遭遇中) return false;
        if (!门.锁着) { 播报("这扇门没锁，直接走过去就行。"); return false; }
        if (!够得着门(门)) { 播报("太远了——先走到门前。"); 音效管理器.实例?.播放失败(); return false; }
        switch (方式)
        {
            case 开锁方式.钥匙: return 用钥匙开锁(门);
            case 开锁方式.撬锁: return 撬锁开门(门);
            default:
                播报("砸锁还没做。");   // 留空：等做"巨响惊动敌人"再接
                音效管理器.实例?.播放失败();
                return false;
        }
    }

    // ① 用钥匙：开一次就消耗（每把钥匙只认这一扇门）
    private bool 用钥匙开锁(网格实体 门)
    {
        if (档案 == null || !档案.持有物品(门.锁钥匙))
        {
            播报($"你身上没有{门.锁钥匙}。");
            音效管理器.实例?.播放失败();
            return false;
        }
        string 钥匙 = 门.锁钥匙;
        档案.移除物品(钥匙, 1);
        事件?.发布(new 背包变化事件(钥匙, -1, 变化原因.消耗));
        推进游戏分钟(钥匙开锁游戏分钟);
        解锁(门);
        音效管理器.实例?.播放成功();
        播报($"你用{钥匙}拧开了{门.名称}，顺手把钥匙留在了锁孔里。");
        return true;
    }

    // ② 撬锁：花行动点 + 时间，按成功率判定；失败扣工具耐久（能反复试）
    private bool 撬锁开门(网格实体 门)
    {
        string 工具 = 找撬锁工具();
        if (string.IsNullOrEmpty(工具))
        {
            播报("你身上没有能撬锁的东西（撬棍 / 螺丝刀 / 钳子）。");
            音效管理器.实例?.播放失败();
            return false;
        }
        if (档案 == null || !档案.消耗行动点(撬锁行动点))
        {
            播报("你太累了，手抖得对不准锁孔。");
            音效管理器.实例?.播放失败();
            return false;
        }
        事件?.发布(new 精力变化事件(档案.行动点, 档案.最大行动点, -撬锁行动点));
        推进游戏分钟(撬锁游戏分钟);
        int 成功率 = 撬锁成功率();
        if (UnityEngine.Random.Range(0, 100) < 成功率)
        {
            解锁(门);
            音效管理器.实例?.播放成功();
            播报($"你用{工具}别开了锁芯——咔哒一声，{门.名称}开了。");
            return true;
        }
        bool 磨损 = 档案.扣背包耐久(工具, 撬锁耐久损耗);
        音效管理器.实例?.播放失败();
        播报(磨损 ? $"锁芯卡住了，{工具}崩掉一块（耐久 -{撬锁耐久损耗}）。" : $"锁芯卡住了，{工具}没能别开。");
        发布显示();
        return false;
    }

    // 身上能撬锁的东西：物品数据.用途 == "撬锁"；优先"用不坏的"（无耐久上限），否则用当前耐久最高的
    public string 找撬锁工具()
    {
        if (数据 == null || 档案 == null) return "";
        string 最好 = "";
        int 最好分 = int.MinValue;
        foreach (var (标识, 物品) in 数据.物品)
        {
            if (物品 == null || 物品.用途 != 撬锁用途) continue;
            if (!档案.持有物品(标识)) continue;
            int 上限 = 档案.有效最大耐久(标识);
            int 分 = 上限 <= 0 ? int.MaxValue : Math.Max(0, 档案.背包当前耐久(标识));   // 无耐久 = 用不坏，最优先
            if (分 > 最好分) { 最好分 = 分; 最好 = 标识; }
        }
        return 最好;
    }

    public int 撬锁成功率()
    {
        int 敏 = 档案?.敏捷 ?? 0, 智 = 档案?.智慧 ?? 0;
        return Mathf.Clamp(撬锁基础成功率 + 敏 * 3 + 智 * 2, 5, 95);
    }

    // 解锁：门变成"能站、能看穿"的门洞 → 走上去就转移；并记进本趟的解锁表
    private void 解锁(网格实体 门)
    {
        门.已解锁 = true;
        门.占格 = false;
        门.挡视线 = false;
        已解锁门.Add(实例标识(门));
        发布显示();
    }

    // 门链：踩到"能过的门"上 → 直接转移（内门 = 去那间房；大门 = 出楼）
    // 建筑里：门只在**本层内**串联（跨层一律走楼梯）
    private bool 推门出去(网格实体 门)
    {
        if (门.是大门 || string.IsNullOrEmpty(门.通向))
        {
            播报("你从大门走了出去。");
            发布显示();
            事件?.发布(new 离开房间事件());   // 出楼：UI 侧回上一个面板（房间面板.回退 → 服务.离开）
            return true;
        }
        if (在建筑里)
        {
            int 序号 = 建筑生成器.房间序号(当前建筑, 当前层, 门.通向);
            if (序号 < 0)
            {
                播报("那扇门通不到这儿。");
                音效管理器.实例?.播放失败();
                return false;
            }
            string 来路 = 当前世界.模板标识;
            if (!切到房间(当前层, 序号, 从外面进: false, 来路: 来路)) return false;
            播报($"你推门进了{当前世界.名称}。{危险度文本(当前世界.危险度)}");
            发布显示();
            return true;
        }
        return 进入房间(门.通向, 出行种子, 当前世界.模板标识);
    }

    // 脚下这一格是不是"能过的门"（无锁 / 已解锁）→ 是就转移
    private bool 踩到能过的门()
    {
        if (当前世界 == null) return false;
        var 门们 = 当前世界.门列表();
        for (int i = 0; i < 门们.Count; i++)
        {
            if (!门们[i].覆盖(玩家列, 玩家行)) continue;
            if (门们[i].锁着) return false;    // 锁着（占格，正常上不去）
            return 推门出去(门们[i]);
        }
        return false;
    }

    // 门的显示名（右键菜单用）：内门带目标房名，大门 = 外面
    public string 门去向文本(网格实体 门)
    {
        if (门 == null) return "";
        if (门.是大门 || string.IsNullOrEmpty(门.通向)) return "外面";
        if (数据 != null && 数据.房间模板.TryGetValue(门.通向, out var 目标) && !string.IsNullOrEmpty(目标.名称)) return 目标.名称;
        return 门.通向;
    }

    // ================= 钥匙投放（锁着的门：钥匙随机塞进本房某个容器 / 或挂在本房敌人身上） =================

    // 钥匙在谁身上：**按种子随机**（同一趟同一间房固定，重玩会变）
    //   · 本房有敌人 → 钥匙挂在敌人身上：打死他们 → 战斗胜利在遭遇格留一具尸体（战利品容器）→ 翻尸体拿钥匙
    //   · 本房有柜子 → 钥匙塞进某个容器（那个柜子的内容第一次生成时塞）
    //   · 敌人 / 柜子都没有（或柜子塞不下）→ 顺延另一种来源；两种都没有 → 那扇门自动取消锁
    private void 放钥匙()
    {
        if (搜索 == null || 当前世界 == null) return;
        敌人身上的钥匙.Clear();   // 每间房重新决定（这间房若把钥匙挂在敌人身上，就记在这）
        var 容器们 = 当前世界.取类型(网格实体类型.容器);
        var 敌人们 = 当前世界.取类型(网格实体类型.敌人);
        bool 有敌人 = 敌人们.Count > 0;
        foreach (var 门 in 当前世界.门列表())
        {
            if (!门.锁着) continue;                      // 无锁 / 本趟已解锁：不用放
            if (容器们.Count == 0 && !有敌人)
            {
                // 兜底：这间房既没柜子也没敌人 → 钥匙无处可放，门自动不锁（绝不出现"永远打不开的门"）
                门.锁钥匙 = "";
                门.占格 = false;
                门.挡视线 = false;
                Debug.LogWarning($"[房间] {当前世界.名称} 既没有容器也没有敌人，{门.标识} 的锁自动取消（钥匙没地方放）");
                continue;
            }
            var 源流 = 确定性随机.随机流(确定性随机.派生(当前种子, $"钥匙来源{门.标识}"));
            bool 放敌人身上 = 有敌人 && (容器们.Count == 0 || 确定性随机.范围(源流, 0, 1) == 0);   // 50/50；没柜子就只能挂敌人
            if (放敌人身上)
            {
                // 按种子指定**哪一只**敌人带着钥匙：一场遭遇只打一只，杀了它才掉
                var 敌流 = 确定性随机.随机流(确定性随机.派生(当前种子, $"钥匙敌人{门.标识}"));
                var 持有者 = 敌人们[确定性随机.范围(敌流, 0, 敌人们.Count - 1)];
                敌人身上的钥匙[门.标识] = (门.锁钥匙, 持有者.标识);
                Debug.Log($"[房间] {当前世界.名称}：{门.锁钥匙} 在 {持有者.名称}[{持有者.标识}] 身上");
                continue;
            }
            // 放柜子里：按种子挑一个，塞不下的顺延下一个
            var 流 = 确定性随机.随机流(确定性随机.派生(当前种子, $"钥匙{门.标识}"));
            int 起 = 确定性随机.范围(流, 0, 容器们.Count - 1);
            for (int i = 0; i < 容器们.Count; i++)
                if (塞钥匙(容器们[(起 + i) % 容器们.Count], 门.锁钥匙)) break;   // 这个柜子放不下 → 顺延下一个
        }
    }

    // 塞钥匙进某个柜子：返回 true = 处理完了（塞进去了 / 内容早生成过不用再塞）；false = 这柜子不合适，换下一个
    private bool 塞钥匙(网格实体 柜, string 钥匙)
    {
        if (柜 == null || 柜.容器定义 == null || string.IsNullOrEmpty(钥匙)) return false;
        登记实例(柜);
        string 实例 = 实例标识(柜);
        if (搜索.已打开(实例)) return true;      // 内容已生成（钥匙早塞过 / 已被拿走）→ 不重复塞
        return 把钥匙放进容器(实例, 钥匙);
    }

    // 把钥匙塞进「已经注册过的容器」（柜子 / 尸体战利品都走这里）
    private bool 把钥匙放进容器(string 容器标识, string 钥匙)
    {
        if (搜索 == null || string.IsNullOrEmpty(容器标识) || string.IsNullOrEmpty(钥匙)) return false;
        var 定义 = 搜索.查找容器(容器标识);
        var 视图 = 搜索.打开(定义);
        if (视图?.网格物品 == null) return false;
        var 堆叠 = new 物品堆叠(钥匙, 1);
        var 空位 = 视图.寻找可放置格智能旋转(堆叠, out bool 需旋转);
        if (空位 == null) return false;           // 塞满了 → 调用方换下一个来源
        堆叠.旋转 = 需旋转;
        堆叠.列 = 空位.Value.列;
        堆叠.行 = 空位.Value.行;
        视图.网格物品.Add(堆叠);
        return true;
    }

    // 钥匙挂在敌人身上时：**杀了那一只**这一场 → 把钥匙塞进它的战利品容器（尸体实体随后才创建，正好带着钥匙）
    // 战利品为空（没生成尸体）= 塞不进去 → 顺延到本房柜子（不让钥匙凭空消失）
    private void 塞钥匙进尸体(string 尸体容器, string 死者标识)
    {
        if (string.IsNullOrEmpty(死者标识) || 敌人身上的钥匙.Count == 0) return;
        string 门键 = 找持钥门(死者标识);
        if (string.IsNullOrEmpty(门键)) return;        // 死的不是带钥匙那只 → 什么都没掉
        string 钥匙 = 敌人身上的钥匙[门键].钥匙;
        if (!string.IsNullOrEmpty(尸体容器) && 把钥匙放进容器(尸体容器, 钥匙))
        {
            敌人身上的钥匙.Remove(门键);
            Debug.Log($"[房间] {死者标识} 身上掉出了 {钥匙}");
            return;
        }
        var 容器们 = 当前世界?.取类型(网格实体类型.容器);
        if (容器们 != null)
            for (int i = 0; i < 容器们.Count; i++)
                if (塞钥匙(容器们[i], 钥匙))
                {
                    敌人身上的钥匙.Remove(门键);
                    Debug.LogWarning($"[房间] 战利品为空、没生成尸体，{钥匙} 改放进本房容器");
                    return;
                }
    }

    // 哪扇门把钥匙挂在这个死者身上（没有 → 空）
    private string 找持钥门(string 死者标识)
    {
        foreach (var (门键, 值) in 敌人身上的钥匙)
            if (值.敌人标识 == 死者标识) return 门键;
        return "";
    }

    // 调试/自检用：本房"钥匙挂在敌人身上"的摘要（空 = 本房钥匙不在敌人身上）
    public string 敌人持钥摘要()
    {
        if (敌人身上的钥匙.Count == 0) return "";
        var 段 = new List<string>();
        foreach (var (_, 值) in 敌人身上的钥匙) 段.Add($"{值.钥匙} 在 {值.敌人标识} 身上");
        return string.Join("；", 段);
    }

    // ================= 遭遇 / 战斗 =================

    // 玩家是否与敌人相邻 → 触发遭遇（敌人先手；若先前在 ≥3 格看清过该敌人 → 玩家先手）
    private bool 检查遭遇()
    {
        if (当前世界 == null || 遭遇中) return false;
        foreach (var 敌 in 当前世界.取类型(网格实体类型.敌人))
        {
            if (Math.Abs(敌.列 - 玩家列) + Math.Abs(敌.行 - 玩家行) != 1) continue;
            开始遭遇(敌);
            return true;
        }
        return false;
    }

    private void 开始遭遇(网格实体 敌)
    {
        遭遇中 = true;
        遭遇目标 = 敌;
        本次战斗来自房间 = true;
        当前路径.Clear();
        int 先手 = 已察觉.Contains(敌) ? 先手看清 : 先手撞上;
        播报(先手 == 先手看清 ? $"你早就看见它了——先动手。（{敌.名称}）" : $"{敌.名称}扑了上来！");
        if (战斗 == null)
        {
            Debug.LogError("[房间] 战斗服务未装配，遭遇无法开始");
            return;
        }
        // **一场遭遇 = 一个敌人**：只把这一个标识的（定义标识 + 网格实体标识）交给战斗。
        // 房间里的敌人是一只一个标识，解决掉它，再碰到下一只就是另一场战斗 ——
        // 既不按 敌人组 展开（那是"一个标识变多只"的旧 bug），也不把整间房一起拉进来打。
        var 参战 = new List<(string 定义标识, string 实例标识)>
        {
            (敌.定义标识, 敌.标识)
        };
        Debug.Log($"[房间] {当前世界.名称} 遭遇 {敌.名称}[{敌.标识}]：参战 1 只（一个标识 = 一个敌人）");
        战斗.开始战斗(当前世界.敌人组, "__房间胜利", "__房间返回", 先手, "", 当前世界.战斗棋盘, 参战);
    }

    // 战斗结束（BattleService 发布）：先记住本次的战利品尸体容器（钥匙投放留到 战斗胜利 —— 那时尸体容器一定已经备好）
    private void 战斗结束响应(战斗结束事件 e)
    {
        if (!本次战斗来自房间) return;
        if (!e.胜利) return;
        if (!string.IsNullOrEmpty(e.尸体容器)) 最近尸体容器 = e.尸体容器;
    }

    // 胜利：**只解决掉遭遇的那一只**（一个标识 = 一个敌人），在它的位置留一具可搜尸体。
    // 尸体是硬保证：战斗没产出战利品（很多敌人补给值 <4 → 面包/水 都是 0、又没有掉落）时，
    // 这里自己登记一具**空尸体** —— 打死谁都得留下一具能翻的（钥匙挂在它身上时也才有地方掉）。
    // 屋里其它的敌人原封不动 —— 之后碰到哪一只，就是和哪一只的另一场遭遇。
    public void 战斗胜利()
    {
        if (当前世界 == null) return;
        遭遇中 = false;
        本次战斗来自房间 = false;
        var 尸位 = 遭遇目标;
        if (尸位 != null) 当前世界.移除实体(尸位);   // 只移除被解决的那一只（原来是"敌人全灭"）
        bool 还有敌人 = 当前世界.敌人总数() > 0;
        if (尸位 != null && string.IsNullOrEmpty(最近尸体容器) && 搜索 != null)
            最近尸体容器 = 搜索.注册尸体容器("敌人的尸体", 8, 5, null, 0.5f);   // 空尸体（搜一下就知道啥也没有，不拖时间）
        // 钥匙挂在这一只身上 → 塞进它的尸体（先把尸体容器备好，再决定钥匙放哪；放不进去才顺延放本房柜子）
        塞钥匙进尸体(最近尸体容器, 尸位?.标识 ?? "");
        if (尸位 != null && !string.IsNullOrEmpty(最近尸体容器))
        {
            当前世界.实体.Add(new 网格实体
            {
                标识 = 最近尸体容器,       // 直接用搜索服务登记的战利品容器 id：点击即搜那一份战利品
                类型 = 网格实体类型.尸体,
                阵营 = 网格阵营.中立,
                定义标识 = "尸体",
                名称 = "尸体",
                列 = 尸位.列,
                行 = 尸位.行,
                占格 = false,               // 尸体可以踩过去
                挡视线 = false,
                容器定义 = 搜索?.查找容器(最近尸体容器)
            });
        }
        遭遇目标 = null;
        最近尸体容器 = "";
        刷新视野();
        同步网格();
        播报(还有敌人 ? "它倒下了。地上留着具尸体——屋里还有别的东西在动。"
                      : "周围安静下来了。地上留着具尸体——能翻出点东西。");
        发布显示();
        事件?.发布(new 回到房间事件());   // 战斗结算完：面板管理器 把面板切回房间面板（否则战斗面板会留在最上面）
    }

    // 逃跑：敌人留在原地，玩家退回遭遇前那一格
    public void 战斗逃跑()
    {
        if (当前世界 == null) return;
        遭遇中 = false;
        本次战斗来自房间 = false;
        遭遇目标 = null;
        最近尸体容器 = "";
        当前路径.Clear();
        if (当前世界.可通行(遭遇前格.列, 遭遇前格.行))
            当前世界.移动玩家(遭遇前格.列, 遭遇前格.行);
        刷新视野();
        同步网格();
        播报("你退了出来，那东西还在里面。");
        发布显示();
        事件?.发布(new 回到房间事件());   // 逃跑结算完：同样把面板切回房间面板
    }

    // ================= 搜索 =================

    // 右键容器/尸体 → 搜索：**必须先走到旁边**（相邻）→ 首次 扣行动点 + 推时间 → 登记实例定义 → 打开现有搜索面板
    // 容器**不是一次性的**：翻过一次还能再打开（右键给「接着翻」），里头的进度原样留着（翻出来的不会再盖黑块，
    // 没翻的接着翻，拿走的不会回来）。所以 10 行动点 + 5 分钟**只在第一次打开时**扣，再打开只是接着看。
    public bool 搜索容器(网格实体 实体)
    {
        if (当前世界 == null || 实体 == null) return false;
        if (实体.类型 != 网格实体类型.容器 && 实体.类型 != 网格实体类型.尸体) return false;
        if (!够得着(实体)) { 播报("太远了——先走到旁边才能翻。"); return false; }
        bool 首次 = !已翻过(实体);
        if (首次 && (档案 == null || !档案.消耗行动点(搜索行动点)))
        {
            播报("你太累了，翻不动了。");
            音效管理器.实例?.播放失败();
            return false;
        }
        if (首次)
        {
            事件?.发布(new 精力变化事件(档案.行动点, 档案.最大行动点, -搜索行动点));
            推进游戏分钟(搜索游戏分钟);
            实体.已搜 = true;   // 本趟点过（表现位；能不能再翻由 搜索服务 的战局进度说了算，不看这个）
        }
        登记实例(实体);
        音效管理器.实例?.播放成功();
        搜索面板.打开搜索(实例标识(实体));
        播报(首次 ? $"你拉开了{实体.名称}。" : $"你又回到{实体.名称}前，接着翻。");
        发布显示();
        return true;
    }

    // 战局实例 id：容器 → 「当前种子#实体标识」（同一模板换个种子进去就是**另一批实物**，
    // 绝不能共用同一份已生成内容）；尸体 → 用战利品容器自己的 id（战斗系统已按 尸体_N 登记过）。
    public string 实例标识(网格实体 实体)
    {
        if (实体 == null) return "";
        if (实体.类型 == 网格实体类型.尸体) return 实体.标识;
        return $"{当前种子}#{实体.标识}";
    }

    // 这一处翻过没有（问 搜索服务 的战局进度；跨"再进这间房"保持，回安全屋才清）
    public bool 已翻过(网格实体 实体)
    {
        if (实体 == null || 搜索 == null) return false;
        if (实体.类型 != 网格实体类型.容器 && 实体.类型 != 网格实体类型.尸体) return false;
        return 搜索.已打开(实例标识(实体));
    }

    // 容器实例：拿实例 id 登记一份定义副本——同一间房两个"货架"必须各有一份内容
    private void 登记实例(网格实体 实体)
    {
        if (搜索 == null || 实体 == null) return;
        string 实例 = 实例标识(实体);
        if (搜索.已注册实例(实例)) return;
        var 源 = 实体.容器定义;
        if (源 == null) return;
        搜索.注册实例容器(new 搜索容器
        {
            标识 = 实例,
            名称 = 源.名称,
            描述 = 源.描述,
            容器列 = 源.容器列,
            容器行 = 源.容器行,
            容器形状 = 源.容器形状,
            容器允许类型 = 源.容器允许类型,
            搜索时间 = 源.搜索时间,
            搜索表 = 源.搜索表
        });
    }

    // ================= 信息 =================

    // 房间层的信息条（基类默认只给地点名）
    public override string 信息条()
    {
        if (当前世界 == null) return "";
        int 已搜 = 当前世界.已搜数(), 总 = 当前世界.容器总数();
        return $"{当前世界.名称} · {危险度文本(当前世界.危险度)}    " +
               $"行动 {档案?.行动点 ?? 0}/{档案?.最大行动点 ?? 0}    {时间文本()}    " +
               $"已搜 {已搜}/{总}    敌 {当前世界.敌人总数()}";
    }

    // HUD「地点」位：在楼里显示"楼名 · 楼层名"（一层一间房，房间名由信息条来说）
    public override string 地点文本()
        => 在建筑里 ? $"{当前建筑.名称} · {建筑生成器.楼层名(当前建筑, 当前层)}" : base.地点文本();

    // ================= 数据取用（生成器回调） =================

    // 容器表：(地图类型, 房间) → 该房间的容器定义列表（房间 空 = 该地图类型全部房间）
    private List<搜索容器> 取容器表(string 地图类型, string 房间标识)
    {
        var 结果 = new List<搜索容器>();
        if (数据 == null || string.IsNullOrEmpty(地图类型)) return 结果;
        if (!数据.搜索地图类型.TryGetValue(地图类型, out var 类型) || 类型.房间 == null) return 结果;
        foreach (var 房 in 类型.房间)
        {
            if (房?.容器 == null) continue;
            if (!string.IsNullOrEmpty(房间标识) && 房.标识 != 房间标识) continue;
            foreach (var 容器 in 房.容器)
                if (容器 != null) 结果.Add(容器);
        }
        return 结果;
    }

    // 敌人组：敌人组标识 → 展开成"一只一项"的敌人定义标识列表
    private List<string> 取敌人组(string 敌人组标识)
    {
        var 结果 = new List<string>();
        if (数据 == null || string.IsNullOrEmpty(敌人组标识)) return 结果;
        if (!数据.敌人组.TryGetValue(敌人组标识, out var 组) || 组.敌人 == null) return 结果;
        foreach (var 项 in 组.敌人)
            for (int i = 0; i < Mathf.Max(1, 项.数量); i++)
                结果.Add(项.敌人);
        return 结果;
    }

using System;
using System.Collections.Generic;

// 工作台制作服务：安全屋 制作 家具（工作台/灶台/医疗站）按配方制作物品——末日生存 手工制作 体系。
// 校验：家具 等级 ≥ 配方.需要等级 + 图纸 持有（如有）+ 材料 足够（跨 穿戴容器/仓库）+ 精力（行动点）足够 + 饱食/水分 达标。
// 破损 家具（0 级）：也能 正常 制作（效率 减半——耗时 ×2，饱食/水分 消耗 随 耗时 翻倍）；修复（0→1 级）恢复 全效。
// 消耗 规则：每 游戏时 基础 消耗 饱食 2、水分 2；制作 消耗 = 基础 2 × 配方.消耗倍率 × 制作 时数（四舍五入 至少 1），
//           饱食/水分 消耗 相同（基础速率 相同）。
// 制作 流程（动画 驱动）：开始制作（校验 + 扣 材料 + 扣 精力 → 返回 上下文）→ 动画（推进 游戏时间 + 展示 进度）→
//           结算制作（扣 饱食/水分 + 产物 入包；背包 满 → 原子 回滚）。
// 事件：背包变化（材料- / 产物+）、日志反馈、制作完成事件（天赋服务·美食家 = 灶台 饮食 双倍产出）。
public sealed class 工作台制作服务
{
    private readonly EventBus 事件;
    private readonly DataService 数据;
    private 玩家档案 玩家 => ServiceRegistry.Get<PlayerService>().档案;

    // 饱食/水分 阈值：低于 此值 禁止 制作（太饿/太渴 干不动活）
    private const int 最低饱食 = 10;
    private const int 最低水分 = 10;

    public 工作台制作服务(EventBus 事件, DataService 数据)
    {
        this.事件 = 事件;
        this.数据 = 数据;
    }

    // ===== 配方 查询（面板 用） =====

    // 该 制作 家具 的 全部 配方（含 未解锁：等级 未达 / 图纸 缺失——面板 灰显 标注 原因）
    public 配方数据[] 配方列表(string 家具标识)
    {
        var 列表 = new List<配方数据>();
        foreach (var 配方 in 数据.配方.Values)
            if (配方.类型 == 家具标识)
                列表.Add(配方);
        return 列表.ToArray();
    }

    // 等级 是否 解锁（0 级 破损 = 视为 1 级 可用——能做 1 级 配方；2/3 级 配方 仍需 真 升级）
    public bool 等级解锁(string 家具标识, 配方数据 配方)
        => System.Math.Max(玩家.家具等级(家具标识), 1) >= 配方.需要等级;

    // 破损 倍率（0 级 家具 = 耗时 ×2；修复 后 = 1）
    public int 破损倍率(string 家具标识) => 玩家.家具等级(家具标识) <= 0 ? 2 : 1;

    // 图纸 是否 持有（无 图纸 需求 = true）
    public bool 图纸解锁(配方数据 配方) => string.IsNullOrEmpty(配方.解锁图纸) || 玩家.持有物品(配方.解锁图纸);

    // 材料 是否 足够（跨 穿戴容器/仓库）
    public bool 材料足够(配方数据 配方)
    {
        if (配方.材料 == null) return true;
        foreach (var 材 in 配方.材料)
            if (玩家.持有管理.物品数量(材.物品) < 材.数量) return false;
        return true;
    }

    // 面板 状态 文本：未满足 的 首要 原因（"" = 可制作）——顺序：等级 / 图纸 / 材料 / 精力 / 饱食 / 水分
    public string 未满足原因(string 家具标识, 配方数据 配方)
    {
        if (!等级解锁(家具标识, 配方)) return $"需 {家具名(家具标识)} {配方.需要等级} 级";
        if (!图纸解锁(配方)) return $"需图纸：{物品名(配方.解锁图纸)}";
        if (!材料足够(配方)) return "材料不足";
        if (玩家.行动点 < 配方.消耗精力) return "精力不足";
        if (玩家.饱食度 < 最低饱食) return "太饿了";
        if (玩家.水分度 < 最低水分) return "太渴了";
        return "";
    }

    // 材料 摘要（面板 显示）
    public string 材料文本(配方数据 配方)
    {
        if (配方.材料 == null || 配方.材料.Length == 0) return "";
        var 段 = new List<string>();
        foreach (var 材 in 配方.材料)
            段.Add($"{物品名(材.物品)}×{材.数量}");
        return string.Join(" ", 段);
    }

    // 该 配方 的 饱食/水分 消耗 预期（面板 详情 显示；0 级 破损 按 耗时 ×2 算）
    public float 消耗预期(配方数据 配方) => 消耗值(配方.消耗倍率, 配方.制作时间分 * 破损倍率(配方.类型));

    // ===== 制作（两步：开始 = 校验+扣费；结算 = 推进时间+消耗+产物——动画 驱动） =====

    // 制作 上下文（开始制作 校验扣费 通过后 返回；结算制作 用——动画 期间 玩家 不能 重复 制作）
    public sealed class 制作上下文
    {
        public 配方数据 配方;
        public int 总分钟;        // 制作时间分 × 破损倍率
        public float 扣饱食;      // 结算 时 扣（基础 2 × 倍率 × 时数，float 精确 0.1）
        public float 扣水分;
        public bool 破损;         // 0 级 家具（耗时 ×2）
        public 网格服务 输入网格;  // 会话 制作：材料 来源（从 输入 区 扣；null = 全局 持有）
    }

    // 开始制作：校验（未建/等级/图纸/材料/精力/饱水）+ 扣 材料 + 扣 精力；通过 返回 上下文（动画 用），失败 null + 提示
    public 制作上下文 开始制作(string 配方标识)
    {
        if (!数据.配方.TryGetValue(配方标识, out var 配方)) { 提示("未知配方。"); return null; }
        string 家具 = 配方.类型;
        if (玩家.家具实例(家具) == null) { 提示($"还没有 {家具名(家具)}。"); return null; }   // 未建 = 不可制作（已建 0 级破损 = 可用 减半）
        string 原因 = 未满足原因(家具, 配方);
        if (原因.Length > 0) { 提示($"{原因}（{配方.名称}）。"); return null; }
        bool 破损 = 破损倍率(家具) > 1;
        int 总分钟 = 配方.制作时间分 * 破损倍率(家具);
        float 扣饱食 = 消耗值(配方.消耗倍率, 总分钟);
        float 扣水分 = 扣饱食;   // 饱食/水分 消耗 相同（基础速率 同 2）
        // 扣 材料（跨 穿戴容器/仓库）
        if (配方.材料 != null)
            foreach (var 材 in 配方.材料)
            {
                玩家.持有管理.移除物品(材.物品, 材.数量);
                事件.发布(new 背包变化事件(材.物品, -材.数量, 变化原因.消耗));
            }
        // 扣 精力（行动点）
        玩家.生存管理.消耗行动点(配方.消耗精力);
        return new 制作上下文 { 配方 = 配方, 总分钟 = 总分钟, 扣饱食 = 扣饱食, 扣水分 = 扣水分, 破损 = 破损 };
    }

    // 会话 开始制作（输入/输出 网格 版）：材料 从 输入网格服务 扣（不在 背包 全局）——
    // 校验 输入 网格 材料 足够 + 扣 精力；材料 扣 由 结算 时 执行（原子）？
    // 简化：这里 只 校验 + 扣 精力 + 推进 时间 留 结算；材料 从 输入 网格 在 结算 扣。
    // 说明：输入 网格 = 面板 会话 容器（材料 已 从 背包 拖入），结算 时 从 输入 扣 → 产物 入 输出 网格。
    public 制作上下文 开始制作_会话(string 配方标识, 网格服务 输入网格)
    {
        if (!数据.配方.TryGetValue(配方标识, out var 配方)) { 提示("未知配方。"); return null; }
        string 家具 = 配方.类型;
        if (玩家.家具实例(家具) == null) { 提示($"还没有 {家具名(家具)}。"); return null; }
        string 原因 = 未满足原因(家具, 配方);
        if (原因.Length > 0) { 提示($"{原因}（{配方.名称}）。"); return null; }
        // 输入 网格 材料 足够 校验（跨 输入 网格 内 堆叠 统计）
        if (!输入网格材料足够(配方, 输入网格)) { 提示($"请把 {配方.名称} 的材料拖进输入区。"); return null; }
        bool 破损 = 破损倍率(家具) > 1;
        int 总分钟 = 配方.制作时间分 * 破损倍率(家具);
        float 扣饱食 = 消耗值(配方.消耗倍率, 总分钟);
        float 扣水分 = 扣饱食;
        // 扣 精力（行动点）——立即（动画 前）
        玩家.生存管理.消耗行动点(配方.消耗精力);
        return new 制作上下文 { 配方 = 配方, 总分钟 = 总分钟, 扣饱食 = 扣饱食, 扣水分 = 扣水分, 破损 = 破损, 输入网格 = 输入网格 };
    }

    // 输入 网格 是否 材料 足够（各 材料 在 输入 网格 内 数量 ≥ 需求）
    private bool 输入网格材料足够(配方数据 配方, 网格服务 输入网格)
    {
        if (输入网格 == null || 配方.材料 == null) return false;
        foreach (var 材 in 配方.材料)
        {
            int 有 = 0;
            foreach (var 堆叠 in 输入网格.网格物品)
                if (堆叠 != null && 堆叠.列 >= 0 && 堆叠.标识 == 材.物品) 有 += 堆叠.数量;
            if (有 < 材.数量) return false;
        }
        return true;
    }

    // 会话 结算制作：从 输入 网格 扣 材料 → 产物 入 输出 网格（非 全局 持有）；失败 回滚 材料/精力/时间/饱水
    public bool 结算制作_会话(制作上下文 上下文, 网格服务 输出网格)
    {
        if (上下文 == null || 上下文.配方 == null || 输出网格 == null) return false;
        var 配方 = 上下文.配方;
        // 扣 饱食/水分
        玩家.饱食度 = System.Math.Max(0f, 玩家.饱食度 - 上下文.扣饱食);
        玩家.水分度 = System.Math.Max(0f, 玩家.水分度 - 上下文.扣水分);
        ServiceRegistry.Get<世界时间管理器>()?.结算时间段(上下文.总分钟, false);
        // 从 输入 网格 扣 材料
        if (配方.材料 != null)
            foreach (var 材 in 配方.材料)
                输入网格扣(上下文.输入网格, 材.物品, 材.数量);
        // 产物 入 输出 网格
        int 放入 = 输出网格.放入网格(配方.产物, 配方.产物数量);
        if (放入 < 配方.产物数量)
        {
            会话回滚(上下文, 输出网格);
            提示("输出区满了，制作失败。");
            return false;
        }
        事件.发布(new 背包变化事件(配方.产物, 放入, 变化原因.获得));
        事件.发布(new 制作完成事件(配方.产物, 放入, 配方.类型));
        事件.发布(new 日志事件(日志类型.反馈, $"制作完成：{物品名(配方.产物)} ×{放入}！"));
        音效管理器.实例?.播放家具放下();
        return true;
    }

    // 从 输入 网格 扣 指定 标识（耗尽 移除 堆叠）
    private static void 输入网格扣(网格服务 输入网格, string 标识, int 数量)
    {
        if (输入网格 == null) return;
        int 剩 = 数量;
        for (int i = 输入网格.网格物品.Count - 1; i >= 0 && 剩 > 0; i--)
        {
            var 堆叠 = 输入网格.网格物品[i];
            if (堆叠 == null || 堆叠.列 < 0 || 堆叠.标识 != 标识) continue;
            int 扣 = Math.Min(剩, 堆叠.数量);
            堆叠.数量 -= 扣;
            剩 -= 扣;
            if (堆叠.数量 <= 0) 输入网格.网格物品.RemoveAt(i);
        }
    }

    // 会话 失败 回滚：材料 放回 输入 网格 + 精力/时间/饱水 返还
    private void 会话回滚(制作上下文 上下文, 网格服务 输出网格)
    {
        var 配方 = 上下文.配方;
        // 材料 放回 输入 网格（从 输入 扣 的 退回 输入）
        if (配方.材料 != null)
            foreach (var 材 in 配方.材料)
                上下文.输入网格?.放入网格(材.物品, 材.数量);
        玩家.生存管理.恢复行动点(配方.消耗精力);
        玩家.游戏分钟数 -= 上下文.总分钟;
        玩家.饱食度 = System.Math.Min(100f, 玩家.饱食度 + 上下文.扣饱食);
        玩家.水分度 = System.Math.Min(100f, 玩家.水分度 + 上下文.扣水分);
    }

    // 结算制作：扣 饱食/水分（配方 消耗）+ 补 副作用（跳过 时间 的 伤病/疲劳/寒潮——统一 结算 入口，不含 饱水）+
    // 产物 入包；背包 满 → 原子 回滚（材料/精力/时间/饱水 全 返还）。
    // 注意：游戏 时间 推进 已 由 制作 面板 动画 按 进度 完成（视觉 同步 HUD 时钟），此处 不再 推进。
    public bool 结算制作(制作上下文 上下文)
    {
        if (上下文 == null || 上下文.配方 == null) return false;
        var 配方 = 上下文.配方;
        // 扣 饱食/水分（下限 0；float 精确 0.1）
        玩家.饱食度 = System.Math.Max(0f, 玩家.饱食度 - 上下文.扣饱食);
        玩家.水分度 = System.Math.Max(0f, 玩家.水分度 - 上下文.扣水分);
        // 补 副作用：跳过 时间 里 的 伤病 持续 / 疲劳 恢复 / 寒潮 感冒（不含 饱食/水分——已 按 配方 扣）
        ServiceRegistry.Get<世界时间管理器>()?.结算时间段(上下文.总分钟, false);
        // 产物：跨容器放入（优先 穿戴容器 → 仓库 兜底）；背包 满 → 回滚
        int 放入 = 玩家.持有管理.放入物品(配方.产物, 配方.产物数量);
        if (放入 < 配方.产物数量)
        {
            回滚(上下文);
            提示("背包满了，制作失败。");
            return false;
        }
        事件.发布(new 背包变化事件(配方.产物, 放入, 变化原因.获得));
        事件.发布(new 制作完成事件(配方.产物, 放入, 配方.类型));   // 美食家（灶台 饮食 双倍）
        事件.发布(new 日志事件(日志类型.反馈, $"制作完成：{物品名(配方.产物)} ×{放入}！" + (上下文.破损 ? "（破损家具，耗时翻倍）" : "")));
        音效管理器.实例?.播放家具放下();
        return true;
    }

    // 消耗 值：基础速率(每游戏时 2) × 配方 倍率 × 制作 时数（float 精确 0.1，至少 0.1）
    private float 消耗值(float 倍率, int 总分钟)
        => System.Math.Max(0.1f, (float)System.Math.Round(2.0 * 倍率 * 总分钟 / 60.0, 1, System.MidpointRounding.AwayFromZero));

    // 背包满 回滚：材料/行动点/时间/饱水 全 返还（材料 已 腾出 空间，放回 必然 成功）
    private void 回滚(制作上下文 上下文)
    {
        var 配方 = 上下文.配方;
        if (配方.材料 != null)
            foreach (var 材 in 配方.材料)
            {
                玩家.持有管理.放入物品(材.物品, 材.数量);
                事件.发布(new 背包变化事件(材.物品, 材.数量, 变化原因.获得));
            }
        玩家.生存管理.恢复行动点(配方.消耗精力);
        玩家.游戏分钟数 -= 上下文.总分钟;
        玩家.饱食度 = System.Math.Min(100f, 玩家.饱食度 + 上下文.扣饱食);
        玩家.水分度 = System.Math.Min(100f, 玩家.水分度 + 上下文.扣水分);
    }

    private string 物品名(string 标识) => 数据.物品.TryGetValue(标识, out var 物) ? 物.标识 : 标识;
    private string 家具名(string 标识) => 数据.家具.TryGetValue(标识, out var 家具) ? 家具.名称 : 标识;
    private void 提示(string 文本) => 事件.发布(new 日志事件(日志类型.反馈坏, 文本));
}

// 就地转化网格：**就地转化 家具**（种植箱 / 晾晒架）的 网格 语义（继承 物品网格面板）——
//   ① 只 收 能 转化 的 东西：物品数据.转化用途 必须 等于 这件 家具 的 功能类型（种植箱 收 种子、晾晒架 收 生肉/兽皮）。
//      家具数据 的 容器允许类型/种类 只能 粗筛：晾晒架 配的 "材料·食物原料|其他" 里 还 躺着 盐/香料/鸡蛋/
//      土豆/肥料/塑料/破旧衣物 —— 不 按 "转化用途" 再收一道，这些 全 能 挂 到 晾晒架 上 白占 格 子。
//   ② 单株定根（由 面板 按 家具功能类型 设置，见 就地转化面板基类.初始化面板）：
//      种植箱 = 一次 只 种 一 棵（容器 非空 → 拒绝 再 放）+ 种下 就 不能 拖走（定根）；
//      晾晒架 = 4×2 格 可 同时 晾 多件（各 晾 各 的、各 自 计时）+ 晾晒中 也 能 取下来（进度 冻 在 物品 上，挂回 接着 晾）。
// 转化 本身 不 在 网格 里 发生（世界时间管理器.生长推进 推），这里 只 管 "什么 能 放 进来 / 什么 能 拖走"。
public sealed class 就地转化网格 : 物品网格面板
{
    // 面板 绑定 数据源 时 设（唯一的 判据 来源 = 家具数据.功能类型，网格 自己 不 再 猜）；
    // 不 序列化 —— 免得 预制体 里 存 一份 会 和 家具 对不上 的 副本。
    [System.NonSerialized] public bool 单株定根 = true;

    // 目标 允许放入：基类 校验（容器/类型/种类）之上，加 "转化归属" 与 "单株" 两道
    protected override bool 目标允许放入(string 标识)
    {
        if (!base.目标允许放入(标识)) return false;
        if (!可就地转化(标识)) return false;   // 转不了 的（盐/肥料/塑料/成品…）不 许 放
        if (!单株定根) return true;             // 晾晒架：8 格 挂 满 都 行
        var 容器 = 所属容器;
        return 容器?.容器物品 == null || 容器.容器物品.Count == 0;   // 种植箱：已 有 种子/作物 → 先 收获 或 销毁
    }

    // 拖拽：种植箱 里 生长中 的 种子 禁止 拖拽（种下 定根，不能 拖走/换位/拖回 背包）；
    // 成熟 作物 可 拖拽 收获 移动；晾晒架 上 的 一切（含 晾晒中）都 可 拖（取下 = 暂停，挂回 = 继续）。
    protected override bool 允许开始拖拽(物品堆叠 堆叠)
    {
        if (!单株定根) return true;
        if (堆叠 == null || string.IsNullOrEmpty(堆叠.标识)) return false;
        if (!数据.物品.TryGetValue(堆叠.标识, out var 模板)) return false;
        if (模板.生长时间 > 0 && !string.IsNullOrEmpty(模板.成熟产物) && 堆叠.生长分钟 > 0) return false;   // 种子 且 生长中
        return true;   // 成熟 作物 / 其他 物品
    }

    // 本 家具 管不管 这件 东西：判据 只有 一条（家具工具.可就地转化），这里 只 负责 把 家具定义 取出来
    private bool 可就地转化(string 标识)
    {
        if (string.IsNullOrEmpty(标识) || 所属容器 == null) return false;
        var (定义标识, _) = 家具工具.解码(所属容器.标识);
        return 数据.物品.TryGetValue(标识, out var 物)
               && 数据.家具.TryGetValue(定义标识, out var 家)
               && 家具工具.可就地转化(物, 家);
    }
}

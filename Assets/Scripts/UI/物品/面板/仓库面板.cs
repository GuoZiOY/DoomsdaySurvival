using UnityEngine;

// 仓库面板（右区·仓库模式，塔科夫 stash）：收纳型大网格（档案.仓库物品，10×20）。
//   模式面板：仅 持有面板 仓库模式（上下文 null）显示；搜索模式 时隐藏（与 搜索面板 二选一）。
//   场景搭建：ScrollRect（Viewport → Content）+ 挂 物品网格面板（Inspector 配 网格容器）；
//   本组件 注入 数据源 = 档案.仓库视图()（跨网格转移/拖拽 与穿戴容器互通）。
//   仓库不占负重（收纳）；背包变化 → 网格自动刷新（物品网格面板 已订阅事件）。
public sealed class 仓库面板 : MonoBehaviour
{
    [SerializeField] private 物品网格面板 面板;   // 仓库网格（场景预搭：物品网格面板）

    void Awake()
    {
        // 不再订阅 背包/属性变化：物品网格面板 自身已订阅（事件 → 脏标记 → Update 合并刷新），这里再订阅会造成双重全量重建
        刷新();
    }

    private void OnEnable() => 刷新();   // 面板每次打开时刷新（数据源/格尺寸）

    // 注入 仓库视图 数据源（每次重建视图，背包列表绑定 档案.仓库物品 同一引用）；网格常驻（不管有无物品）
    public void 刷新()
    {
        var 档案 = ServiceRegistry.Get<PlayerService>()?.档案;
        if (面板 == null)
        {
            Debug.LogWarning("[仓库面板] 未配置 面板 引用（请拖入 物品网格面板）。");
            return;
        }
        if (档案 == null) return;
        // ★ 刀66 删掉了原来这一行 `面板.gameObject.SetActive(true);` ——
        //   它让"仓库可见性"有了**两个主人**：本组件自己 + `持有面板.刷新`（仓库模式显示 / 搜索模式隐藏）。
        //   本组件是**模式面板**，可见性归 `持有面板` 管（它才做"仓库 / 搜索"二选一）；
        //   这里只管**数据源与格尺寸**。原来那行是颗地雷：将来任何路径再调一次 刷新()，
        //   都会在搜索模式下把仓库一起点亮 → 两个右区面板同时出现。
        面板.数据源 = 档案.仓库视图();
        面板.配置视图显示();   // 格尺寸统一常量（物品网格面板.格尺寸=100）；尺寸用 服务.网格列/行（10×20）
        面板.请求刷新();   // 脏标记：Update 帧末按 尺寸/增量 判定（避免直接全量重载 + 面板自身刷新 = 双重重建）
    }
}

using System;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.UI;

// ============================================================
// 大世界网格面板：探索网格面板 子类（对位 区域网格面板 / 房间网格面板）——只写「大世界里的实体语义」。
// 实体承载：墙（城市边界废墟）/ **区域**（一片街区，占多格）/ 障碍 / 营地（安全屋）/ 玩家
//           都是 物品堆叠（由 大世界探索服务 同步进 数据源 网格服务）；通行判定 = 该格有没有实体。
//
// 三类东西的语义（与 大世界生成器 一一对应）：
//   · **区域**：整块占格、只有**门口那一格**能站能走（`建筑外形.底边中点` 选出来的），走上去就进副本。
//             门口那一格按解锁状态上色（金色 = 进得去 / 红色 = 锁着），一眼看出哪片能去。
//   · **营地**：3×3 的安全屋，门口那一格走上去 = 回安全屋（这一趟出行结束）。
//   · **障碍**：单格，挡路不挡视线以外的东西；只在亮 / 白天记忆里画（夜里看不见废车，免得一头撞上去）。
//
// 点击规矩（和另外两层一致）：**点哪一格就走到哪一格**——区域块与营地**不吃点击**
//   （框根与每格块体都 raycastTarget = false），所以点在块上的哪一格都落到"那一格的交互层"：
//   点块体 = 走到它旁边、点**门口那一格** = 走到门口（走上去就进去）。右键那一格 = 那块实体的菜单。
//
// ★ 大网格两个开关（100×100 的关键，见 111 行附近）：
//   建底格 = false / 建格线 = false（省 30,200 张看不见的图）+ 大世界图层 开格子池（再省到 3×~400）。
//
// ⚠ 本类**绝对不能写 void Update()**（基类的 Update 是 private，会隐藏它）——每帧逻辑一律放 大世界图层。
// ============================================================
public sealed class 大世界网格面板 : 探索网格面板
{
    private 大世界图层 图层缓存;
    private bool 报过缺图层;

    // ★ 大网格开关：地表层本来就逐格盖满，底座层那 10,000 张底格与线层那 20,200 条格线**根本看不见**。
    //   默认是 true（房间层/区域层/背包/仓库 照旧），只有大世界关掉。
    protected override bool 建底格 => false;
    protected override bool 建格线 => false;

    private 大世界探索服务 大世界服务 => ServiceRegistry.Get<大世界探索服务>();
    private 网格数据 大世界 => 大世界服务?.当前大世界;

    protected override 格子探索服务 探索服务 => 大世界服务;

    public override 探索图层接口 图层()
    {
        if (图层缓存 == null)
        {
            图层缓存 = GetComponent<大世界图层>();
            if (图层缓存 == null && !报过缺图层)
            {
                报过缺图层 = true;
                Debug.LogError($"[大世界] {name} 上找不到 大世界图层 —— 地表/迷雾/路径/落点/逐格点击都靠它，点了也不会动。"
                             + "请在同一物体上加 大世界图层 组件。");
            }
        }
        return 图层缓存;
    }

    // ================= 实体框（大世界外观） =================

    // ================= 实体框（大世界外观） =================
    // 骨架已上提到 探索网格面板.创建实体框（v51 刀21）—— 这里只剩"从高处看这座城怎么画"。

    protected override bool 需要实体描边(网格实体 实体)
        // 障碍给方块黑描边（体量感）；区域块/营地靠自己的轮廓线、墙靠转角描边
        => 实体 != null && 实体.类型 == 网格实体类型.障碍;

    protected override void 建实体外观(GameObject 物体, 物品框 框, 网格实体 实体, 物品堆叠 堆叠, int 宽, int 高)
    {
        float 整宽 = 宽 * 格尺寸, 整高 = 高 * 格尺寸;
        bool 是墙 = 实体 != null && 实体.类型 == 网格实体类型.墙;
        bool 是区域 = 实体 != null && 实体.类型 == 网格实体类型.区域;
        bool 是障碍 = 实体 != null && 实体.类型 == 网格实体类型.障碍;
        bool 是营地 = 实体 != null && 实体.类型 == 网格实体类型.建筑 && 实体.定义标识 == "安全屋";
        bool 是临时 = 实体 != null && 实体.类型 == 网格实体类型.临时建筑;
        bool 是玩家 = 实体 != null && 实体.是玩家;

        if (是区域) 建区域块(物体, 框, 实体, 整宽, 整高);
        else if (是营地) 建方块(物体, 框, 实体, 整宽, 整高, 大世界贴图.营地(), "安全屋", 网格面板配色.区域门色);
        else if (是临时) 建方块(物体, 框, 实体, 整宽, 整高, 大世界贴图.临时建筑(), 实体.名称, 网格面板配色.区域门色);
        else if (是墙)
        {
            // **不描转角边**：100×100 的边界墙是 400 格（区域层只有 104 格），每格 2~3 条描边线就是
            // ~1,000 个多余 GameObject —— 而物品层**没有格子池**（池只管地表/迷雾/交互），这里是真开销。
            // 一条整圈的墙用同一种贴图连着铺，本来就该是"一道连续的墙"；地图边界由单张 底盘 框住，读得出来。
            var 墙图 = 摆满(物体.transform, "墙", 大世界贴图.墙顶(), Color.white, 整宽, 整高);
            框.内容层 = 墙图.rectTransform;
        }
        else if (是障碍)
        {
            // 障碍也**不挂名称标签**：100×100 上有 200 个障碍，200 个 TMP 文本既费又糊成一片；
            // 想知道是什么，右键看菜单（"查看"那条会给名字）。
            var 图 = 摆满(物体.transform, "障碍", 大世界贴图.障碍(实体.名称), Color.white, 整宽 - 8f, 整高 - 8f);
            框.内容层 = 图.rectTransform;
        }
        else if (是玩家)
        {
            float 边长 = Mathf.Min(整宽, 整高) - 18f;
            var 偏移 = new Vector2(0f, 6f);
            var 盘 = 摆居中(物体.transform, "盘", 大世界贴图.圆盘(), 边长, 偏移);
            摆居中(物体.transform, "剪影", 大世界贴图.剪影(), 边长, 偏移);
            摆居中(物体.transform, "环", 大世界贴图.圆环(), 边长, 偏移).color = 网格面板配色.玩家令牌边;
            框.内容层 = 盘.rectTransform;
            框.框图 = 盘;   // 令牌：圆盘按阵营上色
            框.名称 = 建名称(物体.transform, "你", new Vector2(0.5f, 0f), new Vector2(整宽, 20f), 15f);
        }
        else
        {
            var 图 = 摆满(物体.transform, "块", null, 网格面板配色.底座色, 整宽 - 10f, 整高 - 10f);
            框.内容层 = 图.rectTransform;
            框.名称 = 建名称(物体.transform, 实体?.名称 ?? 堆叠.标识, new Vector2(0.5f, 0.5f), new Vector2(整宽, 整高), 14f);
        }
    }

    // 区域副本：按掩码**逐格铺砖纹** + 只描朝外的轮廓 + 块名 + 门口那一格（按解锁状态上色）
    private void 建区域块(GameObject 物体, 物品框 框, 网格实体 区, float 整宽, float 整高)
    {
        // 整块不吃点击 → 点在块上的哪一格都落到那一格的交互层（面板才知道被点的是哪一格）
        物体.GetComponent<Image>().raycastTarget = false;
        框.内容层 = null;
        for (int r = 0; r < 区.高; r++)
            for (int c = 0; c < 区.宽; c++)
            {
                if (!区.覆盖(区.列 + c, 区.行 + r)) continue;   // 非矩形（L/凸/凹）的空缺不铺
                var 格图 = 摆格块(物体.transform, c, r, 大世界贴图.区域块());
                建块边(格图.transform, 区, c, r);
            }
        框.名称 = 建名称(物体.transform, 区.名称, new Vector2(0.5f, 0.5f), new Vector2(整宽 - 12f, 36f), 20f);
        建门口(物体.transform, 区, 大世界服务 == null || 大世界服务.已解锁(区) ? 网格面板配色.区域门色 : 网格面板配色.区域锁色);
    }

    // 一块"占格的方块建筑"（营地 / 临时建筑，都是纯矩形）：逐格铺 + 只描外边 + 名字 + 门口那一格。
    // **整块不吃点击** → 点在块上哪一格都落到那一格的交互层（点块体 = 走到边上，点门口 = 走上去进去）。
    private void 建方块(GameObject 物体, 物品框 框, 网格实体 块, float 整宽, float 整高, Sprite 精灵, string 名, Color 门色)
    {
        物体.GetComponent<Image>().raycastTarget = false;
        框.内容层 = null;
        for (int r = 0; r < 块.高; r++)
            for (int c = 0; c < 块.宽; c++)
            {
                if (!块.覆盖(块.列 + c, 块.行 + r)) continue;
                var 格图 = 摆格块(物体.transform, c, r, 精灵);
                建块边(格图.transform, 块, c, r);
            }
        框.名称 = 建名称(物体.transform, 名, new Vector2(0.5f, 0.5f), new Vector2(整宽 - 12f, 34f), 17f);
        建门口(物体.transform, 块, 门色);
    }

    // 门口那一格：走上去就进去（区域 = 进副本 / 营地 = 回安全屋 / 临时建筑 = 进去看看）。
    // 画在块自己身上、**不吃点击**。
    private void 建门口(Transform 父, 网格实体 块, Color 色)
    {
        if (块 == null) return;
        (int 列, int 行) 门格;
        switch (块.类型)
        {
            case 网格实体类型.区域:     门格 = 大世界生成器.区域门口格(块); break;
            case 网格实体类型.临时建筑: 门格 = 大世界生成器.临时建筑门口格(块); break;
            default:                    门格 = 大世界生成器.营地门口格(大世界); break;
        }
        if (门格.列 < 0 || !块.覆盖(门格.列, 门格.行)) return;
        var 门图 = UI工具.创建图(父, "门口", 大世界贴图.门(), 色, new Vector2(0f, 1f), new Vector2(0f, 1f));
        UI工具.设锚(门图.rectTransform, new Vector2(0f, 1f), new Vector2(0f, 1f),
            new Vector2((门格.列 - 块.列) * 格尺寸, -(门格.行 - 块.行) * 格尺寸),
            new Vector2(格尺寸, 格尺寸));
        门图.raycastTarget = false;
    }

    protected override void 更新实体框(物品框 框, 物品堆叠 堆叠)
    {
        if (框?.根 == null || 堆叠 == null) return;
        var 实体 = 找实体(堆叠.标识);
        var (宽, 高) = 格数(堆叠);
        // 玩家令牌：位置由 大世界图层 平滑接管时，这里不要把它拽回格子（否则会和插值打架）
        if (!(接管玩家位置 && 实体 != null && 实体.是玩家))
            框.根.anchoredPosition = new Vector2(格x(堆叠.列, 堆叠.行), -格y(堆叠.列, 堆叠.行));
        var 目标尺寸 = new Vector2(宽 * 格尺寸, 高 * 格尺寸);
        if ((框.根.sizeDelta - 目标尺寸).sqrMagnitude > 0.01f) 框.根.sizeDelta = 目标尺寸;

        // 可见性按"档"：规则**唯一一份**在 网格可见性.显示()（三层共用）。
        //   ⚠ 修正记录（v52）：这里原来也是 `else 显示 = 亮 || 档 == 暗记忆;`，**敌人落进了 else**
        //     → 站在街上看得见全城的敌人。与 区域网格面板 同一个错，一起收进共用规则。
        //   地形类（墙/区域/建筑/临时建筑）：不是全黑就留轮廓 —— "那片街区我去过"一眼看得出来。
        //   多格实体（区域 / 营地）：档取占地里最亮的那一格（看见一个角，整块就画出来，剩下由迷雾层盖黑）。
        var 档 = 整体档(实体);
        bool 显示 = 网格可见性.显示(实体, 档);
        if (框.根.gameObject.activeSelf != 显示) 框.根.gameObject.SetActive(显示);
        if (!显示) return;
        // 暗处的压暗**不在这里做**：迷雾层在物品层之上，地板/块/障碍一起压同一个 阴影压暗 值
        // ★ v51 刀18：CanvasGroup 从 物品框 缓存取（原来是每次刷新每实体一次 GetComponent）
        var 组 = 框.组;
        if (组 != null && Mathf.Abs(组.alpha - 1f) > 0.01f) 组.alpha = 1f;
        if (框.框图 != null && 实体 != null)
        {
            var 色 = 实体色(实体);
            if (框.框图.color != 色) 框.框图.color = 色;
        }
    }

    // 多格实体的"整体档"：取占地掩码里**最亮**的那一格 —— 只看见一个角，整块就该画出来
    // （没看见的部分由 迷雾层 逐格盖黑）。单格实体退化成 档(列,行)，与另外两层等价。
    private 视野档 整体档(网格实体 实体)
    {
        var 服 = 探索服务;
        if (服 == null || 实体 == null) return 视野档.亮;
        var 最好 = 视野档.全黑;
        for (int r = 实体.行; r < 实体.行 + 实体.高; r++)
            for (int c = 实体.列; c < 实体.列 + 实体.宽; c++)
            {
                if (!实体.覆盖(c, r)) continue;      // 非矩形的空缺不算
                var 档 = 服.档(c, r);
                if (档 > 最好) 最好 = 档;
                if (最好 == 视野档.亮) return 最好;
            }
        return 最好;
    }

    // ================= 右键菜单（大世界内容） =================

    public override void 右键格(int 列, int 行)
    {
        // 点**自己脚下那一格** → 「在附近搜索」。
        // 为什么走右键而不是加个按钮：加按钮要场景接线（引用位），而右键复用现成的交互层与菜单，
        // **零接线就能玩**；"大世界点击搜索"这条动作本身也就有了入口。
        if (探索服务 != null && 列 == 探索服务.玩家列 && 行 == 探索服务.玩家行)
        { 打开搜索菜单(图层()?.格位框(列, 行)); return; }

        var 实体 = 世界?.格上实体(列, 行);
        if (实体 == null) return;
        打开菜单(实体, 图层()?.格位框(列, 行));
    }

    private void 打开搜索菜单(RectTransform 框)
    {
        if (右键菜单.实例 == null) return;
        var 参 = 大世界服务?.当前模板?.搜索;
        string 代价 = 参 != null ? $"（-{参.行动点} 精力 · {参.游戏分钟} 分钟 · 半径 {参.半径} 格）" : "";
        右键菜单.实例.目标面板 = this;
        右键菜单.实例.显示动作(new List<(string 文本, Action 动作)>
        {
            ($"在附近搜索{代价}", () => 大世界服务?.搜索()),
        }, 框);
    }

    protected override void 右键实体(物品堆叠 堆叠, RectTransform 框)
        => 打开菜单(找实体(堆叠?.标识), 框);

    private void 打开菜单(网格实体 实体, RectTransform 框)
    {
        if (实体 == null || 右键菜单.实例 == null) return;
        bool 是区域 = 实体.类型 == 网格实体类型.区域;
        bool 是营地 = 实体.类型 == 网格实体类型.建筑 && 实体.定义标识 == "安全屋";
        bool 是临时 = 实体.类型 == 网格实体类型.临时建筑;
        bool 是障碍 = 实体.类型 == 网格实体类型.障碍;
        if (!是区域 && !是营地 && !是临时 && !是障碍) return;

        右键菜单.实例.目标面板 = this;
        var 条目 = new List<(string 文本, Action 动作)>();
        if (是区域)
        {
            var 门 = 大世界生成器.区域门口格(实体);
            条目.Add(($"走到门口（{门.列},{门.行}）", () => 点格反馈(门.列, 门.行)));
            条目.Add(("查看", () => 查看区域(实体)));
        }
        else if (是营地)
        {
            var 门 = 大世界生成器.营地门口格(大世界);
            条目.Add(($"走到门口（{门.列},{门.行}）", () => 点格反馈(门.列, 门.行)));
            条目.Add(("查看", () => 查看营地()));
        }
        else if (是临时)
        {
            var 门 = 大世界生成器.临时建筑门口格(实体);
            条目.Add(($"走到门口（{门.列},{门.行}）", () => 点格反馈(门.列, 门.行)));
            条目.Add(("查看", () => 说明($"{实体.名称}：搜索翻出来的临时窝点 —— 走门口那一格进去看看。**进去一趟就塌**，别指望它留到下一趟。")));
        }
        else 条目.Add(("查看", () => 说明($"{实体.名称}：挡在路中间，绕过去就行。")));

        右键菜单.实例.显示动作(条目, 框);
    }

    private void 查看区域(网格实体 区)
    {
        string 缘由 = 大世界服务?.未解锁缘由(区);
        if (!string.IsNullOrEmpty(缘由)) { 说明($"{区.名称}：现在还进不去 —— {缘由}"); return; }
        string 内在 = "";
        var 数据 = ServiceRegistry.Get<DataService>();
        if (数据 != null && 数据.区域模板.TryGetValue(区.定义标识 ?? "", out var 模板))
            内在 = $"　里面是一片 {模板.列}×{模板.行} 的街区，危险度 {模板.危险度}。每趟从安全屋出来，里头都是新的一批东西。";
        var 门 = 大世界生成器.区域门口格(区);
        ServiceRegistry.Get<EventBus>()?.发布(new 日志事件(日志类型.探索,
            $"{区.名称}：门口在（{门.列},{门.行}）那一格 —— 点那一格走过去，走上去就进副本。{内在}"));
    }

    private void 查看营地()
    {
        var 门 = 大世界生成器.营地门口格(大世界);
        ServiceRegistry.Get<EventBus>()?.发布(new 日志事件(日志类型.探索,
            $"安全屋：门口在（{门.列},{门.行}）那一格 —— 走上去就回屋。回屋 = 这一趟出行结束，外头翻到一半的柜子下次重算。"));
    }

    // ================= 画块 =================

    // 块内单格（相对块包围盒左上角摆）——**不吃点击**：让点击落到交互层，面板才知道被点的是哪一格
    private Image 摆格块(Transform 父, int 列偏移, int 行偏移, Sprite 精灵)
    {
        var 图 = UI工具.创建图(父, $"块_{列偏移}_{行偏移}", 精灵, Color.white, new Vector2(0f, 1f), new Vector2(0f, 1f));
        UI工具.设锚(图.rectTransform, new Vector2(0f, 1f), new Vector2(0f, 1f),
            new Vector2(列偏移 * 格尺寸, -行偏移 * 格尺寸), new Vector2(格尺寸, 格尺寸));
        图.raycastTarget = false;
        return 图;
    }

    // 块的轮廓：只在"邻居不在本块里"的边补一条暗线（L / 凸 / 凹 的凹口与转角都自然闭合）
    private void 建块边(Transform 格根, 网格实体 块, int c, int r)
    {
        int 列 = 块.列 + c, 行 = 块.行 + r;
        if (!块.覆盖(列, 行 - 1)) 建线条(格根, "边上", new Vector2(0.5f, 1f), new Vector2(格尺寸, 3f));
        if (!块.覆盖(列, 行 + 1)) 建线条(格根, "边下", new Vector2(0.5f, 0f), new Vector2(格尺寸, 3f));
        if (!块.覆盖(列 - 1, 行)) 建线条(格根, "边左", new Vector2(0f, 0.5f), new Vector2(3f, 格尺寸));
        if (!块.覆盖(列 + 1, 行)) 建线条(格根, "边右", new Vector2(1f, 0.5f), new Vector2(3f, 格尺寸));
    }

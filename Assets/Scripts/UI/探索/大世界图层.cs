using UnityEngine;

// ============================================================
// 大世界图层：探索图层 子类（对位 区域图层 / 房间图层）——这一层只差一件事：**地表换城市地面**。
// 迷雾 / 视野 / 移动节奏都和另外两层一样（走基类那套读 视野.json；速度 = 0.30 秒/格）。
//
// ★ 与另外两层唯一的实质区别：**开格子池**（`格子池化 = true`）。
//   100×100 逐格全建是 地表/迷雾 各 10,000 张图（交互层 v51 刀20 起已是**整层一张命中面**，
//   不逐格建、也不参与池化），会把 Canvas 拖死；开池之后只实例化相机窗口覆盖的那些格
//   （约 400 槽 ≈ 800 张图），相机滚过一格就把池槽重排。
//   （底格与格线在 大世界网格面板 里也关掉了 —— 地表层本来就逐格盖满，那两层根本看不见。）
//   池是逐层可选的：房间层/区域层都没覆写这个开关，所以它们的行为**一字未变**。
//
// 说明：本组件与 大世界网格面板 挂在**同一个物体**上（面板 GetComponent<大世界图层>() 取它）。
// ============================================================
public sealed class 大世界图层 : 探索图层
{
    private 大世界探索服务 大世界服务 => ServiceRegistry.Get<大世界探索服务>();

    protected override 格子探索服务 服务 => 大世界服务;

    // 城市地面
    protected override Sprite 地表贴图() => 大世界贴图.地面();

    // ★ 大网格专用：只建窗口覆盖的那些格（见文件头）
    protected override bool 格子池化 => true;

    // 速度：**不覆写** → 用基类默认（0.30 秒/格）。注意"走一格花多少**游戏**时间"是服务层的事
    // （大世界探索服务 覆写 移动游戏分钟 = 5），这里是"令牌走多快"的表现节奏，两者无关。
}

using System;
using System.Collections.Generic;
using TMPro;
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.UI;

// ============================================================
// 房间网格面板：探索网格面板 子类（对位 区域网格面板）——只写「房间里的实体语义」。
// 实体承载：墙 / 门 / 容器 / 尸体 / 敌人 / 玩家 都是 物品堆叠（由 房间探索服务 同步进 数据源 网格服务）；
// 通行判定 = 该格有没有实体 —— 与 A* 用的是同一份 网格数据，不会两边打架。
//
// 外观（"简单美术"，全部由 房间贴图 程序化生成，零美术资源）：
//   墙   = 墙顶竖纹贴图铺满整格（相邻墙无缝连成一片）+ 只在与"非墙"相邻的边描一条暗边（转角闭合）
//   门   = 门槛 + 门框 + 门扇（锁着 = 关严 + 锁点；开着 = 斜开一片）
//   容器 = 按名称挑剪影（柜 / 冰箱 / 纸箱 / 货架）+ 名称淡字；翻过 → 灰化 + 打勾（还能再打开，右键「接着翻」）
//   尸体 = 躺姿剪影；敌人 = 圆盘 + 丧尸剪影 + 血条；玩家 = 圆盘 + 人形 + 圆环 + "你"
// 分层：底盘/底座层/线层/物品层 由 网格面板基类 管；地表/迷雾/路径/效果/交互 由 房间图层 管。
// 共用的那半（点格反馈 / 点击转发 / 外观工具 / 拖拽三禁）在 探索网格面板 里。
// ⚠ 本类**绝对不能写 void Update()**（基类的 Update 是 private，会隐藏它）——每帧逻辑一律放 房间图层。
// ============================================================
public sealed class 房间网格面板 : 探索网格面板
{
    private 房间图层 图层缓存;
    private bool 报过缺图层;

    private 房间探索服务 房间服务 => ServiceRegistry.Get<房间探索服务>();
    private 网格数据 房间 => 房间服务?.当前房间;

    protected override 格子探索服务 探索服务 => 房间服务;

    public override 探索图层接口 图层()
    {
        if (图层缓存 == null)
        {
            图层缓存 = GetComponent<房间图层>();
            if (图层缓存 == null && !报过缺图层)
            {
                报过缺图层 = true;
                Debug.LogError($"[房间] {name} 上找不到 房间图层 —— 地表/迷雾/路径/落点/逐格点击都靠它，点了也不会动。请在同一物体上加 房间图层 组件。");
            }
        }
        return 图层缓存;
    }

    // ================= 实体框（房间外观） =================
    // 骨架（物体/框根/高光层/定位/挂交互）已上提到 探索网格面板.创建实体框（v51 刀21）——
    // 这里只剩"房间里的东西怎么画"。

    protected override bool 需要实体描边(网格实体 实体)
    {
        // 墙靠相邻描边、令牌靠圆盘、门/楼梯靠自己的贴图，都不要方块黑框
        if (实体 == null) return true;
        return 实体.类型 != 网格实体类型.墙 && !实体.是玩家
            && 实体.类型 != 网格实体类型.敌人 && 实体.类型 != 网格实体类型.门 && 实体.类型 != 网格实体类型.楼梯;
    }

    protected override void 建实体外观(GameObject 物体, 物品框 框, 网格实体 实体, 物品堆叠 堆叠, int 宽, int 高)
    {
        float 整宽 = 宽 * 格尺寸, 整高 = 高 * 格尺寸;
        bool 是墙 = 实体 != null && 实体.类型 == 网格实体类型.墙;
        bool 是玩家 = 实体 != null && 实体.是玩家;
        bool 是敌人 = 实体 != null && 实体.类型 == 网格实体类型.敌人;
        bool 是尸体 = 实体 != null && 实体.类型 == 网格实体类型.尸体;
        bool 是门 = 实体 != null && 实体.类型 == 网格实体类型.门;
        bool 是楼梯 = 实体 != null && 实体.类型 == 网格实体类型.楼梯;
        bool 是界外 = 实体 != null && 实体.类型 == 网格实体类型.界外;   // 挡通行但**不画**（楼梯间那一侧的空档）

        if (是墙)
        {
            var 墙图 = 摆满(物体.transform, "墙", 房间贴图.墙顶(), Color.white, 整宽, 整高);
            框.内容层 = 墙图.rectTransform;
            建墙边(物体.transform, 实体, 整宽, 整高);
        }
        else if (是门)
        {
            // 门 = 墙上那个洞：门槛 + 门框 + 门扇（锁着 = 关严 + 锁点；开着 = 斜开一片）
            var 门图 = 摆满(物体.transform, "门", 房间贴图.门(实体.朝向, 实体.锁着), Color.white, 整宽, 整高);
            框.内容层 = 门图.rectTransform;
            框.框图 = 门图;   // 解锁后要换图（关 → 开），见 更新实体框
            框.名称 = 建名称(物体.transform, 门标签(实体), new Vector2(0.5f, 0f), new Vector2(格尺寸 * 宽, 18f), 14f);
        }
        else if (是楼梯)
        {
            // 楼梯间：网格在那一侧**真的多长了一格**（四周是墙、只有内侧一个口），所以这里照常铺满一格就行
            var 梯图 = 摆满(物体.transform, "楼梯", 房间贴图.楼梯(实体.朝向), Color.white, 整宽, 整高);
            框.内容层 = 梯图.rectTransform;
            框.框图 = 梯图;
            框.名称 = 建名称(物体.transform, "楼梯", new Vector2(0.5f, 0f), new Vector2(格尺寸 * 宽, 18f), 14f);
        }
        else if (是玩家 || 是敌人)
        {
            float 边长 = Mathf.Min(整宽, 整高) - 18f;
            var 偏移 = new Vector2(0f, 6f);
            var 盘 = 摆居中(物体.transform, "盘", 房间贴图.圆盘(), 边长, 偏移);
            摆居中(物体.transform, "剪影", 房间贴图.剪影(), 边长, 偏移);
            if (是玩家)
                摆居中(物体.transform, "环", 房间贴图.圆环(), 边长, 偏移).color = 网格面板配色.玩家令牌边;
            框.内容层 = 盘.rectTransform;
            框.框图 = 盘;   // 令牌：圆盘按阵营上色（更新时改色）
            框.名称 = 建名称(物体.transform, 是玩家 ? "你" : (实体?.名称 ?? ""), new Vector2(0.5f, 0f), new Vector2(格尺寸 * 宽, 20f), 15f);
        }
        else if (是尸体)
        {
            var 图 = 摆居中(物体.transform, "尸体", 房间贴图.尸体(), Mathf.Min(整宽, 整高) - 12f, Vector2.zero);
            框.内容层 = 图.rectTransform;
            框.名称 = 建名称(物体.transform, "尸体", new Vector2(0.5f, 0.5f), new Vector2(整宽, 整高), Mathf.Clamp(格尺寸 * 0.20f, 13f, 26f));
        }
        else if (是界外)
        {
            // 什么都不画（它的作用只是"挡住通行"）
        }
        else
        {
            var 图 = 摆满(物体.transform, "容器", 房间贴图.容器(实体?.名称), Color.white, 整宽 - 10f, 整高 - 10f);
            框.内容层 = 图.rectTransform;
            框.名称 = 建名称(物体.transform, 实体?.名称 ?? 堆叠.标识, new Vector2(0.5f, 0.5f), new Vector2(整宽, 整高), Mathf.Clamp(格尺寸 * 0.20f, 13f, 26f));
            if (亮底(实体?.名称)) 框.名称.color = new Color(0.12f, 0.12f, 0.14f, 0.85f);   // 浅色容器（冰箱/冷柜）上用深字，不然看不清
        }

        if (!是墙 && !是玩家 && !是敌人 && !是门 && !是楼梯) 建边界线(物体.transform);   // 容器/尸体 画自己的边界线（墙连成一片、令牌用圆盘、门/楼梯是贴图，都不画）
        if (是界外) 物体.SetActive(false);   // 界外格整块隐藏（它不画，只挡路）
    }

    protected override void 更新实体框(物品框 框, 物品堆叠 堆叠)
    {
        if (框?.根 == null || 堆叠 == null) return;
        var 实体 = 找实体(堆叠.标识);
        if (实体 != null && 实体.类型 == 网格实体类型.界外)
        {
            if (框.根.gameObject.activeSelf) 框.根.gameObject.SetActive(false);
            return;
        }
        var (宽, 高) = 格数(堆叠);
        // 玩家令牌：位置由 房间图层 平滑接管时，这里不要把它拽回格子（否则会和插值打架）
        if (!(接管玩家位置 && 实体 != null && 实体.是玩家))
            框.根.anchoredPosition = new Vector2(格x(堆叠.列, 堆叠.行), -格y(堆叠.列, 堆叠.行));
        var 目标尺寸 = new Vector2(宽 * 格尺寸, 高 * 格尺寸);
        if ((框.根.sizeDelta - 目标尺寸).sqrMagnitude > 0.01f) 框.根.sizeDelta = 目标尺寸;

        // 可见性按"档"：规则**唯一一份**在 网格可见性.显示()（三层共用 —— 别在这里再写一遍，会漂）
        //   玩家永远画；敌人只在 亮（核心）里画；墙/门/楼梯 只要不是全黑就画；
        //   容器/尸体 只在 亮 或 白天的暗记忆 里画（夜晚弱视野里看不见要翻的东西）
        var 档 = 房间服务?.档(实体.列, 实体.行) ?? 视野档.亮;
        bool 显示 = 网格可见性.显示(实体, 档);
        if (框.根.gameObject.activeSelf != 显示) 框.根.gameObject.SetActive(显示);
        if (!显示) return;

        // ★ v51 刀18：CanvasGroup 从 物品框 缓存取（原来是每帧每实体一次 GetComponent）。
        //   刷新物品() 是"全实体遍历"，区域层一次就是 700+ 个实体 —— 每个都查一次组件表纯属浪费。
        var 组 = 框.组;
        if (组 != null)
        {
            // 只留"已翻过"这一档灰化；**暗处的压暗不在这里做** —— 那是 迷雾层 的事（雾在物品层之上，
            // 地板/家具/墙/门一起压同一个 阴影压暗 值，新加实体不用再各自写一遍压暗规则）。
            float 透明 = 1f;
            if (实体 != null && 已翻过(实体)) 透明 = 网格面板配色.已搜灰化;
            if (Mathf.Abs(组.alpha - 透明) > 0.01f) 组.alpha = 透明;
        }
        if (框.框图 != null && 实体 != null)
        {
            if (实体.类型 == 网格实体类型.门)
            {
                // 门：图随"锁着 / 开着"换（解锁后当帧就换成开着的门洞）
                var 门图 = 房间贴图.门(实体.朝向, 实体.锁着);
                if (框.框图.sprite != 门图) 框.框图.sprite = 门图;
            }
            else
            {
                var 色 = 实体色(实体);
                if (框.框图.color != 色) 框.框图.color = 色;
            }
        }
        if (框.名称 != null && 实体 != null)
        {
            string 文本 = 实体.类型 == 网格实体类型.门 ? 门标签(实体)
                        : 实体.已搜 ? $"{实体.名称} ✓" : 实体.名称;
            if (框.名称.text != 文本) 框.名称.text = 文本;
        }
    }

    // ================= 右键菜单（房间内容） =================

    protected override void 右键实体(物品堆叠 堆叠, RectTransform 框)
    {
        var 实体 = 找实体(堆叠?.标识);
        if (实体 == null || 右键菜单.实例 == null) return;
        if (实体.类型 != 网格实体类型.容器 && 实体.类型 != 网格实体类型.尸体
            && 实体.类型 != 网格实体类型.敌人 && 实体.类型 != 网格实体类型.门
            && 实体.类型 != 网格实体类型.楼梯) return;
        右键菜单.实例.目标面板 = this;
        var 条目 = new List<(string 文本, Action 动作)>();
        if (实体.类型 == 网格实体类型.门)
        {
            if (房间服务 != null && !房间服务.够得着门(实体))
            {
                条目.Add(("移动到此处", () => 房间服务?.点格(实体.列, 实体.行)));
            }
            else if (房间服务 != null && 房间服务.锁着(实体))
            {
                // 锁着：三条破解路径里**本刀实现两条**（钥匙 / 撬锁）；
                // 砸锁 **留空** —— 服务里 开锁方式.砸锁 已占位，等做"巨响惊动敌人"再出这条菜单
                string 钥匙 = 实体.锁钥匙;
                if (!string.IsNullOrEmpty(钥匙) && 档案 != null && 档案.持有物品(钥匙))
                    条目.Add(($"用钥匙开锁（{钥匙}）", () => { 房间服务?.开锁(实体, 房间探索服务.开锁方式.钥匙); 图层()?.刷新(); }));
                else
                    条目.Add(($"需要{钥匙}（身上没有）", () => 说明($"你身上没有{钥匙}——先翻翻这间屋里的柜子。")));

                string 工具 = 房间服务?.找撬锁工具() ?? "";
                if (!string.IsNullOrEmpty(工具))
                {
                    int 成功率 = 房间服务?.撬锁成功率() ?? 0;
                    条目.Add(($"撬锁（{工具} · 成功率 {成功率}%）", () => { 房间服务?.开锁(实体, 房间探索服务.开锁方式.撬锁); 图层()?.刷新(); }));
                }
                else
                {
                    条目.Add(("需要撬棍 / 螺丝刀 / 钳子（身上没有）", () => 说明("你身上没有能撬锁的东西。")));
                }
            }
            else
            {
                // 无锁 / 已解锁：走上去就转移（这里给个一键的等价入口）
                条目.Add((实体.是大门 || string.IsNullOrEmpty(实体.通向) ? "推门出去"
                        : $"推门过去（→ {房间服务?.门去向文本(实体)}）",
                        () => { if (房间服务 != null) 房间服务.点格(实体.列, 实体.行); 图层()?.刷新(); }));
            }
            条目.Add(("查看", () => 查看(实体)));
        }
        else if (实体.类型 == 网格实体类型.楼梯)
        {
            // 楼梯：站到楼梯格上（或正交相邻）才能上下楼。选项按"有没有上一层/下一层"给（没有就给说明项）
            if (房间服务 != null && !房间服务.够得着楼梯(实体))
            {
                条目.Add(("移动到此处", () => 房间服务?.点格(实体.列, 实体.行)));
            }
            else if (房间服务 != null && 房间服务.在建筑里)
            {
                var 建 = 房间服务.当前建筑;
                int 层 = 房间服务.当前层, 总 = 建筑生成器.楼层数(建);
                if (层 + 1 < 总)
                    条目.Add(($"上楼（→ {建筑生成器.楼层名(建, 层 + 1)}）", () => { 房间服务.上楼(); 图层()?.刷新(); }));
                else
                    条目.Add(("上楼（上面没有了）", () => 说明("这已经是顶楼了。")));
                if (层 - 1 >= 0)
                    条目.Add(($"下楼（→ {建筑生成器.楼层名(建, 层 - 1)}）", () => { 房间服务.下楼(); 图层()?.刷新(); }));
                else
                    条目.Add(("下楼（下面没有了）", () => 说明("这已经是最底层了。")));
            }
            else
            {
                条目.Add(("上楼 / 下楼", () => 说明("一段楼梯——不过这间房不在任何一栋楼里。")));
            }
            条目.Add(("查看", () => 查看(实体)));
        }
        else if (实体.类型 == 网格实体类型.敌人)
        {
            条目.Add(("查看", () => 查看(实体)));
        }
        else if (房间服务 != null && !房间服务.够得着(实体))
        {
            // 隔着屋子不能翻：只给「移动到此处」（= 走到它旁边停下，与左键点它是同一件事）
            条目.Add(("移动到此处", () => 房间服务?.点格(实体.列, 实体.行)));
        }
        else
        {
            // 容器不是一次性的：没翻过 = 「搜索」（首次扣行动点）；翻过 = 「接着翻」（不扣，进度原样留着）
            if (!已翻过(实体)) 条目.Add(("搜索", () => 搜索(实体)));
            else 条目.Add(("接着翻", () => 搜索(实体)));
            条目.Add(("查看", () => 查看(实体)));
        }
        if (条目.Count == 0) return;
        右键菜单.实例.显示动作(条目, 框);
    }

    // ================= 房间内容小工具 =================

    // 门的显示名：锁着要一眼看出来（锁着还得先开锁才能过）
    private static string 门标签(网格实体 门)
    {
        if (门 == null) return "门";
        string 名 = 门.是大门 ? "大门" : "门";
        return 门.锁着 ? $"{名}（锁着）" : 名;
    }

    // 这一处翻过没有 —— 一律问 房间探索服务（战局进度，跨"再进这间房"仍保持）。
    // 不看 网格实体.已搜：那只是"本趟点过"的表现位，房间一重生成就没了，用它会让翻过的柜子又变回没翻过。
    private bool 已翻过(网格实体 实体) => 房间服务?.已翻过(实体) == true;

    private void 搜索(网格实体 实体)
    {
        房间服务?.搜索容器(实体);
        图层()?.刷新();
    }

    private void 查看(网格实体 实体)
    {
        string 文本 = 实体.类型 switch
        {
            网格实体类型.敌人 => $"{实体.名称}：它还没发现你，或者正在等你靠近。",
            网格实体类型.尸体 => "一具尸体。翻一翻也许还有东西。",
            网格实体类型.门 => 门描述(实体),
            网格实体类型.楼梯 => 楼梯描述(),
            _ => 实体.容器定义 != null && !string.IsNullOrEmpty(实体.容器定义.描述)
                ? 实体.容器定义.描述
                : $"{实体.名称}：看起来能翻一翻。",
        };
        ServiceRegistry.Get<EventBus>()?.发布(new 日志事件(日志类型.探索, 文本));
    }

    // 楼梯的描述：说清"这是上下楼唯一的路 + 现在能上到哪 / 下到哪"
    private string 楼梯描述()
    {
        var 服 = 房间服务;
        if (服 == null || !服.在建筑里) return "一段楼梯。";
        int 层 = 服.当前层, 总 = 建筑生成器.楼层数(服.当前建筑);
        string 上 = 层 + 1 < 总 ? $"能上到{建筑生成器.楼层名(服.当前建筑, 层 + 1)}" : "上面没有了";
        string 下 = 层 - 1 >= 0 ? $"能下到{建筑生成器.楼层名(服.当前建筑, 层 - 1)}" : "下面没有了";
        return $"一段楼梯：{上}，{下}。站到这一格上右键就能走。";
    }

    // 门的描述：把"锁着没锁着 / 需要什么 / 开门的两条路"一次说清（查看 走日志）
    private string 门描述(网格实体 门)
    {
        bool 通外面 = 门.是大门 || string.IsNullOrEmpty(门.通向);
        string 去向 = 通外面 ? "外面" : (房间服务?.门去向文本(门) ?? 门.通向);
        if (门.锁着)
        {
            string 工具 = 房间服务?.找撬锁工具() ?? "";
            bool 有钥匙 = 档案 != null && !string.IsNullOrEmpty(门.锁钥匙) && 档案.持有物品(门.锁钥匙);
            string 后半 = 有钥匙 ? $"你身上有{门.锁钥匙}，直接开就行。"
                        : string.IsNullOrEmpty(工具) ? "你身上没有这把钥匙，也没有能撬锁的东西（撬棍 / 螺丝刀 / 钳子）。"
                        : $"身上没有钥匙，但有{工具}，可以撬（成功率 {房间服务?.撬锁成功率() ?? 0}%）。";
            return $"一扇锁着的门，通向{去向}。{后半}";
        }
        return 通外面
            ? "大门。外面就是街上——走上去就出去了。"
            : $"一扇门，通向{去向}。走到门上（踩在门格上）就过去了。";
    }

    // 墙的转角闭合：只在与"非墙"相邻的那条边描一条暗边（相邻墙之间不描 → 连成一整片墙）
    private void 建墙边(Transform 父, 网格实体 墙, float 宽, float 高)
    {
        var 房 = 房间;
        if (房 == null || 墙 == null) return;
        if (!是墙(房, 墙.列, 墙.行 - 1)) 建线条(父, "边上", new Vector2(0.5f, 1f), new Vector2(宽, 3f));
        if (!是墙(房, 墙.列, 墙.行 + 1)) 建线条(父, "边下", new Vector2(0.5f, 0f), new Vector2(宽, 3f));
        if (!是墙(房, 墙.列 - 1, 墙.行)) 建线条(父, "边左", new Vector2(0f, 0.5f), new Vector2(3f, 高));
        if (!是墙(房, 墙.列 + 1, 墙.行)) 建线条(父, "边右", new Vector2(1f, 0.5f), new Vector2(3f, 高));
    }

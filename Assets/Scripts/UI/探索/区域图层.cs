using UnityEngine;
using UnityEngine.UI;

// ============================================================
// 区域图层：探索图层 子类（对位 房间图层）——区域这一层只差一件事：**地表换沥青**（街道）。
// **迷雾、视野、移动节奏都和房间层一样**（迷雾/视野走基类那套读 视野.json；
// 速度 = 基类默认 0.30 秒/格，和楼里一致 —— 街上原来那个 0.12 秒/格 已按拍板取消）——
// 于是"哪栋楼没去过"一眼看得出来：没去过的街区是黑的，走过的是压暗的记忆，跟前一圈才全亮。
// 说明：本组件与 区域网格面板 挂在**同一个物体**上（面板 GetComponent<区域图层>() 取它）。
// ============================================================
public sealed class 区域图层 : 探索图层
{
    private 区域探索服务 区域服务 => ServiceRegistry.Get<区域探索服务>();

    protected override 格子探索服务 服务 => 区域服务;

    // 街道地面：沥青
    protected override Sprite 地表贴图() => 区域贴图.地面();

    // 速度：**不覆写** → 用基类默认（`格子探索服务.每格现实秒` = 0.30 秒/格，与楼里一致）。
    // 要给街上单独定速，就在这类里覆写 `每格现实秒`（一改只影响区域层）。

    // 注：迷雾层由基类按 服务.档() 铺（区域有雾，所以照建照刷）；
    //     楼门**不在这里画**——门长在建筑自己身上，由 区域网格面板 画在楼体那一格上（这里画会被楼挡住）。
}

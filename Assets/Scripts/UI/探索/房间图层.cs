using UnityEngine;

// ============================================================
// 房间图层：探索图层 子类（对位 区域图层）——房间这一层只差"地表贴图"一件。
// 共用的那套（自建层装配 / 迷雾三态 / 路径 / 效果 / 令牌自己走路 / 悬停 / 闪红 / 落点）全在 探索图层 里。
// 说明：本组件与 房间网格面板 挂在**同一个物体**上（面板 GetComponent<房间图层>() 取它；
//       两者是"同一物体上的两个组件"，不是父子关系）。
// ============================================================
public sealed class 房间图层 : 探索图层
{
    protected override 格子探索服务 服务 => ServiceRegistry.Get<房间探索服务>();

    // 房间的地表：程序化水泥地（斑块 + 板缝）
    protected override Sprite 地表贴图() => 房间贴图.地板();
}

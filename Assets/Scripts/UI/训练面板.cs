// 训练面板：训练功能（属性训练 + 技能熟练训练；训练场/武馆/学堂共用）
public sealed class 训练面板 : 设施功能面板基类
{
    protected override string 标题文字() => $"{逻辑.名称} · 训练";

    protected override void 渲染列表()
    {
        if (逻辑 is not 训练功能 训练) return;
        var 玩家 = 逻辑.当前玩家;
        // 属性训练区
        foreach (var 项目 in 训练.可训项目())
        {
            var 标识 = 项目.标识;
            int 当前 = 玩家.属性值(项目.属性);
            创建行(内容区, $"【属性】{项目.名称}（{项目.属性} {当前}→{当前 + 项目.加成}）  {项目.花费}金", () => 训练.尝试训练(标识));
        }
        // 熟练训练区
        foreach (var 技能 in 训练.可练熟练技能())
        {
            var 标识 = 技能.标识;
            int 等级 = 玩家.技能熟练等级(标识);
            int 进度 = 玩家.技能熟练度(标识);
            int 每级 = 训练.每级熟练度(技能);
            int 花费 = 训练.熟练训练花费(标识);
            创建行(内容区, $"【熟练】{技能.名称} 等级{等级}/{玩家档案.熟练等级上限}  熟练 {进度}/{每级}  +{训练逻辑.熟练训练点数}    {花费}金", () => 训练.尝试熟练训练(标识));
        }
    }
}

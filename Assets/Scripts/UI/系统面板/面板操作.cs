using System.Collections.Generic;
using UnityEngine;

// 面板操作：玩家档案的通用面板操作（加点/换装/技能书/恢复品）——多个面板/子面板共用，避免重复实现。
// 只做领域操作 + 发事件，不碰 UI；UI 订阅事件自行刷新。
public static class 面板操作
{
    // 槽位兼容规则（拖拽穿戴/换槽/投影 统一判定）：
    // 头部/胸部/腿部/脚部/手部 严格匹配；主手/副手 互通（武器均可持，槽位数据决定默认）。
    public static bool 槽位匹配(string 物品槽位, string 目标槽)
    {
        if (string.IsNullOrEmpty(物品槽位) || string.IsNullOrEmpty(目标槽)) return false;
        if (物品槽位 == 目标槽) return true;
        if ((物品槽位 == "主手" || 物品槽位 == "副手") && (目标槽 == "主手" || 目标槽 == "副手")) return true;
        return false;
    }

    // 加点：消耗 1 自由属性点，成功后发 属性变化事件 + 日志
    public static void 加点(玩家档案 玩家, 属性类型 类型)
    {
        if (!玩家.加点(类型)) return;
        var 事件 = ServiceRegistry.Get<EventBus>();
        事件.发布(new 属性变化事件(玩家.体质, 玩家.力量, 玩家.智慧, 玩家.敏捷, 玩家.意志, 玩家.自由属性点));
        事件.发布(new 日志事件(日志类型.反馈, $"{类型} +1"));
    }

    // 换装（转移模型·模板级，旧入口）：按 物品.槽位 自动定位槽（饰品→饰品1/饰品2 空槽优先），旧装备回背包(含词缀) + 新装备(含词缀)入槽 + 背包扣 1。
    // 换背包槽：先校验新网格能否容纳现有物品（缩容禁止），成功后应用新网格尺寸。返回是否成功。
    // 注意：这是"按标识取第一件"的模板级入口（旧背包列表 UI 用）；塔科夫实例级操作（容器里的具体一件，保留词缀/耐久/容器数据）请用 换装堆叠。
    public static bool 换装(玩家档案 玩家, 物品数据 物品)
    {
        string 槽 = 物品.槽位;
        if (string.IsNullOrEmpty(槽)) return false;   // 非装备类防误用
        if (槽 == "饰品") 槽 = 玩家.饰品目标槽();
        var 事件 = ServiceRegistry.Get<EventBus>();
        // 换背包：缩容校验（在扣物品之前）
        if (槽 == "背包" && !背包可容纳(玩家, 物品.标识))
        {
            音效管理器.实例?.播放失败();
            事件.发布(new 日志事件(日志类型.反馈坏, "背包空间不足，无法更换。"));
            return false;
        }
        var 词缀 = 玩家.背包词缀(物品.标识);   // 取选中堆叠的词缀（换上前先取）
        int 新耐久 = 玩家.背包当前耐久(物品.标识);   // 取选中堆叠的当前耐久（随实例存档）
        if (!玩家.移除物品(物品.标识, 1)) return false;
        var 旧 = 玩家.装备到槽(槽, 物品.标识, 词缀, 新耐久);
        if (槽 == "背包") 玩家.应用背包装备();   // 背包槽影响网格尺寸
        if (旧 != null && !string.IsNullOrEmpty(旧.标识) && 旧.标识 != 物品.标识)
        {
            // 旧装备(含词缀/容器数据)回背包（入格）；背包已满则回滚换装：旧装备回槽 + 新装备回背包 + 网格尺寸还原
            if (!玩家.放入网格堆叠(装备转堆叠(旧)))
            {
                玩家.装备到槽(槽, 旧);   // 完整恢复（不丢容器内部物品）
                if (槽 == "背包") 玩家.应用背包装备();
                玩家.放入网格堆叠(新装备堆叠(玩家, 物品.标识, 词缀, 新耐久));
                事件.发布(new 日志事件(日志类型.反馈坏, "背包已满，装备更换取消。"));
                return false;
            }
            事件.发布(new 背包变化事件(旧.标识, 1, 变化原因.获得));
        }
        事件.发布(new 背包变化事件(物品.标识, -1, 变化原因.消耗));
        事件.发布(new 属性变化事件(玩家.体质, 玩家.力量, 玩家.智慧, 玩家.敏捷, 玩家.意志, 玩家.自由属性点));
        事件.发布(new 日志事件(日志类型.反馈, $"装备了 {物品.名称}。"));
        return true;
    }

    // 换装（实例级）：装备 指定堆叠实例（保留其词缀/耐久——同标识多件时装备"这一件"而非第一个）。
    // 指定槽 非空：装备到指定槽（拖拽穿戴用，已由调用方校验 槽位匹配）；为空：按 物品.槽位 自动定位（双击/菜单装备）。
    // 源服务 非空：从该背包服务（穿戴容器/主背包视图）移除堆叠，旧件回该服务（塔科夫式：物品在容器里，不在档案.背包）。
    public static bool 换装堆叠(玩家档案 玩家, 物品堆叠 堆叠, string 指定槽 = null, 背包服务 源服务 = null)
    {
        if (堆叠 == null || string.IsNullOrEmpty(堆叠.标识)) return false;
        var 数据 = ServiceRegistry.Get<DataService>();
        if (!数据.物品.TryGetValue(堆叠.标识, out var 物品)) return false;
        string 槽 = !string.IsNullOrEmpty(指定槽) ? 指定槽 : 物品.槽位;
        if (string.IsNullOrEmpty(槽)) return false;
        if (槽 == "饰品" && string.IsNullOrEmpty(指定槽)) 槽 = 玩家.饰品目标槽();
        var 事件 = ServiceRegistry.Get<EventBus>();
        if (槽 == "背包" && !背包可容纳(玩家, 堆叠.标识))
        {
            音效管理器.实例?.播放失败();
            事件.发布(new 日志事件(日志类型.反馈坏, "背包空间不足，无法更换。"));
            return false;
        }
        var 源背包 = 源服务 ?? 玩家.背包服务;   // 物品实际所在服务（穿戴容器/主背包）
        // 移除 该具体堆叠（不是按标识取第一个）
        if (!源背包.背包.Remove(堆叠)) return false;
        if (堆叠.数量 > 1)   // 罕见（可堆叠装备）：剩 数量-1 留原格
        {
            堆叠.数量 -= 1;
            源背包.背包.Add(堆叠);
        }
        var 旧 = 玩家.装备到槽(槽, 堆叠.标识, 堆叠.词缀, 堆叠.当前耐久, 堆叠, 来源名(玩家, 源背包));   // 容器源 = 堆叠：卸下再穿上时内部物品保留；来源 = 从哪来回哪去
        if (槽 == "背包") 玩家.应用背包装备();
        if (旧 != null && !string.IsNullOrEmpty(旧.标识) && 旧.标识 != 堆叠.标识)
        {
            if (!源背包.放入网格堆叠(装备转堆叠(旧)))   // 旧件回 源服务（从哪来回哪去；含容器数据）
            {
                玩家.装备到槽(槽, 旧);   // 完整恢复旧件回槽（不丢容器内部物品）
                if (槽 == "背包") 玩家.应用背包装备();
                源背包.背包.Add(堆叠);   // 新装备回 源服务（列/行 未变，原位）
                事件.发布(new 日志事件(日志类型.反馈坏, "背包已满，装备更换取消。"));
                return false;
            }
            事件.发布(new 背包变化事件(旧.标识, 1, 变化原因.获得));
        }
        事件.发布(new 背包变化事件(堆叠.标识, -1, 变化原因.消耗));
        事件.发布(new 属性变化事件(玩家.体质, 玩家.力量, 玩家.智慧, 玩家.敏捷, 玩家.意志, 玩家.自由属性点));
        事件.发布(new 日志事件(日志类型.反馈, $"装备了 {物品.名称}。"));
        音效管理器.实例?.播放放下();   // 装备成功 → 放下音效（右键菜单/双击/拖拽 统一）
        return true;
    }

    // 换背包槽/卸下背包前校验：旧"主背包"网格（档案.背包服务）尺寸还原时现有物品能否容纳。
    // 主背包已废弃（不再存放物品）→ 恒通过，保留为防御（防旧档残留）。
    private static bool 背包可容纳(玩家档案 玩家, string 新包标识)
    {
        var (新列, 新行) = 玩家.背包网格尺寸(新包标识);
        if (玩家.形状解析 == null) return true;
        foreach (var 堆叠 in 玩家.背包)
        {
            if (堆叠 == null || 堆叠.列 < 0) continue;
            var 形状 = 玩家.形状解析(堆叠.标识);
            int 宽 = 堆叠.旋转 ? 形状.高 : 形状.宽;
            int 高 = 堆叠.旋转 ? 形状.宽 : 形状.高;
            if (堆叠.列 + 宽 > 新列 || 堆叠.行 + 高 > 新行) return false;
        }
        return true;
    }

    // 卸下（转移模型）：清空指定槽（含词缀）+ 物品回放（从哪来回哪去：来源=仓库 → 仓库；来源=穿戴容器槽 → 原容器；
    // 未知/旧档 → 统一放入 穿戴容器→仓库；入格失败 → 物品保留在槽位）
    public static void 卸下(玩家档案 玩家, string 槽位)
    {
        var 记录 = 玩家.卸下装备(槽位);
        if (记录 == null || string.IsNullOrEmpty(记录.标识)) return;
        if (槽位 == "背包")
        {
            // 卸下背包 → 网格还原默认尺寸：先校验现有物品能否容纳，放不下则穿回
            if (!背包可容纳(玩家, ""))
            {
                玩家.装备到槽("背包", 记录);   // 完整恢复（含容器数据，不丢内部物品）
                玩家.应用背包装备();
                音效管理器.实例?.播放失败();
                ServiceRegistry.Get<EventBus>().发布(new 日志事件(日志类型.反馈坏, "背包空间不足，无法卸下。"));
                return;
            }
            玩家.应用背包装备();
        }
        var 堆叠 = 装备转堆叠(记录);
        bool 放下 = 回放(玩家, 记录.来源, 堆叠);
        if (!放下)
        {
            玩家.装备到槽(槽位, 记录);   // 回滚：放不下就穿回（完整恢复，不丢容器内部物品）
            if (槽位 == "背包") 玩家.应用背包装备();     // 还原背包网格尺寸
            音效管理器.实例?.播放失败();
            ServiceRegistry.Get<EventBus>().发布(new 日志事件(日志类型.反馈坏, "背包已满，无法卸下。"));
            return;
        }
        var 事件 = ServiceRegistry.Get<EventBus>();
        事件.发布(new 背包变化事件(记录.标识, 1, 变化原因.获得));
        事件.发布(new 属性变化事件(玩家.体质, 玩家.力量, 玩家.智慧, 玩家.敏捷, 玩家.意志, 玩家.自由属性点));
        string 名称 = ServiceRegistry.Get<DataService>().物品.TryGetValue(记录.标识, out var 物品) ? 物品.名称 : 记录.标识;
        事件.发布(new 日志事件(日志类型.反馈, $"卸下了 {名称}。"));
        音效管理器.实例?.播放放下();   // 卸下成功 → 放下音效
    }

    // 按 来源 回放物品（从哪来回哪去）：仓库 → 仓库视图；穿戴容器槽 → 原容器；未知 → 统一放入（穿戴容器→仓库）。
    // 各处 满/不可用 时逐级兜底，最终兜底 统一放入。
    private static bool 回放(玩家档案 玩家, string 来源, 物品堆叠 堆叠)
    {
        if (来源 == "仓库")
        {
            var 仓库 = 玩家.仓库视图();
            if (仓库.放入网格堆叠(堆叠)) return true;
        }
        else if (来源 == "弹挂" || 来源 == "腰封" || 来源 == "背包")
        {
            var 容器视图 = 玩家.穿戴容器视图(来源);   // 容器 可能 已卸下/未穿戴 → null
            if (容器视图 != null && 容器视图.放入网格堆叠(堆叠)) return true;
        }
        // 兜底：统一放入（穿戴容器 → 仓库）
        return 玩家.放入堆叠(堆叠) > 0;
    }

    // 装备来源网格名：从哪来回哪去（卸下/回滚 时按来源回放）。
    // 仓库视图 判定用 背包列表引用（== 档案.仓库物品）；穿戴容器视图（背包引用 == 某 装备记录.容器物品）→ 该槽位名。
    // 无"主背包"概念：其他/未知 兜底 仓库（档案.背包 已废弃，不再存放物品）。
    private static string 来源名(玩家档案 玩家, 背包服务 服务)
    {
        if (服务 == null || 服务.背包 == 玩家.仓库物品) return "仓库";
        foreach (var 槽 in new[] { "弹挂", "腰封", "背包" })
        {
            var 记录 = 玩家.装备.Find(e => e.槽位 == 槽);
            if (记录?.容器物品 != null && 记录.容器物品 == 服务.背包) return 槽;
        }
        return "仓库";
    }

    // 卸下到指定格（装备拖拽放置用）：清空槽（含词缀/容器数据）→ 放入 目标服务 指定格；目标格不可放 → 穿回原位。
    // 背包槽：卸下影响主背包网格尺寸 → 先缩容校验 + 应用默认尺寸（放不下现有物品 → 穿回）。返回是否成功
    public static bool 卸下到格(玩家档案 玩家, string 槽位, 背包服务 目标服务, int 列, int 行)
    {
        var 记录 = 玩家.卸下装备(槽位);
        if (记录 == null || string.IsNullOrEmpty(记录.标识)) return false;
        var 堆叠 = 装备转堆叠(记录);
        // 背包槽：卸下 → 主背包网格还原默认尺寸（缩容校验：现有物品必须能容纳）
        if (槽位 == "背包")
        {
            if (!背包可容纳(玩家, ""))
            {
                玩家.装备到槽(槽位, 记录);   // 完整恢复穿回
                return false;
            }
            玩家.应用背包装备();
        }
        if (目标服务 != null && 目标服务.放入指定格(堆叠, 列, 行))
        {
            var 事件 = ServiceRegistry.Get<EventBus>();
            事件.发布(new 背包变化事件(记录.标识, 1, 变化原因.获得));
            事件.发布(new 属性变化事件(玩家.体质, 玩家.力量, 玩家.智慧, 玩家.敏捷, 玩家.意志, 玩家.自由属性点));
            return true;
        }
        玩家.装备到槽(槽位, 记录);   // 放不下 → 穿回原位（完整恢复，不丢容器内部物品）
        if (槽位 == "背包") 玩家.应用背包装备();   // 还原背包网格尺寸
        return false;
    }

    // 装备记录 → 物品堆叠（完整携带 词缀/耐久/容器数据——穿戴容器卸下后内部物品不丢失）
    private static 物品堆叠 装备转堆叠(装备记录 记录)
        => new 物品堆叠(记录.标识, 1)
        {
            词缀 = 记录.词缀,
            当前耐久 = 记录.当前耐久,
            容器物品 = 记录.容器物品,
            容器列 = 记录.容器列,
            容器行 = 记录.容器行,
        };

    // 按 物品模板 构造 新装备堆叠（换装回滚用）：容器位 带模板容器尺寸 + 空容器
    private static 物品堆叠 新装备堆叠(玩家档案 玩家, string 标识, List<词缀条> 词缀, int 当前耐久)
    {
        var 堆叠 = new 物品堆叠(标识, 1) { 词缀 = 词缀, 当前耐久 = 当前耐久 };
        var 尺寸 = 玩家.容器尺寸解析?.Invoke(标识);
        if (尺寸 != null && 尺寸.Value.列 > 0)   // 容器位（弹挂/腰封/背包）
        {
            堆叠.容器列 = 尺寸.Value.列;
            堆叠.容器行 = 尺寸.Value.行;
            堆叠.容器物品 = new List<物品堆叠>();
        }
        return 堆叠;
    }

    // 技能书：技能系统统一入口（属性前提达标才学），成功才消耗书本
    public static void 学习技能书(玩家档案 玩家, 物品数据 物品)
    {
        if (string.IsNullOrEmpty(物品.技能)) return;
        if (ServiceRegistry.Get<技能服务>().尝试学习(物品.技能))
        {
            玩家.移除物品(物品.标识);
            ServiceRegistry.Get<EventBus>().发布(new 背包变化事件(物品.标识, -1, 变化原因.消耗));
        }
    }

    // 使用恢复品（战斗外/背包）：扣物品 + 按 恢复目标 结算（饱食/水分/生命/伤病）+ 发事件
    // 医疗类（生命/伤病）受 医疗修正（医者仁心）加成；恢复量 × 品质倍率
    public static void 使用恢复(玩家档案 玩家, DataService 数据, string 标识)
    {
        if (!数据.物品.TryGetValue(标识, out var 物品) || 物品.恢复量 <= 0) return;   // 带恢复量才可战斗外使用
        if (!玩家.移除物品(标识)) { 音效管理器.实例?.播放失败(); return; }
        var 事件 = ServiceRegistry.Get<EventBus>();
        int 恢复 = Mathf.Max(1, Mathf.RoundToInt(物品.恢复量 * 品质工具.倍率(物品.品质档)));
        string 目标 = string.IsNullOrEmpty(物品.恢复目标) ? "生命" : 物品.恢复目标;
        bool 医疗类 = 目标 != "饱食" && 目标 != "水分";
        if (医疗类) 恢复 = Mathf.Max(1, Mathf.RoundToInt(恢复 * 玩家.医疗修正));
        switch (目标)
        {
            case "饱食":
                玩家.饱食度 = Mathf.Clamp(玩家.饱食度 + 恢复, 0, 100);
                事件.发布(new 生存状态变化事件(生存状态类型.饱食度, 玩家.饱食度, 恢复));
                break;
            case "水分":
                玩家.水分度 = Mathf.Clamp(玩家.水分度 + 恢复, 0, 100);
                事件.发布(new 生存状态变化事件(生存状态类型.水分度, 玩家.水分度, 恢复));
                break;

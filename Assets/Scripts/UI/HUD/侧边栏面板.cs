using UnityEngine;
using UnityEngine.UI;

// 侧边栏面板：右侧常驻功能按钮栏。现在是 6 颗：设置 / 音量 / 暂停 / 存档 / 背包 / 角色。
//
// ★ 可开合（用户 2026-09-15）：「HUD 是常驻的，但侧边栏不一定」→ HUD 上那颗开关按钮
//   调 `切换显示()`；本类自己记住"用户想不想看见"。
//
// ★ 为什么"想不想看见"必须记在字段里、而不是直接 SetActive：
//   侧边栏挂在 `面板管理器.常驻UI` 里，`面板管理器.显示()` **每次切面板都会把它 SetActive(true)**
//   （`常驻UI` 的作用是"开始流程后常驻、主菜单时收起"）。如果只是简单关掉它，
//   玩家下一次点任何面板它就会自己弹回来 —— 看起来像"关不掉"。
//   所以：`刷新显隐()` 在我们**自己**这一侧把 `用户要看见` 重新应用一遍。
//   时机是安全的：`面板管理器.显示()` 在最后一步才发 `面板切换事件`（SetActive 全跑完之后），
//   我们订阅它 → 于是每次都被重新收起。
//
// ★ 已删除 2 颗（用户 2026-09-15：「任务、取消、角色 都不需要了」→「你停用，就删掉啊」）：
//   字段、onClick 订阅、「取消」文案的 `取消文字`（TMP）全部移除。
//   删掉带来的影响记在这里，别以后当成 bug 查：
//   · **取消**：它曾经是全局回退的唯一入口。现在**本项目没有全局回退键**（用户拍板不绑 Esc）——
//     离开面板靠各面板自己的出口按钮，或走到出口格（房间大门/楼梯、区域街口、大世界营地门口格）。
//     受影响最大的是**大世界**：不再有「一键回安全屋」，回家要走到营地门口格
//     （`大世界探索服务.抵达格` 发 `打开营地事件` —— 那条路本来就是设计里的正路）。
//   · **任务**：任务面板本来就没建（`面板管理器.任务` 是个 `面板基类 待建` 引用位），
//     而用户 2026-09-13 已拍板「剧情 / 任务不做」→ 那颗按钮点了本来就没反应。
//
// ★ **角色 按钮已经加回来**（用户拍板"开工"重建角色面板 → 那个面板重新需要入口）：
//   `角色按钮` 字段 + 一条 onClick = 发布 `打开角色面板事件`（`面板管理器` 订阅它 → `显示(角色)`）。
//   它过去是、现在**仍然是** `打开角色面板事件` 的**唯一发布方** —— 这颗按钮不接线，角色面板就进不去。
//   ⚠ 按钮**物体**由用户在 Unity 里加（本类不建物体，也不碰场景）：把物体拖到 `角色按钮` 引用位即可。
//   背包仍由本面板的「背包」按钮 / F1 打开（`玩家输入系统.切换持有面板()`）。
public sealed class 侧边栏面板 : MonoBehaviour
{
    // 供 HUD 的开关按钮取用（HUD 不需要拖侧边栏的引用位）
    public static 侧边栏面板 实例 { get; private set; }

    [SerializeField] private Button 设置按钮, 音量按钮, 暂停按钮, 存档按钮, 背包按钮, 角色按钮;
    // 注：设置 / 存档 两个覆盖层**不在这里留引用位** —— 开关收口在 `面板管理器`（打开设置() / 打开存档()），
    //   本栏只是快捷方式（原来侧边栏也各拖了一份，等于同一个面板两处引用位，谁改了另一处都不知道）。

    // 暂停图标（暂停符号 / 继续符号）
    [SerializeField] private Image 暂停图;
    [SerializeField] private Sprite 暂停图标, 继续图标;
    // 音量图标（开 / 关）
    [SerializeField] private Image 音量图;
    [SerializeField] private Sprite 音量开图标, 音量关图标;

    // 用户通过 HUD 开关决定的显隐意图（见文件头：必须记住，否则一切面板就弹回来）
    private bool 用户要看见 = true;
    private bool 上次广播可见 = true;   // 只在真的变了才广播 `侧边栏显隐变化事件`

    public bool 显示中 => 用户要看见;

    // 实际可见（已经把"未开局/主菜单"算进去）——会被侧边栏盖住的右区部件读这个来"让位"
    public bool 可见 => gameObject.activeSelf;

    void Awake()
    {
        // ★ 场景里可能挂了**多个** 侧边栏面板（当前实际有一个多余的、引用位全空）。
        //   原来直接 `实例 = this` → 谁后 Awake 谁赢 → HUD 那颗开关可能认到空的那一个，"点了没反应"。
        //   这里显式检测：**只认第一个**并报警，别让它悄悄认错。
        if (实例 != null && 实例 != this)
            Debug.LogError($"[侧边栏] 场景里有多个 侧边栏面板（本物体「{name}」是后来者）—— HUD 的开关只会认第一个，" +
                           "请把多余的那个物体删掉。");
        else 实例 = this;
        var 事件 = ServiceRegistry.Get<EventBus>();
        事件?.订阅<面板切换事件>(_ => 刷新显隐());
        // 战斗开始/结束 刷新按钮显隐（战斗中禁存档，见 刷新显隐）
        事件?.订阅<战斗开始事件>(_ => 刷新显隐());
        事件?.订阅<战斗结束事件>(_ => 刷新显隐());
        设置按钮?.onClick.AddListener(() => 面板管理器.实例?.打开设置());
        音量按钮?.onClick.AddListener(() => { 音效管理器.实例?.切换静音(); 刷新音量(); });
        暂停按钮?.onClick.AddListener(暂停切换);
        存档按钮?.onClick.AddListener(存档);
        背包按钮?.onClick.AddListener(玩家输入系统.切换持有面板);
        // 角色：本面板是 `打开角色面板事件` 的唯一发布方（接法与上面几颗一致：判空 + AddListener）
        角色按钮?.onClick.AddListener(() => 事件?.发布(new 打开角色面板事件()));
        刷新显隐();
        刷新音量();
    }

    void OnDestroy() { if (实例 == this) 实例 = null; }

    // —— 开合（HUD 的开关按钮调这两个中的一个）——
    public void 切换显示() { 用户要看见 = !用户要看见; 刷新显隐(); }
    public void 设为显示(bool 显示) { 用户要看见 = 显示; 刷新显隐(); }

    // 存档：打开存档面板（选槽保存/读取/删除）。
    // ★ 刀64：允许条件收敛到 **存档门禁**（"唯一真相"）—— 未开局 / 战斗中 都在那里判，
    //   文案也统一从那里来（含用户口径「战斗时不需要存档读档」）。
    //   本按钮的显隐（刷新显隐）是第一层"体验"，门禁才是第二层"正确性"——两层都要在。
    private void 存档()
    {
        string 拒 = 存档门禁.存前检查();
        if (拒 != "")
        {
            音效管理器.实例?.播放失败();
            ServiceRegistry.Get<EventBus>()?.发布(new 日志事件(日志类型.警告, 拒));
            return;
        }
        面板管理器.实例?.打开存档(false);
    }

    // 暂停：Time.timeScale 0↔1（游戏世界冻结）；图标切换 暂停/继续
    private void 暂停切换()
    {
        bool 暂停中 = Time.timeScale == 0f;
        Time.timeScale = 暂停中 ? 1f : 0f;
        if (暂停图 != null) 暂停图.sprite = 暂停中 ? 暂停图标 : 继续图标;
    }

    // 每帧不该做的事这里都不做；这个方法在 面板切换 / 战斗开始结束 / 开合 时被调。
    // 两件事：① 应用"用户想不想看见"（还要让开主菜单 —— 常驻UI 在标题界面收起，见 面板管理器）
    //        ② 战斗中隐藏「存档」
    private void 刷新显隐()
    {
        // ★ 步2：改读**会话阶段**（原来自己判"当前显示面板是不是主菜单" —— 同一答案的第三种写法）
        bool 主菜单 = 游戏会话.是未开局;
        // 回主菜单 = 顺手重置：下一局开始时侧边栏默认是开着的（否则玩家会以为它坏了）
        if (主菜单) 用户要看见 = true;
        gameObject.SetActive(用户要看见 && !主菜单);
        // ★ 只在**可见性真的变了**时广播一次（这个方法会被面板切换/战斗开始结束频繁调到）
        bool 现在可见 = gameObject.activeSelf;
        if (现在可见 != 上次广播可见)
        {
            上次广播可见 = 现在可见;
            ServiceRegistry.Get<EventBus>()?.发布(new 侧边栏显隐变化事件(现在可见));
        }

        bool 战斗中 = ServiceRegistry.Get<BattleService>()?.战斗中 ?? false;
        if (暂停按钮 != null) 暂停按钮.gameObject.SetActive(!主菜单);
        if (存档按钮 != null) 存档按钮.gameObject.SetActive(!主菜单 && !战斗中);
        if (主菜单 && Time.timeScale == 0f)
        {
            Time.timeScale = 1f;
            if (暂停图 != null) 暂停图.sprite = 暂停图标;
        }
    }

    private void 刷新音量()
    {
        bool 静音 = 音效管理器.实例?.已静音 ?? false;
        if (音量图 != null) 音量图.sprite = 静音 ? 音量关图标 : 音量开图标;
    }
}

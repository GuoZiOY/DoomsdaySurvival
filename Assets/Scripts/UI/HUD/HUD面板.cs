using TMPro;
using UnityEngine;
using UnityEngine.UI;

// HUD 面板：常驻顶栏，显示并实时更新 6 项——生命 / 行动点（精力）/ 饱食度 / 水分度 / 世界时间 / 世界地点。
// 样式：状态项（生命/精力/饱食/水分）只显示数字，不带文字标签，用颜色区分：
//       生命=红 / 精力=金 / 饱食=绿 / 水分=蓝；时间=灰蓝（14:35），地点=灰（文字）。
// 刷新双保险：
//   ① 事件驱动：订阅 生命/行动点/饱食/水分/时间/地点 变化事件，即时更新（吃/喝/战斗/时钟/地图切换）。
//   ② 轮询兜底：Update 每帧对比玩家档案缓存，值变才刷新（行动点消耗遍布 探索/训练/制作 等无事件路径，
//     轮询保证任何改动都能同步；比较为轻量 int/string，无 GC 压力）。
// ★ 侧边栏开关（用户 2026-09-15）：「HUD 是常驻的，但侧边栏不一定」——
//   这颗按钮呼出/收起右侧功能栏（`侧边栏面板.切换显示()`）。侧边栏自己记住开合意图，
//   所以它被 `面板管理器.常驻UI` 每次切面板强制打开之后，会自己再收起（见 侧边栏面板 文件头）。
// 场景搭建：顶部栏 物体 挂 本组件，拖入 6 个 TMP 文本 引用位 + 1 个 侧边栏开关按钮（字段名 = 语义，按名拖即可）。
public sealed class HUD面板 : 面板基类
{
    [SerializeField] private TMP_Text 生命;
    [SerializeField] private TMP_Text 行动点;   // 精力（探索/战斗消耗）——金色
    [SerializeField] private TMP_Text 饱食度;
    [SerializeField] private TMP_Text 水分度;   // 蓝色
    [SerializeField] private TMP_Text 时间;
    [SerializeField] private TMP_Text 地点;

    // 侧边栏开关：按钮必填（不拖就没有入口）；**两颗图**替换显示（照「暂停」按钮那套写法）——
    // 侧边栏开着时显示"收起"图，收起时显示"呼出"图。
    [SerializeField] private Button 侧边栏开关;
    [SerializeField] private Image 侧边栏开关图;
    [SerializeField] private Sprite 侧边栏收起图标, 侧边栏呼出图标;

    // 关闭按钮：给"当前面板"用的统一出口（用户 2026-09-15 放到 HUD 上）。
    // **按需显隐**：当前面板声明 `可关闭`（= 它覆写了 `取消文本`，即它有真的退出口）时才显示；
    //   主菜单 / 战斗 / 没有面板 时自动收起。判据见 `面板基类.可关闭`。
    [SerializeField] private Button 关闭按钮;

    // 轮询缓存（避免每帧重复设文本）
    private int 上次生命 = -1, 上次行动 = -1;
    private float 上次饱食 = -1f, 上次水分 = -1f;
    private string 上次时间 = "", 上次地点 = "";

    void Awake()
    {
        var 事件 = ServiceRegistry.Get<EventBus>();
        事件.订阅<生命变化事件>(e => 设文本(生命, 着(游戏主题.危险色值, $"{e.当前}/{e.最大}")));
        事件.订阅<精力变化事件>(e => 设文本(行动点, 着(游戏主题.金色色值, $"{e.当前}/{e.最大}")));   // 精力 = 金色
        事件.订阅<生存状态变化事件>(e =>
        {
            if (e.类型 == 生存状态类型.饱食度) 设文本(饱食度, 着(游戏主题.成功色值, $"{e.当前:0.#}/100"));
            else if (e.类型 == 生存状态类型.水分度) 设文本(水分度, 着(游戏主题.远程色值, $"{e.当前:0.#}/100"));   // 水分 = 蓝
        });
        事件.订阅<伤病变化事件>(e =>
        {
            if (e.当前 > 30 && e.变化量 > 0)
                事件.发布(new 日志事件(日志类型.警告, $"伤病加重：{伤病名(e.类型)}（{e.当前}）"));
        });
        事件.订阅<时间变化事件>(e => 设文本(时间, 着(游戏主题.时间戳色值, 时间文本(e.游戏分钟数))));
        事件.订阅<地图位置事件>(e => 设文本(地点, 着(游戏主题.暗淡色值, 地点名(e))));
        事件.订阅<战斗结束事件>(_ => 刷新全量());
        事件.订阅<面板切换事件>(_ => { 刷新全量(); 刷新侧边栏开关(); 刷新关闭按钮(); });   // 面板一切换：侧边栏文案、关闭按钮显隐都要跟着变

        侧边栏开关?.onClick.AddListener(切换侧边栏);
        关闭按钮?.onClick.AddListener(关闭当前面板);
        刷新侧边栏开关();
        刷新关闭按钮();
    }

    // 关闭按钮：关掉"当前面板"（= 调它的 `回退()`，与各面板自己的出口按钮同一条路）
    private void 关闭当前面板()
    {
        var 当前 = 面板管理器.实例?.当前显示面板;
        if (当前 == null || !当前.可关闭) { 刷新关闭按钮(); return; }
        当前.回退();
        刷新关闭按钮();
    }

    // 关闭按钮**按需显隐**：只有"当前面板声明自己能关"时才出现（主菜单 / 战斗 / 无面板 → 收起）
    private void 刷新关闭按钮()
    {
        if (关闭按钮 == null) return;
        关闭按钮.gameObject.SetActive(面板管理器.实例?.当前显示面板?.可关闭 == true);
    }

    // 侧边栏开关按钮：呼出 / 收起右侧功能栏
    private void 切换侧边栏()
    {
        var 栏 = 侧边栏面板.实例;
        if (栏 == null)
        {
            Debug.LogWarning("[HUD] 场景里没有 侧边栏面板 —— 这颗开关按钮没东西可开合。");
            return;
        }
        栏.切换显示();
        刷新侧边栏开关();
    }

    // 开关按钮的**图**：侧边栏开着 → 显示「收起」图；收起 → 显示「呼出」图。
    private void 刷新侧边栏开关()
    {
        if (侧边栏开关图 == null) return;
        var 栏 = 侧边栏面板.实例;
        侧边栏开关图.sprite = (栏 != null && 栏.显示中) ? 侧边栏收起图标 : 侧边栏呼出图标;
    }

    // 轮询兜底：任何状态变化（含无事件路径）都同步到 HUD
    void Update()
    {
        var 玩家 = ServiceRegistry.Get<PlayerService>()?.档案;
        if (玩家 == null) return;
        if (玩家.生命 != 上次生命) { 上次生命 = 玩家.生命; 设文本(生命, 着(游戏主题.危险色值, $"{玩家.生命}/{玩家.最大生命}")); }
        if (玩家.行动点 != 上次行动) { 上次行动 = 玩家.行动点; 设文本(行动点, 着(游戏主题.金色色值, $"{玩家.行动点}/{玩家.最大行动点}")); }
        if (玩家.饱食度 != 上次饱食) { 上次饱食 = 玩家.饱食度; 设文本(饱食度, 着(游戏主题.成功色值, $"{玩家.饱食度:0.#}/100")); }
        if (玩家.水分度 != 上次水分) { 上次水分 = 玩家.水分度; 设文本(水分度, 着(游戏主题.远程色值, $"{玩家.水分度:0.#}/100")); }
        string 时 = 时间文本(玩家.游戏分钟数);
        if (时 != 上次时间) { 上次时间 = 时; 设文本(时间, 着(游戏主题.时间戳色值, 时)); }
    }

    // 按玩家档案重写（兜底刷新：读档/战斗结束/面板切换 后 全量同步）
    private void 刷新全量()
    {
        var 玩家 = ServiceRegistry.Get<PlayerService>()?.档案;
        if (玩家 == null) return;
        上次生命 = 玩家.生命; 上次行动 = 玩家.行动点; 上次饱食 = 玩家.饱食度; 上次水分 = 玩家.水分度;
        设文本(生命, 着(游戏主题.危险色值, $"{玩家.生命}/{玩家.最大生命}"));
        设文本(行动点, 着(游戏主题.金色色值, $"{玩家.行动点}/{玩家.最大行动点}"));
        设文本(饱食度, 着(游戏主题.成功色值, $"{玩家.饱食度:0.#}/100"));
        设文本(水分度, 着(游戏主题.远程色值, $"{玩家.水分度:0.#}/100"));
        设文本(时间, 着(游戏主题.时间戳色值, 时间文本(玩家.游戏分钟数)));
    }

    protected override void 刷新(object 上下文) { }

    private static string 着(string 色, string 正文) => $"<color={色}>{正文}</color>";

    private static string 时间文本(float 分钟)
    {
        int 分钟整 = (int)分钟;
        return $"{分钟整 / 60 % 24:00}:{分钟整 % 60:00}";
    }

    private static string 伤病名(伤病类型 类型)
    {
        switch (类型)
        {
            case 伤病类型.疲劳: return "疲劳";
            case 伤病类型.中毒: return "中毒";
            case 伤病类型.感冒: return "感冒";
            case 伤病类型.流血: return "流血";
            case 伤病类型.骨折: return "骨折";
            case 伤病类型.发烧: return "发烧";
            default: return "";
        }
    }

    private string 地点名(地图位置事件 e)
    {
        // v51：节点网图退役 → `地图位置事件.大节点` 里装的**已经是显示名**（各格子层发的是 地点文本()：
        // 大世界 = "废城" / 区域 = 区域名 / 房间 = 房间名），不再需要拿标识去 `地图` 表里查名字。
        // 也不再拼"（野外）"—— 那个后缀的依据 地图模式.野外 已随 地图服务 一起消失。
        return e.大节点;
    }
}

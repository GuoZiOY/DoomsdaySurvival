using TMPro;
using UnityEngine;
using UnityEngine.UI;

// 角色面板：全局角色信息（属性查看 + 加点 + 装备换装 + 背包使用）。HUD 按钮打开，返回回到上个面板。
public sealed class 角色面板 : 面板基类
{
    [SerializeField] private TMP_Text 标题;
    // 内容区 由 面板基类 提供（行容器：属性/装备/背包都往里塞）
    [SerializeField] private Button 返回按钮;

    void Awake()
    {
        var 事件 = ServiceRegistry.Get<EventBus>();
        事件.订阅<属性变化事件>(_ => 刷新(null));
        事件.订阅<背包变化事件>(_ => 刷新(null));
        返回按钮?.onClick.AddListener(() => 面板管理器.实例?.返回上一面板());
    }

    protected override void 刷新(object 上下文)
    {
        var 玩家 = ServiceRegistry.Get<PlayerService>().档案;
        var 数据 = ServiceRegistry.Get<DataService>();
        var 事件 = ServiceRegistry.Get<EventBus>();
        设文本(标题, $"—— 角色 ——  等级 {玩家.等级}   自由属性点 {玩家.自由属性点}");
        清空(内容区);

        // —— 属性区（自由点足够时显示加点按钮）——
        创建标签(内容区, "—— 属性 ——");
        if (玩家.自由属性点 > 0)
        {
            创建行(内容区, $"体力 {玩家.体力}    [+]", () => 加点(玩家, 事件, 属性类型.体力));
            创建行(内容区, $"力量 {玩家.力量}    [+]", () => 加点(玩家, 事件, 属性类型.力量));
            创建行(内容区, $"智力 {玩家.智力}    [+]", () => 加点(玩家, 事件, 属性类型.智力));
            创建行(内容区, $"敏捷 {玩家.敏捷}    [+]", () => 加点(玩家, 事件, 属性类型.敏捷));
        }
        else
        {
            创建行(内容区, $"体力 {玩家.体力}", null);
            创建行(内容区, $"力量 {玩家.力量}", null);
            创建行(内容区, $"智力 {玩家.智力}", null);
            创建行(内容区, $"敏捷 {玩家.敏捷}", null);
        }

        // —— 派生数值 ——
        创建标签(内容区, "—— 能力 ——");
        创建行(内容区, $"物理伤害 {玩家.物理伤害}    魔法伤害 {玩家.魔法伤害}", null);
        创建行(内容区, $"暴击 {Mathf.RoundToInt(玩家.暴击概率 * 100)}%    闪避 {Mathf.RoundToInt(玩家.闪避概率 * 100)}%", null);
        创建行(内容区, $"生命 {玩家.生命}/{玩家.最大生命}    魔力 {玩家.魔力}/{玩家.最大魔力}", null);

        // —— 装备换装（背包里的武器/防具，点选装备）——
        创建标签(内容区, "—— 装备 ——");
        foreach (var 堆叠 in 玩家.背包)
        {
            if (堆叠.数量 <= 0 || !数据.物品.TryGetValue(堆叠.标识, out var 物品)) continue;
            if (物品.类型 != "武器" && 物品.类型 != "防具") continue;
            bool 已装 = (物品.类型 == "武器" && 玩家.武器标识 == 堆叠.标识) || (物品.类型 == "防具" && 玩家.防具标识 == 堆叠.标识);
            创建行(内容区, $"{品质工具.标签(物品.品质档)}{物品.名称}" + (已装 ? "  [已装备]" : "  [装备]"), () => 换装(玩家, 事件, 物品));
        }

        // —— 背包（技能书学习 / 恢复品使用）——
        创建标签(内容区, "—— 背包 ——");
        foreach (var 堆叠 in 玩家.背包)
        {
            if (堆叠.数量 <= 0 || !数据.物品.TryGetValue(堆叠.标识, out var 物品)) continue;
            if (物品.类型 == "武器" || 物品.类型 == "防具") continue;   // 装备已在上面
            if (物品.类型 == "技能书")
                创建行(内容区, $"{品质工具.标签(物品.品质档)}{物品.名称} ×{堆叠.数量}  [学习]", () => 学习技能书(玩家, 数据, 事件, 物品));
            else if (物品.类型 == "恢复")
                创建行(内容区, $"{品质工具.标签(物品.品质档)}{物品.名称} ×{堆叠.数量}  [使用]", () => 使用恢复(玩家, 数据, 事件, 堆叠.标识));
            else
                创建行(内容区, $"{品质工具.标签(物品.品质档)}{物品.名称} ×{堆叠.数量}", null);
        }
    }

    // 加点：消耗自由属性点
    private void 加点(玩家档案 玩家, EventBus 事件, 属性类型 类型)
    {
        if (!玩家.加点(类型)) return;
        事件.发布(new 属性变化事件(玩家.体力, 玩家.力量, 玩家.智力, 玩家.敏捷, 玩家.自由属性点));
    }

    // 换装：设置当前武器/防具
    private void 换装(玩家档案 玩家, EventBus 事件, 物品数据 物品)
    {
        if (物品.类型 == "武器") 玩家.武器标识 = 物品.标识;
        else if (物品.类型 == "防具") 玩家.防具标识 = 物品.标识;
        事件.发布(new 日志事件(日志类型.反馈, $"装备了 {物品.名称}。"));
    }

    // 技能书：技能系统统一入口（属性前提达标才学），成功才消耗书本
    private void 学习技能书(玩家档案 玩家, DataService 数据, EventBus 事件, 物品数据 物品)
    {
        if (string.IsNullOrEmpty(物品.技能)) return;
        if (ServiceRegistry.Get<技能服务>().尝试学习(物品.技能))
        {
            玩家.移除物品(物品.标识);
            事件.发布(new 背包变化事件(物品.标识, -1, 变化原因.消耗));
        }
    }

    // 使用恢复品（战斗外恢复）
    private void 使用恢复(玩家档案 玩家, DataService 数据, EventBus 事件, string 标识)
    {
        if (!数据.物品.TryGetValue(标识, out var 物品) || 物品.类型 != "恢复") return;
        if (!玩家.移除物品(标识)) return;
        int 恢复 = Mathf.Max(1, Mathf.RoundToInt(物品.恢复量 * 品质工具.倍率(物品.品质档)));
        玩家.恢复生命(恢复);
        事件.发布(new 生命变化事件(玩家.生命, 玩家.最大生命, 恢复));
        事件.发布(new 背包变化事件(标识, -1, 变化原因.消耗));
        事件.发布(new 日志事件(日志类型.反馈, $"你使用了{物品.名称}，恢复 {恢复} 点生命。"));
    }
}

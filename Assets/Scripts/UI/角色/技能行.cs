using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.UI;
using TMPro;

// 技能行：技能子面板「下面 · 已学技能列表」的行模板组件（挂在模板行根节点上，场景里默认 SetActive(false)）。
// 一行 = 一个**已学会**的技能（未学会的不列 —— 用户钦定）；行序 = `玩家档案.已学技能` 的原始顺序（学习先后）。
//
// 为什么单独一个文件（照 `知识行` / `配方行` 的做法）：行组件是**模板资产上的脚本**，与页面逻辑分开才好让用户
//   在 Unity 里单独把模板行拆出来摆。
//
// 本批改版（用户定稿）：行是**纯索引**（与 `知识行` 同一口径），只有三样东西 ——
//   ① 名称（已由页面按品质着色，本类不再包颜色）；
//   ② 按钮（模板行自带的点击面，**可选**；不挂 Button 也能点，见下面的 `IPointerClickHandler`）；
//   ③ **置灰**（一个预置节点，显隐由本类切）—— 判据 = "这条技能**有没有装进技能槽**"：
//      没装的行灰着，6 格里放了哪几条一眼看得出（`知识子面板.绑行` 传进来的就是这个事实）。
// **删掉**（连同页面里的写入一起）：`类别` / `主动与否` / `熟练` / `已装` 四个文本位 + `待装高亮`：
//   · 前四个是"细节"，现在由页面右下方的**那一个说明文本**承载（点哪条看哪条）—— 行里再留一份就是同一件事
//     写两遍，改口径时必有一边漏掉；
//   · `待装高亮` 按用户口径"只有一个名字、按钮、置灰"一并去掉 —— 待装的反馈由说明区 + 上面技能槽的高亮给
//     （槽那边的 `技能格.待装高亮` 一个字没动）。
//   ⚠ `置灰` 用**结构手段**（预置节点的显隐）而不是写 `Color` / `CanvasGroup.alpha`：本项目 UI 层的硬边界是
//     "外观 100% 归场景 / 预制体"（本类与 `技能子面板` 一个口径）—— "怎么灰"（半透明灰罩 / 另写一套灰字 /
//     换个灰图标）留给用户在场景里定，代码只 `SetActive`，不关心罩子里有什么。
//
// 只做这几件事，别的一概不碰：
//   ① 内容填空（名称）；
//   ② 置灰态 **只用 `SetActive`**（一个预置节点，颜色/透明度全归场景）；
//   ③ 点击转发（`IPointerClickHandler`，与 `知识行` / `配方行` 同款：不用 Button 也能点，行内子节点点到也算行）。
//   ⚠ **护栏**（照 `知识行` 那条，本批一并带上）：`置灰` 若被误接成**行根节点本身**（`知识行.prefab` 就这么
//     接错过），`SetActive` 关掉的就是**整行**（表现是"列表里 13 行全灭"，且一条报错都没有）——
//     所以这个引用位一律先过 `可切显隐`：命中就**跳过 `SetActive`** 并 `LogWarning` 一次（static 标志，
//     一开列表只喊一条），宁可灰不生效，也不许整行消失。
public sealed class 技能行 : MonoBehaviour, IPointerClickHandler
{
    // 字段名保持 `名称` / `按钮` 不动：它们是序列化引用位的名字（改名 = 场景/预制体上已经接过的线会丢）。
    [SerializeField] private TMP_Text 名称;          // 技能名（**已由页面按品质着色**，本类不再包颜色）
    [SerializeField] private Button 按钮;            // 可选：模板行若用 Button 做点击面，本类也接同一路
    [SerializeField] private GameObject 置灰;        // 未装进技能槽时亮出的"灰罩 / 灰字"预置节点（本类只切显隐）

    // 节点名兜底（照 `知识行.名未掌握置灰` 的口径）：用户常常"加了节点、忘了拖引用位"——
    //   `置灰` 这个名字独一无二，误配不了别的东西，所以引用位空着时按名找一次（**只找，不建**）。
    private const string 名置灰 = "置灰";
    private GameObject 灰缓存;      // 按名找到的结果（含"找到了没有"这个结论，见 `取置灰`）
    private bool 找过灰;

    private UnityEngine.Events.UnityAction 点击回调;

    // 点击行：uGUI 事件沿层级冒泡 —— 点到行内任何子节点都算点这一行（照 `配方行`）。
    // 音效不在这里播放：待装/取消由页面统一决定（选中的反馈音只在状态真的变了时响）。
    public void OnPointerClick(PointerEventData 事件) => 点击回调?.Invoke();

    // 绑定一行 —— 本类只认三样：名称文本 / 置灰与否 / 点击回调（见类头）。
    // `置灰中` = 页面算好的**事实**（这条技能没装进技能槽）；本类不自己去查档案 ——
    //   行是池化复用的，让它拿着 `玩家档案` 去查会把"数据口径"漏进视图层两份。
    public void 绑定(string 名称文本, bool 置灰中, UnityEngine.Events.UnityAction 点击)
    {
        点击回调 = 点击;
        面板基类.设文本(名称, 名称文本);

        // 置灰：只切一个预置节点的显隐，不写任何颜色 / 透明度（"怎么灰"归场景）。
        var 灰 = 取置灰();
        if (可切显隐(灰)) 灰.SetActive(置灰中);

        // 按钮那条路（模板行若挂了 Button）：只在首次绑定时接线一次，之后换的是"这次点谁"的回调
        if (按钮 != null)
        {
            按钮.onClick.RemoveAllListeners();
            按钮.onClick.AddListener(() => 点击回调?.Invoke());
            音效管理器.实例?.注册按钮(按钮);   // 幂等：悬停/点击反馈沿用项目既有口径
        }
    }

    // ================= 护栏：预置节点不许是"行根" =================

    // 为什么需要（`知识行` 那边实证过的坑，不是防御性编程）：`知识行.prefab` 里 `选中高亮` 被误接成了
    //   **行根节点自己**，于是 `SetActive(false)` 关掉的是**整行** —— 一打开列表 13 行全灭；
    //   而代码这边一条报错都没有（对行根调 `SetActive` 完全合法），用户只能靠肉眼猜是哪一处接错。
    // 判据（两种都挡，因为表现一模一样：关掉 = 本行跟着没）：
    //   · `目标 == gameObject`  → 接成了本组件所在的那个物体（行根本身）；
    //   · 本行是目标的子孙       → 接成了行的**祖先容器**（比如整个列表容器）。
    // 命中就**跳过 `SetActive`**：置灰不生效只是少个视觉提示，整行消失却是"列表空了"这种致命表现。
    private bool 可切显隐(GameObject 目标)
    {
        if (目标 == null) return false;
        if (目标 == gameObject || transform.IsChildOf(目标.transform))
        {
            警告接成行根();
            return false;
        }
        return true;
    }

    // "只喊一次"的标志用 **static**：行是**池化克隆**的（同一份预制体在场景里 N 份实例），
    //   实例字段 = "一开列表刷 N 条，每次重算再刷 N 条"——同一处预制体误配，喊一次就够人去改了。
    private static bool 已警告置灰接行根;

    private static void 警告接成行根()
    {
        if (已警告置灰接行根) return;
        已警告置灰接行根 = true;
        Debug.LogWarning("[技能行] `置灰` 接成了行根节点（或行的祖先容器），会导致整行被隐藏；" +
                         "请在预制体里改接一个专门的置灰子节点" +
                         "（本行已跳过对这个节点的 SetActive，行内其它内容照常显示）。");
    }

    // 置灰节点的取用：Inspector 引用位优先 → 按名兜底；两边都没有 → null（调用方据此退化成"不改外观"）。
    // 为什么要 `找过灰` 这个标记：兜底找不到是**常态**（模板里压根没搭灰罩的场景），
    //   而 `绑定` 是每行每次刷新都要跑的 —— 不记住"找过了、没有"，就会每次每行都白翻一遍子树。
    //   ⚠ 它是**可选**的表现层，不是功能位，所以不进 `技能子面板.报缺引用`。
    private GameObject 取置灰()
    {
        if (灰缓存 == null && !找过灰)
        {
            找过灰 = true;
            灰缓存 = 置灰 != null ? 置灰 : 找子(transform, 名置灰)?.gameObject;
        }
        return 灰缓存;
    }

    // 按名找子节点（任意深度）—— 照 `知识行.找子`：`Transform.Find` 只找直接子节点，
    //   而灰罩很可能被用户塞在"内容"容器里一层，直接子节点找法会漏。
    private static Transform 找子(Transform 根, string 名)
    {
        if (根 == null) return null;
        for (int i = 0; i < 根.childCount; i++)
        {
            var 子 = 根.GetChild(i);
            if (子.name == 名) return 子;
            var 深 = 找子(子, 名);
            if (深 != null) return 深;
        }
        return null;
    }
}

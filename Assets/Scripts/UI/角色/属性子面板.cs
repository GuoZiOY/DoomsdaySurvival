using System;
using System.Collections.Generic;
using TMPro;
using UnityEngine;
using UnityEngine.UI;

// 属性子面板 —— 角色面板「属性」页的内容（三个子面板里的第一个，按用户 2026-09-17 定稿重建）。
//
// 分工（硬边界，别越界）：
//   · **显隐不由本组件管**：壳（`角色面板`）只做 `SetActive`。所以本类**不继承 `面板基类`**
//     —— 不参与「显示面板 / 回退」那套协议，也不覆写 `刷新(object)`。
//   · 自刷入口两个：`Awake()` 与 `OnEnable()` 各刷一次（切页 = 壳把这一页 `SetActive(true)` → `OnEnable` 触发）。
//     `刷新()` **幂等**：全量重算（行值都是 `玩家档案` 上的计算属性，重算零成本，不做增量/缓存）。
//   · **外观 100% 归场景 / 预制体**（用户口径："那些色号、字号不要 —— 我在 Unity 里自己调"）：
//     本文件不写任何配色、字号、尺寸、进度数值；状态表达只用 `SetActive` 与 `Button.interactable`。
//
// 三个区 + 日志反馈（结构由用户在场景里搭，本组件只接线，**不建节点**）：
//   ① 身份条   ：`角色名文本` + `职业文本` + `等级文本`（"Lv.N"）+ `经验文本` + `经验滑条`（0→1）
//   ② 五维区   ：小标题 + `剩余点数文本` + **5 行**（行内：名 / 值 / 加按钮）
//   ③ 延伸属性区：**14 行只读行**（从 `属性行模板` 克隆；行内：名 / 值）
//   ④ 反馈**不走本页的 UI 文本**（用户 2026-09-17 拍板：删掉「提示文本」，改日志提示）：
//      无点数 / 战斗中 / 加点失败 → `日志事件(日志类型.警告, …)` 打到左下角日志面板；
//      加点成功 → `面板操作.加点` 自己发的那条日志（"{类型} +1"）就是成功反馈（见 点击加点）。
//      口径与 `家具行.材料不足反馈`（失败音 + 警告日志）一致。
//
// —— 下标 ↔ 属性（照 `玩家档案.cs` 里 `属性类型` 的**声明顺序**排，改枚举顺序必须同时改场景节点名）——
//   `public enum 属性类型 { 体质, 力量, 智慧, 敏捷, 意志 }` →
//     下标 0 = 体质 · 1 = 力量 · 2 = 智慧 · 3 = 敏捷 · 4 = 意志
//   Inspector 的 `五维行[0..4]`、场景节点名 `五维行1..5`、`[+]` 的点击回调 全部按这个下标。
//
// —— 点数来源（口径，写在这里免得下次又猜）——
//   唯一来源 = **升级**：`成长管理器.获得经验` 里 `玩家.自由属性点 += 3`（每级 +3）。
//   开局的 10 点是**另一套**（`角色创建面板` 的本地预算 `剩余自由点`，从不进 `玩家档案.自由属性点` 这个字段）。
//   **没有单属性上限** —— `成长管理器.加点` 只校验"自由点够不够"。
//   `[+]` 是**即时生效、不可撤销**：不建 `[−]`、不建洗点、不加"立刻落盘"（档案本来随档走）。
//
// —— 为什么战斗中不允许加点 ——
//   `战斗单位` 是进场时按五维**投影快照**出来的（`战斗单位.从玩家投影`）：战斗里再改五维不会回头改
//   已经进场的那一份。所以本页在战斗中把 `[+]` 置灰，点了也只得到一条警告日志。
//   判据用 `存档门禁.正在战斗` —— 与存档/读档同一份真相，不自己看 `BattleService`。
public sealed class 属性子面板 : MonoBehaviour
{
    // 五维的一行（数组长度 5，**下标 = `属性类型` 枚举下标**）。
    // 为什么是 `[Serializable]` 数据类而不是 MonoBehaviour：这 5 行是场景里的**静态节点**，
    //   不值得各挂一个组件；模板克隆出来的延伸行也复用同一个视图结构（延伸行只读 → `加按钮` 为 null）。
    [Serializable]
    public class 属性行视图
    {
        public TMP_Text 名;      // 行名（五维 = 枚举成员名；延伸 = "生命"/"速度"…）
        public TMP_Text 值;      // 行值
        public Button 加按钮;    // `[+]`：只有五维行有（延伸行只读，模板里带了也会被隐藏）
    }

    // —— 身份条（用户 2026-09-17：角色的名字 / 职业 / 等级 / 经验 也放进属性页）——
    [SerializeField] private TMP_Text 角色名文本;   // `玩家档案.角色名`
    [SerializeField] private TMP_Text 职业文本;     // 职业显示名（`DataService.职业[标识].名称`；取不到退回标识，未选职业留空）
    [SerializeField] private TMP_Text 等级文本;     // "Lv.N"（照旧角色面板那条口径）
    [SerializeField] private TMP_Text 经验文本;     // "当前经验 / 升级所需"（与本页其它"当前 / 上限"同款）
    [SerializeField] private Slider 经验滑条;       // 经验进度 **0→1**：min/max 在预制体里设 0/1，代码只写 `.value`

    [SerializeField] private 属性行视图[] 五维行 = new 属性行视图[5];
    [SerializeField] private TMP_Text 剩余点数文本;    // 显示 `玩家档案.自由属性点`
    [SerializeField] private GameObject 属性行模板;     // 延伸行的**模板行**（场景里默认 SetActive(false)；本页只克隆它）
    [SerializeField] private RectTransform 延伸行容器;  // 延伸行的父节点（14 行固定顺序铺在这里）

    // 延伸属性区：**固定 14 行**，顺序就是定稿里的顺序，行名即显示名。
    // 取值一律读 `玩家档案` 上**已经存在**的字段/计算属性 —— 本页不自己算任何数值（口径不许漂）。
    private static readonly (string 名, Func<玩家档案, string> 取值)[] 延伸行表 =
    {
        ("生命", 玩家 => $"{玩家.生命} / {玩家.最大生命}"),          // 当前 / 上限
        ("行动点", 玩家 => $"{玩家.行动点} / {玩家.最大行动点}"),     // 当前 / 上限
        ("速度", 玩家 => $"{玩家.速度}"),                            // 生存管理器：敏捷 / 配件 / 伤病
        ("近战伤害", 玩家 => $"{玩家.近战伤害}"),                     // 装备管理器
        ("枪械伤害", 玩家 => $"{玩家.枪械伤害}"),
        ("总防御", 玩家 => $"{玩家.总防御}"),
        ("暴击概率", 玩家 => 百分(玩家.暴击概率)),                    // 0~1 的比例 → ×100 带 %
        ("闪避概率", 玩家 => 百分(玩家.闪避概率)),                    // 同上
        ("命中率", 玩家 => 百分(命中率(玩家))),                        // `玩家档案` 上没有这一项（见 命中率）
        ("抗性", 玩家 => $"{玩家.抗性百分比}%"),                       // 本身已是百分数（装备管理器 已封顶 50）→ **不 ×100**
        ("潜行", 玩家 => $"{玩家.潜行值}"),
        ("感知", 玩家 => $"{玩家.感知}"),
        ("恐惧抗性", 玩家 => 百分(玩家.恐惧抗性)),                     // 0~1 的比例
        ("负重", 玩家 => $"{玩家.负重占用} / {玩家.负重上限}"),         // 占用 / 上限
    };

    // 行内子节点名（节点名兜底与模板克隆取件共用；`名`/`值` 沿用旧角色面板那一套既有约定）
    private const string 子名 = "名";
    private const string 子值 = "值";
    private static readonly string[] 加按钮节点名 = { "加", "加按钮" };   // 场景里两种叫法都常见，都认

    // 运行时克隆出来的延伸行（**不序列化**：它们不属于资产，随本组件实例生死）
    private readonly List<属性行视图> 延伸行 = new List<属性行视图>();

    // —— 事件订阅（属性/经验/生命/精力 任一变了都整页重算）——
    private EventBus 事件总线;
    private bool 已订阅;
    private Action<属性变化事件> 属性回调;
    private Action<经验变化事件> 经验回调;
    private Action<生命变化事件> 生命回调;
    private Action<精力变化事件> 精力回调;

    // 档案：UI 层读 `PlayerService.档案` 是本项目的既有模式（不新增服务、不缓存副本）
    private static 玩家档案 档案
        => ServiceRegistry.已注册<PlayerService>() ? ServiceRegistry.Get<PlayerService>()?.档案 : null;

    // ================= 生命周期 =================

    void Awake()
    {
        备数组(ref 五维行);
        自找();          // Inspector → 按节点名兜底（只找，不建；全程不崩）
        接加按钮();
        建延伸行();
        刷新();
        报缺引用();      // 找完再点名：报的是"引用位与节点名两边都没找到"的那些位
    }

    // 切页时壳把这一页 `SetActive(true)` → 这里自己刷一次（"切过去看到旧数据"因此不可能发生）。
    // 订阅也放在这里：只在**亮着**的时候听事件，关掉/切走时不空转。
    void OnEnable()
    {
        订阅();
        刷新();
    }

    void OnDisable() => 退订();

    // 组件销毁也要退订（`OnDisable` 通常已来过一次；这里兜"被直接 Destroy / 场景卸载"那条路，照 区域面板 的写法）
    void OnDestroy() => 退订();

    // ================= 刷新（幂等：全量重算） =================

    public void 刷新()
    {
        var 玩家 = 档案;
        if (玩家 == null) return;   // 未开局 / 坏档：没有可显示的东西（加点那条路也一并判空）
        刷身份(玩家);
        刷五维(玩家);
        面板基类.设文本(剩余点数文本, $"{玩家.自由属性点}");
        刷延伸(玩家);
    }

    // 身份条：名字 / 职业 / 等级 / 经验。
    // 等级与经验只在**升级/得经验**时变，所以订阅里的 `经验变化事件` 就是这一块的刷新信号
    //   （换角色/读档由壳打开这一页 → `OnEnable` 兜住）。
    private void 刷身份(玩家档案 玩家)
    {
        面板基类.设文本(角色名文本, 玩家.角色名);
        面板基类.设文本(职业文本, 职业显示名(玩家));
        面板基类.设文本(等级文本, $"Lv.{玩家.等级}");   // "Lv.N"：照旧角色面板那条口径
        // 升级所需经验 = 等级 × 25（`成长管理器.升级所需经验`，`玩家档案` 上门面转发）。
        // `Max(1, …)` 只为除零兜底（正常值 ≥ 25；读档清理过，等级 ≥ 1）。
        int 需要 = Mathf.Max(1, 玩家.升级所需经验);
        面板基类.设文本(经验文本, $"{玩家.经验} / {需要}");
        // 滑条走"比值 0→1"这条既有口径（`净水器面板` / `书籍面板` 同款）：**只写 value**；
        //   min/max（0/1）与"不可拖动"都在预制体里配 —— 本组件不碰外观，也不改场景调好的交互设置。
        if (经验滑条 != null) 经验滑条.value = Mathf.Clamp01(玩家.经验 / (float)需要);
    }

    // 职业的**显示名**：优先数据表里的 `职业数据.名称`（`DataService.职业`：标识 → 定义），
    //   取不到（数据缺失/旧档里的标识已被改掉）就退回**标识本身** —— 宁可显示"消防员"这种标识，
    //   也不要静默空白让人以为职业丢了。还没选职业（`玩家.职业` 空，未开局）就留空。
    // 口径照旧角色面板的 `身份行()`（那边是"幸存者 · 职业"，本页只取职业那一段）。
    private static string 职业显示名(玩家档案 玩家)
    {
        if (string.IsNullOrEmpty(玩家.职业)) return "";
        var 数据 = ServiceRegistry.已注册<DataService>() ? ServiceRegistry.Get<DataService>() : null;
        return 数据 != null && 数据.职业 != null && 数据.职业.TryGetValue(玩家.职业, out var 定义)
               && 定义 != null && !string.IsNullOrEmpty(定义.名称)
            ? 定义.名称
            : 玩家.职业;
    }

    // 五维：行名 = `属性类型` 的成员名（枚举成员名就是中文显示名 —— 改枚举名即改行名，不会各写一份漂掉）；
    //       行值 = `玩家档案` 上的**纯值**。职业分布 / 自由加点 / 天赋都已经落在同一个字段里，
    //       所以**不显示**"职业 + 自由"那种合成式（合成式是开局创建页那一套，本页只显示字段本体）。
    private void 刷五维(玩家档案 玩家)
    {
        bool 可点 = 可加点(玩家);
        for (int i = 0; i < 五维行.Length; i++)
        {
            var 行 = 五维行[i];
            if (行 == null) continue;
            var 类型 = (属性类型)i;   // 下标 = 枚举下标（对照表见文件头）
            面板基类.设文本(行.名, 类型.ToString());
            面板基类.设文本(行.值, $"{五维值(玩家, 类型)}");
            if (行.加按钮 != null) 行.加按钮.interactable = 可点;
        }
    }

    // 延伸属性：行数固定 14（`延伸行表`），行身是从 `属性行模板` 克隆出来的（见 建延伸行）
    private void 刷延伸(玩家档案 玩家)
    {
        for (int i = 0; i < 延伸行.Count && i < 延伸行表.Length; i++)
        {
            var 行 = 延伸行[i];
            if (行 == null) continue;
            var (行名, 取值) = 延伸行表[i];
            面板基类.设文本(行.名, 行名);
            面板基类.设文本(行.值, 取值(玩家));
        }
    }

    // `[+]` 可点条件：档案存在（调用点已判）· `自由属性点 > 0` · 非战斗中
    private static bool 可加点(玩家档案 玩家) => 玩家.自由属性点 > 0 && !存档门禁.正在战斗;

    // ================= `[+]` 加点（即时生效、不可撤销） =================

    private void 点击加点(属性类型 类型)
    {
        var 玩家 = 档案;
        if (玩家 == null) return;

        // ① 战斗中：进场时五维已经**投影快照**进 `战斗单位`，这里加了也不生效 → 拦下并说明为什么
        if (存档门禁.正在战斗)
        {
            音效管理器.实例?.播放失败();
            警告("战斗中不能加点（技能/属性在进场时已锁定）");
            return;
        }

        // ② 没有自由点：唯一来源是升级（每级 +3，见文件头）
        if (玩家.自由属性点 <= 0)
        {
            音效管理器.实例?.播放失败();
            警告("没有可分配的属性点（升级每级 +3）");
            return;
        }

        // ③ 真正加点：`面板操作.加点` 负责"改档案 + 发 属性变化事件 + 发日志"，本页只管反馈
        bool 成功 = 面板操作.加点(玩家, 类型);
        if (!成功)
        {
            音效管理器.实例?.播放失败();
            警告("加点失败");
        }
        // 成功那条**不重复发**：`面板操作.加点` 已经发了 `日志事件(获得, "{类型} +1")`（面板操作.cs:28），
        //   本页再补一条"已加点"只会让同一次点击在日志里出现两行。
        // 成功音同理 = `注册按钮` 挂在这颗按钮上的按钮成功音效（本项目的既有口径），这里不手动再调一次
        //   —— 手动调会响两遍（失败那条已经用"本帧失败"把成功音压掉了）。
        刷新();   // 兜底：事件链万一断了，界面也照当前档案重算一次
    }

    // 接 `[+]` 的点击（只在 Awake 接一次）。
    // 先 `RemoveAllListeners`：免得场景/预制体上手接的旧监听和脚本接线叠在一起（同一颗按钮被接两次会加两次点）。
    private void 接加按钮()
    {
        for (int i = 0; i < 五维行.Length; i++)
        {
            var 钮 = 五维行[i]?.加按钮;
            if (钮 == null) continue;
            int 序 = i;   // 闭包捕获：循环变量必须另存一份，否则五行全会加到最后一个属性上
            钮.onClick.RemoveAllListeners();
            钮.onClick.AddListener(() => 点击加点((属性类型)序));
            音效管理器.实例?.注册按钮(钮);   // 幂等：按钮成功音 + 悬停反馈
        }
    }

    // ================= 延伸行：克隆模板（行数固定，只增不减） =================

    // 为什么用 `创建模板<Transform>` 而不是行组件：`属性行视图` 是 `[Serializable]` 数据类、不是组件
    //   （5 行五维没必要各挂一个 MonoBehaviour），所以拿克隆体的 Transform 再按节点名取件。
    // 为什么"只增不减"：行数固定 14，已经够了就不再克隆（刷新不会重建，避免每次刷都 Instantiate/Destroy）。
    private void 建延伸行()
    {
        if (延伸行容器 == null || 属性行模板 == null) return;   // 缺哪个由 报缺引用() 点名
        while (延伸行.Count < 延伸行表.Length)
        {
            var 克隆 = 面板基类.创建模板<Transform>(延伸行容器, 属性行模板);
            if (克隆 == null) return;   // 容器/模板 中途没了 → 停手（别在这里转圈）
            var 行 = new 属性行视图
            {
                名 = 子文本(克隆, 子名),
                值 = 子文本(克隆, 子值),
                加按钮 = 子按钮(克隆),
            };
            // 延伸属性是**只读**行：模板里若带了 `[+]` 就整颗隐藏（状态表达只用 SetActive，不动任何外观）
            if (行.加按钮 != null) 行.加按钮.gameObject.SetActive(false);
            延伸行.Add(行);
        }
    }

    // 反馈出口 = 日志（左下角日志面板）。被拦下的操作一律 `警告`：与 `家具行.材料不足反馈`、
    //   `面板操作.换装` 那些"点了但不给做"的提示同一个口径 —— 玩家在同一个地方看到"为什么没成"。
    private static void 警告(string 文本)
        => ServiceRegistry.Get<EventBus>()?.发布(new 日志事件(日志类型.警告, 文本));

    // ================= 事件订阅 / 退订 =================

    private void 订阅()
    {
        if (已订阅) return;
        事件总线 = ServiceRegistry.Get<EventBus>();
        if (事件总线 == null) return;
        // 四条信号都表示"五维 / 上限 / 派生值可能变了" —— 本页整页重算，不区分是哪一条打来的
        属性回调 = _ => 刷新();   // 加点、换装、读书、天赋
        经验回调 = _ => 刷新();   // 得经验 / 升级 → 身份条的名字、等级、经验文本、经验滑条
        生命回调 = _ => 刷新();   // "当前 / 上限"（上限吃体质）
        精力回调 = _ => 刷新();   // 行动点"当前 / 上限"（上限吃意志）
        事件总线.订阅(属性回调);
        事件总线.订阅(经验回调);
        事件总线.订阅(生命回调);
        事件总线.订阅(精力回调);
        已订阅 = true;
    }

    private void 退订()
    {
        if (!已订阅) return;
        已订阅 = false;
        if (事件总线 == null) return;
        事件总线.取消订阅(属性回调);
        事件总线.取消订阅(经验回调);
        事件总线.取消订阅(生命回调);
        事件总线.取消订阅(精力回调);
        属性回调 = null; 经验回调 = null; 生命回调 = null; 精力回调 = null;
    }

    // ================= 引用兜底：按节点名找回来（只找，不建） =================

    private void 自找()
    {
        if (角色名文本 == null) 角色名文本 = 子文本(transform, "角色名");
        if (职业文本 == null) 职业文本 = 子文本(transform, "职业");
        if (等级文本 == null) 等级文本 = 子文本(transform, "等级");
        if (经验文本 == null) 经验文本 = 子文本(transform, "经验");     // 与下面的「经验滑条」节点名不同，不会互撞
        if (经验滑条 == null) 经验滑条 = 找节点(transform, "经验滑条")?.GetComponent<Slider>();
        if (剩余点数文本 == null) 剩余点数文本 = 子文本(transform, "剩余点数");
        if (属性行模板 == null) 属性行模板 = 找节点(transform, "属性行模板")?.gameObject;
        if (延伸行容器 == null) 延伸行容器 = 子矩形(transform, "延伸行");

        // 五维行：按节点名 `五维行1..5` 找（本组件下面**任意深度** —— 行摆在区节点里面一层也能找到）
        for (int i = 0; i < 五维行.Length; i++)
        {
            if (!未接线(五维行[i])) continue;
            var 节点 = 找节点(transform, $"五维行{i + 1}");
            if (节点 != null) 五维行[i] = 从节点建行(节点);
        }
    }

    // 这个五维引用位算"没接线"吗？
    // 为什么不能只判 null：`五维行` 是 `[Serializable]` 类的数组，Unity 给**每个元素**都实例化一个空对象
    //   —— 于是"Inspector 里一个都没拖"在运行时不是 null，而是三个引用全空。两种都算没接。
    private static bool 未接线(属性行视图 行)
        => 行 == null || (行.名 == null && 行.值 == null && 行.加按钮 == null);

    // 缺引用**要出声**：Inspector 少接一个位 → 表现只是"某一行永远空着 / 点了没反应"，一条日志都没有。
    // 打**一条** LogError 把缺的名字列全（不崩、不中断别的面板）。
    private void 报缺引用()
    {
        var 缺 = new List<string>();
        if (角色名文本 == null) 缺.Add("角色名文本（节点名「角色名」）");
        if (职业文本 == null) 缺.Add("职业文本（节点名「职业」）");
        if (等级文本 == null) 缺.Add("等级文本（节点名「等级」）");
        if (经验文本 == null) 缺.Add("经验文本（节点名「经验」）");
        if (经验滑条 == null) 缺.Add("经验滑条（节点名「经验滑条」）");
        for (int i = 0; i < 五维行.Length; i++)
        {
            if (未接线(五维行[i])) { 缺.Add($"五维行[{i}]（节点名「五维行{i + 1}」）"); continue; }
            if (五维行[i].名 == null) 缺.Add($"五维行[{i}].名（行内节点名「名」）");
            if (五维行[i].值 == null) 缺.Add($"五维行[{i}].值（行内节点名「值」）");
            if (五维行[i].加按钮 == null) 缺.Add($"五维行[{i}].加按钮（行内节点名「加」）");
        }
        if (剩余点数文本 == null) 缺.Add("剩余点数文本（节点名「剩余点数」）");
        if (属性行模板 == null) 缺.Add("属性行模板（节点名「属性行模板」）");
        if (延伸行容器 == null) 缺.Add("延伸行容器（节点名「延伸行」）");
        if (缺.Count == 0) return;
        Debug.LogError("[属性子面板] 缺引用：" + string.Join("、", 缺) +
                       "。请在场景里把这些节点拖到本组件的 Inspector 引用位上" +
                       "（或让节点名与括号里的一致、挂在本组件下面）。" +
                       "外观在场景 / 预制体里调：本组件只克隆「属性行模板」做延伸行，不建别的节点。");
    }

    // ================= 小工具 =================

    // 按名找节点：本组件下面**任意深度**的第一个同名节点。
    // 为什么不能只用 `Transform.Find`：它只找**直接子节点**，而 `五维行1..5` 在区节点里面一层。
    private static Transform 找节点(Transform 根, string 名)
    {
        if (根 == null) return null;
        for (int i = 0; i < 根.childCount; i++)
        {
            var 子 = 根.GetChild(i);
            if (子.name == 名) return 子;
            var 深 = 找节点(子, 名);
            if (深 != null) return 深;
        }
        return null;
    }

    private static TMP_Text 子文本(Transform 父, string 名) => 找节点(父, 名)?.GetComponent<TMP_Text>();
    private static RectTransform 子矩形(Transform 父, string 名) => 找节点(父, 名)?.GetComponent<RectTransform>();

    // `[+]` 的节点名：`加` / `加按钮` 都认
    private static Button 子按钮(Transform 父)
    {
        foreach (var 名 in 加按钮节点名)
        {
            var 钮 = 找节点(父, 名)?.GetComponent<Button>();
            if (钮 != null) return 钮;
        }
        return null;
    }

    // 按节点名兜底时：现场从命名子节点组出"一行"
    private static 属性行视图 从节点建行(Transform 节点)
        => new 属性行视图
        {
            名 = 子文本(节点, 子名),
            值 = 子文本(节点, 子值),
            加按钮 = 子按钮(节点),
        };

    // 五维的纯值：逐条点名 `玩家档案` 上的字段（不走"按名字查属性"那种字符串入口 —— 字段改名要编译期就炸）
    private static int 五维值(玩家档案 玩家, 属性类型 类型)
    {
        switch (类型)
        {
            case 属性类型.体质: return 玩家.体质;
            case 属性类型.力量: return 玩家.力量;
            case 属性类型.智慧: return 玩家.智慧;
            case 属性类型.敏捷: return 玩家.敏捷;
            case 属性类型.意志: return 玩家.意志;
            default: return 0;
        }
    }

    // 比例 → 百分数文本（0.235 → "24%"）：四舍五入到整数，口径照旧角色面板
    private static string 百分(float 比例) => $"{Mathf.RoundToInt(比例 * 100f)}%";

    // 命中率：`玩家档案` 上**没有**这一项 —— 它只活在战斗单位上（0.95 + 命中副属性，上限 0.99）。
    // 这里取战斗投影里那一份**权威值**（`从玩家投影` 是 public static 工厂），**不照抄那条公式**：
    //   副本一定会漂。投影一次 = 一次对象构造，本页每次刷新只调一次。
    private static float 命中率(玩家档案 玩家) => 战斗单位.从玩家投影(玩家).命中率;

    // 数组可能是 null / 短数组（老场景存下来的）→ 先补到 5 个，否则按 5 个下标遍历就会越界。
    // ⚠ 已有的引用要**带过来**：直接 `数组 = new 属性行视图[5]` 会把用户在 Inspector 拖好的行全丢掉。
    private static void 备数组(ref 属性行视图[] 数组)
    {
        if (数组 != null && 数组.Length == 5) return;
        var 旧 = 数组;
        var 新 = new 属性行视图[5];
        if (旧 != null)
            for (int i = 0; i < 旧.Length && i < 新.Length; i++) 新[i] = 旧[i];
        数组 = 新;
    }

using System;
using System.Collections.Generic;
using System.Text;
using TMPro;
using UnityEngine;

// 技能子面板 —— 角色面板「技能」页的内容（三页里的第二页）。
//
// 分工（硬边界，照 `属性子面板` / `知识子面板` 那一批定的口径）：
//   · **显隐不由本组件管**：壳（`角色面板`）只做 `SetActive` → 本类**不继承 `面板基类`**，不参与"显示面板/回退"协议。
//   · 自刷入口：`Awake()` + `OnEnable()` 各 `刷新()` 一次（切页 = 壳把这一页 `SetActive(true)` → `OnEnable` 触发）。
//   · **不订阅任何事件**（用户定稿）：`技能服务` 只发 `日志事件`，换槽没有专门信号 →
//     本页靠 `OnEnable` 全量重算 + 每次写操作后**全量重算**，不做"事件驱动的增量刷新"。
//   · **外观 100% 归场景 / 预制体**：本文件不写配色、字号、尺寸常量；状态表达只用 `SetActive`
//     （待装高亮 = 一个预置节点亮了而已）。布局尺寸一律**从模板 RectTransform 量**（见 量行高），不写死数字。
//
// 版式（本批用户定稿）：
//   · 上 = 6 个技能槽（横排，预搭或按 `技能格模板` 克隆 —— 这一段**一个字都没动**）；
//   · 下 = 已学技能列表：行是**纯索引** —— 只有「名称 · 按钮 · 置灰」三样（见 `技能行`）。
//     原来的 `类别 / 主动与否 / 熟练 / 已装` 四个文本位与 `待装高亮` 已删；
//   · 说明区 = **只有一个 `TMP_Text`**（用户定稿，照 `知识子面板.详情文本` 那一批的口径）：
//     原来拆成 说明文本 / 说明目标 / 说明距离 / 说明时机 / 说明消耗 **五个**引用位 ——
//     拆开时**少接一个就少一行**，而"少一行"从画面上看不出来（还得靠 `报缺引用` 才发现）；
//     现在按行拼进一个字符串、块间空行（见 `说明内容`）。行里删掉的「熟练 / 已装」也搬进了这一段，
//     信息一条不丢。
//
// ★ 槽索引 ↔ 数据下标 ↔ 界面格号（**三处必须同一套**，整个页面按这一条写）：
//   槽索引 i == `玩家档案.战斗技能槽` 的下标 i == 界面第 i+1 格（格上显示的序号 = i+1）。
//   界面格数恒为 `成长管理器.技能槽数`（6）；但 `战斗技能槽` **这张表可能比它短**（新档就是空表，
//   `成长管理器.填入技能槽` 学会技能时才按需增长、用 null 填空）——**短表 = 后面几格都算空槽**，
//   页面对此天然正确（`槽标识` 越界返回 null）。空槽用**空串/null** 表示（见 `成长管理器.卸下槽` 的注释：
//   写空串而不是 RemoveAt —— 长度一变，索引↔槽位的对应就全错位）。所以：
//   · 页面**按 `成长管理器.技能槽数` 遍历**，代码里没有写死的 6；
//   · 若场景里预搭了这几格（节点名 `技能格1`..`技能格N`），数组下标必须**等于槽位下标**，
//     长度必须等于 `成长管理器.技能槽数`（多了轮不到、少了会按模板补克隆）。
//
// 布局（定稿）：**上面 = 技能槽横排 / 下面 = 已学技能列表**，两个都走**专用模板 + `面板基类.创建模板<T>`**
//   （`配方行` 是先例）；**不用** `面板基类.创建行`（那是"运行时造按钮行"的工具，槽格/列表行的外观得在场景里调）。
//
// 交互（点选式，用户钦定；状态 = `待装技能标识` + `待装来源槽`）：
//   点列表某条 → 设待装（只重绘，**不写档案**）；再点它一次 = 取消。
//   点空槽（手里有待装）→ `成长管理器.切换入槽(i, 待装)`；点已装槽（手里有待装）→ 同样 `切换入槽`
//     （**同技能已在别槽会自动对调**，原槽技能因此退回列表）；点已装槽（手里无待装）→ `成长管理器.卸下槽(i)`。
//   点同一个槽（`待装来源槽 == i`）→ 取消待装（不调领域方法）。点空槽但无待装 → 弱提示（日志，不播失败音）。
//   **战斗中禁止换槽**：`存档门禁.正在战斗` → 失败音 + 警告日志 + return（不调任何写方法）。
//
// 为什么战斗中禁止（理由照 `属性子面板` 那条，写在这里免得下次又猜）：
//   `战斗单位.从玩家投影` 是**进场一次性投影** —— 槽里有什么技能在进场那一刻就分流完了（主动进 `已学技能`、
//   被动进 `被动技能`），被动增幅也是那一刻一次性叠加。战斗中再改 `战斗技能槽`：已经进场的那一份不回头，
//   改完只有"下次进场"才生效 → 界面会显示一个当场不成立的技能栏，比不让改更坏。
//
// 反馈口径（照属性页那一批）：**不建"提示文本"节点**，失败/提示一律
//   `EventBus.发布(new 日志事件(日志类型.警告, …))` + `音效管理器.实例?.播放失败()`。
//   成功**不补日志**：`切换入槽` / `卸下槽` 本身不发日志，界面上格与列表已经全量重算（装没装上看得见），
//   本页再补一条只会和别处重复 —— 口径与 `属性子面板.点击加点`（成功不重复发）一致。
public sealed class 技能子面板 : MonoBehaviour
{
    // 列表每一行的视图（模板 → `技能行` 组件；`标识` 只在"池子复用"时用来对账，运行时不改）。
    [Serializable]
    public class 技能行视图
    {
        public string 标识;
        public 技能行 行;
    }

    // 每一个槽格的视图（模板 → `技能格` 组件）。`预搭` = 场景里已经摆好的格子（点选/高亮状态都在它身上）。
    private sealed class 槽格视图
    {
        public 技能格 格;
        public bool 预搭;
    }

    // —— Inspector 引用位（缺了就按节点名兜底，再缺就一条 LogError 点名，不崩）——
    [SerializeField] private RectTransform 槽容器;     // 上面 6 个技能槽的容器
    [SerializeField] private GameObject 技能格模板;    // 槽格模板（挂 `技能格`；场景里默认 SetActive(false)）
    [SerializeField] private RectTransform 列表容器;   // 下面已学技能列表的容器（行克隆到这里）
    [SerializeField] private GameObject 技能行模板;    // 列表行模板（挂 `技能行`；场景里默认 SetActive(false)）
    // 技能说明区：**只有一个 `TMP_Text`**（本批用户定稿 —— 原来拆成 名称/目标/距离/时机/消耗 五个引用位，
    //   少接一个就少一行，而"少一行"从画面上看不出来）。没选中/没待装时整段 `SetActive(false)`；
    //   没搭这个节点的档也不报错（`报缺引用` 只点"缺了就没法工作"的那几处）。
    [SerializeField] private TMP_Text 说明文本;

    // 节点名兜底用的名字（Inspector 接上引用位就与名字无关）。
    // 一律用**精确名**："技能格模板" 不会误配到 "技能行模板"（用 Contains 式匹配就会被抢走）。
    private const string 名槽容器 = "槽容器";
    private const string 名技能格模板 = "技能格模板";
    private const string 名列表容器 = "列表容器";
    private const string 名技能行模板 = "技能行模板";
    private const string 名说明文本 = "说明文本";
    // 说明区的旧名 / 别名兜底：上一版这一块是**五个**节点（`说明文本` / `说明目标` / `说明距离` /
    //   `说明时机` / `说明消耗`）—— 现在只认一个节点，所以除了正名再认两个常见叫法，
    //   用户把新版单独一个文本节点起成哪个都能接上（引用位优先，都不接才走名字）。
    private const string 名说明文本别名 = "技能说明";
    private const string 名说明文本别名2 = "说明";
    private const string 名空列表 = "暂无技能";        // 列表为空时的兜底节点名（内容不随档变，值得常驻）
    private const string 空列表文本 = "还没有学到任何技能。";

    // 预搭槽格的节点名前缀：`技能格1`..`技能格N`（N = `成长管理器.技能槽数`；下标 0 用 `技能格1`）。
    // 与 `角色面板` 的 `五维行1..5` 同款约定；用户没预搭就直接用 `技能格模板` 克隆。
    private const string 槽格名前缀 = "技能格";

    // 找到同名节点、但节点上没挂 `技能格` 的槽位（槽索引）。这是**静默失败**的经典形态（那一格永远空白），
    //   所以收集起来在 `报缺引用` 里点一次名（同一次刷新只报一次，不每帧刷屏）。
    private readonly List<int> 缺组件槽 = new List<int>();

    // —— 运行时状态（不序列化：不属于资产，随本组件实例生死）——
    private string 待装技能标识;      // null = 手里没有待装技能
    private int 待装来源槽 = -1;      // -1 = 来自列表（无来源槽）；>=0 = 这次待装是从该槽"拿起"的
    private int 选中序号 = -1;        // `已学技能` 里的下标（= 说明区当前显示哪一条）；-1 = 没选中

    private readonly List<槽格视图> 槽格池 = new List<槽格视图>();     // 只增不减（刷新只重新绑定 + 切显隐）
    private readonly List<技能行视图> 行池 = new List<技能行视图>();   // 同上
    private TMP_Text 空列表节点;                                       // 常驻兜底文本（随内容建的会被 `清空()` 删掉）
    private bool 已报槽数不符;

    // 档案：UI 层读 `PlayerService.档案` 是本项目的既有模式（不新增服务、不缓存副本）
    private static 玩家档案 档案
        => ServiceRegistry.已注册<PlayerService>() ? ServiceRegistry.Get<PlayerService>()?.档案 : null;

    // ================= 生命周期 =================

    void Awake()
    {
        自找();          // Inspector → 节点名兜底（只找，不建）
        备槽格();        // 先把 6 个槽位（预搭的 + 缺的克隆）备齐，`报缺引用` 之后才有话可说
        报缺引用();      // 找完再点名：报的是"引用位与节点名两边都没找到"的那些位
        刷新();          // 建行 + 刷一遍（`OnEnable` 紧接着还会刷一次，这里只为"先有行、再报错"的顺序）
    }

    // 切页 / 重开面板：**清掉待装**（换槽那件事离开了这一页就不该还揣在手里）→ 全量重算。
    // 为什么不保留待装：待装是"正在把某条往某个槽里放"的**中间态**，切走再回来时槽位可能已经被别处改过
    //   （快速测试面板直接写 `战斗技能槽`），保留它只会在回来时误导玩家。
    void OnEnable()
    {
        待装技能标识 = null;
        待装来源槽 = -1;
        刷新();
    }

    // ================= 刷新（幂等：全量重算） =================

    // 全量重算 = 槽 + 列表 + 说明 + 待装高亮。
    // 幂等：所有值都是从 `玩家档案` / 数据表现算的，不做增量、**不缓存"哪格装了什么"的差异**
    //   （快速测试面板会绕过 `切换入槽` 直接写槽，缓存差异必然对不上）。
    public void 刷新()
    {
        var 玩家 = 档案;
        if (玩家 == null) return;   // 未开局 / 坏档：没有可显示的东西（清空会显得像"没数据"，干脆不动）

        校验槽数(玩家);
        刷槽(玩家);
        建列表(玩家);
        刷选中态();
        刷说明(玩家);
    }

    // 槽数口径核对：只有**比 `成长管理器.技能槽数` 长**才算异常（多出来的槽位永远轮不到，却会被存档整表写下去）。
    //   ⚠ **短表/空表不是异常，别再喊了**（本批修的假警报）：`玩家档案.战斗技能槽` 初始就是**空表**，
    //     只有 `成长管理器.填入技能槽`（学会技能时）才**按需增长**（`while (Count <= i) Add(null)`），
    //     `补齐技能槽()` 又只在 `切换入槽` / `卸下槽` 里调 —— 所以"新档 0 格""刚学会一个技能 = 1 格"
    //     都是**正常的中间形态**，而不是谁写坏了。页面对短表天然正确：`槽标识` 越界返回 null = 空槽，
    //     下面那圈照样按 `技能槽数` 画满 6 格。原来那条 `Count != 技能槽数` 的判据于是每次打开技能页
    //     （玩家还没换过槽时）都刷一条 LogError —— 真出问题时反而被这种噪音埋掉。
    //   不符只报**一条**（不裁、不补数据）—— 本页照数据现有内容显示，把差异喊出来让人去看是谁写的。
    private void 校验槽数(玩家档案 玩家)
    {
        if (已报槽数不符) return;
        var 槽 = 玩家.战斗技能槽;
        if (槽 == null || 槽.Count <= 成长管理器.技能槽数) return;
        已报槽数不符 = true;
        Debug.LogError($"[技能子面板] `玩家档案.战斗技能槽` 有 {槽.Count} 格，比 `成长管理器.技能槽数`" +
                       $"（{成长管理器.技能槽数}）**长** —— 多出来的槽位界面永远显示不到（本页只遍历前 {成长管理器.技能槽数} 格），" +
                       "却会被 `存档模型` 整表写下去。本页照数据现有内容显示，不做增删；请检查是谁写长了这张表。");
    }

    // ================= 上：6 个技能槽 =================

    // 备齐槽位：先按节点名收**场景预搭**的格子（下标必须等于槽位下标），不够的按模板克隆补上。
    // 为什么允许预搭：`知识子面板` 的 `逐级表` 就是一格一个克隆；但技能槽只有 6 格、且用户很可能想
    //   在场景里直接摆好这 6 格的外观（间距/对齐在布局组上），所以两条路都认：预搭优先、模板兜底。
    private void 备槽格()
    {
        while (槽格池.Count < 成长管理器.技能槽数)
        {
            int 槽索引 = 槽格池.Count;
            var 预搭 = 找节点(transform, 槽格名前缀 + (槽索引 + 1));
            if (预搭 != null)
            {
                var 组件 = 预搭.GetComponent<技能格>();
                if (组件 == null && !缺组件槽.Contains(槽索引)) 缺组件槽.Add(槽索引);
                槽格池.Add(new 槽格视图 { 格 = 组件, 预搭 = true });
                continue;
            }
            var 格 = 面板基类.创建模板<技能格>(槽容器, 技能格模板);
            if (格 == null) return;   // 容器/模板 中途没了 → 停手（`报缺引用` 已点名，别在这里转圈）
            量行高(格.gameObject, 技能格模板);
            槽格池.Add(new 槽格视图 { 格 = 格, 预搭 = false });
        }
    }

    // 顺序对账：各槽格的兄弟序号 = 槽索引（预搭的或池化复用的都靠它归位）。
    private void 排槽格(int 槽索引)
    {
        var 视图 = 槽索引 < 槽格池.Count ? 槽格池[槽索引] : null;
        var 格 = 视图?.格;
        if (格 == null) return;
        if (!视图.预搭) 格.gameObject.transform.SetSiblingIndex(槽索引);
        格.gameObject.SetActive(true);
    }

    private void 刷槽(玩家档案 玩家)
    {
        // 只有"容器 + 模板"和"预搭槽格"**两条路都断了**才停手；`报缺引用` 已经点过名。
        //   （槽容器只在需要克隆时用得上：用户预搭满 6 格时可以完全不接它。）
        if (槽格池.Count == 0 && (槽容器 == null || 技能格模板 == null)) return;
        备槽格();

        for (int i = 0; i < 成长管理器.技能槽数; i++)
        {
            var 视图 = i < 槽格池.Count ? 槽格池[i] : null;
            if (视图?.格 == null) continue;                 // 模板丢了：停手（已点名）
            排槽格(i);

            string 标识 = 槽标识(玩家, i);                   // ""/null = 空槽
            bool 空 = string.IsNullOrEmpty(标识);
            var 技能 = 空 ? null : 技能数据(玩家, 标识);
            int 序 = i;                                      // 闭包捕获：循环变量必须另存一份
            // 槽格只写三样（本批用户定稿："就是个能点的格子，信息只需要名字"）：
            //   名称 / 待装高亮 / 点击。原来喂给它的 类别·品质·主动被动·熟练·序号·空槽提示 全删 ——
            //   那些数现在都在右下角那**一个说明文本**里（点哪格看哪条）。
            //   ⚠ 6 格**一律可点**（空槽也接回调）：空槽点了要么装进待装那条、要么给一句弱提示
            //     （见 `点击槽` 的 ③⑤ 两支）。"被动不可点"那条特例已随 `技能格` 一并删掉。
            视图.格.绑定(
                技能标识: 标识,
                // 名字按**品质着色**（与左边列表行同一个技能同一个色）；**不加书名号** ——
                //   6 个格子挤在一排，书名号是纯占位的噪音（列表行那边加是因为跟知识行的样式对齐）。
                名称文本: 品质工具.名称着色(技能 != null ? 技能.品质档 : 品质.普通, 名称文本(标识, 技能)),
                待装: !空 && 标识 == 待装技能标识 && 待装来源槽 == i,
                点击: () => 点击槽(序));
        }
    }

    // 槽位上的标识：**照抄 `战斗技能槽[i]`**（null/空串都是空槽）。
    //   不 `Trim`、不"顺便修数据" —— 那是 `成长管理器` 的事；本页只显示它读到的东西。
    private static string 槽标识(玩家档案 玩家, int 槽索引)
    {
        var 槽 = 玩家.战斗技能槽;
        return 槽 != null && 槽索引 >= 0 && 槽索引 < 槽.Count ? 槽[槽索引] : null;
    }

    // ================= 下：已学技能列表 =================

    // 重建列表：**只列 `已学技能`**（未学会的不显示），顺序 = `已学技能` 原序（学习先后，稳定）。
    //   池子复用：行够用就只重新绑定 + 切显隐，不 Destroy / 不重复 Instantiate（避免列表每次刷新跳一下）。
    private void 建列表(玩家档案 玩家)
    {
        if (列表容器 == null || 技能行模板 == null) return;

        var 已学 = 玩家.已学技能;
        int 条数 = 已学?.Count ?? 0;

        // 列表为空：亮出常驻兜底文本，并把行全部收起来（不建空行）。
        if (条数 == 0)
        {
            备空列表();
            for (int i = 0; i < 行池.Count; i++) 行池[i].行.gameObject.SetActive(false);
            if (空列表节点 != null) 空列表节点.gameObject.SetActive(true);
            return;
        }
        if (空列表节点 != null) 空列表节点.gameObject.SetActive(false);

        bool 断了 = false;
        for (int i = 0; i < 条数; i++)
        {
            var 掌握 = 已学[i];
            if (掌握 == null || string.IsNullOrEmpty(掌握.标识)) { 收行(i); continue; }   // 坏档兜底（PlayerService 也会清，见其迁移段）
            var 标识 = 掌握.标识;
            var 行 = 取行(i);
            if (行 == null) { 断了 = true; break; }     // 模板丢了：停手（已点名），但下面的收尾照做
            行.行.gameObject.transform.SetSiblingIndex(i);   // 顺序 = `已学技能` 原序
            行.行.gameObject.SetActive(true);
            行.标识 = 标识;
            var 技能 = 技能数据(玩家, 标识);             // 一行只查一次（名称与品质共用同一份）
            int 序 = i;                                  // 闭包捕获（同上）
            // 行是**纯索引**（本批用户定稿："像知识行那样"）：只写名称 + 置灰两样，点击转发走第三样。
            //   名字也照知识行的样式加**书名号**（`《重击》`），且同样包在品质着色里面 —— 两页的列表长得一样。
            //   原来绑在这里的 `类别 / 主动与否 / 熟练 / 已装` 四个文本位已删 —— 那些数现在都在
            //   右下方的**单个说明文本**里（点哪条看哪条），行里再留一份就是同一件事写两遍。
            行.行.绑定(
                名称文本: 品质工具.名称着色(技能 != null ? 技能.品质档 : 品质.普通, "《" + 名称文本(标识, 技能) + "》"),
                置灰中: 已装格(玩家, 标识) < 0,          // 没装进技能槽的行灰着（判据见 `已装格`）
                点击: () => 点击行(序));
        }
        // 池子里多出来的（技能变少了：旧档/改数据）→ 收起来，不删（下次又多了不用重建）。
        // 中途停手（`断了`）时把**所有**行都收起来：否则上一次刷新留下的行会继续亮着，
        //   列表看起来"多出几条点不动的行"。
        int 收起起点 = 断了 ? 0 : 条数;
        for (int i = 收起起点; i < 行池.Count; i++)
            if (行池[i].行 != null) 行池[i].行.gameObject.SetActive(false);
    }

    private void 收行(int 序)
    {
        if (序 < 行池.Count && 行池[序].行 != null) 行池[序].行.gameObject.SetActive(false);
    }

    // 池子取第 i 行：不够就地克隆（模板行默认隐藏，`创建模板` 已负责激活），并从模板量行高。
    private 技能行视图 取行(int 序)
    {
        while (行池.Count <= 序)
        {
            var 组件 = 面板基类.创建模板<技能行>(列表容器, 技能行模板);
            if (组件 == null) return null;
            量行高(组件.gameObject, 技能行模板);
            行池.Add(new 技能行视图 { 标识 = null, 行 = 组件 });
        }
        return 行池[序];
    }

    // 待装态：只切**技能槽**上的预置高亮（**不重建列表本体**，避免滚动位置归零 / 点击态丢失）。
    //   列表行本批已没有"高亮"这个节点（用户口径：行只有 名字 / 按钮 / 置灰），所以这里只跑槽那一圈；
    //   行怎么灰由 `建列表` 在绑定时一次算好（灰不随"点一下"变，只有重新建列表才会变）。
    private void 刷选中态()
    {
        var 玩家 = 档案;
        if (玩家 == null) return;
        for (int i = 0; i < 槽格池.Count; i++)
        {
            var 视图 = 槽格池[i];
            if (视图?.格 == null) continue;
            var 标识 = 槽标识(玩家, i);
            视图.格.绑定待装态(!string.IsNullOrEmpty(标识) && 标识 == 待装技能标识 && 待装来源槽 == i);
        }
    }

    // 空列表兜底：场景里若有名为 `暂无技能` 的常驻节点就写它；否则**克隆一次模板行**、只留里面那个文本节点当纯文本容器。
    //   ⚠ **顺序要紧**（本批修的 NullReferenceException）：**先认领模板里的文本节点，再清掉其余子节点**。
    //     旧写法是"先把克隆的子节点全 `Destroy` 掉、再给行根 `AddComponent<TextMeshProUGUI>()`"，
    //     随后写 `.text` 就炸在那一行 —— 行根是 Button/Image，**临时 Add 出来的 TMP 组件没有模板里那套
    //     字体/材质/排版状态**，而模板自己那个名字节点（已经在预制体里被 Unity 初始化过）反过来是安全的
    //     （列表行长年就在对同一个节点写 `名称.text`）。
    //     于是现在：文本节点就地沿用（连它的父链一起留着，锚点/字号/颜色都不动），其余兄弟节点丢掉。
    //   ⚠ 空列表这句话**完全不随档变**，所以只建一次、常驻（`空列表节点` 缓存）—— 每次重算都新建一个
    //     TMP 对象会 unload/reload 字体，新旧两份还并存一帧（照 `知识子面板.备空列表`）。
    private void 备空列表()
    {
        if (空列表节点 != null) return;

        var 现成 = 找节点(列表容器, 名空列表);
        if (现成 != null)
        {
            // 用户放的兜底节点：文本可能在它自己身上，也可能在它的子节点里（两种都认）
            空列表节点 = 现成.GetComponent<TMP_Text>() ?? 现成.GetComponentInChildren<TMP_Text>(true);
            if (空列表节点 != null) return;
        }

        // 模板里连一个文本节点都没有 → 兜底字没处写，**直接不建**（不硬 AddComponent，见上面的 ⚠）
        if (技能行模板 == null || 技能行模板.GetComponentInChildren<TMP_Text>(true) == null) return;

        var 克隆 = 面板基类.创建模板<Transform>(列表容器, 技能行模板);
        if (克隆 == null) return;
        克隆.name = 名空列表;

        var 文本 = 克隆.GetComponent<TMP_Text>() ?? 克隆.GetComponentInChildren<TMP_Text>(true);
        if (文本 == null) return;   // 上面查过模板，理论上到不了；保险起见不往下走

        for (int i = 克隆.childCount - 1; i >= 0; i--)
        {
            var 子 = 克隆.GetChild(i);
            if (子 == 文本.transform || 文本.transform.IsChildOf(子)) continue;   // 留着那个文本节点（多半就在子节点上）
            Destroy(子.gameObject);
        }
        文本.text = 空列表文本;    // 字号/颜色沿用模板（本类不碰外观）
        空列表节点 = 文本;
    }

    // ================= 说明区（一个文本，按行拼） =================

    // 说明区：显示**待装那个**技能（玩家正打算装它，信息此刻最相关）；手里没有待装就显示列表里选中的那条；
    //   两者都没有 → 整段 `SetActive(false)`，不留一堆空标题。
    private void 刷说明(玩家档案 玩家)
    {
        var 待装 = 技能数据(玩家, 待装技能标识);
        var 选中 = 技能数据(玩家, 当前选中标识(玩家));
        var 技能 = 待装 ?? 选中;
        bool 有 = 技能 != null;

        // ⚠ 只收"**本组件自己下面**的节点"：说明文本若直接挂在本组件下，它的父节点就是根节点 ——
        //   连根一起 SetActive(false) 会把整个技能页连带关掉（壳那边切页就再也亮不起来）。
        if (说明文本 != null) 切父显隐(说明文本.transform, 有, "说明区");

        面板基类.设文本(说明文本, 有 ? 说明内容(玩家, 技能) : "");
    }

    // 说明文本的拼法（用户定稿：**一个文本**，块间空行 —— 与 `知识子面板.详情拼法` 同一口径）：
    //   [块1] `《技能名》`（品质着色；书名号与知识页标题同源）
    //         / `{类别} · 主动|被动` / `熟练　Lv2/5　30/100` / `已装·第3格|未装`
    //   [块2] `目标　…` / `攻击距离　… 格` / `出手时机　…` / `消耗精力　…　冷却　… 秒`（**最后一行只有主动才写**）
    //   为什么把"熟练 / 已装"搬进来：它们原来是列表行里的两栏，本批行只留名字（用户口径），
    //     这两条信息没有别的去处 —— 挪进说明区正好"一条不丢"。
    //   为什么被动不写消耗：被动技能的数据里这两个字段有值，但对被动永不生效（不消耗行动、没有冷却）——
    //     显示出来就是骗人（用户钦定的被动硬规矩 ③），所以整行**不写**（不是写 0）。
    //   为什么类别/目标照抄 JSON 原字符串（不写"解析后的枚举"）：见 `类别文本` 的注释 ——
    //     认不出的字符串会退化成枚举的第一个值，那时界面会显示一个数据里根本没有的类别。
    private static string 说明内容(玩家档案 玩家, 技能数据 技能)
    {
        var 头 = new StringBuilder();
        加行(头, 品质工具.名称着色(技能.品质档, "《" + 名称文本(技能.标识, 技能) + "》"));
        加行(头, $"{类别文本(技能)} · {(技能.被动 ? "被动" : "主动")}");
        加行(头, $"熟练　{熟练文本(玩家, 技能.标识)}");
        加行(头, 已装文本(玩家, 技能.标识));

        var 身 = new StringBuilder();
        if (技能.被动)
        {
            // 被动**不走**"目标 / 攻击距离 / 出手时机 / 消耗精力"那一套：它不释放，那些字段在被动数据里
            //   或有值或为空，但对被动**永不生效** —— 照旧拼出来就是骗人（与下一段"被动不写消耗"同一条理由，
            //   而且"攻击距离 1 格 / 出手时机 蓄力"这两行对一个不释放的技能纯属噪音）。
            //   被动真正有信息量的是：它是**增幅**还是**机制**，以及增幅了什么。
            加行(身, 标签行("被动类型", 技能.被动类型));
            加行(身, 增幅文本(技能));
        }
        else
        {
            加行(身, 标签行("目标", 技能.目标));
            加行(身, $"攻击距离　{攻击距离(技能)} 格");
            加行(身, $"出手时机　{时机文本(技能)}");
            加行(身, $"消耗精力　{技能.消耗精力}　冷却　{冷却(技能)} 秒");
        }

        var 文本 = new StringBuilder();
        加块(文本, 头.ToString());
        加块(文本, 身.ToString());
        return 文本.ToString();
    }

    // `标签　值`：**值为空就整行不写**（照知识页"空项一个字都不写"的口径）——
    //   数据里 `目标` 是空串的技能（被动技普遍不配目标）若照旧硬拼，界面上会留下一行光秃秃的"目标　"。
    private static string 标签行(string 标签, string 值)
        => string.IsNullOrEmpty(值) ? "" : $"{标签}　{值}";

    // 被动增幅一行：`增幅　命中 +5点` / `增幅　近战 +10%`（属性为空 = 这条被动不增幅，整行不写）。
    //   **单位照抄数据**（`技能数据.增幅单位`），不套知识页那套"按属性名猜百分点"的规则：
    //   数据里 `致命点`（暴击）的单位写的是"点"、`狠劲`（近战）写的是"%" —— 按属性名猜会把前者显示成 +10%。
    //   数值用 `0.##`：增幅值是 float，去掉没意义的 ".0"（数据里都是整数，写 "5" 而不是 "5.0"）。
    private static string 增幅文本(技能数据 技能)
        => string.IsNullOrEmpty(技能.增幅属性)
            ? ""
            : $"增幅　{技能.增幅属性} +{技能.增幅值.ToString("0.##")}{技能.增幅单位}";

    // 块内换行：往同一个块里追加一行（块的第一行不加 `\n`）。照 `知识子面板.加行`。
    private static void 加行(StringBuilder 块, string 内容)
    {
        if (string.IsNullOrEmpty(内容)) return;
        if (块.Length > 0) 块.Append('\n');
        块.Append(内容);
    }

    // 块间空行：有内容才追加（**空块不留空行** —— 否则会多出一片空白）。照 `知识子面板.加块`。
    private static void 加块(StringBuilder 全文, string 内容)
    {
        if (string.IsNullOrEmpty(内容)) return;
        if (全文.Length > 0) 全文.Append('\n').Append('\n');
        全文.Append(内容);
    }

    // 攻击距离：数据缺省（0）在投影里按 1 算（`技能数据.攻击距离` 注释："0 = 按 1"）→ 显示也跟着按 1，别写 0 格。
    private static int 攻击距离(技能数据 技能) => 技能.攻击距离 > 0 ? 技能.攻击距离 : 1;

    // 冷却：0 = 无冷却（`技能数据.冷却` 注释）→ 显示"无"而不是"0 秒"（0 秒看起来像"立刻就能再放"，
    //   而实际语义是"没有冷却条要等"）。**原字符串**照抄，不参与任何枚举解析。
    private static string 冷却(技能数据 技能) => 技能.冷却 > 0 ? 技能.冷却.ToString() : "无";

    // 出手时机：JSON 原字符串照抄（`技能数据.出手时机`）；空 = 数据缺省，投影按"蓄力"处理 → 显示也写"蓄力"
    //   （见 `技能数据.出手时机枚举` 的缺省分支：空字符串 = 蓄力）。
    private static string 时机文本(技能数据 技能)
        => string.IsNullOrEmpty(技能.出手时机) ? "蓄力" : 技能.出手时机;

    // ================= 交互：点列表 =================

    // 点列表某条：设为待装（**只重绘，不写档案**）；**再点它一次 = 取消**（用户钦定）。
    private void 点击行(int 序)
    {
        var 玩家 = 档案;
        if (玩家?.已学技能 == null || 序 < 0 || 序 >= 玩家.已学技能.Count) return;
        var 标识 = 玩家.已学技能[序]?.标识;
        if (string.IsNullOrEmpty(标识)) return;

        // 数据缺失的已学标识：**禁止待装**。为什么：`切换入槽` 只校验"学过没有"，数据缺失的标识能写进槽，
        //   但战斗投影查不到技能数据 → 那一格在战斗里就是空的（玩家以为装了、实际什么都没装）。
        if (技能数据(玩家, 标识) == null)
        {
            警告($"skills.json 里没有这个技能，装入也不会生效：{标识}");
            return;
        }

        bool 取消 = 标识 == 待装技能标识 && 待装来源槽 < 0;
        if (取消)
        {
            待装技能标识 = null;
            待装来源槽 = -1;
            音效管理器.实例?.播放成功();   // 取消了（状态真的变了）→ 给一声反馈
        }
        else
        {
            待装技能标识 = 标识;
            待装来源槽 = -1;
            选中序号 = 序;                 // 选中 = 说明区显示这一条（与"待装"是两件事，但点它就是"我在看它"）
            音效管理器.实例?.播放成功();
        }
        刷新();   // 只重绘（不写档案）
    }

    // ================= 交互：点槽 =================

    // 点某个槽格。分支顺序就是用户的定稿表，一条条对着看：
    //   ① 战斗中 → 拦下（不调任何写方法）；
    //   ② 手里这个待装正是从这一格拿起来的（`待装来源槽 == i`）→ 取消待装，**不调领域方法**；
    //   ③ 手里有待装 → `切换入槽`（同技能已在别槽会自动对调，原槽技能退回列表）；
    //   ④ 手里没有待装、这一格装着技能 → `卸下槽`（技能不会丢，它回列表）；
    //   ⑤ 手里没有待装、这一格是空的 → 弱提示（日志，**不播失败音**）。
    private void 点击槽(int 槽索引)
    {
        if (槽索引 < 0 || 槽索引 >= 成长管理器.技能槽数) return;
        var 玩家 = 档案;
        if (玩家 == null) return;

        if (存档门禁.正在战斗)
        {
            音效管理器.实例?.播放失败();
            警告("战斗中不能调整技能位（技能栏在进场时已锁定）");
            return;
        }

        string 现有 = 槽标识(玩家, 槽索引);

        // ② 同一个槽：这次点的是"待装它自己待过的那一格" → 取消（不写档案、不调领域方法）
        if (!string.IsNullOrEmpty(待装技能标识) && 待装来源槽 == 槽索引)
        {
            待装技能标识 = null;
            待装来源槽 = -1;
            音效管理器.实例?.播放成功();
            刷新();
            return;
        }

        // ③ 手里有待装 → 装进这一格（`切换入槽` 是角色面板换槽的**唯一写入口**）
        if (!string.IsNullOrEmpty(待装技能标识))
        {
            bool 成功 = 玩家.成长管理 != null && 玩家.成长管理.切换入槽(槽索引, 待装技能标识);
            if (!成功)
            {
                // 失败在这里是**内部异常**：标识非空、槽索引本页clamp 过、标识来自 `已学技能`（= 已掌握）。
                //   所以保留待装 + 失败音 + 警告，并**强制全量重算**（把界面拉回档案的真实状态，别停在半路）。
                音效管理器.实例?.播放失败();
                警告($"装入第 {槽索引 + 1} 格失败：{待装技能标识}（界面已按档案重算）");
                刷新();
                return;
            }
            待装技能标识 = null;
            待装来源槽 = -1;
            刷新();   // 全量重算：对调会同时改两格（原槽那一格也要跟着变）
            return;
        }

        // ④ 手里没有待装、这一格装着技能 → 直接卸下（技能回列表）
        if (!string.IsNullOrEmpty(现有))
        {
            bool 成功 = 玩家.成长管理 != null && 玩家.成长管理.卸下槽(槽索引);
            if (!成功)
            {
                音效管理器.实例?.播放失败();
                警告($"卸下第 {槽索引 + 1} 格失败（界面已按档案重算）");
            }
            刷新();
            return;
        }

        // ⑤ 空槽 + 手里没待装：弱提示（用户钦定：**不播失败音**）
        警告("先在下面的列表里点一个技能，再点这一格装进去。");
    }

    // ================= 数据取值（本页不自己发明数值） =================

    // 标识 → `技能数据`：走 `玩家档案.技能解析`（PlayerService 接线到 `DataService.技能`）。
    //   为什么用这个委托而不是自己取 `DataService`：这是档案**对外暴露的技能表入口**（战斗投影也走它），
    //   口径只有一份；取不到 = null = 数据缺失（页面据此禁止待装 / 名称附"（数据缺失）"）。
    private static 技能数据 技能数据(玩家档案 玩家, string 标识)
        => string.IsNullOrEmpty(标识) ? null : 玩家?.技能解析?.Invoke(标识);

    // 名称：`技能数据.名称`；**取不到数据就显示标识 + "（数据缺失）"**（宁可显示标识，也不要一行空白，
    //   更不能拿标识去猜一个名字）。
    private static string 名称文本(string 标识, 技能数据 技能)
        => 技能 != null && !string.IsNullOrEmpty(技能.名称) ? 技能.名称 : 标识 + "（数据缺失）";

    // 类别：**JSON 原字符串照抄**（`技能数据.类别`）。为什么不用 `技能数据.类别枚举`：
    //   那是个 `数据解析.枚举<...>` 转换，字符串认不出时会退化成枚举的**第一个值** → 界面上显示一个
    //   数据里根本没有的类别（"解析失败"看起来和"真是攻击技"一模一样）。要显示就显示真的那个字符串。
    private static string 类别文本(技能数据 技能) => 技能?.类别 ?? "";

    // （原 `品质文本` = `品质工具.标签` 那个"[优秀]"徽章，随槽格简化一起删了：本批槽格只写名字，
    //   品质已经由**名字的颜色**表达 —— 再挂一个徽章就是同一件事写两遍，而且 6 个格子里塞不下。）

    // 熟练：走 `玩家档案` 上的门面（`技能熟练等级` / `技能熟练度`），阈值走 `技能服务.每级熟练度(标识)`。
    // 满级只显示 `Lv{上限}/{上限}` —— 满级后熟练度不再累积（`成长管理器.记录熟练度` 到上限直接 return），
    //   继续写 "{熟练度}/{每级}" 会让玩家以为"再练练还能涨"。
    private static string 熟练文本(玩家档案 玩家, string 标识)
    {
        int 等级 = 玩家.技能熟练等级(标识);
        int 上限 = 玩家档案.熟练等级上限;
        return 等级 >= 上限 ? $"Lv{上限}/{上限}" : $"Lv{等级}/{上限}　{玩家.技能熟练度(标识)}/{每级熟练度(标识)}";
    }

    // 每级熟练度阈值：`技能服务.每级熟练度` 是唯一入口（取不到服务/没这个技能 → 它自己给 100 兜底）。
    private static int 每级熟练度(string 标识)
        => ServiceRegistry.已注册<技能服务>() ? ServiceRegistry.Get<技能服务>()?.每级熟练度(标识) ?? 0 : 0;

    // 已装格号：**一次 `FindIndex`** 同时回答"在不在槽里"和"在第几格"（-1 = 没装）。
    //   为什么不 `Contains` + `IndexOf` 查两遍：那是同一张表扫两次，而且两次之间表若被别处改过，
    //   两个答案会互相打架（`-1` 会变成"未装"却真的在槽里）。
    //   ⚠ 列表行的**置灰**判据与说明区的 `已装·第N格` 都走它 —— 同一件事只有一份算法。
    private static int 已装格(玩家档案 玩家, string 标识)
        => 玩家?.战斗技能槽?.FindIndex(s => s == 标识) ?? -1;

    // 已装标记：`已装·第3格` / `未装`（说明区那一行）。
    private static string 已装文本(玩家档案 玩家, string 标识)
    {
        int 索引 = 已装格(玩家, 标识);
        return 索引 >= 0 ? $"已装·第{索引 + 1}格" : "未装";
    }

    private string 当前选中标识(玩家档案 玩家)
    {
        var 已学 = 玩家?.已学技能;
        if (选中序号 < 0 || 已学 == null || 选中序号 >= 已学.Count) return null;
        return 已学[选中序号]?.标识;
    }

    // ================= 反馈出口（照属性页那一批） =================

    // 被拦下的操作 / 提示一律 `警告` 日志（左下角日志面板）：与 `家具行.材料不足反馈`、
    //   `属性子面板` 的 `警告` 同一个口径 —— 玩家在同一个地方看到"为什么没成"。
    private static void 警告(string 文本)
        => ServiceRegistry.Get<EventBus>()?.发布(new 日志事件(日志类型.警告, 文本));

    // ================= 引用兜底：按节点名找回来（只找，不建） =================

    private void 自找()
    {
        if (槽容器 == null) 槽容器 = 子矩形(transform, 名槽容器);
        if (技能格模板 == null) 技能格模板 = 找节点(transform, 名技能格模板)?.gameObject;
        if (列表容器 == null) 列表容器 = 子矩形(transform, 名列表容器);
        if (技能行模板 == null) 技能行模板 = 找节点(transform, 名技能行模板)?.gameObject;
        // 说明区那一个文本**可空**：没搭也不报错（用户只要求"要技能说明"，节点怎么摆归场景）
        if (说明文本 == null)
            foreach (var 名 in new[] { 名说明文本, 名说明文本别名, 名说明文本别名2 })
            {
                说明文本 = 子文本(transform, 名);
                if (说明文本 != null) break;
            }
    }

    // 缺引用**要出声**：Inspector 少接一个位 → 表现只是"某一块永远空着 / 点了没反应"，一条日志都没有。
    // 打**一条** LogError 把缺的名字列全（不崩、不中断别的面板）。说明区那**一个**文本不算缺（可空）。
    private void 报缺引用()
    {
        var 缺 = new List<string>();
        if (槽容器 == null) 缺.Add($"槽容器（节点名「{名槽容器}」）");
        if (技能格模板 == null) 缺.Add($"技能格模板（节点名「{名技能格模板}」）");
        if (列表容器 == null) 缺.Add($"列表容器（节点名「{名列表容器}」）");
        if (技能行模板 == null) 缺.Add($"技能行模板（节点名「{名技能行模板}」）");
        // 预搭槽格：只有一格都没收到、模板也没有时才真的没法工作（模板在就算能跑）
        if (槽格池.Count == 0 && 技能格模板 == null)
            缺.Add($"槽格（节点名「{槽格名前缀}1」..「{槽格名前缀}{成长管理器.技能槽数}」，或接上 `技能格模板`）");
        // 找到了同名节点、但没挂 `技能格`：那一格永远空白（**静默失败**，必须点名）
        if (缺组件槽.Count > 0)
        {
            var 格号 = new List<string>();
            foreach (var i in 缺组件槽) 格号.Add((i + 1).ToString());
            缺.Add($"第 {string.Join("、", 格号)} 格上的「{槽格名前缀}N」节点没挂 `技能格` 组件");
        }
        if (缺.Count == 0) return;
        Debug.LogError("[技能子面板] 缺引用：" + string.Join("、", 缺) +
                       "。请在场景里把这些节点拖到本组件的 Inspector 引用位上" +
                       "（或让节点名与括号里的一致、挂在本组件下面）。" +
                       "外观在场景 / 预制体里调：本组件只克隆「技能格模板 / 技能行模板」，不建别的节点。");
    }

    // ================= 小工具 =================

    // 切"某个文本节点的父节点"显隐（把标题与它那一段内容一起收/放）。
    // 两道保险（照 `知识子面板.切父显隐`）：父节点必须是**本组件自己下面**的（绝不碰根节点）；
    //   且父节点里不能装着本组件赖以工作的引用 —— 否则一收就把槽/列表也收掉了
    //   （那样"这一行没内容"和"整个面板坏了"看起来一模一样，极难排查）。
    private void 切父显隐(Transform 节点, bool 显, string 说明)
    {
        var 父 = 节点 != null ? 节点.parent : null;
        if (父 == null || 父 == transform) return;                   // 直挂本组件下 → 只有那个文本自己，别动别的
        if (!父.IsChildOf(transform)) return;                        // 不知道是什么，别碰
        if (包含关键引用(父)) return;
        if (父.gameObject.activeSelf != 显) 父.gameObject.SetActive(显);
    }

    private bool 包含关键引用(Transform 节点)
    {
        if (节点 == null) return false;
        if (槽容器 != null && (节点 == 槽容器 || 槽容器.IsChildOf(节点))) return true;
        if (列表容器 != null && (节点 == 列表容器 || 列表容器.IsChildOf(节点))) return true;
        if (技能格模板 != null && 技能格模板.transform.IsChildOf(节点)) return true;
        if (技能行模板 != null && 技能行模板.transform.IsChildOf(节点)) return true;
        return false;
    }

    // 从模板量行高写进克隆体的 `LayoutElement`：容器挂了 `VerticalLayoutGroup` / `HorizontalLayoutGroup` 时，
    //   `LayoutElement.preferredHeight` 会**覆盖** RectTransform 的高度 → 用户在模板上量的高度会被布局组吃掉
    //   （每行挤成 0 高）。取的值就是模板自己的高度（**不写死数字**），照 `知识子面板.量行高`。
    private static void 量行高(GameObject 克隆, GameObject 模板)
    {
        if (克隆 == null || 模板 == null) return;
        var 模板矩形 = 模板.GetComponent<RectTransform>();
        if (模板矩形 == null) return;
        var 模板布局 = 模板.GetComponent<UnityEngine.UI.LayoutElement>();
        float 高 = 模板布局 != null && 模板布局.preferredHeight > 0f ? 模板布局.preferredHeight : 模板矩形.rect.height;
        if (高 <= 0f) return;   // 模板还没被布局过（场景刚搭好）→ 不写，免得写成 0 高
        var 布局 = 克隆.GetComponent<UnityEngine.UI.LayoutElement>();
        bool 新加 = false;
        if (布局 == null) { 布局 = 克隆.AddComponent<UnityEngine.UI.LayoutElement>(); 新加 = true; }
        if (新加 || 布局.preferredHeight <= 0f) 布局.preferredHeight = 高;
    }

    // 按名找节点：本组件下面**任意深度**的第一个同名节点。
    // 为什么不能只用 `Transform.Find`：它只找**直接子节点**，而槽/列表/说明通常还在区节点里面一层。
    private static Transform 找节点(Transform 根, string 名)
    {
        if (根 == null || string.IsNullOrEmpty(名)) return null;
        for (int i = 0; i < 根.childCount; i++)
        {
            var 子 = 根.GetChild(i);
            if (子.name == 名) return 子;
            var 深 = 找节点(子, 名);
            if (深 != null) return 深;
        }
        return null;
    }

    private static TMP_Text 子文本(Transform 父, string 名) => 找节点(父, 名)?.GetComponent<TMP_Text>();
    private static RectTransform 子矩形(Transform 父, string 名) => 找节点(父, 名)?.GetComponent<RectTransform>();
}

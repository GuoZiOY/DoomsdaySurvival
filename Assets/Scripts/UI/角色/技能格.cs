using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.UI;
using TMPro;

// 技能格：技能子面板「上面那 6 个技能槽」的槽格模板组件（挂在模板格根节点上，场景里默认 SetActive(false)）。
// 为什么单独一个文件（照 `知识行` / `配方行` 的做法）：槽格是**模板资产上的脚本**，与页面逻辑分开才好让用户
//   在 Unity 里单独把模板格拆出来摆；塞进 `技能子面板.cs` 会让那个文件既不只讲"页"、又成了两个组件的家。
//
// ★ 槽索引 ↔ 数据下标 ↔ 界面格号（**三处必须同一套**，写在这里免得下次又猜）：
//   槽索引 i（本组件由页面传入） == `玩家档案.战斗技能槽` 的下标 i == 界面第 i+1 格。
//   页面按 `成长管理器.技能槽数` 遍历，不与任何写死的 6 对齐。
//
// 本批改版（用户定稿）：**槽格就是个格子** —— 只有 名字 + 待装高亮 + 可点，别的都不写。
//   ① 名称：技能名（已由页面按品质着色）；空槽写 `空槽文案` 这两个字（想换文案只改那一个常量）；
//   ② 待装高亮：一个预置节点，显隐由本类切 —— 它只表达"我正拿着这条技能"（颜色/透明度全归场景）；
//   ③ 点击转发：`IPointerClickHandler`（不用 Button 也能点）+ 可选 `Button`，两条路走同一个回调。
// **删掉**（连同页面里的写入一起）：序号 / 类别 / 品质 / 主动与否 / 熟练 / 被动说明 / 空槽提示 七个位 ——
//   它们要的信息现在都在右下角**那一个说明文本**里（点哪格看哪条），格子上再写一遍就是同一件事写两遍。
//   序号一栏也去掉了：槽位号在说明区的 `已装·第N格` 里写着（用户口径："信息只需要名字"）。
//   ⚠ 连带**删掉"被动不可点"那条特例**：那条原本是给**战斗内释放**定的规矩（"占槽不可点击释放"），
//     落在角色面板上就变成了"被动技能装进槽以后再也点不动"——现在 6 格一律可点：空槽点了给弱提示，
//     装着的点了卸下/换装（页面 `点击槽` 里那 5 条分支对被动同样成立）。
public sealed class 技能格 : MonoBehaviour, IPointerClickHandler
{
    [SerializeField] private TMP_Text 名称;        // 技能名（已由页面按品质着色）；空槽 = `空槽文案`
    [SerializeField] private GameObject 待装高亮;  // 待装/选中态预置高亮节点（本类只切显隐，不写颜色）
    [SerializeField] private Button 按钮;          // 可选：模板格若用 Button 做点击面，本类也接同一路

    // 空槽那一格写什么：**归拼串**（不是外观），所以留一个常量；想写"空"或"—"改这里一处即可。
    public const string 空槽文案 = "空槽";

    private UnityEngine.Events.UnityAction 点击回调;

    // 点击格：uGUI 事件沿层级冒泡 —— 点到格内任何子节点都算点这一格（照 `知识行`）。
    // 音效不在这里播：页面统一播（成功音随 `注册按钮`，失败音由页面按结果播）。
    public void OnPointerClick(PointerEventData 事件) => 点击回调?.Invoke();

    // 绑定一个槽格：`技能标识` 为空 = 空槽（名称栏写 `空槽文案`）；`名称文本` 由页面拼好（含品质着色）。
    //   `待装` = 这一格是不是"手里正拿着的那一条"要放的目标（页面算好的事实）。
    public void 绑定(string 技能标识, string 名称文本, bool 待装, UnityEngine.Events.UnityAction 点击)
    {
        点击回调 = 点击;
        面板基类.设文本(名称, string.IsNullOrEmpty(技能标识) ? 空槽文案 : 名称文本);

        var 高亮 = 待装高亮;
        if (可切显隐(高亮)) 高亮.SetActive(待装);

        // Button 那条路：只在每次绑定时重接一次（幂等）。`interactable` 跟着"有没有回调"走 ——
        //   它是**状态表达**（按不动就别装得像能按），不是外观：颜色/过渡仍在场景里调，本类不碰。
        if (按钮 != null)
        {
            按钮.onClick.RemoveAllListeners();
            按钮.interactable = 点击 != null;
            if (点击 != null)
            {
                按钮.onClick.AddListener(触发);
                音效管理器.实例?.注册按钮(按钮);   // 幂等：悬停/点击反馈沿用项目既有口径
            }
        }
    }

    // 只切待装态：槽格是**池化复用**的（写操作后全量重算，见 `技能子面板`），
    //   所以重算时可以只翻高亮，不必把格内内容再写一遍（免得日后有人在 `绑定` 里加了带副作用的写法）。
    public void 绑定待装态(bool 待装)
    {
        var 高亮 = 待装高亮;
        if (可切显隐(高亮)) 高亮.SetActive(待装);
    }

    private void 触发() => 点击回调?.Invoke();

    // ================= 护栏：预置节点不许是"格根" =================

    // 为什么需要（`知识行` 那边实证过的坑，不是防御性编程）：`待装高亮` 若被误接成**格根节点自己**
    //   （`知识行.prefab` 就这么接错过），`SetActive(false)` 关掉的是**整格** —— 6 个槽看起来全没了，
    //   而代码这边一条报错都没有。判据两种都挡（表现一模一样）：`目标 == gameObject`（接成了格根本身）、
    //   本格是目标的子孙（接成了格的祖先容器，比如整个槽容器）。
    // 命中就**跳过 `SetActive`**：高亮不生效只是少个提示，整格消失却是"槽位没了"这种致命表现。
    private bool 可切显隐(GameObject 目标)
    {
        if (目标 == null) return false;
        if (目标 == gameObject || transform.IsChildOf(目标.transform))
        {
            警告接成格根();
            return false;
        }
        return true;
    }

    // "只喊一次"的标志用 **static**：槽格是**池化克隆**的（同一份预制体在场景里 6 份实例），
    //   实例字段 = "一开页刷 6 条，每次重算再刷 6 条"——同一处预制体误配，喊一次就够人去改了。
    private static bool 已警告待装高亮接格根;

    private static void 警告接成格根()
    {
        if (已警告待装高亮接格根) return;
        已警告待装高亮接格根 = true;
        Debug.LogWarning("[技能格] `待装高亮` 接成了格根节点（或格的祖先容器），会导致整格被隐藏；" +
                         "请在预制体里改接一个专门的高亮子节点" +
                         "（本格已跳过对这个节点的 SetActive，格内其它内容照常显示）。");
    }
}

using System;
using UnityEngine;

// 角色面板皮肤：角色面板**整块**（板底 + 遮罩 + 顶部身份条 + 四个栏页）共用的颜色 / 字号 / 尺寸参数。
//
// ★ 本版口径（用户 2026-09 拍板，配套"布局由用户手动搭"那一批）：**皮肤是"可序列化的参数类"**。
//   原来它是一堆 `static readonly` 常量 —— 那时布局由代码自建，改一处常量全局面板都变；
//   现在布局由用户在 Unity 里手动搭（见 `角色面板` 文件头），所以参数必须是**每个面板实例自己的序列化数据**：
//   `角色面板` 组件上的 `皮肤` 字段展开就能看/能改，改颜色字号立刻在运行时生效。
//   为什么不做成"参数类 + 静态实例"：一个面板一份参数才叫皮肤参数 —— 静态字段改一处全项目变，
//   与代码自建年代的老毛病同源，且没法在 Inspector 里按面板调。
//
// 谁在用（决定了改哪个字段会真的动起来）：
//   · **运行时会写进场景物体的**：遮罩 / 板底 / 身份条底 / 内容区底 / 分隔线 / Tab 下划线的颜色，
//     身份文本·等级文本·栏目标题·Tab 标签 的字号与颜色，Tab 的悬停色与禁用色，经验格的点亮色与空槽色；
//   · **只当"搭 UI 时那把尺子"的**：页边距 / 段距 / 行高 / 身份条高 / 边框粗 / 板宽高比例与上限 /
//     进度格尺寸 / 技能槽尺寸 —— 布局已改手动，代码不再按它们算位置，但照这些数摆才和原口径一致。
//
// 视觉口径（照它搭，别自己发明）：
//   ① 暖调近黑 + 唯一强调色暗锈红（**没有琥珀**：炭黑配琥珀是 AI 深色仪表盘的标准配色，明令去掉）；
//   ② **没有**圆角、阴影、发光、渐变、图标、动画 —— 只有实色方块与文字（Image 不给 sprite 就是实心方块）；
//   ③ 品质色**不在这里**：按项目既有口径读 `品质工具.颜色()`，不要另发明一套品质配色；
//   ④ 本类只服务角色面板这一块（`游戏主题` 是全局暖暗余烬风、`网格面板配色` 是网格/地图层），三者互不覆盖。
[Serializable]
public class 角色面板皮肤
{
    // ===================== 颜色 =====================
    // 写的是"这个颜色画在哪、影响什么观感"，改之前先想清楚它在不在唯一的强调色体系里（见文件头①）。

    public Color 板底 = new Color(0.0706f, 0.0627f, 0.0549f, 1f);    // #12100E 板子最外层的底：身份条/内容区以外露出来的那一圈就是它（配上 2px 边框才成"板"）
    public Color 内容底 = new Color(0.1020f, 0.0941f, 0.0824f, 1f);   // #1A1815 身份条与内容区的底：比板底亮一档，边框线落在两者之间才分得开
    public Color 边框 = new Color(0.2275f, 0.2118f, 0.1882f, 1f);     // #3A3630 板子四边的 2px 边框 + Tab 行下方那条分隔线（**按 2px 画**，不是 1px）
    public Color 正文 = new Color(0.8941f, 0.8745f, 0.8392f, 1f);     // #E4DFD6 主文字色：身份文本、栏目标题、**选中的**那个 Tab 标签
    public Color 次要 = new Color(0.5412f, 0.5137f, 0.4706f, 1f);     // #8A8378 次要文字色：未选中的 Tab 标签、右侧等级文本（低一档，不跟标题抢视线）
    public Color 强调 = new Color(0.7059f, 0.3333f, 0.2353f, 1f);     // #B4553C 全屏唯一强调色（暗锈红）：选中 Tab 的下划线 + 已点亮的经验格；用多了就不叫强调
    public Color 恢复 = new Color(0.4314f, 0.5608f, 0.3843f, 1f);     // #6E8F62 增益/治疗语义色（低饱和苔绿）——本版四个栏页还没填内容，先留着别删
    public Color 悬停底 = new Color(0.1490f, 0.1333f, 0.1255f, 1f);   // #262220 Tab 鼠标悬停/按下时底图的颜色（代码写进 Button 的 Colors，无过渡动画）
    public Color 遮罩 = new Color(0f, 0f, 0f, 0.65f);                 // #000000 65% 黑：压在安全屋画面上的暗色层（只负责变暗；挡不挡点击看那个 Image 的 Raycast Target）
    public Color 禁选底 = new Color(0.2275f, 0.2118f, 0.1882f, 1f);   // #3A3630 未点亮的经验格底色（= 边框色，让空槽也看得见）；也用作 Tab 的禁用态底色

    // ===================== 字号（单位 = TMP 的 fontSize，不是像素高度） =====================

    public int 字号_标题 = 30;       // 身份条左边那行"幸存者 · 职业"的字号（板内最大的一档）
    public int 字号_栏目标题 = 24;   // 内容区顶部"属性/技能/知识/天赋"这几个栏目标题的字号
    public int 字号_Tab = 24;        // 顶部横排四个大字 Tab 的字号（与栏目标题同档，但颜色/位置不同所以不冲突）
    public int 字号_等级 = 20;       // 身份条右边的"Lv.N"字号（比标题小一档）
    public int 字号_正文 = 19;       // 栏页里列表行名称、正文的字号（本版还没填内容，先定下来）
    public int 字号_小字 = 16;       // 行附属信息、次要说明的字号（同上）

    // ===================== 间距（搭 UI 时照这些数摆） =====================

    public float 页边距 = 40f;      // 板内四边留白：身份条 / Tab 行 / 内容区 左右往上都从这条线起（同一个数，板子才整齐）
    public float 段距 = 20f;        // 段与段之间：身份条→Tab 行、Tab 行→分隔线、Tab 与 Tab 之间都用它
    public float 行高 = 48f;        // 列表行高：**行与行之间不画线**，靠这个留白分层（本版还没填内容，先定下来）
    public float 身份条高 = 88f;    // 顶部身份条的高度（标题 30 + 段距 + 进度格 10 + 上下留白）
    public float 边框粗 = 2f;       // 板子四边边框与分隔线的线宽（搭的时候摆 2 高/2 宽；不是 1px 发丝线）

    // ===================== 板子尺寸（"覆盖大半即可"，不铺满屏） =====================
    // 原算法：宽 = min(屏宽 × 板宽比例, 板宽上限)，高 = min(屏高 × 板高比例, 板高上限)，屏幕居中。
    // 现在布局手动摆 → 代码不再算，这几个数留给两种用法：① 按锚点比例摆（例如 anchorMin/Max = 0.08/0.92 ≈ 0.84）；
    //   ② 直接定尺（宽 1180 × 高 760 就是上限那档）。

    public float 板宽比例 = 0.84f;   // 板宽占屏宽的比例（照它摆锚点：左右各留 8%）
    public float 板高比例 = 0.88f;   // 板高占屏高的比例（照它摆锚点：上下各留 6%）
    public float 板宽上限 = 1180f;   // 板宽硬上限：大屏上不让板子跟着一起变宽（一行字横跨 1900px 就不是档案板了）
    public float 板高上限 = 760f;    // 板高硬上限，理由同上

    // ===================== 进度格子（经验条）：分段格子，不是连续细条 =====================
    // 经验格由用户在场景里摆成 N 个 Image；这三个数是"摆的时候的格子尺寸"，
    // 用 GridLayoutGroup 的话：Cell Size = (进度格宽, 进度格高)、Spacing = (进度格间隔, 0)。

    public float 进度格高 = 10f;     // 单个经验格的高度（这一版进度条就是 10px 高的小方块串）
    public float 进度格宽 = 10f;     // 单个经验格的宽度（正方形格子；窄了会看成虚线）
    public float 进度格间隔 = 2f;    // 格子之间的间隙（2px → 一眼能数出"亮了几格"）

    // ===================== 技能槽（技能栏页用；本版还没填内容） =====================

    public float 技能槽高 = 96f;     // 技能槽的高度（下批做技能栏时照它摆格子）
    public float 技能槽宽 = 150f;    // 技能槽的宽度（同上）
}

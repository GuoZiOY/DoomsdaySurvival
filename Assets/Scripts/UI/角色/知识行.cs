using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.UI;
using TMPro;

// 知识行：知识子面板「左列表」的行模板组件（挂在模板行根节点上，场景里默认 SetActive(false)）。
// 为什么单独一个文件（照 `配方行` 的做法）：行组件是**模板资产上的脚本**，与页面逻辑分开才好让用户在 Unity 里
//   单独把模板行从场景里拆出来摆；塞进 `知识子面板.cs` 会让那个文件既不只讲"页"、又成了两个组件的家。
//
// 本批改版（用户定稿）：左列表是**纯索引**，一行只有四样东西 ——
//   ① 名称（已由页面按品质着色，本类不再包颜色）；
//   ② 等级（**罗马数字**，如 "VI"；未掌握 = "—"）；
//   ③ 选中高亮（一个预置节点，显隐由本类切）；
//   ④ **未掌握置灰**（一个预置节点，显隐由本类切）—— 未掌握的行**灰着显示**，不藏起来：
//      13 本知识永远都在列表里，读者一眼就能看出"还有哪几本没入门"，藏起来反而要自己数。
// **删掉**（连同页面里的写入一起）：`进度`（累计经验）· `还差`（还差 N 本）· `持有`（持有 M 本）·
//   以及上一版的 `未掌握提示`（那段"未掌握"文字）—— 这些都是"细节"，现在全部由**右详情区**承载；
//   列表行里再留一份就是同一件事写两遍，改口径时必有一边漏掉。
//   ⚠ `未掌握置灰` 与上一版那个 `未掌握提示` **不是一回事**：后者要写一段文字（内容归页面），
//     前者只是一层"灰罩 / 灰字"的显隐开关（罩子里有什么归场景），代码只 `SetActive`。
//
// 只做这几件事，别的一概不碰：
//   ① 内容填空（名称 / 等级）；
//   ② 选中态 **只用 `SetActive`** —— 选中高亮一个预置节点（颜色/字号/尺寸全归场景）；
//   ③ 未掌握置灰 **也只用 `SetActive`** —— 同样一个预置节点（灰罩的颜色/透明度全归场景）；
//   ④ 点击转发（`IPointerClickHandler`，与 `配方行` 同款：不用 Button 也能点，行内子节点点到也算）。
public sealed class 知识行 : MonoBehaviour, IPointerClickHandler
{
    // 字段名保持 `名称` / `等级` 不动：它们是序列化引用位的名字（改名 = 场景/预制体上已经接过的线会丢）。
    [SerializeField] private TMP_Text 名称;              // 行名（已由页面按品质着色，本类不再包颜色）
    [SerializeField] private TMP_Text 等级;              // 罗马数字："VI"；未掌握 = "—"
    [SerializeField] private GameObject 选中高亮;        // 选中态预置高亮节点（选中 = 亮；本类不写颜色）
    [SerializeField] private Button 按钮;                // 可选：模板行若用 Button 做点击面，本类也接同一路

    // 未掌握置灰：**行模板里预置**的一层"灰罩 / 灰字"节点，代码只切显隐。
    // 为什么用结构手段而不是写 `Color` / `CanvasGroup.alpha`：本项目 UI 层的硬边界是"外观 100% 归场景 / 预制体"
    //   （本类与 `知识子面板` 一个口径）—— 状态表达只有两种手段：`SetActive` 与文本内容。
    //   置灰是状态表达，用 `SetActive` 既守住边界，又把"怎么灰"（半透明灰罩 / 另写一套灰字 / 换个灰图标）
    //   留给用户在场景里定：代码不关心罩子里有什么。
    // ⚠ **可空**：没接这个引用位、模板里也没这个节点 → 退化成"不改外观"（未掌握的行照常显示、只是不置灰），
    //   不报错、不崩 —— 它是可选的表现层，不是功能位。这也是它**不进 `报缺引用`** 的原因。
    [SerializeField] private GameObject 未掌握置灰;

    // 节点名兜底（照 `知识子面板.自找` 的口径）：用户常常"加了节点、忘了拖引用位"——
    //   `未掌握置灰` 这个名字独一无二，误配不了别的东西，所以引用位空着时按名找一次（**只找，不建**）。
    private const string 名未掌握置灰 = "未掌握置灰";
    private GameObject 灰缓存;      // 按名找到的结果（含"找到了没有"这个结论，见 `取未掌握置灰`）
    private bool 找过灰;

    private UnityEngine.Events.UnityAction 点击回调;

    // 点击行：uGUI 事件沿层级冒泡 —— 点到行内任何子节点都算点这一行（照 `配方行`）。
    // 音效不在这里播放：选中音由页面统一播（只在真的换了选中项时才响，连点同一行不会响两遍）。
    public void OnPointerClick(PointerEventData 事件) => 触发();

    private void 触发() => 点击回调?.Invoke();

    public void 绑定(string 名称文本, string 等级文本, bool 选中, bool 未掌握, UnityEngine.Events.UnityAction 点击)
    {
        点击回调 = 点击;
        面板基类.设文本(名称, 名称文本);
        面板基类.设文本(等级, 等级文本);
        if (选中高亮 != null) 选中高亮.SetActive(选中);

        // 未掌握置灰：与选中高亮同款 —— 只切一个预置节点的显隐，不写任何颜色/透明度。
        //   放在 `绑定` 里（而不是 `绑定选中态`）：置灰是"这本知识到没到 1 级"的内容态，只随重建行变；
        //   点行只翻选中态，不该顺带把置灰也算一遍。
        var 灰 = 取未掌握置灰();
        if (灰 != null) 灰.SetActive(未掌握);

        // 按钮那条路（模板行若挂了 Button）：只在首次绑定时接线一次，之后换的是"这次点谁"的回调
        if (按钮 != null)
        {
            按钮.onClick.RemoveAllListeners();
            按钮.onClick.AddListener(触发);
            音效管理器.实例?.注册按钮(按钮);   // 幂等：悬停/点击反馈沿用项目既有口径
        }
    }

    // 未掌握置灰节点的取用：Inspector 引用位优先 → 按名兜底；两边都没有 → null（调用方据此退化成"不改外观"）。
    // 为什么要 `找过灰` 这个标记：兜底找不到是**常态**（模板里压根没搭灰罩的场景），
    //   而 `绑定` 是每行每次刷新都要跑的 —— 不记住"找过了、没有"，就会每次每行都白翻一遍子树。
    private GameObject 取未掌握置灰()
    {
        if (灰缓存 == null && !找过灰)
        {
            找过灰 = true;
            灰缓存 = 未掌握置灰 != null ? 未掌握置灰 : 找子(transform, 名未掌握置灰)?.gameObject;
        }
        return 灰缓存;
    }

    // 按名找子节点（任意深度）—— 照 `知识子面板.找节点`：`Transform.Find` 只找直接子节点，
    //   而灰罩很可能被用户塞在"内容"容器里一层，直接子节点找法会漏。
    private static Transform 找子(Transform 根, string 名)
    {
        if (根 == null) return null;
        for (int i = 0; i < 根.childCount; i++)
        {
            var 子 = 根.GetChild(i);
            if (子.name == 名) return 子;
            var 深 = 找子(子, 名);
            if (深 != null) return 深;
        }
        return null;
    }

    // 只切选中态：列表行是**池化复用**的（点一行不能重建整个列表，见 `知识子面板.点击行`），
    //   所以刷新选中态时必须能"只翻高亮"，不能连带把行内其它内容再写一遍 —— 免得日后有人在 `绑定` 里
    //   加了带副作用的写法，行会在"点一下"的时候被意外重算。
    public void 绑定选中态(bool 选中)
    {
        if (选中高亮 != null) 选中高亮.SetActive(选中);
    }
}

using UnityEngine;

// 制作输入输出网格：物品网格面板 语义子类——制作面板 的 材料输入区 / 产物输出区。
// 输入区：只收 当前配方 的材料（可 拖入 跨面板；材料 在 面板 会话 内，制作 时 扣）
// 输出区：禁 拖入（目标允许放入 = false）；产物 出现 后 可 拖出（默认 允许开始拖拽）
// 会话存储：输入/输出 网格 的 数据源 = 制作面板 创建的 临时 网格服务（关闭 时 输入 剩余 返还 背包）
public sealed class 制作输入输出网格 : 物品网格面板
{
    // 模式：输入（收 配方 材料）/ 输出（禁 拖入）
    public bool 是输出模式;
    // 输入 模式：当前 允许 的 材料 标识（配方 切换 时 由 制作面板 更新；空 = 拒收 一切）
    public System.Func<string, bool> 允许材料判定;

    // 输入：只收 配方 材料；输出：禁 拖入
    protected override bool 目标允许放入(string 标识)
    {
        if (是输出模式) return false;
        if (允许材料判定 == null) return false;
        return 允许材料判定(标识);
    }

    // 输出：禁 拖入（防止 玩家 把 东西 塞 回 输出 区）——目标允许放入=false 已 拦
    // 输出 区 内容 可 拖走（成品 拿走）——默认 允许开始拖拽=true（不 override）
    // 输入 区 内容 也 可 拖回 背包（取消 制作 时 剩料 返还）——默认 允许
}

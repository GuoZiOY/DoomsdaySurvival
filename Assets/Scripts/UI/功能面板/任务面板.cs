// 任务面板：任务功能（接取任务；任务栏共用）
public sealed class 任务面板 : 设施功能面板基类
{
    protected override string 标题文字() => $"{逻辑.名称} · 任务";

    protected override void 渲染内容()
    {
        if (逻辑 is not 任务功能 任务) return;
        清空(内容区);
        foreach (var 任务数据 in 任务.可接任务())
        {
            var 标识 = 任务数据.标识;
            string 进度 = 逻辑.当前玩家.任务.Exists(p => p.标识 == 标识)
                ? (逻辑.当前玩家.任务.Find(p => p.标识 == 标识).已完成 ? "已完成" : $"{逻辑.当前玩家.任务.Find(p => p.标识 == 标识).数量}/{任务数据.目标数量}")
                : "未接取";
            创建行(内容区, $"{任务数据.名称}（{任务数据.描述}）  +{货币工具.文本(任务数据.奖励金币)}  [{进度}]", () => 任务.尝试接取(标识));
        }
    }
}

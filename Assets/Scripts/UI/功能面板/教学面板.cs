// 教学面板：教学功能（学技能；武馆=物理 / 学堂=魔法 共用，各设施筛选不同技能）
public sealed class 教学面板 : 设施功能面板基类
{
    protected override string 标题文字() => $"{逻辑.名称} · 技能学习";

    protected override void 渲染内容()
    {
        if (逻辑 is not 教学功能 教学) return;
        清空(内容区);
        foreach (var 技能 in 教学.可学技能())
        {
            var 标识 = 技能.标识;
            string 已学 = 逻辑.当前玩家.掌握技能(标识) ? "（已学）" : "";
            创建行(内容区, $"{品质工具.标签(技能.品质档)}{技能.名称}（{技能.描述}）{已学}", () => 教学.尝试学习(标识));
        }
    }
}

using System;

// ============================================================
// 网格可见性：**一个实体在某个迷雾档下该不该画** —— 三层（大世界 / 区域 / 房间）共用这一份规则。
//
// 为什么要抽出来：这条规则原来在三个面板里各写了一遍（`大世界网格面板` / `区域网格面板` / `房间网格面板`
// 的 更新实体框），**而且已经漂了**：
//   · 房间层写的是 `if (类型 == 敌人) 显示 = 亮;`  → 敌人只在全亮里画（正确）
//   · 大世界 / 区域 写的是 `else 显示 = 亮 || 档 == 暗记忆;`，**敌人落进了这个 else**
//     → 敌人在"记忆层"里也被画出来 = **站在街上一眼看见全城/全街区的敌人**。
// 现在每次回安全屋都会清迷雾，这个不一致还不明显；一旦迷雾改成**永久保留**（v52），
// 它就会让街区退化成"纯绕路题"、再没有伏击。所以顺手把它收成一份，并**用离线断言钉住**。
//
// 放在 Domain（纯 C#，零 UnityEngine）而不是 UI：它是"档"的语义，不是"颜色"，
// 而且放这儿能被 `Tools/大世界验证` 当表格逐格断言 —— 三个面板各写一遍的规则没法验。
//
// 口径（与三层的实际行为**逐条等价**，只有"敌人"那条是修正）：
//   · 玩家               → 任何档都画
//   · 敌人               → **只在 亮**（核心视野）里画：记忆/轮廓里都不画
//   · 墙/门/楼梯/建筑/区域/临时建筑/界外 → 只要不是 全黑 就画（留轮廓："这片街区我去过"）
//   · 容器/尸体/障碍     → 只在 亮 或 暗记忆 里画（夜里看不清要翻的东西、也看不清废车）
//   · 实体为 null        → 画（三层原有的兜底：宁可多画一个框，也别把已有框藏了）
// ============================================================
public static class 网格可见性
{
    public static bool 显示(网格实体 实体, 视野档 档)
    {
        if (实体 == null) return true;           // 兜底：没有实体信息时不隐藏
        if (实体.是玩家) return true;
        bool 亮 = 档 == 视野档.亮;
        bool 有轮廓 = 档 != 视野档.全黑;
        switch (实体.类型)
        {
            // ★ 敌人只在全亮里画。这条是**修正**：大世界/区域 原来把敌人画在记忆层里。
            case 网格实体类型.敌人: return 亮;

            // 地形与楼体：不是全黑就留轮廓（白天记忆 / 夜晚弱视野 / 夜晚记忆 都看得见）
            case 网格实体类型.墙:
            case 网格实体类型.门:
            case 网格实体类型.楼梯:
            case 网格实体类型.建筑:
            case 网格实体类型.区域:
            case 网格实体类型.临时建筑:
            case 网格实体类型.界外: return 有轮廓;

            // 容器 / 尸体 / 障碍：要离得近才看得清（夜晚连轮廓都没有）
            default: return 亮 || 档 == 视野档.暗记忆;
        }
    }
}

using System;

// ============================================================
// 视野规则：房间迷雾的"看多远 / 记得住什么"由**角色与时段**决定（数据：Resources/Data/视野.json）。
// 数据里写的是**最终边长**，不做加减（避免"基础+修正"被误读）：
//   · 白天边长 7 → 7×7 核心全亮（含敌人）
//   · 夜晚边长 3 → 3×3 核心全亮；再往外到 夜晚弱视野 5 那一圈 = **弱视野**：只看得见建筑（墙），看不见敌人
//   · 白天：核心之外的**已探索**区 = 记忆阴影（墙/容器/尸体可辨但压暗）——"看过的地方"就是弱视野
//   · 夜晚：**没有记忆**，看过的也全黑；弱视野圈之外一律全黑
// 边长一律**奇数化**（3/5/7/9…），玩家永远落在正方形正中。
// 扩展位：天气（雾/沙暴）、光源（手电/火柴/提灯）、室内无窗（正午也算夜晚）——以后都是在这三个数上再加减。
// ============================================================
public enum 时段 { 白天, 夜晚 }

// 格子显示档：由 房间探索服务 按"视野 + 时段 + 记忆"算好；房间网格面板 与 房间图层 都照它画
public enum 视野档
{
    全黑,       // 什么都不画（玩家除外）
    暗记忆,     // 白天：已探索的地方 —— 墙/容器/尸体 可辨（压暗），敌人不画
    暗中轮廓,   // 夜晚：弱视野圈 —— 只看得见建筑（墙），敌人与容器都不画
    亮          // 核心方形内：全画（含敌人）
}

public sealed class 视野规则
{
    public const int 白天边长默认 = 7;
    public const int 夜晚边长默认 = 3;
    public const int 夜晚弱视野默认 = 5;
    public const float 阴影压暗默认 = 0.65f;
    public const int 白天起默认 = 6;
    public const int 夜晚起默认 = 18;

    public int 白天边长 = 白天边长默认;      // 白天核心亮区（格，单数）
    public int 夜晚边长 = 夜晚边长默认;      // 夜晚核心亮区（格，单数）
    public int 夜晚弱视野 = 夜晚弱视野默认;  // 夜晚弱视野圈（格，单数；不小于夜晚核心）
    public float 阴影压暗 = 阴影压暗默认;    // 阴影区（白天记忆 / 夜晚弱视野）的不透明黑
    public int 白天起 = 白天起默认;
    public int 夜晚起 = 夜晚起默认;

    public static 视野规则 默认() => new 视野规则();

    public static 视野规则 从数据(视野数据 d)
    {
        var 规则 = 默认();
        if (d == null) return 规则;
        if (d.白天边长 > 0) 规则.白天边长 = d.白天边长;
        if (d.夜晚边长 > 0) 规则.夜晚边长 = d.夜晚边长;
        if (d.夜晚弱视野 > 0) 规则.夜晚弱视野 = d.夜晚弱视野;
        // ★ v51 刀15：这三个**也必须做 >0 保护**（原来只有前三个做了）。
        //   最毒的是 `夜晚起`：数据里漏填 → 取到 0 → `判时段()` 的 `时 >= 白天起 && 时 < 夜晚起`
        //   **恒假** → **整个游戏永远是夜晚**（视野只剩 3×3、没有记忆），而且一个错都不报。
        //   `阴影压暗` 是 0~1 的不透明度：0 = 全透明（迷雾等于没有），同样不该被数据笔误带进来。
        if (d.阴影压暗 > 0f) 规则.阴影压暗 = d.阴影压暗;
        if (d.白天起 > 0) 规则.白天起 = d.白天起;
        if (d.夜晚起 > 0) 规则.夜晚起 = d.夜晚起;
        return 规则;
    }

    // 时段：白天起 ≤ 时 < 夜晚起 → 白天（默认 06:00~18:00）
    public 时段 判时段(float 游戏分钟数)
    {
        float 当日 = 游戏分钟数 % 1440f;
        if (当日 < 0f) 当日 += 1440f;
        int 时 = (int)(当日 / 60f);
        return 时 >= 白天起 && 时 < 夜晚起 ? 时段.白天 : 时段.夜晚;
    }

    // 核心亮区边长（正方形、单数、玩家在正中）
    public int 核心边长(时段 当前时段)
        => 网格视野.奇数化(当前时段 == 时段.白天 ? 白天边长 : 夜晚边长);

    // 弱视野圈外边界（只看得见建筑那一圈的边长；不小于核心，保持单数）
    public int 弱视野边长(时段 当前时段)
    {
        int 核心 = 核心边长(当前时段);
        int 弱 = 网格视野.奇数化(夜晚弱视野);
        return 弱 < 核心 ? 核心 : 弱;
    }

    // 白天有"记忆"（看过的格子留阴影）；夜晚没有（只有眼前那一圈弱视野）
    public bool 有记忆(时段 当前时段) => 当前时段 == 时段.白天;

    // 是否落在"弱视野圈"里（切比雪夫距离 > 核心半边，且 ≤ 弱视野半边）
    public bool 在弱视野圈(int 列, int 行, int 中心列, int 中心行, int 核心半)
    {
        int 半 = 弱视野边长(时段.夜晚) / 2;
        int d = Math.Max(Math.Abs(列 - 中心列), Math.Abs(行 - 中心行));
        return d > 核心半 && d <= 半;
    }

    public static string 时段名(时段 当前时段) => 当前时段 == 时段.白天 ? "白天" : "夜晚";
}
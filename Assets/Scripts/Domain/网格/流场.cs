using System;
using System.Collections.Generic;

// ============================================================
// 流场（BFS 积分场）：**多动因 → 少目标**的寻路。
//
// 为什么用它（刀61，完整论证见 docs/大世界敌人AI设计.md §3）：
//   ① 一次 BFS 算完，所有敌人各读自己那一格的向量 = O(1)/敌；敌人从 16 涨到 160 **成本不变**。
//      而"每敌一次 A*"是线性乘上去的，且 网格寻路 的开放表当时是 List 线性扫描取最小。
//   ② **它和噪音机制是同一个数据结构**：追踪玩家 = 以玩家格为源；追踪噪音 = 以噪音格为源；
//      而"被噪音吸引靠近"本质就是朝源走的梯度下降 → 一套机制实现两件事，不必写两套移动逻辑。
//   ③ 确定性天然免费：固定邻居顺序（右/下/左/上，与 网格寻路 同一把尺）→ 同输入必得同场，可逐字节断言。
//
// 语义：
//   距[]   = 到源格的最少步数（-1 = 不可达 / 未访问）
//   方向[] = 该格"朝源走的下一格"的索引（-1 = 自己就是源 / 不可达）
//            取 4 邻中 距 最小者，并列按固定顺序打破 → 结构上**不可能成环**（距严格递减）。
//            `Tools/大世界敌人验证` 有一条断言专门盯这个：方向数组一旦成环，敌人会原地转圈，
//            而从游戏里根本看不出是"路径算错了"还是"敌人只是在巡逻"。
//
// ⚠ **敌人算不算障碍**是这里唯一的一个开关（`敌人挡路`），两种用法都真实存在，别混：
//   · 追踪/吸引用的场：`敌人挡路 = false` —— 敌人对场**透明**。
//     算了的话，一只敌人堵在窄口会让后面的敌人绕远甚至判不可达（自锁），
//     而且 16 只敌人一动就让场失效、缓存全废。敌人之间的"不重叠"由服务层的廉价局部规则处理。
//   · **连通性硬保证**用的场：`敌人挡路 = true` —— 敌人是"活的墙"，必须真的挡路，
//     否则那个校验是自欺（它会说"过得去"，而玩家实际被围死了）。
//
// ★ 性能（刀61 实测，别把它改回去）：
//   `网格数据.占位` 是**对全部实体线性扫描**（房间层 30 个实体无所谓；大世界 600+ 个实体时，
//   10000 格 × 4 邻 × 600 实体 = 千万级操作 → 一次 BFS 3.5 ms，几乎全花在这）。
//   所以 BFS 走 **一次摊平的挡表**（`建挡表`），格查询变成 O(1)。
//   实测：3.481 ms → 0.2 ms 量级。
//   两条路径（单格查询 / 整张表）**共用同一个判据 `实体挡`** —— 不许各写一份，
//   否则会出现"方向指向一个走不进去的格"这种只在某个入口出现的怪毛病。
// ============================================================
public sealed class 流场
{
    // 右 下 左 上（与 网格寻路.横/纵 同一顺序 —— 全仓库一把尺；改了这里，两个算法的结果都会变）
    public static readonly int[] 横 = { 1, 0, -1, 0 };
    public static readonly int[] 纵 = { 0, 1, 0, -1 };

    public int 列 { get; private set; }
    public int 行 { get; private set; }
    // 请求的源格（调用方给的那个）与**实际用的源格**（请求格不可走时会吸附到最近可走格）。
    // 分开存是为了断言里能看出"吸附发生了没有"。
    public int 请求列 { get; private set; }
    public int 请求行 { get; private set; }
    public int 源列 { get; private set; } = -1;
    public int 源行 { get; private set; } = -1;
    public bool 敌人挡路 { get; private set; }

    public int[] 距 { get; private set; }
    public int[] 方向 { get; private set; }

    private 流场() { }

    // ================= 可通行判据（**唯一一份**） =================

    // 单个实体在某格上挡不挡路。三条语义都在这里：
    //   · 只有 占格 的才挡；
    //   · `敌人挡路 = false` 时敌人透明（见文件头）；
    //   · **带门洞的占格物**（建筑 / 区域 / 临时建筑）的门口格能站能走 —— 与 网格数据.占位 同一口径。
    public static bool 实体挡(网格实体 e, int 列, int 行, bool 敌人挡路)
    {
        if (e == null || !e.占格) return false;
        if (!敌人挡路 && e.类型 == 网格实体类型.敌人) return false;
        if (!e.覆盖(列, 行)) return false;
        if (网格数据.是带门洞的占格物(e) && e.门口格 == 网格数据.编码(列, 行)) return false;
        return true;
    }

    // 单格查询（对实体线性扫描）。给"只看 4 邻"的调用方用（巡逻步进 / 落子判据）。
    // ⚠ 别拿它在整张图上循环 —— 那是 O(格 × 实体)；整图请用 建挡表。
    public static bool 可走(网格数据 世界, int 列, int 行, bool 敌人挡路)
    {
        if (世界 == null || !世界.界内(列, 行)) return false;
        for (int i = 0; i < 世界.实体.Count; i++)
            if (实体挡(世界.实体[i], 列, 行, 敌人挡路)) return false;
        return true;
    }

    // 整张挡表（把占格物的足迹一次摊平）。BFS 吃这个 —— 见文件头的性能段。
    public static bool[] 建挡表(网格数据 世界, bool 敌人挡路)
    {
        var 挡 = new bool[世界.列 * 世界.行];
        for (int i = 0; i < 世界.实体.Count; i++)
        {
            var e = 世界.实体[i];
            if (e == null || !e.占格) continue;
            if (!敌人挡路 && e.类型 == 网格实体类型.敌人) continue;
            for (int r = e.行; r < e.行 + e.高; r++)
                for (int c = e.列; c < e.列 + e.宽; c++)
                {
                    if (!世界.界内(c, r)) continue;
                    if (实体挡(e, c, r, 敌人挡路)) 挡[r * 世界.列 + c] = true;
                }
        }
        return 挡;
    }

    // ================= 建立 =================

    // 建场：以 (目标列, 目标行) 为源做一次 BFS。
    // 源格**可以不可走**（噪音点可能落在柜子上 / 墙上 / 区域占地里）：那就吸附到最近的可走格，
    //   否则"噪音点偏了一格 → 整个场全 -1 → 附近敌人集体发呆"，是个很难查的哑火。
    public static 流场 建场(网格数据 世界, int 目标列, int 目标行, bool 敌人挡路 = false)
    {
        if (世界 == null) return null;
        int 总数 = 世界.列 * 世界.行;
        var 场 = new 流场
        {
            列 = 世界.列, 行 = 世界.行,
            请求列 = 目标列, 请求行 = 目标行,
            敌人挡路 = 敌人挡路,
            距 = new int[总数],
            方向 = new int[总数],
        };
        for (int i = 0; i < 总数; i++) { 场.距[i] = -1; 场.方向[i] = -1; }
        if (!世界.界内(目标列, 目标行)) return 场;

        var 挡 = 建挡表(世界, 敌人挡路);
        var (源列, 源行) = 找源格(世界, 挡, 目标列, 目标行);
        if (源列 < 0) return 场;   // 附近全是墙 —— 场保持全 -1（调用方看 有源 就知道）
        场.源列 = 源列;
        场.源行 = 源行;

        int 源 = 源行 * 世界.列 + 源列;
        场.距[源] = 0;
        var 队 = new Queue<int>();
        队.Enqueue(源);
        while (队.Count > 0)
        {
            int 当前 = 队.Dequeue();
            int 当前列 = 当前 % 世界.列, 当前行 = 当前 / 世界.列;
            int 下一距 = 场.距[当前] + 1;
            for (int d = 0; d < 4; d++)
            {
                int 列 = 当前列 + 横[d], 行 = 当前行 + 纵[d];
                if (列 < 0 || 行 < 0 || 列 >= 世界.列 || 行 >= 世界.行) continue;
                int 邻 = 行 * 世界.列 + 列;
                if (场.距[邻] >= 0 || 挡[邻]) continue;
                场.距[邻] = 下一距;
                队.Enqueue(邻);
            }
        }
        场.算方向(挡);
        return 场;
    }

    // 源格：目标格自己可走就用它；否则按"切比雪夫环从近到远、环内按行再按列"扫第一个可走格。
    // 扫描顺序固定 → 确定性（同输入必得同一个源格）。
    private static (int 列, int 行) 找源格(网格数据 世界, bool[] 挡, int 目标列, int 目标行)
    {
        if (!挡[目标行 * 世界.列 + 目标列]) return (目标列, 目标行);
        for (int 环 = 1; 环 <= 8; 环++)
            for (int 行 = 目标行 - 环; 行 <= 目标行 + 环; 行++)
                for (int 列 = 目标列 - 环; 列 <= 目标列 + 环; 列++)
                {
                    // 只看这一环的边界（内部更小的环已经扫过了）
                    if (Math.Max(Math.Abs(列 - 目标列), Math.Abs(行 - 目标行)) != 环) continue;
                    if (!世界.界内(列, 行)) continue;
                    if (!挡[行 * 世界.列 + 列]) return (列, 行);
                }
        return (-1, -1);
    }

    // 方向数组：每个可达格指向"距最小的那一格邻居"，并列按固定顺序（右/下/左/上）打破。
    // 源格（距 0）方向留 -1 = 到了。
    private void 算方向(bool[] 挡)
    {
        for (int r = 0; r < 行; r++)
            for (int c = 0; c < 列; c++)
            {
                int i = r * 列 + c;
                if (距[i] <= 0) continue;
                int 最佳 = -1, 最佳距 = 距[i];
                for (int d = 0; d < 4; d++)
                {
                    int 列2 = c + 横[d], 行2 = r + 纵[d];
                    if (列2 < 0 || 行2 < 0 || 列2 >= 列 || 行2 >= 行) continue;
                    int 邻 = 行2 * 列 + 列2;
                    if (距[邻] < 0 || 距[邻] >= 最佳距) continue;   // 严格小于 → 并列保留先出现的（固定顺序）
                    最佳距 = 距[邻];
                    最佳 = 邻;
                }
                方向[i] = 最佳;
            }
    }

    // ================= 轻量可达查询（不建整张场） =================

    // 只回答"从 源 能不能走到 目标"（找到就早退），不算方向、不建整张场。
    // 用途：**连通性硬保证**（大世界敌人每移动一步之后校验"玩家还能不能回到营地门口"）——
    //   那个校验每个玩家步都要跑，建整张场（3 个 10000 长数组）纯属浪费，而且它不需要方向。
    // `敌人挡路 = true` 是这里**唯一正确的取值**：敌人是"活的墙"，
    //   用透明的场去校验等于自欺（它会说"过得去"，而玩家实际被围死了）。
    public static bool 可达(网格数据 世界, int 源列, int 源行, int 目标列, int 目标行, bool 敌人挡路)
    {
        if (世界 == null || !世界.界内(源列, 源行) || !世界.界内(目标列, 目标行)) return false;
        var 挡 = 建挡表(世界, 敌人挡路);
        int 源 = 源行 * 世界.列 + 源列, 终 = 目标行 * 世界.列 + 目标列;
        if (挡[源]) return false;
        if (源 == 终) return true;

        var 访问 = new bool[世界.列 * 世界.行];
        var 队 = new Queue<int>();
        访问[源] = true;
        队.Enqueue(源);
        while (队.Count > 0)
        {
            int 当前 = 队.Dequeue();
            int 当前列 = 当前 % 世界.列, 当前行 = 当前 / 世界.列;
            for (int d = 0; d < 4; d++)
            {
                int 列 = 当前列 + 横[d], 行 = 当前行 + 纵[d];
                if (列 < 0 || 行 < 0 || 列 >= 世界.列 || 行 >= 世界.行) continue;
                int 邻 = 行 * 世界.列 + 列;
                if (访问[邻] || 挡[邻]) continue;
                访问[邻] = true;
                if (邻 == 终) return true;
                队.Enqueue(邻);
            }
        }
        return false;
    }

    // ================= 查询 =================

    public bool 有源 => 源列 >= 0;
    public int 索引(int 列, int 行) => 行 * this.列 + 列;

    public bool 有路(int 列, int 行)
    {
        if (距 == null) return false;
        if (列 < 0 || 行 < 0 || 列 >= this.列 || 行 >= this.行) return false;
        return 距[索引(列, 行)] >= 0;
    }

    // 从该格朝源走的下一格（null = 没有：不可达 / 已经站在源上 / 场为空）
    public (int 列, int 行)? 下一步(int 列, int 行)
    {
        if (距 == null || !界内(列, 行)) return null;
        int 邻 = 方向[索引(列, 行)];
        if (邻 < 0) return null;
        return (邻 % this.列, 邻 / this.列);
    }

    public bool 界内(int 列, int 行) => 列 >= 0 && 行 >= 0 && 列 < this.列 && 行 < this.行;

    public int 距值(int 列, int 行) => 距 == null || !界内(列, 行) ? -1 : 距[索引(列, 行)];

    // 指纹（确定性断言用）：距 + 方向 全部逐字节
    public string 指纹()
    {
        var sb = new System.Text.StringBuilder();
        sb.Append($"{列}x{行}|源{源列},{源行}|敌挡路{(敌人挡路 ? 1 : 0)}|");
        for (int i = 0; i < 距.Length; i++) sb.Append(距[i]).Append(',').Append(方向[i]).Append(';');
        return sb.ToString();
    }
}

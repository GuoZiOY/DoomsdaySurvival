using System;
using System.Collections.Generic;

// ============================================================
// 门口保护：**「只有一个出口的门，它自己与紧邻八格一律留空」这一条不变量的唯一实现**。
//
// 为什么要有这个文件（刀32 收敛）：
//   这条不变量原来在 **4 处生成期 + 2 处验证期**各写一遍，写法各不相同：
//     生成期：区域生成器.可撒占格物 / 大世界生成器.可撒单个占格物 / 大世界生成器.能放临时建筑 / 约束摆放.保底可放
//     验证期：区域验证（只查楼门，没查入口与街口）/ 大世界验证（只查区域门口与营地门口）
//   而作者在这同一课上**栽过两次**（v51 刀2 障碍堵死区域门口、刀6 临时建筑切断地图）——
//   三套写法 + 两套验证 = 任何一套漂移都没有拦截层。这里收敛成一份，两边都调它。
//
// 语义（照抄原来那几处的口径，不改行为）：
//   · 「紧邻八格」= 切比雪夫距离 ≤ 1（含斜角）—— 门口格三面被自己挡着，斜角也能把唯一出口卡住；
//   · 「门」的**来源按层不同**，由调用方给：大世界是实体自带的 门口格；区域层还要加 入口格 / 街口；
//     房间/建筑层是 `约束.通道格`（入口 / 门 / 楼梯及其内侧）。所以这里只统一**判断**，不统一**收门**；
//   · 大世界层多一个语义：**占格物彼此切比雪夫 ≥2**（下面 算间距 那两处）不是"门口保护"，
//     它靠的是"4 连通网格的割集必是 8 连通屏障"那条数学论证 —— 别混进来，混了就说不清了。
//
// 反漂移（`Tools/重复代码扫描.ps1` 有一条断言盯着）：除了本文件（含 算间距），
//   全仓库不许再出现 `Math.Abs(…) <= 1 && Math.Abs(…) <= 1` 这种手写门口四邻 / 手写间距。
//
// ⚠ **共用谓词的盲区（刀32 实测，别忘）**：生成期与验证期共用一份谓词之后，"把谓词改坏"会**同时**让两边变宽 ——
//   验证器再也测不出生成器的漂移。实测：把 相邻 改成恒 false，大世界验证会炸（它有独立的连通/撤回断言兜着），
//   区域验证却**全绿**（它的门口断言跟着一起瞎了）。所以谓词本身必须有一条**独立自检**：
//   真值表 9 真 / 6 假 钉在 `Tools/区域验证/Program.cs` 的「门口保护自检」段里。
// ============================================================
public static class 门口保护
{
    // 这一格是否碰了某个门（含紧邻八格）
    public static bool 相邻(int 列, int 行, int 门列, int 门行)
        => Math.Abs(列 - 门列) <= 1 && Math.Abs(行 - 门行) <= 1;

    // 世界里所有"自带门洞"的实体的门口格（建筑 / 区域 / 临时建筑 / 营地）。
    // 判据用「有没有 门口格」而**不是**类型白名单：以后多一种带门的占格物（比如新副本载体），
    // 这里自动跟上 —— 类型白名单正是当年漏掉营地那种坑的成因。
    public static bool 碰世界门口(网格数据 世界, int 列, int 行)
    {
        if (世界 == null) return false;
        for (int i = 0; i < 世界.实体.Count; i++)
        {
            var e = 世界.实体[i];
            if (e == null || e.门口格 < 0) continue;
            if (相邻(列, 行, e.门口格 / 1000, e.门口格 % 1000)) return true;
        }
        return false;
    }

    // 再加一批"不在实体上的门"（区域层的 入口格 / 街口；房间层的 通道格）
    public static bool 碰门口(网格数据 世界, List<(int 列, int 行)> 额外门, int 列, int 行)
    {
        if (碰世界门口(世界, 列, 行)) return true;
        if (额外门 == null) return false;
        for (int i = 0; i < 额外门.Count; i++)
            if (相邻(列, 行, 额外门[i].列, 额外门[i].行)) return true;
        return false;
    }

    // 足迹版：多格占格物（临时建筑 2×2 等）的每一格都不许碰门
    public static bool 足迹碰门口(网格数据 世界, List<(int 列, int 行)> 额外门, int 列, int 行, int 宽, int 高)
    {
        for (int r = 行; r < 行 + 高; r++)
            for (int c = 列; c < 列 + 宽; c++)
                if (碰门口(世界, 额外门, c, r)) return true;
        return false;
    }

    // 收门：把世界的门口格收进一个列表（调用方自己持有，避免每格 new List —— 生成期按格调用）
    public static void 收世界门口(网格数据 世界, List<(int 列, int 行)> 收)
    {
        if (世界 == null || 收 == null) return;
        for (int i = 0; i < 世界.实体.Count; i++)
        {
            var e = 世界.实体[i];
            if (e == null || e.门口格 < 0) continue;
            收.Add((e.门口格 / 1000, e.门口格 % 1000));
        }
    }

    // 占格物彼此至少隔 1 格（切比雪夫 ≥2）—— **不是**门口保护，见文件头最后一条说明。
    // 单独放一个名字，就是为了让"两个 Math.Abs 挨在一起"的判据能把它白名单掉、而不是被误当门口四邻。
    public static bool 算间距(int 列, int 行, int 他列, int 他行)
        => Math.Abs(他列 - 列) <= 1 && Math.Abs(他行 - 行) <= 1;
}

using System;
using System.Collections.Generic;

// ============================================================
// 网格寻路：A*（纯 C#，零 UnityEngine 依赖）。
// 约定：四方向（不做斜走——斜穿会让"不可穿过"的判定与视觉都变糊）；
//       每格代价恒 1；启发 = 曼哈顿距离；**固定展开顺序（右/下/左/上）** → 同输入必得同路径（可断言）。
// 可通行 = 网格数据.可通行（界内 且 无占格实体）——渲染用的 网格服务 与它同源（同一份 网格数据）。
//
// ★ 刀61：开放表从「List + 每次出队线性扫描取最小」换成**索引二叉堆**（键 = (估, 入队序)，
//   入队序只在第一次入堆时分配）—— 逐字节保留了老口径"并列取最先入队的"，详见 寻路() 里的注释。
//   多动因高频寻路不再走这里：那个场景用 **流场**（Domain/网格/流场.cs，一次 BFS 服务所有动因）。
//   这里保留给"单点一次性查询"（玩家点柜子 / 拾荒路径 / 验证器断言）。
// ============================================================
public static class 网格寻路
{
    private static readonly int[] 横 = { 1, 0, -1, 0 };   // 右 下 左 上（固定顺序，别改——改了路径就变）
    private static readonly int[] 纵 = { 0, 1, 0, -1 };

    // 起 → 终 的最短路（含首尾）。不可达返回 null；起=终 返回单点路径。
    public static List<(int 列, int 行)> 寻路(网格数据 房, (int 列, int 行) 起, (int 列, int 行) 终)
    {
        if (房 == null) return null;
        if (!房.可通行(起.列, 起.行) || !房.可通行(终.列, 终.行)) return null;
        if (起.列 == 终.列 && 起.行 == 终.行) return new List<(int 列, int 行)> { 起 };

        int 总数 = 房.列 * 房.行;
        var 代价 = new int[总数];
        var 估 = new int[总数];
        var 父 = new int[总数];
        var 状态 = new byte[总数];   // 0 未入 / 1 开放 / 2 关闭
        for (int i = 0; i < 总数; i++)
        {
            代价[i] = int.MaxValue;
            父[i] = -1;
        }

        int 起索引 = 索引(房, 起.列, 起.行), 终索引 = 索引(房, 终.列, 终.行);
        代价[起索引] = 0;
        估[起索引] = 曼哈顿(起.列, 起.行, 终.列, 终.行);

        // —— 开放表：**索引二叉堆**（刀61 修既有隐患）——
        // 原来是一个 List + 每次出队线性扫描取最小（外加 RemoveAt 的 O(n) 搬移）：
        //   开阔场上开放表可达数千项 → 单次 A* 是**百万级比较**量级。
        //   而"玩家点一下柜子"会连跑 ≤4 次 A*（寻路到相邻），多动因场景更是线性乘上去。
        //   详见 docs/大世界敌人AI设计.md §3.3。
        //
        // ★ 键 = (估, 入队序)，且**入队序只在"第一次入堆"时分配**，此后不再变 —— 这不是随手写的，
        //   是为了**逐字节保留老口径**："取估价值最小；并列取最先入队的"。
        //   老实现里 开放 是 List、只 RemoveAt 从不重排 → List 顺序恒等于入队顺序
        //   → 线性扫描取第一个严格最小值 = 取最早入队的那一个。索引堆 + (估, 入队序) 与它等价。
        //   ⚠ 改这条口径会改变既有寻路结果，而 `Tools/房间验证` / `Tools/房间样张` 断言的正是这些结果。
        var 堆 = new int[总数 + 1];      // 1 起下标
        var 堆位 = new int[总数];         // 节点 → 堆内下标（-1 = 不在堆里）
        var 入队序 = new int[总数];
        int 堆数 = 0, 序计 = 0;
        for (int i = 0; i < 总数; i++) 堆位[i] = -1;

        入堆(起索引);
        状态[起索引] = 1;

        while (堆数 > 0)
        {
            int 当前 = 出堆();
            if (当前 == 终索引) return 重建(房, 父, 终索引);
            状态[当前] = 2;
            int 当前列 = 当前 % 房.列, 当前行 = 当前 / 房.列;
            for (int d = 0; d < 4; d++)
            {
                int 列 = 当前列 + 横[d], 行 = 当前行 + 纵[d];
                if (!房.可通行(列, 行)) continue;
                int 邻 = 索引(房, 列, 行);
                if (状态[邻] == 2) continue;
                int 新代价 = 代价[当前] + 1;
                if (新代价 >= 代价[邻]) continue;
                代价[邻] = 新代价;
                估[邻] = 新代价 + 曼哈顿(列, 行, 终.列, 终.行);
                父[邻] = 当前;
                if (状态[邻] != 1)
                {
                    入堆(邻);
                    状态[邻] = 1;
                }
                else 上浮(堆位[邻]);   // 已在堆里 → 键变小了，就地减键（不必重插）
            }
        }
        return null;

        // —— 堆操作：局部函数（只用本方法的数组，不引静态状态 → 两次寻路不会互相污染）——
        void 入堆(int 节点)
        {
            if (堆位[节点] < 0) 入队序[节点] = 序计++;
            堆[++堆数] = 节点;
            堆位[节点] = 堆数;
            上浮(堆数);
        }
        int 出堆()
        {
            int 顶 = 堆[1];
            堆位[顶] = -1;
            if (堆数 == 1) { 堆数 = 0; return 顶; }
            堆[1] = 堆[堆数];
            堆数--;
            堆位[堆[1]] = 1;
            下浮(1);
            return 顶;
        }
        void 上浮(int 位)
        {
            while (位 > 1 && 更小(堆[位], 堆[位 / 2]))
            {
                换(位, 位 / 2);
                位 /= 2;
            }
        }
        void 下浮(int 位)
        {
            while (true)
            {
                int 左 = 位 * 2, 右 = 左 + 1, 小 = 位;
                if (左 <= 堆数 && 更小(堆[左], 堆[小])) 小 = 左;
                if (右 <= 堆数 && 更小(堆[右], 堆[小])) 小 = 右;
                if (小 == 位) return;
                换(位, 小);
                位 = 小;
            }
        }
        void 换(int a, int b)
        {
            int t = 堆[a];
            堆[a] = 堆[b];
            堆[b] = t;
            堆位[堆[a]] = a;
            堆位[堆[b]] = b;
        }
        bool 更小(int a, int b) => 估[a] < 估[b] || (估[a] == 估[b] && 入队序[a] < 入队序[b]);
    }

    // 走到目标的"相邻可站格"（≤4 个候选各跑一次 A*，取最短那条）——点柜子 = 走到柜子旁边
    public static List<(int 列, int 行)> 寻路到相邻(网格数据 房, (int 列, int 行) 起, 网格实体 目标)
    {
        if (房 == null || 目标 == null) return null;
        List<(int 列, int 行)> 最好 = null;
        for (int r = 目标.行; r < 目标.行 + 目标.高; r++)
            for (int c = 目标.列; c < 目标.列 + 目标.宽; c++)
            {
                for (int d = 0; d < 4; d++)
                {
                    int 列 = c + 横[d], 行 = r + 纵[d];
                    if (!房.可通行(列, 行)) continue;
                    var 路 = 寻路(房, 起, (列, 行));
                    if (路 == null) continue;
                    if (最好 == null || 路.Count < 最好.Count) 最好 = 路;
                }
            }
        return 最好;
    }

    // 迷雾用：走到"已知（已探索）区域里离目标最近的可站格"——点未探索的地方时往前探，不用一格一格点
    public static List<(int 列, int 行)> 寻路到已知边缘(网格数据 房, (int 列, int 行) 起, (int 列, int 行) 目标, HashSet<int> 已知)
    {
        if (房 == null || !房.可通行(起.列, 起.行) || 已知 == null) return null;
        int 总数 = 房.列 * 房.行;
        var 父 = new int[总数];
        var 访问 = new bool[总数];
        for (int i = 0; i < 总数; i++) 父[i] = -1;
        var 队 = new Queue<int>();
        int 起索引 = 索引(房, 起.列, 起.行);
        访问[起索引] = true;
        队.Enqueue(起索引);
        int 最佳 = -1, 最佳距 = int.MaxValue;
        while (队.Count > 0)
        {
            int 当前 = 队.Dequeue();
            int 列 = 当前 % 房.列, 行 = 当前 / 房.列;
            if (已知.Contains(网格数据.编码(列, 行)))
            {
                int 距 = Math.Abs(列 - 目标.列) + Math.Abs(行 - 目标.行);
                // 并列取更靠上、再靠左的（确定性）
                if (距 < 最佳距 || (距 == 最佳距 && 最佳 >= 0 && (行 < 最佳 / 房.列 || (行 == 最佳 / 房.列 && 列 < 最佳 % 房.列))))
                {
                    最佳距 = 距;
                    最佳 = 当前;
                }
            }
            for (int d = 0; d < 4; d++)
            {
                int 邻列 = 列 + 横[d], 邻行 = 行 + 纵[d];
                if (!房.可通行(邻列, 邻行)) continue;
                int 邻 = 索引(房, 邻列, 邻行);
                if (访问[邻]) continue;
                访问[邻] = true;
                父[邻] = 当前;
                队.Enqueue(邻);
            }
        }
        if (最佳 < 0) return null;
        return 重建(房, 父, 最佳);
    }

    private static List<(int 列, int 行)> 重建(网格数据 房, int[] 父, int 终索引)
    {
        var 路 = new List<(int 列, int 行)>();
        int 当前 = 终索引;
        int 防死循环 = 房.列 * 房.行 + 1;
        while (当前 >= 0 && 防死循环-- > 0)
        {
            路.Add((当前 % 房.列, 当前 / 房.列));
            当前 = 父[当前];
        }
        路.Reverse();
        return 路;
    }

    private static int 索引(网格数据 房, int 列, int 行) => 行 * 房.列 + 列;

    private static int 曼哈顿(int 列, int 行, int 目标列, int 目标行)
        => Math.Abs(列 - 目标列) + Math.Abs(行 - 目标行);
}

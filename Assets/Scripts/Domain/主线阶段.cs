
    // 主线阶段工具：第一章主线阶段的顺序表与判定。
    // 阶段字符串同时用于：玩家档案.主线阶段（存档）、剧情节点.主线阶段（进入更新）、
    // 区域剧情路由.阶段（自动剧情命中）、任务 目标类型=主线阶段。
    // ⚠ 这整套是**奇幻遗留**（阶段名全是 镇长/橡木林/风谷村/骑士团），末日版不用：
    //    原消费者之一 `地图地点.解锁阶段`（前往门槛）已随 v51 节点网图退役一起删掉，
    //    解锁门禁改由 `解锁条件项`（天数/物品/前置区域）承担。剩 QuestService / DialogueService 两处，
    //    等清奇幻残留那一刀连同 `玩家档案.主线阶段` 一起拆。
    public static class 主线阶段工具
    {
        // 阶段顺序（升序；新篇章追加到末尾）
        private static readonly string[] 阶段序 =
        {
            "第一章_序章",
            "第一章_待见镇长",   // 序章进镇 → 卫兵引导去镇长府
            "第一章_穿越橡木林",
            "第一章_抵达风谷村",
            "第一章_特训",
            "第一章_深入调查",
            "第一章_骑士团",
            "第一章_决战",
            "第一章_完成"
        };

        // 阶段序号（未识别=0，保证旧档/空值不越界）
        public static int 序(string 阶段)
        {
            if (string.IsNullOrEmpty(阶段)) return 0;
            for (int i = 0; i < 阶段序.Length; i++)
                if (阶段序[i] == 阶段) return i;
            return 0;
        }

        // 当前阶段是否已达到目标阶段（用于 主线阶段 类任务完成判定 / 解锁判定）
        public static bool 达到(string 当前, string 目标) => 序(当前) >= 序(目标);
    }

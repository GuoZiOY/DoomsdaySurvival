using System;
using System.Collections.Generic;

// ============================================================
// 搜索规则：大世界「搜索」的**纯算术部分**（纯 C#，零 UnityEngine；离线验证器与游戏跑的是同一份）。
//
// 为什么单独一个文件、而且必须是纯函数：
//   · 代价与成功率原来是直接写在 大世界探索服务.搜索() 里的，掷的是 UnityEngine.Random
//     → **离线验证器验不了曲线**（能验的只有几何）。抽到这里之后，"单调递增 / 有下限 / 上限几次"
//     这类断言都能逐点扫出来（见 Tools/大世界验证 的「搜索规则自检」一段）。
//   · 随机源留在服务层（`Func<int,int> 掷`）：一次性副本本来就不需要定点，
//     但**算法**要可验 —— 这是"把随机的部分缩到最小"那条纪律的落地。
//
// 三条约束（设计见 docs/大世界搜索约束设计.md）：
//   ① 局部枯竭  在枯竭区(列,行,…) / 搜索成功率(参, 在枯竭区) → 站在翻过的地方再搜，成功率掉到 枯竭概率
//   ② 越翻越累  搜索行动点(参, 第几次)                        → 一趟里越翻越贵，产量有硬上限
//   ③ 楼型白名单 挑临时建筑(参, 全部楼型, 掷点)                → 永不抽出区专属楼型
// ============================================================
public static class 搜索规则
{
    // ================= ② 越翻越累 =================

    // 一趟里**第 几次**搜索要花多少行动点（第 1 次 = 参.行动点，之后每次多 每多一次多花行动点）。
    // 次数从 1 起（调用方传"这一次是第几次尝试"，**不管上一次成没成功** —— 失败不涨价等于没约束）。
    public static int 搜索行动点(世界搜索参数 参, int 第几次)
    {
        if (参 == null) return 0;
        int 次 = Math.Max(1, 第几次);
        return Math.Max(0, 参.行动点) + (次 - 1) * Math.Max(0, 参.每多一次多花行动点);
    }

    // 这一趟用 `行动点上限` 点精力，最多能搜几次（纯算术，UI 与验证器都用得上）。
    // 用"逐次累加"而不是解不等式：步进小于等于 0 时也要自然退化成"无限次"而不是除零。
    public static int 本趟可搜次数(世界搜索参数 参, int 行动点上限)
    {
        if (参 == null) return 0;
        int 余 = 行动点上限, 次 = 0;
        for (int i = 1; i <= 999 && 余 > 0; i++)
        {
            int 价 = 搜索行动点(参, i);
            if (价 <= 0) { 次 = 999; break; }   // 不要钱 → 不构成上限（数据写 0 时的退化行为）
            if (价 > 余) break;
            余 -= 价;
            次++;
        }
        return 次;
    }

    // ================= ① 局部枯竭 =================

    // 这一格在不在"已翻过"里：到任何一间已翻出的临时建筑**占地**（2×2）的切比雪夫距离 ≤ 半径。
    // 用"到矩形最近一格的距离"而不是"到中心点"：贴着建筑边走一格，手感上就该还算这一带。
    // 半径 ≤ 0 = 这条约束关掉（始终返回 false）。
    public static bool 在枯竭区(int 列, int 行, IReadOnlyList<(int 列, int 行)> 已翻过, int 半径)
    {
        if (半径 <= 0 || 已翻过 == null || 已翻过.Count == 0) return false;
        for (int i = 0; i < 已翻过.Count; i++)
        {
            var (楼列, 楼行) = 已翻过[i];
            int 横 = 0, 纵 = 0;
            if (列 < 楼列) 横 = 楼列 - 列;
            else if (列 > 楼列 + 大世界生成器.临时建筑宽 - 1) 横 = 列 - (楼列 + 大世界生成器.临时建筑宽 - 1);
            if (行 < 楼行) 纵 = 楼行 - 行;
            else if (行 > 楼行 + 大世界生成器.临时建筑高 - 1) 纵 = 行 - (楼行 + 大世界生成器.临时建筑高 - 1);
            if (Math.Max(横, 纵) <= 半径) return true;
        }
        return false;
    }

    // 这一次搜索的成功率（0~100）：站在"已翻过"里 → 枯竭概率；否则 → 出现概率。
    // 不叠加（区里有 1 间还是 3 间都算"在区内"）：避免"越搜越死"的负反馈堆积。
    public static int 搜索成功率(世界搜索参数 参, bool 在枯竭区)
    {
        if (参 == null) return 0;
        int 原 = 夹(参.出现概率, 0, 100);
        if (!在枯竭区) return 原;
        // 枯竭概率**只许比出现概率低**（数据写反了也不该变成"越翻越多"）
        return Math.Min(原, 夹(参.枯竭概率, 0, 100));
    }

    // ================= ③ 楼型白名单 =================

    // 临时建筑能出哪些楼型，逐个（建筑模板, 权重）。白名单为空 → **兜底**：
    //   全部楼型里滤掉 禁区楼型（这样"数据忘了填白名单"也不会退化回"能刷出医院"）。
    public static List<(string 模板, int 权重)> 候选楼型(世界搜索参数 参, IEnumerable<string> 全部楼型)
    {
        var 结果 = new List<(string, int)>();
        var 禁 = new HashSet<string>();
        if (参?.禁区楼型 != null)
            foreach (var s in 参.禁区楼型) if (!string.IsNullOrEmpty(s)) 禁.Add(s);

        if (参?.临时建筑 != null && 参.临时建筑.Length > 0)
        {
            foreach (var 项 in 参.临时建筑)
            {
                if (项 == null || string.IsNullOrEmpty(项.建筑模板)) continue;
                if (禁.Contains(项.建筑模板)) continue;   // 白名单里写了禁区 → 这里也滤掉（校验会另报错）
                结果.Add((项.建筑模板, Math.Max(1, 项.权重)));
            }
            if (结果.Count > 0) return 结果;
        }
        if (全部楼型 != null)
            foreach (var s in 全部楼型)
                if (!string.IsNullOrEmpty(s) && !禁.Contains(s)) 结果.Add((s, 1));
        return 结果;
    }

    // 按权重挑一个楼型。掷点 ∈ [0, 总权重) —— 随机源由调用方给（服务层用 UnityEngine.Random，
    // 验证器直接全扫掷点），所以这个函数是纯的、可离线断言（"掷遍所有点也抽不到禁区楼型"）。
    public static string 挑临时建筑(世界搜索参数 参, IEnumerable<string> 全部楼型, int 掷点)
    {
        var 候选 = 候选楼型(参, 全部楼型);
        if (候选.Count == 0) return "";
        int 总 = 0;
        foreach (var (_, 权) in 候选) 总 += 权;
        if (总 <= 0) return 候选[0].模板;
        int 位 = 掷点 % 总;
        if (位 < 0) 位 += 总;
        foreach (var (模板, 权) in 候选)
        {
            if (位 < 权) return 模板;
            位 -= 权;
        }
        return 候选[候选.Count - 1].模板;   // 到不了（位一定落在总权重内），兜底返回最后一个
    }

    // 白名单楼型的总权重（服务层掷点要用）
    public static int 总权重(世界搜索参数 参, IEnumerable<string> 全部楼型)
    {
        int 总 = 0;
        foreach (var (_, 权) in 候选楼型(参, 全部楼型)) 总 += 权;
        return 总;
    }

    private static int 夹(int 值, int 最小, int 最大)
    {
        if (值 < 最小) return 最小;
        if (值 > 最大) return 最大;
        return 值;
    }
}

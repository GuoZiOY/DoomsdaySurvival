using System;
using System.Collections.Generic;

// ============================================================
// 大世界敌人 AI（刀61）：**三态（静默 / 巡逻 / 追踪）+ 噪音感知**。纯 C#，零 UnityEngine。
// 设计全文见 docs/大世界敌人AI设计.md。这里只放"一只敌人怎么想"，**流程/落子/校验全在服务层**。
//
// 纪律（沿用 Domain/战斗/敌人AI.cs 文件头那一套，别破坏）：
//   · 本文件**不掷骰**：所有随机都由调用方给一个 `掷点` int。
//     → 步可离线复现、可逐种子断言（`Tools/大世界敌人验证` 就靠这条）。
//   · 本文件**不改世界、不改实体**：只算"这一步想去哪一格"，落子由服务层负责
//     （服务层要另做：不重叠 / 不碰门口 / 移动后连通性硬保证 —— 那三件事都需要看全局，不属于"一只敌人怎么想"）。
//
// 三态的职责（用户拍板就是三个）：
//   静默 —— 蜷在出生点不动，视觉半径 ×0.6。**职责是给玩家一个"摸过去 / 先手打它"的窗口**，
//           不是装饰性待机：16 只全在巡逻的话，玩家每次接近都是"被发现 → 挨先手"。
//   巡逻 —— 在出生点 巡逻半径 内走动，步进带**归家偏置**（离得越远越往家走）+ **噪音偏置**（小噪音"过去看看"）。
//           "回巢"不是第四个状态，就是这条偏置 —— 一条规则同时表达溜达 / 从远处走回来 / 被声音吸引。
//   追踪 —— 沿流场朝"目标格"逼近。目标格有两种（这就是流场被选中的原因，见 流场.cs 文件头）：
//           · 玩家当前格（看得见时实时更新）
//           · 噪音发生格（**静止的** → 那个流场算一次就能一直用）
// ============================================================
public static class 大世界敌人AI
{
    // 静默 → 巡逻 的定时（**敌人步**为单位）。
    // ⚠ 刀61 修正：原来写 4~10，那是"敌人步"，而敌人每 **移动步频** 个玩家步才走一步
    //   → 感染者（步频 3）实际要 12~30 个**玩家步**才醒 = 玩家走十几秒全城不动。
    //   这是把"敌人步"当"玩家步"用导致的口径错（口径混用比算错更难发现）。
    //   现在压到 2~4 敌步（感染者 6~12 玩家步 / 狗 4~8 / 鼠 2~4），开局两三秒城市就醒了。
    //   "静默给玩家一个接近窗口"这条设计**没有丢**：回家之后还会重新蛰伏（见 感知与迁移 的 蛰伏周期）。
    public const int 静默最少步 = 2, 静默最多步 = 4;
    // 巡逻到家之后"重新蛰伏"的掷点周期（掷点 % 它 == 0）
    public const int 蛰伏周期 = 4;
    // 小噪音"过去看看"的加权增量（相对基准权重 1；越大家里蹲不住）
    public const int 吸引权重 = 4;
    // 归家偏置：超出巡逻半径时只许往家走 / 在半径内偏向家的增量
    public const int 归家权重超出 = 6, 归家权重在内 = 3;
    // 潜行对感知的削弱上限（−60%）：封顶是防"把潜行堆成隐身"
    public const float 潜行削顶上 = 0.6f;

    // ================= 状态载体 =================

    // 单只敌人的运行期态。**由服务层持有**（Domain 不认识 Services，所以这里是参数不是字段）。
    // 生命期 = 一趟出行：回安全屋（清战局）整体作废，与"内容每趟重置"同一口径。
    public sealed class 敌人AI态
    {
        public 敌人状态 状态 = 敌人状态.静默;
        public bool 已记出生点;
        public int 出生列, 出生行;
        public int 静默倒计时 = -1;        // -1 = 还没初始化（第一次轮到它时按掷点定）
        public int 警觉剩余;               // 追踪时每步 -1，到 0 回巡逻
        public int 目标列 = -1, 目标行 = -1;
        public bool 目标是不是玩家;
        public int 吸引列 = -1, 吸引行 = -1;   // 小噪音的"过去看看"点（只改巡逻方向，不改状态）
        public int 上次列 = -1, 上次行 = -1;   // 不许立刻回头（否则两格之间来回抖，看起来像抽搐）
        public int 步数;                       // 已走过几个"敌人步"（掷点的输入之一）
        // ★ 游戏分钟累加器（刀61 即时制修正）：**敌人按游戏时间走，不按玩家步走**。
        //   本作是**即时制**（时间由 世界时间管理器 每帧推进），所以"站着不动世界就冻结"是 bug 不是取舍。
        //   用整数分钟累加 → 与帧率无关、可离线复现（见 间隔分钟）。
        public int 分钟计;

        public string 状态名 => 状态.ToString();
    }

    // 这只敌人"走一步"要过多少**游戏分钟**。
    // 口径：`移动步频` 仍然表示"玩家走 N 格的时间"（保持原来的平衡：感染者 3 格 / 狗 2 格 / 鼠 1 格），
    //   而玩家在大世界走一格 = `每格游戏分钟`（= 大世界探索服务.移动游戏分钟 = 5）。
    //   → 感染者 15 分钟 / 狗 10 / 鼠 5。走路时与改前**逐格等价**；站着不动时它们照样会动（只是按世界时钟慢下来）。
    public static int 间隔分钟(敌人数据 敌, int 每格游戏分钟)
        => Math.Max(1, 敌?.移动步频 ?? 3) * Math.Max(1, 每格游戏分钟);

    // ================= 掷点（确定性、无状态） =================

    // 这一步的掷点 = 混合(世界种子, 敌人标识, 步数)。
    // **不持有 Random 对象**是刻意的：掷点只跟"哪只敌人、第几步"有关，
    //   → 与"按什么顺序处理敌人"完全无关，确定性不依赖遍历顺序（这类 bug 最难查）。
    public static int 掷点(int 世界种子, string 敌标识, int 步数)
        => 确定性随机.混合(世界种子, 敌标识, 步数);

    // ================= 感知 =================

    // 潜行削弱系数（同时作用于视觉与听觉 —— 潜行是一个统一属性，不是两套）
    public static float 潜行削弱(int 潜行值)
    {
        float 削 = 潜行值 / 100f;
        if (削 > 潜行削顶上) 削 = 潜行削顶上;
        if (削 < 0f) 削 = 0f;
        return 1f - 削;
    }

    // 视觉半径：白天 ×1.0 / 夜晚 ×0.5 / 作息不符再 ×0.5 / 静默 ×0.6 / 潜行削弱。
    // ⚠ 玩家视野 白天 7、夜晚 3（视野.json），而敌人基础感知 6 —— **玩家永远看得比敌人远**，这是设计意图
    //   （否则"看清过就抢到先手"那条规则落不了地，见 格子探索服务.遭遇先手）。
    // `静默` 参数 = 这只敌人此刻是不是蜷着的（静默态的职责就是给玩家一个接近窗口，见文件头）。
    public static int 视觉半径(敌人数据 敌, 时段 当前时段, int 潜行值, bool 静默 = false)
    {
        float f = Math.Max(1, 敌?.感知半径 ?? 6);
        string 作息 = 敌?.作息 ?? "";
        if (当前时段 == 时段.夜晚) f *= 0.5f;
        if (作息 == "昼行" && 当前时段 == 时段.夜晚) f *= 0.5f;
        if (作息 == "夜行" && 当前时段 == 时段.白天) f *= 0.5f;
        if (静默) f *= 0.6f;
        f *= 潜行削弱(潜行值);
        return Math.Max(1, (int)f);
    }

    // 潜行削过之后的**实际强度**（潜行 = 我发出的动静更小；它同时决定"传多远"和"过不过阈"）
    public static float 实际强度(int 强度, int 潜行值) => 强度 * 潜行削弱(潜行值);

    // 实际强度 → 能传多远。**层系数在半径这一环**（空间：声音在旷野/街区/室内传得远近不同），
    //   而不是乘在强度上 —— 乘在强度上会把"传不远"和"不够响"混成一件事（室内开枪就不该因为"房子小"而不算巨响）。
    // `强度 50 = 基准` 是刻意设计：让 听觉半径 这个字段有物理含义（"50 强度的声音能传这么远"）。
    public static int 听距(敌人数据 敌, float 已削强度, float 层系数)
    {
        float f = Math.Max(1, 敌?.听觉半径 ?? 10) * (已削强度 / 噪音强度.基准) * Math.Max(0.05f, 层系数);
        return Math.Max(1, (int)f);
    }

    public static bool 看得见(int 敌列, int 敌行, 敌人数据 敌, int 玩家列, int 玩家行,
                              时段 当前时段, int 潜行值, bool 静默 = false)
        => 切比雪夫(敌列, 敌行, 玩家列, 玩家行) <= 视觉半径(敌, 当前时段, 潜行值, 静默);

    // 听得见吗？`过阈` = **实际强度** ≥ 敌人.噪音阈值（过阈才会**直接进入追踪**；不过阈只是"吸引靠近"）。
    // ⚠ 过阈用的是"削过潜行、但没乘层系数"的强度 —— 层系数只影响"传多远"，不影响"够不够响"。
    public static bool 听得见(int 敌列, int 敌行, 敌人数据 敌, 噪音事件 噪, int 潜行值, float 层系数, out bool 过阈)
    {
        过阈 = false;
        if (噪.强度 <= 0) return false;
        float 实 = 实际强度(噪.强度, 潜行值);
        if (切比雪夫(敌列, 敌行, 噪.列, 噪.行) > 听距(敌, 实, 层系数)) return false;
        过阈 = 实 >= (敌?.噪音阈值 ?? 50);
        return true;
    }

    // ================= 噪音结算（事件驱动：行为一发生就调） =================

    // 返回是否发生了**状态迁移**（服务层据此播报"它朝这边来了"）。
    // 两种作用严格分开（就是用户要的那两条）：
    //   · 听得见但 < 阈值 → **吸引靠近**：只记吸引点，改巡逻方向（"过去看看"，不是锁定你）
    //   · 听得见且 ≥ 阈值 → **直接进入追踪**（目标格 = 噪音格）
    public static bool 结算噪音(敌人AI态 态, 敌人数据 敌, int 敌列, int 敌行, 噪音事件 噪, int 潜行值, float 层系数)
    {
        if (态 == null) return false;
        if (!听得见(敌列, 敌行, 敌, 噪, 潜行值, 层系数, out bool 过阈)) return false;
        态.吸引列 = 噪.列;
        态.吸引行 = 噪.行;
        if (!过阈) return false;
        // 已经在追"玩家"时，噪音不打断 —— 否则会出现"玩家开了一枪，敌人反而掉头去查弹壳"这种蠢行为
        if (态.状态 == 敌人状态.追踪 && 态.目标是不是玩家) return false;
        态.状态 = 敌人状态.追踪;
        态.目标列 = 噪.列;
        态.目标行 = 噪.行;
        态.目标是不是玩家 = false;
        态.警觉剩余 = Math.Max(1, 敌?.警觉步数 ?? 6);
        return true;
    }

    public static void 记账出生点(敌人AI态 态, int 列, int 行)
    {
        if (态 == null || 态.已记出生点) return;
        态.出生列 = 列;
        态.出生行 = 行;
        态.已记出生点 = true;
    }

    // ================= 状态迁移（每个"敌人步"一次） =================

    // 返回是否发生了状态迁移。
    public static bool 感知与迁移(敌人AI态 态, 敌人数据 敌, int 敌列, int 敌行,
                                  int 玩家列, int 玩家行, 时段 当前时段, int 潜行值, int 掷点)
    {
        if (态 == null) return false;
        记账出生点(态, 敌列, 敌行);

        int 出生距 = 切比雪夫(敌列, 敌行, 态.出生列, 态.出生行);
        // ★ 缰绳**先于视觉**判定（刀61 验证器抓出来的真 bug）：
        //   原来"看见玩家"是提前 return 的，于是看得见就一直追 ——
        //   实测流浪狗追到离出生点 21 格还在追（追击上限 16 形同不存在），
        //   而"不恋战"这条设计正是为了防"全图敌人被引到营地门口堆成一坨"。
        //   现在：超出缰绳 = 无论看不看得见都必须在下一步落回巡逻。
        bool 超出缰绳 = 出生距 > Math.Max(1, 敌?.追击上限 ?? 12);
        bool 看见 = !超出缰绳 && 看得见(敌列, 敌行, 敌, 玩家列, 玩家行, 当前时段, 潜行值, 态.状态 == 敌人状态.静默);
        if (看见)
        {
            bool 变化 = 态.状态 != 敌人状态.追踪 || !态.目标是不是玩家
                     || 态.目标列 != 玩家列 || 态.目标行 != 玩家行;
            态.状态 = 敌人状态.追踪;
            态.目标列 = 玩家列;
            态.目标行 = 玩家行;
            态.目标是不是玩家 = true;
            态.警觉剩余 = Math.Max(1, 敌?.警觉步数 ?? 6);
            return 变化;
        }

        switch (态.状态)
        {
            case 敌人状态.静默:
                if (态.静默倒计时 < 0) 态.静默倒计时 = 静默时长(掷点);
                else 态.静默倒计时--;
                if (态.静默倒计时 <= 0) { 态.状态 = 敌人状态.巡逻; return true; }
                return false;

            case 敌人状态.巡逻:
                // 到家门口 + 掷点命中蛰伏周期 → 重新蜷起来（不是永远巡逻）
                if (出生距 <= 1 && 非负(掷点) % 蛰伏周期 == 0)
                {
                    态.状态 = 敌人状态.静默;
                    态.静默倒计时 = 静默时长(掷点);
                    return true;
                }
                return false;

            default:   // 追踪
                态.警觉剩余--;
                bool 到目标 = 态.目标列 == 敌列 && 态.目标行 == 敌行;
                if (态.警觉剩余 <= 0 || 到目标 || 超出缰绳)
                {
                    态.状态 = 敌人状态.巡逻;
                    态.目标列 = -1;
                    态.目标行 = -1;
                    态.目标是不是玩家 = false;
                    return true;
                }
                return false;
        }
    }

    // ================= 走一步（决策） =================

    // 算出这一步想去哪一格（返回 false = 这一步不动）。
    // **纯决策**：不改 态、不改 敌。落子（含不重叠 / 门口 / 连通）在服务层。
    // `追踪场` = 以"当前追踪目标格"为源的流场（服务层按目标格缓存；静止的噪音格可以长期复用）。
    public static bool 想走的格(网格数据 世界, 敌人AI态 态, 敌人数据 敌, int 敌列, int 敌行,
                                流场 追踪场, int 掷点, out int 目标列, out int 目标行)
    {
        目标列 = 敌列;
        目标行 = 敌行;
        if (世界 == null || 态 == null) return false;

        if (态.状态 == 敌人状态.静默) return false;   // 蜷着不动

        if (态.状态 == 敌人状态.追踪)
        {
            if (追踪场 == null) return false;
            var 下 = 追踪场.下一步(敌列, 敌行);
            if (下 == null) return false;               // 不可达 / 已经站在目标上 → 停
            目标列 = 下.Value.列;
            目标行 = 下.Value.行;
            return 目标列 != 敌列 || 目标行 != 敌行;
        }
        return 巡逻一步(世界, 态, 敌, 敌列, 敌行, 掷点, out 目标列, out 目标行);
    }

    // 巡逻一步：4 邻 + 权重（基准 1 + 归家偏置 + 噪音偏置），按固定顺序（右/下/左/上）掷。
    private static bool 巡逻一步(网格数据 世界, 敌人AI态 态, 敌人数据 敌, int 敌列, int 敌行,
                                 int 掷点, out int 目标列, out int 目标行)
    {
        目标列 = 敌列;
        目标行 = 敌行;
        int 巡逻半径 = Math.Max(0, 敌?.巡逻半径 ?? 8);
        if (巡逻半径 <= 0) return false;   // 巡逻半径 0 = 钉在原地（Boss 用）

        int 出生距 = 切比雪夫(敌列, 敌行, 态.出生列, 态.出生行);
        bool 在外 = 出生距 > 巡逻半径;

        // ★ 先探一遍"有没有严格更近的可走邻格"。
        //   为什么必须先探：在范围外时我们**连"平距"都不许走**（平距会沿着切比雪夫等距圈原地打转，
        //   永远回不了家 —— 这是 `Tools/大世界敌人验证` 抓出来的真 bug：追完人退回来时卡在 18 格外不动）。
        //   但"一近的都没有"（被墙夹在凹角里）时必须退回普通权重，否则敌人会**永久卡死**。
        //   数学上四邻里总有一个沿主轴的更近格，所以这条兜底只在被墙挡住时才用得上。
        bool 有更近 = false;
        if (在外)
            for (int d = 0; d < 4 && !有更近; d++)
            {
                int 列 = 敌列 + 流场.横[d], 行 = 敌行 + 流场.纵[d];
                if (!流场.可走(世界, 列, 行, false)) continue;
                if (切比雪夫(列, 行, 态.出生列, 态.出生行) < 出生距) 有更近 = true;
            }

        int[] 权重 = new int[4];
        int 总 = 0;
        for (int d = 0; d < 4; d++)
        {
            int 列 = 敌列 + 流场.横[d], 行 = 敌行 + 流场.纵[d];
            if (!流场.可走(世界, 列, 行, false)) continue;          // 敌人对巡逻也透明（不重叠由服务层管）
            // "不许立刻回头"只在**没跑超**时生效：跑超了就是要掉头回家，
            //   而"回家那一格"常常正好是它刚来的那一格 —— 拦着它就会原地打转（验证器抓过）。
            if (!在外 && 列 == 态.上次列 && 行 == 态.上次行) continue;
            int 新距 = 切比雪夫(列, 行, 态.出生列, 态.出生行);
            int w = 1;
            if (在外)
            {
                if (新距 < 出生距) w = 归家权重超出;
                else if (有更近) w = 0;        // 有回家的路 → 不许平着走，也不许往外走
                // ⚠ 这里**不加噪音吸引**：否则"过去看看"会把已经跑超的敌人越带越远
                //   （实测就是这么漂到离出生点 21 格的）。回家优先。
            }
            else
            {
                if (新距 < 出生距 && 出生距 > 1) w += 归家权重在内;
                if (态.吸引列 >= 0
                    && 切比雪夫(列, 行, 态.吸引列, 态.吸引行) < 切比雪夫(敌列, 敌行, 态.吸引列, 态.吸引行))
                    w += 吸引权重;
            }
            权重[d] = w;
            总 += w;
        }
        if (总 <= 0) return false;

        int 掷 = 非负(掷点) % 总;
        for (int d = 0; d < 4; d++)
        {
            if (权重[d] <= 0) continue;
            掷 -= 权重[d];
            if (掷 < 0)
            {
                目标列 = 敌列 + 流场.横[d];
                目标行 = 敌行 + 流场.纵[d];
                return true;
            }
        }
        return false;
    }

    // ================= 落子判据（服务层与验证器**共用这一份**） =================

    // 能不能把这只敌人挪到 (目标列, 目标行)。四条全局约束都在这里：
    //   ① 真·可通行（墙 / 容器 / 障碍 / 建筑 / 区域 / **别的敌人** 都挡）
    //      —— 顺带把"两只叠在一格"堵死：`网格数据.可通行` 查的就是"有没有占格实体"。
    //   ② 不碰任何门口格的紧邻八格。门口格三面被自己挡着、**只有一个出口**，
    //      堵住它就是"玩家出门即死"（同一个坑在 v51 刀2 / 刀6 / 刀32 各栽过一次，别来第四次）。
    //   ③ **不许踩到玩家那一格**（刀61 验证器自检抓出来的真坑）：
    //      遭遇判据是"正交相邻"（曼哈顿距离 == 1），敌人一旦和玩家同格就变成距离 0
    //      → **永远触发不了遭遇**，玩家会和它叠在一起走。`大世界生成器.撒敌人` 的注释里
    //      为"敌人必须占格"写过同一条坑（不让玩家从它身上走过去），这里是那条坑的孪生兄弟：
    //      静态敌人不占格 → 玩家穿过去；动态敌人不避让 → 贴上来。**两头都得堵**。
    // 为什么放在 Domain 而不是服务层：**验证器必须跑同一份判据**，
    //   否则"验证器全绿、游戏里敌人却堵死了门口"这种事没有任何拦截层（门口保护 文件头记的正是这个教训）。
    public static bool 能落子(网格数据 世界, 网格实体 敌, int 目标列, int 目标行)
    {
        if (世界 == null || 敌 == null) return false;
        if (目标列 < 0 || 目标行 < 0) return false;
        if (目标列 == 敌.列 && 目标行 == 敌.行) return false;
        if (!世界.可通行(目标列, 目标行)) return false;
        if (门口保护.碰世界门口(世界, 目标列, 目标行)) return false;
        if (世界.玩家列() == 目标列 && 世界.玩家行() == 目标行) return false;
        return true;
    }

    // **真的把敌人挪过去**：服务层与验证器共用（唯一一处落子）。
    // 同时记下"从哪一格来" —— 巡逻步进的"不许立刻回头"读的就是它。
    // ⚠ 这个字段必须在这里写：它一旦没人写，`上次列/行` 永远停在 -1，那条规则就**静默失效**
    //   （表现是敌人两格之间来回抖，看起来像抽搐 —— 很难在游戏里定位到原因）。
    public static bool 落子(网格数据 世界, 网格实体 敌, 敌人AI态 态, int 目标列, int 目标行)
    {
        if (!能落子(世界, 敌, 目标列, 目标行)) return false;
        if (态 != null) { 态.上次列 = 敌.列; 态.上次行 = 敌.行; }
        敌.列 = 目标列;
        敌.行 = 目标行;
        return true;
    }

    // ================= 小工具 =================

    public static int 切比雪夫(int 列1, int 行1, int 列2, int 行2)
        => Math.Max(Math.Abs(列1 - 列2), Math.Abs(行1 - 行2));

    public static int 静默时长(int 掷点)
        => 静默最少步 + 非负(掷点) % (静默最多步 - 静默最少步 + 1);

    private static int 非负(int v) => v < 0 ? -v : v;
}

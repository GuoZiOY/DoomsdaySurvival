using System;
using System.Collections.Generic;

// ============================================================
// 大世界生成器：一张 **100×100 的格子世界**（纯 C#，零 UnityEngine；离线验证器与游戏跑的是同一份）。
//
// 与 区域生成器 的分工（别混）：
//   区域生成器   = **副本内部**（一片 32×22 街区：地块制摆几栋楼 + 街道障碍）
//   大世界生成器 = 副本"坐落在哪"的那张图（100×100：营地 + 若干区域占地 + 街道障碍）
//
// 摆法不是地块制（大世界没有"格子配额"这一说），四段：
//   ① 造壳：整圈边界墙（城市边界废墟，挡通行）—— 玩家走不出地图
//   ② 营地：安全屋落在 模板.营地，占 营地宽×营地高，门口格开在**底边中格**（能站能走）→ 玩家从这里出发
//   ③ 区域：逐个按 模板.区域[] 摆 —— 占地掩码复用 建筑外形（矩形/L/凸/凹 + 朝向/镜像）
//        **占格 = true / 挡视线 = false**：一片街区是"看得见、穿不过去的整块"，
//        只有**门口那一格**（底边中点）能站能走 → 走上去进副本（与"楼门长在楼上"同一套直觉）
//   ④ 障碍：撒在自由格上（废墟/车障），撒完做**一次**全图连通校验；破了就从最后撒的开始撤，撤到连通为止
//        ⚠ 不能像 区域生成器 那样"每撒一个就整图校验"：100×100 单次 连通分量数() ≈ 10000 格 × 500 实体，
//          每撒一个跑一遍会慢到不可用（区域只有 704 格、30 来个实体，所以那边可以那么写）。
//          代价是"最后一次校验"之外的中间态不保证连通 —— 但障碍彼此强制隔开 1 格（见 可撒障碍），
//          真要切断 98×98 的开阔地需要一整条连续屏障，实际上不会发生；真发生了也会被撤回到连通为止。
//
// 不变量（Tools/大世界验证 逐颗种子断言）：
//   ① 同模板 + 同种子 = 同布局（确定性，指纹逐字节一致）
//   ② 区域占地：界内（四周留 世界规格.边距）、掩码连通、**互不重叠**、不压营地
//   ③ 营地门口格可通行 + 从它可达
//   ④ 可站格连通分量 = 1（无孤岛）
//   ⑤ 障碍不压营地门口四邻、不压任何区域占地
// ============================================================
public static class 大世界生成器
{
    // ================= 生成 =================

    // 生成：种子 + 世界模板 → 网格数据。
    // 取名 = 标识 → 显示名（区域名由调用方给：Domain 不认识 DataService）
    public static 网格数据 生成(int 种子, 世界模板 模板, Func<string, string> 取名 = null)
    {
        if (模板 == null) return null;
        var 世界 = 造壳(模板);
        摆营地(世界, 模板);
        摆区域(种子, 世界, 模板, 取名);
        撒敌人(种子, 世界, 模板);
        撒障碍(种子, 世界, 模板);
        保证连通(世界);   // 撒完敌人与障碍做**一次**全图连通校验（破了先撤障碍、还破再撤敌人）
        return 世界;
    }

    // ================= 造壳 =================

    private static 网格数据 造壳(世界模板 模板)
    {
        var 世界 = new 网格数据
        {
            模板标识 = 模板.标识 ?? "",
            名称 = string.IsNullOrEmpty(模板.名称) ? 模板.标识 : 模板.名称,
            描述 = 模板.描述 ?? "",
            列 = 夹(模板.列, 世界规格.最小列, 世界规格.最大列),
            行 = 夹(模板.行, 世界规格.最小行, 世界规格.最大行),
            危险度 = 1,                                                     // 大世界本身不设危险度；危险在各片区域里
            视野边长 = 网格视野.奇数化(视野规则.白天边长默认),                  // 兜底值；真边长由服务按"角色 + 时段"写入
            战斗棋盘 = 模板.战斗棋盘 ?? "",
            敌人组 = "",                                                    // 大世界街上暂时没有敌人（遭遇在后面的刀里做）
        };
        建墙(世界);
        return 世界;
    }

    private static void 建墙(网格数据 世界)
    {
        int 序 = 0;
        for (int c = 0; c < 世界.列; c++)
        {
            加墙(世界, c, 0, ref 序);
            加墙(世界, c, 世界.行 - 1, ref 序);
        }
        for (int r = 1; r < 世界.行 - 1; r++)
        {
            加墙(世界, 0, r, ref 序);
            加墙(世界, 世界.列 - 1, r, ref 序);
        }
    }

    private static void 加墙(网格数据 世界, int 列, int 行, ref int 序)
    {
        世界.实体.Add(new 网格实体
        {
            标识 = $"{世界.模板标识}#墙{序++}",
            类型 = 网格实体类型.墙,
            阵营 = 网格阵营.中立,
            定义标识 = "墙",
            名称 = "城市的边界",
            列 = 列,
            行 = 行,
            占格 = true,
            挡视线 = true
        });
    }

    // ================= 营地 =================

    private static void 摆营地(网格数据 世界, 世界模板 模板)
    {
        int 列 = 模板.营地 != null ? 模板.营地.列 : (世界.列 - 世界规格.营地宽) / 2;
        int 行 = 模板.营地 != null ? 模板.营地.行 : (世界.行 - 世界规格.营地高) / 2;
        // 夹进边界：数据写歪了也别把营地摆到墙上（越界本身由 DataService / 大世界验证 报）
        列 = 夹(列, 世界规格.边距, Math.Max(世界规格.边距, 世界.列 - 世界规格.营地宽 - 世界规格.边距));
        行 = 夹(行, 世界规格.边距, Math.Max(世界规格.边距, 世界.行 - 世界规格.营地高 - 世界规格.边距));

        var 营 = new 网格实体
        {
            标识 = $"{世界.模板标识}#营地",
            类型 = 网格实体类型.建筑,
            阵营 = 网格阵营.中立,
            定义标识 = "安全屋",
            名称 = "安全屋（营地）",
            列 = 列,
            行 = 行,
            宽 = 世界规格.营地宽,
            高 = 世界规格.营地高,
            朝向 = 0,                 // 门开在下边
            占格 = true,
            挡视线 = true
        };
        营.门口格 = 网格数据.编码(列 + 世界规格.营地宽 / 2, 行 + 世界规格.营地高 - 1);
        世界.实体.Add(营);

        var 门 = 营地门口格(世界);
        世界.入口列 = 门.列;
        世界.入口行 = 门.行;
        世界.实体.Add(new 网格实体
        {
            标识 = $"{世界.模板标识}#玩家",
            类型 = 网格实体类型.玩家,
            阵营 = 网格阵营.玩家,
            定义标识 = "玩家",
            名称 = "你",
            列 = 门.列,
            行 = 门.行,
            占格 = false,
            挡视线 = false
        });
    }

    // 营地门口格（玩家落点）：从营地实体上读（找不到就退回入口格）
    public static (int 列, int 行) 营地门口格(网格数据 世界)
    {
        var 营 = 营地实体(世界);
        if (营 == null) return (世界?.入口列 ?? 0, 世界?.入口行 ?? 0);
        if (营.门口格 < 0) return (营.列 + 营.宽 / 2, 营.行 + 营.高);
        return (营.门口格 / 1000, 营.门口格 % 1000);
    }

    public static 网格实体 营地实体(网格数据 世界)
    {
        if (世界 == null) return null;
        foreach (var e in 世界.实体)
            if (e != null && e.类型 == 网格实体类型.建筑 && e.定义标识 == "安全屋") return e;
        return null;
    }

    // ================= 区域 =================

    private static void 摆区域(int 种子, 网格数据 世界, 世界模板 模板, Func<string, string> 取名)
    {
        if (模板.区域 == null) return;
        int 序 = 0;
        foreach (var 项 in 模板.区域)
        {
            if (项 == null || string.IsNullOrEmpty(项.区域模板)) continue;
            var 形 = 项.占地 ?? new 建筑外形数据 { 形状 = 建筑外形.矩形, 宽 = 6, 高 = 5 };
            var 掩 = 建筑外形.生成(形, out int 宽, out int 高);

            // 界内检查：越界就**不摆**并记账（不静默缩到边界里 —— 那会让"数据写歪"变成"看着没问题"）
            if (项.列 < 世界规格.边距 || 项.行 < 世界规格.边距 ||
                项.列 + 宽 > 世界.列 - 世界规格.边距 || 项.行 + 高 > 世界.行 - 世界规格.边距)
            {
                世界.区域摆不下++;
                continue;
            }

            var 区 = new 网格实体
            {
                标识 = $"{世界.模板标识}#区域{序++}",
                类型 = 网格实体类型.区域,
                阵营 = 网格阵营.中立,
                定义标识 = 项.区域模板,
                名称 = 取名?.Invoke(项.区域模板) ?? 项.区域模板,
                列 = 项.列,
                行 = 项.行,
                宽 = 宽,
                高 = 高,
                形状掩码 = 掩,
                掩码列 = 宽,
                朝向 = 形.朝向,
                占格 = true,          // 整块穿不过去
                挡视线 = false,        // 但"看得见"：方形视野本来就不做遮挡，这里表明语义
                解锁 = 项.解锁,        // 解锁条件跟着实体走，服务层靠它决定"进不进得去"
            };
            var (门列, 门行) = 建筑外形.底边中点(掩, 宽, 高);
            区.门口格 = 门列 < 0 ? -1 : 网格数据.编码(项.列 + 门列, 项.行 + 门行);
            世界.实体.Add(区);
        }
    }

    // 大世界上的全部区域（按摆放顺序）
    public static List<网格实体> 区域列表(网格数据 世界)
        => 世界 == null ? new List<网格实体>() : 世界.取类型(网格实体类型.区域);

    // 区域门口格（玩家站这一格 = 进副本）
    public static (int 列, int 行) 区域门口格(网格实体 区域)
    {
        if (区域 == null) return (0, 0);
        if (区域.门口格 < 0) return (区域.列 + 区域.宽 / 2, 区域.行 + 区域.高);
        return (区域.门口格 / 1000, 区域.门口格 % 1000);
    }

    // ================= 街道障碍 =================

    // ================= 街道敌人 =================

    // 撒街道敌人：按 模板.敌人[] 的 定义标识 + 数量 撒在自由格上。
    // **占格 = true**（和房间层的敌人一样挡路）→ 走到它相邻那一格就会触发遭遇（检查遭遇 判的是"正交相邻"）。
    // 若做成不占格，玩家会**从它身上走过去**（距离 0 ≠ 1）而不触发遭遇 —— 那是个隐蔽的坑，别改。
    // 显示名（"感染者"之类）由服务层从 enemies.json 补上：Domain 不认识数据服务，这里先塞 定义标识。
    private static void 撒敌人(int 种子, 网格数据 世界, 世界模板 模板)
    {
        if (模板.敌人 == null || 模板.敌人.Length == 0) return;
        var 流 = 确定性随机.随机流(确定性随机.派生(种子, "世界敌人"));
        int 序 = 0;
        foreach (var 项 in 模板.敌人)
        {
            if (项 == null || string.IsNullOrEmpty(项.定义标识)) continue;
            int 要 = Math.Max(1, 项.数量);
            for (int i = 0; i < 要; i++)
            {
                // 每只独立试若干次；撒不下就少一只（不报错 —— 世界太挤是允许的结果，验证器会统计实际数量）
                for (int 次 = 0; 次 < 80; 次++)
                {
                    int 列 = 确定性随机.范围(流, 1, 世界.列 - 1), 行 = 确定性随机.范围(流, 1, 世界.行 - 1);
                    if (!可撒单个占格物(世界, 列, 行)) continue;
                    世界.实体.Add(new 网格实体
                    {
                        标识 = $"{世界.模板标识}#敌人{序++}",
                        类型 = 网格实体类型.敌人,
                        阵营 = 网格阵营.敌人,
                        定义标识 = 项.定义标识,
                        名称 = 项.定义标识,       // 服务层会换成真名
                        列 = 列,
                        行 = 行,
                        占格 = true,
                        挡视线 = false,          // 街上看得见对面（方形视野本来也不做遮挡）
                    });
                    break;
                }
            }
        }
    }

    // ================= 街道障碍 =================

    // 撒障碍（只负责撒，连通由 保证连通() 统一兜底）
    private static void 撒障碍(int 种子, 网格数据 世界, 世界模板 模板)
    {
        int 要 = Math.Max(0, 模板.障碍数);
        if (要 == 0) return;
        var 流 = 确定性随机.随机流(确定性随机.派生(种子, "世界障碍"));
        int 序 = 0;
        for (int 次 = 0; 次 < 要 * 12 && 序 < 要; 次++)
        {
            int 列 = 确定性随机.范围(流, 1, 世界.列 - 1), 行 = 确定性随机.范围(流, 1, 世界.行 - 1);
            if (!可撒单个占格物(世界, 列, 行)) continue;
            世界.实体.Add(new 网格实体
            {
                标识 = $"{世界.模板标识}#障碍{序}",
                类型 = 网格实体类型.障碍,
                阵营 = 网格阵营.中立,
                定义标识 = "障碍",
                名称 = 障碍名(序),
                列 = 列,
                行 = 行,
                占格 = true,
                挡视线 = true
            });
            序++;
        }
    }

    private static string 障碍名(int 序)
    {
        string[] 名 = { "废弃汽车", "塌下来的楼板", "翻倒的公交站牌", "锈死的垃圾箱", "塌陷的路面" };
        return 名[Math.Abs(序) % 名.Length];
    }

    // 撒敌人 / 撒障碍**共用**的一条判据：这一格能不能放一个单格占格物。
    //
    // 两条留空规则各自堵一个真实的坑（都是 大世界验证 抓出来的）：
    //   · **门口格四邻必须留空**：区域/营地的门口格三面被自己挡着、**只有一个出口**。
    //     只排掉"压住门口格本身"是不够的 —— 把**出口那一格**占掉，门口格就成了"能站却走不到"的孤岛。
    //     （这个坑在 v51 刀2 与 刀6 各栽过一次：先是障碍、后是临时建筑。）
    //   · **占格物彼此隔开 1 格**（切比雪夫距离恒 ≥2）→ 永远凑不出"8 连通屏障"，
    //     而 4 连通网格的割集必须是一条 8 连通屏障（对偶关系）→ **它们在数学上不可能切断开阔地**。
    //     有了这条，保证连通() 那次全图校验就只是"万一"的保险，而不是主力。
    //
    // ⚠ 敌人也走这条判据（它占格）—— 所以敌人同样凑不出屏障。但**临时建筑不在此列**（它是 2×2 一整块，
    //   能凑出屏障），所以 搜索落点 才要"试放 + 连通校验"，见那边的注释。
    private static bool 可撒单个占格物(网格数据 世界, int 列, int 行)
    {
        if (列 < 世界规格.边距 || 行 < 世界规格.边距 || 列 > 世界.列 - 1 - 世界规格.边距 || 行 > 世界.行 - 1 - 世界规格.边距) return false;
        if (!世界.可通行(列, 行)) return false;

        var 营门 = 营地门口格(世界);
        if (Math.Abs(列 - 营门.列) <= 1 && Math.Abs(行 - 营门.行) <= 1) return false;

        foreach (var 区 in 区域列表(世界))
        {
            if (区.覆盖(列, 行)) return false;
            var 区门 = 区域门口格(区);
            if (Math.Abs(列 - 区门.列) <= 1 && Math.Abs(行 - 区门.行) <= 1) return false;
        }

        // 与已有的 障碍 / 敌人 / 临时建筑 都至少隔 1 格
        foreach (var 他 in 世界.实体)
        {
            if (他 == null) continue;
            if (他.类型 != 网格实体类型.障碍 && 他.类型 != 网格实体类型.敌人 && 他.类型 != 网格实体类型.临时建筑) continue;
            if (Math.Abs(他.列 - 列) <= 1 && Math.Abs(他.行 - 行) <= 1) return false;
        }
        return true;
    }

    // 撒完敌人与障碍之后做**一次**全图连通校验。破了就撤：**先撤障碍（纯装饰），还破再撤敌人（能打的）**。
    // 为什么只做一次：100×100 单次 连通分量数() ≈ 10000 格 × 500 实体，每撒一个跑一遍会慢到不可用。
    // 撤不动了也不在这里喊 —— Domain 层不引 UnityEngine（离线验证器要能编它）；
    // 撤掉的障碍/敌人 两个计数会如实报出来，`Tools/大世界验证` 断言它们必须是 0。
    private static void 保证连通(网格数据 世界)
    {
        if (世界.连通分量数() <= 1) return;
        foreach (var 障 in 世界.取类型(网格实体类型.障碍))
        {
            世界.实体.Remove(障);
            世界.撤掉的障碍++;
            if (世界.连通分量数() <= 1) return;
        }
        var 敌人们 = 世界.取类型(网格实体类型.敌人);
        for (int i = 敌人们.Count - 1; i >= 0; i--)
        {
            世界.实体.Remove(敌人们[i]);
            世界.撤掉的敌人++;
            if (世界.连通分量数() <= 1) return;
        }
    }

    // ================= 搜索：找落点 + 放临时建筑 =================
    // 「大世界点击搜索，以角色半径内搜索，会出现一个临时建筑，可以进去探索」——
    // 这里是那条动作的**纯几何部分**（扣行动点/游戏时间、掷概率在服务层）。
    // 临时建筑 = **一次性**：进去探索完、回到大世界时就被拆掉（服务层负责）；
    // 它的楼型是当场随机挑的一个 建筑模板/房间模板（不必固定种子 —— 一次性副本没有"再来一次"）。

    public const int 临时建筑宽 = 2, 临时建筑高 = 2;

    // 搜索落点：玩家半径内找一块**能放临时建筑**的空地。
    // 返回 找到 = false 表示附近太挤（**不是错误**，调用方给玩家一句反馈就行）。
    // 确定性：同 (世界现状, 玩家格, 半径, 种子) → 同结果（`Tools/大世界验证` 据此逐种子断言）。
    //
    // ★ 「试放 + 连通校验」这一步是验证器逼出来的：
    //   2×2 的临时建筑是一整块 **8 连通**的墙，而障碍之间只是"切比雪夫 ≥2"（彼此 8 不相邻）——
    //   障碍凑不出屏障，但**临时建筑能**：它和地图边界 / 障碍 / 区域凑在一起真能把地图切成两半。
    //   （50 种子 × 6 次搜索里实测 15 次。所以候选要**逐个试放**，破了就连着撤掉换下一个。）
    //   代价可以接受：失败率约 5%，第一个候选基本就成 → 每次搜索通常只跑一两次连通校验。
    public static (bool 找到, int 列, int 行) 搜索落点(网格数据 世界, int 玩家列, int 玩家行, int 半径, int 种子)
    {
        if (世界 == null) return (false, 0, 0);
        int 半 = Math.Max(1, 半径);
        var 候选 = new List<(int 列, int 行)>();
        for (int 行 = 玩家行 - 半; 行 <= 玩家行 + 半; 行++)
            for (int 列 = 玩家列 - 半; 列 <= 玩家列 + 半; 列++)
            {
                // 不放在脚底下：2×2 会把自己站的那格也占掉，等于把自己砌进墙里
                if (列 <= 玩家列 && 玩家列 < 列 + 临时建筑宽 && 行 <= 玩家行 && 玩家行 < 行 + 临时建筑高) continue;
                if (能放临时建筑(世界, 列, 行)) 候选.Add((列, 行));
            }
        if (候选.Count == 0) return (false, 0, 0);

        var 流 = 确定性随机.随机流(确定性随机.派生(种子, "搜索落点"));
        确定性随机.洗牌(流, 候选);   // 确定性地打乱候选顺序 → 尽量试到"放下去不破连通"的那一个
        foreach (var (列, 行) in 候选)
        {
            var 试 = 放临时建筑(世界, 列, 行, "试", "试", "");
            if (试 == null) continue;
            bool 好 = 世界.连通分量数() <= 1;
            世界.移除实体(试);   // 试完就撤：世界状态必须原样还给调用方（确定性靠这条）
            if (好) return (true, 列, 行);
        }
        return (false, 0, 0);
    }

    // 这一格能不能当临时建筑的左上角：2×2 每一格都得"空"
    //   · 可通行（没有占格实体）
    //   · 不被任何区域占地 / 营地压着（区域是"一片街区"，临时建筑不该长在它里头）
    //   · **不压任何"带门洞的占格物"的门口格**，而且**门口格的紧邻八格也要留空**
    //     ★ 这一条是 `Tools/大世界验证` 抓出来的（第二次栽在同一个坑上，见下）：
    //       区域/营地/临时建筑的门口格都是"三面被自己挡着、只有一个出口"的格子。
    //       只排掉"压住门口格本身"是不够的 —— 把**门口下面那一格**占掉，门口格就成了
    //       "能站却走不到"的孤岛（连通分量 +1，玩家也进不去）。
    //       同一课在 刀2 已经上过一次（当时是**障碍**堵了区域门口，见 docs 大世界网格与副本设计.md §9.3），
    //       这里是同一个坑换了个人踩：**凡"只有一个出口"的格子，留空规则必须保护它和它的出口。**
    public static bool 能放临时建筑(网格数据 世界, int 列, int 行)
    {
        if (世界 == null) return false;
        for (int r = 行; r < 行 + 临时建筑高; r++)
            for (int c = 列; c < 列 + 临时建筑宽; c++)
            {
                if (!世界.界内(c, r)) return false;
                if (!世界.可通行(c, r)) return false;
            }
        // 再排掉"被区域/营地覆盖"的格（区域那块本身占格，上面那条已挡住大部分；
        // 但区域的**门口格**是可通行的，一个 2×2 正好横跨门口就会把门口堵死 —— 必须显式排掉）
        foreach (var e in 世界.实体)
        {
            if (e == null) continue;
            if (e.类型 != 网格实体类型.区域 && e.类型 != 网格实体类型.建筑) continue;
            for (int r = 行; r < 行 + 临时建筑高; r++)
                for (int c = 列; c < 列 + 临时建筑宽; c++)
                    if (e.覆盖(c, r)) return false;
        }
        // 也不许碰**任何门口格及其紧邻八格**（含已有临时建筑的门口）—— 见方法头上那条 ★
        for (int r = 行; r < 行 + 临时建筑高; r++)
            for (int c = 列; c < 列 + 临时建筑宽; c++)
                foreach (var e in 世界.实体)
                {
                    if (!网格数据.是带门洞的占格物(e) || e.门口格 < 0) continue;
                    int 门列 = e.门口格 / 1000, 门行 = e.门口格 % 1000;
                    if (Math.Abs(c - 门列) <= 1 && Math.Abs(r - 门行) <= 1) return false;
                }
        return true;
    }

    // 放一间临时建筑（2×2，门开在底边中点那一格 → 走上去就进去）
    public static 网格实体 放临时建筑(网格数据 世界, int 列, int 行, string 序号, string 名称, string 定义标识)
    {
        if (世界 == null) return null;
        var 物 = new 网格实体
        {
            标识 = $"{世界.模板标识}#临时{序号}",
            类型 = 网格实体类型.临时建筑,
            阵营 = 网格阵营.中立,
            定义标识 = 定义标识,
            名称 = string.IsNullOrEmpty(名称) ? "临时窝点" : 名称,
            列 = 列,
            行 = 行,
            宽 = 临时建筑宽,
            高 = 临时建筑高,
            朝向 = 0,
            占格 = true,
            挡视线 = false,     // 一间小屋，不该在方形视野里挖出一块黑
        };
        var (相对列, 相对行) = 建筑外形.底边中点(null, 临时建筑宽, 临时建筑高);
        物.门口格 = 相对列 < 0 ? -1 : 网格数据.编码(列 + 相对列, 行 + 相对行);
        世界.实体.Add(物);
        return 物;
    }

    public static List<网格实体> 临时建筑列表(网格数据 世界)
        => 世界 == null ? new List<网格实体>() : 世界.取类型(网格实体类型.临时建筑);

    // 临时建筑的门口格（玩家站这一格 = 进去）
    public static (int 列, int 行) 临时建筑门口格(网格实体 物)
    {
        if (物 == null) return (0, 0);
        if (物.门口格 < 0) return (物.列 + 物.宽 / 2, 物.行 + 物.高);
        return (物.门口格 / 1000, 物.门口格 % 1000);
    }

    // ================= 校验（Tools/大世界验证 逐颗种子跑） =================

    public static bool 校验(网格数据 世界, 世界模板 模板)
    {
        if (世界 == null || 模板 == null) return false;
        if (世界.区域摆不下 > 0) return false;
        if (世界.取类型(网格实体类型.玩家).Count != 1) return false;

        var 可达 = 世界.可达集();
        if (可达.Count == 0) return false;
        if (世界.连通分量数() > 1) return false;

        // 营地门口格：可通行 + 可达
        var 门 = 营地门口格(世界);
        if (!世界.可通行(门.列, 门.行)) return false;
        if (!可达.Contains(网格数据.编码(门.列, 门.行))) return false;

        var 营 = 营地实体(世界);
        var 区们 = 区域列表(世界);
        for (int i = 0; i < 区们.Count; i++)
        {
            var a = 区们[i];
            // 界内（四周留 边距）
            if (a.列 < 世界规格.边距 || a.行 < 世界规格.边距 ||
                a.列 + a.宽 > 世界.列 - 世界规格.边距 || a.行 + a.高 > 世界.行 - 世界规格.边距) return false;
            // 掩码连通（一片区域不能是两块飞地）
            if (!建筑外形.连通(a.形状掩码, a.宽, a.高)) return false;
            // 不压营地
            if (营 != null && a.重叠(营)) return false;
            // 互不重叠
            for (int j = i + 1; j < 区们.Count; j++)
                if (a.重叠(区们[j])) return false;
            // 门口格必须在自己的楼体上（否则"走到门口进副本"这条规则落空）
            var 门2 = 区域门口格(a);
            if (!a.覆盖(门2.列, 门2.行)) return false;
        }

        // 障碍不压区域占地 / 不压营地
        foreach (var 障 in 世界.取类型(网格实体类型.障碍))
        {
            foreach (var 区 in 区们) if (区.覆盖(障.列, 障.行)) return false;
            if (营 != null && 营.覆盖(障.列, 障.行)) return false;
        }
        return true;
    }

    private static int 夹(int 值, int 最小, int 最大)
    {
        if (值 < 最小) return 最小;
        if (值 > 最大) return 最大;
        return 值;
    }

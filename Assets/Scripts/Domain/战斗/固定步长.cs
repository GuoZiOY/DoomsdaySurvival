// 固定步长累加器（纯 C#，零 UnityEngine）—— 把"这一帧过了 现实秒"折成"整数个逻辑步 + 余量"。
//
// 为什么需要（审计 D8）：原来 `BattleService.推进战斗` 直接吃 `Time.deltaTime`，
//   而"读条临界点被撞断 / 眩晕到期 / 冷却过零"都精确依赖**这一帧多少秒** →
//   60fps 与 30fps 打出来的结果不同，也没法离线复现玩家报的那一场。
//   切成固定步长后：任何帧率下**每一步都一样**，余量跨帧累积不丢。
//
// 三条口径（都有断言钉住，见 Tools/战斗验证）：
//   ① 余量永远 < 步长（跑完取步数 之后）；
//   ② 不同切分方式喂同样的总时长 → 累计步数**差 ≤ 1**（不是"完全相同"：
//      调用方自己把 0.01f 累加十次也凑不出精确的 0.1f，浮点误差会让某一步延后一拍。
//      关键在于**余量是带过帧的**，误差不会累积——一秒的累计恒在 30±1 步，不会 29、28 一路掉下去）；
//   ③ 卡帧保护：单帧最多 单帧上限 步，超出的部分**丢掉**（宁可慢一点，也不要"一帧补几百步"雪崩：
//      那会让一次卡顿变成下一次卡顿的原因）。
public static class 固定步长
{
    public const float 步长 = 1f / 30f;   // 30Hz 逻辑步：战斗里所有判定都在这个粒度上
    public const int 单帧上限 = 8;        // 一帧最多推进 8 步（≈0.27 秒）

    // 累加 + 取步：返回值 = 这一帧该跑几步；余量用 ref 带过帧
    public static int 取步数(ref float 余量, float 现实秒)
    {
        if (现实秒 > 0f) 余量 += 现实秒;
        if (余量 < 步长) return 0;
        int 步;
        checked { 步 = (int)(余量 / 步长); }
        if (步 > 单帧上限) { 步 = 单帧上限; 余量 = 0f; }   // 见口径 ③：超出部分丢掉
        else 余量 -= 步 * 步长;
        return 步;
    }
}

using System;

// ============================================================
// 伤害计算（纯 C#，零 UnityEngine）—— **全项目唯一的伤害公式权威**。
//
// 为什么抽出来（v51 刀26）：
//   原来是 `BattleService.造成伤害` 一个函数里同时做"判定 + 随机 + 改档案 + 发事件 + 拼富文本"，
//   于是**唯一的伤害公式既不能离线验证、也调不动平衡**（只能进游戏打一把看看）。
//   抽成纯函数后：给定同一批掷点，伤害**逐位相同** → 可离线断言、可批量跑胜率、与帧率无关。
//
// 调用方（BattleService）负责的（有意留在外面）：
//   · 掷点（`UnityEngine.Random.value`）—— 由调用方掷、以参数传进来，纯函数自己不掷；
//     ⚠ **掷点次数必须与拆分前逐路径一致**：无敌 0 次 / 闪避 1 次 / 真实伤害 1 次 / 普通 2 次
//       （次数一变，全局随机序列就变，别处的战斗结果会跟着变）。
//   · 无敌判定与"闪避"早退（要发不同的事件与文案）；
//   · 耐久回写档案、扣血、发事件、拼文本、检查死亡。
//
// ⚠ 取整口径：一律 `(int)Math.Round(...)`（**银行家舍入 / 四舍六入五取偶**）——
//   与 Unity 的 `Mathf.RoundToInt` 完全一致（它内部就是 `(int)Math.Round(f)`）。
//   自己换 `(int)(v + 0.5f)` 会让 2.5 从 2 变成 3，战斗数值就悄悄偏了。
// ============================================================
public struct 伤害输入
{
    public 伤害类型 类型;
    public int 攻击者近战;      // 战斗单位.当前近战（已含 buff 修正）
    public int 攻击者远程;      // 战斗单位.当前远程
    public int 倍率100;         // 100 = 一倍
    public int 附加;            // 技能附加（可为负）
    public float 攻击者暴击率;  // 战斗单位.当前暴击率（调用方已封顶）
    public float 目标防御减伤;  // 战斗单位.防御减伤（0~0.5，调用方已封顶）
    public int 目标抗性百分比;  // 装备抗性（0~50，调用方已封顶）
    public bool 目标防御姿态;
    public float 掷暴击;        // 0~1，调用方掷
}

public struct 伤害结果
{
    public bool 是真实伤害;   // 走的是"无视一切"的分支（文案与耐久都与普通伤害不同）
    public bool 暴击;
    public int 数值;          // 实际扣血（≥1）
}

public static class 伤害计算
{
    public const float 暴击倍率 = 1.5f;
    public const int 抗性上限 = 50;       // %（与 战斗单位 的注释口径一致）
    public const int 物防上限 = 50;       // %（同上）

    // 命中判定：`掷点 >= 命中率 - 目标闪避率` → 被闪避（注意是 >=，相等也算闪避）
    public static bool 是否命中(float 掷点, float 命中率, float 目标闪避率)
        => !(掷点 >= 命中率 - 目标闪避率);

    // 伤害数值（**调用方已确认命中、且目标不无敌**）
    // 判定顺序照抄拆分前：真实伤害 → 基础伤害 → 暴击 → 防御% → 抗性% → 防御姿态，**每一步都夹下限 1**
    public static 伤害结果 计算(伤害输入 入)
    {
        // 真实伤害：无视命中/攻防/暴击/抗性（毒伤/固定伤走这条）
        if (入.类型 == 伤害类型.真实)
            return new 伤害结果 { 是真实伤害 = true, 暴击 = false, 数值 = Max(1, 入.倍率100 + 入.附加) };

        int 基础攻 = 入.类型 == 伤害类型.远程 ? 入.攻击者远程 : 入.攻击者近战;
        int 基础伤害 = Max(1, 取整(基础攻 * 入.倍率100 / 100f) + 入.附加);
        bool 暴击 = 入.掷暴击 < 入.攻击者暴击率;
        if (暴击) 基础伤害 = 取整(基础伤害 * 暴击倍率);

        int 伤害 = Max(1, 取整(基础伤害 * (1f - 入.目标防御减伤)));
        if (入.目标抗性百分比 > 0) 伤害 = Max(1, 取整(伤害 * (1f - 入.目标抗性百分比 / 100f)));
        if (入.目标防御姿态) 伤害 = Max(1, 取整(伤害 * 0.5f));
        return new 伤害结果 { 是真实伤害 = false, 暴击 = 暴击, 数值 = 伤害 };
    }

    private static int 取整(float v) => (int)Math.Round(v);   // 见文件头：银行家舍入，与 Mathf.RoundToInt 同
    private static int Max(int a, int b) => a > b ? a : b;
}

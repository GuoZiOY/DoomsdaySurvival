using System;

// ============================================================
// 随机源：战斗的**可播种**随机数来源（v51 刀33 / 档2 #26）。
//
// 为什么需要（原来什么样）：
//   · 战斗里 7 处直接掷 `UnityEngine.Random`（全局静态：不能按战斗播种，序列还会被特效/UI 搅动）；
//   · `战斗单位.Random(上限)` 每次 `new System.Random()`（按时间播种 → 不可复现；同帧连建两个实例还会拿到相关的数）；
//   · 后果：**一场战斗无法复现** —— 玩家报"这场打不过/卡住"，只能靠运气再碰一次；
//     胜率也只能靠手感试（P7 调敌人权重就没有依据）。
// 现在：一场战斗 = 初始状态 + 种子 的纯函数（同种子两遍，逐次掷点完全一致）。
//
// 口径（与 UnityEngine 对齐，**别改**，改了等于悄悄改数值期望）：
//   值()      ~ `Random.value`        → [0.0, 1.0)（Unity 是 [0,1]；恰好等于 1.0 的概率为 0，
//                                        对 `值() < 概率` 这类比较没有任何差别）
//   范围(a,b) ~ `Random.Range(a,b)`   → 整数 **左闭右开** [a, b)；b <= a 时退化为 a（与 Unity 一致）
//   范围含(a,b)                        → 左闭右闭 [a, b]（Unity 的 `Range(float,float)` 才是双闭；
//                                        这里显式给名字，免得用错端点）
//
// 用法纪律：**掷点留在服务层**（域层只做判定，掷点当参数传进去 —— 见 伤害计算.cs / 敌人AI.cs 的注释）。
//   所以本类只给 Services/战斗 用；Domain 里谁都不许自己掷。
// ============================================================
public sealed class 随机源
{
    public int 种子 { get; }

    private readonly Random 流;

    public 随机源(int 种子)
    {
        this.种子 = 种子;
        this.流 = new Random(种子);
        // 注：`new Random(种子)` 在 net10.0 / Mono / IL2CPP 上逐字符一致（`docs/优化实施进度.md` §五 已实测盖章），
        //     所以"离线验证器跑出来的战斗"与"游戏里那一场"是同一条序列 —— 复现才有意义。
    }

    public float 值() => (float)流.NextDouble();

    public int 范围(int 最小, int 最大) => 最大 <= 最小 ? 最小 : 流.Next(最小, 最大);

    public int 范围含(int 最小, int 最大) => 最大 <= 最小 ? 最小 : 流.Next(最小, 最大 + 1);
}

using System;
using System.Collections.Generic;

// ============================================================
// 建筑生成器：一栋楼 = 楼层表 + 一部楼梯（纯 C#，可离线跑种子自检）。
//   ① 楼梯位：按**建筑种子**算一次（边 + 沿边第几格）→ 全楼共用同一格（楼上楼下才对得齐）；
//   ② 每层 = 房间生成器.生成(层种子, 该层首间房模板, …, 含大门: 该层.大门, 楼梯: 楼梯位)
//      —— 层种子 = 派生(建筑种子, "F层号")，同一颗种子下每层的柜子/敌人也是固定的；
//   ③ 一层多间房（第 1 刀不填）：门在**本层内**横向串联，由 房间模板.门 自己声明，跨层一律走楼梯。
// 硬规则：同一栋楼所有楼层同尺寸（= 建筑模板.列×行）；各层 房间[0]（楼梯间）的模板尺寸必须与它一致。
// 不变量（建筑验证 逐颗种子断言）：
//   ① 每一层都有且只有一部楼梯，且**坐标全楼相同**；
//   ② 楼梯格上原本那格墙没了、可通行（能站上去 = 能上下楼），楼梯内侧格从入口可达；
//   ③ 每层的门都在本层内（门.通向 属于该层的 房间 列表）；
//   ④ 同种子 + 同建筑 = 同布局（确定性）。
// ============================================================
public static class 建筑生成器
{
    // 内容取用直接沿用 房间生成器 的两个委托类型（同一个签名，不要另立门户——否则传参会类型不匹配）
    //   public delegate List<搜索容器> 容器表取用(string 地图类型, string 房间);
    //   public delegate List<string> 敌人组取用(string 敌人组标识);

    // ================= 楼梯位（全楼共用） =================

    // 楼梯位 = (开在哪条外墙边, 沿边第几格)。楼梯位 = -1 时取中点按种子抖一下（同一种子固定）。
    public static (int 边, int 号) 楼梯位(int 建筑种子, 建筑模板 模板)
    {
        int 边 = 边码(模板?.楼梯边);
        int 列 = 夹(模板?.列 ?? 16, 房间生成器.最小列, 房间生成器.最大列);
        int 行 = 夹(模板?.行 ?? 10, 房间生成器.最小行, 房间生成器.最大行);
        int 长 = (边 == 0 || 边 == 2) ? 列 : 行;
        int 号;
        if (模板 != null && 模板.楼梯位 >= 0) 号 = 模板.楼梯位;
        else
        {
            var 流 = 确定性随机.随机流(确定性随机.派生(建筑种子, "楼梯位"));
            号 = 长 / 2 + 确定性随机.范围(流, -2, 2);
        }
        // 和门一样离墙角 ≥2 格（门离角），否则"凸"会顶在角上
        if (长 - 1 - 房间生成器.门离角 >= 房间生成器.门离角)
            号 = 夹(号, 房间生成器.门离角, 长 - 1 - 房间生成器.门离角);
        return (边, 号);
    }

    // ================= 生成一层 =================

    // 生成第 层（0 基）：返回这一层的**首间房**（= 楼梯间，从区域/大门/楼梯进来的那间）。
    // 同层的其它房间（房间[1..]）由 房间探索服务 在走门时按需生成（同一套层种子）。
    public static 网格数据 生成楼层(int 建筑种子, 建筑模板 模板, int 层, 房间生成器.容器表取用 取容器, 房间生成器.敌人组取用 取敌人,
                                  Func<string, 房间模板> 取房间模板)
    {
        if (模板?.楼层 == null || 层 < 0 || 层 >= 模板.楼层.Length) return null;
        var 楼层项 = 模板.楼层[层];
        if (楼层项?.房间 == null || 楼层项.房间.Length == 0) return null;
        var 房模板 = 取房间模板?.Invoke(楼层项.房间[0]);
        if (房模板 == null) return null;
        var 位 = 楼梯位(建筑种子, 模板);
        return 房间生成器.生成(层号种子(建筑种子, 层), 房模板, 取容器, 取敌人, 含大门: 楼层项.大门, 楼梯: 位);
    }

    // 生成同层第 序号 间房（序号 0 = 楼梯间；其余房间没有楼梯、也没有大门）
    public static 网格数据 生成房间(int 建筑种子, 建筑模板 模板, int 层, int 序号,
                                  房间生成器.容器表取用 取容器, 房间生成器.敌人组取用 取敌人, Func<string, 房间模板> 取房间模板)
    {
        if (模板?.楼层 == null || 层 < 0 || 层 >= 模板.楼层.Length) return null;
        var 楼层项 = 模板.楼层[层];
        if (楼层项?.房间 == null || 序号 < 0 || 序号 >= 楼层项.房间.Length) return null;
        var 房模板 = 取房间模板?.Invoke(楼层项.房间[序号]);
        if (房模板 == null) return null;
        bool 是首间 = 序号 == 0;
        var 位 = 楼梯位(建筑种子, 模板);
        return 房间生成器.生成(房间种子(建筑种子, 层, 序号), 房模板, 取容器, 取敌人,
                          含大门: 是首间 && 楼层项.大门, 楼梯: 是首间 ? 位 : ((int, int)?)null);
    }

    // ================= 种子 / 名字 =================

    // 层种子：同一颗建筑种子下，每层固定（换层回来柜子还是那批）
    public static int 层号种子(int 建筑种子, int 层) => 确定性随机.派生(建筑种子, $"F{层}");

    // 房间种子：层 + 序号 + 模板三重进键 —— 同一层两间"杂物间"也是两份不同内容
    public static int 房间种子(int 建筑种子, int 层, int 序号)
        => 确定性随机.派生(建筑种子, $"F{层}#{序号}");

    // 楼层显示名：楼层.名称 优先，空则 "N F"
    public static string 楼层名(建筑模板 模板, int 层)
    {
        if (模板?.楼层 == null || 层 < 0 || 层 >= 模板.楼层.Length) return "";
        var 项 = 模板.楼层[层];
        return string.IsNullOrEmpty(项?.名称) ? $"{层 + 1}F" : 项.名称;
    }

    // 楼层数
    public static int 楼层数(建筑模板 模板) => 模板?.楼层?.Length ?? 0;

    // 第 层 有没有大门（有 = 从外面/区域进来就落在这一层）
    public static bool 有大门的层(建筑模板 模板, int 层)
        => 模板?.楼层 != null && 层 >= 0 && 层 < 模板.楼层.Length && 模板.楼层[层] != null && 模板.楼层[层].大门;

    // 进来时该落在哪一层（有大门那层；没有就 1F）
    public static int 入口层(建筑模板 模板)
    {
        int 数 = 楼层数(模板);
        for (int i = 0; i < 数; i++) if (有大门的层(模板, i)) return i;
        return 0;
    }

    // 第 层、模板 标识 是这一层的第几间（找不到 = -1）——走门时用它算出"同层哪一间"
    public static int 房间序号(建筑模板 模板, int 层, string 房间模板标识)
    {
        if (模板?.楼层 == null || 层 < 0 || 层 >= 模板.楼层.Length) return -1;
        var 房间 = 模板.楼层[层]?.房间;
        if (房间 == null) return -1;
        for (int i = 0; i < 房间.Length; i++) if (房间[i] == 房间模板标识) return i;
        return -1;
    }

    private static int 边码(string 边)
    {
        if (边 == "上") return 2;
        if (边 == "左") return 1;
        if (边 == "右") return 3;
        return 0;   // 默认 下
    }

    private static int 夹(int 值, int 最小, int 最大)
    {
        if (值 < 最小) return 最小;
        if (值 > 最大) return 最大;
        return 值;
    }
}

using System;

// 生存管理器：生命/行动点/饱食/水分/伤病/时间 领域逻辑（玩家档案 组合的子管理器——职责分离、调度器模式）。
// 负责：状态 增减/夹取；每小时生存结算/睡觉；状态驱动 派生数值（最大生命/最大行动点/速度/修正系数）。
// 数据（状态字段/天赋/解析委托）由 玩家档案 持有；装备加成 经 玩家.装备管理 读取。
public sealed class 生存管理器
{
    public readonly 玩家档案 玩家;
    public 生存管理器(玩家档案 玩家) { this.玩家 = 玩家; }

    // —— 状态 操作 ——

    public void 恢复生命(int 数值) => 玩家.生命 = 夹(玩家.生命 + 数值, 0, 最大生命);
    public void 受到伤害(int 数值) => 玩家.生命 = Math.Max(0, 玩家.生命 - 数值);

    public bool 消耗行动点(int 数值)
    {
        if (玩家.行动点 < 数值) return false;
        玩家.行动点 -= 数值;
        return true;
    }
    public void 恢复行动点(int 数值) => 玩家.行动点 = 夹(玩家.行动点 + 数值, 0, 最大行动点);

    public void 进食(int 数值) => 玩家.饱食度 = 夹(玩家.饱食度 + 数值, 0, 100);
    public void 饮水(int 数值) => 玩家.水分度 = 夹(玩家.水分度 + 数值, 0, 100);

    public void 调整伤病(伤病类型 类型, int 数值)
    {
        switch (类型)
        {
            case 伤病类型.疲劳: 玩家.疲劳 = 夹(玩家.疲劳 + 数值, 0, 100); break;
            case 伤病类型.中毒: 玩家.中毒 = 夹(玩家.中毒 + 数值, 0, 100); break;
            case 伤病类型.感冒: 玩家.感冒 = 夹(玩家.感冒 + 数值, 0, 100); break;
            case 伤病类型.流血: 玩家.流血 = 夹(玩家.流血 + 数值, 0, 100); break;
            case 伤病类型.骨折: 玩家.骨折 = 夹(玩家.骨折 + 数值, 0, 100); break;
            case 伤病类型.发烧: 玩家.发烧 = 夹(玩家.发烧 + 数值, 0, 100); break;
        }
    }

    public int 伤病值(伤病类型 类型)
    {
        switch (类型)
        {
            case 伤病类型.疲劳: return 玩家.疲劳;
            case 伤病类型.中毒: return 玩家.中毒;
            case 伤病类型.感冒: return 玩家.感冒;
            case 伤病类型.流血: return 玩家.流血;
            case 伤病类型.骨折: return 玩家.骨折;
            case 伤病类型.发烧: return 玩家.发烧;
            default: return 0;
        }
    }

    // —— 每小时生存结算（游戏时钟调用）：饱食/水分下降 + 伤病持续影响 ——
    public void 每小时结算(天气类型 天气)
    {
        // 饱食/水分随时间下降（体质/天赋修正）
        玩家.饱食度 = 夹(玩家.饱食度 - (int)(2 * 饱食下降修正), 0, 100);
        玩家.水分度 = 夹(玩家.水分度 - (int)(3 * 水分下降修正), 0, 100);
        // 雨天：水分不降（自动补水）；酷暑：水分消耗↑
        if (天气 == 天气类型.雨 || 天气 == 天气类型.雷雨) 玩家.水分度 = 夹(玩家.水分度 + 1, 0, 100);
        if (天气 == 天气类型.酷暑) 玩家.水分度 = 夹(玩家.水分度 - 2, 0, 100);
        // 寒潮：无火炉/厚衣可能感冒（感冒概率由 意志 抵抗；慢性病天赋 ×2）
        if (天气 == 天气类型.寒潮 && 玩家.感冒 == 0)
        {
            int 感冒阈值 = 玩家.意志 * 3;
            if (玩家.天赋.Contains("慢性病")) 感冒阈值 /= 2;
            if (随机(100) > 感冒阈值) 玩家.感冒 = 5;
        }
        // 疲劳缓慢恢复（行动时累积，这里基础恢复）
        玩家.疲劳 = 夹(玩家.疲劳 - 1, 0, 100);
        // 伤病持续掉血
        if (玩家.流血 > 0) 受到伤害(玩家.流血 / 20 + 1);
        if (玩家.中毒 > 0) 受到伤害(玩家.中毒 / 25 + 1);
        if (玩家.发烧 > 0) 受到伤害(玩家.发烧 / 30 + 1);
        // 饱食/水分归零：不致死，只削弱（持续少量掉血警示）
        if (玩家.饱食度 <= 0) 受到伤害(1);
        if (玩家.水分度 <= 0) 受到伤害(2);
    }

    // —— 睡觉结算（回营地睡觉）：恢复生命/行动点/疲劳，推进时间到次日 6:00 ——
    public void 睡觉()
    {
        // 失眠天赋：恢复 -40%
        float 恢复系数 = 玩家.天赋.Contains("失眠") ? 0.6f : 1f;
        玩家.生命 = Math.Max(1, (int)(最大生命 * 恢复系数));
        玩家.行动点 = Math.Max(1, (int)(最大行动点 * 恢复系数));
        玩家.疲劳 = Math.Max(0, (int)(玩家.疲劳 * (1 - 0.8f * 恢复系数)));
        玩家.感冒 = Math.Max(0, 玩家.感冒 - (int)(20 * 恢复系数));
        玩家.流血 = Math.Max(0, 玩家.流血 - (int)(30 * 恢复系数));
        玩家.发烧 = Math.Max(0, 玩家.发烧 - (int)(15 * 恢复系数));
        玩家.中毒 = Math.Max(0, 玩家.中毒 - (int)(10 * 恢复系数));
        // 推进时间到次日 6:00
        玩家.游戏分钟数 = (玩家.游戏天数 + 1) * 1440f + 360f;
    }

    // —— 状态驱动 派生数值 ——

    // 生命上限：100 + 每点体质 +8（超出基础5）+ 每级 +5 + 装备/词缀
    public int 最大生命 => 100 + (玩家.体质 - 5) * 8 + (玩家.等级 - 1) * 5
        + 玩家.装备管理.装备总加成(玩家.生命加成解析) + 玩家.装备管理.词缀总数值(词缀属性.生命);

    // 行动点上限：100 + 体质×2 + 等级×2
    public int 最大行动点 => 100 + 玩家.体质 * 2 + 玩家.等级 * 2;

    // 速度：敏捷×2 + 装备/词缀速度（行动序 + 逃跑；伤病削弱）
    public int 速度 => Math.Max(1, 玩家.敏捷 * 2 + 玩家.装备管理.词缀总数值(词缀属性.速度)
        - (玩家.骨折 > 0 ? 玩家.骨折 / 10 : 0) - (玩家.疲劳 > 50 ? 玩家.疲劳 / 10 : 0));

    // 饱食下降速度修正（体质减缓；天赋"铁胃"减缓、"胃口大"加速）
    public float 饱食下降修正
    {
        get
        {
            float 修正 = 1f - (玩家.体质 - 5) * 0.04f;   // 每点体质 -4%
            if (玩家.天赋.Contains("铁胃")) 修正 -= 0.15f;
            if (玩家.天赋.Contains("胃口大")) 修正 += 0.6f;
            return Math.Max(0.2f, 修正);
        }
    }

    // 水分下降速度修正（体质减缓；天赋"口渴快"加速）
    public float 水分下降修正
    {
        get
        {
            float 修正 = 1f - (玩家.体质 - 5) * 0.04f;
            if (玩家.天赋.Contains("口渴快")) 修正 += 0.6f;
            return Math.Max(0.2f, 修正);
        }
    }

    // 伤病致弱（感冒/发烧/中毒 全属性惩罚）
    public float 伤病削弱
    {
        get
        {
            float 削弱 = 0f;
            if (玩家.感冒 > 0) 削弱 += 玩家.感冒 / 200f;
            if (玩家.发烧 > 0) 削弱 += 玩家.发烧 / 150f;
            if (玩家.中毒 > 0) 削弱 += 玩家.中毒 / 200f;
            return Math.Min(0.5f, 削弱);
        }
    }

    // —— 工具 ——
    private static int 夹(int 值, int 最小, int 最大) => 值 < 最小 ? 最小 : (值 > 最大 ? 最大 : 值);
    private static int 随机(int 上限) => 上限 <= 0 ? 0 : new System.Random().Next(上限);
}

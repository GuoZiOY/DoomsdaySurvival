// 整点结算的**纯计算**（零 UnityEngine 依赖）——v52 刀64 从 世界时间管理器 里抽出来的。
//
// 为什么必须抽出来：原来这段 while 只活在 `世界时间管理器.推进()` 里，而那个类吃 UnityEngine
// （Mathf / Random / Debug）→ 离线验证器根本编译不了它，只能"照着源码再写一遍"来断言 ——
// 项目自己的评估（06 §3 / 探索接线核对 的注释）点名批评过这种"验的是副本，不是代码"。
// 抽到这里之后，游戏与验证器跑的是**同一个函数**（Tools/存档验证 通过 <Compile Include> 链接本文件）。
//
// 这段计算之所以值得单独立案：它是"读档即死"那个 bug 的现场。
//   `上次结算分钟`（基准）是纯运行期字段、初值 0，而 推进() 是"从基准追到当前时间，每满 60 分钟结算一次"。
//   读一张第 5 天的档（游戏分钟数 = 7200）而基准还是 0 → 应结算次数 = 120 →
//   同一帧里扣 120 次"1 小时生存"：饱食/水分归零 → 按 3 点/小时扣满血 → 腐坏结算把仓库清空。
public static class 整点结算
{
    // 一个整点的游戏分钟数（也是 结算时间段 的粒度）
    public const float 整点分钟 = 60f;

    // 一天的游戏分钟数（跨天 / 自愈阈值 用）
    public const float 一天分钟 = 1440f;

    // 单次调用最多结算多少个整点。**这是防呆上限，不是语义上限** ——
    // 正常运行时 需要重对齐() 已经把"基准与当前时间差 1 天以上"那条路拦掉了，
    // 所以真实路径上这个数永远不会接近。它只为"基准被写坏成 -1e9"这种输入兜底：
    // 没有它，while 会空转 1600 万次，一帧卡死。
    // 取 365 天：任何**合法**的补算（哪怕挂机一整年）都不会被截断，而天文数字会被截断。
    // （曾经写成 24+2 = 26，被 Tools/存档验证 的"基准 0 + 第 5 天 = 120 次"这条断言当场抓出来 ——
    //   26 会把 120 截成 26，等于把"读档即死"这件事**藏起来**，那正是这条断言要防的。）
    public const int 单次上限 = 365 * 24;

    // 从 基准 追到 当前分钟，需要结算多少个整点；`新基准` = 追完之后的基准。
    // 与老代码逐字同源（`while ((int)(当前/60) > (int)(基准/60)) { 基准 += 60; ... }`）——
    // 用 (int) 截断而不是"差 / 60"，是为了与"整点时刻"对齐（7:59 不结算，8:00 才结算）。
    public static int 应结算次数(float 当前分钟, float 基准分钟, out float 新基准)
    {
        新基准 = 基准分钟;
        if (当前分钟 < 0f) 当前分钟 = 0f;
        int 次数 = 0;
        while ((int)(当前分钟 / 整点分钟) > (int)(新基准 / 整点分钟) && 次数 < 单次上限)
        {
            新基准 += 整点分钟;
            次数++;
        }
        return 次数;
    }

    // 基准是否需要"自愈重对齐"：与当前时间差超过 1 游戏天，或者基准跑到了当前时间的**前面**（时间倒退）。
    //   差 > 1 天  → 某个入口忘了对齐（新游戏 / 读档）→ 不修就会补算天文数字次结算；
    //   差 < -1 分  → 时间倒退（新游戏重置到 420 / 读档换档 / 制作取消回滚）→ 不修就会"白送时间"：
    //                 基准在未来，while 一次都不结算，玩家可以几天不吃不喝。
    // 阈值取 1 天而不是 1 整点：合法的单帧大推进（应用挂起恢复）只有几分钟，不该被这条吞掉。
    public static bool 需要重对齐(float 当前分钟, float 基准分钟) => 需要重对齐(当前分钟, 基准分钟, out _);

    public static bool 需要重对齐(float 当前分钟, float 基准分钟, out float 差)
    {
        差 = 当前分钟 - 基准分钟;
        return 差 > 一天分钟 || 差 < -1f;
    }
}

using System;
using System.Collections.Generic;

// ============================================================
// 战局快照的载荷形状（纯 C#，零 UnityEngine 依赖）—— v52 刀65。
//
// 为什么需要它：刀64 让存档"读得回来且不会读档即死"，但**读档仍然回不到原地**
// （读档 = 用 世界种子 重建同一座废城，玩家落营地门口格）。刀65 补上这一半：
// **存档时你在哪一层、哪一格、周围翻过什么、敌人在哪，读回来一模一样。**
//
// 三条硬约束（勘察结论，决定了这里为什么是"快照"而不是"增量 + 种子重建"）：
//   ① 柜子内容来自 **无种子** `System.Random`（搜索服务.cs:14）→ 不可复现，必须真存内容；
//   ② 一次性临时建筑内部用 `UnityEngine.Random` 播种、标识还依赖 `搜索次数` → 同样不可复现；
//   ③ **三层世界的敌人同时在跑**（世界时间管理器 每帧喂三层，而进楼/进区域时上层 `当前世界` 并不清空）
//      → 要存"所有**活着的**层"，不只是玩家站的这一层。
//
// 一个必须记住的坑：`网格实体.容器定义` 是**指向 DataService 模板的共享引用**
// （房间生成器.cs:166 `容器定义 = 定`）。直接序列化 网格数据 会把每张搜索表复制进存档；
// 所以快照里 `容器定义` **置空**，只留实体上本来就有的 `定义标识`，读档时按它回填。
// ============================================================

// 一个敌人的 AI 运行期态（键 = 敌人**实例标识**）。
// 为什么要存它：不存的话，读档后那只"正在追你"的敌人会退回静默 —— 位置对了但状态不对。
// 拍平成一"条"是因为 JsonUtility 不支持 `Dictionary<网格实体, 敌人AI态>`（键还是对象引用）。
[Serializable]
public class 敌人态条
{
    public string 敌标识 = "";
    public 大世界敌人AI.敌人AI态 态;
}

// 一个容器的战局（键 = 搜索服务 用的**实例标识**：容器是 `{当前种子}#{实体标识}`，尸体是 `尸体_N`）。
[Serializable]
public class 容器战局条
{
    public string 实例标识 = "";
    public 网格服务 视图;                  // 已生成的内容（含每件物品的 列/行/旋转/耐久/嵌套容器）
    // "已搜过"的物品：**按 (标识,列,行) 记键**，不存下标也不存引用。
    //   不存下标的理由：玩家拿走一件物品会让 网格物品 的下标整体位移，存下标读回来就串了；
    //   (标识,列,行) 在一个容器内唯一（每件占着各自的格），且拿走后那条记录自然找不到 → 自动失效。
    //   不存引用的理由：JsonUtility 存不了对象引用。
    public List<string> 已搜物品 = new List<string>();
}

// 一层世界的快照（大世界 / 区域 / 建筑里的某一层 / 单间房间，各自一份）。
[Serializable]
public class 层快照
{
    public const int 类大世界 = 1, 类区域 = 2, 类房间 = 3;   // 类房间 = 建筑内某层 或 单间房间

    public int 层类 = 类大世界;             // 这份快照属于哪一个服务
    public int 层号 = -1;                  // 仅"建筑内"有意义（第几层）；单间 = -1
    public string 标识 = "";                // 当前世界的 模板标识（区域标识 / 建筑标识 / 房间模板 / 世界标识）
    public int 种子;                        // 当前种子（重建时喂给 进入X()，读回来要一致）
    public string 迷雾 = "";                // 已探索 位图（房间层不在档案的永久迷雾里，所以必须随快照走）
    public 网格数据 世界;                   // 实体位置 / 已搜标记 / 门锁 / 敌人位置（容器定义已置空）
    public List<敌人态条> 敌人们 = new List<敌人态条>();
}

// 整个战局：玩家在哪一层 + 每层怎么重建 + 每层的快照 + 玩家格。
[Serializable]
public class 存档战局
{
    public const int 层安全屋 = 0, 层大世界 = 1, 层区域 = 2, 层建筑 = 3, 层单间 = 4;

    public int 层 = 层安全屋;               // 玩家存档时在哪

    // —— 重建链路（由外向内；只填到玩家所在那一层为止）——
    public string 大世界标识 = "";
    public int 大世界种子;
    public string 区域标识 = "";            // 区域模板标识（层 >= 区域 时有效）
    public int 区域种子;
    public string 建筑标识 = "";            // 区域生成产物 "{区模板}#建筑N"（层 == 建筑 时有效）
    public int 建筑种子;
    public int 建筑层 = -1;
    public string 房间模板 = "";            // 单间房间的模板标识（层 == 单间 时有效）

    public int 玩家列, 玩家行;               // 玩家在最内层世界里的格

    // 所有**活着的**层（由外向内）。为什么不是只有一层：见文件头 ③。
    public List<层快照> 活层 = new List<层快照>();

    // 容器战局（**全局一份**，不放进 层快照）：`搜索服务` 本身就是全局单例，
    // 而且它的键是 `{当前种子}#{实体标识}`（种子带在键里）→ 不同层的容器天然不会撞名。
    public List<容器战局条> 容器们 = new List<容器战局条>();

    // 单间房间/临时建筑那个世界的实际种子（**不能**由 世界种子 派生 ——
    // 一次性临时建筑是 `UnityEngine.Random` 播的种，不可复现），所以直接存快照里的种子。
    public int 单间种子;

    public 层快照 找(int 层类)
    {
        if (活层 == null) return null;
        foreach (var 快 in 活层) if (快 != null && 快.层类 == 层类) return 快;
        return null;
    }

    // 给 存档头.位置 用的人类可读文本（存档面板列表显示"你存在哪儿"）
    public string 位置文本()
    {
        switch (层)
        {
            case 层大世界: return string.IsNullOrEmpty(大世界标识) ? "大世界" : $"大世界 · {大世界标识}";
            case 层区域: return string.IsNullOrEmpty(区域标识) ? "区域" : $"区域 · {区域标识}";
            case 层建筑: return $"楼内 · {建筑标识} {建筑层 + 1}F";
            case 层单间: return string.IsNullOrEmpty(房间模板) ? "房间" : $"房间 · {房间模板}";
            default: return "安全屋";
        }
    }
}

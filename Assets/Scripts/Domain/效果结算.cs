
    // 剧情效果结算：对玩家档案生效并发布对应事件。逻辑不直接碰 UI，UI 订阅事件刷新。
    public static class 效果结算
    {
        public static void 应用(EventBus 事件, 玩家档案 玩家, 剧情效果 效果)
        {
            if (效果 == null) return;

            // 生命：正=恢复，负=伤害
            if (效果.生命 != 0)
            {
                玩家.恢复生命(效果.生命);
                事件.发布(new 生命变化事件(玩家.生命, 玩家.最大生命, 效果.生命));
            }

            // 行动点（原"魔力/精力"合并语义：剧情效果.魔力 = 行动点恢复）
            if (效果.魔力 != 0)
            {
                玩家.恢复行动点(效果.魔力);
                事件.发布(new 精力变化事件(玩家.行动点, 玩家.最大行动点, 效果.魔力));
            }

            // 精力：正=恢复，负=消耗（休息事件等）——映射行动点
            if (效果.精力 != 0)
            {
                玩家.恢复行动点(效果.精力);
                事件.发布(new 精力变化事件(玩家.行动点, 玩家.最大行动点, 效果.精力));
            }

            // 生存状态（末日新增：饥饿/口渴/疲劳/感染/士气/噪音）
            if (效果.饥饿 != 0)
            {
                玩家.调整生存状态(生存状态类型.饥饿, 效果.饥饿);
                事件.发布(new 生存状态变化事件(生存状态类型.饥饿, 玩家.饥饿, 效果.饥饿));
            }
            if (效果.口渴 != 0)
            {
                玩家.调整生存状态(生存状态类型.口渴, 效果.口渴);
                事件.发布(new 生存状态变化事件(生存状态类型.口渴, 玩家.口渴, 效果.口渴));
            }
            if (效果.疲劳 != 0)
            {
                玩家.调整生存状态(生存状态类型.疲劳, 效果.疲劳);
                事件.发布(new 生存状态变化事件(生存状态类型.疲劳, 玩家.疲劳, 效果.疲劳));
            }
            if (效果.感染 != 0)
            {
                玩家.调整生存状态(生存状态类型.感染度, 效果.感染);
                事件.发布(new 生存状态变化事件(生存状态类型.感染度, 玩家.感染度, 效果.感染));
            }
            if (效果.士气 != 0)
            {
                玩家.调整生存状态(生存状态类型.士气, 效果.士气);
                事件.发布(new 生存状态变化事件(生存状态类型.士气, 玩家.士气, 效果.士气));
            }

            // 铜币（剧情效果.金币 字段单位 = 铜币）
            if (效果.金币 != 0)
            {
                玩家.铜币 += 效果.金币;
                事件.发布(new 金币变化事件(玩家.铜币, 效果.金币));
            }

            // 经验（可能触发升级；升级给自由点，发布属性事件刷新角色面板）
            if (效果.经验 != 0)
            {
                bool 升级了 = 玩家.获得经验(效果.经验);
                事件.发布(new 经验变化事件(玩家.等级, 玩家.经验, 玩家.升级所需经验, 升级了));
                if (升级了)
                    事件.发布(new 属性变化事件(玩家.体质, 玩家.力量, 玩家.智慧, 玩家.敏捷, 玩家.意志, 玩家.自由属性点));
            }

            // 获得物品（获得数量 缺省 1）
            if (!string.IsNullOrEmpty(效果.获得物品))
            {
                int 数量 = 效果.获得数量 > 0 ? 效果.获得数量 : 1;
                玩家.添加物品(效果.获得物品, 数量);
                事件.发布(new 背包变化事件(效果.获得物品, 数量, 变化原因.获得));
            }

            // 获得物品表（一次获得多种）
            if (效果.获得物品表 != null)
                foreach (var 项 in 效果.获得物品表)
                {
                    if (string.IsNullOrEmpty(项.标识)) continue;
                    int 数量 = 项.数量 > 0 ? 项.数量 : 1;
                    玩家.添加物品(项.标识, 数量);
                    事件.发布(new 背包变化事件(项.标识, 数量, 变化原因.获得));
                }

            // 失去物品（无则忽略）
            if (!string.IsNullOrEmpty(效果.失去物品))
            {
                if (玩家.移除物品(效果.失去物品))
                    事件.发布(new 背包变化事件(效果.失去物品, -1, 变化原因.失去));
            }

            // 失去物品表（一次失去多种，修桥交付等）
            if (效果.失去物品表 != null)
                foreach (var 项 in 效果.失去物品表)
                {
                    if (string.IsNullOrEmpty(项.标识)) continue;
                    int 数量 = 项.数量 > 0 ? 项.数量 : 1;
                    if (玩家.移除物品(项.标识, 数量))
                        事件.发布(new 背包变化事件(项.标识, -数量, 变化原因.失去));
                }
        }
    }

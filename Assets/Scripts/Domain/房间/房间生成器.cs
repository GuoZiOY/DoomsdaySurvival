using System;
using System.Collections.Generic;

// ============================================================
// 房间生成器：一个「完全中空的大房间」，按种子摆可搜索容器与敌人（纯 C#，可离线跑 200 种子自检）。
// 三阶段：定尺（抽内容清单）→ **约束摆放**（引擎在 Domain/网格/约束摆放.cs：分区块 + 大件优先 + 约束采样）
//         → 连通校验与重试（保底布局兜底）。
// 本文件只负责"房间语义"：造壳（墙 / 入口 / 门）、抽内容（容器 / 敌人）、校验与保底布局怎么摆。
// 不变量（任何一条破了就是 bug）：
//   ① 物件不越界、不重叠、不压通道格（入口格 + 门格 + 门内侧格）；两个占位物之间至少隔 1 格走道；
//   ② 每个容器至少有一个相邻可站格，且该格与入口连通（否则就是"看得见搜不着的死内容"）；
//   ③ 每个敌人的相邻可站格同样与入口连通；
//   ④ 可站格无孤岛（连通分量 = 1）；
//   ⑤ 每扇门的内侧格都必须从入口走得到（门是结构，堵了就没法修，只能在摆放阶段避开）；
//   ⑥ 同模板 + 同种子 = 同布局（确定性）。
// ============================================================
public static class 房间生成器
{
    // 容器表取用：(地图类型, 房间) → 该房间的容器定义列表（房间 传空 = 该地图类型下全部房间）
    public delegate List<搜索容器> 容器表取用(string 地图类型, string 房间);
    // 敌人组取用：敌人组标识 → 展开成「一只一项」的敌人定义标识列表
    public delegate List<string> 敌人组取用(string 敌人组标识);

    public const int 最大重掷 = 5;
    public const int 最小列 = 8, 最大列 = 26;
    public const int 最小行 = 6, 最大行 = 18;

    // 门的位置约束：离墙角 ≥2 格、同一条边上两扇门 ≥3 格（都为了让门框与走道好看、不贴角）
    public const int 门离角 = 2;
    public const int 门间距 = 3;

    // 含大门 = false：这间房不是"这一趟进来的第一间"，就不在外墙上开那扇通向外面的大门
    // 楼梯 = (边, 沿边第几格)：建筑层专用 —— 外墙上那一格"凸"（上下楼就走它），不传 = 这间房没有楼梯
    public static 网格数据 生成(int 种子, 房间模板 模板, 容器表取用 取容器, 敌人组取用 取敌人, bool 含大门 = true,
                              (int 边, int 号)? 楼梯 = null)
    {
        if (模板 == null) return null;

        int 容器下限, 敌人下限;
        var 容器清单 = 抽容器(种子, 模板, 取容器, out 容器下限);
        var 敌人清单 = 抽敌人(种子, 模板, 取敌人, out 敌人下限);
        // 占位物只跟"内容清单"有关（与房间实例无关）→ 重掷/保底共用同一份，标识序号由引擎给
        var 容器占位 = 造容器占位(容器清单);
        var 敌人占位 = 造敌人占位(敌人清单);

        for (int 次 = 0; 次 <= 最大重掷; 次++)
        {
            var 房 = 造空房(种子, 模板, 含大门, 楼梯);
            摆物件(房, 种子, 次, 容器占位, 敌人占位);
            if (校验(房, 容器下限, 敌人下限))
            {
                房.重掷次数 = 次;
                return 房;
            }
        }

        // 兜底：沿内墙一圈隔格摆（天然保证走道与连通），敌人放中段空地
        var 兜底 = 造空房(种子, 模板, 含大门, 楼梯);
        保底布局(兜底, 容器占位, 敌人占位);
        兜底.走了保底布局 = true;
        兜底.重掷次数 = 最大重掷 + 1;
        return 兜底;
    }

    // ================= 内容清单（只抽一次，重掷只换摆法，不换内容） =================

    private static List<搜索容器> 抽容器(int 种子, 房间模板 模板, 容器表取用 取容器, out int 下限)
    {
        下限 = 0;
        var 清单 = new List<搜索容器>();
        var 池 = 模板.容器池;
        if (池 == null || 取容器 == null) return 清单;

        var 流 = 确定性随机.随机流(确定性随机.派生(种子, "容器清单"));
        foreach (var 项 in 池)
        {
            if (项 == null) continue;
            var 表 = 取容器(项.地图类型, 项.房间);
            if (表 == null || 表.Count == 0) continue;
            int 数量 = 确定性随机.范围(流, Math.Max(0, 项.数量最小), Math.Max(0, 项.数量最大));
            int 实际最小 = Math.Min(数量, Math.Max(0, 项.数量最小));
            下限 += 实际最小;
            for (int i = 0; i < 数量; i++)
            {
                var 定义 = 确定性随机.轮盘(流, 表, _ => 1);
                if (定义 != null) 清单.Add(定义);
            }
        }

        // 占格上限保护：超了就按池权重从低到高裁（权重低的先让位）
        裁剪到占格上限(清单, 池, 模板);
        if (下限 > 清单.Count) 下限 = 清单.Count;
        if (下限 < 1 && 清单.Count > 0) 下限 = 1;
        return 清单;
    }

    private static void 裁剪到占格上限(List<搜索容器> 清单, 房间容器池项[] 池, 房间模板 模板)
    {
        int 列 = 夹(模板.列, 最小列, 最大列), 行 = 夹(模板.行, 最小行, 最大行);
        int 上限 = 约束摆放.占格上限(列, 行);
        int 已占 = 0;
        for (int i = 0; i < 清单.Count; i++)
        {
            容器规格.占格(清单[i], out int 宽, out int 高);
            已占 += 宽 * 高;
        }
        while (已占 > 上限 && 清单.Count > 1)
        {
            var 去 = 清单[清单.Count - 1];
            清单.RemoveAt(清单.Count - 1);
            容器规格.占格(去, out int 宽, out int 高);
            已占 -= 宽 * 高;
        }
    }

    private static List<string> 抽敌人(int 种子, 房间模板 模板, 敌人组取用 取敌人, out int 下限)
    {
        下限 = 0;
        var 清单 = new List<string>();
        if (模板 == null || string.IsNullOrEmpty(模板.敌人组) || 取敌人 == null) return 清单;
        var 展开 = 取敌人(模板.敌人组);
        if (展开 == null || 展开.Count == 0) return 清单;

        int 要 = 夹(展开.Count, Math.Max(0, 模板.敌人数量最小), Math.Max(0, 模板.敌人数量最大));
        if (要 <= 0) return 清单;
        var 流 = 确定性随机.随机流(确定性随机.派生(种子, "敌人清单"));
        for (int i = 0; i < 要; i++)
        {
            // 不够就从展开表里循环取（保证数量落在模板区间内）
            int 源 = i % 展开.Count;
            string 标识 = 展开[源];
            if (i >= 展开.Count) 标识 = 展开[确定性随机.范围(流, 0, 展开.Count - 1)];
            清单.Add(标识);
        }
        下限 = Math.Min(Math.Max(0, 模板.敌人数量最小), 清单.Count);
        return 清单;
    }

    // ================= 内容 → 占位物（"怎么变成实体"交给引擎回调，标识格式仍在这里定） =================

    private static List<约束摆放.占位物> 造容器占位(List<搜索容器> 清单)
    {
        var 结果 = new List<约束摆放.占位物>();
        foreach (var 定义 in 清单)
        {
            if (定义 == null) continue;
            容器规格.占格(定义, out int 宽, out int 高);
            var 定 = 定义;
            结果.Add(new 约束摆放.占位物
            {
                宽 = 宽,
                高 = 高,
                建 = (房, 列, 行, 序) => new 网格实体
                {
                    标识 = $"{房.模板标识}#容器{序}",
                    类型 = 网格实体类型.容器,
                    阵营 = 网格阵营.中立,
                    定义标识 = 定.标识,
                    名称 = string.IsNullOrEmpty(定.名称) ? 定.标识 : 定.名称,
                    列 = 列,
                    行 = 行,
                    宽 = 宽,
                    高 = 高,
                    占格 = true,
                    挡视线 = 容器规格.挡视线(定),
                    容器定义 = 定
                }
            });
        }
        return 结果;
    }

    private static List<约束摆放.占位物> 造敌人占位(List<string> 清单)
    {
        var 结果 = new List<约束摆放.占位物>();
        foreach (var 标识 in 清单)
        {
            if (string.IsNullOrEmpty(标识)) continue;
            var 定 = 标识;
            结果.Add(new 约束摆放.占位物
            {
                宽 = 1,
                高 = 1,
                建 = (房, 列, 行, 序) => new 网格实体
                {
                    标识 = $"{房.模板标识}#敌人{序}",
                    类型 = 网格实体类型.敌人,
                    阵营 = 网格阵营.敌人,
                    定义标识 = 定,
                    名称 = 定,
                    列 = 列,
                    行 = 行,
                    占格 = true,
                    挡视线 = true
                }
            });
        }
        return 结果;
    }

    // ================= 造壳 =================

    private static 网格数据 造空房(int 种子, 房间模板 模板, bool 含大门, (int 边, int 号)? 楼梯 = null)
    {
        var 房 = new 网格数据
        {
            模板标识 = 模板.标识 ?? "",
            名称 = string.IsNullOrEmpty(模板.名称) ? 模板.标识 : 模板.名称,
            描述 = 模板.描述 ?? "",
            列 = 夹(模板.列, 最小列, 最大列),
            行 = 夹(模板.行, 最小行, 最大行),
            危险度 = Math.Max(1, 模板.危险度),
            视野边长 = 网格视野.奇数化(视野规则.白天边长默认),   // 兜底值；真正的边长由 房间探索服务 按"角色 + 时段"写入
            战斗棋盘 = 模板.战斗棋盘 ?? "",
            敌人组 = 模板.敌人组 ?? ""
        };
        // 楼梯间：**往外延伸一格**（那一格在原外墙之外，只包住它自己：两侧补墙、外侧是网格边缘）
        int 楼梯边 = 楼梯 != null ? 楼梯.Value.边 : -1;
        if (楼梯边 >= 0) 扩楼梯间(房, 楼梯边);   // 先长一格（这格给楼梯间）
        建墙(房, 楼梯边);                        // 外圈墙（楼梯那一侧内缩一格）
        取入口格(种子, 房, 模板.入口边, 楼梯边);
        加楼梯间(房, 楼梯);                      // 挖门洞 + 放楼梯 + 包住它 + 这一侧其余填"界外"
        开门(种子, 房, 模板, 含大门, 楼梯边);   // **在墙上开洞**：先拆掉那格墙，再放门实体（必须在摆物件之前，物件要避开门口）
        房.实体.Add(new 网格实体
        {
            标识 = $"{房.模板标识}#玩家",
            类型 = 网格实体类型.玩家,
            阵营 = 网格阵营.玩家,
            定义标识 = "玩家",
            名称 = "你",
            列 = 房.入口列,
            行 = 房.入口行,
            占格 = false,       // 自己站着的格要能走
            挡视线 = false
        });
        return 房;
    }

    // 建墙：外圈一圈（**楼梯那一侧内缩一格** —— 那一格留给"凸出去的楼梯间"）
    private static void 建墙(网格数据 房, int 楼梯边 = -1)
    {
        int 左 = 楼梯边 == 1 ? 1 : 0;
        int 上 = 楼梯边 == 2 ? 1 : 0;
        int 右 = 房.列 - 1 - (楼梯边 == 3 ? 1 : 0);
        int 下 = 房.行 - 1 - (楼梯边 == 0 ? 1 : 0);
        int 序 = 0;
        for (int c = 左; c <= 右; c++)
        {
            加墙(房, c, 上, ref 序);
            加墙(房, c, 下, ref 序);
        }
        for (int r = 上 + 1; r < 下; r++)
        {
            加墙(房, 左, r, ref 序);
            加墙(房, 右, r, ref 序);
        }
    }

    private static void 加墙(网格数据 房, int 列, int 行, ref int 序)
    {
        房.实体.Add(new 网格实体
        {
            标识 = $"{房.模板标识}#墙{序++}",
            类型 = 网格实体类型.墙,
            阵营 = 网格阵营.中立,
            定义标识 = "墙",
            名称 = "墙",
            列 = 列,
            行 = 行,
            占格 = true,
            挡视线 = true
        });
    }

    // 往外延伸一格：只在楼梯那一侧把网格长一格（长完 建墙 会把这一圈也算进外墙）
    private static void 扩楼梯间(网格数据 房, int 边)
    {
        if (边 == 0 || 边 == 2) 房.行 += 1;   // 上/下 → 长一行
        else 房.列 += 1;                      // 左/右 → 长一列
    }

    private static void 取入口格(int 种子, 网格数据 房, string 边, int 楼梯边 = -1)
    {
        var 流 = 确定性随机.随机流(确定性随机.派生(种子, "入口"));
        // 楼梯那一侧多长了一格（+隔墙一格）→ 内区从那侧缩 1 格，入口别落进楼梯间/隔墙
        int 内左 = 1 + (楼梯边 == 1 ? 1 : 0);
        int 内上 = 1 + (楼梯边 == 2 ? 1 : 0);
        int 内右 = 房.列 - 2 - (楼梯边 == 3 ? 1 : 0);
        int 内下 = 房.行 - 2 - (楼梯边 == 0 ? 1 : 0);
        int 抖 = 确定性随机.范围(流, -2, 2);
        string 用边 = string.IsNullOrEmpty(边) ? "下" : 边;
        // 入口格所在的那一列/行 = 大门在墙上的位置 → 和门一样离墙角 ≥门离角（否则大门会顶在角上）
        if (用边 == "上")
        {
            房.入口行 = 内上;
            房.入口列 = 夹((内左 + 内右) / 2 + 抖, 门离角, 房.列 - 1 - 门离角);
            return;
        }
        if (用边 == "左")
        {
            房.入口列 = 内左;
            房.入口行 = 夹((内上 + 内下) / 2 + 抖, 门离角, 房.行 - 1 - 门离角);
            return;
        }
        if (用边 == "右")
        {
            房.入口列 = 内右;
            房.入口行 = 夹((内上 + 内下) / 2 + 抖, 门离角, 房.行 - 1 - 门离角);
            return;
        }
        房.入口行 = 内下;
        房.入口列 = 夹((内左 + 内右) / 2 + 抖, 门离角, 房.列 - 1 - 门离角);
    }

    // ================= 门（在墙上开洞） =================
    // 规则：外墙上原本整圈是墙；每扇门把**那一格墙拆掉**，换成占格=false 的门实体（门洞能站能走）。
    //   · 大门：外墙上那扇通向外面的门，位置由 入口边 + 入口格 定（入口格就在它内侧）
    //   · 内门：由 房间模板.门 声明（边 + 通向哪间房），位置按种子在这条边上抖一下，再按约束就近找位
    // 约束：离墙角 ≥2 格、同一条边上两扇门 ≥3 格；排不开就记 门开不出（自检会报，不静默吞掉）
    // ★ v51 刀15 新增约束：**楼梯那一侧一概不许开门**（`楼梯边` 那条边）。
    //   那一侧的外线（最外一行/列）整个属于楼梯间：楼梯格 + 它两侧的墙 + 其余填"界外"。
    //   门开在那条线上三种结局都是坏的（用户实测报过这个 bug）：
    //     · 落在**楼梯格**上 → 带锁的门占格 → 站不上楼梯（上不了楼）；无锁也变成"一格两个实体"
    //     · 落在**号±1** → 顶掉楼梯间的侧墙 → 楼梯间围不住（建筑验证 ③' 会报）
    //     · 落在**别的位置** → 掉进"界外" → 那扇门走不到、也进不去
    //   所以这里直接不开并记 门开不出；静态侧由 DataService 判成校验错误（首间房的 入口边/内门边 == 楼梯边）。
    private static void 开门(int 种子, 网格数据 房, 房间模板 模板, bool 含大门, int 楼梯边 = -1)
    {
        int 序 = 0;
        if (含大门)
        {
            int 边 = 边码(模板.入口边);
            if (边 == 楼梯边) 房.门开不出++;   // 见方法头 ★：大门也不能开在楼梯那一侧
            else
            {
                int 号 = (边 == 0 || 边 == 2) ? 房.入口列 : 房.入口行;
                var 格 = 边格(房, 边, 号);
                加门(房, 格.列, 格.行, 边, "", true, ref 序);
            }
        }
        if (模板.门 == null) return;
        for (int i = 0; i < 模板.门.Length; i++)
        {
            var 项 = 模板.门[i];
            if (项 == null || string.IsNullOrEmpty(项.通向)) continue;
            int 边 = 边码(项.边);
            if (边 == 楼梯边) { 房.门开不出++; continue; }   // 见方法头 ★：楼梯那一侧不许开门
            int 长 = 边长(房, 边);
            var 流 = 确定性随机.随机流(确定性随机.派生(种子, $"门{i}"));
            int 期望 = 夹(长 / 2 + 确定性随机.范围(流, -3, 3), 门离角, 长 - 1 - 门离角);
            var 位 = 找门位(房, 边, 期望, 长);
            if (位 == null) { 房.门开不出++; continue; }
            // 位 = 沿边第几格
            加门(房, 位.Value, 边, 项.通向, false, ref 序, 项.锁);
        }
    }

    // 楼梯间：**外墙上凸出去的一格**（不是嵌在墙里），而且**只包住它自己**：
    //   ① 外圈墙上挖门洞（那格原本是墙）→ 门内侧格 = 这个口
    //   ② 凸出去那一格放楼梯（能站能走）
    //   ③ 沿边的上下两格补墙 → 把这块包住（外侧是网格边缘，渲染时会描边）
    //   ④ 这一侧剩下的格子填 **界外**（挡通行、不画成墙）—— 网格是矩形，不填就会多出"能走却走不到"的空列
    private static void 加楼梯间(网格数据 房, (int 边, int 号)? 楼梯)
    {
        if (楼梯 == null) return;
        int 边 = 楼梯.Value.边;
        int 长 = 边长(房, 边);
        int 号 = 夹(楼梯.Value.号, 门离角, 长 - 1 - 门离角);

        // ① 门洞：外圈墙上那一格
        var 洞口 = 边格(房, 边, 号, 1);
        if (房.界内(洞口.列, 洞口.行))
        {
            var 原墙 = 房.占位(洞口.列, 洞口.行);
            if (原墙 != null && 原墙.类型 == 网格实体类型.墙) 房.移除实体(原墙);
        }

        // ② 楼梯：凸出去那一格
        var 梯格 = 边格(房, 边, 号, 0);
        if (!房.界内(梯格.列, 梯格.行)) return;
        var 挡路 = 房.占位(梯格.列, 梯格.行);
        if (挡路 != null && 挡路.类型 == 网格实体类型.墙) 房.移除实体(挡路);
        房.实体.Add(new 网格实体
        {
            标识 = $"{房.模板标识}#楼梯",
            类型 = 网格实体类型.楼梯,
            阵营 = 网格阵营.中立,
            定义标识 = "楼梯",
            名称 = "楼梯",
            列 = 梯格.列,
            行 = 梯格.行,
            朝向 = 边,          // 0下 1左 2上 3右（决定这间小屋鼓在哪边）
            占格 = false,       // 能站能走：站到这一格上才能上下楼
            挡视线 = false
        });

        // ③ 包住它：沿边前后两格补墙
        int 序 = 房.实体.Count;
        var 侧甲 = 沿边偏(梯格, 边, -1);
        var 侧乙 = 沿边偏(梯格, 边, 1);
        补一堵墙(房, 侧甲.列, 侧甲.行, ref 序);
        补一堵墙(房, 侧乙.列, 侧乙.行, ref 序);

        // ④ 这一侧剩下的格子填"界外"
        int 序2 = 房.实体.Count;
        for (int 位 = 0; 位 < 长; 位++)
        {
            if (位 >= 号 - 1 && 位 <= 号 + 1) continue;      // 楼梯格 + 它两侧那两堵墙
            var 格 = 边格(房, 边, 位, 0);
            if (!房.界内(格.列, 格.行)) continue;
            if (房.格上实体(格.列, 格.行) != null) continue;
            房.实体.Add(new 网格实体
            {
                标识 = $"{房.模板标识}#界外{序2++}",
                类型 = 网格实体类型.界外,
                阵营 = 网格阵营.中立,
                定义标识 = "界外",
                名称 = "界外",
                列 = 格.列,
                行 = 格.行,
                占格 = true,        // 挡通行，但**不画成墙**（面板会跳过这一种）
                挡视线 = false
            });
        }
    }

    private static void 补一堵墙(网格数据 房, int 列, int 行, ref int 序)
    {
        if (!房.界内(列, 行)) return;
        if (房.格上实体(列, 行) != null) return;   // 已经有东西（外圈墙转角等）就不补
        加墙(房, 列, 行, ref 序);
    }

    // 加一扇门：拆掉那格墙 + 放门实体
    private static void 加门(网格数据 房, int 列, int 行, int 边, string 通向, bool 是大门, ref int 序, string 锁钥匙 = "")
    {
        if (房.界内(列, 行))
        {
            var 原墙 = 房.占位(列, 行);
            if (原墙 != null) 房.移除实体(原墙);   // 墙上开洞
        }
        bool 有锁 = !string.IsNullOrEmpty(锁钥匙);
        房.实体.Add(new 网格实体
        {
            标识 = $"{房.模板标识}#门{序++}",
            类型 = 网格实体类型.门,
            阵营 = 网格阵营.中立,
            定义标识 = "门",
            名称 = 是大门 ? "大门" : "门",
            列 = 列,
            行 = 行,
            朝向 = 边,          // 0下 1左 2上 3右（也决定门框画横还是画竖）
            // 无锁 = 门洞（能站能走、不挡视线）；有锁 = 一扇关着的门（站不上去、挡住视线）
            // → 锁着时 A* 自动只让你走到"门前那一格"（寻路到相邻），这就是"只能站在门前"的实现
            占格 = 有锁,
            挡视线 = 有锁,
            通向 = 通向,
            是大门 = 是大门,
            锁钥匙 = 锁钥匙
        });
    }

    private static void 加门(网格数据 房, int 号, int 边, string 通向, bool 是大门, ref int 序, string 锁钥匙 = "")
    {
        var 格 = 边格(房, 边, 号);
        加门(房, 格.列, 格.行, 边, 通向, 是大门, ref 序, 锁钥匙);
    }

    // "上/下/左/右" → 0下 1左 2上 3右（与 网格实体.朝向 同义）
    private static int 边码(string 边)
    {
        if (边 == "上") return 2;
        if (边 == "左") return 1;
        if (边 == "右") return 3;
        return 0;   // 默认 下
    }

    // 这条边有多少格（上下边 = 列数，左右边 = 行数）
    private static int 边长(网格数据 房, int 边) => (边 == 0 || 边 == 2) ? 房.列 : 房.行;

    // 边上第 号 格（内缩 = 往里退几格）
    //   内缩 0 = 最外那一格（凸出去的楼梯间就在这）
    //   内缩 1 = 外圈墙那一格（门洞挖在这）
    private static (int 列, int 行) 边格(网格数据 房, int 边, int 号, int 内缩 = 0)
    {
        if (边 == 2) return (号, 内缩);
        if (边 == 1) return (内缩, 号);
        if (边 == 3) return (房.列 - 1 - 内缩, 号);
        return (号, 房.行 - 1 - 内缩);
    }

    // 沿边方向偏移（门/楼梯那一行/列的前后一格）
    private static (int 列, int 行) 沿边偏((int 列, int 行) 格, int 边, int 偏)
        => (边 == 0 || 边 == 2) ? (格.列 + 偏, 格.行) : (格.列, 格.行 + 偏);

    // 从期望位向两侧找最近的可开门处（返回"沿边第几格"；确定性：同样输入必得同样结果）
    private static int? 找门位(网格数据 房, int 边, int 期望, int 长)
    {
        int 最小 = 门离角, 最大 = 长 - 1 - 门离角;
        if (最小 > 最大) return null;
        int 起点 = 夹(期望, 最小, 最大);
        for (int 距 = 0; 距 <= 长; 距++)
            for (int 方 = 0; 方 < 2; 方++)
            {
                if (距 == 0 && 方 == 1) continue;
                int 号 = 方 == 0 ? 起点 - 距 : 起点 + 距;
                if (号 < 最小 || 号 > 最大) continue;
                if (!门位可用(房, 边, 号)) continue;
                return 号;
            }
        return null;
    }

    private static bool 门位可用(网格数据 房, int 边, int 号)
    {
        var 门们 = 房.门列表();
        for (int i = 0; i < 门们.Count; i++)
        {
            if (门们[i].朝向 != 边) continue;
            int 他号 = (边 == 0 || 边 == 2) ? 门们[i].列 : 门们[i].行;
            if (Math.Abs(他号 - 号) < 门间距) return false;
        }
        // 楼梯也占这条边上的一格：门别挤在楼梯旁边（同一套"相邻 ≥3 格"的规矩）
        var 梯们 = 房.楼梯列表();
        for (int i = 0; i < 梯们.Count; i++)
        {
            if (梯们[i].朝向 != 边) continue;
            int 他号 = (边 == 0 || 边 == 2) ? 梯们[i].列 : 梯们[i].行;
            if (Math.Abs(他号 - 号) < 门间距) return false;
        }
        return true;
    }

    // ================= 摆放（交给 约束摆放 引擎；这里只给"摆什么"和"什么不能压"） =================

    private static void 摆物件(网格数据 房, int 种子, int 轮次, List<约束摆放.占位物> 容器占位, List<约束摆放.占位物> 敌人占位)
    {
        var 流 = 确定性随机.随机流(确定性随机.派生(种子, $"摆放{轮次}"));
        var 约束 = 造约束(房);
        // 顺序 = RNG 顺序：容器（区块配额 → 统一全图补位）在前，敌人（区块配额 → 当场全图补位）在后
        var 清单们 = new List<约束摆放.清单>
        {
            new 约束摆放.清单 { 项 = 容器占位, 大件优先 = true,  避开区块心 = false, 失败后立即全图补位 = false },
            new 约束摆放.清单 { 项 = 敌人占位, 大件优先 = false, 避开区块心 = true,  失败后立即全图补位 = true },
        };
        约束摆放.摆(房, 流, 约束, 清单们);
    }

    // 通道格（入口 + 门 + 门内侧）不许压；区块心 = 入口格（敌人优先避开它那一块，别一进门贴脸）
    private static 约束摆放.约束 造约束(网格数据 房) => new 约束摆放.约束
    {
        通道格 = 房.通道格(),
        物件距墙 = 约束摆放.物件距墙,
        区块心 = (房.入口列, 房.入口行),
    };

    // ================= 连通校验 =================

    private static bool 校验(网格数据 房, int 容器下限, int 敌人下限)
    {
        var 可达 = 房.可达集();
        if (可达.Count == 0) return false;

        // 坏容器：没有任何相邻可站格落在可达集里 → 移除（不动整间房，避免大改观感）
        var 容器们 = 房.取类型(网格实体类型.容器);
        foreach (var e in 容器们)
            if (!有相邻可达格(房, 可达, e))
            {
                房.移除实体(e);
                房.被移除的坏容器++;
            }

        var 敌人们 = 房.取类型(网格实体类型.敌人);
        foreach (var e in 敌人们)
            if (!有相邻可达格(房, 可达, e))
            {
                房.移除实体(e);
                房.被移除的坏敌人++;
            }

        if (房.容器总数() < 容器下限) return false;
        if (房.敌人总数() < 敌人下限) return false;
        if (房.连通分量数() > 1) return false;
        // 门内侧格必须从入口走得到（门是结构件，堵住就进不去了 → 只能重掷/保底）
        var 门们 = 房.门列表();
        for (int i = 0; i < 门们.Count; i++)
        {
            var 内 = 房.门内侧格(门们[i]);
            if (!检查(房, 可达, 内.列, 内.行)) return false;
        }
        // 楼梯内侧格同理：楼梯是上下楼唯一的路，堵住就等于把这层楼废了
        var 梯们 = 房.楼梯列表();
        for (int i = 0; i < 梯们.Count; i++)
        {
            var 内 = 房.门内侧格(梯们[i]);
            if (!检查(房, 可达, 内.列, 内.行)) return false;
        }
        return true;
    }

    private static bool 有相邻可达格(网格数据 房, HashSet<int> 可达, 网格实体 e)
    {
        for (int r = e.行; r < e.行 + e.高; r++)
            for (int c = e.列; c < e.列 + e.宽; c++)
            {
                if (检查(房, 可达, c - 1, r)) return true;
                if (检查(房, 可达, c + 1, r)) return true;
                if (检查(房, 可达, c, r - 1)) return true;
                if (检查(房, 可达, c, r + 1)) return true;
            }
        return false;
    }

    private static bool 检查(网格数据 房, HashSet<int> 可达, int 列, int 行)
        => 房.界内(列, 行) && 可达.Contains(网格数据.编码(列, 行));

    // ================= 保底布局（必定成功） =================
    // 沿内区边框隔一格摆容器（天然留出走道，中心全空 → 必然连通可达），敌人放中段空地。

    private static void 保底布局(网格数据 房, List<约束摆放.占位物> 容器占位, List<约束摆放.占位物> 敌人占位)
    {
        var 约束 = 造约束(房);
        var 环 = 约束摆放.取内环格(房);
        int 容器序 = 0, 已放 = 0;
        for (int i = 0; i < 环.Count && 已放 < 容器占位.Count; i += 2)
        {
            var (c, r) = 环[i];
            var 项 = 容器占位[已放];
            if (!约束摆放.保底可放(房, 约束, c, r, 项.宽, 项.高)) continue;
            房.实体.Add(项.建(房, c, r, 容器序++));
            已放++;
        }

        int 敌序 = 0;
        int 中列 = 房.列 / 2, 中行 = 房.行 / 2;
        for (int i = 0; i < 敌人占位.Count; i++)
        {
            var 位 = 约束摆放.找中段空格(房, 约束, 中列, 中行, i);
            if (位 == null) break;
            房.实体.Add(敌人占位[i].建(房, 位.Value.列, 位.Value.行, 敌序++));
        }
    }

    private static int 夹(int 值, int 最小, int 最大)
    {
        if (值 < 最小) return 最小;
        if (值 > 最大) return 最大;
        return 值;
    }

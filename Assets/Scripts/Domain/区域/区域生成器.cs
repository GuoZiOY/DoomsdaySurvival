using System;
using System.Collections.Generic;

// ============================================================
// 区域生成器：一张格子世界（区域网格），按**地块制**摆若干建筑 + 街道（纯 C#，可离线跑种子自检）。
//   地块制：内区切成 地块列数 × 地块行数 个地块，地块之间留 1 格街道，内区最底留 1 行街道。
//   一栋楼占一个地块：宽 = min(建筑项.宽, 地块宽)、居中；高 = min(建筑项.高, 地块高)；
//   楼的门开在**下边**（朝向 0）→ 入口格 = 楼底正下方那一格，永远落在街上 → 天然可达。
//   哪栋楼进哪个地块 = 按种子洗牌（同种子同布局）。
// 五段（生成() 里的顺序就是这个）：
//   ① 造壳：整圈边界废墟墙 + 入口格（内区最底那一行）+ **街口**（边界墙上开一格能走出去的门）
//   ② 摆建筑：地块制洗牌摆进去
//   ③ 撒敌人：按 模板.敌人[] 撒在自由街格上（**占格 = true** → 走到相邻格触发遭遇；v51 刀12）
//   ④ 撒障碍：废墟/车障（撒完必须仍连通）
//   ⑤ 每撒一只敌人/一个障碍都当场跑一遍 校验()，破了就撤回（绝不留下孤岛或堵死的门）
// 不变量（区域验证 逐颗种子断言）：
//   ① 同区域模板 + 同种子 = 同布局（确定性）；
//   ② 建筑不越界、不重叠、互不相邻（地块之间本来就隔着街道）；
//   ③ 每个建筑的入口格界内、可通行、且从区域入口可达；
//   ④ **街口格**（出口）界内、可通行、且从区域入口可达 —— 走上去就离开这一片；
//   ⑤ 可站格连通分量 = 1（无孤岛）；
//   ⑥ 街道敌人/障碍只撒在"自由街道格"上，撒完必须仍然满足 ③④⑤（否则当场撤回）。
// ============================================================
public static class 区域生成器
{
    public const int 最小列 = 12, 最大列 = 40;   // 格子恒 90px（全项目统一）；上限按"相机跟随跑得开"给（一屏约看 19×10 格）
    public const int 最小行 = 8, 最大行 = 28;
    public const int 街道宽 = 2;        // 地块之间的街道格数（2 格：能站开、也能放街道障碍）
    public const int 预留底行 = 1;       // 内区最底那一行永远留作街道（入口落点 + 楼门前的街）
    public const int 地块列数 = 2, 地块行数 = 2;
    public const int 最小地块宽 = 3, 最小地块高 = 2;   // 地块小于这个就不切（网格太小）

    // 生成：种子 + 区域模板 → 网格数据。
    // 取名 = 标识 → 显示名（楼名/区名由调用方给：Domain 不认识 DataService）
    // 取建筑模板 = 建筑标识 → 建筑模板（拿它的**外形**：非矩形楼的地块形状）
    public static 网格数据 生成(int 种子, 区域模板 模板, Func<string, string> 取名 = null,
                              Func<string, 建筑模板> 取建筑模板 = null)
    {
        if (模板 == null) return null;
        var 区 = 造空区(种子, 模板);
        摆建筑(种子, 区, 模板, 取名, 取建筑模板);
        撒敌人(种子, 区, 模板);
        撒障碍(种子, 区, 模板);
        return 区;
    }

    // ================= 造壳 =================

    private static 网格数据 造空区(int 种子, 区域模板 模板)
    {
        var 区 = new 网格数据
        {
            模板标识 = 模板.标识 ?? "",
            名称 = string.IsNullOrEmpty(模板.名称) ? 模板.标识 : 模板.名称,
            描述 = 模板.描述 ?? "",
            列 = 夹(模板.列, 最小列, 最大列),
            行 = 夹(模板.行, 最小行, 最大行),
            危险度 = Math.Max(1, 模板.危险度),
            视野边长 = 网格视野.奇数化(视野规则.白天边长默认),   // 兜底值；真正的边长由 区域探索服务 按"角色 + 时段"写入
            战斗棋盘 = 模板.战斗棋盘 ?? "",
            // 街上遭遇走的是"地图上摆好一只只敌人，撞上去开打"（见 撒敌人 + 格子探索服务.检查遭遇），
            // 不是"按 敌人组 随机遭遇"那套 → 这里留空（真正开打时只把**脚下那一只**交给战斗）。
            敌人组 = "",
        };
        建墙(区);
        取入口格(种子, 区);
        开街口(区);   // 在边界墙上开一格"街口"（走上去 = 离开这一片，回大世界）
        区.实体.Add(new 网格实体
        {
            标识 = $"{区.模板标识}#玩家",
            类型 = 网格实体类型.玩家,
            阵营 = 网格阵营.玩家,
            定义标识 = "玩家",
            名称 = "你",
            列 = 区.入口列,
            行 = 区.入口行,
            占格 = false,
            挡视线 = false
        });
        return 区;
    }

    private static void 建墙(网格数据 区)
    {
        int 序 = 0;
        for (int c = 0; c < 区.列; c++)
        {
            加墙(区, c, 0, ref 序);
            加墙(区, c, 区.行 - 1, ref 序);
        }
        for (int r = 1; r < 区.行 - 1; r++)
        {
            加墙(区, 0, r, ref 序);
            加墙(区, 区.列 - 1, r, ref 序);
        }
    }

    private static void 加墙(网格数据 区, int 列, int 行, ref int 序)
    {
        区.实体.Add(new 网格实体
        {
            标识 = $"{区.模板标识}#墙{序++}",
            类型 = 网格实体类型.墙,
            阵营 = 网格阵营.中立,
            定义标识 = "墙",
            名称 = "墙",
            列 = 列,
            行 = 行,
            占格 = true,
            挡视线 = true
        });
    }

    // 入口格：第 1 刀恒为"下边"——落在内区最底那一行（预留的街道），所以永远可通行、永远连通
    private static void 取入口格(int 种子, 网格数据 区)
    {
        var 流 = 确定性随机.随机流(确定性随机.派生(种子, "入口"));
        int 内左 = 1, 内右 = 区.列 - 2, 内下 = 区.行 - 2;
        int 抖 = 确定性随机.范围(流, -2, 2);
        区.入口行 = 内下;
        区.入口列 = 夹((内左 + 内右) / 2 + 抖, 2, 区.列 - 3);
    }

    // ================= 街口（区域出口格） =================
    // 「走出这一片」的那一格：把**边界墙上正对入口的那一格**打通，放一扇门。
    //   为什么放在这一格：① 就在入口正下方，玩家一进来就看得见"街口在身后"；
    //                     ② 边界墙其余格照旧是墙（点了报"那边过不去"）→ 出口**只有这一个**，不存在迷路；
    //                     ③ 它天然与入口格相邻 → 连通性不可能被破坏（校验里的 ⑤）。
    // 门实体 **占格 = false**：它就是个"能站能走的门洞"（和楼门那种"长在楼身上、走上去才进楼"不同，
    //   这里是真的走出去），所以不能占格 —— 占了格玩家就走不上去了。
    private static void 开街口(网格数据 区)
    {
        int 列 = 区.入口列, 行 = 区.行 - 1;
        if (!区.界内(列, 行)) return;
        // 把那一格上的边界墙摘掉（只摘得掉墙；别误删别的东西）
        foreach (var 墙 in 区.取类型(网格实体类型.墙))
            if (墙 != null && 墙.列 == 列 && 墙.行 == 行) { 区.移除实体(墙); break; }
        区.实体.Add(new 网格实体
        {
            标识 = $"{区.模板标识}#街口",
            类型 = 网格实体类型.门,
            阵营 = 网格阵营.中立,
            定义标识 = "街口",
            名称 = "街口",
            列 = 列,
            行 = 行,
            是大门 = true,
            占格 = false,
            挡视线 = false
        });
    }

    // 街口格（区域出口）：站在这一格上 = 离开这一片、回大世界。
    // 取法 = 入口正下方那一格（开街口 打通的就是它）。
    public static (int 列, int 行) 出口格(网格数据 区)
        => 区 == null ? (-1, -1) : (区.入口列, 区.行 - 1);

    // ================= 地块 =================

    // 地块列表（行优先）：内区切 地块列数 × 地块行数，地块之间留 街道宽，最底留 预留底行
    public static List<(int 左, int 上, int 宽, int 高)> 算地块(网格数据 区)
    {
        var 结果 = new List<(int 左, int 上, int 宽, int 高)>();
        if (区 == null) return 结果;
        int 内左 = 1, 内上 = 1, 内右 = 区.列 - 2, 内下 = 区.行 - 2;
        int 可用宽 = 内右 - 内左 + 1;
        int 可用高 = 内下 - 内上 + 1 - 预留底行;
        if (可用宽 <= 0 || 可用高 <= 0) return 结果;
        int 块宽 = (可用宽 - (地块列数 - 1) * 街道宽) / 地块列数;
        int 块高 = (可用高 - (地块行数 - 1) * 街道宽) / 地块行数;
        if (块宽 < 最小地块宽 || 块高 < 最小地块高) return 结果;
        for (int j = 0; j < 地块行数; j++)
            for (int i = 0; i < 地块列数; i++)
                结果.Add((内左 + i * (块宽 + 街道宽), 内上 + j * (块高 + 街道宽), 块宽, 块高));
        return 结果;
    }

    // 楼的入口格（玩家站这一格 = 进楼）：
    //   · 有 门口格 → 就是**建筑自己底边中间那一格**（门长在楼上，最直观）
    //   · 没有 → 退回"楼外那一格"（旧口径，兼容）
    public static (int 列, int 行) 建筑入口格(网格实体 楼)
    {
        if (楼 == null) return (0, 0);
        if (楼.门口格 >= 0) return (楼.门口格 / 1000, 楼.门口格 % 1000);
        switch (楼.朝向)
        {
            case 2: return (楼.列 + 楼.宽 / 2, 楼.行 - 1);         // 门在上边
            case 1: return (楼.列 - 1, 楼.行 + 楼.高 / 2);         // 门在左边
            case 3: return (楼.列 + 楼.宽, 楼.行 + 楼.高 / 2);     // 门在右边
            default: return (楼.列 + 楼.宽 / 2, 楼.行 + 楼.高);     // 门在下边（楼外那一格）
        }
    }

    // ================= 摆建筑 =================

    private static void 摆建筑(int 种子, 网格数据 区, 区域模板 模板, Func<string, string> 取名,
                              Func<string, 建筑模板> 取建筑模板)
    {
        var 清单 = 展开建筑(模板);
        if (清单.Count == 0) return;
        var 地块 = 算地块(区);
        if (地块.Count == 0) return;

        // 哪栋楼进哪个地块：按种子洗牌（确定性）
        var 流 = 确定性随机.随机流(确定性随机.派生(种子, "建筑"));
        var 序 = new List<int>();
        for (int i = 0; i < 地块.Count; i++) 序.Add(i);
        确定性随机.洗牌(流, 序);

        int 栋 = 0;
        for (int i = 0; i < 清单.Count && i < 序.Count; i++)
        {
            var 项 = 清单[i];
            var 块 = 地块[序[i]];
            string 定义 = string.IsNullOrEmpty(项.建筑模板) ? 项.房间模板 : 项.建筑模板;
            if (string.IsNullOrEmpty(定义)) continue;

            // 外形：建筑模板里写了就用它（掩码）；没写就按 区域建筑项.宽/高 的矩形
            var 外形 = 外形数据(项, 取建筑模板?.Invoke(定义));
            var 掩 = 建筑外形.生成(外形, out int 宽, out int 高);

            // 夹进地块：① **东西两侧各留 1 格**（楼不贴区域外墙）；② 放不下就按可用范围缩小
            //   留那 1 格的道理：区域外墙是死的（挡路又挡不住视线），"凸"这种形状**北部两角是空地** ——
            //   西边是外墙、东边是自己的凸出部、南边是自己那一排 → 那块空地谁也走不进去，可站格连通分量当场炸
            //   （区域验证 的"分量 = 1"就是这条的守门人）。留一格就多一条侧巷能绕出去。
            //   南边不用留：楼底那一行下面**永远是街道**（地块之间的街 / 内区预留底行）。
            int 可用左 = Math.Max(块.左, 1 + 1);
            int 可用右 = Math.Min(块.左 + 块.宽 - 1, 区.列 - 3);
            int 可宽 = Math.Max(1, 可用右 - 可用左 + 1);
            int 可高 = Math.Max(1, 块.高);
            int 用宽 = Math.Min(宽, 可宽), 用高 = Math.Min(高, 可高);
            if (用宽 != 宽 || 用高 != 高)
            {
                var 缩 = 复制外形(外形);
                缩.宽 = 用宽;
                缩.高 = 用高;
                掩 = 建筑外形.生成(缩, out 宽, out 高);
            }
            int 列 = 可用左 + (可宽 - 宽) / 2;
            int 行 = 块.上;                                       // 顶对齐：楼门前那一条街永远在楼底下面

            var 楼 = new 网格实体
            {
                标识 = $"{区.模板标识}#建筑{栋++}",
                类型 = 网格实体类型.建筑,
                阵营 = 网格阵营.中立,
                定义标识 = 定义,
                名称 = 取名?.Invoke(定义) ?? 定义,
                列 = 列,
                行 = 行,
                宽 = 宽,
                高 = 高,
                形状掩码 = 掩,       // 非矩形占地（null = 矩形）
                掩码列 = 宽,
                朝向 = 0,            // 门开在下边
                占格 = true,
                挡视线 = true
            };
            楼.门口格 = 选门口格(楼);   // 在掩码最靠下的那一行里找最长连续段取中点
            区.实体.Add(楼);
        }
    }

    // 外形数据：建筑模板.外形 优先；没有就按 区域建筑项.宽/高 造一个矩形外形
    private static 建筑外形数据 外形数据(区域建筑项 项, 建筑模板 建)
    {
        if (建?.外形 != null) return 建.外形;
        return new 建筑外形数据
        {
            形状 = 建筑外形.矩形,
            宽 = Math.Max(2, 项.宽),
            高 = Math.Max(2, 项.高)
        };
    }

    private static 建筑外形数据 复制外形(建筑外形数据 源) => new 建筑外形数据
    {
        形状 = 源.形状,
        宽 = 源.宽,
        高 = 源.高,
        切角宽 = 源.切角宽,
        切角高 = 源.切角高,
        突出宽 = 源.突出宽,
        突出高 = 源.突出高,
        凹口宽 = 源.凹口宽,
        凹口深 = 源.凹口深,
        朝向 = 源.朝向,
        左右镜像 = 源.左右镜像
    };

    // 门口格：掩码里**最靠下的那一行**中，最长的连续楼体段的中点（那一格能站能走 → 走上去进楼）
    // 取法已上移到 建筑外形.底边中点（大世界生成器 的区域门走同一条规则，见那里的注释）
    private static int 选门口格(网格实体 楼)
    {
        var (相对列, 相对行) = 建筑外形.底边中点(楼.形状掩码, 楼.宽, 楼.高);
        if (相对列 < 0) return -1;
        return 网格数据.编码(楼.列 + 相对列, 楼.行 + 相对行);
    }

    // 建筑项 → 逐栋展开（按 数量）
    public static List<区域建筑项> 展开建筑(区域模板 模板)
    {
        var 清单 = new List<区域建筑项>();
        if (模板?.建筑 == null) return 清单;
        foreach (var 项 in 模板.建筑)
        {
            if (项 == null) continue;
            if (string.IsNullOrEmpty(项.建筑模板) && string.IsNullOrEmpty(项.房间模板)) continue;
            for (int i = 0; i < Math.Max(1, 项.数量); i++) 清单.Add(项);
        }
        return 清单;
    }

    // ================= 街道敌人 =================

    // 撒街道敌人：按 模板.敌人[] 的 定义标识 + 数量 撒在自由街格上（v51 刀12）。
    // **占格 = true**：和房间层的敌人一样挡路 → 走到它相邻那一格就触发遭遇
    //   （`格子探索服务.检查遭遇` 判的是"正交相邻"）。**若做成不占格，玩家会从它身上走过去**
    //   （距离 0 ≠ 1）而永远打不起来 —— 那是个隐蔽的坑，别改。
    // 挡视线 = false：大世界/区域这一层的方形视野本来就不做遮挡（见 网格视野 文件头），
    //   街上看得见对面，敌人不该比障碍更"遮"。
    // 显示名（"感染者"之类）由服务层从 enemies.json 补上：Domain 不认识数据服务，这里先塞 定义标识。
    private static void 撒敌人(int 种子, 网格数据 区, 区域模板 模板)
    {
        if (模板.敌人 == null || 模板.敌人.Length == 0) return;
        var 流 = 确定性随机.随机流(确定性随机.派生(种子, "街上敌人"));
        int 序 = 0;
        foreach (var 项 in 模板.敌人)
        {
            if (项 == null || string.IsNullOrEmpty(项.定义标识)) continue;
            int 要 = Math.Max(0, 项.数量);
            for (int i = 0; i < 要; i++)
            {
                // 每只独立试若干次；撒不下就少一只（不报错 —— 街区太挤是允许的结果，
                // 服务层会按实际数量显示，区域验证 也会统计）
                for (int 次 = 0; 次 < 60; 次++)
                {
                    int 列 = 确定性随机.范围(流, 1, 区.列 - 2), 行 = 确定性随机.范围(流, 1, 区.行 - 2);
                    if (!可撒占格物(区, 列, 行)) continue;
                    var 敌 = new 网格实体
                    {
                        标识 = $"{区.模板标识}#敌人{序++}",
                        类型 = 网格实体类型.敌人,
                        阵营 = 网格阵营.敌人,
                        定义标识 = 项.定义标识,
                        名称 = 项.定义标识,       // 服务层会换成真名
                        列 = 列,
                        行 = 行,
                        占格 = true,
                        挡视线 = false,
                    };
                    区.实体.Add(敌);
                    if (校验(区)) break;
                    区.实体.Remove(敌);   // 把路堵死了 → 当场撤回（绝不留下孤岛）
                }
            }
        }
    }

    // ================= 街道障碍 =================

    private static void 撒障碍(int 种子, 网格数据 区, 区域模板 模板)
    {
        int 要 = Math.Max(0, 模板.街道障碍数);
        if (要 == 0) return;
        var 流 = 确定性随机.随机流(确定性随机.派生(种子, "障碍"));
        int 撒 = 0;
        for (int 次 = 0; 次 < 要 * 12 && 撒 < 要; 次++)
        {
            int 列 = 确定性随机.范围(流, 1, 区.列 - 2), 行 = 确定性随机.范围(流, 1, 区.行 - 2);
            if (!可撒占格物(区, 列, 行)) continue;
            var 障 = new 网格实体
            {
                标识 = $"{区.模板标识}#障碍{撒}",
                类型 = 网格实体类型.障碍,
                阵营 = 网格阵营.中立,
                定义标识 = "障碍",
                名称 = 障碍名(撒),
                列 = 列,
                行 = 行,
                占格 = true,
                挡视线 = true
            };
            区.实体.Add(障);
            if (校验(区)) 撒++;
            else 区.实体.Remove(障);   // 把路堵死了 → 当场撤回（绝不留下孤岛）
        }
    }

    private static string 障碍名(int 序)
    {
        string[] 名 = { "废弃汽车", "塌方的砖堆", "翻倒的报亭", "锈死的垃圾箱" };
        return 名[Math.Abs(序) % 名.Length];
    }

    // 能不能往这一格撒**占格物**（障碍 / 街上敌人 —— 两者同一套留空规则）：
    // 空格 + 不压区域入口与街口（含四邻）+ 不挡任何楼门（门口格及其四邻留空）。
    // ⚠ "含四邻"不是讲究：入口格 / 街口 / 楼门都只有**一个出口**，旁边被占格物堵上就是死格
    //   （v51 刀2 障碍堵死区域门口、刀6 临时建筑切断地图，都栽在这同一课上）。
    private static bool 可撒占格物(网格数据 区, int 列, int 行)
    {
        if (!区.可通行(列, 行)) return false;
        if (Math.Abs(列 - 区.入口列) <= 1 && Math.Abs(行 - 区.入口行) <= 1) return false;
        var 口 = 出口格(区);
        if (Math.Abs(口.列 - 列) <= 1 && Math.Abs(口.行 - 行) <= 1) return false;
        foreach (var 楼 in 区.取类型(网格实体类型.建筑))
        {
            var 门 = 建筑入口格(楼);
            if (Math.Abs(门.列 - 列) <= 1 && Math.Abs(门.行 - 行) <= 1) return false;
        }
        return true;
    }

    // ================= 校验（区域验证 逐颗种子跑） =================

    public static bool 校验(网格数据 区)
    {
        if (区 == null) return false;
        var 可达 = 区.可达集();
        if (可达.Count == 0) return false;
        if (区.连通分量数() > 1) return false;
        // 入口格与街口格：都得能站能走、且从区域里走得到（走不到就出不去 / 进不来）
        if (!格好用(区, 区.入口列, 区.入口行, 可达)) return false;
        var 口 = 出口格(区);
        if (!格好用(区, 口.列, 口.行, 可达)) return false;
        foreach (var 楼 in 区.取类型(网格实体类型.建筑))
        {
            var 门 = 建筑入口格(楼);
            if (!格好用(区, 门.列, 门.行, 可达)) return false;
        }
        return true;
    }

    private static bool 格好用(网格数据 区, int 列, int 行, HashSet<int> 可达)
        => 区.界内(列, 行) && 区.可通行(列, 行) && 可达.Contains(网格数据.编码(列, 行));

    private static int 夹(int 值, int 最小, int 最大)
    {
        if (值 < 最小) return 最小;
        if (值 > 最大) return 最大;
        return 值;
    }

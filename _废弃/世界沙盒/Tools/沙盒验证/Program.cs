    private static 搜索房间 房(string 标识, params string[] 容器标识)
    {
        var 容器 = new List<搜索容器>();
        foreach (var 名 in 容器标识)
            容器.Add(new 搜索容器
            {
                标识 = 名, 名称 = 名, 容器列 = 3, 容器行 = 3, 搜索时间 = 2f,
                搜索表 = new[] { new 搜索条目 { 物品标识 = "绷带", 权重 = 1, 数量最小 = 1, 数量最大 = 1 } },
            });
        return new 搜索房间 { 标识 = 标识, 名称 = 标识, 容器 = 容器.ToArray() };
    }

    // ===== 示例打印（肉眼看一眼生成结果是否合理）=====

    private static void 打印示例(int 种子, 片区数据 片区)
    {
        Console.WriteLine($"--- 种子 {种子} · {片区.名称} · 街道 {片区.街道.列}×{片区.街道.行} · 建筑 {片区.建筑.Count} 栋 ---");
        Console.WriteLine("图例：#墙/建筑体  ·街道/地板  E出口  X障碍  c搜索点  Z敌人  D建筑入口");
        打印层(片区.街道, 片区.街道.出生列, 片区.街道.出生行);
        foreach (var 楼 in 片区.建筑)
        {
            Console.WriteLine($"楼[{楼.标识}] 入口@街道({楼.入口列},{楼.入口行}) 楼层 {楼.楼层.Count}");
            for (int i = 0; i < 楼.楼层.Count; i++)
            {
                Console.WriteLine($"  {楼.楼层[i].名称} {楼.楼层[i].列}×{楼.楼层[i].行}（图例：#墙 ·地板 c容器 Z敌人 >楼梯 @出生）");
                打印层(楼.楼层[i], 楼.楼层[i].出生列, 楼.楼层[i].出生行);
            }
        }
        Console.WriteLine();
    }

    private static void 打印层(沙盒层数据 层, int 出生列, int 出生行)
    {
        for (int r = 0; r < 层.行; r++)
        {
            var 行文本 = new StringBuilder("  ");
            for (int c = 0; c < 层.列; c++)
            {
                if (c == 出生列 && r == 出生行) { 行文本.Append('@'); continue; }
                var 格 = 层.取(c, r);
                if (格 == null) { 行文本.Append('?'); continue; }
                switch (格.对象)
                {
                    case 沙盒对象.搜索点: 行文本.Append('c'); break;
                    case 沙盒对象.敌人: 行文本.Append('Z'); break;
                    case 沙盒对象.建筑入口: 行文本.Append('D'); break;
                    case 沙盒对象.楼梯: 行文本.Append('>'); break;
                    case 沙盒对象.尸体: 行文本.Append('x'); break;
                    default:
                        行文本.Append(格.地形 switch
                        {
                            沙盒地形.墙 => '#',
                            沙盒地形.建筑体 => '#',
                            沙盒地形.障碍 => 'X',
                            沙盒地形.出口 => 'E',
                            沙盒地形.门 => 格.门开 ? '/' : '|',
                            _ => '·',
                        });
                        break;
                }
            }
            Console.WriteLine(行文本.ToString());
        }
    }

    // ===== 输出 =====

    private static void 报错(int 种子, string 文本)
    {
        失败++;
        if (失败 <= 40) Console.WriteLine($"[失败] 种子{种子}：{文本}");
    }

    private static string 百分比(int 分子, int 分母) => 分母 <= 0 ? "0%" : $"{分子 * 100 / 分母}%";
    private static double 平均(int 分子, int 分母) => 分母 <= 0 ? 0 : (double)分子 / 分母;
}

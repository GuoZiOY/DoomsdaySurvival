using System;
using System.Collections.Generic;
using System.Text;

// 沙盒验证：批量跑种子，校验「世界沙盒生成器」的不变量（无 Unity、纯命令行）。
// 用法：dotnet run --project Tools/沙盒验证 [种子数]
//
// 校验项（生成器的验收标准，任何一条挂了就是 bug）：
//   ① 确定性：同种子两次生成 → 结构指纹一致；
//   ② 街道：出生点（出口）可通行；建筑入口 / 搜索点 全部从出生点可达；
//   ③ 建筑：楼层数 = 模板层数；每层出生点可通行；每层所有对象（容器/敌人/楼梯）从出生点可达；
//   ④ 容器：每层容器实例数与「该层房间的容器表」一致（不丢容器）；
//   ⑤ 无越界/空引用；房间数 = 请求数占比（BSP 成功率）。
public static class Program
{
    private static bool 参数含示例;
    private static int 失败;
    private static int 兜底楼层;
    private static int 总楼层;
    private static int 总房间;
    private static int 总容器;

    public static int Main(string[] args)
    {
        Console.OutputEncoding = Encoding.UTF8;
        int 总数 = args.Length > 0 && int.TryParse(args[0], out var n) ? n : 200;
        参数含示例 = Array.IndexOf(args, "示例") >= 0;

        var 数据 = 造数据();
        var 地区 = 数据.地区[0];

        Console.WriteLine($"=== 沙盒生成验证：{总数} 颗世界种子 ===");
        Console.WriteLine($"地区[{地区.标识}] 网格 {地区.网格列}×{地区.网格行} 建筑 {地区.建筑数量最小}~{地区.建筑数量最大} 搜索点 {地区.搜索点数量} 敌人 {地区.敌人数量最小}~{地区.敌人数量最大}");
        Console.WriteLine();

        for (int 种子 = 1; 种子 <= 总数; 种子++)
        {
            var 甲 = 区域生成器.生成(种子, 地区, id => 找建筑(数据, id), id => 找地图类型(数据, id));
            var 乙 = 区域生成器.生成(种子, 地区, id => 找建筑(数据, id), id => 找地图类型(数据, id));
            校验(种子, 甲, 数据);
            if (指纹(甲) != 指纹(乙)) 报错(种子, "确定性失败：同种子两次生成不一致");
            if (种子 == 1 || (参数含示例 && 种子 == 7)) 打印示例(种子, 甲);
        }

        Console.WriteLine();
        Console.WriteLine($"楼层总数 {总楼层} / 兜底楼层 {兜底楼层}（{百分比(兜底楼层, 总楼层)}）");
        Console.WriteLine($"平均每层房间 {平均(总房间, 总楼层):F1} / 平均每层容器 {平均(总容器, 总楼层):F1}");
        Console.WriteLine($"失败 {失败} 处（{总数} 颗种子）");
        return 失败 == 0 ? 0 : 1;
    }

    // ===== 校验 =====

    private static void 校验(int 种子, 片区数据 片区, 测试数据 数据)
    {
        if (片区 == null) { 报错(种子, "生成返回 null"); return; }
        var 街道 = 片区.街道;
        if (街道 == null) { 报错(种子, "街道层缺失"); return; }

        // ② 街道层
        if (街道.出生列 < 0 || 街道.出生行 < 0) 报错(种子, "街道出生点未设");
        var 出生格 = 街道.取(街道.出生列, 街道.出生行);
        if (出生格 == null) { 报错(种子, "街道出生点越界"); return; }
        if (出生格.地形 != 沙盒地形.出口) 报错(种子, $"街道出生点不是出口（{出生格.地形}）");
        var 可达 = 沙盒格工具.可达集(街道, 街道.出生列, 街道.出生行);
        var 街道含占位 = 沙盒格工具.可达集含占位(街道, 街道.出生列, 街道.出生行);
        foreach (var (c, r, 格) in 街道.全部())
        {
            if (格 == null) continue;
            if (!格.有对象 && !格.是门) continue;
            if (格.对象 == 沙盒对象.敌人) continue;
            if (!沙盒格工具.可达(街道, 可达, c, r)) 报错(种子, $"街道对象不可达：{格.对象}[{格.标识}] @({c},{r})");
            if (沙盒格工具.占位物(格) && !沙盒格工具.有相邻落脚点(街道, c, r, 街道含占位))
                报错(种子, $"街道家具被围死，搜不到 @({c},{r})");
            if (格.是门 && !沙盒格工具.可达(街道, 街道含占位, c, r)) 报错(种子, $"楼门被家具堵死 @({c},{r})");
        }
        if (片区.建筑.Count == 0) 报错(种子, "一栋楼都没生成");

        // ③④ 建筑逐层
        foreach (var 楼 in 片区.建筑)
        {
            if (楼 == null) { 报错(种子, "建筑为 null"); continue; }
            if (楼.入口列 < 0) 报错(种子, $"建筑[{楼.标识}] 没有入口格");
            var 模板 = 找建筑(数据, 楼.模板);
            int 期望层数 = 模板 != null ? Math.Max(1, 模板.层数) : 1;
            if (楼.楼层.Count != 期望层数) 报错(种子, $"建筑[{楼.标识}] 楼层数 {楼.楼层.Count} ≠ 模板 {期望层数}");
            if (楼.入口列 >= 0)
            {
                var 入口格 = 街道.取(楼.入口列, 楼.入口行);
                if (入口格 == null || 入口格.对象 != 沙盒对象.建筑入口)
                    报错(种子, $"建筑[{楼.标识}] 入口格未标记为建筑入口");
                else if (!沙盒格工具.可达(街道, 可达, 楼.入口列, 楼.入口行))
                    报错(种子, $"建筑[{楼.标识}] 入口不可达");
            }
            for (int 层 = 0; 层 < 楼.楼层.Count; 层++)
            {
                总楼层++;
                var 层数据 = 楼.楼层[层];
                校验楼层(种子, 楼, 层, 层数据, 数据);
            }
        }
    }

    private static void 校验楼层(int 种子, 建筑数据 楼, int 层, 沙盒层数据 层数据, 测试数据 数据)
    {
        // ④ 楼层：出生点可通行；门/楼梯/楼门 在「家具占格」下仍可达；每件家具旁边有落脚点
        if (层数据.出生列 < 0 || 层数据.出生行 < 0) { 报错(种子, $"建筑[{楼.标识}] 层{层} 出生点未设"); return; }
        var 出生 = 层数据.取(层数据.出生列, 层数据.出生行);
        if (出生 == null || !沙盒格工具.当前可通行(出生))
        { 报错(种子, $"建筑[{楼.标识}] 层{层} 出生点不可通行"); return; }

        var 可达 = 沙盒格工具.可达集(层数据, 层数据.出生列, 层数据.出生行);
        var 含占位 = 沙盒格工具.可达集含占位(层数据, 层数据.出生列, 层数据.出生行);
        int 容器数 = 0, 房间格数 = 0, 门数 = 0;
        foreach (var (c, r, 格) in 层数据.全部())
        {
            if (格 == null) { 报错(种子, $"建筑[{楼.标识}] 层{层} 格({c},{r}) 为 null"); continue; }
            if (沙盒格工具.可通行(格.地形)) 房间格数++;
            if (格.是门) 门数++;
            if (!格.有对象 && !格.是门) continue;
            if (!沙盒格工具.可达(层数据, 可达, c, r))
                报错(种子, $"建筑[{楼.标识}] 层{层} 对象不可达：{格.对象}[{格.标识}] @({c},{r})");
            if (格.对象 == 沙盒对象.搜索点)
            {
                容器数++;
                if (string.IsNullOrEmpty(格.标识) || string.IsNullOrEmpty(格.附加))
                    报错(种子, $"建筑[{楼.标识}] 层{层} 搜索点缺少 实例id/容器定义标识");
                if (!沙盒格工具.有相邻落脚点(层数据, c, r, 含占位))
                    报错(种子, $"建筑[{楼.标识}] 层{层} 家具被围死，搜不到 @({c},{r})");
            }
            if (格.对象 == 沙盒对象.楼梯)
            {
                if (string.IsNullOrEmpty(格.标识)) 报错(种子, $"建筑[{楼.标识}] 层{层} 楼梯缺少楼梯组");
                if (!沙盒格工具.可达(层数据, 含占位, c, r)) 报错(种子, $"建筑[{楼.标识}] 层{层} 楼梯被家具堵死");
            }
            if (格.对象 == 沙盒对象.建筑入口 && !沙盒格工具.可达(层数据, 含占位, c, r))
                报错(种子, $"建筑[{楼.标识}] 层{层} 楼门被家具堵死");
            if (格.是门 && !沙盒格工具.可达(层数据, 含占位, c, r))
                报错(种子, $"建筑[{楼.标识}] 层{层} 门被家具堵死 @({c},{r})");
        }
        if (门数 == 0) 报错(种子, $"建筑[{楼.标识}] 层{层} 一扇门都没有（房间之间应当有真门）");
        总房间 += 房间格数;
        总容器 += 容器数;

        // 多层楼：每层应有楼梯（层数>1），且上下层楼梯在同一格（真实楼梯上下对齐）
        if (楼.楼层.Count > 1)
        {
            bool 有楼梯 = false;
            foreach (var (_, _, 格) in 层数据.全部()) if (格 != null && 格.对象 == 沙盒对象.楼梯) { 有楼梯 = true; break; }
            if (!有楼梯) 报错(种子, $"建筑[{楼.标识}] 层{层} 没有楼梯（多层楼必须能上下）");
            var 基准 = 楼梯格(楼.楼层[0]);
            var 本层梯 = 楼梯格(层数据);
            if (基准 != null && 本层梯 != null && 基准 != 本层梯)
                报错(种子, $"建筑[{楼.标识}] 层{层} 楼梯与 1F 不在一格（{本层梯} vs {基准}）");
        }
        // 兜底判定：房间格数占比过低 → 走了条带兜底（记录，不报错）
        int 总面积 = 层数据.列 * 层数据.行;
        if (房间格数 * 100 / Math.Max(1, 总面积) > 95) 兜底楼层++;

        // 外墙圈：除门口开洞外，边界一圈必须是墙（楼层要像室内）
        int 圈开口 = 0;
        for (int c = 0; c < 层数据.列; c++)
            for (int r = 0; r < 层数据.行; r++)
            {
                if (c != 0 && r != 0 && c != 层数据.列 - 1 && r != 层数据.行 - 1) continue;
                var 格 = 层数据.取(c, r);
                if (格 != null && 沙盒格工具.可通行(格.地形)) 圈开口++;
            }
        if (圈开口 > 1) 报错(种子, $"建筑[{楼.标识}] 层{层} 外墙圈有 {圈开口} 处开口（应 ≤1：门口）");
    }

    // ===== 指纹（确定性判定用：只取结构关键量）=====

    private static (int 列, int 行)? 楼梯格(沙盒层数据 层)
    {
        if (层 == null) return null;
        foreach (var (列, 行, 格) in 层.全部())
            if (格 != null && 格.对象 == 沙盒对象.楼梯) return (列, 行);
        return null;
    }

    private static string 指纹(片区数据 片区)
    {
        if (片区?.街道 == null) return "null";
        var 缓冲 = new StringBuilder();
        foreach (var (_, _, 格) in 片区.街道.全部())
            缓冲.Append((int)格.地形).Append(格.对象 == 沙盒对象.无 ? "" : 格.标识);
        foreach (var 楼 in 片区.建筑)
        {
            缓冲.Append(楼.标识).Append(楼.入口列).Append(',').Append(楼.入口行);
            foreach (var 层 in 楼.楼层)
                foreach (var (_, _, 格) in 层.全部())
                    缓冲.Append((int)格.地形).Append(格.对象 == 沙盒对象.无 ? "" : 格.标识);
        }
        return 缓冲.ToString();
    }


using System;
using System.Collections.Generic;

// 建筑生成器：一栋楼 → 逐层 BSP 房间网格（含 楼梯 / 门 / 搜索容器 / 敌人）——纯 C#，确定性。
// 流程（每层独立跑一次，失败重试，最后兜底）：
//   ① 尺寸随机 → ② 房间请求（地图类型的房间各一块 + 楼梯间）→ ③ 房间切块器 递归二分
//   ④ 未覆盖格 = 墙 → ⑤ 相邻块之间开门（矩形划分的相邻图必连通）→ ⑥ 撒容器/敌人 → ⑦ 校验可达性
//
// 关键约定：
//   · 容器实例 id = 地区#建筑#层#房间#容器（确定性派生，同一实例跨会话稳定）——
//     绝不能拿「容器定义标识」当实例键（"衣柜"在一栋楼里有好几个，会串物资，见 搜索服务）。
//   · 房间「里有什么」一律来自 搜索_地图类型（房间→容器），本生成器不另立容器表。
public static class 建筑生成器
{
    private const int 每层最大尝试 = 12;

    // 生成一栋楼；regionKey 用于派生种子（地区标识），buildingKey 是本栋在片区内的唯一标识
    public static 建筑数据 生成(long 世界种子, string 地区标识, string 建筑标识, 建筑模板 模板, 搜索地图类型 地图类型)
    {
        var 楼 = new 建筑数据
        {
            标识 = 建筑标识,
            模板 = 模板?.标识,
            名称 = 模板?.名称 ?? 建筑标识,
            地图类型 = 模板?.地图类型,
            战斗棋盘 = string.IsNullOrEmpty(模板?.战斗棋盘) ? "室内" : 模板.战斗棋盘,
        };
        int 层数 = Math.Max(1, 模板?.层数 ?? 1);
        // 同一栋楼的每一层用同一块footprint（真实楼房上下对齐）；房间划分仍逐层独立随机
        var 尺寸随机 = 沙盒种子.随机流(沙盒种子.派生(世界种子, "建筑尺寸", 地区标识, 建筑标识));
        int 楼层列 = 沙盒种子.范围(尺寸随机, Math.Max(6, 模板.层宽最小), Math.Max(6, 模板.层宽最大));
        int 楼层行 = 沙盒种子.范围(尺寸随机, Math.Max(5, 模板.层高最小), Math.Max(5, 模板.层高最大));
        (int 列, int 行)? 楼梯基准 = null;   // 1F 的楼梯格：上层楼梯对齐到同一格（真实楼梯是上下对齐的）
        for (int 层 = 0; 层 < 层数; 层++)
        {
            var 层数据 = 生成楼层(世界种子, 地区标识, 建筑标识, 层, 层数, 模板, 地图类型, 楼层列, 楼层行, 楼梯基准, out bool _);
            if (层数据 == null) return 楼;      // 极端失败：返回已生成的楼层（调用方防御性判空）
            楼.楼层.Add(层数据);
            if (楼梯基准 == null)
            {
                foreach (var (列, 行, 格) in 层数据.全部())
                    if (格 != null && 格.对象 == 沙盒对象.楼梯) { 楼梯基准 = (列, 行); break; }
            }
        }
        // 1F 入口：贴边房间的内侧格（区域生成器据此在街道上放「建筑入口」）
        var 一层 = 楼.取楼层(0);
        if (一层 != null && 一层.出生列 >= 0) { 楼.入口边 = 一层.附加入口边; 楼.内入口列 = 一层.出生列; 楼.内入口行 = 一层.出生行; }
        return 楼;
    }

    // ===== 单层 =====

    private static 沙盒层数据 生成楼层(long 世界种子, string 地区标识, string 建筑标识, int 层, int 层数,
        建筑模板 模板, 搜索地图类型 地图类型, int 楼层列, int 楼层行, (int 列, int 行)? 楼梯基准, out bool 成功)
    {
        成功 = false;
        for (int 尝试 = 0; 尝试 < 每层最大尝试; 尝试++)
        {
            var 随机 = 沙盒种子.随机流(沙盒种子.派生(世界种子, "楼层", 地区标识, 建筑标识, 层, 尝试));
            var 层数据 = 尝试生成楼层(随机, 地区标识, 建筑标识, 层, 层数, 模板, 地图类型, 楼层列, 楼层行, 楼梯基准, false);
            if (层数据 != null) { 成功 = true; return 层数据; }
        }
        // 兜底：条带划分（保证出房间，绝不空手）
        var 兜底随机 = 沙盒种子.随机流(沙盒种子.派生(世界种子, "楼层兜底", 地区标识, 建筑标识, 层));
        return 尝试生成楼层(兜底随机, 地区标识, 建筑标识, 层, 层数, 模板, 地图类型, 楼层列, 楼层行, 楼梯基准, true);
    }

    // 一次尝试：force兜底=true 时用 条带兜底 代替 BSP（一定产出）
    private static 沙盒层数据 尝试生成楼层(Random 随机, string 地区标识, string 建筑标识, int 层, int 层数,
        建筑模板 模板, 搜索地图类型 地图类型, int 楼层列, int 楼层行, (int 列, int 行)? 楼梯基准, bool force兜底)
    {
        int 列 = 楼层列, 行 = 楼层行;
        var 层数据 = new 沙盒层数据(列, 行) { 名称 = 层 == 0 ? "1F" : $"{层 + 1}F", 地图类型 = 模板.地图类型, 战斗棋盘 = 模板.战斗棋盘 };
        // 外墙圈：房间只在 (1,1)-(列-2,行-2) 内切（外围一圈留墙，门口再开洞）——楼层才像室内
        int 内列 = 列 - 2, 内行 = 行 - 2;
        int 偏移 = 1;

        // —— 房间请求：房间池按楼层轮转分配（1F 玄关/客厅…，2F 卧室/洗浴间…——真实住宅的两层不会一模一样）；
        //    多层楼每层再加一间「楼梯间」；按切块区容量裁剪，避免「排不下 → 兜底成一个大间」——
        var 请求 = new List<切块请求>();
        var 房间名 = new List<string>();
        var 规格表 = 房间规格表(模板, 地图类型);
        var 本层规格 = new List<房间规格>();
        int 步长 = Math.Max(1, 层数);
        for (int i = 层; i < 规格表.Count; i += 步长) 本层规格.Add(规格表[i]);
        if (层 == 0 && !本层规格.Contains(规格表[0])) 本层规格.Insert(0, 规格表[0]);   // 1F 必须有门口房间
        if (本层规格.Count == 0) 本层规格.Add(规格表[0]);
        // 容量：每间房按 3×3（含缝）粗估；多层楼要给楼梯间留一格
        int 容量 = Math.Max(1, ((内列 + 1) / 3) * ((内行 + 1) / 3)) - (层数 > 1 ? 1 : 0);
        while (本层规格.Count > Math.Max(1, 容量)) 本层规格.RemoveAt(本层规格.Count - 1);
        foreach (var 规格 in 本层规格)
        {
            bool 本层需贴边 = 规格.需贴边 || (层 == 0 && 请求.Count == 0);   // 1F 第一间必须贴边（门口在此）
            请求.Add(new 切块请求(规格.标识, 规格.最小宽, 规格.最小高, 规格.目标宽, 规格.目标高, 本层需贴边));
            房间名.Add(规格.标识);
        }
        if (层数 > 1)
        {
            请求.Add(new 切块请求("楼梯间", 2, 2, 3, 3));
            房间名.Add("楼梯间");
        }

        // —— 切块（失败 → null，由外层重试/兜底）；结果整体平移 +1 落到外墙圈内侧 ——
        var 原始块 = force兜底 ? 房间切块器.兜底(内列, 内行, 请求) : 房间切块器.切块(随机, 内列, 内行, 请求);
        if (原始块 == null || 原始块.Count == 0) return null;
        // 非兜底尝试要求至少两块（单块 = 一整层没有隔墙、没有门 → 不像室内，重来）
        if (!force兜底 && 请求.Count >= 2 && 原始块.Count < 2) return null;
        var 块 = new List<切块结果>(原始块.Count);
        foreach (var b in 原始块) 块.Add(new 切块结果(b.标识, b.列 + 偏移, b.行 + 偏移, b.宽, b.高));

        // —— 铺地板：块内 = 地板；其余 = 墙 ——
        foreach (var 单块 in 块)
            for (int c = 单块.列; c < 单块.列 + 单块.宽; c++)
                for (int r = 单块.行; r < 单块.行 + 单块.高; r++)
                    层数据.设(c, r, 沙盒地形.地板);

        // —— 开门：相邻块之间在缝上放一扇【真门】（关着，点它推开）——
        // 矩形划分的相邻图必连通，所以「每对相邻块一扇门」就能保证全层连通
        var 门格 = new List<(int 列, int 行)>();
        for (int i = 0; i < 块.Count; i++)
            for (int j = i + 1; j < 块.Count; j++)
            {
                var 边界 = 房间切块器.公共边界(块[i], 块[j]);
                if (边界.Count == 0) continue;
                var 门 = 边界[随机.Next(边界.Count)];
                层数据.设(门.墙列, 门.墙行, 沙盒地形.门);
                var 单格 = 层数据.取(门.墙列, 门.墙行);
                if (单格 != null) 单格.门开 = false;
                门格.Add((门.墙列, 门.墙行));
            }

        // —— 出生点（进入本层的落脚点）：楼梯格优先；1F 用门口内侧格；1F 还要在墙上开一扇真门（出口门）——
        int 楼梯列 = -1, 楼梯行 = -1;
        if (层数 > 1)
        {
            int 楼梯块 = 块.FindIndex(b => b.标识 == "楼梯间");
            var 基格 = 楼梯基准 != null ? 层数据.取(楼梯基准.Value.列, 楼梯基准.Value.行) : null;
            if (楼梯基准 != null)
            {
                // 对齐 1F 的楼梯（上下是同一根楼梯）：这一格必须能站人；放不下就换一次布局重来（兜底时才放宽）
                if (基格 != null && 沙盒格工具.可通行(基格.地形) && !基格.是门)
                {
                    楼梯列 = 楼梯基准.Value.列; 楼梯行 = 楼梯基准.Value.行;
                }
                else if (!force兜底) return null;
            }
            if (楼梯列 < 0 && 楼梯块 >= 0)
            {
                楼梯列 = 块[楼梯块].列 + 块[楼梯块].宽 / 2;
                楼梯行 = 块[楼梯块].行 + 块[楼梯块].高 / 2;
            }
            // 最后保底：多层楼一定要有能上下的楼梯（兜底布局把楼梯间丢了也要补一格）
            if (楼梯列 < 0)
            {
                var 补 = 任意可站格(层数据);
                if (补 != null) { 楼梯列 = 补.Value.列; 楼梯行 = 补.Value.行; }
            }
            if (楼梯列 >= 0) 层数据.设对象(楼梯列, 楼梯行, 沙盒对象.楼梯, $"{建筑标识}_梯");
        }
        层数据.出生列 = 楼梯列 >= 0 ? 楼梯列 : 块[0].列 + 块[0].宽 / 2;
        层数据.出生行 = 楼梯行 >= 0 ? 楼梯行 : 块[0].行 + 块[0].高 / 2;
        if (层 == 0)
        {
            int 门口块 = 0;
            for (int i = 0; i < 块.Count; i++) if (块[i].标识 != "楼梯间" && 块[i].标识 == 房间名[0]) { 门口块 = i; break; }
            var 门内 = 贴边内侧格(块[门口块], 内列, 内行, 随机, out int 边);
            if (门内 != null)
            {
                层数据.出生列 = 门内.Value.列; 层数据.出生行 = 门内.Value.行;
                层数据.附加入口边 = 边;
                // 外墙圈上放一扇【真门】= 这栋楼的出入口：在楼里点它 = 出楼
                int 外列 = 门内.Value.列 + (边 == 2 ? -1 : 边 == 3 ? 1 : 0);
                int 外行 = 门内.Value.行 + (边 == 0 ? -1 : 边 == 1 ? 1 : 0);
                var 外门 = 层数据.取(外列, 外行);
                if (外门 != null)
                {
                    外门.地形 = 沙盒地形.门; 外门.门开 = false;
                    外门.对象 = 沙盒对象.建筑入口; 外门.标识 = 建筑标识;
                }
            }
        }
        // 门口/楼梯/门这些格子不许再摆家具
        var 已用格 = new HashSet<int>();
        已用格.Add(层数据.出生行 * 层数据.列 + 层数据.出生列);
        if (楼梯列 >= 0) 已用格.Add(楼梯行 * 层数据.列 + 楼梯列);
        foreach (var (门列, 门行) in 门格) 已用格.Add(门行 * 层数据.列 + 门列);
        foreach (var (c, r, 格) in 层数据.全部()) if (格 != null && 格.是门) 已用格.Add(r * 层数据.列 + c);

        // —— 容器（真实家具：占格、点它搜刮）——
        var 已用实例 = new HashSet<string>();
        var 家具备份 = new List<沙盒格>();   // 摆完做「家具不得堵路」校验时回退用
        if (地图类型?.房间 != null)
            foreach (var 房间 in 地图类型.房间)
            {
                if (房间?.容器 == null) continue;
                int 块号 = 块.FindIndex(b => b.标识 == 房间.标识);
                if (块号 < 0) continue;
                foreach (var 容器 in 房间.容器)
                {
                    if (容器 == null || string.IsNullOrEmpty(容器.标识)) continue;
                    if (随机.NextDouble() > Math.Min(1f, Math.Max(0f, 模板.容器出现概率))) continue;   // 不是每个房间都塞满柜子
                    var 落点 = 随机空位(随机, 块[块号], 层数据, 已用格);
                    if (落点 == null) continue;
                    string 实例 = $"{地区标识}#{建筑标识}#F{层}#{房间.标识}#{容器.标识}";
                    if (!已用实例.Add(实例)) continue;   // 同房间同名容器：只放一件（重名由内容侧改数据解决）
                    var 落格 = 层数据.取(落点.Value.列, 落点.Value.行);
                    if (落格 == null) continue;
                    家具备份.Add(new 沙盒格(落格.地形, 落格.对象, 落格.标识, 落格.附加) { 门开 = 落格.门开 });
                    落格.对象 = 沙盒对象.搜索点; 落格.标识 = 实例; 落格.附加 = 容器.标识;
                    已用格.Add(落点.Value.列 * 层数据.行 + 落点.Value.行);
                }
            }

        // —— 敌人：随机落在房间空地（不与家具/楼梯重叠）——
        int 敌人数量 = 沙盒种子.范围(随机, Math.Max(0, 模板.敌人数量最小), Math.Max(0, 模板.敌人数量最大));
        if (敌人数量 > 0 && !string.IsNullOrEmpty(模板.敌人池))
            for (int i = 0; i < 敌人数量; i++)
            {
                int 块号 = 随机.Next(块.Count);
                var 落点 = 随机空位(随机, 块[块号], 层数据, 已用格);
                if (落点 == null) continue;
                已用格.Add(落点.Value.列 * 层数据.行 + 落点.Value.行);
                层数据.设对象(落点.Value.列, 落点.Value.行, 沙盒对象.敌人, 模板.敌人池);
            }

        // 保底：一层至少有 1 件可搜的东西（否则玩家白跑一层）
        if (地图类型?.房间 != null && !有家具(层数据))
            foreach (var 房间 in 地图类型.房间)
            {
                if (房间?.容器 == null || 房间.容器.Length == 0) continue;
                int 块号 = 块.FindIndex(b => b.标识 == 房间.标识);
                if (块号 < 0) continue;
                var 容器 = 房间.容器[随机.Next(房间.容器.Length)];
                var 落点 = 随机空位(随机, 块[块号], 层数据, 已用格);
                if (落点 == null) continue;
                string 实例 = $"{地区标识}#{建筑标识}#F{层}#{房间.标识}#{容器.标识}";
                if (!已用实例.Add(实例)) continue;
                var 落格 = 层数据.取(落点.Value.列, 落点.Value.行);
                if (落格 == null) continue;
                家具备份.Add(new 沙盒格(落格.地形, 落格.对象, 落格.标识, 落格.附加) { 门开 = 落格.门开 });
                落格.对象 = 沙盒对象.搜索点; 落格.标识 = 实例; 落格.附加 = 容器.标识;
                已用格.Add(落点.Value.列 * 层数据.行 + 落点.Value.行);
                break;
            }

        // —— 校验①（结构）：所有 容器/敌人/楼梯/门 从出生点可达（门视为可通行——总能推开）——
        var 可达 = 沙盒格工具.可达集(层数据, 层数据.出生列, 层数据.出生行);
        foreach (var (c, r, 格) in 层数据.全部())
        {
            if (格 == null) continue;
            if (!格.有对象 && !格.是门) continue;
            if (!沙盒格工具.可达(层数据, 可达, c, r)) return null;   // 有东西被墙围死 → 本层重来
        }

        // —— 校验②（家具不得堵路）：把家具当阻挡后，门/楼梯/楼门 仍要到得了，且每件家具旁边有落脚点 ——
        // 不满足就撤掉最后摆的那件家具，重算（有界循环，确定性）
        for (int 撤销 = 0; 撤销 <= 家具备份.Count; 撤销++)
        {
            if (家具布局可行(层数据)) break;
            var 撤点 = 找最后一件家具(层数据);
            if (撤点 == null) break;
            var 撤格 = 层数据.取(撤点.Value.列, 撤点.Value.行);
            if (撤格 == null) break;
            撤格.对象 = 沙盒对象.无; 撤格.标识 = null; 撤格.附加 = null;
        }
        if (!家具布局可行(层数据)) return null;   // 撤完还不行 → 本层重来
        return 层数据;
    }

    // 家具布局可行性：家具当阻挡后，门/楼梯/楼门 仍可达，且每件家具旁边有可站立的落脚点
    private static bool 家具布局可行(沙盒层数据 层数据)
    {
        var 含占位 = 沙盒格工具.可达集含占位(层数据, 层数据.出生列, 层数据.出生行);
        foreach (var (列, 行, 格) in 层数据.全部())
        {
            if (格 == null) continue;
            if (沙盒格工具.占位物(格))
            {
                if (!沙盒格工具.有相邻落脚点(层数据, 列, 行, 含占位)) return false;   // 家具被围死 → 搜不到
                continue;
            }
            if (格.是门 || 格.对象 == 沙盒对象.楼梯 || 格.对象 == 沙盒对象.建筑入口)
                if (!沙盒格工具.可达(层数据, 含占位, 列, 行)) return false;            // 关键物件被家具堵住
        }
        return true;
    }

    private static (int 列, int 行)? 找最后一件家具(沙盒层数据 层数据)
    {
        (int 列, int 行)? 结果 = null;
        foreach (var (列, 行, 格) in 层数据.全部())
            if (格 != null && 沙盒格工具.占位物(格)) 结果 = (列, 行);
        return 结果;
    }

    private static bool 有家具(沙盒层数据 层数据)
    {
        foreach (var (_, _, 格) in 层数据.全部()) if (格 != null && 沙盒格工具.占位物(格)) return true;
        return false;
    }

    // ===== 小工具 =====

    // 房间规格表：模板房间池优先；为空 → 用 地图类型.房间（每个房间一块，尺寸按房间名给经验值）
    private static List<房间规格> 房间规格表(建筑模板 模板, 搜索地图类型 地图类型)
    {
        var 表 = new List<房间规格>();
        if (模板?.房间池 != null && 模板.房间池.Length > 0)
        {
            foreach (var 规格 in 模板.房间池)
                if (规格 != null && !string.IsNullOrEmpty(规格.标识)) 表.Add(规格);
            if (表.Count > 0) return 表;
        }
        if (地图类型?.房间 != null)
            foreach (var 房间 in 地图类型.房间)
                if (房间 != null && !string.IsNullOrEmpty(房间.标识)) 表.Add(默认规格(房间.标识));
        if (表.Count == 0) 表.Add(默认规格("空房"));
        return 表;
    }

    // 默认房间规格：按房间语义给尺寸（未知房间名 → 3×3）
    private static 房间规格 默认规格(string 标识)
    {
        switch (标识)
        {
            case "玄关": return new 房间规格 { 标识 = 标识, 最小宽 = 2, 最小高 = 2, 目标宽 = 3, 目标高 = 2, 需贴边 = true };
            case "客厅": return new 房间规格 { 标识 = 标识, 最小宽 = 3, 最小高 = 3, 目标宽 = 4, 目标高 = 4 };
            case "厨房": return new 房间规格 { 标识 = 标识, 最小宽 = 2, 最小高 = 3, 目标宽 = 3, 目标高 = 3 };
            case "卧室": return new 房间规格 { 标识 = 标识, 最小宽 = 3, 最小高 = 2, 目标宽 = 4, 目标高 = 3 };
            case "洗浴间": return new 房间规格 { 标识 = 标识, 最小宽 = 2, 最小高 = 2, 目标宽 = 2, 目标高 = 2 };
            case "杂物间": return new 房间规格 { 标识 = 标识, 最小宽 = 2, 最小高 = 2, 目标宽 = 3, 目标高 = 3 };
            default: return new 房间规格 { 标识 = 标识, 最小宽 = 2, 最小高 = 2, 目标宽 = 3, 目标高 = 3 };
        }
    }

    // 块内随机找一个「可通行 + 未被占用 + 不是门」的格（找不到返回 null）。
    // 不贴门的格优先——家具贴着门摆最容易把门口堵死（后面还有一道回退校验兜着）。
    private static (int 列, int 行)? 随机空位(Random 随机, 切块结果 块, 沙盒层数据 层, HashSet<int> 已用)
    {
        var 首选 = new List<(int 列, int 行)>();
        var 次选 = new List<(int 列, int 行)>();
        for (int c = 块.列; c < 块.列 + 块.宽; c++)
            for (int r = 块.行; r < 块.行 + 块.高; r++)
            {
                var 单格 = 层.取(c, r);
                if (单格 == null || !沙盒格工具.可通行(单格.地形)) continue;
                if (单格.是门) continue;                 // 门格不摆家具
                if (单格.有对象) continue;               // 已被占用（楼梯/别的家具/敌人）
                if (已用 != null && 已用.Contains(c * 层.行 + r)) continue;
                (贴门(层, c, r) ? 次选 : 首选).Add((c, r));
            }
        var 池 = 首选.Count > 0 ? 首选 : 次选;
        if (池.Count == 0) return null;
        return 池[随机.Next(池.Count)];
    }

    // 任意一个能站人的格（楼梯保底用；从内圈开始找，避免贴外墙）
    private static (int 列, int 行)? 任意可站格(沙盒层数据 层)
    {
        for (int 行 = 1; 行 < 层.行 - 1; 行++)
            for (int 列 = 1; 列 < 层.列 - 1; 列++)
            {
                var 格 = 层.取(列, 行);
                if (格 != null && 沙盒格工具.可通行(格.地形) && !格.是门 && !格.有对象) return (列, 行);
            }
        return null;
    }

    private static bool 贴门(沙盒层数据 层, int 列, int 行)    {
        foreach (var (偏列, 偏行) in 沙盒格工具.四方向)
        {
            var 邻 = 层.取(列 + 偏列, 行 + 偏行);
            if (邻 != null && 邻.是门) return true;
        }
        return false;
    }

    // 贴边块的内侧格（门口）：取块上贴着「房间切块区」外沿的边，返回该边上的一个格 + 边编号（0上 1下 2左 3右）
    private static (int 列, int 行)? 贴边内侧格(切块结果 块, int 内列, int 内行, Random 随机, out int 边)
    {
        边 = -1;
        var 候选边 = new List<int>();
        if (块.行 == 1) 候选边.Add(0);
        if (块.行 + 块.高 == 1 + 内行) 候选边.Add(1);
        if (块.列 == 1) 候选边.Add(2);
        if (块.列 + 块.宽 == 1 + 内列) 候选边.Add(3);
        if (候选边.Count == 0) return null;
        边 = 候选边[随机.Next(候选边.Count)];
        switch (边)
        {
            case 0: return (块.列 + 随机.Next(块.宽), 块.行);
            case 1: return (块.列 + 随机.Next(块.宽), 块.行 + 块.高 - 1);
            case 2: return (块.列, 块.行 + 随机.Next(块.高));
            default: return (块.列 + 块.宽 - 1, 块.行 + 随机.Next(块.高));
        }
    }

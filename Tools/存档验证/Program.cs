using System;
using System.Collections.Generic;
using System.Reflection;

// ============================================================
// 存档验证（v52 刀64）—— 离线断言"存档载荷"这一层。
//
// 验什么 / 不验什么（说清楚，免得把"没验"当成"验过了"）：
//   ✅ 版本检查真值表、迁移链（v4→v5）幂等、槽位规格、
//      **整点结算**（"读档即死"的现场，游戏跑的就是这个函数）、
//      **玩家档案 每一个标量字段都被 存档指纹 覆盖**（自动抓"新加字段忘了进指纹"）。
//   ❌ JsonUtility 的实际往返 —— 它 Unity 专属，离线编译不了。
//      那一半由两道**另一处**的关口补上，不要以为本文件盖住了：
//        · 游戏内「存档往返自检」（快速测试面板 的按钮）：真 SaveService + 真 JsonUtility，存→读→比指纹；
//        · Tools/存档接线核对.ps1：源码级门禁（载荷里出现 Dictionary/HashSet/ValueTuple/未标 NonSerialized 的
//          Func ⇒ 报错；读档路径必须调 世界时间管理器.读档后对齐；等等）。
// ============================================================
public static class Program
{
    private static int 通过, 失败;

    private static void 断言(bool 条件, string 说明)
    {
        if (条件) { 通过++; Console.WriteLine($"  [ok] {说明}"); }
        else { 失败++; Console.WriteLine($"  [!!] {说明}"); }
    }

    private static void 段(string 标题) => Console.WriteLine($"\n===== {标题} =====");

    public static int Main(string[] 参数)
    {
        Console.OutputEncoding = System.Text.Encoding.UTF8;
        Console.WriteLine("存档验证（刀64）：存档载荷 / 版本迁移 / 整点结算 / 指纹覆盖");

        验版本检查();
        验迁移链();
        验槽位规格();
        验整点结算();
        验指纹覆盖();

        Console.WriteLine($"\n===== 结果：{通过} 通过 / {失败} 失败 =====");
        return 失败 == 0 ? 0 : 1;
    }

    // ---------------------------------------------------------------- 版本检查

    private static void 验版本检查()
    {
        段("版本检查（老代码读了版本号但从不检查 —— 见 存档版本.检查 的注释）");
        断言(存档版本.检查(0) != "", "版本 0 → 拒（没有版本号，不是本游戏的档）");
        断言(存档版本.检查(-3) != "", "负版本 → 拒");
        断言(存档版本.检查(4) == "", "v4 旧档 → 可读（要迁移）");
        断言(存档版本.检查(存档规格.当前版本) == "", "当前版本 → 可读");
        断言(存档版本.检查(存档规格.当前版本 + 1) != "", "未来版本（v+1）→ 拒");
        断言(存档版本.检查(99).Contains("新"), "拒绝原因说清是「版本太新」，玩家看得懂");
    }

    // ---------------------------------------------------------------- 迁移链

    private static void 验迁移链()
    {
        段("迁移链（v4 → v5）");
        var 数据 = new 存档数据 { 头 = new 存档头 { 版本 = 4 }, 玩家 = new 玩家档案() };
        var 步骤 = 存档版本.迁移(数据);
        断言(数据.头.版本 == 存档规格.当前版本, $"v4 迁到当前版本（{数据.头.版本}）");
        断言(步骤.Count > 0, "迁移有记录（写日志/文档用）");
        断言(存档版本.迁移(数据).Count == 0, "迁移幂等：已是最新就不再动");

        var 无头 = new 存档数据 { 头 = null, 玩家 = new 玩家档案() };
        存档版本.迁移(无头);
        断言(无头.头 != null, "头 缺失时自动补一个（v4 的载荷根本没有头）");
        断言(无头.头.版本 == 存档规格.当前版本, "补出来的头带上当前版本");

        断言(存档版本.迁移(null) != null, "迁移 null 不抛（返回空步骤表）");

        // 关键口径：整点基准缺省 0 = "读档时退化为当前时间"，不许猜一个值出来
        var 缺基准 = new 存档数据 { 头 = new 存档头 { 版本 = 4 }, 玩家 = new 玩家档案(), 整点基准 = 0f };
        存档版本.迁移(缺基准);
        断言(缺基准.整点基准 == 0f, "★ v4 迁移**不猜**整点基准（0 = 读档时退化为当前时间，安全等价）");
    }

    // ---------------------------------------------------------------- 槽位规格

    private static void 验槽位规格()
    {
        段("槽位规格");
        断言(存档规格.当前版本 >= 5, "当前版本 >= 5（v5 才开始有 头 / 整点基准 / 文件多槽）");
        断言(存档规格.合法槽(存档规格.自动槽号), "自动槽合法");
        断言(存档规格.合法槽(存档规格.手动槽数), $"手动槽 1..{存档规格.手动槽数} 合法");
        断言(!存档规格.合法槽(-1), "槽 -1 → 不合法");
        断言(!存档规格.合法槽(存档规格.手动槽数 + 1), "槽 超出上限 → 不合法");

        var 名 = new HashSet<string>();
        int 数 = 0;
        foreach (int 槽 in 存档规格.全部槽()) { 数++; 名.Add(存档规格.文件名(槽)); }
        断言(数 == 存档规格.手动槽数 + 1, $"槽位数量 = 1 自动 + {存档规格.手动槽数} 手动");
        断言(名.Count == 数, "每个槽的文件名互不相同（否则两个槽写同一个文件 = 互相覆盖）");
        断言(存档规格.文件名(0).EndsWith(".json"), "存档是 .json 文本（可读 / 可备份 / 可 diff）");
        断言(存档规格.旧档键.Contains("v4"), "旧档键保留 v4 字样（迁移只认它，改了老玩家的档就找不到了）");
        断言(存档规格.槽名(存档规格.自动槽号).Contains("自动"), "自动槽 的名字里带「自动」（UI 上区隔开）");
    }

    // ---------------------------------------------------------------- 整点结算（核心）

    private static void 验整点结算()
    {
        段("整点结算（★「读档即死」的现场：游戏跑的就是 整点结算 这个函数）");
        float 第5天 = 5f * 整点结算.一天分钟;   // 7200 游戏分钟 = 第 5 天 0:00

        int 次 = 整点结算.应结算次数(第5天, 0f, out float 新基准);
        断言(次 == 120, $"★ 基准 0 + 第 5 天(7200 分) → 应结算 {次} 次（= 5 天 × 24 小时）= 读档即死的现场");
        断言(新基准 == 第5天, "追完基准正好落到当前时间");

        次 = 整点结算.应结算次数(第5天, 第5天, out _);
        断言(次 == 0, "★ 读档后对齐（基准 = 游戏分钟数）→ 0 次结算 —— 修好了");

        次 = 整点结算.应结算次数(第5天 + 30f, 第5天, out 新基准);
        断言(次 == 0 && 新基准 == 第5天, "不足 1 整点不结算，且基准保相位（不吞掉那 30 分钟）");
        次 = 整点结算.应结算次数(第5天 + 59f, 第5天, out _);
        断言(次 == 0, "差 59 分仍不结算（按整点时刻对齐，不是按差值算）");
        次 = 整点结算.应结算次数(第5天 + 60f, 第5天, out 新基准);
        断言(次 == 1 && 新基准 == 第5天 + 60f, "正好到整点 → 结算 1 次");
        次 = 整点结算.应结算次数(第5天 + 150f, 第5天, out _);
        断言(次 == 2, "跨 2 个整点 → 结算 2 次");
        断言(整点结算.应结算次数(第5天, 第5天 - 60f, out _) == 1, "落后 1 整点 → 补 1 次");
        断言(整点结算.应结算次数(第5天, 第5天 + 600f, out _) == 0, "基准在未来 → 一次都不结算（「白送时间」的现场）");

        // 自愈判据
        断言(整点结算.需要重对齐(第5天, 0f), "★ 基准 0 + 第 5 天 → 判为需要自愈（差 7200 > 1440）");
        断言(整点结算.需要重对齐(420f, 5000f), "时间倒退（新游戏重置 / 读档换档）→ 判为需要自愈");
        断言(!整点结算.需要重对齐(第5天, 第5天), "已对齐 → 不需要自愈");
        断言(!整点结算.需要重对齐(第5天 + 30f, 第5天), "正常推进 30 分钟 → 不需要自愈");
        断言(!整点结算.需要重对齐(第5天 + 1439f, 第5天), "单帧推进 1439 分钟（挂起恢复的极端值）→ 不触发自愈");
        断言(整点结算.需要重对齐(第5天 + 1441f, 第5天), "差超过 1 游戏天 → 判为「某个入口忘了对齐」");
        断言(整点结算.需要重对齐(第5天, 第5天 + 2f, out _), "基准超前 2 分钟也算倒退（哪怕只超前一点，「不结算」就是白送）");

        // 坏输入不许崩、不许卡死
        断言(整点结算.应结算次数(-5f, 0f, out _) == 0, "负时间 → 不结算、不崩");
        断言(整点结算.应结算次数(第5天, -5000f, out _) <= 整点结算.单次上限, "基准是负的巨大值 → 有上限保护（不许一帧补算到卡死）");
        断言(整点结算.应结算次数(1e9f, 0f, out _) == 整点结算.单次上限, "时间被写坏成 1e9 → 正好停在防呆上限上");
        断言(整点结算.单次上限 >= 365 * 24, $"★ 防呆上限（{整点结算.单次上限}）必须远大于任何**合法**补算 —— " +
             "写小了会把「读档即死」这条证据藏起来（本断言就是为此立的）");
    }

    // ---------------------------------------------------------------- 指纹覆盖

    private static void 验指纹覆盖()
    {
        段("档案指纹（往返断言的判据）");
        var 档 = new 玩家档案();
        string 甲 = 存档指纹.取(档);
        断言(甲 == 存档指纹.取(档), "同一状态取两次指纹一致（确定性）");
        断言(存档指纹.取(null) == "<null>", "null 档案不抛");

        // —— 自动覆盖检查：**每一个**标量序列化字段都必须在指纹里留下痕迹 ——
        // 这条是为了自动抓住"给 玩家档案 加了个新字段、忘了加进指纹"这类退化 ——
        // `天赋冷却` 就是现成的例子：它是 Dictionary，被 JsonUtility 静默丢弃，而没有任何断言看得见。
        int 查过 = 0, 漏 = 0;
        foreach (var 字段 in typeof(玩家档案).GetFields(BindingFlags.Public | BindingFlags.Instance))
        {
            if (字段.IsNotSerialized) continue;   // [NonSerialized] 的解析器与子管理器 —— 本来就不进档
            var 类型 = 字段.FieldType;
            bool 是标量 = 类型 == typeof(int) || 类型 == typeof(float) || 类型 == typeof(bool) || 类型 == typeof(string);
            if (!是标量) continue;
            var 样本 = new 玩家档案();
            string 前 = 存档指纹.取(样本);
            object 值 = 字段.GetValue(样本);
            object 新值;
            if (类型 == typeof(int)) 新值 = (int)值 + 7;
            else if (类型 == typeof(float)) 新值 = (float)值 + 7f;
            else if (类型 == typeof(bool)) 新值 = !(bool)值;
            else 新值 = (值 as string ?? "") + "改";
            字段.SetValue(样本, 新值);
            查过++;
            if (存档指纹.取(样本) == 前)
            {
                漏++;
                Console.WriteLine($"      [!!] 指纹漏了标量字段：{字段.Name}（{类型.Name}）");
            }
        }
        断言(漏 == 0, $"玩家档案 的 {查过} 个标量序列化字段**全部**被指纹覆盖（漏 {漏} 个）");
        断言(查过 >= 20, $"确实扫到了足够多的标量字段（{查过} 个）—— 防止反射扫空了还报「通过」");

        // —— 集合 / 复合字段：逐个手改（类型太杂，没法通用地"改成另一个值"）
        断言(变了(档, x => x.天赋.Add("测试天赋")), "改 天赋 → 指纹变");
        断言(变了(档, x => x.记天赋冷却("钢铁意志")), "★ 改 天赋冷却（原 Dictionary，被静默丢弃的那个）→ 指纹变");
        断言(变了(档, x => x.已学技能.Add(new 技能掌握("测试技能"))), "改 已学技能 → 指纹变");
        断言(变了(档, x => x.战斗技能槽.Add("测试技能")), "改 战斗技能槽 → 指纹变");
        断言(变了(档, x => x.已习得配方.Add("测试配方")), "改 已习得配方 → 指纹变");
        断言(变了(档, x => x.抉择记录.Add("测试抉择")), "改 抉择记录 → 指纹变");
        断言(变了(档, x => x.已清空地点.Add("测试地点")), "改 已清空地点 → 指纹变");
        断言(变了(档, x => x.幸存者.Add("测试幸存者")), "改 幸存者 → 指纹变");
        断言(变了(档, x => x.写迷雾("格子|1#地图", 4, 4, new[] { 1, 2 })), "改 迷雾记忆 → 指纹变");
        断言(变了(档, x => x.已拆墙.Add("3,4")), "★ 改 已拆墙（刀64 新增）→ 指纹变");
        断言(变了(档, x => x.任务.Add(new 任务进度 { 标识 = "测试任务", 数量 = 1 })), "改 任务 → 指纹变");
        断言(变了(档, x => x.日常.Add(new 日常任务 { 标识 = "测试日常", 目标标识 = "面包", 目标数量 = 1 })), "改 日常 → 指纹变");
        断言(变了(档, x => x.家具.Add(new 物品堆叠("床", 1))), "改 家具 → 指纹变");
        断言(变了(档, x => x.仓库物品.Add(new 物品堆叠("面包", 2))), "改 仓库物品 → 指纹变");
        断言(变了(档, x => x.装备.Add(new 装备记录("主手", "军刀"))), "改 装备 → 指纹变");
        断言(变了(档, x => x.网格服务.网格物品.Add(new 物品堆叠("水", 1))), "改 主背包 网格物品 → 指纹变");

        // —— 递归容器：箱中箱的内容丢了要能被抓到
        断言(变了(档, x => x.仓库物品[0].容器物品 = new List<物品堆叠> { new 物品堆叠("绷带", 3) }),
            "★ 嵌套容器内容（容器物品）→ 指纹变（递归）");
        断言(变了(档, x => x.仓库物品[0].容器列 = 4), "容器尺寸 → 指纹变");
        断言(变了(档, x => x.仓库物品[0].新鲜分钟 = 12f), "保质期 新鲜分钟 → 指纹变");
        断言(变了(档, x => x.仓库物品[0].配件 = new List<配件条> { new 配件条("枪口", "消音器") }), "配件 → 指纹变");
        断言(变了(档, x => x.装备[0].当前耐久 = 3), "装备实例耐久 → 指纹变");
        断言(变了(档, x => x.装备[0].容器物品 = new List<物品堆叠> { new 物品堆叠("弹匣", 1) }), "穿戴容器内容 → 指纹变");
    }

    private static bool 变了(玩家档案 档, Action<玩家档案> 改)
    {
        string 前 = 存档指纹.取(档);
        改(档);
        return 存档指纹.取(档) != 前;
    }
}

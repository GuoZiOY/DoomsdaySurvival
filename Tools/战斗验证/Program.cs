    private static int 失败;
    private static int 断言数;

    private static void 断言(bool 条件, string 说明)
    {
        断言数++;
        if (!条件) { Console.WriteLine("  ✗ " + 说明); 失败++; }
    }

    private static void 报错(string 说明) { Console.WriteLine("  ✗ " + 说明); 失败++; }

    private static void 小节(string 名) => Console.WriteLine(名);

    private static int Main()
    {
        Console.WriteLine("=== 战斗验证（纯 C# 面）===");
        Console.WriteLine($"链接源：Domain/战斗/战斗单位.cs · Data/数据模型.cs（零 UnityEngine，无需桩）");
        Console.WriteLine("");

        精力();
        秒制冷却();
        秒制眩晕();
        Buff叠层与到期();
        属性修正与封顶();
        防御减伤();
        持续伤害与控制();
        工厂();
        伤害公式();
        固定步长累加();
        敌人AI决策();
        随机源();

        Console.WriteLine("");
        if (断言数 < 20)
        {
            报错($"只跑了 {断言数} 条断言 —— 少于预期（20），判据可能被改没了（别让「空检查」当成通过）");
        }
        if (失败 == 0)
        {
            Console.WriteLine($"✅ 战斗验证（第一步）通过：{断言数} 条断言");
            return 0;
        }
        Console.WriteLine($"❌ 战斗验证失败：{失败} 处（共 {断言数} 条断言）");
        return 1;
    }


using System;
using System.Collections.Generic;

// ============================================================
// 战斗验证（第一步：**纯 C# 面**）—— 战斗是全项目唯一零覆盖的子系统（其余五个验证器都不碰它）。
//
// 这一批只验 `Domain/战斗/战斗单位.cs`（它是纯 C#、零 UnityEngine，所以**连桩都不用**）：
//   精力 / 秒制冷却 / 秒制眩晕 / Buff 叠层与到期 / 无敌 / 属性修正与封顶 / 防御减伤封顶 /
//   持续伤害按结算时机 / 控制类异常 / 两个工厂（从敌人生成、从助战生成）。
//
// ⚠ 为什么值得写：这些规则**全是数值与状态机**，错了不会崩、只会让战斗"感觉不对"（掉血少一点、
//   眩晕短一点、层数不封顶），靠进游戏打一把几乎发现不了。它们又都在一个纯函数文件里 → 逐点断言最划算。
//
// 还没覆盖的（下一步，见 docs/优化实施进度.md）：
//   ① `BattleService` 整场跑（收尾必达 / 结算守恒 / 节点与射程）—— 需要给 11 个静态服务
//      与 `Resources.Load` + `JsonUtility` 做桩，是单独一刀；
//   ② `品质工具.倍率`（`Quality.cs` 现在还用 `Color`）—— 等它提纯后并进来；
//   ③ 数据完整性（enemies/skills 交叉引用）—— 已由 `Tools/数据引用核对.ps1` 第 9 段覆盖。
//
// 用法：dotnet run --project Tools\战斗验证 -c Release
// ============================================================
static class 战斗验证
{
    private static int 失败;
    private static int 断言数;

    private static void 断言(bool 条件, string 说明)
    {
        断言数++;
        if (!条件) { Console.WriteLine("  ✗ " + 说明); 失败++; }
    }

    private static void 报错(string 说明) { Console.WriteLine("  ✗ " + 说明); 失败++; }

    private static void 小节(string 名) => Console.WriteLine(名);

    private static int Main()
    {
        Console.WriteLine("=== 战斗验证（纯 C# 面）===");
        Console.WriteLine($"链接源：Domain/战斗/战斗单位.cs · Data/数据模型.cs（零 UnityEngine，无需桩）");
        Console.WriteLine("");

        精力();
        秒制冷却();
        秒制眩晕();
        Buff叠层与到期();
        属性修正与封顶();
        防御减伤();
        持续伤害与控制();
        工厂();

        Console.WriteLine("");
        if (断言数 < 20)
        {
            报错($"只跑了 {断言数} 条断言 —— 少于预期（20），判据可能被改没了（别让「空检查」当成通过）");
        }
        if (失败 == 0)
        {
            Console.WriteLine($"✅ 战斗验证（第一步）通过：{断言数} 条断言");
            return 0;
        }
        Console.WriteLine($"❌ 战斗验证失败：{失败} 处（共 {断言数} 条断言）");
        return 1;
    }

    // ============ 构造测试数据 ============

    private static 敌人数据 敌人(string 移动AI = "冲锋", int 攻击距离 = 1, int 身形 = 1,
        float 移动秒 = 0f, float 攻击秒 = 0f, float 技能秒 = 0f, AI行动项[] 行动表 = null)
        => new 敌人数据
        {
            标识 = "测试敌人", 名称 = "测试敌人",
            生命 = 30, 攻击 = 8, 防御 = 20, 速度 = 6,
            移动AI = 移动AI, 攻击距离 = 攻击距离, 身形 = 身形,
            移动间隔秒 = 移动秒, 攻击间隔秒 = 攻击秒, 技能间隔秒 = 技能秒,
            行动表 = 行动表,
        };

    private static Buff定义 Buff(string 类型, string 属性 = "", int 数值 = 0, int 持续 = 1,
        int 最大层 = 1, bool 控制 = false, string 结算时机 = null, string 标识 = null)
        => new Buff定义
        {
            标识 = 标识 ?? (类型 + 属性 + 数值 + 持续 + 最大层), 名称 = "测试" + 类型,
            类型 = 类型, 属性 = 属性, 数值 = 数值,
            持续回合 = 持续, 最大层数 = 最大层, 控制 = 控制, 结算时机 = 结算时机,
        };

    private static 战斗单位 单位(int 生命 = 20, int 精力 = 10, int 物防 = 0)
        => new 战斗单位 { 名称 = "测试", 是否我方 = true, 生命 = 生命, 最大生命 = 生命, 精力 = 精力, 最大精力 = 精力, 基础物防 = 物防 };

    // ============ 断言 ============

    private static void 精力()
    {
        小节("[1] 精力：够了才扣、不超上限");
        var u = 单位(精力: 10);
        断言(u.消耗精力(3), "精力 10 扣 3 应当成功");
        断言(u.精力 == 7, $"扣完应当是 7，实际 {u.精力}");
        断言(!u.消耗精力(99), "不够时应当返回 false");
        断言(u.精力 == 7, $"失败**不许**扣掉任何精力（「精力被吞」那类 bug），实际 {u.精力}");
        u.恢复精力(100);
        断言(u.精力 == u.最大精力, $"恢复不许超上限，实际 {u.精力}/{u.最大精力}");
    }

    private static void 秒制冷却()
    {
        小节("[2] 技能冷却：现实秒递减、到 0 移除、0 不写入");
        var u = 单位();
        断言(u.冷却剩余("重斩") == 0f, "没放过的技能冷却应当是 0");
        u.开始冷却("重斩", 5f);
        断言(Math.Abs(u.冷却剩余("重斩") - 5f) < 0.001f, "开始冷却 5 秒后剩余应当是 5");
        u.推进冷却(2f);
        断言(Math.Abs(u.冷却剩余("重斩") - 3f) < 0.001f, $"推进 2 秒后应当是 3，实际 {u.冷却剩余("重斩")}");
        u.推进冷却(3f);
        断言(u.冷却剩余("重斩") == 0f, "推进到 0 应当被移除（剩余 0）");
        断言(!u.技能冷却.ContainsKey("重斩"), "到 0 之后字典里不该再留着这个 key（否则每帧白遍历）");
        u.开始冷却("瞬发", 0f);
        断言(!u.技能冷却.ContainsKey("瞬发"), "冷却 0 的技能不该写进字典");
        u.推进冷却(1f);   // 空表时不应崩
        断言(true, "空冷却表推进不崩");
    }

    private static void 秒制眩晕()
    {
        小节("[3] 眩晕：秒制、刷新取更长、0/负数不生效、期间无法行动");
        var u = 单位();
        断言(!u.无法行动, "没眩晕时应当能行动");
        u.施加眩晕(2f);
        断言(Math.Abs(u.眩晕剩余秒 - 2f) < 0.001f, $"眩晕 2 秒应当记 2，实际 {u.眩晕剩余秒}");
        断言(u.无法行动, "眩晕期间 无法行动 必须为真");
        u.施加眩晕(1f);
        断言(Math.Abs(u.眩晕剩余秒 - 2f) < 0.001f, $"更短的眩晕不许缩短（刷新取更长），实际 {u.眩晕剩余秒}");
        u.施加眩晕(3f);
        断言(Math.Abs(u.眩晕剩余秒 - 3f) < 0.001f, $"更长的眩晕应当刷新，实际 {u.眩晕剩余秒}");
        u.眩晕剩余秒 = 0f;
        u.施加眩晕(0f); u.施加眩晕(-5f);
        断言(u.眩晕剩余秒 == 0f && !u.无法行动, "0 / 负数眩晕不许生效");
    }

    private static void Buff叠层与到期()
    {
        小节("[4] Buff：同标识叠层（封顶）+ 刷新计时；回合结束递减/移除；无敌回合");
        var u = 单位();
        var 攻 = Buff("增益", 属性: "攻击", 数值: 20, 持续: 2, 最大层: 3, 标识: "猛攻");
        for (int i = 0; i < 5; i++) u.添加Buff(攻);
        断言(u.Buffs.Count == 1, $"同标识只该有一份，实际 {u.Buffs.Count}");
        断言(u.Buffs[0].层数 == 3, $"层数应当封顶在 3，实际 {u.Buffs[0].层数}");
        断言(u.Buffs[0].剩余回合 == 2, $"每次添加都该刷新计时，实际 {u.Buffs[0].剩余回合}");
        u.回合结束();
        断言(u.Buffs.Count == 1 && u.Buffs[0].剩余回合 == 1, "过一轮后还应当在（剩 1 回合）");
        u.回合结束();
        断言(u.Buffs.Count == 0, "计时到 0 应当被移除");
        u.无敌回合 = 2;
        断言(u.无敌, "无敌回合 > 0 时 无敌 为真");
        u.回合结束(); u.回合结束();
        断言(!u.无敌 && u.无敌回合 == 0, "无敌回合应当递减到 0（且不为负）");
        u.移除Buff("不存在");
        断言(true, "移除不存在的 Buff 不崩");
    }

    private static void 属性修正与封顶()
    {
        小节("[5] 属性修正：增益加、减益减、当前值按百分比修正且下限 0；暴击/闪避封顶 0.8");
        var u = 单位();
        u.基础近战 = 10;
        u.添加Buff(Buff("增益", 属性: "攻击", 数值: 20, 持续: 9, 标识: "A"));
        u.添加Buff(Buff("增益", 属性: "攻击", 数值: 10, 持续: 9, 标识: "B"));
        断言(u.属性修正("攻击") == 30, $"两个攻击增益应当相加成 30，实际 {u.属性修正("攻击")}");
        断言(u.当前近战 == 13, $"10 × 1.30 应当取整成 13，实际 {u.当前近战}");
        u.添加Buff(Buff("减益", 属性: "攻击", 数值: -200, 持续: 9, 标识: "C"));
        断言(u.当前近战 == 0, $"修正到负数时必须夹在 0（不许出现负攻），实际 {u.当前近战}");
        var v = 单位();
        v.暴击率 = 0.5f; v.闪避率 = 0.5f; v.基础敏捷 = 5;
        v.添加Buff(Buff("增益", 属性: "敏捷", 数值: 100, 持续: 9, 标识: "猎人"));
        断言(Math.Abs(v.当前暴击率 - 0.8f) < 0.0001f, $"暴击率必须封顶 0.8，实际 {v.当前暴击率}");
        断言(Math.Abs(v.当前闪避率 - 0.8f) < 0.0001f, $"闪避率必须封顶 0.8，实际 {v.当前闪避率}");
    }

    private static void 防御减伤()
    {
        小节("[6] 防御减伤：物防 1 点 = 1%，**封顶 50%**");
        断言(Math.Abs(单位(物防: 0).防御减伤) < 0.0001f, "物防 0 不该有减伤");
        断言(Math.Abs(单位(物防: 30).防御减伤 - 0.30f) < 0.0001f, "物防 30 应当是 30%");
        断言(Math.Abs(单位(物防: 50).防御减伤 - 0.50f) < 0.0001f, "物防 50 应当是 50%");
        断言(Math.Abs(单位(物防: 80).防御减伤 - 0.50f) < 0.0001f,
            $"物防 80 必须封顶 50%（不封顶会让高防单位免伤），实际 {单位(物防: 80).防御减伤}");
    }

    private static void 持续伤害与控制()
    {
        小节("[7] 持续伤害按结算时机汇总、控制类不计入；控制类异常 → 无法行动");
        var u = 单位();
        // 毒：加**两层**（添加Buff 默认加 1 层）→ 用来验"按层数乘算"
        u.添加Buff(Buff("异常", 数值: 3, 持续: 9, 最大层: 2, 结算时机: "开始", 标识: "毒"));
        u.添加Buff(Buff("异常", 数值: 3, 持续: 9, 最大层: 2, 结算时机: "开始", 标识: "毒"));
        u.添加Buff(Buff("异常", 数值: 5, 持续: 9, 结算时机: "结束", 标识: "流血"));
        断言(u.持续伤害量("开始") == 6, $"毒 3×2 层 = 6，实际 {u.持续伤害量("开始")}");
        断言(u.持续伤害量("结束") == 5, $"流血应当是 5，实际 {u.持续伤害量("结束")}");
        断言(u.持续伤害量() == 6, "缺省时机应当等于开始");
        u.添加Buff(Buff("异常", 数值: 9, 持续: 9, 控制: true, 标识: "麻痹"));
        断言(u.持续伤害量("开始") == 6, $"控制类异常**不算**持续伤害，实际 {u.持续伤害量("开始")}");
        断言(u.无法行动, "控制类异常必须让单位无法行动");
        var v = 单位();
        v.添加Buff(Buff("异常", 数值: 3, 持续: 9, 控制: false, 标识: "中毒"));
        断言(!v.无法行动, "非控制类异常不该拦住行动（只是每轮掉血）");
    }

    private static void 工厂()
    {
        小节("[8] 工厂：从敌人生成 / 从助战生成（缺省值、行动表、归属）");
        var 表 = new[] { new AI行动项 { 行动 = "普攻", 权重 = 7 }, new AI行动项 { 行动 = "扑咬", 权重 = 3 } };
        var 敌 = 敌人(移动AI: "风筝", 攻击距离: 0, 身形: 0, 行动表: 表);
        var u = 战斗单位.从敌人生成(敌);
        断言(!u.是否我方, "敌人单位必须不是我方");
        断言(u.源数据 == 敌, "源数据 必须指回敌人数据（AI/掉落要用）");
        断言(u.生命 == 敌.生命 && u.最大生命 == 敌.生命, "生命应当照抄敌人数据");
        断言(u.攻击距离 == 1, $"攻击距离 数据写 0 时必须兜底成 1，实际 {u.攻击距离}");
        断言(u.身形 == 1, $"身形 数据写 0 时必须兜底成 1，实际 {u.身形}");
        断言(Math.Abs(u.移动间隔秒 - 5f) < 0.001f && Math.Abs(u.攻击间隔秒 - 5f) < 0.001f && Math.Abs(u.技能间隔秒 - 5f) < 0.001f,
            $"间隔秒 缺省 0 必须兜底成 5，实际 {u.移动间隔秒}/{u.攻击间隔秒}/{u.技能间隔秒}");
        断言(u.已学技能.Contains("扑咬"), "行动表里的技能应当进 已学技能（AI 才抽得到）");
        断言(!u.已学技能.Contains("普攻"), "「普攻」不该当技能塞进 已学技能");
        var 助 = 战斗单位.从助战生成(敌);
        断言(助.是否我方, "助战必须归我方（敌人 AI 才会打它）");
        断言(助.生命 == 敌.生命 && 助.攻击距离 == 1, "助战其余数值应当与敌人同源");
        var 快 = 战斗单位.从敌人生成(敌人(移动秒: 2.5f, 攻击秒: 3f, 技能秒: 4f));
        断言(Math.Abs(快.移动间隔秒 - 2.5f) < 0.001f && Math.Abs(快.攻击间隔秒 - 3f) < 0.001f && Math.Abs(快.技能间隔秒 - 4f) < 0.001f,
            "写了间隔秒就该照用（没写才兜底 5）");
    }
}

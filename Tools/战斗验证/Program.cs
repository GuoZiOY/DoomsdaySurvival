    private static void 精力()
    {
        小节("[1] 精力：够了才扣、不超上限");
        var u = 单位(精力: 10);
        断言(u.消耗精力(3), "精力 10 扣 3 应当成功");
        断言(u.精力 == 7, $"扣完应当是 7，实际 {u.精力}");
        断言(!u.消耗精力(99), "不够时应当返回 false");
        断言(u.精力 == 7, $"失败**不许**扣掉任何精力（「精力被吞」那类 bug），实际 {u.精力}");
        u.恢复精力(100);
        断言(u.精力 == u.最大精力, $"恢复不许超上限，实际 {u.精力}/{u.最大精力}");
    }

    private static void 秒制冷却()
    {
        小节("[2] 技能冷却：现实秒递减、到 0 移除、0 不写入");
        var u = 单位();
        断言(u.冷却剩余("重斩") == 0f, "没放过的技能冷却应当是 0");
        u.开始冷却("重斩", 5f);
        断言(Math.Abs(u.冷却剩余("重斩") - 5f) < 0.001f, "开始冷却 5 秒后剩余应当是 5");
        u.推进冷却(2f);
        断言(Math.Abs(u.冷却剩余("重斩") - 3f) < 0.001f, $"推进 2 秒后应当是 3，实际 {u.冷却剩余("重斩")}");
        u.推进冷却(3f);
        断言(u.冷却剩余("重斩") == 0f, "推进到 0 应当被移除（剩余 0）");
        断言(!u.技能冷却.ContainsKey("重斩"), "到 0 之后字典里不该再留着这个 key（否则每帧白遍历）");
        u.开始冷却("瞬发", 0f);
        断言(!u.技能冷却.ContainsKey("瞬发"), "冷却 0 的技能不该写进字典");
        u.推进冷却(1f);   // 空表时不应崩
        断言(true, "空冷却表推进不崩");
    }

    private static void 秒制眩晕()
    {
        小节("[3] 眩晕：秒制、刷新取更长、0/负数不生效、期间无法行动");
        var u = 单位();
        断言(!u.无法行动, "没眩晕时应当能行动");
        u.施加眩晕(2f);
        断言(Math.Abs(u.眩晕剩余秒 - 2f) < 0.001f, $"眩晕 2 秒应当记 2，实际 {u.眩晕剩余秒}");
        断言(u.无法行动, "眩晕期间 无法行动 必须为真");
        u.施加眩晕(1f);
        断言(Math.Abs(u.眩晕剩余秒 - 2f) < 0.001f, $"更短的眩晕不许缩短（刷新取更长），实际 {u.眩晕剩余秒}");
        u.施加眩晕(3f);
        断言(Math.Abs(u.眩晕剩余秒 - 3f) < 0.001f, $"更长的眩晕应当刷新，实际 {u.眩晕剩余秒}");
        u.眩晕剩余秒 = 0f;
        u.施加眩晕(0f); u.施加眩晕(-5f);
        断言(u.眩晕剩余秒 == 0f && !u.无法行动, "0 / 负数眩晕不许生效");
    }

    private static void Buff叠层与到期()
    {
        小节("[4] Buff：同标识叠层（封顶）+ 刷新计时；回合结束递减/移除；无敌回合");
        var u = 单位();
        var 攻 = Buff("增益", 属性: "攻击", 数值: 20, 持续: 2, 最大层: 3, 标识: "猛攻");
        for (int i = 0; i < 5; i++) u.添加Buff(攻);
        断言(u.Buffs.Count == 1, $"同标识只该有一份，实际 {u.Buffs.Count}");
        断言(u.Buffs[0].层数 == 3, $"层数应当封顶在 3，实际 {u.Buffs[0].层数}");
        断言(u.Buffs[0].剩余回合 == 2, $"每次添加都该刷新计时，实际 {u.Buffs[0].剩余回合}");
        u.回合结束();
        断言(u.Buffs.Count == 1 && u.Buffs[0].剩余回合 == 1, "过一轮后还应当在（剩 1 回合）");
        u.回合结束();
        断言(u.Buffs.Count == 0, "计时到 0 应当被移除");
        u.无敌回合 = 2;
        断言(u.无敌, "无敌回合 > 0 时 无敌 为真");
        u.回合结束(); u.回合结束();
        断言(!u.无敌 && u.无敌回合 == 0, "无敌回合应当递减到 0（且不为负）");
        u.移除Buff("不存在");
        断言(true, "移除不存在的 Buff 不崩");
    }

    private static void 属性修正与封顶()
    {
        小节("[5] 属性修正：增益加、减益减、当前值按百分比修正且下限 0；暴击/闪避封顶 0.8");

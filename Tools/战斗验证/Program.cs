        u.添加Buff(Buff("异常", 数值: 3, 持续: 9, 最大层: 2, 结算时机: "开始", 标识: "毒"));
        u.添加Buff(Buff("异常", 数值: 5, 持续: 9, 结算时机: "结束", 标识: "流血"));

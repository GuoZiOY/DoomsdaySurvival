    // ============ 伤害公式（Domain/战斗/伤害计算.cs，v51 刀26 提纯） ============

    private static 伤害输入 入(伤害类型 类型 = 伤害类型.物理, int 近战 = 10, int 远程 = 10,
        int 倍率 = 100, int 附加 = 0, float 暴击率 = 0f, float 掷暴击 = 0.9f,
        float 防御减伤 = 0f, int 抗性 = 0, bool 姿态 = false)
        => new 伤害输入
        {
            类型 = 类型, 攻击者近战 = 近战, 攻击者远程 = 远程, 倍率100 = 倍率, 附加 = 附加,
            攻击者暴击率 = 暴击率, 掷暴击 = 掷暴击,
            目标防御减伤 = 防御减伤, 目标抗性百分比 = 抗性, 目标防御姿态 = 姿态,
        };

    private static void 伤害公式()
    {
        小节("[9] 伤害公式（唯一权威）：命中判定 / 真实伤害 / 暴击 / 减伤链 / 下限 / 取整口径 / 确定性");

        // —— 命中判定：`掷点 >= 命中率 - 闪避率` 就算被闪避（注意是 >=，相等也闪避）——
        断言(伤害计算.是否命中(0.50f, 0.95f, 0.00f), "掷 0.50 < 命中 0.95 → 应当命中");
        断言(!伤害计算.是否命中(0.95f, 0.95f, 0.00f), "掷点 == 命中率 的边界必须算**被闪避**（原式是 >=）");
        断言(伤害计算.是否命中(0.84f, 0.95f, 0.10f), "0.84 vs 0.85 → 应当命中");
        断言(!伤害计算.是否命中(0.85f, 0.95f, 0.10f), "0.85 vs 0.85（命中-闪避）→ 边界应当算被闪避");
        断言(!伤害计算.是否命中(0.10f, 0.95f, 0.90f), "闪避率很高时低掷点也该被闪避");

        // —— 真实伤害：无视攻防/暴击/抗性，只吃"下限 1"——
        var 真 = 伤害计算.计算(入(类型: 伤害类型.真实, 倍率: 30, 附加: 5, 防御减伤: 0.5f, 抗性: 50, 姿态: true, 暴击率: 1f, 掷暴击: 0f));
        断言(真.是真实伤害, "真实伤害分支必须被认出来（文案/耐久都与普通伤害不同）");
        断言(真.数值 == 35, $"真实伤害 = 倍率+附加 = 35，不受任何减伤影响，实际 {真.数值}");
        断言(!真.暴击, "真实伤害不参与暴击");
        断言(伤害计算.计算(入(类型: 伤害类型.真实, 倍率: 0)).数值 == 1, "真实伤害也要夹下限 1");

        // —— 暴击：×1.5（同样走银行家舍入）——
        断言(伤害计算.计算(入(暴击率: 0.5f, 掷暴击: 0.0f)).数值 == 15, "10 × 1.5 = 15（掷点在暴击率内）");
        断言(伤害计算.计算(入(暴击率: 0.5f, 掷暴击: 0.9f)).数值 == 10, "掷点在暴击率之外 → 不暴击");

        // —— 取整口径：银行家舍入（与 Mathf.RoundToInt 一致）——
        断言(伤害计算.计算(入(近战: 5, 倍率: 50)).数值 == 2,
            $"5×50% = 2.5 必须按银行家舍入取 2（若取 3 说明有人换成了 +0.5 截断）");
        断言(伤害计算.计算(入(近战: 1, 暴击率: 1f, 掷暴击: 0f)).数值 == 2,
            $"1 × 1.5 = 1.5 → 银行家舍入取 2（这里 2 是偶数）");

        // —— 减伤链：防御% → 抗性% → 防御姿态，**每一步独立取整**——
        断言(伤害计算.计算(入(近战: 100, 防御减伤: 0.5f)).数值 == 50, "物防 50% → 100 减半成 50");
        断言(伤害计算.计算(入(近战: 100, 防御减伤: 0.5f, 抗性: 50)).数值 == 25, "再叠抗性 50% → 25");
        断言(伤害计算.计算(入(近战: 100, 防御减伤: 0.5f, 抗性: 50, 姿态: true)).数值 == 12,
            $"再叠防御姿态半减：25×0.5 = 12.5 → 银行家舍入取 12，实际 {伤害计算.计算(入(近战: 100, 防御减伤: 0.5f, 抗性: 50, 姿态: true)).数值}");

        // —— 下限 1：怎么叠都不许出现 0 伤害（否则"打了没反应"）——
        断言(伤害计算.计算(入(近战: 1, 防御减伤: 0.5f)).数值 == 1, "1 攻被减半 → 至少 1");
        断言(伤害计算.计算(入(近战: 1, 防御减伤: 0.5f, 抗性: 50, 姿态: true)).数值 == 1, "三重减伤叠满也至少 1");

        // —— 远程/近战取的是对应那一栏 ——
        断言(伤害计算.计算(入(类型: 伤害类型.远程, 近战: 1, 远程: 50)).数值 == 50, "远程伤害必须取 当前远程");
        断言(伤害计算.计算(入(类型: 伤害类型.物理, 近战: 1, 远程: 50)).数值 == 1, "物理伤害必须取 当前近战");

        // —— 确定性：同一输入跑 100 次结果逐位相同（证明纯函数里没有藏随机/状态）——
        var 样 = 入(近战: 37, 倍率: 133, 附加: 7, 暴击率: 0.3f, 掷暴击: 0.29f, 防御减伤: 0.21f, 抗性: 17, 姿态: true);
        int 首 = 伤害计算.计算(样).数值;
        bool 全同 = true;
        for (int i = 0; i < 100; i++) if (伤害计算.计算(样).数值 != 首) 全同 = false;
        断言(全同, $"同一输入 100 次必须逐位相同（否则离线复现无从谈起），首次 {首}");
    }

    // ============ 固定步长累加器（Domain/战斗/固定步长.cs，v51 刀27） ============

    private static void 固定步长累加()
    {
        小节("[10] 固定步长：切分等价 / 余量不丢且恒小于步长 / 卡帧上限 / 0 与负数");
        float 步 = 固定步长.步长;
        断言(步 > 0f && 步 < 0.1f, $"步长应当是 1/30 秒那个量级，实际 {步}");
        断言(固定步长.单帧上限 > 0, "单帧上限必须 > 0（否则永远推不动）");

        // ① 切分等价：一次给 0.1 秒 vs 十次给 0.01 秒 —— 步数**允许差 1**
        //    （调用方把 0.01f 累加十次凑不出精确 0.1f：实测 3 步 vs 2 步。这是浮点累加误差，
        //     不是实现错；真正的保证是"余量带过帧、误差不累积"，见 ② 与 ⑥。）
        float 余甲 = 0f; int 步甲 = 固定步长.取步数(ref 余甲, 0.1f);
        float 余乙 = 0f; int 步乙 = 0;
        for (int i = 0; i < 10; i++) 步乙 += 固定步长.取步数(ref 余乙, 0.01f);
        断言(Math.Abs(步甲 - 步乙) <= 1, $"切分方式最多只能造成 1 步之差（一次 0.1s → {步甲} 步；十次 0.01s → {步乙} 步）");
        断言(步甲 == 3, $"0.1 秒 = 3 个 1/30 步，实际 {步甲}");
        断言(余甲 < 步 && 余乙 < 步, $"跑完余量必须 < 步长（{余甲} / {余乙}）");

        // ② 不丢时间：把 1 秒按 60 帧喂进去，累计步数应当是 30（浮点容差 ±1）
        float 余丙 = 0f; int 总 = 0;
        for (int i = 0; i < 60; i++) 总 += 固定步长.取步数(ref 余丙, 1f / 60f);
        断言(Math.Abs(总 - 30) <= 1, $"1 秒应当折成 ≈30 步，实际 {总}");
        断言(余丙 < 步, $"喂完余量仍须 < 步长，实际 {余丙}");

        // ③ 小增量不丢：40 × 0.001 秒 = 0.04 秒 > 一步
        float 余丁 = 0f; int 步丁 = 0;
        for (int i = 0; i < 40; i++) 步丁 += 固定步长.取步数(ref 余丁, 0.001f);
        断言(步丁 >= 1, $"小增量累积到超过一步时必须推进（实际 {步丁} 步）");

        // ④ 卡帧上限：一次给 10 秒也不许跑几百步，且**余量清零**（丢掉补不上的部分，防雪崩）
        float 余戊 = 0f;
        int 步戊 = 固定步长.取步数(ref 余戊, 10f);
        断言(步戊 == 固定步长.单帧上限, $"卡帧时必须夹在单帧上限 {固定步长.单帧上限} 步，实际 {步戊}");
        断言(余戊 == 0f, $"卡帧丢时间时余量必须清零（否则每帧都会再撞上限），实际 {余戊}");
        int 步戊2 = 固定步长.取步数(ref 余戊, 0f);
        断言(步戊2 == 0, $"卡帧之后紧接着的一帧不该还有欠账，实际 {步戊2} 步");

        // ⑤ 0 与负数：不许推进、不许把余量搞成负数
        float 余己 = 0.5f * 步;
        断言(固定步长.取步数(ref 余己, 0f) == 0, "0 秒不推进");
        断言(固定步长.取步数(ref 余己, -5f) == 0, "负数秒不推进");
        断言(余己 >= 0f && 余己 < 步, $"余量不许变负、也要 < 步长，实际 {余己}");

        // ⑥ 不变式：连续喂各种 dt，每一次之后余量都必须 < 步长
        float 余庚 = 0f; bool 不变式 = true;
        float[] 序列 = { 0.016f, 0.016f, 0.033f, 0.001f, 0.2f, 0.016f, 0.5f, 0.004f };
        for (int i = 0; i < 200; i++)
        {
            固定步长.取步数(ref 余庚, 序列[i % 序列.Length]);
            if (余庚 >= 步 || 余庚 < 0f) 不变式 = false;
        }
        断言(不变式, "连续喂 200 次不同 dt 之后，余量必须始终落在 [0, 步长)");
    }

    // ============ 敌人 AI 决策（Domain/战斗/敌人AI.cs，v51 刀28；审计 D15） ============

    private static 敌人数据 带行动表(params (string 行动, int 权重)[] 项)
        => new 敌人数据
        {
            标识 = "AI测试", 名称 = "AI测试", 生命 = 10, 攻击 = 1, 防御 = 0, 速度 = 5,
            行动表 = System.Array.ConvertAll(项, t => new AI行动项 { 行动 = t.行动, 权重 = t.权重 }),
        };

    private static 技能数据 技能(目标类型 目标) => new 技能数据 { 标识 = "测试技能", 名称 = "测试技能", 目标 = 目标.ToString() };

    private static void 敌人AI决策()
    {
        小节("[11] 敌人 AI：抽招（权重只采样一次）/ 选目标（残血·随机）/ 选友方 / 越界与空表兜底");

        // —— 权重总和：空表 0；权重 < 1 一律按 1 算（与拆分前 Mathf.Max(1,权重) 同口径）——
        断言(敌人AI.权重总和(带行动表()) == 0, "没有行动项时权重总和应当是 0");
        断言(敌人AI.权重总和(带行动表(("扑咬", 7), ("普攻", 3))) == 10, "7+3 = 10");
        断言(敌人AI.权重总和(带行动表(("a", 0), ("b", -5))) == 2,
            $"0 / 负数权重都必须按 1 算（否则这些行动永远抽不到、甚至除以 0），实际 {敌人AI.权重总和(带行动表(("a", 0), ("b", -5)))}");
        断言(敌人AI.权重总和(null) == 0, "敌数据为 null 时不崩、返回 0");

        // —— 抽招：掷点落在各段的边界要对得上；越界/空表 → 普攻 ——
        var 两招 = 带行动表(("扑咬", 7), ("普攻", 3));
        断言(敌人AI.抽行动(两招, 0) == "扑咬", "掷 0 落在第一段");
        断言(敌人AI.抽行动(两招, 6) == "扑咬", "掷 6 仍在第一段（0~6 共 7 个点）");
        断言(敌人AI.抽行动(两招, 7) == "普攻", "掷 7 进第二段");
        断言(敌人AI.抽行动(两招, 9) == "普攻", "掷 9 是最后一个点");
        断言(敌人AI.抽行动(两招, 10) == 敌人AI.普攻, "掷点越界 → 兜底普攻（不许返回空）");
        断言(敌人AI.抽行动(带行动表(), 0) == 敌人AI.普攻, "空行动表 → 普攻");
        断言(敌人AI.抽行动(null, 0) == 敌人AI.普攻, "敌数据为 null → 普攻");

        // —— 权重真的生效：把整个掷点空间数一遍（这也是"只采样一次"的证据）——
        int 扑咬数 = 0, 普攻数 = 0;
        for (int 掷 = 0; 掷 < 敌人AI.权重总和(两招); 掷++)
        {
            if (敌人AI.抽行动(两招, 掷) == "扑咬") 扑咬数++; else 普攻数++;
        }
        断言(扑咬数 == 7 && 普攻数 == 3, $"权重 7:3 必须真的抽成 7:3（实际 {扑咬数}:{普攻数}）");

        // —— 选目标 ——
        var 甲 = 单位(生命: 30); var 乙 = 单位(生命: 10); var 丙 = 单位(生命: 20);
        var 三人 = new List<战斗单位> { 甲, 乙, 丙 };
        var 残血敌 = new 敌人数据 { 标识 = "x", 目标策略 = "残血" };
        断言(敌人AI.选目标(残血敌, 三人, 0) == 乙, "「残血」策略必须打血最少的");
        断言(三人[0] == 甲 && 三人[1] == 乙 && 三人[2] == 丙, "选目标**不许改动**传入的列表顺序（内部要先复制）");
        断言(敌人AI.选目标(带行动表(), 三人, 0) == 甲, "非残血策略：掷 0 → 第 0 个");
        断言(敌人AI.选目标(带行动表(), 三人, 2) == 丙, "非残血策略：掷 2 → 第 2 个");
        断言(敌人AI.选目标(带行动表(), 三人, 99) == 丙, "掷点越界要夹住，不许越界访问");
        断言(敌人AI.选目标(带行动表(), new List<战斗单位>(), 0) == null, "没有存活目标 → null");
        断言(敌人AI.选目标(带行动表(), null, 0) == null, "列表为 null → null（不崩）");

        // —— 选友方（治疗/增益）——
        var 施法 = 单位(生命: 50);
        var 队友甲 = 单位(生命: 40); var 队友乙 = 单位(生命: 5);
        var 队友 = new List<战斗单位> { 队友甲, 队友乙 };
        断言(敌人AI.选友方(施法, 技能(目标类型.自己), 队友, null) == 施法, "目标=自己 → 选施法者本人");
        断言(敌人AI.选友方(施法, 技能(目标类型.我方单体), 队友, null) == 队友乙, "目标=我方单体 → 选最残血的队友");
        断言(敌人AI.选友方(施法, 技能(目标类型.我方全体), 队友, null) == 队友甲, "目标=我方全体 → 取第一个");
        断言(敌人AI.选友方(施法, 技能(目标类型.我方单体), new List<战斗单位>(), 施法) == 施法, "没有队友 → 用调用方给的兜底");
    }

    // ===== 随机源（v51 刀33 / 档2 #26）：战斗唯一的掷点入口 =====
    // 这里钉三件事：① 口径与 UnityEngine 对齐（值∈[0,1)、范围左闭右开、端点退化）；
    //   ② **同种子可复现**（这是"复现 bug / 批量验胜率"的全部前提）；
    //   ③ 不同种子确实不同（否则"能播种"是假的 —— 有人把种子忽略了也看不出来）。
    private static void 随机源()
    {
        小节("[12] 随机源：口径 / 可复现 / 不同种子不同序列");

        // ① 同种子两遍：逐掷完全一致（整数与浮点都比）
        var 甲 = new 随机源(12345);
        var 乙 = new 随机源(12345);
        bool 一致 = true;
        for (int i = 0; i < 200; i++)
        {
            if (Math.Abs(甲.值() - 乙.值()) > 1e-7f) { 一致 = false; break; }
            if (甲.范围(0, 100) != 乙.范围(0, 100)) { 一致 = false; break; }
        }
        断言(一致, "同种子两遍必须逐掷一致（否则「复现」是空话）");

        // ② 不同种子：200 次里至少有一次不同（防"种子被忽略/写死"）
        var 丙 = new 随机源(12345);
        var 丁 = new 随机源(54321);
        bool 有不同 = false;
        for (int i = 0; i < 200 && !有不同; i++) if (Math.Abs(丙.值() - 丁.值()) > 1e-7f) 有不同 = true;
        断言(有不同, "不同种子必须给出不同序列（防「种子写死/被忽略」）");

        // ③ 口径：值 ∈ [0,1)；范围(a,b) ∈ [a,b) 且**取得到 a、取不到 b**
        var 流 = new 随机源(7);
        bool 值在范围内 = true;
        for (int i = 0; i < 2000; i++) { float v = 流.值(); if (v < 0f || v >= 1f) { 值在范围内 = false; break; } }
        断言(值在范围内, "值() 必须落在 [0,1)（与 Random.value 同口径）");

        var 范 = new 随机源(7);
        bool 范围在界内 = true; bool 见过下界 = false; bool 见过上界 = false;
        for (int i = 0; i < 4000; i++)
        {
            int n = 范.范围(3, 8);
            if (n < 3 || n >= 8) { 范围在界内 = false; break; }
            if (n == 3) 见过下界 = true;
            if (n == 7) 见过上界 = true;
        }
        断言(范围在界内, "范围(3,8) 必须落在 [3,8)（左闭右开，与 Random.Range(int,int) 一致）");
        断言(见过下界 && 见过上界, "范围(3,8) 应当同时取到 3 与 7（两端都通，不是把某端吃掉）");

        // ④ 端点退化：b <= a 时返回 a（Unity 同口径），不许抛异常
        断言(new 随机源(1).范围(5, 5) == 5, "范围(5,5) 退化 → 5");
        断言(new 随机源(1).范围(5, 3) == 5, "范围(5,3)（反的）退化 → 5，不许抛异常");
        断言(new 随机源(1).范围含(4, 4) == 4, "范围含(4,4) → 4");

        // ⑤ 范围含 = 双闭：能取到上界
        var 含 = new 随机源(9);
        bool 见过上 = false;
        for (int i = 0; i < 4000 && !见过上; i++) if (含.范围含(0, 2) == 2) 见过上 = true;
        断言(见过上, "范围含(0,2) 必须能取到 2（双闭，别用成范围()）");

        // ⑥ 分布别太歪（粗筛：均匀整数 6 档，2000 次每档都该出现；给宽裕的宽容度）
        var 均 = new 随机源(20260913);
        var 计数 = new int[6];
        for (int i = 0; i < 2000; i++) 计数[均.范围(0, 6)]++;
        bool 都出现 = true;
        foreach (var c in 计数) if (c == 0) 都出现 = false;
        断言(都出现, "均匀整数 6 档 2000 次里每档至少出现一次（分布严重偏斜说明实现错了）");

        // ⑦ 负数种子不崩、仍然可复现（派生出来的种子可能是负数 —— int 溢出很常见）
        var 负甲 = new 随机源(-12345);
        var 负乙 = new 随机源(-12345);
        bool 负一致 = true;
        for (int i = 0; i < 50; i++) if (负甲.范围(0, 1000) != 负乙.范围(0, 1000)) { 负一致 = false; break; }
        断言(负一致, "负数种子同样要可复现（确定性随机.派生 可能给出负种子）");
    }

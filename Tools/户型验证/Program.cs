using System;
using System.Collections.Generic;
using System.Linq;

class Program
{
    static string 类型符(安全屋户型.房间类型 t) => t switch
    {
        安全屋户型.房间类型.门 => "门",
        安全屋户型.房间类型.大厅 => "厅",
        安全屋户型.房间类型.主屋 => "主",
        安全屋户型.房间类型.厨房 => "厨",
        安全屋户型.房间类型.洗浴间 => "浴",
        安全屋户型.房间类型.阳台 => "阳",
        _ => "二",
    };

    static void Main()
    {
        int 总数 = 2000, 走兜底 = 0;
        int 贴边违例 = 0, 重叠 = 0, 空洞 = 0, 尺寸违例 = 0;
        long 利用率和 = 0;
        int 低于60 = 0, 低于65 = 0, 低于70 = 0;
        var 布局签名 = new HashSet<string>();
        var 样例 = new List<(int 种子, 安全屋户型 户型)>();
        for (int 种子 = 1; 种子 <= 总数; 种子++)
        {
            var 户型 = 安全屋户型.生成(种子);
            bool 兜底 = 户型.房间列数 == 10 && 户型.房间行数 == 10 && 固定形状(户型);
            if (兜底) 走兜底++;
            利用率和 += 户型.面积利用率();
            int 利 = 户型.面积利用率();
            if (利 < 60) 低于60++;
            if (利 < 65) 低于65++;
            if (利 < 70) 低于70++;
            // 检查 门/阳台 长边 贴 网格 边界（修正 语义：2×1 长边 贴 上/下；1×2 贴 左/右）
            foreach (var 块 in 户型.形状块)
            {
                int i = 户型.形状块.IndexOf(块);
                var 类型 = 户型.房间类型表[i];
                bool 贴 = 类型 == 安全屋户型.房间类型.门
                    ? ((块.宽 == 2 && (块.行 == 0 || 块.行 + 块.高 == 户型.房间行数)) || (块.高 == 2 && (块.列 == 0 || 块.列 + 块.宽 == 户型.房间列数)))
                    : 类型 == 安全屋户型.房间类型.阳台
                        ? (块.宽 > 块.高 ? (块.行 == 0 || 块.行 + 块.高 == 户型.房间行数) : (块.列 == 0 || 块.列 + 块.宽 == 户型.房间列数))
                        : true;
                if (!贴) { 贴边违例++; Console.WriteLine($"[贴边违例] 种子{种子} {类型} {块.列},{块.行} {块.宽}x{块.高} 网格{户型.房间列数}x{户型.房间行数}"); }
                // 门 尺寸 恒 2×1/1×2；阳台 长条（宽=1 或 高=1）
                if (类型 == 安全屋户型.房间类型.门 && !((块.宽 == 2 && 块.高 == 1) || (块.宽 == 1 && 块.高 == 2)))
                { 尺寸违例++; Console.WriteLine($"[尺寸违例-门] 种子{种子} {块.宽}x{块.高}"); }
                if (类型 == 安全屋户型.房间类型.阳台 && !(块.宽 == 1 || 块.高 == 1))
                { 尺寸违例++; Console.WriteLine($"[尺寸违例-阳台] 种子{种子} {块.宽}x{块.高}"); }
            }
            // 检查 重叠：每 块 矩形 内 是否 全 属于 自身 块号
            for (int i = 0; i < 户型.形状块.Count; i++)
            {
                var 块 = 户型.形状块[i];
                for (int c = 块.列; c < 块.列 + 块.宽; c++)
                    for (int r = 块.行; r < 块.行 + 块.高; r++)
                        if (户型.格所属块[c, r] != i + 1) { 重叠++; Console.WriteLine($"[重叠] 种子{种子} 块{i+1} 格({c},{r}) 实际={户型.格所属块[c,r]}"); }
            }
            if (!无内部空洞(户型)) 空洞++;
            var sb = new System.Text.StringBuilder();
            for (int r = 0; r < 户型.房间行数; r++)
                for (int c = 0; c < 户型.房间列数; c++)
                    sb.Append(户型.格所属块[c, r] == -2 ? '.' : (char)('A' + Math.Max(0, 户型.格所属块[c, r] - 1)));
            布局签名.Add(sb.ToString());
            if (样例.Count < 8 && !兜底) 样例.Add((种子, 户型));
        }
        Console.WriteLine("=== 块 尺寸 诊断（非兜底 前 6 个） ===");
        foreach (var (种子, 户型) in 样例.Take(6))
        {
            int 墙数 = 0;
            for (int c = 0; c < 户型.房间列数; c++)
                for (int r = 0; r < 户型.房间行数; r++)
                    if (户型.格所属块[c, r] == -2) 墙数++;
            Console.WriteLine($"种子{种子} 网格{户型.房间列数}x{户型.房间行数} 利用{户型.面积利用率()}% 墙{墙数}格");
            foreach (var 块 in 户型.形状块)
            {
                int i = 户型.形状块.IndexOf(块);
                Console.WriteLine($"  {类型符(户型.房间类型表[i])} {块.列},{块.行} {块.宽}x{块.高}");
            }
        }
        Console.WriteLine($"总数 {总数}，走兜底 {走兜底}（{100 * 走兜底 / 总数}%），贴边违例 {贴边违例}，重叠格 {重叠}，内部空洞户型 {空洞}，尺寸违例 {尺寸违例}");
        Console.WriteLine($"平均利用率 {利用率和 / 总数}%；<60%: {低于60}，<65%: {低于65}，<70%: {低于70}");
        Console.WriteLine($"去重布局数 {布局签名.Count}");
        Console.WriteLine("=== 8 个 非兜底 样例 ===");
        foreach (var (种子, 户型) in 样例)
        {
            Console.WriteLine($"--- 种子 {种子} {户型.房间列数}x{户型.房间行数} 利用{户型.面积利用率()}% ---");
            for (int r = 0; r < 户型.房间行数; r++)
            {
                var line = new System.Text.StringBuilder();
                for (int c = 0; c < 户型.房间列数; c++)
                {
                    int b = 户型.格所属块[c, r];
                    line.Append(b == -2 ? "  " : b == -1 ? "·" : 类型符(户型.房间类型表[b - 1]) + " ");
                }
                Console.WriteLine(line.ToString());
            }
        }
    }

    static bool 固定形状(安全屋户型 户型) => 户型.房间列数 == 10 && 户型.房间行数 == 10;

    // 内部 空洞：空白 格 被 房间 完全 包围（4 邻 全 房间 且 不 贴 网格 边界）
    static bool 无内部空洞(安全屋户型 户型)
    {
        var 四方向 = new[] { (0, 1), (0, -1), (1, 0), (-1, 0) };
        for (int 列 = 0; 列 < 户型.房间列数; 列++)
            for (int 行 = 0; 行 < 户型.房间行数; 行++)
            {
                if (户型.格所属块[列, 行] >= 0) continue;
                if (列 == 0 || 行 == 0 || 列 == 户型.房间列数 - 1 || 行 == 户型.房间行数 - 1) continue;
                bool 全房间 = true;
                foreach (var (dx, dy) in 四方向)
                {
                    int c = 列 + dx, r = 行 + dy;
                    if (c < 0 || r < 0 || c >= 户型.房间列数 || r >= 户型.房间行数 || 户型.格所属块[c, r] < 0) { 全房间 = false; break; }
                }
                if (全房间) return false;
            }
        return true;
    }
}

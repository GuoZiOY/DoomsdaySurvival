    private static T 读<T>(string 路径, JsonSerializerOptions 选项) where T : class
    {
        if (!File.Exists(路径)) { Console.WriteLine($"找不到 {路径}"); return null; }
        try { return JsonSerializer.Deserialize<T>(File.ReadAllText(路径, Encoding.UTF8), 选项); }
        catch (Exception e) { Console.WriteLine($"{Path.GetFileName(路径)} 解析失败：{e.Message}"); return null; }
    }

    private static string 找仓库根()
    {
        var 目录 = new DirectoryInfo(AppContext.BaseDirectory);
        while (目录 != null)
        {
            if (Directory.Exists(Path.Combine(目录.FullName, "Assets", "Resources", "Data"))) return 目录.FullName;
            目录 = 目录.Parent;
        }
        return null;
    }

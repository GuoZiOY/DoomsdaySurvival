using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.Json;

// ============================================================
// 大世界敌人验证（刀61）：离线跑「大世界生成器 + 大世界敌人AI」——
// 逐颗种子模拟"玩家在废城里乱走 + 时不时开一枪"，每走一步断言不变量。
// 用法：dotnet run --project Tools/大世界敌人验证 -c Release -- 20 示例
//
// 为什么要有它：会移动的占格敌人是**活的墙**，而"两只敌人永远不叠、永远不堵门口、永远不把玩家围死"
//   这三件事在游戏里**看不出来**（真出问题时表现是"偶尔卡一下"或"偶尔出不去"）。
//   它们在数学上也不再由生成期那条论证兜着 —— 那条论证的前提（占格物从不移动）被这一刀打掉了。
//
// 断言（破了就是 bug）：
//   ① 确定性：同世界 + 同种子 + 同步数 → 两次模拟的**全部敌人位置与 AI 态指纹逐字节一致**；
//   ② 确定性（噪音）：同一串噪音事件 → 状态迁移逐字节一致（含在其中）；
//   ③ 连通硬保证：**任意一步之后**，玩家都走得到营地门口格（敌人挡路 = true 的真校验）；
//   ④ 门口保护：敌人**永不**停在任何门口格（营地 / 区域 / 临时建筑）的紧邻八格内；
//   ⑤ 不重叠：任意时刻**没有两只敌人占同一格**；
//   ⑥ 不越界：敌人不超出 巡逻半径（静默/巡逻态）/ 追击上限（追踪态），各留 1 格余量（见 §余量说明）；
//   ⑦ 不入墙：敌人不站在任何占格实体上（墙 / 容器 / 障碍 / 建筑 / 区域）；
//   ⑧ 流场自身合法：`方向[]` 恒指向"距 −1"的邻格（**结构上不成环**——成环 = 敌人原地转圈，
//      而从游戏里根本看不出是路径算错了还是它只是在巡逻）；且同输入的场指纹逐字节一致。
//   ⑨ 数量守恒：AI 不会让敌人凭空消失（只有战斗胜利才移除敌人，那是服务层的事）。
// ============================================================
public static class Program
{
    public static int Main(string[] args)
    {
        Console.OutputEncoding = Encoding.UTF8;
        int 种子数 = 20, 步数 = 60;
        bool 打示例 = false, 打轨迹 = false;
        var 位置参数 = new List<int>();
        foreach (var a in args)
        {
            if (a == "示例") { 打示例 = true; continue; }
            if (a == "轨迹") { 打轨迹 = true; continue; }
            if (int.TryParse(a, out int n) && n > 0) 位置参数.Add(n);
        }
        if (位置参数.Count > 0) 种子数 = 位置参数[0];
        if (位置参数.Count > 1) 步数 = 位置参数[1];

        var 根 = 找仓库根();
        if (根 == null) { Console.WriteLine("找不到仓库根"); return 2; }
        var 选项 = new JsonSerializerOptions { IncludeFields = true, AllowTrailingCommas = true, ReadCommentHandling = JsonCommentHandling.Skip };

        var 世界根 = 读<世界根>(Path.Combine(根, "Assets/Resources/Data/世界.json"), 选项);
        var 区根 = 读<区域模板根>(Path.Combine(根, "Assets/Resources/Data/区域模板.json"), 选项);
        var 房根 = 读<房间模板根>(Path.Combine(根, "Assets/Resources/Data/房间模板.json"), 选项);
        var 建根 = 读<建筑模板根>(Path.Combine(根, "Assets/Resources/Data/建筑模板.json"), 选项);
        var 敌根 = 读<敌人根>(Path.Combine(根, "Assets/Resources/Data/enemies.json"), 选项);
        if (世界根?.世界 == null || 世界根.世界.Length == 0) { Console.WriteLine("世界.json 没读到世界"); return 2; }
        if (敌根?.敌人 == null || 敌根.敌人.Length == 0) { Console.WriteLine("enemies.json 没读到敌人"); return 2; }

        var 名表 = new Dictionary<string, string>();
        if (房根?.房间 != null)
            foreach (var 房 in 房根.房间) if (房 != null) 名表[房.标识] = string.IsNullOrEmpty(房.名称) ? 房.标识 : 房.名称;
        if (建根?.建筑 != null)
            foreach (var 建 in 建根.建筑) if (建 != null) 名表[建.标识] = string.IsNullOrEmpty(建.名称) ? 建.标识 : 建.名称;
        // 区域显示名来自 区域模板（游戏里 大世界探索服务.取名 就是这条链）→ 这里也照它取名，读的是同一份数据
        if (区根?.区域 != null)
            foreach (var 区 in 区根.区域) if (区 != null) 名表[区.标识] = string.IsNullOrEmpty(区.名称) ? 区.标识 : 区.名称;
        string 取名(string 标识) => 名表.TryGetValue(标识 ?? "", out var v) ? v : (标识 ?? "");

        var 敌表 = new Dictionary<string, 敌人数据>();
        foreach (var e in 敌根.敌人) if (e != null && !string.IsNullOrEmpty(e.标识)) 敌表[e.标识] = e;

        Console.WriteLine($"=== 大世界敌人验证：{种子数} 颗种子 × {世界根.世界.Length} 个世界 × {步数} 步 ===");
        Console.WriteLine($"敌人定义 {敌表.Count} / 房间模板 {(房根?.房间?.Length ?? 0)} / 建筑模板 {(建根?.建筑?.Length ?? 0)}");
        Console.WriteLine();

        // ★ 谓词独立自检**必须先跑**（门口保护 文件头记的盲区）：
        //   `能落子 / 落子 / 流场.可走 / 碰世界门口 / 玩家能回营地` 是**服务层与验证器共用**的谓词，
        //   把谓词本身改坏（比如漏掉门口保护）会**同时**让两边变宽 → 下面的模拟会全绿，什么都没测出来。
        //   所以这些谓词必须有一张**不依赖模拟的独立真值表**。自检不过就不必跑模拟了。
        var 自检坏 = 自检();
        if (自检坏.Count > 0)
        {
            Console.WriteLine($"❌ 谓词自检失败 {自检坏.Count} 条（模拟不再进行 —— 谓词坏了，模拟跑绿也没有意义）：");
            foreach (var v in 自检坏) Console.WriteLine("  · " + v);
            return 1;
        }
        Console.WriteLine("✅ 谓词自检通过（能落子 / 碰世界门口 / 流场.可走 / 流场吸附 / 玩家能回营地 / AI 三态真值表）");
        Console.WriteLine();

        int 失败 = 0, 世界数 = 0, 总步 = 0, 追踪峰 = 0, 撤销数 = 0;
        var 违规 = new List<string>();

        foreach (var 世 in 世界根.世界)
        {
            if (世?.敌人 == null || 世.敌人.Length == 0) continue;
            世界数++;
            for (int s = 1; s <= 种子数; s++)
            {
                int 种子 = 确定性随机.派生(s, "敌AItest");
                // 时段按种子奇偶交替：白天/夜晚两条路径都要覆盖（视觉半径与作息修正都在这里分叉）
                var 本时段 = (s % 2 == 0) ? 时段.白天 : 时段.夜晚;

                var a = 跑一趟(世, 敌表, 取名, 种子, 步数, 本时段, 打轨迹 && s == 1, out var 统计a);
                var b = 跑一趟(世, 敌表, 取名, 种子, 步数, 本时段, false, out _);
                if (a != b)
                {
                    失败++;
                    违规.Add($"种子{s}【①确定性】两次模拟指纹不一致\n      A={a}\n      B={b}");
                }
                if (统计a.违规.Count > 0)
                {
                    失败++;
                    foreach (var v in 统计a.违规) 违规.Add($"种子{s}(时段{本时段})【{v}】");
                }
                if (统计a.抬枪 > 追踪峰) 追踪峰 = 统计a.抬枪;
                撤销数 += 统计a.撤销;
                总步 += 步数;
            }

            // ⑧ 流场自身合法性（不依赖模拟，单独跑一遍）
            var 场自检 = 流场自检(世, 取名);
            if (场自检 != null) { 失败++; 违规.Add($"世界{世.标识}【⑧流场】{场自检}"); }

            if (打示例) 打图(世, 敌表, 取名, 确定性随机.派生(1, "敌AItest"), 12, 时段.白天);
        }

        Console.WriteLine($"模拟：{世界数} 个世界 × {种子数} 种子，共 {总步} 玩家步；峰值同屏追踪 {追踪峰} 只");
        Console.WriteLine($"连通硬保证回滚次数：{撤销数}");
        Console.WriteLine();
        if (违规.Count == 0)
        {
            Console.WriteLine("✅ 全部断言通过（①确定性 ②噪音确定性 ③连通 ④门口 ⑤不重叠/不踩人 ⑥不越界 ⑦不入墙 ⑧流场 ⑨数量 ⑩即时制·挂机也会动）");
        }
        else
        {
            Console.WriteLine($"❌ {失败} 处失败：");
            foreach (var v in 违规) Console.WriteLine("  · " + v);
        }

        打性能();
        return 违规.Count == 0 ? 0 : 1;
    }

    // ================= 谓词独立自检（不依赖模拟的真值表） =================
    // 为什么必须有一份：这些谓词**服务层与验证器共用**，改坏谓词会让两边一起变宽
    //   → 模拟全绿但什么也没测出来。`门口保护` 文件头把这条教训写得很清楚，照做。
    private static List<string> 自检()
    {
        var 坏 = new List<string>();
        void 真(string 名, bool 期望, Func<bool> 算)
        {
            bool 实;
            try { 实 = 算(); }
            catch (Exception e) { 坏.Add($"{名}：抛异常 {e.GetType().Name}"); return; }
            if (实 != 期望) 坏.Add($"{名}：期望 {(期望 ? "真" : "假")}，实际 {(实 ? "真" : "假")}");
        }

        // —— 造一张 12×8 的小世界：边界墙 + 营地 + 一个区域(带门口格) + 障碍 + 两只敌人 ——
        var 世 = 造小世界(out var 甲, out var 乙, out var 区域实体);
        int 门口列 = 8, 门口行 = 5;

        // ⑧-a 能落子：真值表（每一条都对应一个真实踩过的坑）
        真("能落子·同格", false, () => 大世界敌人AI.能落子(世, 甲, 甲.列, 甲.行));
        真("能落子·负坐标", false, () => 大世界敌人AI.能落子(世, 甲, -1, 5));
        真("能落子·界外", false, () => 大世界敌人AI.能落子(世, 甲, 2, 99));
        真("能落子·边界墙", false, () => 大世界敌人AI.能落子(世, 甲, 0, 0));
        真("能落子·障碍", false, () => 大世界敌人AI.能落子(世, 甲, 4, 4));
        真("能落子·别的敌人占着", false, () => 大世界敌人AI.能落子(世, 甲, 乙.列, 乙.行));
        真("能落子·空地为真", true, () => 大世界敌人AI.能落子(世, 甲, 5, 5));
        真("能落子·玩家那一格（踩上去遭遇就永不触发）", false, () => 大世界敌人AI.能落子(世, 甲, 世.玩家列(), 世.玩家行()));
        真("能落子·区域占地内", false, () => 大世界敌人AI.能落子(世, 甲, 区域实体.列, 区域实体.行));
        真("能落子·区域门口格自己（可通行但被门口保护禁）", false, () => 大世界敌人AI.能落子(世, 甲, 门口列, 门口行));
        真("能落子·门口格紧邻（上）", false, () => 大世界敌人AI.能落子(世, 甲, 门口列, 门口行 - 1));
        真("能落子·门口格紧邻（斜角）", false, () => 大世界敌人AI.能落子(世, 甲, 门口列 + 1, 门口行 + 1));
        真("能落子·距门口 2 格（放行）", true, () => 大世界敌人AI.能落子(世, 甲, 门口列 - 2, 门口行));

        // ④ 碰世界门口 真值表
        真("碰门口·门口格自己", true, () => 门口保护.碰世界门口(世, 门口列, 门口行));
        真("碰门口·斜角紧邻", true, () => 门口保护.碰世界门口(世, 门口列 - 1, 门口行 - 1));
        真("碰门口·距 2 格", false, () => 门口保护.碰世界门口(世, 门口列 + 2, 门口行));

        // 流场.可走：敌人透明 vs 敌人挡路 —— 同一格必须给出不同答案
        真("流场可走·敌人透明", true, () => 流场.可走(世, 乙.列, 乙.行, false));
        真("流场可走·敌人挡路", false, () => 流场.可走(世, 乙.列, 乙.行, true));
        真("流场可走·墙恒挡", false, () => 流场.可走(世, 0, 0, false) || 流场.可走(世, 0, 0, true));
        真("流场可走·区域门口格可站", true, () => 流场.可走(世, 门口列, 门口行, false));

        // 流场 吸附：目标格落在障碍上时，源格必须是它旁边那一格（否则"噪音点偏一格"整个场全 -1）
        真("流场吸附·源不在障碍上", true, () =>
        {
            var 场 = 流场.建场(世, 4, 4);
            return 场 != null && 场.有源 && (场.源列 != 4 || 场.源行 != 4)
                && 大世界敌人AI.切比雪夫(场.源列, 场.源行, 4, 4) == 1;
        });

        // ③ 玩家能回营地：靠"一整排敌人把玩家隔开"造出一个真·不可达（这是验证器唯一能自证有牙的办法）
        真("连通·通", true, () => 大世界生成器.玩家能回营地(世));
        var 墙排 = new List<网格实体>();
        for (int c = 1; c <= 10; c++)
        {
            var e = 敌人实体($"封{c}", c, 5);
            世.实体.Add(e);
            墙排.Add(e);
        }
        真("连通·被一整排敌人封死（敌人挡路必须为真才测得出来）", false, () => 大世界生成器.玩家能回营地(世));
        世.实体.Remove(墙排[0]);
        真("连通·拆掉一只即恢复", true, () => 大世界生成器.玩家能回营地(世));
        foreach (var e in 墙排) 世.实体.Remove(e);

        // —— AI 三态真值表 ——
        var 数据 = new 敌人数据 { 标识 = "测试", 名称 = "测试", 感知半径 = 6, 听觉半径 = 10, 噪音阈值 = 50,
                                  巡逻半径 = 8, 追击上限 = 12, 警觉步数 = 6, 移动步频 = 3 };

        真("静默·不动", false, () =>
        {
            var 态 = new 大世界敌人AI.敌人AI态 { 状态 = 敌人状态.静默 };
            大世界敌人AI.记账出生点(态, 3, 3);
            return 大世界敌人AI.想走的格(世, 态, 数据, 3, 3, null, 0, out _, out _);
        });
        真("巡逻半径 0（Boss）·不动", false, () =>
        {
            var 态 = new 大世界敌人AI.敌人AI态 { 状态 = 敌人状态.巡逻 };
            大世界敌人AI.记账出生点(态, 3, 3);
            return 大世界敌人AI.想走的格(世, 态, new 敌人数据 { 巡逻半径 = 0 }, 3, 3, null, 0, out _, out _);
        });

        // 噪音：低于阈值只"吸引靠近"（状态不变），≥ 阈值才"直接进追踪"
        真("噪音·低于阈值不改状态只记吸引点", true, () =>
        {
            var 态 = new 大世界敌人AI.敌人AI态 { 状态 = 敌人状态.巡逻 };
            大世界敌人AI.记账出生点(态, 5, 3);
            bool 迁移 = 大世界敌人AI.结算噪音(态, 数据, 5, 3, new 噪音事件(5, 4, 25), 0);
            return !迁移 && 态.状态 == 敌人状态.巡逻 && 态.吸引列 == 5 && 态.吸引行 == 4;
        });
        真("噪音·达阈值直接进追踪且目标=噪音格", true, () =>
        {
            var 态 = new 大世界敌人AI.敌人AI态 { 状态 = 敌人状态.静默 };
            大世界敌人AI.记账出生点(态, 5, 3);
            bool 迁移 = 大世界敌人AI.结算噪音(态, 数据, 5, 3, new 噪音事件(7, 3, 90), 0);
            return 迁移 && 态.状态 == 敌人状态.追踪 && 态.目标列 == 7 && 态.目标行 == 3 && !态.目标是不是玩家;
        });
        真("噪音·听不见（超出听觉半径）", true, () =>
        {
            var 态 = new 大世界敌人AI.敌人AI态 { 状态 = 敌人状态.巡逻 };
            大世界敌人AI.记账出生点(态, 5, 3);
            // 强度 25 → 听觉半径 10×25/50 = 5；放在 8 格外 → 听不见
            return !大世界敌人AI.结算噪音(态, 数据, 5, 3, new 噪音事件(13, 3, 25), 0)
                && 态.吸引列 < 0 && 态.状态 == 敌人状态.巡逻;
        });

        // 视觉半径：白天 6 / 夜晚 3 / 夜行者白天再减半 / 潜行削顶 −60%
        真("视觉·白天", true, () => 大世界敌人AI.视觉半径(数据, 时段.白天, 0) == 6);
        真("视觉·夜晚减半", true, () => 大世界敌人AI.视觉半径(数据, 时段.夜晚, 0) == 3);
        真("视觉·夜行者白天再减半", true, () => 大世界敌人AI.视觉半径(new 敌人数据 { 感知半径 = 8, 作息 = "夜行" }, 时段.白天, 0) == 4);
        真("视觉·潜行 60 削到 40%", true, () => 大世界敌人AI.视觉半径(数据, 时段.白天, 60) == 2);
        真("视觉·潜行封顶 −60%（写 200 也只削 60%）", true, () => 大世界敌人AI.视觉半径(数据, 时段.白天, 200) == 2);

        // ★ 缰绳真值表：**超出追击上限时，看得见玩家也必须落回巡逻**。
        //   这条正是验证器抓出来的那个真 bug（原来"看见"是提前 return 的，追击上限形同虚设，
        //   实测流浪狗追到离出生点 21 格还在追）—— 把它钉成真值表，以后谁再改回去这里就炸。
        真("缰绳·超上限时看得见也要放弃", true, () =>
        {
            var 态 = new 大世界敌人AI.敌人AI态 { 状态 = 敌人状态.追踪 };
            大世界敌人AI.记账出生点(态, 10, 10);
            // 敌人在 (10,30)，离出生点 20 格 > 追击上限 12；玩家就站在它旁边（一定看得见）
            大世界敌人AI.感知与迁移(态, 数据, 10, 30, 10, 31, 时段.白天, 0, 0);
            return 态.状态 == 敌人状态.巡逻;
        });
        真("缰绳·未超上限时看得见就追", true, () =>
        {
            var 态 = new 大世界敌人AI.敌人AI态 { 状态 = 敌人状态.静默 };
            大世界敌人AI.记账出生点(态, 10, 10);
            大世界敌人AI.感知与迁移(态, 数据, 10, 12, 10, 13, 时段.白天, 0, 0);

    // 返回"最终状态指纹"（确定性断言用）
    private static string 跑一趟(世界模板 世, Dictionary<string, 敌人数据> 敌表, Func<string, string> 取名,
                                 int 种子, int 步数, 时段 当前时段, bool 轨迹, out 统计 统计出)
    {
        统计出 = new 统计();
        var 世界 = 大世界生成器.生成(种子, 世, 取名);
        if (世界 == null) { 统计出.违规.Add("世界生成失败"); return ""; }
        int 初始敌数 = 世界.敌人总数();

        var 态表 = new Dictionary<网格实体, 大世界敌人AI.敌人AI态>();
        var 出生 = new Dictionary<网格实体, (int 列, int 行)>();
        var 场表 = new Dictionary<(int, int), 流场>();
        var 随机 = 确定性随机.随机流(确定性随机.派生(种子, "玩家闲逛"));
        int 每格游戏分钟 = 5;   // = 大世界探索服务.移动游戏分钟（玩家走一格消耗的游戏时间）
        float 分钟累计 = 0f;
        int 首次移动步 = -1, 累计移动 = 0;

        if (轨迹) Console.WriteLine("  玩家步 | 静默 巡逻 追踪 | 本次移动 累计 | 玩家");

        for (int 步 = 1; 步 <= 步数; 步++)
        {
            // —— 玩家走一格（确定性闲逛；不在服务层，验证器只关心"玩家在动"这件事）——
            玩家挪一格(世界, 随机);

            // —— 玩家走完一步：先脚步噪音，再（可选）抬枪打一发 ——
            int 潜行 = 潜行样本(步);   // 让潜行值也扫过几档：0 / 30 / 60（60 = 削顶上）
            结算噪音(世界, 态表, 敌表, 出生, new 噪音事件(世界.玩家列(), 世界.玩家行(), 噪音强度.走一格), 潜行, 当前时段);
            if (步 % 7 == 0)
                结算噪音(世界, 态表, 敌表, 出生, new 噪音事件(世界.玩家列(), 世界.玩家行(), 噪音强度.开枪), 潜行, 当前时段);

            // —— 时间推进：走一格 = 每格游戏分钟（服务层由 世界时间管理器 每帧喂，这里是等价的分块喂）——
            int 移动前 = 统计出.移动数;
            if (!有敌人相邻(世界))
                推时间(世界, 态表, 敌表, 出生, 场表, 种子, 当前时段, 潜行, 每格游戏分钟, 每格游戏分钟, ref 分钟累计, 统计出);
            int 本步 = 统计出.移动数 - 移动前;
            累计移动 += 本步;
            if (本步 > 0 && 首次移动步 < 0) 首次移动步 = 步;

            if (轨迹)
            {
                int 静 = 0, 巡 = 0, 追 = 0;
                foreach (var 敌 in 世界.取类型(网格实体类型.敌人))
                {
                    if (!态表.TryGetValue(敌, out var 态) || 态 == null) { 静++; continue; }
                    if (态.状态 == 敌人状态.静默) 静++; else if (态.状态 == 敌人状态.巡逻) 巡++; else 追++;
                }
                Console.WriteLine($"  {步,6} | {静,4} {巡,4} {追,4} | {本步,8} {累计移动,4} | ({世界.玩家列()},{世界.玩家行()})");
            }

            // —— 断言 ——
            查(世界, 态表, 敌表, 出生, 步, 统计出);
        }

        // ⑩ **即时制**：玩家站着不动，敌人也必须动。
        //   为什么单独钉一条：曾经用"玩家步"驱动敌人 → **站着不动世界就冻结** ——
        //   那是把即时制当回合制写的 bug，而且从截图/录屏上看起来"跟没做一样"，极容易漏。
        //   挂机 120 游戏分钟（够最慢的感染者醒过来再走一步：静默最多 4 步 × 15 分钟 + 1 步 = 75 分钟）。
        var 挂机前 = new Dictionary<网格实体, (int 列, int 行)>();
        var 挂机前状态 = new Dictionary<网格实体, 敌人状态>();
        foreach (var 敌 in 世界.取类型(网格实体类型.敌人))
        {
            挂机前[敌] = (敌.列, 敌.行);
            挂机前状态[敌] = 态表.TryGetValue(敌, out var 态) && 态 != null ? 态.状态 : 敌人状态.静默;
        }
        for (int i = 0; i < 120; i++)
            推时间(世界, 态表, 敌表, 出生, 场表, 种子, 当前时段, 0, 每格游戏分钟, 1f, ref 分钟累计, 统计出);
        bool 挂机有人动 = false;
        foreach (var 敌 in 世界.取类型(网格实体类型.敌人))
            if (挂机前.TryGetValue(敌, out var p) && (敌.列 != p.列 || 敌.行 != p.行)) { 挂机有人动 = true; break; }
        if (!挂机有人动)
        {
            string 样本 = "";
            foreach (var 敌 in 世界.取类型(网格实体类型.敌人))
                if (挂机前状态.TryGetValue(敌, out var s) && s == 敌人状态.静默) { 样本 = 敌.定义标识; break; }
            统计出.违规.Add($"⑩即时制：玩家站着不动 120 游戏分钟，一个敌人都没动（世界被冻结）—— 样本 {样本} 仍在静默");
        }
        if (轨迹) Console.WriteLine($"  → 挂机 120 游戏分钟：{(挂机有人动 ? "有敌人移动 ✅" : "无人移动 ❌")}");

        if (世界.敌人总数() != 初始敌数) 统计出.违规.Add($"⑨数量守恒：敌人 {初始敌数} → {世界.敌人总数()}");
        统计出.指纹 = 指纹(世界, 态表, 出生);
        if (轨迹) Console.WriteLine($"  → 首次有敌人移动：第 {首次移动步} 玩家步；{步数} 步内累计移动 {累计移动} 格（{初始敌数} 只敌人）");
        return 统计出.指纹;
    }

    private static int 潜行样本(int 步) => 步 % 3 == 0 ? 60 : (步 % 3 == 1 ? 0 : 30);

    private static void 玩家挪一格(网格数据 世界, Random 随机)
    {
        int 列 = 世界.玩家列(), 行 = 世界.玩家行();
        var 候选 = new List<(int 列, int 行)>();
        for (int d = 0; d < 4; d++)
        {
            int c = 列 + 流场.横[d], r = 行 + 流场.纵[d];
            if (世界.可通行(c, r)) 候选.Add((c, r));
        }
        if (候选.Count == 0) return;
        var 选 = 候选[确定性随机.范围(随机, 0, 候选.Count - 1)];
        世界.移动玩家(选.列, 选.行);
    }

    private static bool 有敌人相邻(网格数据 世界)
    {
        int 列 = 世界.玩家列(), 行 = 世界.玩家行();
        foreach (var 敌 in 世界.取类型(网格实体类型.敌人))
            if (Math.Abs(敌.列 - 列) + Math.Abs(敌.行 - 行) == 1) return true;
        return false;
    }

    // 与服务层 大世界探索服务.噪音结算 同一套（这里只有"听到 → 改状态"这一步）
    private static void 结算噪音(网格数据 世界, Dictionary<网格实体, 大世界敌人AI.敌人AI态> 态表,
                                 Dictionary<string, 敌人数据> 敌表, Dictionary<网格实体, (int 列, int 行)> 出生,
                                 噪音事件 噪, int 潜行, 时段 当前时段)
    {
        foreach (var 敌 in 世界.取类型(网格实体类型.敌人))
        {
            if (!敌表.TryGetValue(敌.定义标识 ?? "", out var 数据) || 数据 == null) continue;
            var 态 = 取态(态表, 出生, 敌);
            大世界敌人AI.结算噪音(态, 数据, 敌.列, 敌.行, 噪, 潜行);
        }
    }

    // 与服务层 大世界探索服务.驱动敌人 同一套（顺序、游戏分钟节拍、掷点、连调整体回滚）。
    // ★ 刀61 即时制修正：驱动单位从"玩家步"改成**游戏分钟** —— 服务层由 世界时间管理器 每帧喂时间，
    //   这里用固定分钟数喂（同样的总分钟数 = 同样的步序 → 可离线复现）。
    private static void 驱动敌人(网格数据 世界, Dictionary<网格实体, 大世界敌人AI.敌人AI态> 态表,
                                 Dictionary<string, 敌人数据> 敌表, Dictionary<网格实体, (int 列, int 行)> 出生,
                                 Dictionary<(int, int), 流场> 场表, int 种子, 时段 当前时段, int 潜行,
                                 int 整数分, int 每格游戏分钟, 统计 统计)
    {
        var 敌人们 = 世界.取类型(网格实体类型.敌人);
        var 本步移动 = new List<(网格实体 敌, int 原列, int 原行)>();
        int 追踪数 = 0;

        foreach (var 敌 in 敌人们)
        {
            if (!敌表.TryGetValue(敌.定义标识 ?? "", out var 数据) || 数据 == null) continue;
            var 态 = 取态(态表, 出生, 敌);
            态.分钟计 += 整数分;
            int 间隔 = 大世界敌人AI.间隔分钟(数据, 每格游戏分钟);
            while (态.分钟计 >= 间隔)
            {
                态.分钟计 -= 间隔;
                态.步数++;
                int 掷 = 大世界敌人AI.掷点(种子, 敌.标识, 态.步数);
                大世界敌人AI.感知与迁移(态, 数据, 敌.列, 敌.行, 世界.玩家列(), 世界.玩家行(), 当前时段, 潜行, 掷);
                if (态.状态 == 敌人状态.追踪) 追踪数++;

                流场 场 = null;
                if (态.状态 == 敌人状态.追踪 && 态.目标列 >= 0)
                {
                    var 键 = (态.目标列, 态.目标行);
                    if (!场表.TryGetValue(键, out 场) || 场 == null)
                    {
                        if (场表.Count >= 8) 场表.Clear();
                        场 = 流场.建场(世界, 态.目标列, 态.目标行);
                        场表[键] = 场;
                    }
                }
                if (!大世界敌人AI.想走的格(世界, 态, 数据, 敌.列, 敌.行, 场, 掷, out int 目标列, out int 目标行)) continue;
                if (大世界敌人AI.落子(世界, 敌, 态, 目标列, 目标行))
                {
                    本步移动.Add((敌, 态.上次列, 态.上次行));
                    统计.移动数++;
                }
            }
        }

        if (追踪数 > 统计.抬枪) 统计.抬枪 = 追踪数;
        if (本步移动.Count == 0) return;
        if (!大世界生成器.玩家能回营地(世界))
        {
            // 硬保证：这一步会切断玩家回营地的路 → **整体撤销**（与服务层同一处理）
            foreach (var (敌, 原列, 原行) in 本步移动) { 敌.列 = 原列; 敌.行 = 原行; }
            统计.撤销++;
        }
    }

    // 服务层 大世界探索服务.时间推进 的镜像：整数分钟累加（攒够整分钟才算）
    private static void 推时间(网格数据 世界, Dictionary<网格实体, 大世界敌人AI.敌人AI态> 态表,
                              Dictionary<string, 敌人数据> 敌表, Dictionary<网格实体, (int 列, int 行)> 出生,
                              Dictionary<(int, int), 流场> 场表, int 种子, 时段 当前时段, int 潜行,
                              int 每格游戏分钟, float 游戏分钟, ref float 分钟累计, 统计 统计)
    {
        分钟累计 += 游戏分钟;
        int 整数分 = (int)分钟累计;
        if (整数分 <= 0) return;
        分钟累计 -= 整数分;
        驱动敌人(世界, 态表, 敌表, 出生, 场表, 种子, 当前时段, 潜行, 整数分, 每格游戏分钟, 统计);
    }

    private static 大世界敌人AI.敌人AI态 取态(Dictionary<网格实体, 大世界敌人AI.敌人AI态> 态表,
                                              Dictionary<网格实体, (int 列, int 行)> 出生, 网格实体 敌)
    {
        if (态表.TryGetValue(敌, out var 态) && 态 != null) return 态;
        态 = new 大世界敌人AI.敌人AI态();
        大世界敌人AI.记账出生点(态, 敌.列, 敌.行);
        态表[敌] = 态;
        if (!出生.ContainsKey(敌)) 出生[敌] = (敌.列, 敌.行);
        return 态;
    }

    // ================= 断言 =================

    private static void 查(网格数据 世界, Dictionary<网格实体, 大世界敌人AI.敌人AI态> 态表,
                           Dictionary<string, 敌人数据> 敌表,
                           Dictionary<网格实体, (int 列, int 行)> 出生, int 步, 统计 统计)
    {
        // ③ 连通硬保证
        if (!大世界生成器.玩家能回营地(世界))
            统计.违规.Add($"③连通：第 {步} 步后玩家走不回营地门口格");

        var 敌人们 = 世界.取类型(网格实体类型.敌人);
        var 已占 = new HashSet<int>();
        foreach (var 敌 in 敌人们)
        {
            // ④ 门口保护（含紧邻八格）
            if (门口保护.碰世界门口(世界, 敌.列, 敌.行))
                统计.违规.Add($"④门口：{敌.定义标识} 停在了门口格的紧邻八格内 @({敌.列},{敌.行})（第 {步} 步）");

            // ⑤ 不重叠（两只敌人同格）
            int 码 = 网格数据.编码(敌.列, 敌.行);
            if (!已占.Add(码))
                统计.违规.Add($"⑤重叠：两只敌人同格 @({敌.列},{敌.行})（第 {步} 步）");

            // ⑤-b 敌人**不许踩到玩家那一格**：遭遇判据是"正交相邻"，同格 = 距离 0 = 永远触发不了遭遇
            //     （`能落子` 有一条同样的约束；这条断言是它在**整局模拟里**的兜底）
            if (敌.列 == 世界.玩家列() && 敌.行 == 世界.玩家行())
                统计.违规.Add($"⑤踩人：{敌.定义标识} 站到了玩家那一格（遭遇将永不触发）（第 {步} 步）");

            // ⑦ 不入墙（`占位` 会返回到敌人**自己** —— 占格物当然覆盖自己脚下那一格，所以要比一下是不是它）
            var 占位者 = 世界.占位(敌.列, 敌.行);
            if (占位者 != null && 占位者 != 敌)
                统计.违规.Add($"⑦入墙：{敌.定义标识} 站在 {占位者.定义标识} 上 @({敌.列},{敌.行})（第 {步} 步）");

            // ⑥ 不越界（相对出生点）。三态各有自己的界，**分开写**才是有信息量的断言：
            //   静默：`巡逻 → 静默` 要求 出生距 ≤ 1，此后不动 → 距 恒 ≤ 1；
            //   巡逻/追踪：`追击上限` 是缰绳（超出就在下一次 感知与迁移 里落回巡逻），
            //              而从追踪落回巡逻时人还在外面 → 巡逻态的界必须是 max(巡逻半径, 追击上限)。
            //   余量 1 格：判定发生在"这一步开始时"，迈出去那一步是"上一步结束时"干的。
            //   （写余量正是为了让这条断言**只抓真 bug**；少了它就会天天误报，然后被人关掉。）
            if (出生.TryGetValue(敌, out var 出) && 态表.TryGetValue(敌, out var 态) && 态 != null
                && 敌表.TryGetValue(敌.定义标识 ?? "", out var 数据) && 数据 != null)
            {
                int 距 = 大世界敌人AI.切比雪夫(敌.列, 敌.行, 出.列, 出.行);
                int 上限 = 态.状态 == 敌人状态.静默
                    ? 1
                    : Math.Max(Math.Max(0, 数据.巡逻半径), Math.Max(1, 数据.追击上限)) + 1;
                if (距 > 上限)
                    统计.违规.Add($"⑥越界：{敌.定义标识}（{态.状态}）离出生点 {距} 格 > 上限 {上限}（第 {步} 步）");
            }
        }
    }

    // ================= 流场自检（⑧） =================

    private static string 流场自检(世界模板 世, Func<string, string> 取名)
    {
        var 世界 = 大世界生成器.生成(确定性随机.派生(1, "敌AItest"), 世, 取名);
        if (世界 == null) return "世界生成失败";
        var 门 = 大世界生成器.营地门口格(世界);

        var 场 = 流场.建场(世界, 门.列, 门.行);
        if (场 == null || !场.有源) return "以营地门口格为源建场失败";
        var 场2 = 流场.建场(世界, 门.列, 门.行);
        if (场.指纹() != 场2.指纹()) return "同目标格两次建场指纹不一致（确定性破了）";

        // 方向必须指向"距 −1"的邻格 → 结构上不成环
        for (int r = 0; r < 世界.行; r++)
            for (int c = 0; c < 世界.列; c++)
            {
                int 距 = 场.距值(c, r);
                if (距 <= 0) continue;
                var 下 = 场.下一步(c, r);
                if (下 == null) return $"({c},{r}) 距={距} 却没有方向（不可达格不该有距离）";
                int 下距 = 场.距值(下.Value.列, 下.Value.行);
                if (下距 != 距 - 1) return $"({c},{r}) 距={距} 的方向指向 距={下距} 的格（应为 {距 - 1} → 可能成环）";
                if (大世界敌人AI.切比雪夫(c, r, 下.Value.列, 下.Value.行) != 1)
                    return $"({c},{r}) 的方向不是相邻格（4 连通破了）";
            }

        // 不可走格不该有距离（除了被吸附的源格）
        for (int r = 0; r < 世界.行; r++)
            for (int c = 0; c < 世界.列; c++)
            {
                if (场.距值(c, r) < 0) continue;
                if (c == 场.源列 && r == 场.源行) continue;
                if (!流场.可走(世界, c, r, false)) return $"({c},{r}) 有距离却是不可走格";
            }
        return null;
    }

    // ================= 指纹 =================

    private static string 指纹(网格数据 世界, Dictionary<网格实体, 大世界敌人AI.敌人AI态> 态表,
                              Dictionary<网格实体, (int 列, int 行)> 出生)
    {
        var 段 = new List<string>();
        foreach (var 敌 in 世界.取类型(网格实体类型.敌人))
        {
            态表.TryGetValue(敌, out var 态);
            string s = 态 == null ? "无态"
                : $"{态.状态}/{态.警觉剩余}/{态.目标列},{态.目标行}/{(态.目标是不是玩家 ? 1 : 0)}/{态.吸引列},{态.吸引行}/{态.步数}";
            段.Add($"{敌.标识}@{敌.列},{敌.行}:{s}");
        }
        段.Sort(StringComparer.Ordinal);
        return $"玩家@{世界.玩家列()},{世界.玩家行()}|" + string.Join(";", 段);
    }


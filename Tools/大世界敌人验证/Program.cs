    private static int 数追踪(网格数据 世界, Dictionary<网格实体, 大世界敌人AI.敌人AI态> 态表)
    {
        int n = 0;
        foreach (var 敌 in 世界.取类型(网格实体类型.敌人))
            if (态表.TryGetValue(敌, out var 态) && 态 != null && 态.状态 == 敌人状态.追踪) n++;
        return n;
    }

    private static string 格字符(网格数据 世界, int 列, int 行)
    {
        for (int r = 行; r < 行 + 5 && r < 世界.行; r++)
            for (int c = 列; c < 列 + 5 && c < 世界.列; c++)
                if (c == 世界.玩家列() && r == 世界.玩家行()) return "@";
        for (int r = 行; r < 行 + 5 && r < 世界.行; r++)
            for (int c = 列; c < 列 + 5 && c < 世界.列; c++)
            {
                var e = 世界.格上实体(c, r);
                if (e == null) continue;
                if (e.类型 == 网格实体类型.敌人) return "1";
                if (e.类型 == 网格实体类型.障碍) return "#";
                if (e.类型 == 网格实体类型.区域 || e.类型 == 网格实体类型.建筑) return "B";
                if (e.类型 == 网格实体类型.临时建筑) return "T";
                if (e.类型 == 网格实体类型.墙) return "·";
            }
        return " ";
    }

